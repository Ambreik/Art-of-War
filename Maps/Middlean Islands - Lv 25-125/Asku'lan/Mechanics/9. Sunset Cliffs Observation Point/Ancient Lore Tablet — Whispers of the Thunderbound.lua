			Ancient Lore Tablet — "Whispers of the Thunderbound"

---

	Description :

	An ancient stone tablet embedded into the fractured cliffside at the "Sunset Cliffs Observation Point". The surface is eroded by centuries of wind and salt, yet
faint inscriptions remain visible when lightning flashes across the horizon.
	The tablet is not man-made in a traditional sense — its carvings appear too deep, too smooth, as if cut directly by pressure, wind, and lightning rather than 
tools. The script does not belong to any known modern civilization of Middlean Islands.
	When players interact with it, faint electrical resonance travels through the ground, and the text becomes briefly legible during storm or high-wind 
environmental states.

---

	Lore Content (Readable Text Reveal) :

> "Before land had shape, there was only sky pressure and screaming wind."
>
> "From the collision of storm and stone, they were formed — not born."
>
> "The three who carry the sky’s memory are not beasts, nor gods… but echoes."
>
> "They do not guard the island. The island exists because they allow it to remain whole."
>
> "When lightning strikes without rain, it is not weather. It is their breath."
>
> "To see them is to be measured. To resist them is to be rewritten."

---

	Environmental Trigger Condition :

* Fully readable during :
	* Storm weather states ⚡
	* High wind intensity zones 🌪️
* Partially visible during normal weather (fragmented glyphs only)
* Hidden completely during blackout storm events (tablet "goes silent")

---

	Associated Lore Hook :
* The tablet refers indirectly to the "Ancient Thunder Guardians", implying :
	* They are not natural creatures, but emergent storm entities
	* They are tied to the structural stability of Asku’lan itself
	* Their existence predates recorded civilizations on the island
	* Lightning events are potentially biological or conscious activity, not weather

