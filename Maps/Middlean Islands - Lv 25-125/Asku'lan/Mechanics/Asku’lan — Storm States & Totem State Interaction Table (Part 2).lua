			Asku’lan — Part 2: Storm States & Totem State Interaction Table

---

	The Totem mini-game does not reward players locally.
	It changes the rules of the island for everyone currently on Asku’lan.
	At any moment, the island is in one of four "Global States".
	These states are controlled by the outcome of the "Skyreach Spire Totem" mini-game.

---

		State I — Dormant Sky (Default State)

	Totem inactive / puzzle unsolved / neutral alignment

| System            | Behavior                        |
| ----------------- | ------------------------------- |
| Weather           | Light wind, clear or cloudy sky |
| Lightning         | Very rare, mostly cosmetic      |
| Traversal         | Safe zip lines and cliffs       |
| Rivers            | Safe                            |
| Creatures         | Normal ecosystem behavior       |
| Thunder Guardians | Inactive, statue-like or hidden |
| Player Risk       | Minimal environmental danger    |

	This is the learning state of the island.

---

		State II — Stirring Storm

	Totem partially activated / incorrect sequence / unstable charge

| System            | Behavior                                  |
| ----------------- | ----------------------------------------- |
| Weather           | Dark clouds form rapidly                  |
| Lightning         | Begins striking high elevation randomly   |
| Traversal         | Zip lines become risky at high points     |
| Rivers            | Occasional electric pulses during strikes |
| Creatures         | Some become restless, move toward cover   |
| Thunder Guardians | Low chance to animate briefly             |
| Player Risk       | Moderate, especially at elevation         |

	Players start realizing :

> "The island is reacting to something."

---

		State III — Thunder Dominion

	Totem successfully activated / correct alignment

	This is the intended powerful state of the island.

| System            | Behavior                                         |
| ----------------- | ------------------------------------------------ |
| Weather           | Heavy storm, constant thunder                    |
| Lightning         | Frequent, targeted to spires and exposed cliffs  |
| Traversal         | Fast but very dangerous via zip lines            |
| Rivers            | Electrified during most strikes                  |
| Creatures         | Many retreat to cover, some gain buffs           |
| Thunder Guardians | Fully active — can spawn as Semi-Boss encounters |
| Player Risk       | High everywhere except dense cover               |

	This is when" Asku’lan" feels hostile and alive.
	This is also when the Totem mini-game indirectly spawns content via the Guardians.

---

		State IV — Overload / Unstable Sky

	Totem failed critically / misaligned repeatedly

	A chaotic, rare state.

| System            | Behavior                                      |
| ----------------- | --------------------------------------------- |
| Weather           | Violent winds + erratic lightning             |
| Lightning         | Unpredictable, even low ground not fully safe |
| Traversal         | Some zip lines temporarily disabled           |
| Rivers            | Constantly dangerous                          |
| Creatures         | Disoriented movement patterns                 |
| Thunder Guardians | Rampage behavior, roaming instead of guarding |
| Player Risk       | Very high everywhere                          |

	This state feels like the island is angry.

---

		How State Transitions Happen

| Trigger                       | Result                 |
| ----------------------------- | ---------------------- |
| Totem untouched for long time | Returns to Dormant Sky |
| Partial interaction           | Stirring Storm         |
| Successful completion         | Thunder Dominion       |
| Repeated failures             | Overload               |

	The state is global for all players on island.

---

		What This Achieves

	Without quests, bosses, or NPCs :
* Players indirectly control the island
* The mini-game affects traversal, monsters, and safety
* Thunder Guardians are naturally integrated
* Exploration feels different each time

	Asku’lan becomes system-driven gameplay.

