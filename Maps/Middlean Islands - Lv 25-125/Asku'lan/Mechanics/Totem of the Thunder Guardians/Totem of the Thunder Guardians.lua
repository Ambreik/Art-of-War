			Totem of the Thunder Guardians

* POI : "Skyreach Spire Totem"
* Location : Summit of "Skyreach Spire"
* Purpose : A high-risk, high-reward interactive mechanic that lets players unlock dramatic island effects by solving an environmental puzzle using rare 
monster-dropped pieces.

	This is not a quest but a world mechanic that affects the entire island.

---

		1. Core Concept

	Players collect three unique "Totem Puzzle Pieces" from monsters across "Asku’lan".

	When all three are brought to the Totem and placed correctly :
* A powerful system outcome triggers
* Island state is impacted
* Monsters may be summoned or lightning events occur

	This makes the Totem a landmark of risk, spectacle, and competition in a non-quest context.

---

		2. Totem Puzzle Pieces

	Players must gather three components dropped from specific monster types :

| Piece Name               | Monster Source       | Rank              | Drop Rate        |
| ------------------------ | -------------------- | ----------------- | ---------------- |
| Piece of the Storm Orb   | Stormclaw Raptors    | Rank III – Flying | Low (~2–5%)      |
| Shard of Skyrunestone    | Skyreach Golems      | Rank IV – Ground  | Very Low (~1–3%) |
| Lightning Sigil Fragment | Thunderfang Serpents | Rank III – Ambush | Low (~2–5%)      |

	*Drops are intentionally rare to encourage exploration and competition for island resources.*

---

		3. Puzzle Mini-Game Interaction

	When a player with all 3 pieces interacts with the Totem :

	A drag-and-drop UI appears showing three empty slots.

	Player must :
1. Place each item in the correct Totem slot
2. If correct → activate the Totem outcome
3. If incorrect → Totem feedback triggers environmental risk (see failure response below)

		Correct Placement

	Success triggers :
* Dramatic lightning visual and sound effect
* Heavy system notification to all players
* Island outcome event (see 4)

---

		4. Event Outcomes (Successful Activation)

	Multiplayer Aware Outcome

	If other players are on the island nearby (within area threshold) :
* Storm lightning strikes all players except the activating player
* A 3-minute respawn grace timer applies
* No mount usage permitted for 15 minutes after death

	Players see system message :

> "You have summoned the Thunder Strike upon Asku’lan!"

	This creates tension, risk, and island-wide spectacle.

---

		Solo Activation Outcome

	If no other players are present on island (only the activating player) :

	Lightning strikes three fixed locations, each with a rare monster summoned :

| Monster Spawn      | Spawn Location          |
| ------------------ | ----------------------- |
| Stormclaw Drake    | Emerald Jungle Clearing |
| Skyreach Elemental | Northern High Ridge     |
| Thunderfang Hydra  | Hidden River Gorge      |

	System message :

> "Lightning storms awaken fearsome guardians…"
> (with mini-map markers revealed briefly)

	World message is visible to activating player only.
	These monsters can be fought for drops, rare resources, or unique buffs, separate from Totem puzzle pieces.

---

		5) Failure & Risk Feedback

	If a player incorrectly places a piece :
* Totem emits a thunder warning pulse
* Minor lightning arcs unpredictably
* Nearby terrain receives environmental hazard
* No monster spawns — only risk

	This keeps the mechanic dangerous and meaningful even on failure.

---

		6) Environmental Integration

	While puzzle is active or during island storm states :
* Visual: Totem glows with electric blue runes
* Piece icons float above player’s head during interaction
* Lightning syncs with major storms (weather engine ties in)

	This ensures the mechanic feels organic and dynamic, not separate from the world. 

---

		7. Monster Behavior Context (Reinforcement Loop)

	The Totem mini-game connects seamlessly with the monster ecosystem :
* "Thunderfang Serpents" : stealth predators hiding in jungle — encourage sound awareness
* "Stormclaw Raptors" : airborne threats — tie into zip line hazard zones
* "Skyreach Golems" : heavy ground threats — tie into cliff traverse tension

	Their piece drops are rare, reinforcing island traversal and traversal systems like zip lines and wind columns.

---

		8. Drop RNG & Persistence

	To prevent endless farming :
* Totem piece drops are low (~2–5%) and shared RNG
* Pieces despawn after 10 minutes if not placed
* Players can only hold one copy of each type at a time

	This prevents :
* camping at monster spawns
* stockpiling for global impact

---

		9. Multiplayer Non-Consent Interaction

	Because the Totem affects other players when activated :
* A clear UI consent prompt is shown
* Players receive a warning that activating will call lightning on others
* They must confirm before final placement

	This prevents griefing and aligns with MMO etiquette.

---

		10. System Messaging Flow

	Player With Pieces Interacts : 

> "You sense ancient power in the Totem…"

	On Confirmation Prompt : 

> "Activating this Totem will bring thunder upon Asku’lan. Continue?"

	On Success : 

> "You have summoned the Thunder Strike upon Asku’lan!"

	On Solo Outcome : 

> "Lightning storms awaken fearsome guardians…"

	On Failure : 

> "The Totem rumbles… but rejects your offering."

---

		11. Recurring Utilization

	This mechanic stays relevant because :
* Puzzle pieces always drop (rare)
* Totem states persist until reset
* Events can overlap with state weather conditions
* Players will pursue rare monsters that are tied to piece drops

	This makes the Totem not a one-off toy, but an enduring island mechanic.

