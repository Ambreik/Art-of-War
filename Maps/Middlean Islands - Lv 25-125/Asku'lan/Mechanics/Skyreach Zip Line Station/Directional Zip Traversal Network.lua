			Skyreach Zip Line Station — Directional Zip Traversal Network

---

	A mechanical traversal hub that lets players launch themselves from the heights of "Asku’lan" toward key island locations using gravity-powered zip lines.
	This is the horizontal counterpart to the vertical "Wind Ascension Columns" at "Skyreach Spire".

	Players go up by wind → travel across by zip.

---

		Purpose of This POI Mechanic

	This is not fast travel.

	This is risk travel and positional traversal across dangerous terrain that would otherwise be :
* Long to reach
* Hazardous to cross on foot
* Hard to navigate because of storms, cliffs, and broken geography

	The Zip Station becomes :

> The island’s aerial routing system.

---

		Design Philosophy

	When a player reaches the Zip Line Launcher, they are asked :

> "Where do you want the storm to take you?"

	Destinations are not random.
	They are carefully chosen high-value island locations players repeatedly want to reach.

---

		Destinations Players Actually Care About

	From the POIs / Secret Locations relevant to gameplay loops, traversal need, and Totem/Guardian ecosystem.

---

	1. Skyreach Spire (Return Line)

	Why players want this :
* They fell during Wind Ascension
* They finished Totem mini-game
* They want to quickly return to the top

	This line goes back upward toward a mid-ledge, not the peak.

	Creates a loop :

> Zip → climb by wind → Totem → zip again

---

	2. Thunderbreak Ledge

	Why important :
* High lightning activity area
* One of the Ancient Guardian spawn regions
* Rare minerals embedded in struck rocks

	Players farming, hunting, or waiting for Guardian spawn will prefer this route.

---

	3. Gale Ravine

	Why important :
* Violent wind canyon, hard to cross on foot
* Rare herbs growing in wind-protected pockets
* Environmental hazard zone from Area Info

Zip lets players bypass dangerous descent paths.

---

	4. Shattered Perch

	Why important :
* Fragmented floating cliffs / broken terrain
* One Guardian possible spawn area
* Vertical maze if reached by ground

	Zip line drops players directly onto safe rock platforms.

---

	5. Stormroot Basin

	Why important :
* Lower island region
* Resource rich
* Difficult to descend safely from Spire

	This is the "downward" travel option.

---

	6. Totem Lightning Impact Fields

	Why important :
* Where lightning strikes from the Totem land
* Where the 3 Ancient Thunder Guardians can spawn
* High player interest during/after mini-game

	This becomes a Guardian hunter route.

---

		How the Zip System Works

	When interacting with the launcher :

	A UI appears with destinations :

```
Choose Zip Destination:
• Thunderbreak Ledge
• Gale Ravine
• Shattered Perch
• Stormroot Basin
• Lightning Impact Fields
• Return toward Skyreach Spire
```

	Player locks in.

	A heavy crank sound. Cable tension.

	Launch.

---

		The Hazard Layer (very important)

	This is not a safe zip.

	While zipping :
* Strong crosswinds sway the cable
* Lightning may strike nearby (visual + minor shake)
* Player must hold balance (light input correction)
* During Thunder Dominion → harder to stay aligned

	If player fails balance :

> They fall mid-zip onto terrain below (not death, but displacement)

