			Seagull Harassment System

	This expands your dock event into a layered, scalable ambient system rather than a single repeating joke event, while keeping it lightweight enough to never 
interrupt core gameplay.

---

		1. Core Identity

	The seagulls are not just "ambient animals".

	They are :

> Dock predators of opportunity

	They associate the dock with :
* food scraps
* weak rope bindings
* fish crates
* distracted travelers
* storm-washed remains

	So they behave like a semi-coordinated nuisance swarm, not random birds.

---

		2. Trigger System (Refined)

	Instead of a flat timer, the event uses three conditions layered together :

	Base Cycle : 
* Every 8–12 minutes → soft chance roll

	Weather Modifier : 
* Fog / light storm → higher chance
* Heavy storm → slightly reduced (birds shelter inland)

	Activity Modifier : 
* More players at dock → higher spawn intensity
* Empty dock → “silent flyby” version only

---

		3. Event Phases (Important Expansion)

	Phase 1 — Distant Gathering

	Players may notice :
* distant screeching
* black shapes circling fog line
* dock ropes vibrating slightly

	Dockmaster line :

> "Not again… they’re circling the bay."

---

	Phase 2 — Dock Swarm Arrival

	A flock arrives in waves :
* pecking crates
* stealing food items (visual only or minor resource interaction)
* pulling ropes loose
* disrupting torches

	Guard enters combat stance immediately.

---

	Phase 3 — Interaction Window (Player Agency)

	Players now have 4 valid interaction archetypes :

---

	1. Improvised Ranged Defense

* Pick up rocks from dock crates
* Throw at birds (light aim system)
* Stuns small groups briefly

	Effect :
* reduces swarm density
* increases Guard effectiveness

---

	2. Fire Intimidation

* Light torch interaction
* Wave animation
* creates short “fire cone fear zone”

	Effect :
* birds avoid torch area
* works best during fog nights

---

	3. Environmental Luring (smart system)

	Players can :
* drag birds toward nearby shoreline creatures
* bait them with fish scraps (rare item interaction)
* redirect swarm behavior

	Effect :
* birds break formation temporarily
* creates chaos but reduces dock pressure

---

	4. Guard Synergy Assist

	Players fight alongside Guard :
* timing-based strikes
* knockback assist actions
* "stun windows" on bird clusters

	Effect :
* fastest resolution
* unlocks best reward tier

---

		4. Dynamic Difficulty Scaling

	The system adjusts automatically :

| Condition   | Behavior                             |
| ----------- | ------------------------------------ |
| 1–2 players | small flock, simple harassment       |
| 3–5 players | full swarm, coordinated attack loops |
| large group | chaotic multi-wave event             |

	This prevents farming or trivialization.

---

		5. Reward Structure (Expanded but controlled)

	Instead of fixed rewards, we use tiered contribution rewards :

	Low Contribution : 
* minor XP
* small food item (fish, ration scrap)

	Medium Contribution : 
* better XP
* "Dock Supply Pack" (usable consumables)
* Guard dialogue recognition

	High Contribution : 
* rare consumable chance
* temporary buff :
	> "Dock Defender’s Favor"
	> (minor movement speed + stamina regen near coast for 15 minutes)

---

		6. Narrative & Humor Layer

	This is important for identity.

	Dockmaster reactions vary :
* frustrated
* comedic
* slightly traumatized

	Example lines :

> "I swear I built this dock for sailors, not as a buffet for flying rats!"

> "If one more of them steals my fish, I’m retiring into the sea."

	Guard lines :

> "They test my patience more than bandits ever did."

---

		7. Storm Interaction (Asku’lan Integration)

	During lightning-heavy weather :
* birds become more aggressive
* flock size increases slightly
* occasional birds get struck mid-air (visual only)
* dock becomes harder to control

	This connects directly to island identity :

> chaos + nature + survival tone

---

		8) Failure / Ignored State (Important Detail)

	If players ignore the event :
* dock becomes messy (ropes broken, crates scattered)
* Guard handles it alone (slower cleanup)
* Dockmaster becomes visibly annoyed
* slight temporary inconvenience :
	* slower boat preparation time
	* minor dock repair delay

	No punishment — just world reaction.

