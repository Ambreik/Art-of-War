			Emerald Bay Boat System — Storm Navigation Routes

	This upgrades the simple boat rental mechanic into a risk-based traversal network that connects Asku’lan’s coastline, storms, and hidden geography into a single
exploration loop.
	It remains optional, but now becomes meaningful, dangerous, and strategically useful.

---

		1. Core Concept

	Boats are no longer just transport.

	They are :

> Storm-sensitive traversal tools

	Players are not only choosing a destination — they are choosing a route stability level under unpredictable weather conditions.

---

		2. Boat Travel Modes

	When renting a boat, players choose :

	Safe Route (Coastal Drift) :  
* Follows shoreline
* Slower travel
* Minimal risk
* No special encounters

	Best for :
* beginners
* resource runners
* casual travel

---

	Standard Route (Open Water Line) : 
* Direct travel between POIs
* Moderate wind interference
* Small chance of hazards

	Best for :
* normal exploration
* fast island traversal

---

	Storm Route (High Risk Navigation)

	Unlocked only during :
* active storms
* Totem lightning state
* or rare weather cycles

	This is where Asku’lan becomes dangerous.

---

		3. Storm Route Mechanics

	When activated:

	Environmental Effects : 
* waves become unstable
* visibility drops
* lightning strikes sea surface (visual + hazard zones)
* boat drift begins naturally (player correction required)

---

	Player Control Layer

	Players must :
* maintain directional balance (simple steering correction)
* stabilize boat during wind bursts
* avoid lightning “strike zones” marked briefly in water

	Failure does NOT kill instantly — it causes :

> forced displacement onto nearest shoreline or island rock

---

		4. Storm Encounter System (Key Expansion)

	During Storm Routes, random encounters occur :

---

	1. Skyborne Drift Creatures

* Wind-elemental fish / serpents
* pass above or under boat
* may create turbulence

---

	2. Lightning Sea Strikes

* lightning hits ocean surface nearby
* creates temporary “electrified water zones”
* players must steer away quickly

---

	3. Fog Collapse Events

* visibility drops to near zero
* navigation becomes audio-based (wave direction cues)
* dock landmarks disappear temporarily

---

	4. Floating Debris Fields
* broken ship parts drift across sea
* players can :
	* avoid
	* or collide intentionally for loot chances
	
---

		5. Destination Integration (Important)

	Boat routes now connect directly to POIs :
* Core destinations :
	* "Skyreach Spire Base Zone"
	* "Emerald Jungle Coastal Edge"
	* "Thunderfang Gorge Mouth"
	* "Shattered Perch Landing Rocks"	
	* "Hidden River Gorge Entry"
	* *unmarked secret shoreline

---

		Special Rule:

	Some destinations ONLY appear :
* during storms
* after Totem activation
* or during rare island state cycles

	This makes boats part of island discovery gameplay*, not just travel.

---

		6. Synergy With Other Systems

	Totem System Interaction : 
* storm routes become more dangerous after lightning events
* rare charged sea zones appear after Totem activation

---

	Zip Line System Interaction : 
* Zip stations become fallback travel if storms block boats
* players alternate between air and sea traversal

---

	Wind Column System Interaction : 
* wind direction affects boat drift speed
* certain routes become faster or harder depending on weather

---

		7. Risk / Reward Structure

| Route Type | Risk   | Reward                         |
| ---------- | ------ | ------------------------------ |
| Safe       | Low    | No bonus                       |
| Standard   | Medium | Faster travel                  |
| Storm      | High   | Hidden zones + rare encounters |

---

		8. Hidden Rewards (Important MMO Hook)

	Storm Routes can yield :
* rare sea minerals
* storm-touched crafting materials
* map fragments of hidden coastlines
* chance to discover unmarked POIs

	This turns boating into :

> a soft exploration gacha system without RNG frustration

---

		9. Immersive Flavor Layer

	Dockmaster dialogue during storms :

> "You’re leaving in THIS weather? Either brave… or foolish."

	Guard response :

> "If you don’t return, I’m not writing your name on the board."

	During lightning :

> "That wasn’t natural… even the sea is afraid today."

