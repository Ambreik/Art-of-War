			Asku’lan — Thunder Guardians System (Part 3)

---

		What They Are (Design Role)

	They are "Semi-Boss Environmental Entities", not elites.

	Reason :
* They are rare
* They are event-spawned
* They are tied to island state
* They are location-bound
* They cannot be farmed
* They feel like natural disasters given form.

	Players should say :

> "A Guardian spawned."
	Not
> "A rare mob spawned."

---

		Fixed Guardian Sites (3 total)

	Each Guardian is tied to a specific lightning conductor point on the island :

| Guardian     | Terrain Type                  | Symbolism             |
| ------------ | ----------------------------- | --------------------- |
| Guardian I   | Highest cliff / spire         | Sky conductor         |
| Guardian II  | Rocky canyon / stone basin    | Earth conductor       |
| Guardian III | Near river/waterfall crossing | Storm-water conductor |

	They never roam the island.
	They manifest only at their sacred strike point.

---

		What Spawns Them

	They do not have timers in the traditional sense.

	They require ALL of this :
1. Island must be in "Thunder Dominion" (State III)
2. Lightning strike hits their exact conductor point
3. Internal cooldown of 18–26 real hours since last defeat
4. A player must be within regional proximity (prevents empty spawns)

	This makes them feel :

> "summoned by the storm" — not spawned by a script.

---

		Anti-Camping Design 

	Even if players wait there :
* If Storm State is not "Thunder Dominion" → nothing happens
* If lightning doesn’t strike that point → nothing happens
* If cooldown not expired → nothing happens

	So waiting is pointless.

	Players instead :
* Play the Totem
* Trigger the storm
* Travel the island
* And maybe witness a strike

---

		Visual Spawn Event

	When conditions met :
1. Lightning hits the conductor point
2. Ground trembles
3. Wind vortex forms from dust, stones, debris
4. The Guardian shapes itself from the vortex

	Very visible from far away.

	Players nearby immediately know :

> something major just happened.

---

		Behavior Philosophy

	They are not aggressive hunters.

	They behave like territorial storm elementals :
* Slow drifting vortex movement
* Pulling debris and stones around them
* Lightning arcing from their body to terrain
* Attacking anything that stays in the area too long

	Fighting them feels like fighting weather, not a creature.

---

		Time of Day Influence

	They can only manifest :

| Time         | Can Spawn?       |
| ------------ | ---------------- |
| Day          | ❌ No             |
| Sunset       | ⚠️ Rare chance   |
| Night        | ✅ Primary window |
| Stormy night | ✅ Highest chance |

	So players cannot schedule them easily.

---

		Why Semi-Boss (not Elite)

	Because defeating one should feel like :
* A group effort
* A rare opportunity
* A memorable island moment

	And not part of grinding.
	No quests. No markers. No guarantees.

---

		After Defeat

	When defeated :
* Vortex collapses
* Stones fall to ground
* Wind dies instantly
* Storm weakens slightly for several minutes in that region

	Then the 12–26h hidden cooldown starts.

---

	What This Creates : 
* Players talk to each other: "Guardian spawned near the canyon!"
* Totem mini-game becomes meaningful
* Island traversal during storm becomes thrilling
* No farming, no camping, no boredom

