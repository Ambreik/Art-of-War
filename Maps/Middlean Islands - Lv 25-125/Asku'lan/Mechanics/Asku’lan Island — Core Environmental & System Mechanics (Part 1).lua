			Asku’lan Island — Core Environmental & System Mechanics (Part 1)

---

	Purpose : Define the environmental rulebook that governs all gameplay on Asku’lan before any POI mechanics are added.
	Asku’lan is not quest-driven, not settlement-driven, and not boss-driven.

> Asku’lan is traversal-driven, weather-driven, and totem-state–driven.

	Everything a player experiences on this island is controlled by :
1. Height and verticality
2. Exposure to the sky and storms
3. The Skyreach Spire Totem state
4. Natural terrain interaction (cliffs, rivers, vegetation, stone)

---

		1. Island Gameplay Philosophy

	On Asku’lan, the environment is the primary “actor”.

* Players are exposed, not protected
* Movement is skill-based, not path-based
* Weather is gameplay, not ambience
* The Totem is global state control, not a local mini-game
* Creatures exist inside this system, not outside it

---

		2. Verticality as a Gameplay Layer

	Height on Asku’lan is not visual design — it is a mechanic.

	Height Tiers : 

| Tier           | Examples                                   | Mechanical Meaning                       |
| -------------- | ------------------------------------------ | ---------------------------------------- |
| Low Ground     | riverbeds, jungle floor, stone paths       | Minimal storm exposure, dense vegetation |
| Mid Elevation  | broken cliffs, ledges, plateaus            | Moderate exposure, traversal risk        |
| High Elevation | spires, open cliff edges, totem approaches | Maximum exposure to storms and lightning |

	Effect :
* The higher the player is, the more the island systems affect them (see Storm & Lightning below).

---

		3. Exposure System (Sky Exposure)

	Every location on Asku’lan implicitly falls into one of two categories :

| Type    | Examples                                   | Effect                                   |
| ------- | ------------------------------------------ | ---------------------------------------- |
| Covered | under trees, caves, overhangs, canyon cuts | Reduced interaction with storm mechanics |
| Exposed | cliffs, spires, bridges, open rock faces   | Full interaction with storm mechanics    |

	This is not shown in UI. It is felt through gameplay.

---

		4. Storm & Lightning as Active Mechanics

	Storms are not cosmetic on Asku’lan.

	When storm conditions are active :
* Lightning can strike exposed terrain
* High elevation increases strike probability
* Metal armor slightly increases strike chance
* Water surfaces conduct lightning in small radius
* Stone spires and tall objects act as lightning attractors

	Player impact :
* Direct strike → heavy damage
* Near strike → stagger + partial damage
* Conducted strike via water → AoE shock

	Covered areas significantly reduce these risks.

---

		5. Terrain Interaction Rules

	The island terrain itself influences safety and movement.

	Vegetation (Dense jungle, roots, foliage) : 
* Reduces lightning risk
* Reduces visibility for creatures
* Slows player movement slightly
* Encourages ground traversal over cliff traversal

	Stone & Cliff Faces : 
* Increase exposure
* Required for traversal paths
* Often part of zip line networks
* Higher risk during storms

	Rivers & Water Streams :
* Safe during clear weather
* Dangerous during storms (lightning conduction)
* Natural navigation paths when storms are inactive

---

		6. Traversal as Core Gameplay (Zip Lines & Climb Paths)

	As described in Area Info, traversal is a primary island mechanic.

* Zip lines connect high-risk/high-exposure zones
* They allow fast movement but during storms become dangerous
* Climbing paths are slower but often safer due to partial cover
* Players must choose between speed vs safety.

	Traversal is never neutral on Asku’lan.

---

		7. The Skyreach Spire Totem — Global State Anchor

	The Totem is not a POI mechanic.
	It is an island-wide state controller.

	Depending on its state (defined later in Totem file integration) :

* Storm intensity changes
* Lightning frequency changes
* Creature behavior shifts
* Thunder Guardians may become active
* Some traversal paths become more or less dangerous

	This makes the entire island feel “alive” and reactive.

---

		8. Natural Safety vs Natural Danger

	There are no settlements, no guards, no safe hubs.

	Safety comes from :
* Staying low
* Staying covered
* Avoiding spires during storms
* Observing weather before traversing

	Danger comes from :
* Height
* Exposure
* Water during storms
* Totem state changes

---

		9. Player Learning Curve (Unspoken Tutorial)

	Without quests, players learn Asku’lan by experience :
1. First lightning strike teaches exposure
2. First water shock teaches river danger
3. First zip line during storm teaches traversal risk
4. Totem activation teaches island-wide reaction

	The island teaches through consequence, not instructions.

