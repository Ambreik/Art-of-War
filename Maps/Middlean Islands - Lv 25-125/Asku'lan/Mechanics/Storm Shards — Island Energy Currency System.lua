			Storm Shards — Island Energy Currency System

---

		1. Description

	"Storm Shards" are crystallized fragments of atmospheric lightning energy formed within Asku’lan’s unstable weather system. They are not natural minerals, but 
residual storm essence condensed into physical form after violent electrical discharges interact with the island’s terrain and creatures.
	These fragments act as a regional energy currency, used primarily at "Emerald Bay Dock" to convert into "Thunder Chests", representing the island’s ability to 
"compress storm chaos into usable form."

	"Storm Shards" are not commonly dropped loot — they are considered rare atmospheric byproducts of high-risk combat conditions.

---

		2. How to Obtain

	"Storm Shards" can only be obtained through monster encounters on "Asku’lan Island", with drop chances influenced by :
* Monster rank (primary factor)
* Combat location (storm exposure zones increase chance)
* Weather state during kill (storm / lightning storms increase drop rate)
* Kill method efficiency (solo vs group scaling slight variance)

	They are not dropped from passive gathering, NPCs, or environmental objects.

---

		3. Drop Rate System (By Monster Rank)

	Rank I Monsters (Low Tier Wildlife / Basic Creatures) : 
* Base Drop Chance: 0.2%
* Storm Weather Bonus: +0.1%
* Final Range: 0.2% – 0.3%

---

	Rank II Monsters (Standard Combat Wildlife / Island Predators) : 
* Base Drop Chance: 0.5%
* Storm Weather Bonus: +0.3%
* Final Range: 0.5% – 0.8%

---

	Rank III Monsters (Elite Creatures / Environmental Mutations) : 
* Base Drop Chance: 1.2%
* Storm Weather Bonus: +0.8%
* Final Range: 1.2% – 2.0%

---

	Rank IV Monsters (Rare / Semi-Boss Entities) : 
* Base Drop Chance: 3.0%
* Storm Weather Bonus: +2.0%
* Final Range: 3.0% – 5.0%

---

		4. Regional Influence (Island Zone Modifiers)

	"Storm Shard" generation is not uniform across "Asku’lan".

	High Storm Activity Zones (Skyreach Spire, Cliff Regions, Totem Areas) : 
* +25% drop rate multiplier
* Lightning strike proximity bonus chance
* Higher chance of “Double Shard” drop (very rare)

---

	Coastal / Dock Regions (Emerald Bay vicinity) : 
* Standard drop rates (baseline system)
* No environmental bonus

---

	Interior Zones (Forest / Low elevation terrain) : 
* -15% drop rate penalty
* Storm exposure reduced = lower shard formation

---

	Hazard Zones (Guardian Spawn Areas / High Wind Corridors) : 
* +40% drop rate multiplier
* Only active during storm or post-lightning cycles
* Highest chance for elite-tier shard drops

---

		5. Special Drop Conditions

	Storm Shards have conditional behavior mechanics :
*Lightning Kill Bonus

	If a monster is killed :
* during a lightning strike animation OR
* within 5 seconds after a lightning event in the area

	→ Drop chance is doubled (stacking with zone bonuses)

---

	Wind Overload Condition

	If combat occurs in high wind zones :
* +10% additional shard chance

---

		6. Economy Role

	Storm Shards function as a non-inflationary regional currency, meaning :
* They are not tradable on open market (default rule)
* Only usable at "Emerald Bay Harbormaster" conversion system
* Cannot be converted into gold directly
* Designed to control island progression pacing

---

		7. Conversion System Link

	At Emerald Bay Dock :
* 10 × Storm Shards → 1 Thunder Chest

	This creates :
* controlled loot funnel
* progression gating for island rewards
* indirect tie to Totem mini-game system

---

		8. Design Philosophy

	"Storm Shards" are intentionally :
* Rare enough to feel valuable
* Common enough in elite gameplay loops to sustain progression
* Fully tied to risk-based combat + environmental interaction
* Not grindable in safe or low-risk farming loops

	They represent:

> "The island rewarding those who survive its instability, not those who farm it."

---

		9. Flavor

	"Storm does not give rewards. It leaves fragments behind when it forgets you survived it."

