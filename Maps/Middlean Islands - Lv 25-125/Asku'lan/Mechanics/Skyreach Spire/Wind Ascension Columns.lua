			Skyreach Spire — Wind Ascension Columns Mechanic

	A traversal mechanic that turns the climb to the Totem into a storm-ridden vertical journey, not a path or a jump puzzle.
	This is the signature POI mechanic of "Asku’lan".

	Players do not "climb" the spire.
	They ride the storm upward.

---

		Mechanic Name: "Wind Ascension Columns"

	Short Description : Natural vertical wind tornadoes form around the base and mid-levels of the Spire, acting as unstable aerial lifts that carry players upward 
toward the Totem plateau — while the storm actively tries to throw them off.

---

		Design Purpose

	This solves multiple design goals at once :
* Makes reaching the Totem an experience, not travel
* Uses the island’s storm identity in gameplay
* Prevents mounts / trivial climbing
* Creates risk, timing, and spectacle
* Makes players visible to others while ascending (great MMO feel)

---

		Where They Appear

	Wind Columns appear at :
1. Base of the Spire (entry point)
2. Mid-ledge rock outcrop
3. Upper broken cliff ring
4. Final lift near Totem plateau

	Players must chain these columns to reach the top.

---

		How Players Use Them

	When a player steps into the spinning wind column :
* They are lifted vertically in a spiraling motion
* Movement control is limited (slow drift only)
* Camera shakes lightly
* Debris, dust, leaves spiral around

	It feels like being inside a living tornado.

---

		The Hazard Layer 

	While inside a" Wind Column", the storm interacts with the player.

	1. Crosswinds (push mechanic)

	Random side gusts :
* Push the player slightly off center
* If not corrected → player is thrown out of the column
* Player falls to previous level (not death, but setback)

	2. Lightning Interference

	During "Thunder Dominion" :
* Lightning can strike the column
* Player gets stunned mid-air for 1s
* Column destabilizes briefly (faster drift, harder control)

	3. Wind Collapse Windows

	Very rarely :
* Column weakens for 3–5 seconds
* Player must quickly exit onto a rock ledge
* If not → dropped

	This prevents AFK riding.

---

	Storm State Interaction (important)

| Storm State      | Behavior                                |
| ---------------- | --------------------------------------- |
| Calm             | Columns weak, slow, very safe           |
| Wind State       | Normal behavior                         |
| Thunder Dominion | Hazardous, lightning, strong crosswinds |

	So the Totem mini-game indirectly affects how hard it is to reach the Totem.
	Beautiful systemic loop.

---

	No Other Way Up : 
* No climbable path
* No grappling
* No mount access
* No jump puzzle

	Only the wind.
	This makes the Spire iconic.

---

		MMO Social Effect

	Players below see others spiraling upward in the sky.

	It creates :
> “What are they doing up there?”
> “How do I get up?”

C	uriosity, discovery, spectacle.

---

		Bonus Integration (from Area Info)

	While waiting for a column cycle or recovering from a fall :
* Rare herbs on ledges
* Rare minerals in rock pockets

	Risk vs reward while ascending.

---

		Why This Mechanic Is Excellent for This POI

	Because "Skyreach Spire" is :
* Vertical
* Storm-dominated
* Totem-important
* Traversal-required

	This turns all of that into one coherent mechanic instead of separate ideas.

---

		Player Experience

	First time :

> Confusion → fear → learning → mastery → thrill.

	Later times :

> "Let’s go ride the winds."

	Iconic. Memorable. Pure MMO design.

