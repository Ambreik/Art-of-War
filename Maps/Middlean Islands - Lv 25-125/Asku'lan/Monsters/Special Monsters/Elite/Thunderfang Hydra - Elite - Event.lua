			Thunderfang Hydra

	Ancient Thunder Guardian (System Entity C)

---

		1. General Overview

* Name : Thunderfang Hydra
* Title : Ancient Thunder Guardian – River Convergence Manifestation
* Classification : Elite / Semi-Boss (Event-Spawn Entity)
* System Origin : Totem of the Thunder Guardians – Lightning Convergence Output
* Faction Alignment : Neutral Hostile (Ancient System Entity)
* Location : Hidden River Gorge (Asku’lan Island)
* Spawn Type : Event-Based / River Storm Condition Entity

---

		2. Appearance

	The Thunderfang Hydra does not exist as a single organism, but as a network of interconnected pressure vortices embedded within the river system itself. Its
presence is only partially visible, revealing itself through unnatural distortions in water flow and sudden lightning refractions beneath the river surface.
	What appears as heads are actually independent storm nodes — rotating spheres of compressed water, wind, and electrical discharge suspended within the river 
current. These nodes are connected through invisible pressure channels beneath the water, forming a living hydraulic structure that behaves like a unified 
intelligence.
	The river itself seems to react to its presence, flowing against natural direction in certain segments, as if the terrain has lost trust in gravity. Lightning 
travels through the water not as an external strike, but as a native current inside the river system, illuminating the depths in unpredictable pulses.

	When fully active, the gorge becomes a living storm circuit — water, wind, and electricity forming a continuous loop of motion with no stable center.

---

		3. Behavior

	The Thunderfang Hydra functions as a flow control entity, meaning it does not chase or patrol. Instead, it manipulates river physics to control player 
positioning.

	It forces movement through environmental pressure :
* currents push players into hazards
* water zones become conductive traps
* terrain footing becomes unstable or slippery

	It reacts aggressively to attempts at splitting group positioning or avoiding water contact entirely.
	Unlike the other Guardians, it thrives on continuous player displacement, treating stillness as resistance and movement as vulnerability.

---

		4. Skills

	"River Fang Surge" : Generates sudden hydraulic pressure spikes that slam players into terrain edges or natural barriers.

---

	"Conductive Flow Chain" : Lightning travels through water channels, chaining between players standing in connected water paths.

---

	"Whirlpool Lockdown" : Creates circular suction zones that trap players inside rotating water currents, limiting escape routes and movement control.

---

	"Storm Hydration Burst" : A large-scale discharge where all active water nodes release simultaneous lightning-infused pressure waves across the gorge.

---

		5. Combat Behavior

* Prioritizes controlling battlefield flow rather than direct damage
* Dynamically redirects water currents based on player positioning
* Punishes grouped movement inside water zones
* Encourages forced dispersion through environmental hazards
* Gains strength during storm or heavy rainfall conditions

---

		6. Spawn Conditions

* Triggered via Totem of the Thunder Guardians system output
* Requires Hidden River Gorge water activity threshold
* Must coincide with storm surge or lightning-linked weather state
* Enters 18–24 hour respawn cycle after defeat

---

		7. Drops

* Storm Shards (moderate-high drop rate relative to Hydra difficulty tier)
* River Conductive Core (crafting / Totem synergy material)
* Rare chance: Hydra Flow Fragment (used in mini-game enhancement system)

---

		8. Vulnerabilities

* Reduced effectiveness when water flow is interrupted or redirected
* Grounding effects reduce lightning propagation efficiency
* Weakest during low-water or drought-like environmental cycles

