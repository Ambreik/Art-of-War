	Ancient Thunder Guardian (System Entity B)

---

		1. General Overview

* Name : Skyreach Elemental
* Title : Ancient Thunder Guardian – Altitude Pressure Manifestation
* Classification : Elite / Semi-Boss (Event-Spawn Entity)
* System Origin : Totem of the Thunder Guardians – Lightning Convergence Output
* Faction Alignment : Neutral Hostile (Ancient System Entity)
* Location : Northern High Ridge (Asku’lan Island)
* Spawn Type : Event-Based / Altitude Storm Condition Entity

---

		2. Appearance

	The Skyreach Elemental exists as a towering vertical distortion of atmospheric pressure anchored to the high ridge winds of Asku’lan. Its form is not grounded 
in physical matter but suspended in layers of compressed air that shift constantly, forming unstable geometric patterns that resemble shattered storm architecture.
	At its core, faint lightning filaments pulse like exposed nerve pathways, suspended within a floating lattice of wind pressure. This lattice bends and stretches
without breaking, creating the illusion of a humanoid silhouette that is only briefly coherent during lightning flashes.
	Where a head might be interpreted, there is instead a rotating convergence point of atmospheric density — a gravitational storm node that pulls in surrounding 
wind and lightning into continuous circulation. Its “limbs” extend outward as vertical air columns that anchor to the terrain below, as if the sky itself is 
attempting to root itself into the mountain.
	When idle, it remains suspended above the ridge line, barely touching the ground with unstable pressure threads that crackle softly like distant thunder trapped
inside glass.

---

		3. Behavior

	The Skyreach Elemental behaves as a pressure-based battlefield controller rather than a direct attacker. It monitors elevation changes, positioning advantage, 
and terrain usage.
	Players attempting to maintain stable high-ground positioning are actively disrupted. The entity continuously modifies local gravity and wind direction to 
prevent static combat control.
	It escalates its aggression when players rely on predictable terrain advantage or ranged camping strategies.
	Unlike predator-type entities, it does not chase — it redefines the space around the player until survival becomes unstable.

