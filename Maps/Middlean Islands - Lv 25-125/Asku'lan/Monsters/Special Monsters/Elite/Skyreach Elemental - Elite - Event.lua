---

	"Thunderline Grid" : Creates vertical lightning lines across terrain, segmenting the battlefield into dangerous traversal zones.

---

	"Airlock Dome" : Compresses surrounding air into a sealed combat arena, restricting escape routes and forcing engagement.

---

	"Apex Skybreak Sequence" : A multi-point lightning strike pattern descending from randomized sky coordinates, punishing stationary or clustered positioning.

