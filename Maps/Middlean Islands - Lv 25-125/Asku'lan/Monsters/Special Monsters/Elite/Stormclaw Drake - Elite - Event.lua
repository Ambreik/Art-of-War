		10. Lore Function (System Role)

	"The Stormclaw Drake" is a fractured enforcement layer of the Primordial Wind God’s predatory logic — representing the concept that movement itself is a flaw to
be punished in unstable storm ecosystems.

	It exists in "Asku’lan" not as a creature, but as a persistent correction algorithm inside living weather systems.

