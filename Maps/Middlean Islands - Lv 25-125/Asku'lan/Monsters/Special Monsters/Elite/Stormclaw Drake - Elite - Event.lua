			STORMCLAW DRAKE

	Ancient Thunder Guardian (System Entity A)

---

		1. General Overview

* Name : Stormclaw Drake
* Title : Ancient Thunder Guardian – Wind Predator Manifestation
* Classification : Elite / Semi-Boss (Event-Spawn Entity)
* System Origin : Totem of the Thunder Guardians – Lightning Convergence Output
* Faction Alignment : Neutral Hostile (Ancient System Entity)
* Location : Emerald Jungle Clearing (Asku’lan Island)
* Spawn Type : Event-Based / Time-Restricted World Entity

---

		2. Appearance

	The Stormclaw Drake is not a conventional creature with stable physical form, but rather a constantly shifting mass of compressed wind and fractured lightning 
suspended in a predatory silhouette. At a distance, it resembles a draconic shape carved from storm clouds, but this shape never remains constant. Its body 
continuously fractures into spiraling gusts, reforming in violent pulses that mimic breathing.

	Its “skin” is composed of layered wind shear currents, visible as rotating transparent blades of air that distort the environment around it. Lightning does not 
strike it — it circulates within its form like blood, occasionally leaking through cracks in its storm structure and discharging into nearby trees or ground.

	Where a head would be, there is a vortex of condensed pressure that reacts to movement, constantly tracking targets with unnatural precision. Its wings are not 
physical limbs but sweeping storm fronts that extend and retract like living weather systems. When it moves, it does not fly — it erases distance, appearing 
between positions through instantaneous wind displacement.

---

		3. Behavior

	The Stormclaw Drake behaves like a predatory intelligence embedded within atmospheric pressure. It does not roam randomly. Instead, it patrols invisible wind 
corridors inside the jungle, reacting primarily to movement velocity and directional changes.

	It becomes more aggressive when players sprint, dash, or attempt to reposition quickly through open jungle paths. It deliberately forces combat into narrow 
terrain zones where wind pressure is strongest.

	If players remain still or move cautiously, the entity enters an “observational drift state,” circling above without attacking, as if evaluating whether the 
target is worth engaging.

---

		4. Skills

	"Windclaw Rift" : A slicing arc of compressed air that travels in a linear path. It ignores foliage and terrain and is designed to punish predictable movement 
lines.

	"Predator Wind Lock" : Creates a localized pressure field that reduces movement speed and interrupts sprint/dash mechanics inside jungle corridors.

	"Echo Fracture Illusions" : Generates multiple wind-based afterimages of the player’s last movements, causing misdirection and forced targeting errors.

	"Skyborne Dive Judgment" : The Stormclaw Drake dissolves into storm fragments and reappears above the target, crashing down with a lightning-infused impact 
burst.

---

		5. Combat Behavior

* Highly responsive to movement speed spikes
* Prioritizes players who separate from group formations
* Gains combat advantage in open terrain
* Weakens slightly in tight, enclosed jungle paths
* Designed as a “movement discipline check” encounter

---

		6. Spawn Conditions

* Triggered only through "Totem of the Thunder Guardians" mini-game output
* Requires jungle-aligned storm convergence state in Emerald Jungle Clearing
* Subject to internal cooldown (12+ hours minimum world respawn lock)
* Cannot be farmed continuously due to forced storm recalibration cycle

---

		7. Drops

