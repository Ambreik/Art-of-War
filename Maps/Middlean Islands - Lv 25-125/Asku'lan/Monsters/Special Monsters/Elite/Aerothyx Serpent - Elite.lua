---

		5. Interaction Mechanics

* Players cannot mount or control the Serpent directly
* Players must align with wind lift zones to “catch” its flow
* Acts as a timed traversal window system (natural elevator mechanic)
* Only one active Serpent corridor per region at a time

---

		6. Spawn Conditions

* Random spawn interval: 20 minutes – 5 hours (real-time system variance)
* Spawn triggered by :
	* Wind intensity threshold near Skyreach Spire
	* Atmospheric pressure instability cycles
	* Storm cycle synchronization events
* Despawns naturally after corridor completion or destabilization

