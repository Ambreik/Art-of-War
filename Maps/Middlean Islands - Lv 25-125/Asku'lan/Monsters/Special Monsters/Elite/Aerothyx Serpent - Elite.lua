		10. Lore Function (System Role)

	"The Aerothyx Serpent" is a residual expression of the Primordial Wind God’s transportation logic, representing the idea that movement between heights should 
not be forced, but negotiated through living atmospheric systems.

	It exists not as a creature, but as a natural mobility infrastructure embedded into Asku’lan’s wind architecture.

