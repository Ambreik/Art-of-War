			Open Sea Drift Risk

* Type : Dynamic / Consequence
* Function : Punishes navigation failure
* Player Interaction :
	* Recovering position / escaping drift
* System Behavior :
	* Strong currents can push player into :
		* Deep sea zone
	* Effects :
		* Increased stamina drain
		* Stronger creatures
		* Disorientation (no clear landmarks)
* Conditions / States :
	* Threshold distance from POI

