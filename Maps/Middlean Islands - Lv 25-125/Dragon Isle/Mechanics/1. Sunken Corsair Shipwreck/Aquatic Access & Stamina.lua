			Aquatic Access & Stamina

* Type : Core System
* Function : Controls player ability to reach and explore submerged POI
* Player Interaction :
	* Swimming / diving required
	* Manage stamina / fatigue / breath
* System Behavior :
	* Stamina drains over time while swimming
	* Faster drain when:
		* Carrying loot
		* Fighting
		* Against currents
	* Risk states:
		* Fatigue → Slowed movement
		* Exhaustion → Drowning risk
* Conditions / States :
	* Surface vs Submerged layers
	* Safe return threshold (distance from shore)
* Expansion Hooks :
	* Diving gear / potions
	* Mounts (aquatic)
	* Linked to other underwater POIs

