			Aquatic Combat Constraint

* Type : Core / Interaction
* Function : Alters combat behavior underwater
* Player Interaction :
	* Fighting while submerged
* System Behavior :
	* Reduced mobility
	* Altered attack speed / effectiveness
	* Limited skill usage (depending on class)
* Conditions / States :
	* Surface combat vs underwater combat differences
* Expansion Hooks :
	* Underwater-specific abilities
	* Class advantages/disadvantages

