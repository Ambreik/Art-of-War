			Aquatic Fishing Nod

---

	Aquatic Fishing Node : 
* Type : Environmental / Resource
* Function : Specialized fishing ecosystem

---

	Player Interaction :
* Fishing in specific underwater zones

---

		System Behavior

---

	Fish Pool (Exotic Species) : 

	1. Coralfin Dartschool (School Type) : 
* Small, fast-moving fish cluster
* Found in shallow–mid depth near reef structures
* High catch rate, low individual value
* Used mainly for processing / crafting chains

---

	2. Abyssglow Lanternschool (School Type) : 
* Bioluminescent fish moving in synchronized clusters
* Found in deep compartments / low-light zones
* Medium catch rate
* Higher rarity than Coralfin

---

	3. Tidebreaker Eel (From Area Identity – Pirate/Coastal Integration) : 
* Solitary or small cluster spawn
* Found near :
	* Wreck interiors
	* Metallic debris / ship remains
* Low catch rate
* Considered valuable / rare material fish

---

	Catch Rate Modifiers : 
* Depth : 
	* Shallow → Common fish
	* Deep → Rare species unlocked
* Time : 
	* Day → Higher Coralfin presence
	* Night → Increased Abyssglow spawn
* Current Intensity : 
	* Low → Stable fishing
	* Medium → Increased rare chance
	* High → Reduced catch success, but higher reward pool

---

		Conditions / States

---

	Node Depletion : 
* Each node has limited extraction count
* Overfishing leads to :
	* Reduced catch rate
	* Lower rarity output

---

	Node Regeneration :
* Respawn Timer: 30–45 minutes
* Fully restores fish pool and quality

