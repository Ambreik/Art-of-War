			Reef Resource Fishing System

* Type : Core / Resource / Interaction
* Function : Defines main activity loop

---

	Player Interaction :
* Fish in designated reef pools
* Collect sunken fragments

---

		System Behavior :

	Fishing Pools :
* Contain:
	* Rare fish
	* Exotic species
* Limited charges per pool
* Regenerate over time

---

	Sunken Treasure Fragments :
* Found via :
	* Fishing
	* Direct interaction (low visibility nodes)

---

	Conditions / States :
* Active pool
* Depleted pool
* Regenerating pool

---

	Respawn Timers :
* Pools: 35–75 minutes
* Fragments: 35–90 minutes

---
