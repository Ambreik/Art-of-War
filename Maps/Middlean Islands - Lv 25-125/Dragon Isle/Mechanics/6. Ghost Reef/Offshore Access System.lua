			Offshore Access System

* Type : Core / Environmental / Movement
* Function : Controls how players reach the POI

---

	Player Interaction :
* Reach reef via :
	* Boat
	* Swimming (requires stamina management)

---

	System Behavior :
* Distance from shore creates :
	* Travel commitment
	* Risk exposure
* Swimming :
	* Consumes stamina over time
	* Risk of failure if mismanaged

---

	Conditions / States :
* Accessible (boat)
* Risk access (swimming)

