			Reef Disturbance System (Core Loop Driver)

* Type : Core / Hidden / Dynamic
* Function : Tracks player activity → drives escalation

---

	Player Interaction :
* Repeated fishing
* Repeated resource harvesting

---

	System Behavior :
Each action increases "Disturbance Level"

---

	Disturbance States :
* Calm Reef :
	* Normal fishing
	* No threat

---

* Disturbed Reef : 
	* Slight environmental changes
	* Reduced pool stability

---

* Agitated Reef : 
	* High activity detected
	* Pre-spawn phase

