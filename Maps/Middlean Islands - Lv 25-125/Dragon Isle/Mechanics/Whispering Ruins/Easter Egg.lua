			Easter Egg

	A rare event occurs when:

* All tablets in a ruins cluster are discovered quickly
* Elara is present nearby

	Effects :

* A faint dragon-shaped energy apparition appears
* Whispering voices intensify briefly
* Environmental lighting subtly changes (shimmering glyphs, soft dragon-shaped shadows)

	Note : No combat occurs — this is purely an emergent narrative reward for observant players.

