			Ancient Tablet Interaction

	Players can interact with tablets to :
* Collect lore fragments for the "Living Water Chronicle" codex
* Potentially obtain a "map fragment" ("Fragment of the Whispering Jungle")
* Trigger subtle environmental effects that hint at hidden discovery opportunities

	Environmental Effects Include :
* Glyphs glowing brighter when a fragment is present
* Faint whispering sounds guiding attentive players
* Soft pulses of dragon-energy particles in the vicinity
* Minor directional hints (like faint light shafts or flickering shadows) that lead to adjacent tablets

	Mechanics Details :
* Each tablet can be interacted with once per player
* Map fragment appears randomly on certain tablets, so players may need to explore all ruins in the area
* Some tablets only glow or activate fully when Elara is present, tying her mechanics into this discovery process

