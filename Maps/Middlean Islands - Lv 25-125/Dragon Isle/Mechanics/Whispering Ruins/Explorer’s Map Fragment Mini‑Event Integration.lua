			Explorer’s Map Fragment Mini‑Event Integration

* Fragment Type : Fragment of the Whispering Jungle
* Drop Mechanic : Player interaction with specific tablets may reveal the fragment.

	Meta-Event Flow :
1. Collect fragments from multiple POIs across Dragon Isle (Whispering Ruins, Broken Spire Lookout, Lake of Reflection, Sunken Totem, Blackwater Landing)
2. Assemble fragments into a complete Explorer’s Map at a special interface
3. Map reveals the exact location of the hidden "Seafarer’s Hidden Cache"
4. Full cache spawns once per day, lasts 15 minutes, can be opened solo or in groups
5. Partial maps give directional hints but require players to explore further

	Purpose : This mechanic encourages revisiting multiple locations, rewards exploration and puzzle-solving, and reinforces the island as a cohesive, 
interconnected environment.

