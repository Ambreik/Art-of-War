			Pirate Cache Loot System

---

	Type : Core / Reward / Exploration

	Function : Provides repeatable treasure discovery and acts as a secondary distribution point for pirate systems across the island

---

	Player Interaction :
* Explore cave interior
* Locate hidden / semi-hidden chests
* Open caches for rewards

---

	System Behavior :

---

	Chest Types :

* Standard Hidden Cache : 
	* Common spawn
	* Light concealment (corners, behind rocks, foliage)
* Buried Pirate Cache (Variant) : 
	* Slightly hidden under debris or sand
	* Requires interaction (dig / clear)

---

	Loot Distribution (Integrated System)

---

	A. Core Loot (Always Present Pool) : 

* Gold (variable amounts)
* Basic pirate supplies :
	* Rope bundles
	* Old tools
	* Trade goods

---

	B. Resource Loot : 
	
* Herbs (low–mid tier)
* Low-tier rare minerals
* Crafting scraps (salvaged materials)

---

	C. Pirate System Loot (IMPORTANT INTEGRATION)

---

	1. Pirate Tokens

* Small chance per chest
* Used for :
	* Trading (future vendors / systems)
	* Unlocking pirate-related interactions

---

	2. Weathered Map Fragments

* Low chance drop

---

	Behavior :
* Functions exactly like the system from "Tidebreaker Cove"
* Fragments :
	* Provide vague clues
	* Lead to hidden caches across the island

---

	Design Role :

👉 Expands pirate system beyond one POI
👉 Encourages island-wide exploration

---

	3. Map Fragment Variants (Low Chance Upgrade)

* More detailed fragment :
	* Narrower search area
	* Higher reward cache

---

	D. Cosmetic & Flavor Items (Identity Layer) 

---

	Wearables (Low Chance) : 
* Pirate Hat (various worn styles)
* Tattered Bandana
* Pirate Coat (cosmetic, non-armor)

---

	Purpose :
* Visual identity
* Roleplay / collection

---

	E. Utility Items

---

* Old Lockpicks (limited use)
* Salvage Tools
* Basic Fishing Supplies

---

	Function :
* Small gameplay advantages
* Reinforces “scavenger” theme

---

	F. “Toy” Items

---

	Examples:

* "Rusty Compass" : 
	* Spins randomly
	* Occasionally aligns briefly toward a hidden cache

---

* "Cracked Spyglass" : 
	* Visual zoom
	* Chance to highlight distant interactables (very short duration)

---

* "Dice of the Damned" : 
	* Roll interaction :
		* Small buff OR small debuff

---

	Design Purpose :

👉 Non-essential
👉 Memorable
👉 Player-driven fun

---

	Respawn Logic :
* Chests respawn :
	* 30–180 minutes
* Variant caches :
	* Longer respawn :
		* 240–3600 minutes

---

	Conditions / States :
* Available
* Looted
* Regenerating

---

	System Connections :
* Weathered Map Discovery System (Tidebreaker Cove)
* Pirate Token Economy (future expansion)
* Exploration Systems
* Hidden Cache Systems across Dragon Isle

---

		Expansion Hooks

---

	Cross-POI Integration : 
* Maps found here → lead to :
	* Other pirate caves
	* Shipwreck (Sunken Corsair)
	* Hidden island spots

---

	Rare Cache Variant : 
* Very low chance :
	* Contains :
		* Multiple map fragments
		* Higher token count
		* Unique cosmetic

---

	Key-Based Locked Cache :
* Requires :
	* Item from another pirate POI

