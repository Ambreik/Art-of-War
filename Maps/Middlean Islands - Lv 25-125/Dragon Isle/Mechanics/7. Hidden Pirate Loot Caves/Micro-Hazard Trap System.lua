			Micro-Hazard Trap System
			
* Type : Environmental / Light Risk
* Function : Adds tension without dominating gameplay

---

	Player Interaction :
* Observe environment
* Avoid or navigate hazards

---

	System Behavior :

	Falling Rocks : 
* Triggered by:
	* Movement through certain areas
* Effect:
	* Minor damage
	* Brief path disruption

---

	Weak Bridges : 
* Behavior :
	* Collapse after player steps on them
* Effect :
	* Short fall / reposition

---

	Hidden Spikes : 
* Triggered by :
	* Stepping on specific ground spots
* Effect :
	* Minor damage

---

	Conditions / States :
* Armed
* Triggered
* Reset (after short duration)

