			Skyreach Spire Puzzle System

---

		1. System Identity

* Type : Core / Physical Puzzle / Multi-POI Integration
* Function : Final alignment puzzle using **learned mechanics**, not collected items

---

	Core Concept :

> Player must apply knowledge from :
* Light reflection (Mirrorstone)
* Directional clues (Whispering Stones)
* Environmental awareness

---

---

		2. Core System: Spire Alignment Mechanism

---

	A. Structure

	At Skyreach Spire :
* 3–4 Ancient Stone Pillars
* 1 Central Receiver (core mechanism)

---

---

	B. Player Interaction

	Each pillar can be :
* Rotated
* Aligned toward direction

---

---

	C. System Logic

---

	Step 1: Direction Alignment

* Player must align pillars toward :
	* Specific directions learned from Whispering Stones

---

👉 Not told directly
👉 Learned through exploration

---

---

	Step 2: Light Interaction (Mirrorstone Connection)

* When aligned correctly :

👉 Light begins forming between pillars

---

* Same logic as :
  👉 Mirrorstone Cave system

---

---

	Step 3: Beam Completion

* All pillars aligned correctly → beam reaches central node

---

👉 Unlock condition triggered

---

---

		3. Activation Condition System

---

	Activation Windows :
* Night Time
	OR
* Elara Active

---

	Behavior :
* During activation :
	* Beams visible
	* Feedback clearer

---

* Outside activation :
	* Puzzle still possible
	* Much harder (low feedback)

---

---

		4. Whisper Integration

---

	Whispering Stones do NOT give fragments.

	They provide :
* Directional knowledge

---

	Example:

* "The wind answers from the east"
	→ East alignment

* "Three voices converge where the sky breaks"
	→ Multi-pillar alignment

---

👉 This keeps system :
✔ grounded
✔ immersive
✔ non-UI dependent

---

---

		5. Failure System

---

* Incorrect alignment :
	* Beam breaks
	* Pillars dim

---

* No punishment :
	* Just reset

---

---

		6. Completion System

---

	When solved :
* Central node activates
* Light beam shoots upward
* Spire reacts (visual event)

---

---

		7. Reward System

---

	Rewards :
* Rare crafting material
* Utility item
* Minor unique artifact

---

---

	Example Items :

* "Skyreach Core Fragment"
	* Used in advanced crafting

---

* "Resonant Compass"
	* Improves Whispering Stones accuracy

---

---

		8. System Connections

---

* Mirrorstone Cave → teaches light logic
* Whispering Stones → teaches direction
* Entire island → feeds knowledge

