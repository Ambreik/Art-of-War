			Tide Access System

* Type : Core / Environmental / Dynamic
* Function : Controls availability of the POI

---

	Player Interaction :
* Access area only during low tide
* Must track or discover tide timing

---

	System Behavior :

* Tide cycles :
	* High Tide → Area inaccessible
	* Low Tide → Area fully accessible
* Transition phases :
	* Rising tide (limited time window)
	* Receding tide (entry phase)

---

	Conditions / States :
* High Tide (blocked)
* Low Tide (open)
* Transition (risk phase)

---

