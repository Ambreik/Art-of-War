			Field Research System

---

		Core Concept : 

	The "Field Research System" allows players to actively study Dragon Isle’s jungle ecosystem by :
* Collecting plant samples
* Observing animal behavior
* Investigating natural anomalies

	All actions contribute to a unified system called : "Research Progress"

---

		1. Research Categories : 

	The system is divided into 3 main research paths :

---

		A. Botanical Research (Plant Sampling)

	Players can gather samples from rare or notable jungle plants.

---

	Example Plants : 

* "Emberleaf Fern"
	* Warm to the touch
	* Found near volcanic soil patches

* "Glowcap Fungus"
	* Emits faint blue light
	* Found in shaded, damp areas

* "Spinevine Cluster"
	* Covered in small thorns
	* Reacts when approached

* "Mistbloom Flower"
	* Releases vapor when disturbed
	* Found near water sources

* "Ironroot Bulb"
	* Hard outer shell
	* Requires interaction (not simple gathering)

---

	Interaction Types : 

* "Harvest Sample"
* "Inspect Plant"
* "Observe Reaction" (trigger-based plants)

---

		B. Zoological Research (Animal Behavior)

	Players observe creatures without engaging in combat.

---

	How Observation Works : 

Players must :
* Stay within a safe observation radius
* Avoid:
	* Attacking
	* Sudden movement (optional future mechanic)
* Maintain line of sight for a short duration

---

	Example Behaviors : 

* "Feeding Patterns"
	* Creature stops and consumes environment resource
* "Territorial Display"
	* Creature roars, marks area, or patrols aggressively
* "Pack Coordination"
	* Multiple creatures move and react together
* "Hunting Behavior"
	* Creature stalks prey before attacking
* "Resting State"
	* Creature becomes passive temporarily

---

	Failure Conditions : 

* Attacking the creature
* Getting too close
* Breaking line of sight too early

---

		C. Anomaly Research (Environmental Study)

	Players investigate strange or unstable phenomena.

---

	Example Anomalies : 

* "Shimmering Air Distortion"
	* Slight visual warping
	* May indicate hidden energy
* "Burning Soil Patches"
	* Ground emits heat without fire
* "Whispering Growths"
	* Plant clusters that emit faint sounds
* "Unstable Water Pools"
	* Water surface moves unnaturally
* "Crystalline Residue"
	* Left behind by unknown events or creatures

---

	Interaction Types : 

* "Analyze"
* "Stabilize" (optional interaction)
* "Record Observation"

---

		2. Research Progress System

---

	Core Idea : 

Each successful interaction contributes to :

	"Research Progress"

Tracked per category :
* Botanical
* Zoological
* Anomaly

---

	Progression Mechanics : 

* Each action grants:
	* Small research points
* Completing thresholds unlocks:
	* New knowledge tiers
	* Small rewards

---

	Example Progress Tiers : 

| Tier     | Requirement        | Effect               |
| -------- | ------------------ | -------------------- |
| Tier I   | Basic interactions | Unlock minor rewards |
| Tier II  | Consistent study   | Improved efficiency  |
| Tier III | Advanced research  | Passive bonuses      |

---

		3. Rewards System (Utility Focused)

	Rewards are intentionally small but meaningful, as requested.

---

	A. Consumables

* "Field Tonic"
	* Minor stamina regeneration outside combat
* "Clarity Draught"
	* Slight boost to interaction speed (short duration)
* "Herbal Antiseptic"
	* Reduces minor damage over time effects

---

	B. Utility Items

* "Compressed Ration Pack"
	* Efficient inventory food item
* "Sample Kit Upgrade"
	* Increases chance to obtain bonus research points

---

	C. Passive Skill Unlocks (Important)


	Example Passives : 

* "Carrying Capacity I"
	* +5 inventory slots

* "Efficient Gathering"
	* Small chance to gather double plant samples

* "Steady Observer"
	* Reduces failure chance when observing animals

* "Field Awareness"
	* Slightly increases detection of anomalies

---

	Passive Design Philosophy : 

* Low power
* Always useful
* Encourages long-term engagement

---

	4. Risk vs Reward Layer

---

	Safe Approach : 
* Slow progress
* No danger

---

	Aggressive Approach : 
* Faster interactions
* Higher chance to :
	* Trigger anomalies
	* Alert creatures

---

	5. System Integration

---

	Links to Existing Systems : 

