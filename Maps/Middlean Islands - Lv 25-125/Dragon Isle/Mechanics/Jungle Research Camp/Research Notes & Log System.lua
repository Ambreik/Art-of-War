			Research Notes & Log System

---

	Core Concept : "The Research Notes & Log System" allows players to collect fragmented knowledge across Dragon Isle and reconstruct it into a structured codex :

	Research Log Codex : 

This is not just lore — it becomes :

* A progression tracker
* A discovery system
* A soft guidance tool

---

	1. Research Entry Types

All collected notes are categorized for clarity and progression :

---

	A. Field Journals (Researchers’ Notes)

* Written by camp researchers
* Often incomplete or damaged

	Content : 
* Observations about :
	* Plants
	* Creatures
	* Failed experiments

	Tone : 
* Scentific → gradually unstable

---

	B. Ancient Tablets (Ruins Connection)

* Found near:
	* Jungle ruins
	* Hidden stone structures

	Content : 
* References to:
  * Dragon God
  * Seals
  * Elara

---

	C. Expedition Logs

* Left behind by :
	* Lost crews
	* Explorers
	* Sailors

	Content : 
* Shipwreck hints
* Survival attempts
* Warnings

---

	D. Anomaly Records 

* Found near:
	* Strange environmental phenomena

	Content : 
* Inconsistent / strange data
* Observations that “don’t make sense”

---

	2. Research Log Codex (Player Interface Concept)

---

	Structure

The codex is divided into sections :
* "Flora Studies"
* "Fauna Behavior"
* "Anomalies"
* "Ancient Knowledge"
* "Expeditions & Wrecks"

---

	Entry States : 

Each entry progresses through stages :

| State      | Description            |
| ---------- | ---------------------- |
| Fragmented | Partial information    |
| Assembled  | Combined entries       |
| Completed  | Full understanding     |
| Enhanced   | Bonus insight unlocked |

---

	3. Collection Mechanics 

---

	How Players Obtain Entries

* Interact with :
	* Notes
	* Journals
	* Tablets

* Rewarded from :
	* Exploration
	* Research System
	* Quests

---

	Duplicate Handling

* Duplicates :
	* Convert into "Research Progress"
	* Or unlock hidden variants

---

	4. Dynamic Entry Behavior

This is where your system becomes very strong.

---

	A. Progress-Based Updates

	Entries evolve when players :
* Discover new plants
* Observe creatures
* Trigger anomalies

	Example :
* Initial note :
	"The Spinevine reacts to movement…"
* Updated version :
	"The Spinevine reacts aggressively to fast movement and heat."

---

	B. Location-Based Reactions

Entries update when :

* Visiting :
	* Whispering Ruins
	* Broken Spire
	* Underwater Wreck

---

	C. Elara Interaction

	Some entries :
* Glow or activate when near her
* Unlock hidden lines

	Example :
* "This symbol… I’ve seen it before…" (Elara reaction)

---

	5. Entry Combination System

---

	Core Idea : Some knowledge is incomplete unless combined.

---

	Example : 
* Journal fragment → mentions strange water
* Expedition log → ship sank in same area

	Combined result :

* Unlock :
	* Hidden Underwater Wreck hint

---

	Functionality : 
* System auto-detects related entries
* Unlocks :
	* New codex entries
	* Hidden clues

---

	6. Hidden Insight System

---

	Core Idea : Some entries contain hidden layers.

---

	Triggers : 
* Full completion
* Elara presence
* Specific discoveries

---

	Rewards

* Reveals :
	* Secret locations
	* Rare mechanics
	* Hidden interactions

---

	7. Rewards System (Light but Meaningful)

---

