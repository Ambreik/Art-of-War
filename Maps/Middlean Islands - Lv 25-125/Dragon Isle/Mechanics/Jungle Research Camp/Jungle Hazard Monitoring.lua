			Jungle Hazard Monitoring

---

	Core Concept : The "Jungle Hazard Monitoring System" tracks and manages dangerous zones across the jungle, turning the environment into :

	A dynamic threat layer that changes over time

	Players don’t just explore — they observe, react, and influence the state of the jungle.

---

	1. Hazard Types 

Each monitored zone falls into a category :

---

	A. Aggressive Wildlife Zones

Areas where creatures behave abnormally hostile.

	Characteristics : 
* Increased spawn rate
* Faster aggro detection
* Pack behavior more frequent

	Visual Indicators : 
* Tracks, bones, disturbed vegetation
* Audible growls / movement

---

	B. Unstable Terrain Zones

Environment itself becomes dangerous.

	Examples : 
* "Quicksand Pockets"
* "Collapsing Ground"
* "Root Entanglement Areas"

	Effects : 
* Movement slow
* Risk of immobilization
* Sudden damage triggers

---

	C. Anomaly Zones

Strange, unexplained phenomena.

	Examples :
* Distorted air zones
* Pulsating plant clusters
* Energy-charged ground

	Effects

* Unpredictable :
	* Buffs
	* Debuffs
	* Visual distortions

---

	D. Mixed Hazard Zones

	High-risk areas combining :
* Creatures
* Terrain
* Anomalies

	These are late-stage or escalated zones

---

	2. Hazard State System

Each zone has a state level :

---

	States : 

| State     | Description         |
| --------- | ------------------- |
| Stable    | Minimal danger      |
| Active    | Noticeable threat   |
| Escalated | High danger         |
| Critical  | Extremely dangerous |

---

	State Progression

	Hazards evolve over time if 
* Ignored
* Not surveyed
* Not interacted with

---

	Example Flow : 

Stable → Active → Escalated → Critical

---

	3. Player Interaction Mechanics

---

	A. Survey Action

	Players can :
* Enter hazard zone
* Use interaction :
	"Survey Area"

---

	Survey Requirements

* Stay in zone for duration
* Avoid interruption (combat, movement)

---

	Survey Results

* Updates hazard status
* Grants :
	* Research Progress
	* Quest completion

---

	B. Report Back System

	After surveying :
* Players return to camp
* Submit findings

---

	Rewards : 
* Utility items
* Research bonuses
* Reputation (future-ready system)

---

	4. Dynamic Behavior System

---

	A. Hazard Shifting

	Zones can :
* Move location slightly
* Expand or shrink
* Change type (rare cases)

---

	B. Escalation Mechanics

	If ignored :
* Wildlife becomes more aggressive
* Terrain becomes more unstable
* Anomalies intensify

---

	C. Critical State Effects

	At highest level :
* May spawn:
	* Elite creatures
	* Rare encounters
* Area becomes :
	* Highly dangerous
	* Highly rewarding

---

	5. Player Impact on World

---

	If Players Intervene (Survey + Report) : 
* Hazard level decreases
* Area stabilizes
* Camp becomes safer

---

	If Players Ignore : 
* Hazards spread
* Nearby zones affected
* Camp may experience :
	* More incidents
	* Less safety

---

	This creates a soft world control system

---

	6. Quest Integration

---

	Environmental Tasks

	Directly tied to : 
* Survey specific zones
* Monitor changes
* Report hazard states

---

	Advanced Tasks

* Stabilize anomaly
* Track migrating hazard
* Survive critical zone

---

	7. Rewards System

---

	A. Immediate Rewards
* Field supplies
* Minor consumables

---

	B. Research Bonuses

* Boost to :
	* Field Research System
	* Codex entries

---

	C. Passive Progression

---

	Examples : 
* "Terrain Adaptation"
	* Reduced slow effects
* "Hazard Awareness"
	* Detect zones earlier
* "Stability Training"
	* Reduced survey interruption chance

