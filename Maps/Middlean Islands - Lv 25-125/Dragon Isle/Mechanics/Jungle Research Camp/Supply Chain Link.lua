			Supply Chain Link (Dock Integration)

---

		Core Concept 

	The "Jungle Research Camp" is not self-sustaining. It relies entirely on "Blackwater Landing" for supplies, manpower, and operational stability.
	This creates a dependency system where player activity directly affects the state of the camp.

---

	1. Supply Resource System

---

	Supply Types : The camp depends on multiple categories :

---

	A. Basic Supplies : 
* Food rations
* Water containers
* Medical kits

	Keeps NPCs operational

---

	B. Research Supplies : 
* Tools
* Containers
* Writing materials

	Enables research-related mechanics

---

	C. Restraint Equipment : 
* Cages
* Reinforcements
* Binding tools

	Directly affects Specimen Containment stability

---

	D. Utility Supplies : 
* Rope
* Repair kits
* Camp materials

	Supports environment interaction & safety

---

	2. Supply Level System

---

	"Global Camp Supply Meter"

	The camp operates on a shared supply level :

| Level    | State             |
| -------- | ----------------- |
| Full     | Optimal           |
| Stable   | Functional        |
| Strained | Noticeable issues |
| Critical | System breakdown  |

---

	3. Supply Consumption

	Supplies decrease over time based on :
* Active NPC usage
* Ongoing research
* Triggered events (escaped creatures, anomalies)

---

	This ensures the system is always moving, not static.

---

	4. Player Contribution (Core Loop)

---

	How Players Supply the Camp : 

* "Cargo Delivery Quests" (from Dock)
* Manual transport (future expansion)
* Event-based deliveries

---

	Delivery Impact

	Each completed delivery :
* Restores supply level
* Stabilizes camp systems
* Unlocks better interactions

---

	5. Camp State Effects

---

	A. LOW SUPPLY (Strained → Critical)

---

	NPC Behavior : 
* Some NPCs :
	* Become inactive
	* Offer fewer interactions
* Dialogue reflects tension

---

	System Impact : 

* "Field Research System"
	* Slower progress
	* Fewer available nodes
* "Specimen Containment"
	* Higher chance of failure
	* More creature escapes
* "Hazard Monitoring"
	* Less accurate
	* Zones escalate faster

---

	Environmental Effects : 
* Camp appears damaged
* Broken tools / empty crates
* Signs of abandonment

---

	B. HIGH SUPPLY (Stable → Full)

---

	NPC Behavior : 
* Full activity
* Additional dialogue / hints
* More interaction options

---

	System Boosts : 

* "Field Research"
	* Increased efficiency
	* Bonus progress chance
* "Containment"
	* Stable cages
	* Reduced chaos events
* "Hazard Monitoring"
	* Faster stabilization
	* More accurate reports

---

	Environmental Effects : 
* Camp looks organized
* Active workstations
* Visible improvements

---

	6. Dynamic World Interaction

---

	A. Chain Reaction System : 

	Supply level affects other mechanics :
* Low supply → more chaos → harder gameplay
* High supply → more control → smoother gameplay

---

	B. Player Influence : 
* Solo players → small impact
* Group / repeated deliveries → major impact

---

	Encourages cooperative world shaping

