			Hidden Pirate Beast Cages

	The description of the cove mentions cages holding wild beasts, which is another environmental opportunity.
	Several cages around the camp contain captured animals intended either for food, intimidation, or entertainment.
	Players can interact with these cages and force them open.
	When released, the beasts immediately attack the nearest targets. Sometimes they will attack pirates, sometimes players depending on proximity.
	This creates chaotic combat situations inside the camp and allows clever players to use the pirates’ own captured creatures against them.
	It also makes the settlement feel more alive because the camp is not just a collection of enemies but an interactive environment.

