			Weathered Map Discovery

	Some pirates in "Tidebreaker Cove" carry fragments of old treasure maps obtained through shipwreck scavenging and raids on merchant vessels.

	Occasionally, when players loot pirate corpses, they may discover a "Weathered Map". These maps are not complete navigation charts but rather damaged fragments 
containing partial clues.
	When examied, the map reveals a vague hint pointing to a hidden location somewhere on "Dragon Isle".
	The player must then explore the island to locate the hidden cache described by the map fragment. These caches are small buried stashes that pirates hid for later
retrieval but never recovered.
	The treasure caches can contain a variety of rewards such as coin, pirate tokens, crafting materials, or occasionally rare items linked to pirate activity.
	This mechanic serves an important design role because it connects "Tidebreaker Cove" to the wider island, encouraging exploration beyond the pirate camp itself.

	It transforms the pirate area from a simple combat zone into a source of exploration hooks.
	
