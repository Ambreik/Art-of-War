			Pirate Alarm System

	Type: Environmental Settlement Mechanic / Dynamic Enemy Response

	Within "Tidebreaker Cove", the pirates have installed several crude alarm bells mounted on wooden frames or hanging from broken ship masts. These bells are used
to alert the entire encampment when the camp is under attack or when their supplies are threatened.
	While most pirates in the cove are disorganized raiders, they still rely on simple warning systems to coordinate their defense. If enough disturbance occurs 
within the camp, a nearby pirate will rush to ring the bell, alerting the surrounding pirates.
	This mechanic creates a dynamic combat escalation that makes the pirate camp feel alive and reactive.

---

		Alarm Bell Objects : 

	Several alarm bells are scattered across the pirate camp.

	They are usually located near :
* central campfires
* powder storage areas
* watch posts
* prisoner cages

	These bells are visible environmental objects and can be interacted with indirectly by enemies or players.

---

		Alarm Trigger Conditions : 

	The alarm system activates when pirates perceive a large disturbance in the camp.

	Examples of triggers include :
• Killing several pirates in a short period of time
• Triggering large **gunpowder barrel explosions**
• Destroying powder storage areas
• Attacking certain important pirates (veterans or guards)

	When one of these conditions occurs, nearby pirates may react by attempting to trigger the alarm.

---

		Alarm Activation : 

	If a pirate successfully reaches an alarm bell, they will begin ringing it loudly.

	Once the alarm bell rings :
* nearby pirates immediately become aggressive
* pirate patrols begin moving toward the disturbance
* additional enemies in nearby areas become alerted

	The ringing bell can be heard across a large portion of the cove.
	This creates the feeling that the entire pirate camp has been alerted.

---

		Pirate Response Behavior : 

	Once the alarm is active, pirates behave differently.

	Nearby pirates will :
* abandon idle activities
* move toward the source of the disturbance
* attack players more aggressively

	Some pirates may also attempt to flank players by approaching from different directions.
	This increases the danger of fighting inside the pirate settlement.

---

		Alarm Duration : 

	The alarm state lasts for a limited time.

	After a short period :
* pirates gradually return to their normal routines
* patrol routes resume
* the camp becomes calm again

	If additional disturbances occur while the alarm is active, the alarm duration may extend.

---

		Player Counterplay : 

	Players are not completely powerless against the alarm system.
	Several strategies can prevent or control the alarm.

	Possible counterplay includes :
• Killing pirates before they reach the bell
• Using crowd control to interrupt the alarm attempt
• Destroying the bell structure itself

	If the bell object is destroyed, it cannot be used again until it respawns later.
	This allows stealthier or coordinated players to control the situation.

---

		Interaction with Other Mechanics

	The Pirate Alarm System connects naturally with other mechanics in the area.

	1. Powder Chain Ambush : 
	Large explosions caused by gunpowder barrel chains significantly increase the chance of triggering the alarm.
	This creates a realistic response: pirates panic when their ammunition stores explode.

	2. Captain Rorik Rare Encounter

	If both conditions occur :
• a large explosion chain
• the alarm bell rings

	The probability of "Captain Rorik Powderhand" appearing increases.
	This creates a layered encounter where environmental manipulation can escalate into a dangerous fight.

---

		Environmental Atmosphere

	When the alarm bell rings, several subtle environmental effects occur :
* pirates shouting warnings across the camp
* caged animals becoming agitated
* campfires being knocked over during the rush
* patrol pirates moving toward the noise

These small reactions make the pirate camp feel like a living settlement instead of a static mob zone.

