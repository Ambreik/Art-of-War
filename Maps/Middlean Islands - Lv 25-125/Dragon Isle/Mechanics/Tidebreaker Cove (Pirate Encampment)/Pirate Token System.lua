			Pirate Token System


	This mechanic represents the economic structure of the pirate camp.
	When players defeat pirates in "Tidebreaker Cove", they occasionally obtain "Pirate Tokens". These tokens represent the internal currency used by pirate crews 
to distribute shares of plunder and prove rank within the encampment.
	From a gameplay perspective, the tokens function as a repeatable farming reward for players clearing the pirate settlement.
	The tokens can later be used for several purposes. They may be exchanged for crafting materials, trinkets, or traded with certain NPCs who deal with pirate 
contraband across the "Middlean Islands". Because the cove acts as a pirate stronghold, it is natural that defeated pirates carry these items.

	This mechanic encourages players to revisit the location repeatedly, because the tokens function as a small regional resource economy tied to the pirate 
population.

	Lore-wise, the tokens are crude metal markers stamped with pirate insignias. Different crews may use slightly different symbols, but the tokens still circulate 
within the broader pirate network of the Middlean region.

	"Pirate Tokens" are sometimes used as exchange currency for "Smuggling Network Faction" located in "Capital Island" in "Dockworkers' Guild" building. They provide
great deals in exchange for those tokens since the player defeated them, moreover if the player is a smuggler itself, can benefit for extra items too.
	
