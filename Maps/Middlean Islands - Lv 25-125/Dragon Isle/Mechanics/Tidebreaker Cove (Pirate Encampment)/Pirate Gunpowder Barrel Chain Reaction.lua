			Pirate Gunpowder Barrel Chain Reaction

	Throughout "Tidebreaker Cove", several stacks of gunpowder barrels are scattered between huts, broken ship masts, and supply piles. These barrels are unstable 
and highly flammable.

	Players are able to interact with the barrels in two different ways.

	First, they can push or reposition the barrels slightly along the ground. This allows players to align multiple barrels together, creating the possibility of 
building a chain reaction.
	Second, barrels can be detonated through several methods. Fire-based abilities, thrown explosives, or specific interaction prompts can ignite the gunpowder. 
When a barrel explodes it produces a short-range burst of fire damage.

	If multiple barrels are positioned close together, the explosion spreads to nearby barrels, creating a chain reaction of detonations.
	This mechanic allows players to turn the pirate camp environment into a tactical weapon. A well-placed chain reaction can heavily damage or eliminate groups of 
pirates in the area.
	Because the blast radius is intentionally limited, the mechanic encourages strategic positioning rather than large destructive effects.

	From a lore perspective this fits naturally since pirates store large quantities of unstable gunpowder near their ships and camps.
	The respawn time of the gunpowder barrels is between 10 to 40 minutes with a random chance.
	
