			Powder Chain Ambush (Rare Event Trigger)

	The barrel system can also be used to justify a rare pirate encounter without flooding the area with bosses.
	If players trigger a large enough chain reaction within the camp, the explosions may draw the attention of one of the pirate leaders hiding deeper in the cove.
	Occasionally, after a large explosion chain occurs, a pirate captain and a small group of elite pirates rush into the area to investigate the disturbance.
	This creates a short localized combat event where players face a stronger pirate enemy supported by several veteran crew members.
	The encounter is not meant to be a full boss battle, but rather a rare elite encounter designed for small groups.
	The idea behind the mechanic is that the pirates respond aggressively when their ammunition stores are destroyed.
	This creates a dynamic moment where environmental manipulation can escalate the situation unexpectedly.

