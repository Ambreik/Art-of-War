			Pirate Beast Cages

	Type : Environmental Chaos Mechanic / Settlement Interaction

	Throughout "Tidebreaker Cove", several heavy wooden cages can be found containing captured wild animals. The pirates keep these creatures for various reasons: 
entertainment, intimidation, food, or future sale to exotic beast traders.
	The cages are crude constructions made from ship timber, rusted chains, and reinforced iron bars. Most of the animals inside are aggressive and distressed after
long captivity.
	If the cages are opened or destroyed, the beasts will escape and immediately attack the nearest pirates, creating a brief period of chaotic combat inside the 
camp.
	Importantly, the animals do not ally with players and will ignore them unless directly attacked.

---

		Cage Distribution

	There are 4–6 cages scattered across "Tidebreaker Cove".

	They are usually placed near :
* pirate tents and huts
* central camp areas
* crude fighting pits
* near the docks where animals may have been unloaded

	The cages are meant to look like part of the pirate lifestyle, not special event objects.

---

		Animals Kept in the Cages : 

	The pirates capture creatures from the surrounding island jungle and coastline.

	Examples of creatures found inside the cages include :
* Jungle Panthers (Rank II–III) : Fast and aggressive predators captured in the island jungle.
* Razorback Boars (Rank III) : Wild boars known for their violent charges.
* Island Hyenas (Rank II) : Scavengers attracted to pirate camps and later captured.
* Occasional Rare Cage :A "Young Marsh Crocodile" captured from the nearby lake.

	Not every cage contains the same creature type. This keeps the mechanic unpredictable.

---

		How Players Free the Animals : 

	Instead of a simple interaction button, the cages can be opened through environmental actions.

	Players can release animals in several ways :

	1. Breaking the Cage Lock : 
	
Each cage has a heavy iron lock.

Players can destroy it using :
* weapon attacks
* explosives
* heavy abilities

	Once the lock breaks, the cage door swings open and the animal escapes.

---

	2. Gunpowder Chain Reaction : 

	If a gunpowder barrel explosion occurs near a cage, the shockwave can damage or destroy the lock.
	This means players who trigger the "Powder Chain Ambush" mechanic may accidentally release animals as well.

---

	3. Stray Combat Damage : 

	Some abilities or large attacks may accidentally damage the cage lock during combat.
	This creates unexpected outcomes during large fights.

---

		Beast Behavior After Escape

	Once freed, the animals behave as wild predators.

	Their behavior includes :
* attacking the nearest pirates
* chasing fleeing enemies through the camp
* causing chaos among pirate patrols

	They are not coordinated and simply act on instinct.
	They do not protect players and will not follow them.
	If players attack the animals directly, the beasts will defend themselves.

---

		Duration of the Chaos

	The animals remain active for a short time.

	Eventually :
* the animals are killed by pirates
* or wander away into the jungle
* or return to a neutral roaming state

	After some time, the cage respawns with a new captured creature.

