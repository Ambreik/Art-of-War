			Statue Bridge Mechanic

* Location : Lake of Reflection — Dragon Isle

* Type : Environmental Puzzle / Conditional World Mechanic / Dungeon Access Mechanism

* Description : At the center of the "Lake of Reflection" stands an ancient dragon statue partially submerged in the water. The statue appears fragile in specific 
areas where erosion has weakened its structure. The lake itself is filled with aggressive predators such as "Ancient Crocodiles" and "Water Serpents", making 
swimming across extremely dangerous.

	The statue serves as the key element of a hidden traversal mechanism designed to allow passage across the lake.

---

	Trigger Condition :
* A player using an Archer-class character with maximum attack range must strike the statue's structural weak point using a charged ranged ability.

---

	Mechanic Activation :
	
When the weak point is hit :
* The statue fractures violently.
* Its stone body collapses forward.
* The broken pieces align naturally across the water.

	This forms a temporary stone bridge between the two shores of the lake.

---

	Player Interaction Result :

	Players can :
* safely cross the lake
* reach the entrance of the "Cavern of the Dragon God" without engaging the hostile aquatic creatures.

---
	
	Environmental Constraints :

	The lake contains :
* Ancient Crocodiles (Rank II–III)
* Water Serpents

	These creatures patrol the water and attack any player attempting to cross without activating the bridge.

---

	Reset Behavior :

* Once per in-game day, the statue magically reforms at its original position, restoring the puzzle.
* This allows the mechanic to remain repeatable for other players arriving later.

---

	Environmental Flavor Details :
* The lake water reflects the mountain and sky like a mirror.
* During nighttime lightning storms, faint dragon silhouettes can sometimes appear in the water’s reflection.
* Occasional ripples and whispering sounds can be heard even when the water appears completely still.

---

	Lore Context : Scholars believe the statue was intentionally constructed as a trial of skill, ensuring that only those capable of precise ranged combat could 
safely reach the sacred cavern hidden beyond the lake.

