			Sunken Dragon Relic


	Type : Hidden Exploration Discovery

	Description : Beneath the calm waters of the lake lies a partially buried relic from an ancient dragon cult.
* Most players never notice it because of the hostile creatures patrolling the lake.

---

	Trigger Condition : 

Players must :
* dive near the collapsed statue ruins
* search the lake floor

	There is a small glowing relic partially buried in mud.

---

	Interaction

Player can "Recover Relic".

However the action :
* attracts nearby crocodiles
* triggers a short combat risk

---

	Outcome : 

Rewards one of :
* Dragonbone Fragment
* Old Dragon Cult Talisman (vendor item)
* Small chance for "Ancient Dragon Scale"

---

	Repeatability : 

Respawns every 12 hours.

---

	Lore Context : These relics were offerings thrown into the sacred lake by ancient dragon worshippers.

