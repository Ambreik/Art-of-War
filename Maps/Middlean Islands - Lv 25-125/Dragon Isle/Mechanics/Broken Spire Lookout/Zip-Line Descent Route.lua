			Zip-Line Descent Route

	Attached to the broken tower structure is a rope-and-pulley system installed by explorers and smugglers.

	Once players reach the summit, they can activate a zip-line route that allows rapid descent from the cliffside tower directly into the inner jungle of 
	"Dragon Isle".

	The zip-line travels from the tower toward a dense jungle clearing below.

	This system serves as :
* a fast traversal shortcut
* a safe descent route from the dangerous cliffs
* a convenient travel link between the southern coast and the jungle interior

	The zip-line can only be activated from the top of the tower.

