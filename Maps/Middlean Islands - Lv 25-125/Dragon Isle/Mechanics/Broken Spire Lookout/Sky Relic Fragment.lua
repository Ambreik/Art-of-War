			Sky Relic Fragment

	At the top of the tower lies a glowing relic shard embedded in the broken stone floor.
	This fragment is one of the ancient relic pieces scattered across Dragon Isle.

	When players interact with the relic fragment :
• a faint pulse of energy travels through the tower
• distant dragon-shaped lightning briefly flickers in the clouds
• the relic registers as discovered

	The fragment does not grant immediate rewards, but it becomes relevant when interacting with "Elara – Relic Breaker", who studies and reacts to these relic 
discoveries.
	Players who discover multiple relic fragments across the island may unlock additional dialogue or relic interpretation options with Elara.

