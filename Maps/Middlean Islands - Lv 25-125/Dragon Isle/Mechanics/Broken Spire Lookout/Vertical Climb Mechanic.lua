			Vertical Climb Mechanic


	The Broken Spire can be climbed through a combination of :
* crumbling staircases
* broken interior platforms
* exposed stone ledges
* hanging ropes left by previous explorers

	Because the tower is damaged, parts of the climb require careful movement along narrow stone edges.
	Some sections may be partially collapsed, forcing players to navigate the tower’s exterior wall before reaching the summit.
	The climb is designed to feel like a small exploration challenge rather than a puzzle.

