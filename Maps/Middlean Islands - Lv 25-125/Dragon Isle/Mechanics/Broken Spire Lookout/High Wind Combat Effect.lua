			High Wind Combat Effect

	The Broken Spire sits in an area of powerful coastal winds created by the surrounding cliffs and open sea.
	When players stand on the upper platform of the tower, the strong wind currents affect ranged combat.

	Temporary environmental effect : 
* Ranged Critical Chance: +5%
* However, the unstable winds also make aiming more difficult.
* Ranged Accuracy: reduced

	This effect applies only while standing on the exposed upper section of the tower.
	The mechanic creates a small risk–reward combat zone where ranged players can deal stronger critical hits but must deal with reduced precision.

