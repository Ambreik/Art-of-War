			Sound-Triggered Creature Spawn System

* Type : Dynamic / Hidden

---

	Function :

Links Echo System → Enemy System

---

	System Behavior :

* High sound levels trigger:
	* Creature spawns
	* Increased spawn rate

---

	Spawn Types :
* Lurkers (passive → aggressive)
* Ambushers (spawn only when triggered)

---

	Conditions / States :
* Quiet cave → minimal creatures
* Disturbed cave → active threats

