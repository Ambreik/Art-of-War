			Echo-Based Sound Detection System

* Type : Core / Hidden / Interaction
* Function : Converts player movement into detection mechanic

---

	Player Interaction :
* Control movement speed
* Choose stealth vs speed

---

	System Behavior :

* Every action generates sound intensity value : 
  * Walking → low
  * Running → medium
  * Combat / falling → high
* Cave amplifies sound :
  * Sound travels further than normal

---

	Detection Results :

* High sound triggers :
	* Enemy awareness
	* Ambush events
	* Environmental reactions (rockfalls)

---

	Conditions / States :
* Quiet state
* Alert state
* Disturbed state

