				Stealth vs Ambush System

* Type : Dynamic / Interaction
* Function : Rewards controlled play, punishes noise

---

	Player Interaction :
* Move silently or trigger encounters

---

	System Behavior :
* Low Noise :
	* Reduced enemy presence
	* Safer traversal
* High Noise :
	* Triggers ambush spawns
	* Enemies gain positional advantage

---

	Ambush Logic :
* Enemies spawn :
	* Behind player
	* From hidden tunnels
	* From ceiling / walls

---

	Conditions / States :
* Undetected → Safe
* Detected → Ambush-ready
* Triggered → Active encounter

