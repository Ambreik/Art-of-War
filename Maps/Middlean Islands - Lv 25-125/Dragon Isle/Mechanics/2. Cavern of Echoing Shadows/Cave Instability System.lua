			Cave Instability System

* Type : Dynamic / Environmental

---

	Function :

Represents cave reacting to disturbance

---

	System Behavior :
* Repeated noise / activity :
	* Increases instability level

---

	Effects :
* More frequent rockfalls
* Path alterations (temporary blockages)
* Increased hazard density

---

	Conditions / States :
* Stable
* Unstable
* Critical (high danger zone)

---