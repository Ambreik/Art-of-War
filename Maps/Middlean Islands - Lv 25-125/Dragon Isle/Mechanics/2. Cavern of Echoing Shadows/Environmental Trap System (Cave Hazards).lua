			Environmental Trap System (Cave Hazards)

* Type : Environmental / Dynamic
* Function : Introduces reactive environmental dangers

---

	Player Interaction :
* Avoid triggering traps
* Observe environment

---

		System Behavior :

	Falling Rocks : 
* Triggered by :
	* Movement
	* Noise
* Effect :
	* Area damage
	* Path blocking (temporary)

---

	Slippery Moss : 

* Found on :
	* Slopes
	* Narrow paths
* Effect :
	* Loss of control (short slide)
	* Risk of falling

---

	Conditions / States :
* Trap active / inactive cycles

