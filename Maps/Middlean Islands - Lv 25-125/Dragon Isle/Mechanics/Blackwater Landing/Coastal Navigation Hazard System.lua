			Coastal Navigation Hazard System

	Dragon Isle’s coastline contains natural obstacles that make boat navigation challenging.
	These hazards exist mainly near Blackwater Landing’s outer waters.

	Hazard Types : 
• hidden reefs
• shallow sandbars
• floating wreckage
• sharp rock formations

	Mechanics : 
• Boats hitting hazards take durability damage
• Some hazards may temporarily slow the boat
• Skilled navigation allows players to avoid them

	Design Purpose : 
* Adds skill-based traversal and complements the "Boat Durability System".

