			Hidden Underwater Wreck Mechanic

	Near the outer edge of "Blackwater Landing’s" cove lies the remains of a partially submerged shipwreck, hidden beneath shallow water and coral formations. The 
wreck is not immediately obvious and must be discovered through exploration.

	The wreck likely belonged to an older expedition vessel or merchant ship that attempted to reach "Dragon Isle" but never successfully docked.

---

		Discovery Mechanics : 

	The wreck is not marked on the map and can be discovered through several subtle indicators :
• occasional floating debris drifting near the surface
• damaged cargo crates caught between rocks
• faint glints of metal or coin beneath shallow water
• seabirds circling the same area repeatedly

	Players traveling by boat or swimming along the coastline may notice these signs.

---

		Exploration Interaction

	Once discovered, players can dive or swim down to investigate the wreck.

	Exploration points around the wreck may include :
• broken cargo containers
• scattered coin purses
• damaged navigation instruments
• partially buried supply chests

	Some containers can be opened directly, while others may require players to break open damaged crates.

---

		Possible Rewards : 

	Loot found at the wreck can include :
• small amounts of gold
• salvaged trade goods
• damaged relic fragments
• fishing materials or bait
• rare chance for "Weathered Maps"

	Extremely rare chance :
• "Explorer Map Fragment – Blackwater Coast"

	This ties the wreck to the Explorer Map Fragment mini-event system.

---

		Environmental Risk

	Although the wreck is close to the landing, it is outside the safe zone radius

	Possible risks include :
• minor aquatic creatures inhabiting the wreck
• sharp wreckage causing small damage while exploring
• pirates occasionally searching the wreck for lost cargo

	These threats remain small so the mechanic stays exploration-focused rather than combat-focused.

---

		Boat Interaction

	If players approach the wreck too quickly with rented boats, collisions with submerged debris may cause :
• boat durability damage
• temporary loss of steering control

	This reinforces the coastal navigation hazard system already present near the landing.

---

		Respawn Behavior

	The wreck itself remains permanently present, but lootable containers refresh periodically.
	This allows the wreck to function as a minor repeatable exploration location without turning it into a farming hotspot.

---

		Design Purpose

	This mechanic serves several purposes :
• encourages players to explore the coastline instead of ignoring it
• integrates with boat durability and navigation hazards
• supports the Explorer Map Fragment mini-event system
• provides a small environmental storytelling moment about past expeditions to "Dragon Isle".

	Most importantly, it adds depth to the waters around the island, making them feel like part of the playable environment rather than empty space.

