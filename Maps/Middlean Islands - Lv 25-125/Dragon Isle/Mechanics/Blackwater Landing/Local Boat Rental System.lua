			Local Boat Rental System

	Blackwater Landing allows players to rent small coastal boats used for short-distance travel around "Dragon Isle".
	This system enables players to move between coastal POIs faster than traveling through the jungle.

		Mechanics : 
* Players interact with the "Shipmaster NPC" to rent a boat.

	Rental properties :
• Boats are temporary vehicles
• Boat rental requires a small fee
• Boat automatically despawns when returned or destroyed

	Players can use rented boats to reach locations such as :
• "Tidebreaker Cove"
• nearby fishing areas
• small coastal exploration points

	Restrictions : 
• Boats cannot travel beyond a defined coastal boundary
• Boats cannot leave Dragon Isle’s regional waters

		Design Purpose : 
* Creates localized travel mobility without trivializing island exploration.

