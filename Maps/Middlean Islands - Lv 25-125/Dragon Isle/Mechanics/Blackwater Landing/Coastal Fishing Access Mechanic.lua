			Coastal Fishing Access Mechanic

	Blackwater Landing provides one of the safest fishing points on the island.

		Mechanics : 

	Players can fish from :
• the main dock
• nearby calm-water edges

	Fishing here provides :
• common fish species
• bait fish used for higher-tier fishing

	Rare chance :
• obtain "Weathered Maps" that may lead to hidden caches

		Design Purpose : 
* Provides a calm activity near a dangerous island, encouraging downtime between exploration runs.

