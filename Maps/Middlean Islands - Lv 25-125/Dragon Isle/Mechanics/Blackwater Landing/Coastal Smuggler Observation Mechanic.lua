			Coastal Smuggler Observation Mechanic (Hidden System)

		Mechanics : 
* Players aligned with the Smuggler network may notice hidden signs near the docks.

	Possible discoveries :
• hidden smuggler markings on crates
• coded symbols etched into dock beams
• secret supply drops

	These do not trigger automatically, but observant players can discover them.

		Design Purpose : 
* Links Dragon Isle to the global Smuggler faction ecosystem without adding visible NPC clutter.

