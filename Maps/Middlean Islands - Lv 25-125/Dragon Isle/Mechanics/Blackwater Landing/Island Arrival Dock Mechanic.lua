			Island Arrival Dock Mechanic

	Blackwater Landing functions as the primary physical arrival point for "Dragon Isle".
	Players traveling from "Capital City" or other long-distance transport routes arrive here by boat or ferry.
	Unlike many other regions, teleportation is intentionally disabled for this island, reinforcing the sense of distance and danger.

		Mechanics : 
• Players must arrive via approved maritime transport.
• Arrival occurs at the "Blackwater Landing" dock platform.
• Boats approach the cove and automatically dock once the travel sequence completes.
• Upon arrival, players are placed inside the "Landing Safe Zone" radius.

		Design Purpose : 
* This mechanic ensures Dragon Isle feels remote and physically separated from the mainland, increasing immersion and strategic travel planning.

