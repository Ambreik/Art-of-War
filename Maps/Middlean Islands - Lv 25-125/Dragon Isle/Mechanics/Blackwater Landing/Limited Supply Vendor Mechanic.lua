			Limited Supply Vendor Mechanic

	"Blackwater Landing" hosts a basic supply vendor providing essential items.

		Mechanics : 

	Items sold include :
• travel rations
• fishing bait
• rope bundles for zip-line usage
• basic survival supplies

	Important limitations :
• Equipment upgrades are not sold here
• Supplies are intentionally minimal and practical

		Design Purpose : 
* Encourages players to prepare before traveling to the island, while still allowing emergency resupply.

