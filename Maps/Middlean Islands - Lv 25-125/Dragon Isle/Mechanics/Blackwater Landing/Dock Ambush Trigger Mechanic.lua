			Dock Ambush Trigger Mechanic

	Players who remain outside the safe zone for extended periods may trigger a small pirate attack.

	Trigger Conditions : 
• Players linger in coastal waters or nearby shorelines
• Players repeatedly harvest nearby resources
• Random chance during pirate patrol cycles

	Event Outcome : 
• Small pirate squad appears
• Short skirmish occurs near the landing outskirts

	This is not a boss encounter, only a small combat event.

		Design Purpose : 
* Prevents the dock from becoming an exploit farming zone.

