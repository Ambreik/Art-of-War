			Exploration Guidance Mechanic

	"Blackwater Landing" subtly guides players toward the island’s major exploration areas.

		Mechanics : 
		
	Environmental placement encourages movement toward :
• jungle trails
• coastal paths
• visible landmarks like Broken Spire Lookout

	Players may notice :
• worn paths leading inland
• damaged signposts pointing toward ruins
• abandoned supply carts heading toward Tidebreaker Cove

		Design Purpose : 
* Encourages natural exploration flow rather than map markers.

