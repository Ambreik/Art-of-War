			Explorer Map Fragment Integration

	"Blackwater Landing" participates in the Explorer’s Map Fragment mini-event system.

		Mechanics : 
		
	Players may occasionally obtain a map fragment through :
• fishing at the dock
• certain dock quests
• rare crate searches near the landing

	Fragment type example :
* "Fragment of the Blackwater Coast"

	When combined with fragments from other POIs, this contributes to forming the "Explorer’s Hidden Cache map".

		Design Purpose : 
* Ensures the landing area participates in the island-wide exploration puzzle system.

