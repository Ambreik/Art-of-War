			Safe Zone Radius Mechanic

	The dock area itself acts as a protected zone where players can safely interact with services.

		Mechanics : 
• A small circular safe radius surrounds the dock area
• Hostile NPCs cannot spawn inside this radius and if they cross it, automatically dispawn.
• Aggro from enemies outside the radius resets when players re-enter the safe zone
• Combat actions may be restricted inside the zone .

		Environmental Indicators : 
* Players can visually recognize the safe zone through:
	• Dock lanterns and light posts
	• Mooring ropes and barricades
	• Calm ambient audio

		Design Purpose : 
* Provides a reliable refuge and logistics hub while still allowing danger nearby.

