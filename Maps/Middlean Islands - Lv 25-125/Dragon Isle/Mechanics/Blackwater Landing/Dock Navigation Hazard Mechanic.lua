			Dock Navigation Hazard Mechanic

	Although the cove is relatively calm, currents and coastal winds make docking difficult.
	This creates a small environmental challenge when ships arrive.

		Mechanics : 

	During arrival or departure sequences :
• Strong currents may slow docking alignment
• Players may experience brief movement restriction during landing

	Optional advanced mechanics:
• Boats may take minor durability damage if docking fails
• Arrival sequence may slightly delay during storms

		Design Purpose : 
* Adds environmental realism and immersion without heavily punishing players.

