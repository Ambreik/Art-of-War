			Dock Worker Information System

	Dock workers around the landing occasionally provide contextual hints about "Dragon Isle".

		Mechanics : 
	Talking to these NPCs may reveal :
• pirate activity rumors
• nearby exploration points
• relic-related gossip involving Elara
• navigation advice

	These hints are not formal quests, but subtle information prompts.

		Design Purpose : 
* Encourages conversation and immersion, guiding players naturally toward island content.

