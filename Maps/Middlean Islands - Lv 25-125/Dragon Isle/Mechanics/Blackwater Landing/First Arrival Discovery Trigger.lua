			First Arrival Discovery Trigger

	The first time a player reaches Blackwater Landing, a discovery event occurs.

		Mechanics

	Trigger occurs when:
• player steps onto the dock for the first time

	The system:
• reveals the "Dragon Isle" region map
• unlocks the "Resurrection Anchor"
• grants exploration experience

		Optional flavor :

	A short system message may appear such as :

* "You have reached Dragon Isle — the waters whisper of ancient fire."

		Design Purpose : 
* Creates a memorable arrival moment and formally registers the island as discovered.

