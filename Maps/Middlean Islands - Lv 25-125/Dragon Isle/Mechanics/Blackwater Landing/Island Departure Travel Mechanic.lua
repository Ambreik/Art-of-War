			Island Departure Travel Mechanic

	Blackwater Landing also acts as the primary departure point from "Dragon Isle".
	Players can book return transport to the mainland or travel between nearby coastal locations.

		Mechanics : 

	Players may interact with the "Shipmaster NPC" to access travel options :

• "Return Passage to Capital City"
* Paid travel option
* Scheduled or instant depending on system design

• "Local Boat Travel"
* Small boats can transport players to certain coastal points on the island
* Only available if weather conditions permit

• "Transport Availability"
* Boat travel may occasionally be delayed by environmental factors (storms, tides)

		Design Purpose : 
* Encourages physical exploration and movement rather than instant teleportation.

