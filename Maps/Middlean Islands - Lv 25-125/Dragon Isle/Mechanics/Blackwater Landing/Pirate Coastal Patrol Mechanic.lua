			Pirate Coastal Patrol Mechanic

	Although the landing itself is protected, pirates still patrol nearby waters.

		Mechanics : 
• Pirate patrols spawn outside the safe zone radius
• Patrol routes move along the coastline near the landing
• Players venturing too far from the dock may trigger combat

	Enemy difficulty :
• Rank II – Rank III pirate enemies

		Design Purpose : 
* Maintains tension and prevents the landing area from feeling completely safe or isolated.

