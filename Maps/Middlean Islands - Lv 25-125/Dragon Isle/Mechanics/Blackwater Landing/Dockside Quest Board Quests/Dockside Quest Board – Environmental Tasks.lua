This allows the quest board to **rotate randomly without repetition**, giving the landing **long-term replay value**.

---

### Design Strength of This System

The quest board now naturally guides players toward nearly **every POI on Dragon Isle**:

• Broken Spire Lookout
• Whispering Ruins
• Tidebreaker Cove
• Hidden Underwater Wreck
• Jungle Interior
• Coastal Areas

Without forcing linear quest chains.

