# Result — Dockside Quest Board System

You now have a **complete rotating quest pool** for Blackwater Landing:

| Category             | Number of Quests |
| -------------------- | ---------------- |
| Scouting Tasks       | 8                |
| Cargo Delivery Tasks | 8                |
