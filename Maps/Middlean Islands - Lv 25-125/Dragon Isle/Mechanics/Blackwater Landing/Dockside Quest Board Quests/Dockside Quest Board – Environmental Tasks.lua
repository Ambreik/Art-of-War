			Dockside Quest Board – Environmental Tasks

These missions involve **surveying wildlife, environmental hazards, and natural phenomena** across Dragon Isle.

They help researchers, sailors, and explorers understand the island’s ecosystem while exposing players to its dangers.

---

# Quest 1 — “Survey the Reef”

**Quest Type:** Coastal Environment Survey

### Description

Sailors have reported unusual fish movement near the reefs east of the landing.
Investigate the reef and report your findings.

### Objectives

• Reach the **Eastern Reef Area**
• Observe fish activity
• Record the survey

### Mechanics

• Player must enter the reef zone
• Interaction marker appears once the player reaches the observation point

### Reward

• XP
• Fishing bait bundle

---

# Quest 2 — “Watch the Jungle Beasts”

**Quest Type:** Wildlife Observation

### Description

The jungle north of the landing hosts several aggressive predator species.
Observe their activity patterns without disturbing them.

### Objectives

• Observe **two jungle predator packs**

### Mechanics

• Players must remain within observation distance for several seconds
• Killing the animals fails the observation

### Reward

• XP
• Hunter’s observation token

---

# Quest 3 — “Strange Waters”

**Quest Type:** Environmental Investigation

### Description

The waters around Dragon Isle sometimes emit strange ripples and glowing currents.
Investigate these anomalies.

### Objectives

• Locate a **Water Disturbance Zone**

### Mechanics

• Player interacts with the disturbance
• Brief visual effect triggers (energy ripple)

### Reward

• XP
• Relic-infused water sample

---

# Quest 4 — “Jungle Growth Study”

**Quest Type:** Botanical Survey

### Description

Certain plant species on Dragon Isle grow far larger than normal.
Collect samples for study.

### Objectives

• Harvest **3 Giant Jungle Plants**

### Mechanics

• Plants appear as special resource nodes
• May spawn minor defensive wildlife

### Reward

• Herbal materials
• XP

---

# Quest 5 — “Cliffside Winds”

**Quest Type:** Environmental Observation

### Description

The cliffs overlooking the southern sea generate extremely strong wind currents.
Climb the cliff and measure the wind strength.

### Objectives

• Reach the **Southern Cliff Observation Point**

### Mechanics

• Climbing required
• Interaction triggers wind measurement

### Reward

• XP
• Navigation marker item

---

# Quest 6 — “Predators of the Cove”

**Quest Type:** Wildlife Survey

### Description

Small aquatic predators have begun appearing near the coastline.
Investigate their presence and confirm whether they pose a threat to ships.

### Objectives

• Locate **two aquatic predator nests**

### Mechanics

• Players must approach nests but do not need to kill the creatures

### Reward

• XP
• Fishing supplies

---

# Quest 7 — “The Silent Canopy”

**Quest Type:** Ecological Study

### Description

Certain areas of the jungle canopy appear strangely silent, as if wildlife avoids them.
Investigate the cause.

### Objectives

• Discover the **Silent Canopy Area**

### Mechanics

• Player must reach a hidden jungle clearing
• Environmental audio changes noticeably

### Reward

• XP
• Jungle exploration token

---

# Quest 8 — “Storm-Washed Debris”

**Quest Type:** Coastal Investigation

### Description

Large amounts of debris have recently washed ashore near the landing.
Inspect the debris to determine its origin.

### Objectives

• Search **3 debris piles along the shoreline**

### Mechanics

• Debris piles may contain small loot items
• Rare chance to find **salvage materials**

### Reward

• Gold
• Salvage components

