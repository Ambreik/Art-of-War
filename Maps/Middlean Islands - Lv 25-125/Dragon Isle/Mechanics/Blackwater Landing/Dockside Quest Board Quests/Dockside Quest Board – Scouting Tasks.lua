			Dockside Quest Board – Scouting Tasks

	These quests introduce players to key areas of "Dragon Isle" and encourage early exploration without requiring heavy combat.

---

		Quest 1 — “Eyes on the Broken Spire”

	Quest Type : Exploration / Scouting
	Quest Giver : Blackwater Landing Quest Board

	Description : Dock workers have spotted strange lightning damage on a cliffside tower known as the "Broken Spire Lookout". The shipmaster wants confirmation 
that the structure is still standing and usable as a landmark for navigation.

	Objectives : 
• Travel to "Broken Spire Lookout"
• Climb the tower structure
• Observe the southern sea from the top platform

	Mechanics : 
• Player must reach the top interaction point of the tower
• Activates the "Spire Observation Marker"
• Unlocks the zip-line descent mechanic if not previously discovered

	Reward : 
• Exploration Experience
• Small coin reward
• Chance to receive basic rope supplies

---

		Quest 2 — “Shadows in the Jungle”

	Quest Type : Reconnaissance

	Description : Strange whispers and glowing stones have been reported within the "Whispering Ruins". The dock workers want someone to confirm whether the ruins 
are safe for future expeditions.

	Objectives : 
• Travel to "Whispering Ruins"
• Interact with one ancient tablet
• Return to Blackwater Landing

	Mechanics : 
• Player must activate a tablet interaction
• This may trigger a "Living Water Chronicle entry"

	Reward : 
• Exploration XP
• Minor relic shard

---

		Quest 3 — “Chart the Coast”

	Quest Type : Coastal Survey

	Description : The shipmaster wants updated navigation information for the surrounding coastline. Players are tasked with scouting several coastal points near 
the landing.

	Objectives : 
Visit three shoreline observation points :
• Eastern Reef Marker
• Blackwater Cliff Edge
• Tidebreaker Cove Coastal Path

	Mechanics : 
• Players interact with survey markers
• Survey progress updates the player's coastal navigation map

	Reward : 
• Gold
• Minor navigation tool (cosmetic item or utility tool)

---

		Quest 4 — “Watch the Pirate Fires”

	Quest Type : Surveillance

	Description : Smoke from pirate camps has been spotted west of the island. Confirm the presence of pirate activity near "Tidebreaker Cove".

	Objectives : 
• Reach the outer edge of Tidebreaker Cove
• Observe pirate activity without dying
• Return to the dock

	Mechanics : 
• Entering the pirate detection zone completes the observation
• Player does not need to defeat pirates

	Reward : 
• XP
• Pirate Token (small amount)

---

		Quest 5 — “Survey the Northern Canopy”

	Quest Type : Exploration

	Description : A dense jungle canopy north of the landing blocks visibility from the coast. The dock workers need someone to reach a high vantage point and
observe the area.

	Objectives : 
• Reach the northern jungle ridge
• Interact with a canopy lookout point

	Mechanics : 
• May require climbing environmental terrain
• No combat requirement

	Reward : 
• Exploration XP
• Jungle herb bundle

---

		Quest 6 — “Driftwood and Debris”

	Quest Type : Coastal Investigation

	Description : Unusual debris has been drifting into the cove. Investigate the nearby waters for signs of shipwrecks or lost cargo.

	Objectives : 
• Search the Hidden Underwater Wreck area
• Retrieve one salvageable crate

	Mechanics : 
• Player must swim or dive to wreck site
• Interact with salvage container

	Reward : 
• Salvage materials
• Chance for "Weathered Map"

---

		Quest 7 — “Paths Through the Jungle”

	Quest Type : Exploration

	Description : No reliable inland paths exist yet from the landing to the jungle interior. Players are tasked with locating a stable travel route.

	Objectives : 
• Discover two jungle path markers
• Mark them on the player's map

	Mechanics : 
• Interaction with hidden path markers
• Unlocks faster navigation routes for the player

	Reward : 
• XP
• Small travel supply pack

---

		Quest 8 — “The Silent Cliff”

	Quest Type : Observation

	Description : A cliffside overlooking the southern sea has gone strangely quiet. Investigate the location and report any unusual activity.

	Objectives : 
• Reach the southern cliff overlook
• Activate observation point

	Mechanics : 
• Environmental discovery
• May reveal hidden wildlife or relic traces

	Reward : 
• XP
• Minor relic fragment

