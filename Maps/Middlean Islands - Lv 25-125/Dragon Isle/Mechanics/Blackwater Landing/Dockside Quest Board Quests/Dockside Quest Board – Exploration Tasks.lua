			Dockside Quest Board – Exploration Tasks

	These quests encourage players to investigate ancient remnants, strange locations, and hidden discoveries scattered across Dragon Isle.

---

		Quest 1 — “Fragments of the Past”

	Quest Type : Relic Exploration

	Description : The island is littered with fragments of ancient relics tied to the forgotten guardians of the Dragon God’s seal. Recover one such fragment and 
return it for study.

	Objectives : 
• Locate a "Sky Relic Fragment" somewhere on the island
• Interact with the relic fragment
• Record the discovery

	Mechanics : 
• The relic can be discovered at locations such as "Broken Spire Lookout"
• Discovery automatically registers in the "Living Water Chronicle"

	Reward : 
• Exploration XP
• Minor relic shard

---

		Quest 2 — “Echoes of the Tablets”

	Quest Type : Lore Discovery

	Description : The ruins in the northeastern jungle contain mysterious tablets that sometimes emit strange whispers. Record one of these echoes for the dock 
scholars.

	Objectives :
• Travel to "Whispering Ruins"
• Interact with one "Ancient Tablet"

	Mechanics : 
• Tablet interaction triggers a voice echo memory
• Adds an entry to the "Living Water Chronicle" codex

	Reward : 
• XP
• Small relic fragment

---

		Quest 3 — “Hidden Cache Rumors”

	Quest Type : Treasure Hunting

	Description : Sailors claim that fragments of an explorer’s map are scattered across "Dragon Isle". Find a fragment and report the discovery.

	Objectives : 
• Obtain any "Explorer Map Fragment"

	Mechanics : 

Fragments may be obtained through :
• ancient tablets
• fishing near the coast
• exploring wreckage
• opening hidden containers

	Reward : 
• XP
• Map Fragment bonus reward

---

		Quest 4 — “A Curious Glow”

	Quest Type : Environmental Investigation

	Description : Dock workers have noticed strange glowing particles drifting inland during certain nights. Investigate the source.

	Objectives :
• Locate a dragon-energy anomaly somewhere in the jungle

	Mechanics : 
• Players must find a small relic resonance site
• Interaction causes a brief environmental effect

	Reward : 
• XP
• Relic energy residue

---

		Quest 5 — “Signs of the First Expedition”

	Quest Type : Archaeological Exploration

	Description : Before the current expedition, others attempted to reach "Dragon Isle". Find evidence of their failed journeys.

	Objectives : 
• Search the "Hidden Underwater Wreck"
• Recover a "Damaged Expedition Journal"

	Mechanics : 
• Journal spawns inside wreck containers
• Player must dive to retrieve it

	Reward : 
• Gold
• Historical artifact item

---

		Quest 6 — “Stone Markers”

	Quest Type : Landmark Survey

	Description : Ancient stone markers scattered around the island may form part of a forgotten navigation system.

	Objectives : 
• Discover two ancient markers

	Mechanics : 

Markers can be found near :
• jungle paths
• cliff overlooks
• ruin sites

	Reward : 
• XP
• Navigation token

---

		Quest 7 — “The Relic Breaker”

	Quest Type : NPC Discovery

	Description : Travelers have spoken of a wandering relic hunter named "Elara" who roams the island. Find her and confirm the rumors.

	Objectives : 
• Encounter "Elara – Relic Breaker"

	Mechanics : 
• Quest completes upon first interaction with Elara
• Unlocks additional dialogue options with her

	Reward : 
• XP
• Relic knowledge token

---

		Quest 8 — “Where the Jungle Whispers”

	Quest Type : Exploration

	Description : Certain areas of the jungle seem strangely quiet, as if something ancient watches from within.

	Objectives : 
• Reach the deep jungle interior zone

	Mechanics : 
• Discovery point unlocks a hidden jungle map section

	Reward : 
• Exploration XP
• Jungle herb bundle

