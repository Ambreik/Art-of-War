			Dockside Quest Board – Cargo Delivery Tasks

	These missions simulate the supply chain between Blackwater Landing and other areas of Dragon Isle.
	They encourage travel, sometimes expose players to pirates, and make the island feel like an active expedition zone.

---

		Quest 1 — “Supplies for the Western Watch”

	Quest Type : Cargo Delivery
	Quest Giver : Dockside Quest Board

	Description : Scouts monitoring pirate activity near "Tidebreaker Cove" have run low on provisions. Deliver a crate of supplies before the pirates intercept the
shipment.

	Objectives : 
• Pick up "Supply Crate" at "Blackwater Landing"
• Deliver the crate to the "Western Watch Cache" near "Tidebreaker Cove"

	Mechanics : 
• The crate occupies a temporary quest item slot
• Dropping the crate resets the delivery
• Pirates may patrol the delivery route

	Reward : 
• Gold
• Small amount of "Pirate Tokens"

---

		Quest 2 — “Rope for the Spire”

	Quest Type : Logistics / Delivery

	Description

Explorers at **Broken Spire Lookout** need new rope bundles to maintain the zip-line routes.

	Objectives

• Collect "Rope Bundle Package" from the dock vendor
• Deliver it to the "Spire Maintenance Point"

	Mechanics : 
• Unlocks the zip-line station if the player hasn't activated it before
• Safe travel mission with minor climbing

	Reward : 
• Exploration XP
• Rope bundle (player usable)

---

		Quest 3 — “Fuel for the Beacon”

	Quest Type : Supply Transport

	Description : The signal beacon near the eastern cliffs requires fresh oil fuel. Transport a sealed oil container to the beacon station.

	Objectives : 
• Carry "Beacon Oil Container"
• Deliver it to the "Eastern Cliff Signal Post"

	Mechanics : 
• The oil container slows player movement slightly
• Dropping it breaks the container and fails the mission

	Reward : 
• Gold
• Navigation beacon reputation

---

		Quest 4 — “Medicinal Herbs Run”

	Quest Type : Support Delivery

	Description : A field researcher stationed in the jungle has requested medicinal herbs for treating wildlife injuries.

	Objectives : 
• Retrieve "Herbal Supply Pack" from the vendor
• Deliver to "Jungle Research Camp"

	Mechanics : 
• Player must reach a small jungle outpost
• Hostile wildlife may appear along the path

	Reward : 
• XP
• Herbal crafting materials

---

		Quest 5 — “Salvage Return”

	Quest Type : Retrieval Delivery

	Description : Dock workers believe valuable salvage from a nearby wreck could be recovered and returned to the landing.

	Objectives : 
• Recover "Salvaged Cargo Box" from the "Hidden Underwater Wreck"
• Bring it back to Blackwater Landing

	Mechanics : 
• Requires underwater exploration
• Player must swim with cargo item

	Reward : 
• Gold
• Chance for "Weathered Map"

---

		Quest 6 — “Message for the Ruins”

	Quest Type : Courier

	Description : Elara has been seen wandering near the "Whispering Ruins". Deliver a sealed message requesting her assistance in identifying relic fragments.

	Objectives : 
• Carry "Sealed Message Scroll"
• Deliver it to the "Tablet Shrine within Whispering Ruins"

	Mechanics : 
• Message automatically delivers if Elara is present
• If she is not present, quest completes by leaving the message at the shrine

	Reward : 
• XP
• Chance for "Relic Fragment"

---

		Quest 7 — “Emergency Food Drop”

	Quest Type : Time-sensitive delivery

	Description : A scouting party failed to return on time and may still be hiding near pirate territory.

	Objectives : 
• Deliver "Emergency Food Crate"
• Leave it at a "Hidden Scout Supply Cache"

	Mechanics : 
• Delivery location is close to pirate patrol areas
• Players must avoid heavy combat while carrying cargo

	Reward : 
• XP
• Survival rations bundle

---

		Quest 8 — “Dock Repairs”

	Quest Type : Local logistics

	Description : Parts of the landing dock have begun to deteriorate after repeated ship arrivals.

	Objectives : 
• Deliver "Wooden Repair Planks" to the dock maintenance area

	Mechanics : 
• Very short quest
• Acts as a **quick rotation quest** on the board

	Reward : 
• Small gold reward
• Dockworker reputation

