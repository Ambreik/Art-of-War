			Dockside Quest Board System

	Located near the central dock of "Blackwater Landing", the "Dockside Quest Board" serves as a rotating contract hub where travelers, sailors, and explorers can 
find work across Dragon Isle.
	Rather than providing a large list of missions, the board offers a small selection of rotating contracts drawn from several categories of tasks.

	This design reflects the unpredictable nature of the island and ensures that opportunities change regularly.

---

		Quest Categories

	The board draws from four categories of tasks :
• Scouting Tasks
• Cargo Delivery Tasks
• Exploration Tasks
• Environmental Tasks

	Each category contains a pool of available quests from which the system selects missions.

---

		Daily Quest Generation

	At the daily reset, the quest board generates available missions.

	Generation rules :
• Each category has a 50% chance to generate a quest for that day.
• Maximum 1 quest per category.
• Maximum 4 quests total.

	Failsafe rule :
• If all category rolls fail, the board forces one random quest to appear.

	This ensures the board is never completely empty.

---

		Quest Rarity

	Each generated quest also rolls for rarity :

| Rarity   | Chance |
| -------- | ------ |
| Common   | 60%    |
| Uncommon | 30%    |
| Rare     | 10%    |

	Rare quests often involve special discoveries, relics, or unique encounters.

---

		Solo vs Group Tasks

	Most quests are designed for solo play.

	Distribution :
• Solo Quests – 75%
• Small Group Quests – 25%

	Group quests usually involve :
• pirate patrols
• dangerous salvage operations
• escort missions

---

		Quest Refresh Timer

	The Dockside Quest Board refreshes once every 24 hours at the regional reset time.
	Completed quests disappear until the next rotation.

---

		Design Purpose

	This system ensures that : 
• the island remains dynamic and unpredictable
• players are encouraged to revisit Blackwater Landing regularly
• quests naturally guide players toward all major POIs on Dragon Isle
• exploration systems like relics, wrecks, pirates, and map fragments stay interconnected

