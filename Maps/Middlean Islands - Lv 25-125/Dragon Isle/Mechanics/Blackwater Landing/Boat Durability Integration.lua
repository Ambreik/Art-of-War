			Boat Durability Integration

	Boats can take durability damage from several sources.

	Durability Damage Sources : 
• Colliding with rocks or reefs
• Ramming dock structures incorrectly
• Taking damage from pirate attacks
• Running aground on shallow coastal areas

		Durability States

	Boat condition degrades through stages :
• "Stable" – full durability
• "Damaged" – slower maneuvering
• "Critical" – steering becomes difficult
• "Destroyed" – boat sinks and despawns

	When destroyed :
• Players are forced to swim back to shore
• Rental fee is not refunded

		Design Purpose : 
* Encourages careful navigation and reinforces that boats are tools, not disposable taxis.

