			Dragon Isle Resurrection Anchor Mechanic

	Blackwater Landing acts as the only island’s designated resurrection locations.

		Mechanics : 
*Players who select "Resurrect in Town" while on "Dragon Isle" will respawn at "Blackwater Landing".

		Conditions :
• Player must have discovered the Landing previously
• Resurrection places player inside the "Safe Zone Radius"
• Standard resurrection penalties apply

		Design Purpose : 
* Ensures players always have a secure fallback location after death.

