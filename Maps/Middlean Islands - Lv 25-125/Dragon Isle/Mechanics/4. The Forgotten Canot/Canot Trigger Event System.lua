			Canot Trigger Event System

* Type : Core / Interaction / Event
* Function : Player-driven ambush encounter system

---

	Player Interaction :

* Place item in canot :
	* Meat
	* Fish

---

	System Behavior :
* Valid item → activates canot
* After short delay → triggers ambush encounter

---

	Core Logic :
* Input (bait) → System Response (spawn event)

---

	Variation Layer (Built-in, not separate system) :
* Meat : ( Fresh Bear Belly )
	* Slower trigger
	* Stronger encounter
* Fish : ( Stormfin Barracuda )
	* Faster trigger
	* More agile encounter

---

	Conditions / States :
* Inactive
* Baited
* Triggered
* Cooldown

---

	Cooldown :

* 30 minutes

---

	Availability : 
* Up to 3 times per week, per character	

