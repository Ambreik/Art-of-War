			Captain Rorik "Powderhand"

	Title : Captain of the Tidebreaker Raiders

---

		Classification : 
* Creature Type : Human
* Faction : Tidebreaker Pirates
* Rank : Rare Elite
* Level Range : 72–75

Rare because he does not spawn normally.
Elite because he is stronger than standard enemies and leads a group.

---

		Location : 

* Region : Middlean Islands
* Sub-Region : Dragon Isle
* Primary Location : Tidebreaker Cove

* Spawn Mechanic : Powder Chain Ambush (Environmental Trigger)

Captain Rorik appears only when players trigger a large gunpowder barrel chain explosion inside the pirate encampment.
After the explosion, he arrives with a group of veteran pirates to investigate the destruction.

---

	Overview : "Captain Rorik Powderhand" is one of the pirate leaders operating from Tidebreaker Cove. Unlike the scattered raiders and smugglers that make up most
of the camp, Rorik commands a hardened group of loyal fighters who serve as the camp’s enforcers.
When the pirates’ gunpowder supplies are threatened or destroyed, Rorik personally leads a response team to eliminate whoever caused the damage.
His sudden appearance turns what might begin as a clever environmental trap into a dangerous combat encounter.

---

	Appearance : "Captain Rorik" is a heavily built pirate veteran with a weathered face marked by years of naval combat. His beard is braided with small metal 
rings taken from defeated sailors, and his left arm is covered in dark burn scars from repeated exposure to unstable gunpowder.
	He wears a reinforced leather coat decorated with trophies taken from merchant ships and rival pirates. A curved naval sabre hangs at his side, while a battered
flintlock pistol is tucked into a bandolier of powder charges across his chest.
	When he storms into battle, the smell of burnt powder and saltwater seems to follow him.

---

	Lore : "Rorik" earned the nickname "Powderhand" after surviving an explosion aboard a pirate vessel many years ago. Instead of abandoning explosives after the 
accident, he became obsessed with mastering them.
	Within Tidebreaker Cove he now oversees the storage and distribution of the pirates’ gunpowder reserves.
	Because of this role, any large explosion within the camp immediately draws his attention. Rorik assumes such destruction can only be the work of enemy 
smugglers, rival pirates, or foolish adventurers.
	His response is always the same — find the intruders and make an example of them.

---

		Behavior : 
	Rorik is aggressive and highly territorial.
	When he appears during the "Powder Chain Ambush" event, he immediately begins searching the area for whoever triggered the explosion. Once he identifies a 
target, he charges into battle without hesitation.
	Unlike many pirates, he fights with discipline and coordinates his attacks with the veteran raiders accompanying him.
	He focuses his attacks on the most threatening opponent, attempting to overwhelm that player with aggressive melee strikes and explosives.

---

		Combat Role : 

* Commander-type melee fighter with explosive abilities.
	"Rorik" combines close-quarters sword fighting with improvised explosives. His abilities are designed to force players to reposition frequently while dealing 
with both melee pressure and area damage.

---

		Core Attributes : 

Health : Medium-High for an elite encounter.
Damage Type : Physical + Fire (from explosives).
Armor : Moderate (reinforced pirate coat).
Movement Speed : Standard humanoid speed.
Attack Range : Melee with limited ranged attacks (pistol).
Threat Generation : High — designed to hold player attention while the supporting pirates deal damage.

---

	Resistances : 

Fire Resistance : Moderate (experience with explosives).
Physical Resistance : Low–Moderate.
Magic Resistance : Low.

---

	Weaknesses : 

Frost Damage : Slightly increased damage received.

Control Effects : Moderately vulnerable to crowd control effects.

---

		Combat Behaviour (AI) : 

	Combat AI determines how the monster actually fights.
	"Captain Rorik" uses commander-style AI.

	Behavior priorities :
1. Identify the player who triggered the explosion if still nearby.
2. Engage the nearest hostile target if original target is unavailable.
3. Use pistol attacks on distant targets attempting to kite him.
4. Use explosive abilities when multiple players cluster together.
5. Prioritize attacking the strongest visible opponent.

	Unlike basic pirates, "Rorik" actively changes targets when threatened by high damage dealers.

---

	Aggro Rules : 

Aggro Type : Hostile on sight once spawned.
Aggro Radius : Medium.
Initial Targeting : Prefers players closest to the explosion site.
Threat Reset : Does not reset easily during the encounter.

---

	Crowd Control Interaction : 

Rorik can be affected by most crowd control abilities, but his elite status provides partial resistance.

	Possible CC effects :
Stun – Reduced duration
Slow – Normal effect
Root – Short duration
Silence – Limited impact (few abilities rely on casting)

	Knockback effects are less effective due to his heavy build.

---

		Status Effects Applied

	Several of Rorik’s abilities apply status effects.

* Burning : 
	* Applied by explosive attacks.
	* Deals minor fire damage over time.

* Stagger : 
	* Caused by pistol shot.
	* Briefly interrupts movement or casting.

* Rally Buff : 
	* Applied to nearby pirates when using Raider’s Rally.

---

		Supporting Unit Behavior : 

	The Veteran Pirates accompanying Rorik use simpler AI.

	Their behavior :
* Protect the captain
* Attack the nearest player
* Focus targets affected by Rorik’s rally ability

	They do not retreat.

---

		Abilities : 

	1. "Powder Shot" : Rorik fires a powerful pistol blast at a distant target.

	Effect:
* Moderate physical damage
* Brief stagger effect

	This ability allows him to pressure players attempting to keep their distance.

---

	2. "Black Powder Bomb" : Rorik throws a crude explosive onto the ground.

	Effect :
* Explodes after a short delay
* Deals fire damage in a small radius

	Players must move quickly to avoid the blast.

---

	3. "Raider’s Rally" : Rorik shouts a command that inspires nearby pirates.

	Effect :
* Increases attack speed of allied pirates
* Slightly increases their damage output

	This ability makes the supporting enemies more dangerous.

---

	Cutlass Assault : Rorik performs a rapid series of slashing attacks with his sabre.

	Effect :
* Multiple quick strikes against his current target
* Moderate physical damage

---

		Encounter Mechanics : 

	Powder Chain Ambush : 

	This encounter occurs only if players trigger a large barrel chain explosion inside "Tidebreaker Cove".
	When enough barrels explode, the pirates believe their camp is under attack.

	After a short delay :
* Captain Rorik arrives at the location
* He is accompanied by 3–4 Veteran Pirates (Rank III)

	The group immediately engages nearby players.
	The event is designed to punish careless use of explosives but reward players who are prepared for the resulting fight.

