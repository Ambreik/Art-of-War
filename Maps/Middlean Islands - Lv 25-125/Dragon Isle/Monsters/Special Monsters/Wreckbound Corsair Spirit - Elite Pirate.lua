			Wreckbound Corsair Spirit

---

		1. Basic Information

* Name : Wreckbound Corsair Spirit
* Title : Guardian of the Sunken Greed
* Type : Undead
* Subtype : Ghost Pirate
* Rank : Elite

---

		2. Appearance

	A spectral figure of a long-dead corsair captain, bound eternally to the wreck.
	The entity appears as a partially translucent humanoid, its form constantly shifting between solid and ethereal. The lower half of its body fades into a mist-
like current, giving the impression that it is anchored to the water itself rather than standing on ground.

	Its clothing resembles that of a high-ranking pirate captain :
* Torn longcoat drifting unnaturally as if underwater currents move through it
* Faded sash across the torso, decorated with broken insignias
* Rusted belts and hanging relics fused into its body

	Its face is :
* Hollow, with faint glowing eyes (cold blue/green hue)
* Jaw partially exposed like a drowned corpse
* Expression locked between rage and decay

	Key visual elements :
* Cutlass fused to its arm, appearing both weapon and limb
* Occasional spectral water leaks from its body (as if still drowning)
* Chains, hooks, or ship fragments embedded into its torso
* Emits faint ghostly particles resembling drifting sea debris

	Movement :
* Does not walk — glides slowly, then snaps into sudden aggressive bursts
* During ability use, its form breaks apart into mist and reforms

