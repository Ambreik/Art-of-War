			Pirate Spirit (Standard)

* Role : Guardian / Reactive Spawn
* *Behavior :
	* Dormant until:
		* Loot interaction
		* Deep zone entry
* Combat Style :
	* Melee + short-range spectral attack
* Special Mechanics :
	* "Phase Flicker" → short intangibility windows
	* "Bound to Wreck" → cannot leave area
* Spawn Logic :
	* Trigger-based (not constant presence)
* Notes :
	* Based on undead pirate archetype: cursed sailors bound to shipwrecks and treasure.

