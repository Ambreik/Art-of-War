			Dune Stalker

---

		1. Basic Information

* Name : Dune Stalker
* Title : Lurker Beneath the Drift
* Type : Beast
* Subtype : Coastal Ambusher
* Rank : Standard (Event-Based)

---

		2. Appearance

	A lean, predatory creature evolved for camouflage within dunes, driftwood, and shallow coastal environments.

	Its body is elongated and low to the ground, with a flexible spine allowing it to twist and reposition quickly. The skin is covered in rough,sand-textured hide,
colored in muted tones of beige, grey, and washed-out brown, perfectly blending with the environment.

	Its back is layered with :
* Jagged, uneven protrusions resembling broken driftwood
* Thin, fin-like ridges that mimic dried sea plants

	The head is :
* Narrow and slightly elongated
* Equipped with a split jaw structure, opening wider than expected
* Lined with thin, needle-like teeth

	Eyes :
* Small, recessed, pale yellow
* Almost invisible until it moves

	Limbs : 
* Long and jointed
* End in clawed digits adapted for digging and gripping sand

	Tail :
* Thin and whip-like
* Used for balance during rapid repositioning

	Visual behavior :
* Often partially buried, with only parts of its body visible
* Sand subtly shifts when it moves beneath the surface
* Can remain completely still, blending perfectly into environment

	Movement :
* Slow and crawling when stalking
* Extremely fast bursts during attack
* Frequently disappears and reappears from different angles

