			Stormtide Revenant

---

		1. Basic Information

* Name : Stormtide Revenant
* Title : Warden of the Ghost Reef
* Type : Undead
* Subtype : Drowned Guardian
* Rank : Mini-Boss

---

		2. Appearance

	A drowned warrior bound to the reef, infused with storm energy and oceanic decay.

	The body is humanoid but partially eroded, with sections appearing :
* Waterlogged
* Cracked
* Reinforced with coral and reef growth

	Its armor :
* Broken naval or ceremonial plating
* Covered in barnacles, algae, and salt erosion
* Pieces fused unnaturally into its body

	The skin :
* Pale blue-grey
* Veins glow faint electric blue beneath the surface

	Head :
* Hollow, partially skeletal face
* Eyes glowing with unstable lightning energy
* Mouth occasionally emits faint arcs of electricity

	Weapon: 
* Trident, long and jagged:
	* Metal fused with coral and crystal
	* Tips constantly crackling with electricity
	* Emits small lightning arcs into surrounding water

	Effects :
* Water around its feet ripples unnaturally
* Electrical discharges travel through shallow water
* Occasional lightning flickers across its body

	Movement :
* Slow, deliberate when idle
* Sudden aggressive lunges in combat

---

		3. Location & Habitat

* Area : Dragon Isle – Ghost Reef
* Zone : Reef Fishing Pools / Rock Platforms
* Habitat Type : Shallow Water / Coastal Submerged

---

		4. Role & Combat Profile

* Role : Mini-Boss (Escalation Trigger)
* Combat Style : Zone Control / Close-Range Punisher / Elemental Pressure
* Difficulty Level : Medium–High

---

		5. Core Behavior

* Aggro Type : Triggered (Reef Disturbance System)

---

	Trigger Conditions :
* Reef reaches "Agitated State"
* Repeated fishing / harvesting

---

	Behavior Logic :

* Emerges from :
	* Water beneath reef
* Immediately establishes combat zone in shallow water

---

	Combat Pattern :

* Encourages :
	* Mid-range play
* Punishes :
	* Close-range clustering

---

	Leash Range :
* Bound to reef zone

---

	Reset Condition :
* Player leaves reef
* No target for duration

---

		6. Abilities

---

	Storm Trident Strike : 
* Direct melee attack
* Medium damage
* Applies "Conductive Mark" (short duration)

---

	Tidal Sweep : 
* Wide horizontal swing
* Hits multiple targets
* Pushes players slightly

---

	Static Surge : 
* Emits electric pulse around self
* Stronger in shallow water

---

	Reef Call : 
* Brief channel :
	* Disturbs water
	* Prepares environment for passive interaction

---

		7. Passive Effects (CORE IDENTITY)

---

	Conductive Proximity (Signature Passive)

---

	Function :

Applies bonus electric damage under specific close-range conditions

---

	Trigger Conditions :

Electric surge is triggered when :
* Player is :
	* Within close range
	* Standing in water OR recently affected by water

AND

* Player has :
	* Been hit by trident ability
		OR
	* Remains in close range for a short duration

---

	Effect :
* Additional electric damage proc
* Can chain to nearby players (short radius)

---

	Behavior Logic :

* Encourages :
	* Spacing
	* Positioning awareness
* Punishes :
	* Staying too close
	* Fighting inside water zone

---

	Scaling Factor :
* Stronger when :
	* Multiple players are grouped
	* Water contact is constant

---

		8. Passive Traits

---

	Water Conductor : 
* All electric effects amplified in shallow water

---

	Reef Bound : 
* Gains minor resistance while standing in water

---

