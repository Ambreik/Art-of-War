			Drowned Warden of the Hold

---

		1. Basic Information

* Name : Drowned Warden of the Hold
* Title : Keeper of the Sealed Plunder
* Type : Undead
* Subtype : Bound Spirit
* Rank : Rare

---

		2. Appearance

	A heavily distorted pirate spirit, far more unstable than standard ghost pirates.
	The entity appears as a larger, denser spectral form, with parts of its body constantly phasing between visibility and complete absence. Unlike normal spirits, 
its shape is incomplete, as if pieces of it are missing or trapped elsewhere.

	Its torso is wrapped in :
* Torn naval armor fragments
* Rusted metal plates fused into spectral flesh
* Chains tightly coiled around its chest and arms

	Its lower body :
* Does not fully exist
* Instead dissolves into a swirling mass of dark water and mist

	The head is :
* Partially intact, partially collapsed inward
* One glowing eye visible, the other side hollow or flickering
* Mouth constantly leaking dark spectral water

	Key visual elements :
* Chains extending into nothingness, as if anchoring it to unseen objects
* Occasional flashes of gold, relics, or cursed artifacts embedded in its body
* Its form tears apart and reassembles during phase transitions

	Movement :
* Appears suddenly (no approach animation)
* Flickers between positions instead of traveling normally
* During combat, frequently “breaks” into fragments and reforms

