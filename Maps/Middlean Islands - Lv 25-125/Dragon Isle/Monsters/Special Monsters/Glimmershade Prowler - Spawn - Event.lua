			Glimmershade Prowler

---

		1. Basic Information

* Name : Glimmershade Prowler
* Title : Lurker of Broken Light
* Type : Beast
* Subtype : Cave Predator
* Rank : Standard (Ambush Spawn)

---

		2. Appearance

	A sleek, low-profile predator adapted to crystalline cave environments where light and shadow constantly shift.

	Its body is slender and elongated, similar to a cave panther fused with reptilian traits. The skin is smooth but segmented in places, layered with thin, 
semi-translucent scales that faintly refract light.

	Coloration:
* Base: deep charcoal / dark violet
* Overlay: subtle reflective patterns that shimmer when exposed to light

	Its back is lined with:
* Small crystal-like growths
* Jagged but not oversized, acting as natural light disruptors

	Head:
* Narrow, predatory
* Jaw opens wider than expected
* Teeth thin, sharp, slightly reflective

	Eyes:
* Bright, pale blue or white
* Glow more intensely in darkness
* Dim slightly under direct light

	Limbs:
* Long, silent, padded for stealth
* Claws thin and hooked for gripping stone

	Tail:
* Long and flexible
* Used for balance in narrow paths

	Visual behavior:
* Body distorts slightly under light reflection
* Appears partially “blurred” when moving through shadows
* Light hitting it causes brief shimmer, revealing position

	Movement:
* Silent, smooth stalking
* Quick bursts of speed
* Climbs walls and uneven cave surfaces

