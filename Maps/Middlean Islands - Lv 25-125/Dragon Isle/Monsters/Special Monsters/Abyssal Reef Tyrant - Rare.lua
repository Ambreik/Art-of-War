			Abyssal Reef Tyrant

---

		1. Basic Information=

* Name : Abyssal Reef Tyrant
* Title : Apex of the Sunken Depths
* Type : Beast
* Subtype : Leviathan Predator
* Rank : Rare

---

		2. Appearance 

	A massive, ancient marine predator adapted to both reef and wreck environments.
	The creature has a long, muscular body resembling a hybrid between a shark and a deep-sea leviathan. Its skin is covered in layered coral growths and jagged 
reef-like protrusions, giving it a natural armor appearance.

	Its head is broad and heavily plated, with :
* Multiple rows of uneven, broken teeth
* Bioluminescent scars across the jawline
* Small glowing eyes adapted for deep water hunting

	Along its spine :
* Large, sharp dorsal fins resembling shattered ship fragments or coral blades
* Occasional embedded debris (hooks, chains, metal shards), suggesting long-term survival near wrecks

	Fins are :
* Torn and asymmetrical
* Reinforced with hardened cartilage structures

	Its movement is :
* Slow and controlled when idle
* Explosively fast when attacking

	Visual effects :
* Emits faint trails of disturbed sediment
* Water around it slightly distorts during movement
* When enraged, bioluminescent veins glow brighter

