			Bloodstone Colossus

---

		1. Basic Information

* Name : Bloodstone Colossus
* Title : Devourer of the Feeding Grounds
* Type : Beast
* Subtype : Giant Crustacean
* Rank : Rare

---

		2. Appearance

	An enormous, ancient crab that has adapted to the Bloodstone Cove over countless cycles of feeding and territorial dominance.

	Its body is massive and heavily armored, covered in thick, jagged plates resembling blood-red stone, as if the creature has fused with the mineral 
composition of the cove itself.

	The shell :
* Deep crimson with dark marbling patterns
* Cracked in places, glowing faintly from within
* Covered in barnacles, coral growth, and embedded debris

	Its claws are :
* Asymmetrical :
	* One oversized crushing claw (massive, slow, devastating)
	* One serrated claw (faster, slicing)
* Edges chipped and worn, suggesting constant combat

	The legs :
* Thick and rooted, digging deep into sand when stationary
* Leave deep impressions in the ground

	Eyes :
* Small, recessed, glowing faint amber
* Hard to read, giving an emotionless, ancient presence

	Additional details :
* Sand and small stones constantly fall from its body
* When enraged, cracks in its shell glow brighter
* Emits low grinding sounds, like stone scraping stone

	Movement :
* Slow, deliberate repositioning
* Sudden bursts of lateral movement (side dashes)

---

		3. Location & Habitat

* Area : Dragon Isle – Bloodstone Cove
* Zone : Exposed Shoreline / Sandbanks (Low Tide)
* Habitat Type : Coastal / Buried Sand Emergence

---

		4. Role & Combat Profile

* Role : Rare Apex Encounter
* Combat Style : Zone Control / Heavy Impact / Area Denial
* Difficulty Level : High

---

	5. Core Behavior

* Aggro Type : Triggered (Escalation System)

---

	Trigger Conditions :
* Repeated bait placement within time window
* Cove enters "Feeding Frenzy State"

---

	Behavior Logic :
* Does NOT replace mini-boss immediately
* Instead :
	* Emerges after escalation threshold
* Spawn style :
	* Bursts from sand or shallow water
	* Creates shockwave on emergence

---

	Leash Range :
* Large zone within cove

---

	Reset Condition :
* Player leaves area
* Tide rises (optional interaction)

---

		6. Abilities

---

	Colossal Crush : 
* Heavy claw slam
* Deals massive damage in small area

---

	Seismic Slam :
* Slams both claws into ground
* Creates shockwave:
  * Damages
  * Slight knockback

---

	Lateral Surge :
* Fast sideways dash
* Repositions and damages on impact

---

	Burrow Shift :
* Temporarily burrows into sand
* Re-emerges at new position
* Resets positioning

---

	Shell Fortification (Phase Trigger) : 
* Activates below 50% HP
* Reduces incoming damage
* Slows movement further

---

		7. Passive Effects

---

	Living Fortress : 
* High damage resistance from front

---

	Feeding Ground Dominance : 
* Prevents other predator spawns while active

---

	Bait Resonance : 
* Gains minor buffs based on number of bait triggers used

