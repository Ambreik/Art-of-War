* Shelf Whisper Entity – Rare Elemental type creature. Medium HP Bar. Ambient illusion-based entity. Floating movement. Causes disorientation effects.
* Cliffveil Stalker – Elite Beast type monster. Medium-High HP Bar. Ambush predator. Uses vertical concealment. Applies Bleed.
* Wind Echo Spirit – Rare Elemental creature. Low HP Bar. Pure ambient entity tied to wind currents. Non-hostile unless disturbed.

---

	Quarry Descent Passage : 
* Descent Crusher – Elite Beast type monster. High HP Bar. Slow heavy attacker. Controls narrow passages. Applies Knockdown.
* Tunnel Breaker – Rare Insect type monster. Medium HP Bar. Swarm leader variant of Echo Burrowers. Groups appear in waves.
* Miners’ Lost Shade – Elite Humanoid/Undead type monster. Medium HP Bar. Former miner corrupted entity. Applies Fear + Bleed.

---

	The Drowning Arch : 
* Arch Leviathan – Elite Beast type monster. Very High HP Bar. Massive aquatic predator. Rare spawn. Controls entire submerged arch zone.
* Tidebound Warden – Elite Humanoid/Elemental hybrid. Medium-High HP Bar. Guardian role. Found patrolling submerged ruins.
* Abyssal Drift Serpent – Rare Animal type monster. Medium HP Bar. Long-range aquatic ambusher. Applies Poison.

---

	The Root Maze : 
* Mazeheart Entity – Elite Beast/Elemental hybrid. High HP Bar. Central controlling organism of the maze. Slow movement. Alters root paths behaviorally.
* Root Labyrinth Prime – Rare Beast type monster. Medium-High HP Bar. Large Rootmaze Creeper variant. Leads smaller creepers.
* Viper Knot Matron – Elite Animal type monster. Medium HP Bar. Controls Rootcoil Vipers. Applies strong Poison stacks.

---

	The Forgotten Stair : 
* Ascendant Raptor Alpha – Elite Beast type monster. High HP Bar. Apex stair predator. Controls vertical hunting routes. Applies Heavy Bleed.
* Ruin Sentinel Core – Rare Construct type creature. Medium-High HP Bar. Stationary guardian tied to ruins. Emits defensive pulses.
* Stairwind Spirit – Rare Elemental type creature. Low HP Bar. Ambient entity tied to elevation and wind currents. Non-hostile.

