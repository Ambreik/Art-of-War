		2. Appearance

	The Vinecrawler Lizard is a medium-sized reptilian creature with a slender, elongated body built for agility rather than brute strength. Its body is covered in 
overlapping scales that appear slightly rough in texture, colored in deep greens, earthy browns, and muted moss-like tones that allow it to blend seamlessly into 
dense vegetation and vine-covered environments.
	Its limbs are long and flexible, ending in clawed digits that are distinctly curved and split to allow for gripping onto uneven surfaces such as bark, stone, 
and hanging vines. These claws are particularly well-adapted for climbing, often seen digging into vertical surfaces as the creature ascends or descends with ease.
	The tail of the Vinecrawler Lizard is long and prehensile, often wrapping around vines or branches to stabilize its movement. It frequently uses its tail as a 
balancing tool when navigating narrow or vertical paths, coiling or anchoring itself while pausing or repositioning.
	Its head is narrow and slightly angular, with alert eyes positioned to provide a wide field of vision. Subtle ridges run along the top of its head and down its 
spine, giving it a slightly armored yet organic appearance. Occasionally, small traces of plant matter such as leaves or fibers cling to its scales, reinforcing its
camouflage within its environment.
	When stationary, the Vinecrawler Lizard often remains pressed against vertical surfaces, nearly indistinguishable from the vines and roots surrounding it. Its 
movements are deliberate and controlled, avoiding sudden motions unless fleeing or reacting to disturbances.

