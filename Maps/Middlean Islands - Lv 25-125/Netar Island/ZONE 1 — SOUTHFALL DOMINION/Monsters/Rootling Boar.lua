---

		2. Appearance

	The Rootling Boar is a sturdy, low-built creature with a thick, muscular frame adapted for pushing through dense forest undergrowth. Its body is covered in 
coarse, layered fur that blends tones of dark brown, moss green, and earthen gray, giving it natural camouflage within root-heavy environments.
	Its back is partially overgrown with hardened root-like protrusions that appear to have fused with its hide over time. These natural growths form uneven ridges 
along its spine, some resembling bark or twisted wood rather than bone. In certain individuals, small patches of moss or plant life cling to these structures, 
reinforcing its connection to the forest.
	Its tusks are thick and slightly curved outward, with a rough, stone-worn texture. These tusks are used both for defense and for digging or uprooting terrain. 
The snout is broad and powerful, often stained with soil from constant rooting behavior.
	Its legs are short but extremely strong, built for stability rather than speed. When it moves, it pushes through vegetation rather than avoiding it, often 
breaking small roots or brush in its path. Its eyes are small but alert, reflecting a cautious yet territorial nature.

	When agitated, the Rootling Boar lowers its head, scraping the ground with its front hooves, preparing for a direct charge.

