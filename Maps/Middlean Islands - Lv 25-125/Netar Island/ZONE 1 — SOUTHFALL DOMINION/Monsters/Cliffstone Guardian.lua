			Cliffstone Guardian

---

		1. Basic Information

* Monster Name : Cliffstone Guardian
* Rank : III
* Monster Class : Rare
* Monster Type : Tanky / Patrol / Melee
* Monster Category / Race : Construct
* Element Type : Earth
* Spawn Timer : 35 seconds
* Location / Sub-Area : Netar Island – Zone 1 – Southfall Dominion (cliff edges, ancient ruins, elevated stone platforms, collapsed pathways)
* Group Pattern : Solo
* Aggro Type : Neutral (Aggressive when entering protected zones)
* Special Notes : Ancient guardian entity; tied to ruins and cliffside structures; partial tame variant exists for mount usage

---

		2. Appearance

	The Cliffstone Guardian is a massive humanoid construct carved from ancient stone, its body composed of interlocking slabs of weathered rock held together by 
faintly glowing seams of earthen energy. Its form is bulky and imposing, with exaggerated limbs and a wide, grounded stance that reflects its purpose as a 
stationary or slow-moving protector.
	Its surface is rough and eroded, marked by cracks, chips, and signs of age, as if it has stood in place for centuries. Patches of moss and lichen grow along its
shoulders, arms, and back, blending it seamlessly into the surrounding cliffside and ruins. In some areas, its stone appears fused with fragments of ancient 
architecture, suggesting it was either built from or has merged with the structures it guards.
	Its head is minimalistic, shaped like a carved helm or stone mask, with two dimly glowing eye sockets that emit a steady, amber light. These eyes do not flicker
or move rapidly—instead, they shift slowly and deliberately, reinforcing its heavy, methodical nature.
	When inactive, the Guardian can be mistaken for part of the environment, standing motionless like a statue. When it awakens, deep grinding sounds echo from 
within its body as stone plates shift and align, accompanied by small fragments falling from its frame.
	Each step it takes is heavy and deliberate, causing minor tremors and echoing impacts, especially on stone surfaces.

