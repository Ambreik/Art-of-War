		5. Skills & Abilities

---

* "Stonebreaker Slam" : The Guardian raises its arm and slams the ground with force.
	* Damage Type : Physical / Earth
	* Target : AoE (frontal impact zone)
	* Effect : Heavy damage + knockdown
	* Cooldown : Medium
	* Mechanic : High-impact, telegraphed attack

---

* "Seismic Pulse" : Emits a shockwave through the ground.
	* Damage Type : Earth
	* Target : AoE (circular around self)
	* Effect : Damage + slow
	* Cooldown : Medium–High
	* Mechanic : Area denial and zoning

---

* "Stone Grasp" : Attempts to trap targets using rising stone.
	* Damage Type : Earth
	* Target : Single / small AoE
	* Effect : Root / immobilize
	* Cooldown : Medium
	* Mechanic : Prevents escape or repositioning

---

* "Fortified Core" (Passive) : Reinforces its structure when stationary.
	* Effect :
		* Increased damage resistance
		* Reduced incoming CC effects
	* Mechanic : Encourages stationary combat positioning

