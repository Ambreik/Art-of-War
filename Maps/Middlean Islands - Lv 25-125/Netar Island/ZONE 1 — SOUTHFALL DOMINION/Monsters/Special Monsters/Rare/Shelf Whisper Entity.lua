			Shelf Whisper Entity

---

		1. Basic Information

* Monster Name : Shelf Whisper Entity
* Rank : III
* Monster Class : Rare
* Monster Type : Invoker, Coward, Patrol
* Monster Category / Race : Elemental
* Element Type : Wind
* Spawn Timer : 30 minutes to 15 hours.
* Location / Sub-Area : The Whispering Shelf – Floating Ledges / Fogbound Cliffs
* Group Pattern : Solo
* Aggro Type : Neutral
* Special Notes : Illusion-based entity; causes disorientation; avoids direct combat; relies on psychological pressure mechanics

---

		2. Appearance

	The Shelf Whisper Entity appears as a drifting, semi-transparent mass of pale mist, constantly shifting in form as though struggling to maintain a stable shape.
At times, it resembles a humanoid silhouette, while at others it stretches into thin strands that unravel into the surrounding air.
	Its "body" flickers with faint glimmers of light, like distant reflections seen through fog, and its edges blur into the environment, making it difficult to 
track visually. Subtle distortions ripple around it, bending light and space in unnatural ways, giving the impression that the air itself is unstable in its 
presence. When it becomes active, faint echo-like afterimages trail behind its movement, as if it exists in multiple positions at once.

