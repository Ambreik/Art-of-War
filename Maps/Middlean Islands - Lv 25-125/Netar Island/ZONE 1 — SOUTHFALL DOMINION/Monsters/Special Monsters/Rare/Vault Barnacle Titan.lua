	5. Skills & Abilities

* "Spine Eruption" : The Titan rapidly extends multiple spikes from its surface in a targeted area around its body. These spikes erupt from the ground, walls, or 
nearby surfaces depending on positioning, dealing moderate Physical damage and applying a brief stagger. The attack creates temporary hazard zones that persist for 
a short duration.

* "Barnacle Barrage" : Releases clusters of hardened shell fragments or barnacle-like projectiles from its body toward nearby targets. These projectiles deal 
moderate damage on impact and can apply minor knockback, disrupting positioning.

* "Adhesive Grip" (Passive) : The Titan maintains a strong attachment to the environment, making it resistant to displacement effects. Attempts to move or 
reposition it are largely ineffective.

* "Pressure Release Pulse" : When damaged significantly, the Titan emits a concussive pulse from its core, creating a radial shockwave that deals minor damage and 
pushes players slightly away, reinforcing distance control.

* "Regenerative Shell" (Passive) : Over time, damaged outer layers begin to reform slowly. This regeneration is reduced while the Titan is actively taking sustained
damage.

