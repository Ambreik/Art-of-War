			Lanternbound Wraith

---

		Appearance

* A translucent, drifting spectral entity formed from pale blue and amber light
* Core body appears like a distorted humanoid silhouette, constantly unraveling into wisps of mist
* Fragments of old lantern metal, chains, or handles float within its form, slowly orbiting its center
* Emits a soft flickering glow that pulses in sync with nearby lantern light sources
* Lower body fades into vapor, never fully touching the ground
* When agitated, its glow intensifies and becomes unstable, casting erratic shadows around it
* Its “face” is undefined, occasionally forming hollow eye-like voids that stretch and collapse

---

		Behavior & Combat Profile

* Remains dormant or semi-invisible near lanterns until players enter proximity
* Prefers dim, flickering light zones where visibility is unstable
* Engages suddenly, phasing into visibility before attacking
* Maintains short distance, circling targets rather than direct melee engagement
* Retreats slightly after casting abilities, maintaining pressure through control rather than damage

---

		Abilities

* "Flicker Manifestation" – The wraith shifts between visible and semi-invisible states. While partially phased, it takes reduced damage and becomes harder to target. Fully materializes briefly when attacking.

* "Lantern Pulse" – Channels energy from nearby light sources, emitting a wave that applies "Fear" to targets within range. Fear causes players to lose directional control for a short duration. Effect duration is slightly increased if multiple lanterns are nearby.

* "Essence Drain" – A channeled spectral tether that drains health over time from the target, restoring a portion of it to the wraith. Breaks if line of sight is interrupted or distance is created. Applies "Minor Drain" effect.

* "Light Distortion" – Passively alters nearby light intensity, causing flickering effects that reduce player visibility consistency and make movement harder to track.

---

		Spawn Conditions=

* Time : Night only
* Location : Lantern-lit areas, village outskirts, pathways with artificial light sources
* Group Size : Solo
* Spawn Behavior : Low spawn rate; tied to light sources rather than fixed positions

---

		Loot Identity	

* Light-based or spectral crafting materials
* Rare chance for accessories enhancing regeneration or utility
* Chance to drop: *Flickering Essence* (used in alchemy or enchantments)

