---

		2. Appearance

	The Ruin Sentinel Core appears as a large, hovering or partially embedded construct composed of stone plates, metallic frameworks, and glowing arcane cores at #
its center. Its body is primarily spherical or orb-like, though partially encased within layered geometric armor segments that interlock with precise symmetry.
	At the center of the construct lies a luminous core that emits a steady, pulsating glow. This core is encased within translucent or cracked crystalline 
material, through which veins of light can be seen flowing in rhythmic patterns. The intensity of the glow subtly increases and decreases, resembling a heartbeat or
energy cycle that sustains the entity.
	Surrounding the core are rotating segments of engraved stone and metal plates, each inscribed with ancient runic patterns. These segments slowly orbit or shift 
position, aligning and realigning as the entity activates or reacts to threats. The movement is smooth but mechanical, suggesting a system governed by internal 
magical mechanisms rather than biological motion.
	Thin projections extend outward from the core structure, resembling short stabilizing spires or antenna-like rods. These emit faint pulses of light or energy 
waves, which ripple outward into the surrounding environment. When fully active, the construct emits a low resonant hum that grows stronger as it detects intruders.
	Despite its stationary nature, the Ruin Sentinel Core gives the impression of constant readiness, as if it is perpetually maintaining a defensive field anchored
to the ruins it protects.

