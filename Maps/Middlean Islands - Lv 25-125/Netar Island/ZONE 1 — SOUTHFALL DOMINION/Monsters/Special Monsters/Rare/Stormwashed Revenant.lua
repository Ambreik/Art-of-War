			Stormwashed Revenant

---

		1. Basic Information

* Monster Name : Stormwashed Revenant
* Rank : Elite
* Monster Class : Elemental / Control / Skirmisher
* Monster Type : Magic, Mobility, Area Control
* Monster Category / Race : Elemental (Humanoid-like manifestation)
* Element Type : Wind / Water (Storm-aligned)
* Spawn Timer : Event-based (spawns only during storm conditions; despawns when storm subsides)
* Location / Sub-Area : "Broken Coastline" — open coastal zones, cliff edges, elevated rock platforms, and exposed shoreline areas affected by high winds and 
crashing waves
* Group Pattern : Solo
* Aggro Type : Reactive (becomes hostile when approached or struck during storm presence)
* Special Notes : A transient entity bound to atmospheric instability; its existence is tied directly to storm intensity and coastal turbulence

---

		2. Appearance

	The Stormwashed Revenant manifests as a semi-translucent humanoid figure formed from a turbulent fusion of seawater, mist, and compressed wind currents. Its 
body is not solid in the traditional sense, but instead appears as a constantly shifting silhouette held together by swirling layers of vapor and liquid energy.
	Its form is most clearly visible during lightning flashes or sudden changes in wind pressure, when brief illuminations reveal a humanoid outline composed of 
cascading water streams and spiraling air currents. Outside of these moments, its body blends into the storm itself, appearing as a moving distortion in the rain 
and mist rather than a clearly defined entity.
	The head and upper torso are the most stable parts of its structure, often appearing slightly more condensed than the rest of its body. Within this region, 
faint glowing patterns can be seen, resembling fractured arcs of pale blue and white light that pulse irregularly, like a heartbeat synchronized with thunder and 
wind gusts.
	Its “face” is indistinct, with no clearly defined features. Instead, two hollow, brighter focal points suggest the presence of eyes—these emit a soft, shifting 
glow that intensifies during aggressive states. The absence of a solid facial structure gives it an expressionless yet unnerving presence, as if identity itself is 
dissolved within the storm.
	The Revenant’s limbs extend and retract fluidly, forming and reforming from streams of water and compressed air. When it moves, its arms and legs do not step in
a traditional sense but instead glide forward, carried by wind currents while water trails follow behind in thin, ribbon-like streams. These appendages can elongate
during attacks, striking from unexpected angles before dissipating back into the storm.
	Around its body, small fragments of spray, mist, and airborne droplets continuously orbit and spiral, forming a loose aura that expands and contracts with its 
motion. During stronger storm activity, this aura becomes more chaotic, with visible vortices forming around its limbs and torso.
	Its lower body often fades into a trailing column of mist and water that merges seamlessly with the surrounding environment, making it difficult to determine 
where the entity ends and the storm begins. In moments of intense movement, this trailing mass can stretch outward, creating afterimages that linger briefly before 
dissolving back into the surrounding air.
	Overall, the Stormwashed Revenant appears less like a creature inhabiting the storm and more like a localized condensation of storm energy given temporary 
form—an unstable, transient presence that flickers between visibility and dissolution with every surge of wind and wave.

