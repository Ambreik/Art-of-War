		5. Skills & Abilities

* "Gale Lash" : The Revenant extends a limb formed of compressed wind and water, striking a target with a fast, whipping motion. This ability deals moderate damage 
and applies a "Push" effect, slightly displacing the target in the direction of the strike.

* "Storm Surge Step" : The Revenant rapidly shifts position by riding a burst of wind current, effectively teleporting a short distance within the storm zone. This 
ability allows it to reposition instantly to avoid attacks or close gaps.

* "Thunder-Soaked Discharge" : The entity gathers storm energy and releases it in a localized burst of water and electrical charge (ambient storm synergy). This 
attack deals AoE damage and applies "Shock", briefly disrupting player movement and action timing.

* "Cyclone Drift" : The Revenant generates a swirling vortex around itself, pulling in nearby players slightly before pushing them outward. This creates positional 
instability and can disrupt formations.

* "Storm Resonance" (Passive) : Its abilities become stronger during active storm conditions. Increased wind speed and rainfall amplify its mobility and the range 
of its displacement effects.

