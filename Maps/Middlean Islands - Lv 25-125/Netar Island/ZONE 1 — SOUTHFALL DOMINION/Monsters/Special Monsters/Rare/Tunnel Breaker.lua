	* Damage Type : Physical
	* Target : Single target area
	* Effect : Surprise emergence damage + brief stagger
	* Cooldown : Medium
	* Mechanic : Primary mobility and ambush tool; bypasses terrain restrictions

---

* "Chitin Rend" : A close-range mandible attack.
	* Damage Type : Physical
	* Target : Single target
	* Effect : Moderate damage + Bleed (minor)
	* Cooldown : Short
	* Mechanic : Sustained melee pressure ability

---

* "Swarm Command" : Enhances nearby Echo Burrowers.
