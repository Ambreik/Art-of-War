---

		2. Appearance

	The Tunnel Breaker is a large, heavily armored insectoid creature with an elongated, segmented body covered in layered chitin plates that appear reinforced 
through repeated collisions with stone. Its exoskeleton is dark and rugged, marked with jagged ridges and worn edges, as though it has spent its entire existence 
forcing its way through dense underground rock.
	Its head is broad and wedge-shaped, resembling a natural drilling implement. Mandibles extend forward like interlocking crushers, constantly shifting and 
grinding with faint scraping sounds. Its forelimbs are thicker and more developed than its rear legs, ending in hardened, spade-like appendages designed for digging
and breaking compacted earth.
	Subtle cracks and abrasions line its body, often filled with fine dust and mineral residue. When it moves, it emits a constant low scraping and grinding noise, 
as if its body itself is partially responsible for carving tunnels. Unlike smaller burrowers, the Tunnel Breaker maintains a more upright posture when emerging, 
asserting itself as a dominant presence within the swarm.

