			Root Labyrinth Prime

---

		1. Basic Information

* Monster Name : Root Labyrinth Prime
* Rank : III
* Monster Class : Rare
* Monster Type : Swarm Leader / Heavy Melee / Root Entity
* Monster Category / Race : Beast
* Element Type : Nature / Root
* Spawn Timer : 40 minutes (Swarm node respawn cycle)
* Location / Sub-Area : The Root Maze – Outer Root Networks / Branching Corridors / Dense Creeper Clusters
* Group Pattern : Group (Leads Root Maze Creepers)
* Aggro Type : Aggressive
* Special Notes : Functions as a coordination node for Root Maze Creepers, strengthening and directing nearby lesser root-based creatures

---

		2. Appearance

	The Root Labyrinth Prime is a massive, quadrupedal creature formed from densely interwoven roots, vines, and hardened organic matter. Its body appears as though
multiple root systems have fused together into a single, coherent organism, creating a layered and heavily reinforced structure.
	Its limbs are thick and uneven, resembling clusters of roots bound into leg-like formations that end in sharp, naturally formed root claws. These limbs dig into
the ground as it moves, anchoring itself with each step and leaving behind faint impressions of disturbed earth and trailing root fibers.
	Its head is broad and partially indistinct, blending into its upper torso rather than forming a clearly defined skull. Within this mass, faint glowing lines 
pulse intermittently, suggesting internal energy flow similar to vascular systems. Small tendrils extend from its body, constantly shifting and probing the 
environment, reacting to nearby movement and signals from surrounding root creatures.
	The Prime’s back is covered in layered root protrusions that arch outward like a protective canopy. These protrusions occasionally twitch or extend, as if 
transmitting or receiving signals through the maze’s root network. Its overall presence feels less like a single creature and more like a mobile extension of the 
Root Maze itself.

