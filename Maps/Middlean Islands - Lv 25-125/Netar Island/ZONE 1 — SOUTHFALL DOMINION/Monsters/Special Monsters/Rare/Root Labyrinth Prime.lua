		5. Skills & Abilities

* "Root Commander" : The Prime emits signals that enhance nearby Root Maze Creepers.
	* Effect :
		* Increases attack speed and movement speed of allied creepers
		* Improves their coordination and targeting behavior
	* Cooldown : Passive aura
	* Mechanic : Core leadership ability defining its role as a swarm controller

---

* "Entangling Sweep" : Sweeps its root limbs in a wide arc.
	* Damage Type : Physical + Nature
	* Target : Cone / frontal arc
	* Effect : Damage + Rooting
	* Cooldown : Medium
	* Mechanic : Primary crowd control melee ability

---

* "Burrow Root Strike" : Roots surge from beneath the ground targeting enemies.
	* Damage Type : Nature (AoE)
	* Target : Targeted ground zones
	* Effect : Burst damage + brief immobilization
	* Cooldown : Medium
	* Mechanic : Area denial and anti-positioning tool

---

* "Swarm Signal Pulse" : Sends a pulse through the root network to nearby allies.
	* Effect :
		* Temporarily boosts defense and aggression of nearby creepers
		* Causes synchronized attacks from swarm units
	* Cooldown : Medium
	* Mechanic : Amplifies group combat effectiveness during engagements

---

* "Root Regeneration" (Passive) : The Prime slowly regenerates over time when not heavily pressured.
	* Effect : Gradual HP recovery under low damage conditions
	* Mechanic : Sustained combat resilience

