---

		2. Appearance

	The Abyssal Drift Serpent is a long, slender aquatic creature with a fluid, ribbon-like body that moves with minimal resistance through the water. Its form 
lacks the bulk of larger predators, instead emphasizing agility and subtlety. Its scales are smooth and dark, blending seamlessly with the surrounding depths, often
appearing as a faint shadow until it fully reveals itself.
	Along its elongated body, faint bioluminescent patterns pulse intermittently, resembling slow-moving currents of dim light that travel from head to tail. These 
patterns are usually subdued, but may intensify briefly when the serpent is preparing to strike or has detected prey.0
	Its head is narrow and streamlined, with sharp, needle-like fangs partially visible even when its mouth is closed. Its eyes are small but piercing, reflecting 
faint ambient light in a way that gives the impression of constant vigilance. When it moves, it does so with a drifting, almost weightless motion, weaving through 
water currents as though it is part of them rather than simply moving within them.
	Unlike more aggressive creatures, the Abyssal Drift Serpent rarely announces its presence. It often remains hidden among ruins, submerged arches, or darker 
water pockets, emerging only when an opportunity presents itself.

