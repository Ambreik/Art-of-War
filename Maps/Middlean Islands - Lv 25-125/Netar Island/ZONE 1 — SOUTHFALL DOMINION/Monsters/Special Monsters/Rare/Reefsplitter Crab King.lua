		7. Mechanics Interaction

* Strongly tied to reef clusters, coral density, and narrow underwater terrain
* Controls choke points by occupying large stationary zones
* Enhances surrounding ecosystem, acting as a "mini-boss node" for crab populations
* Encourages players to manage adds (crab groups) while dealing with the main entity
* Terrain favors defensive playstyles rather than mobility-based encounters

