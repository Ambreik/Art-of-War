			Reefsplitter Crab King

---

		1. Basic Information

* Monster Name : Reefsplitter Crab King
* Rank : Rare
* Monster Class : Territorial Tank / Commander
* Monster Type : Melee, Defensive, Area Control, Support Aura
* Monster Category / Race : Beast
* Element Type : Earth / Water (Reef-aligned)
* Spawn Timer : 3–4 hours (real-time)
* Location / Sub-Area : "Broken Coastline" — coral clusters, reef formations, submerged rock gardens, and densely packed tidal structures where narrow passages and natural choke points exist
* Group Pattern : Solo (but surrounded by smaller reef crab colonies)
* Aggro Type : Territorial (reacts aggressively when reef boundaries are disturbed)
* Special Notes : Functions as a hive-like focal entity for local crab populations, enhancing their coordination and durability

---

		2. Appearance

	The Reefsplitter Crab King is an enormous crustacean whose body is encased in a thick, natural armor formed from coral growth, mineral deposits, and layered 
chitin. Its shell is not uniform; instead, it appears as a living reef structure, with branching coral formations, barnacle clusters, and jagged stone-like 
protrusions fused across its carapace over time.
	Its primary shell is massive and dome-shaped, with a rugged, uneven surface that resembles a fragmented reef. Embedded within this structure are patches of 
vibrant coral that range in color from muted reds and oranges to pale blues and off-whites, depending on the surrounding environment and water conditions. These 
coral formations appear partially alive, subtly reacting to movement and currents in the water.
	The creature’s claws are its most striking physical feature. They are disproportionately large, thick, and heavily reinforced, with one claw often larger or 
more dominant than the other. The outer surfaces of the claws are layered with hardened ridges and reef-like textures, giving the impression that they have grown 
and fused with external mineral structures over time. The inner edges of the claws are sharp and serrated, capable of crushing and splitting rock, coral, and shell 
alike.
	Its legs extend from beneath the shell in multiple segmented pairs, each joint reinforced with chitin plates. These legs are sturdy and capable of supporting 
its massive weight, though its movement remains slow and deliberate. As it moves across the seabed or reef surfaces, its legs scrape and press against the terrain, 
occasionally dislodging small fragments of coral or sediment.
	At the front of its body, partially obscured beneath the shell’s overhang, are its eyes—small, dark, and clustered, glowing faintly with a dim bluish or 
greenish hue. These eyes are positioned to provide wide peripheral awareness rather than focused long-range vision, reflecting its reliance on environmental sensing
rather than visual precision.
	The Reefsplitter Crab King often appears as part of the reef itself when stationary. Its shell blends seamlessly into surrounding coral formations, making it 
difficult to distinguish from the environment at a distance. Small reef creatures may cluster around or on its body, reinforcing the impression that it is not 
merely inhabiting the reef—but is an integral, living extension of it.
	When it becomes active, the subtle shifting of coral fragments, the movement of its legs, and the slow opening of its claws reveal that the reef is not static 
at all, but anchored to a massive, living entity beneath.

