		5. Skills & Abilities

* "Reefcrusher Slam" : The Crab King raises one of its massive claws and brings it down with tremendous force onto the ground or a target. This attack deals heavy 
Physical damage in a localized area and may cause minor shock displacement in nearby units.

* "Coral Split Grip" : A targeted grab attack where the Crab King clamps down on a player with its claw. This ability deals sustained damage while the target is 
held briefly, simulating crushing pressure. If uninterrupted, it can follow up with a second crushing strike.

* "Reefguard Aura" : A passive aura that enhances nearby crab-type creatures, increasing their defense and attack coordination. This makes surrounding mobs more 
durable and slightly more aggressive in combat.

* "Tidal Shell Fortification" : The Crab King reinforces its shell temporarily, increasing its damage reduction and resistance to incoming attacks. While active, it
becomes significantly harder to damage but moves even slower.

* "Crust Formation" (Passive) : Over time, additional reef material accumulates on its shell, further reinforcing its defenses during prolonged encounters.

