* CC Resistances : High resistance to Knockback and displacement

---

		4. Combat Behavior / AI

| State                 | Description                                                                                                                   |
| --------------------- | ----------------------------------------------------------------------------------------------------------------------------- |
| Idle / Patrol         | Remains dormant, emitting low pulses; nearby Stone Mites behave passively but remain close.                                   |
| Detection             | Activates when players approach or disturb nearby nodes/mites; pulses become stronger and more frequent.                      |
| Combat                | Focuses on area pulses and empowering nearby Stone Mites rather than direct damage.                                           |
| Enrage / Phase Change | At ~50% HP, pulse frequency increases and begins spawning additional mites periodically.                                      |
| Death                 | Core destabilizes and collapses inward, releasing a final resonance burst that damages and briefly disorients nearby players. |

---

		5. Skills & Abilities

* "Resonance Pulse" : Emits a circular shockwave around itself every few seconds. Deals moderate Earth damage and slightly slows affected players. Pulse range 
increases when multiple "Stone Mites" are nearby.

* "Mite Amplification Aura" : Passive aura that increases nearby "Stone Mites’" attack speed and movement speed. Also causes them to react faster to player presence
and swarm more aggressively.

* "Stonecall Manifestation" : At intervals, the Resonant draws fragments from surrounding rock to spawn 2–4 additional Stone Mites. These mites emerge from cracks 
in the ground near players, creating pressure zones.

* "Echo Feedback" : When struck repeatedly in a short time, the Resonant releases a reactive burst of energy that deals minor damage and briefly disrupts attack 
rhythm (small stagger effect).

* "Core Stabilization" : Passive ability that reduces incoming burst damage; taking sustained damage over time is more effective than heavy single hits.

---

		6. Status Effects / CC Applied

* Minor Slow (from Resonance Pulse)
* Micro-Stagger (from Echo Feedback / death burst)

---

		7. Mechanics Interaction

* Directly tied to "Quarry Resonance" system — more likely to appear after repeated mining triggers
* Enhances "Stone Mite" ecosystem density and aggression
* Punishes static combat due to expanding pulse radius
* Weak to sustained pressure rather than burst damage

---

		8. Quotes / Lore Lines

* "It does not live… it resonates."
* "The deeper you mine, the louder it answers."

---

		9. Respawn & Encounter Rules

* Respawn Timer / Conditions : Spawns only after resonance triggers (mining chains / node activation)
* Single / Group Combat Lock : No lock; surrounding mites join fight dynamically
* Escape / Reset Conditions : Resets if players leave resonance zone radius
* Interaction with other monsters : Continuously spawns and buffs Stone Mites during combat

---

		10. Special Rules

* Cannot spawn without nearby mining activity
* Acts as a force multiplier, not a standalone threat
* Area becomes progressively harder the longer it remains alive

