			Stonecore Resonant

---

		1. Basic Information

* Monster Name : Stonecore Resonant
* Rank : Rare
* Monster Class : Mystic Stone
* Monster Type : Spawner, Support
* Monster Category / Race : Elemental
* Element Type : Earth
* Spawn Timer : 25–35 min (conditional spawn)
* Location / Sub-Area : "The Sundrop Quarry" — mid-to-deep quarry layers, near Sundrop Iron Veins, Quarrysteel Nodes, and resonance-active mining zones
* Group Pattern : Solo (surrounded by Stone Mites)
* Aggro Type : Passive → Reactive (becomes aggressive when engaged or when nearby mites are attacked)
* Special Notes : Rare spawn triggered by repeated mining activity or resonance pulses; acts as a stabilizer/amplifier of quarry ecosystem

---

		2. Appearance

	The Stonecore Resonant does not resemble a creature in the traditional sense, but rather a living convergence of vibration and mineral form. It appears as a 
suspended cluster of jagged stone fragments orbiting a dense, glowing core embedded within the quarry floor or hovering just slightly above it.
	The central core pulses with a deep amber-gold light, dim at rest but intensifying in rhythmic waves, like a heartbeat echoing through the stone. Each pulse 
sends faint ripples through the surrounding air, subtly distorting light and causing nearby dust and loose pebbles to tremble in response.
	The outer fragments—shards of iron-veined rock and crystalline formations—rotate slowly around the core, shifting position in irregular patterns. These pieces 
occasionally grind against one another, producing low, resonant tones that echo unnaturally through the quarry tunnels.
	When fully active, thin lines of glowing energy connect the orbiting shards to the core, forming a lattice of vibrating energy that expands and contracts with 
each pulse. The ground beneath it is often cracked in circular patterns, as if shaped by prolonged exposure to its resonance.
	Despite its mostly stationary nature, the Resonant can subtly reposition itself by sinking and re-emerging through stone, leaving behind faint fractures and 
disturbed terrain. Its presence is always accompanied by a deep, almost inaudible hum that becomes more intense the closer one gets.

