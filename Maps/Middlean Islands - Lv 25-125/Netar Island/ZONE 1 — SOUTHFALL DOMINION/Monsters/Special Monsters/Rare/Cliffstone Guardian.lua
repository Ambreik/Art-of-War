			Cliffstone Guardian

---

		1. Basic Information

* Monster Name : Cliffstone Guardian
* Rank : III
* Monster Class : Rare
* Monster Type : Tanky, Melee, Patrol
* Monster Category / Race : Construct
* Element Type : Earth
* Spawn Timer : 15s
* Location / Sub-Area : Old Watcher’s Rise – Ancient Ruins / Cliffside Structures
* Group Pattern : Solo
* Aggro Type : Neutral
* Special Notes : Rare construct; remains dormant until approached; high durability; heavy slam-based combat

---

		2. Appearance

* Size : Large
* Coloration / Skin / Scales / Fur : Layered stone plates in shades of grey and weathered brown, covered in dust and moss
* Eyes / Markings / Luminescence : Faint glowing runic cracks across its body; core light pulses dim amber when active
* Special Features / Appendages : Massive pillar-like arms, bulky torso, fragmented stone shoulders
* Distinctive Traits / Visual Indicators for Mechanics :
	Cracks glow brighter before heavy attacks; ground trembles slightly before slam abilities

---

		3. Core Attributes

* HP Bar : Giant
* Defense / Armor : High
* Evasion / Dodge : Low
* Movement Speed / Mobility : Low
* Chase / Leash Radius : Small (restricted to ruin area)
* Attack Speed : Slow
* Damage Type : Physical (Crushing)
* Damage Pattern : Crushing Blow, Direct, AoE
* Core Status Mechanics :
	* Passive damage reduction phases
	* High stagger potential on attacks
* CC Resistances : High resistance to Knockback and Stun

---

		4. Combat Behavior / AI

| State                 | Description                                                                    |
| --------------------- | ------------------------------------------------------------------------------ |
| Idle / Patrol         | Completely stationary; appears as part of the ruins                            |
| Detection             | Activates when players enter close proximity                                   |
| Combat                | Slow, heavy attacks with strong area denial; punishes poor positioning         |
| Enrage / Phase Change | At 50% HP, increases frequency of slam attacks and gains temporary armor buffs |
| Death                 | Collapses into rubble; minor debris shockwave around it                        |

---

		5. Skills & Abilities

* "Ruin Slam" : The Guardian raises one arm and smashes the ground with immense force.
	* Damage Type : Physical (Crushing AoE)
	* Target : Circular area around impact
	* Effect : High damage; inner radius applies brief "Stun"
	* Cooldown : Medium
	* Mechanic : Core attack; heavily telegraphed; punishes players who stay too close

---

* "Seismic Pulse" : A delayed shockwave spreads outward from the slam impact.
	* Damage Type : Physical (AoE)
	* Target : Expanding ring
	* Effect : Moderate damage + "Stagger"
	* Cooldown : Triggered after Ruin Slam
	* Mechanic : Designed to punish early dodging; requires timing awareness

---

* "Stonebound Resilience" : The Guardian hardens its outer stone layers.
	* Damage Type : N/A (Defensive)
	* Effect : Significantly reduces incoming damage
	* Cooldown : Long (triggered at HP thresholds)
	* Mechanic : Forces players to adjust damage output timing

---

* Crushing Step (Passive) : Each movement shakes the ground slightly.
	* Effect : Minor AoE damage and micro-stagger on nearby players
	* Mechanic : Discourages staying too close for extended periods

---

		6. Status Effects / CC Applied

* Stun :
	* Duration: Short (center of Ruin Slam only)
* Stagger :
	* Brief interruption from Seismic Pulse and passive movement

---

		7. Mechanics Interaction

* Player Mechanics :
	* Difficult to interrupt due to high CC resistance
	* Encourages hit-and-move playstyle
	* Punishes melee players who overcommit
* Environment Interaction :
	* Anchored to ruin structures; does not leave area
	* Slam attacks interact with terrain (visual cracks, dust effects)
* Spawn Mechanics :
	* Always present but dormant until triggered
	* Blends visually with environment until activated

