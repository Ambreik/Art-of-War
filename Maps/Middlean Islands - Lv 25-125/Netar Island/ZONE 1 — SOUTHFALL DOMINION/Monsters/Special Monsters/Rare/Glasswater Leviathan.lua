---

		5. Skills & Abilities

* "Glasswater Veil" : The Leviathan distorts the surrounding water surface, creating reflective layers that obscure its exact position. This ability reduces player 
visibility and makes targeting more difficult. Within this state, parts of its body may appear duplicated or misaligned due to refraction effects.

* "Tidal Pressure Wave" : The Leviathan releases a massive wave of compressed water pressure in a directional arc. This deals heavy Physical/Elemental damage and 
pushes players back significantly. The wave travels through water and can affect multiple targets along its path.

* "Submerge Surge" : The Leviathan rapidly shifts its body through deep channels, generating localized currents that pull players slightly toward or away from its 
path. This ability disrupts positioning and can separate grouped players.

* "Reflective Fragmentation" (Passive) : Incoming attacks are partially distorted by the Leviathan’s reflective scales, reducing the effectiveness of precision-
based attacks and slightly dispersing incoming damage over its body.

* "Channel Collapse Pulse" : When heavily damaged, the Leviathan releases a radial pressure pulse that temporarily destabilizes the surrounding water, reducing 
visibility and creating hazardous currents for a short duration.

