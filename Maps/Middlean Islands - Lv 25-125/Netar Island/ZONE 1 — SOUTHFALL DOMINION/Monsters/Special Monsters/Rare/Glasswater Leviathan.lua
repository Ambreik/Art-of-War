			Glasswater Leviathan

---

		1. Basic Information

* Monster Name : Glasswater Leviathan
* Rank : Rare
* Monster Class : Legendary Monster
* Monster Type : Tanky, Spawner, Patrol (Limited), Environmental
* Monster Category / Race : Beast
* Element Type : Water
* Spawn Timer : 3–5 hours (real-time, conditional rare spawn)
* Location / Sub-Area : "Shimmering Delta" — deep central channels, submerged trench-like waterways, and rare “glasswater” zones where water becomes unnaturally 
still and reflective
* Group Pattern : Solo
* Aggro Type : Neutral → Aggressive when disturbed
* Special Notes : Environmental-tier entity; does not roam actively across the delta but manifests within deep channels tied to specific hydrodynamic conditions

---

		2. Appearance

	The Glasswater Leviathan is an immense aquatic entity whose true shape is difficult to fully perceive due to the nature of its environment and body. Its form 
appears partially obscured within the water itself, as though its physical presence is layered with reflective distortion that bends light around it. At times, it 
resembles a massive serpent or elongated fish-like construct, but these impressions shift depending on angle, distance, and water movement.
	Its body is covered in smooth, glass-like scales that reflect and refract light rather than absorbing it. These scales create a shimmering, mirror-like surface 
that causes its outline to blur into the surrounding water. When still, it can appear almost invisible, as the water around it behaves like a continuous reflective 
sheet, masking its true dimensions.
	Running along its body are faint, vein-like structures of pale blue and silver luminescence. These lines pulse slowly, creating subtle waves of light that 
travel across its length. The intensity of these pulses increases when the Leviathan becomes active, briefly revealing segments of its massive form beneath the 
reflective distortion.
	Its head is broad and streamlined, with minimal protrusions, designed for hydrodynamic efficiency. The eyes are large, deep-set, and emit a dim, glassy glow 
that seems to refract rather than project light outward. When viewed directly, the eyes often appear duplicated or displaced due to the reflective properties of its
body.
	The Leviathan’s movement is slow and deliberate, but its sheer scale creates powerful shifts in the surrounding water. Even minor adjustments of its body 
generate sweeping currents and subtle pressure changes that ripple outward across the delta channels. When it rises or turns, its full length may not be visible at 
once, instead revealing itself in segments as reflections, refractions, and distortions momentarily align.
	In its resting state, the Leviathan often blends into the “glasswater” zones—areas where the surface is unnaturally still and reflective—making it nearly 
indistinguishable from the environment until it begins to move or react.

