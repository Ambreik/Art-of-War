		5. Skills & Abilities

* "Resonance Pulse" : Emits a wave of energy that expands outward.
	* Damage Type : Magical (minor)
	* Target : AoE radius
	* Effect : Reveals hidden, stealthed, or burrowed units; minor damage
	* Cooldown : Short (periodic)
	* Mechanic : Counters stealth and ambush mechanics

---

* "Echo Amplification" : Enhances nearby allied creatures.
	* Damage Type : N/A (Buff)
	* Target : Allies within radius
	* Effect : Increases damage, movement speed, and attack frequency
	* Cooldown : Passive / periodic refresh
	* Mechanic : Core function; drastically increases threat of nearby enemies

---

* "Harmonic Overload" : Builds energy and releases a stronger pulse.
	* Damage Type : Magical (AoE)
	* Target : Medium radius
	* Effect : Moderate damage + brief "Daze"
	* Cooldown : Medium
	* Mechanic : Punishes players staying too long within range

---

* "Resonant Link" (Passive) : The Core is linked to nearby Echo Burrowers.
	* Effect : Burrowers gain bonus damage and reduced emergence delay
	* Mechanic : Synergy mechanic; increases ambush frequency

---

