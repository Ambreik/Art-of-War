			Echo Nexus Core

---

		1. Basic Information

* Monster Name : Echo Nexus Core
* Rank : III
* Monster Class : Rare
* Monster Type : Spawner, Invoker, Patrol
* Monster Category / Race : Elemental
* Element Type : Wind
* Spawn Timer : 15s
* Location / Sub-Area : Rootfall Hollow – Resonance Caverns / Subroot Chambers
* Group Pattern : Part of a group
* Aggro Type : Neutral
* Special Notes : Stationary resonance entity; amplifies nearby Echo Burrowers; emits detection pulses; acts as a support node rather than direct threat

