* Special Notes : Uses sound propagation through water and enclosed spaces to control engagements; thrives in acoustically favorable environments

---

		2. Appearance

	The Brine Siren presents as an ethereal humanoid figure partially merged with the aquatic environment, her form appearing fluid and slightly distorted as though
seen through rippling water even when at rest. Her body is slender and elongated, with proportions that feel both elegant and unnatural, as if adapted specifically 
for resonance and projection rather than physical strength.
	Her skin carries a translucent, wet sheen, tinted in gradients of pale blue, seafoam green, and muted silver. Beneath the surface, faint currents of 
bioluminescent patterns flow along her limbs and torso, pulsing gently in sync with subtle vocal vibrations. These patterns often intensify when she begins to emit 
sound, visually mirroring the frequency and intensity of her abilities.
	Her hair flows continuously as if suspended underwater, regardless of her actual position relative to water currents. It extends in long, ribbon-like strands 
that drift and coil around her, occasionally moving in ways that appear synchronized with her voice. Within these strands, faint glowing threads can be seen, 
resembling fine channels of energy or resonant filaments.
	Her facial features are delicate but obscured by shifting layers of mist-like distortion, especially around the mouth and throat area. When she vocalizes, the 
air and water around her visibly react, creating ripples and pressure distortions that make her exact position difficult to pinpoint at times.
	Subtle fin-like structures extend from her forearms, back, and along the sides of her body, not large enough for propulsion but clearly contributing to 
stability and resonance control within aquatic environments. These structures subtly vibrate when she prepares to use her abilities, amplifying her sonic output.
	When stationary, the Brine Siren appears calm and almost motionless, but the environment around her betrays her presence—small oscillations in water surfaces, 	
drifting particles aligning in faint patterns, and echoes that seem to originate from multiple directions simultaneously. In combat, her movements remain minimal; 
instead, her presence is defined by how the space around her responds to her voice.

