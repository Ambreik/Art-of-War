		5. Skills & Abilities

* "Siren’s Lure" : The Brine Siren emits a sustained melodic resonance that travels through water and enclosed spaces. Players within range may experience a Charm-
like effect, causing temporary loss of control or forced movement toward the Siren. The effect is reduced if players break line of resonance 
(obstructions, distance, or grounding effects).

* "Resonant Pulse" : A radial sonic burst that deals moderate Elemental damage and applies a brief disorientation effect, slightly delaying player actions and 
interrupting channeling abilities.

* "Echo Binding" : Targets a player and creates a delayed echo that “binds” their position. After a short duration, the echo collapses, briefly rooting the target 
or restricting movement if they remain within the affected zone.

* "Tidal Disruption" : Manipulates surrounding water currents to push or reposition players. This ability can alter spacing, break formations, or separate grouped 
targets.

* "Harmonic Amplification" (Passive) : The Siren’s abilities become more potent in enclosed or echo-rich environments. Chambers with strong resonance amplify the 
duration or effectiveness of control effects.

