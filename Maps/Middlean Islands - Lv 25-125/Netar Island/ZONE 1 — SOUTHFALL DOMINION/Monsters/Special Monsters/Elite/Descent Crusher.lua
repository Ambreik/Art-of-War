			Descent Crusher

---

		1. Basic Information

* Monster Name : Descent Crusher
* Rank : IV
* Monster Class : Elite
* Monster Type : Tanky, Melee, Patrol
* Monster Category / Race : Beast
* Element Type : Earth
* Spawn Timer : 3 hours (Elite real-time timer)
* Location / Sub-Area : Quarry Descent Passage – Narrow Descending Tunnels / Chokepoint Corridors
* Group Pattern : Solo
* Aggro Type : Aggressive
* Special Notes : Controls narrow passageways; high-impact melee attacker; specializes in area denial and choke control; applies Knockdown

---

		2. Appearance

	The Descent Crusher is an enormous, hulking beast whose body is built like a living mass of stone and muscle. Its form is broad and heavily reinforced, with a 
thick, rock-like hide layered over dense, sinewy musculature that visibly shifts beneath its surface as it moves.
	Its limbs are disproportionately large, especially its forelimbs, which resemble massive stone-encrusted hammers rather than natural arms. Each step it takes 
produces a heavy, echoing impact, scattering dust and small fragments of rock across the tunnel floor. Its head is low and heavily armored, with a blunt, almost 
helmet-like structure that appears fused with its skull.
	Cracks and fissures run along its body, faintly glowing with dull earthy tones when it prepares to strike, as if pressure is building within its form. In 
confined spaces, its sheer size becomes even more imposing, often forcing players to confront it within tight corridors where its bulk effectively blocks movement 
and escape routes.

