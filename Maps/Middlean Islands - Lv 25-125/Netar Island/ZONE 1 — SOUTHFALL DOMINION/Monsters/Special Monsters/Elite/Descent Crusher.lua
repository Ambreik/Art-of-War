	* Damage Type : Physical (AoE)
	* Target : Circular area in front
	* Effect : High damage + "Knockdown"
	* Cooldown : Medium
	* Mechanic : Primary area control ability; punishes grouped or stationary targets

---

* "Crushing Advance" : The creature charges forward through narrow passages.
	* Damage Type : Physical (Line AoE)
	* Target : Linear path
	* Effect : Moderate damage + Knockback / Knockdown
	* Cooldown : Medium
	* Mechanic : Used to reposition and disrupt formations in tunnels

---

* "Seismic Stomp" : A heavy stomp that sends a shock through the ground.
	* Damage Type : Physical (AoE)
	* Target : Nearby radius
