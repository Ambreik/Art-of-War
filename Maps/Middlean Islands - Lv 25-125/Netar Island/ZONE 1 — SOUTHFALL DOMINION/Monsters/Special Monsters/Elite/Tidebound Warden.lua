---

		2. Appearance

	The Tidebound Warden appears as a humanoid figure composed partially of water and partially of ancient, sea-weathered armor fused with its body. Its form is 
upright and disciplined, with a posture reminiscent of a trained sentinel standing guard over sacred or forbidden ground.
	Its armor looks heavily corroded yet resilient, covered in marine growth such as barnacles, coral fragments, and layered sediment that has hardened over time. 
Beneath and through the gaps in its armor, its body is formed of flowing water held together by a faint, luminous aquatic energy. This water-like body constantly 
shifts and circulates within its frame, giving the impression that it is both contained and alive at the same time.
	Its head is encased in a helm-like structure with a visor that reveals glowing, deep-blue eyes. These eyes remain fixed and alert, scanning its surroundings 
with unwavering focus. Around its limbs, small streams of water drift and coil, reacting subtly to its movements, as though the surrounding water itself is part of 
its being.
	When it moves, its steps are deliberate and controlled, creating small ripples and currents that ripple outward. Unlike chaotic aquatic creatures, the Tidebound
Warden carries itself with purpose and restraint, embodying the role of a long-standing sentinel bound to its post.

