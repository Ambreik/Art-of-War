		5. Skills & Abilities

* "Aqua Blade Strike" : The Warden forms a concentrated blade of water along its arm to strike enemies.

	* Damage Type : Physical + Water
	* Target : Single target melee
	* Effect : Moderate damage + minor knockback
	* Cooldown : Short
	* Mechanic : Primary melee attack used in close combat

---

* "Tidal Guard" : The Warden summons a rotating barrier of water around itself.
	* Damage Type : Defensive (Utility)
	* Effect : Reduces incoming damage and partially negates ranged attacks
	* Cooldown : Medium
	* Mechanic : Defensive ability used during sustained combat or when heavily pressured

---

* "Ruin Surge" : Manipulates surrounding water to erupt from the ground in controlled bursts.
	* Damage Type : Water (AoE)
	* Target : Area around Warden
	* Effect : Area damage + brief stagger
	* Cooldown : Medium
	* Mechanic : Used to control space and disrupt nearby enemies

---

* "Watershift Reposition" : The Warden briefly disperses into water and reforms at a nearby location.
	* Damage Type : None (Mobility)
	* Effect : Instant repositioning within a limited radius
	* Cooldown : Medium
	* Mechanic : Tactical movement tool to avoid being surrounded or reposition during combat

---

* "Guardian’s Directive" (Passive Aura): Strengthens the Warden while within its designated patrol zone.
	* Effect :
		* Slight increase in defense and resistance while in ruins
		* Enhanced awareness and reaction speed when defending territory
	* Mechanic : Reinforces its role as a territorial guardian

