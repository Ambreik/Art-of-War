* Spawn Timer : 2-7 hours (Elite real-time timer)
* Location / Sub-Area : The Whispering Shelf – Sheer Cliffs / Overhang Ledges / Vertical Rock Faces
* Group Pattern : Solo
* Aggro Type : Aggressive
* Special Notes : Ambush predator; uses vertical terrain for concealment; specializes in surprise attacks; applies Bleed

---

		2. Appearance

	The Cliffveil Stalker is a lean, sinewy predator perfectly adapted to vertical terrain, its entire body built for gripping and blending into sheer rock faces. 
Its fur is short and coarse, colored in layered shades of ash grey, pale stone, and muted beige, allowing it to vanish almost completely against the cliffside.
	Its limbs are long and powerful, ending in hooked claws that dig effortlessly into rock, letting it cling to vertical surfaces as naturally as walking on flat 
ground. Its body remains unnervingly still when hidden, often pressed flat against stone, making it nearly indistinguishable from its surroundings.
	Its eyes are narrow and predatory, glowing faintly with a cold, reflective sheen when light catches them at the right angle. When it prepares to strike, its 
muscles tense subtly, and small fragments of stone may loosen beneath its grip—one of the only warning signs before it launches itself downward in a sudden, 
explosive ambush.

