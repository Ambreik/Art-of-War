			Hollow Root Matriarch

---

		1. Basic Information

* Monster Name : Hollow Root Matriarch
* Rank : IV
* Monster Class : Elite
* Monster Type : Tanky, Spawner, Melee
* Monster Category / Race : Beast
* Element Type : Earth
* Spawn Timer : 3 hours (Elite real-time timer)
* Location / Sub-Area : Rootfall Hollow – Central Root Nexus / Deep Hollow Core
* Group Pattern : Leader of a group
* Aggro Type : Aggressive
* Special Notes : Central ecosystem controller; commands Root Creepers; applies Poison and Root effects; area control specialist

---

		2. Appearance

* Size : Giant
* Coloration / Skin / Scales / Fur : Thick bark-like hide fused with tangled roots and dark, damp soil tones
* Eyes / Markings / Luminescence : Multiple dim green bioluminescent nodes pulsing along its body
* Special Features / Appendages : Massive root tendrils extending from its body, partially embedded into the ground; heavy front limbs for crushing
* Distinctive Traits / Visual Indicators for Mechanics :
	Roots beneath the ground begin to shift and rise before control abilities activate; glowing veins intensify when commanding minions

---

		3. Core Attributes

* HP Bar : Giant
* Defense / Armor : High
* Evasion / Dodge : Low
* Movement Speed / Mobility : Low
* Chase / Leash Radius : Medium (centered around root zone)
* Attack Speed : Slow
* Damage Type : Physical + Nature (Poison-based)
* Damage Pattern : Crushing Blow, DoT, Control
* Core Status Mechanics :
	* Passive control over nearby Root Creepers
	* Applies Poison and Root effects
	* Gains minor regeneration when near active roots
* CC Resistances : High resistance to Root and Knockback

---

		4. Combat Behavior / AI

| State                 | Description                                                         |
| --------------------- | ------------------------------------------------------------------- |
| Idle / Patrol         | Stationary or slow shifting within root cluster                     |
| Detection             | Aggro triggered when players enter central root area                |
| Combat                | Controls battlefield using roots; summons/empowers nearby creatures |
| Enrage / Phase Change | At 45% HP, increases spawn frequency and root control range         |
| Death                 | Root network collapses; surrounding creepers weaken temporarily     |

---

		5. Skills & Abilities

* "Root Dominion" : The Matriarch extends control through underground roots.
	* Damage Type : N/A (Control)
	* Target : Area-based
	* Effect : Summons or empowers "Root Creepers" in the area
	* Cooldown : Medium–Long
	* Mechanic : Core identity; creates sustained pressure through adds

---

* "Entangling Grasp" : Roots erupt from the ground, binding targets in place.
	* Damage Type : Nature (DoT)
	* Target : AoE around players
	* Effect : Applies "Root" + minor Poison damage over time
	* Cooldown : Medium
	* Mechanic : Prevents escape; combos with other attacks

---

* "Toxic Secretion" : Releases a wave of toxic spores around its body.
	* Damage Type : Nature (AoE DoT)
	* Target : Radius around Matriarch
	* Effect : Applies "Poison" (stacking)
	* Cooldown : Medium
	* Mechanic : Punishes close-range players

---

* "Crushing Root Slam" : A heavy downward strike using reinforced root limbs.
	* Damage Type : Physical (Crushing)
	* Target : Frontal AoE
	* Effect : High damage + knockdown
	* Cooldown : Medium
	* Mechanic : Main direct damage tool

---

* "Rootbound Regeneration" (Passive) : Draws energy from surrounding root network.
	* Effect : Gradual HP regeneration while within core area
	* Mechanic : Encourages faster engagement or add control

---

		6. Status Effects / CC Applied

* Poison :
	* Duration: 6–10 seconds
	* Tick Frequency: Every 1 second
	* Effect: Nature damage over time; stacks
* Root :
	* Duration: Short–Medium
	* Effect: Immobilizes target
* Knockdown :
	* Brief displacement from slam

---

		7. Mechanics Interaction

* Player Mechanics :
	* Strongly punishes stationary players
	* Forces AoE and add management
	* Difficult for solo players without mobility

* Environment Interaction :
	* Entire fight area is influenced by root network
	* Terrain may visually shift during abilities

* Spawn Mechanics :
	* Root Creepers spawn or become active during combat
	* Centralized boss tied to root zone

