			Pack Alpha Jackal

---

		Appearance

	The Pack Alpha Jackal stands noticeably larger than the rest of its kind, its frame lean but powerfully built for speed and dominance. Its fur is rough and 
wind-swept, carrying a darker, sand-streaked tone that blends naturally with the coastal terrain, while faint scars mark its body — signs of countless territorial 
fights. Its eyes burn with a sharp, predatory intensity, often glowing faintly in low light, making it immediately distinguishable from the rest of the pack.

	Its posture is confident and upright, rarely lowering its head unless preparing to strike, and its movements carry a sense of control rather than haste. The 
Alpha’s jaws are broader and more defined, with visible worn fangs that hint at repeated combat. When leading the pack, it moves slightly ahead or to the side, 
constantly adjusting position as if directing the others. Subtle vocalizations—low growls, sharp barks—signal commands, and nearby jackals visibly react to its 
presence, tightening formation or becoming more aggressive.

	During combat, its presence feels dominant; the surrounding pack becomes more coordinated, circling and closing in as the Alpha dictates the pace of the 
encounter.

---

		Behavior & Combat Profile

* Always accompanied by Coastal Jackals, acting as the center of pack behavior
* Controls engagement flow, initiating combat or responding to threats
* Rarely retreats unless the entire pack is defeated
* Focuses targets under pressure, coordinating attacks through proximity buffs
* Becomes more aggressive when pack numbers are reduced

---

		Abilities

* "Alpha Command" – Emits a commanding howl that increases attack speed and movement speed of all nearby Coastal Jackals. Effect scales with number of active pack 
members.
* "Coordinated Strike" – Marks a target briefly; nearby jackals prioritize that target, increasing their damage output against it for a short duration.
* "Rending Bite" – A powerful melee attack that applies "Bleed", dealing damage over time. If used on a target already affected by Bleed, the effect duration is 
refreshed and slightly intensified.
* "Pack Instinct (Passive) – Gains increased damage reduction and movement speed while at least one allied jackal is alive nearby. Bonus weakens as pack members 
die.

---

		Spawn Conditions

* Time : Day & Night
* Location : Shoreline edges, dunes, and vegetation borders near coastal areas
* Group Size : 1 Alpha + 3–6 Coastal Jackals
* Spawn Behavior : Replaces standard jackal packs with a lower spawn chance

---

		Loot Identity

* Medium armor pieces (agility/endurance mix)
* Beast-based crafting materials
* Chance to drop: "Alpha Fang" (used in crafting or upgrades)
* Small chance for pack-themed gear enhancing group combat bonuses

