---

		2. Appearance

	The Arch Leviathan is an immense, ancient sea creature whose sheer scale dwarfs the submerged ruins it inhabits. Its body stretches across vast distances 
beneath the water, with a long, serpentine form reinforced by thick, armored plates that resemble weathered stone fused with organic tissue. These plates are 
layered like natural armor, covered in algae, barnacle growth, and deep fissures that hint at centuries of existence.
	Its head is massive and elongated, crowned with jagged ridges and horn-like protrusions that curve backward along its skull. Its eyes glow with a deep, abyssal 
luminescence, faintly visible even in the darkest depths. Along its sides, fin-like appendages ripple slowly, generating powerful currents as it moves.
	The Leviathan’s body is partially enshrouded in drifting particulate matter and faint bioluminescent traces that pulse intermittently along its length. When it 
shifts, the surrounding water reacts violently, forming large-scale pressure waves that distort visibility and push debris outward. Its presence alone alters the 
flow of the surrounding environment, making the water feel heavier, denser, and charged with latent energy.

