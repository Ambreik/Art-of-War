	* Damage Type : Physical
	* Target : Single large target / frontal cone
	* Effect : Extremely high damage + possible instant disruption for unprepared targets
	* Cooldown : Medium
	* Mechanic : Punishes players who remain near the head or core body

---

* "Submerge & Surge" : The Leviathan dives deep and re-emerges at a different location.
