---

		5. Skills & Abilities

* "Commanding Shout" : Emits a loud directional shout that buffs nearby humanoid allies, increasing their attack speed and movement speed for a short duration. Also
forces idle nearby workers into combat.

* "Reinforcement Signal" : Uses a flare or whistle device to call in 2–3 additional quarry workers after a short delay. These reinforcements enter combat from 
nearby paths or elevated positions.

* "Weighted Tool Throw" : Throws a heavy mining tool at a target location, dealing moderate Physical damage and briefly slowing the target. Can be used to interrupt
player repositioning.

* "Foreman’s Strike" : A controlled melee attack using a reinforced hammer. Deals solid single-target damage and applies a minor stagger if it lands cleanly.

* "Control Presence" (Passive) :   Nearby humanoid enemies gain increased coordination—reduced reaction delay and tighter group movement—while the "Overseer" is 
alive.

---

		6. Status Effects / CC Applied

