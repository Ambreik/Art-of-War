		2. Appearance

	The Ascendant Raptor Alpha is a tall, lean avian predator with a posture adapted for vertical terrain. Its body is covered in sleek, layered feathers that 
appear weathered yet sharply defined, ranging from dark slate tones to faint metallic highlights that catch light as it moves along elevated surfaces.
	Its wings are long and narrow, extending beyond its body with feather edges that appear slightly frayed, giving the impression of both age and continuous 
adaptation to harsh aerial movement. When folded, the wings align tightly against its body, allowing it to perch effortlessly on narrow ledges, broken stair edges, 
or crumbling stone surfaces.
	Its legs are powerful and elongated, ending in curved talons that grip stone with precision. These talons are visibly reinforced, suggesting repeated use in 
high-impact landings and vertical launches. Its stance is often slightly crouched, ready to spring at a moment’s notice.
	The head of the Alpha is sharp and angular, with piercing eyes that track movement across multiple elevation levels. Its beak is short but reinforced, designed 
for precision strikes rather than tearing. Subtle markings or faint natural patterns run along its face and neck, giving it a distinct “alpha” presence compared to 
lesser raptors in the region.
	When preparing to attack, its wings partially extend, and its body leans forward, signaling an imminent high-speed dive or leap from elevated terrain.

