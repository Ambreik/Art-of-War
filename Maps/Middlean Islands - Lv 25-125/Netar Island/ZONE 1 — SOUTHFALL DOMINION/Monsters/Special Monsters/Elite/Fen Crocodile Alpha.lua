			Fen Crocodile Alpha

---

		1. Basic Information

* Monster Name : "Fen Crocodile Alpha"
* Rank : Elite
* Monster Class : Superior
* Monster Type : Melee, Patrol, Leader, Burst
* Monster Category / Race : Beast
* Element Type : Water / Earth
* Spawn Timer : 1h 45m (real-time)
* Location / Sub-Area : "Shimmering Delta" — shallow marsh channels, muddy water corridors, reed-lined banks, submerged crossings, and transition zones between open
water and swamp terrain
* Group Pattern : Leader of a group (Alpha + 3–6 Bog Snappers)
* Aggro Type : Aggressive
* Special Notes : Apex predator controlling local crocodilian packs; dominates shallow water ambush zones and patrol routes

---

		2. Appearance

	The Fen Crocodile Alpha is a massive, heavily built predator whose presence is immediately distinguished from the surrounding swamp fauna by both its size and 
its imposing physical structure. Its elongated body is covered in thick, rugged scales that appear layered like overlapping armor plates, colored in deep swamp 
greens, dark browns, and muted black tones that allow it to blend seamlessly with murky waters and dense vegetation.
	Its dorsal ridges are pronounced and uneven, running along its spine in jagged lines that break the surface of the water when it moves. These ridges are 
slightly lighter in color, often catching faint ambient light and creating subtle shimmering reflections that ripple across the water’s surface as it shifts 
position.
	The Alpha’s head is broad and reinforced, with a heavy jawline filled with large, interlocking teeth designed for crushing and gripping rather than quick 
snapping alone. Its eyes are positioned high on its skull, glowing faintly with a dull amber hue that becomes more visible when it surfaces or locks onto prey. 
These eyes remain just above the waterline during stealth approaches, making it difficult to detect until it is already within striking distance.
	Its limbs are short but powerful, ending in clawed feet adapted for both aquatic propulsion and muddy terrain traversal. When submerged, its tail becomes the 
primary driver of movement, sweeping with controlled force to generate sudden bursts of speed beneath the surface. The tail itself is thick and muscular, tapering 
into a flattened structure capable of delivering powerful directional thrusts.
	The Alpha’s overall posture conveys dominance and control rather than constant aggression. It often remains partially submerged, with only its eyes and dorsal 
ridges visible, observing its surroundings in stillness. When it commits to movement, it does so with sudden, explosive bursts that break the surface of the water 
with minimal warning, creating splashes and ripples that quickly fade back into the delta’s calm, concealing its next repositioning.

