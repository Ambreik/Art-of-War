* CC Resistances : Moderate resistance to Slow while in water

---

	4. Combat Behavior / AI

| State                      Description
| Idle / Patrol : Patrols submerged delta channels, often remaining hidden with only partial exposure above water. Coordinates loosely with nearby Bog Snappers. 
| Detection : Detects players through water disturbance; surfaces briefly before initiating ambush or signaling pack engagement.
| Combat : Uses hit-and-run tactics, combining rapid bursts of movement with high-damage melee attacks; prioritizes isolated targets.
| Enrage / Phase Change : At ~50% HP, increases aggression and reduces delay between burst movements and attacks; pack becomes more coordinated.
| Death : Collapses into the water, causing a final disturbance wave; nearby Bog Snappers may briefly scatter or become disorganized.

---

		5. Skills & Abilities

* "Delta Ambush Burst" : The Alpha rapidly accelerates from a submerged position, launching itself forward in a high-speed burst. This attack deals heavy Physical 
damage on impact and applies "Heavy Bleed". It is most effective when used from below or behind the target, leveraging concealment in murky water.

* "Crushing Maul Bite" : A close-range bite attack where the Alpha clamps down on a target with immense force. This ability deals sustained damage over a short 
duration and applies a stronger Bleed effect if the target is already affected.

* "Tail Water Sweep" : The Alpha swings its tail in a wide arc, generating a localized water surge that pushes players away and disrupts positioning. This ability 
can knock back targets and create spacing for repositioning.

* "Reedline Pressure" (Passive) : While near reeds or shallow vegetation zones, the Alpha gains slight bonuses to movement speed and stealth effectiveness, making 
ambushes more reliable.

* "Pack Coordination" (Passive) : Nearby Bog Snapper creatures gain increased aggression and attack speed while the Alpha is alive, improving overall group 
efficiency.

---

		6. Status Effects / CC Applied

* Heavy Bleed : High-duration damage over time from bites and ambush attacks
* Knockback : From Tail Water Sweep
* Minor Displacement : From burst collisions in water

---

		7. Mechanics Interaction 

