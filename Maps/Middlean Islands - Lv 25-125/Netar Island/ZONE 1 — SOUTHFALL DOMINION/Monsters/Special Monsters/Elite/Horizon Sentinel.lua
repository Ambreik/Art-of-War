			Horizon Sentinel

---

		1. Basic Information

* Monster Name : Horizon Sentinel
* Rank : III
* Monster Class : Elite
* Monster Type : Ranger, Patrol, Coward
* Monster Category / Race : Humanoid
* Element Type : Wind
* Spawn Timer : 2 hours (Elite real-time timer)
* Location / Sub-Area : Old Watcher’s Rise – Elevated Cliffs / Watchpoints / Ruin Overlooks
* Group Pattern : Part of a group / Leader of a group
* Aggro Type : Aggressive
* Special Notes : Elite ranged unit; marks targets for increased damage; high-ground specialist; supports nearby enemies

---

		2. Appearance

* Size : Medium
* Coloration / Skin / Scales / Fur : Worn layered armor in muted greys and dark blues, designed to blend with sky and stone
* Eyes / Markings / Luminescence : Helmet visor emits a faint cold glow; subtle wind-like markings etched into armor
* Special Features / Appendages : Long reinforced bow, flowing tattered cloak, lightweight armor plates
* Distinctive Traits / Visual Indicators for Mechanics :
	Target-marking ability creates a glowing sigil above the player; arrows leave faint wind trails when fired

---

		3. Core Attributes

* HP Bar : Medium–High
* Defense / Armor : Medium
* Evasion / Dodge : Medium–High
* Movement Speed / Mobility : High (especially when repositioning)
* Chase / Leash Radius : Large (maintains distance while tracking targets)
* Attack Speed : Medium–Fast
* Damage Type : Physical (Precision-based)
* Damage Pattern : Direct, Critical, DoT (situational via pressure zones)
* Core Status Mechanics :
	* Applies "Mark" increasing incoming damage
	* Maintains distance; prioritizes positioning over direct combat
* CC Resistances : Moderate resistance to Slow effects

---

		4. Combat Behavior / AI

| State                 | Description                                                            |
| --------------------- | ---------------------------------------------------------------------- |
| Idle / Patrol         | Stands at high vantage points, scanning the horizon                    |
| Detection             | Spots targets from long range; prioritizes elevated line of sight      |
| Combat                | Marks target, maintains distance, uses precision shots and area denial |
| Enrage / Phase Change | At 35% HP, increases firing speed and uses abilities more aggressively |
| Death                 | Collapses silently; bow drops beside it; mark effect fades immediately |

---

		5. Skills & Abilities

* "Mark of the Horizon" : The Sentinel designates a target for elimination.
	* Damage Type : N/A (Debuff)
	* Target : Single target
	* Effect : Target takes increased damage from all sources; generates higher threat	
	* Duration : Medium
	* Cooldown : Medium
	* Mechanic : Core support ability; makes target priority for all nearby enemies

---

* "Piercing Shot" : A precisely aimed, high-velocity arrow.
	* Damage Type : Physical (Critical)
	* Target : Single target (line projectile)
	* Effect : High damage; partially ignores armor
	* Cooldown : Short–Medium
	* Mechanic : Main damage skill; extremely dangerous when combined with Mark
	
---

* "Suppressive Volley" : Rapid arrows fired into a designated area.
	* Damage Type : Physical (AoE)
	* Target : Ground-targeted zone
	* Effect : Sustained damage over time within area
	* Cooldown : Medium
	* Mechanic : Area denial; forces players to reposition

---

* "Tactical Reposition" (Passive) : The Sentinel instinctively maintains distance.
	* Effect : Moves away when enemies get too close
	* Mechanic : Makes melee engagement difficult; favors ranged combat

---

		6. Status Effects / CC Applied

* Marked :
	* Duration: ~10 seconds
	* Effect: Increased damage taken from all sources; increased aggro
* *(Indirect)* Area pressure from Suppressive Volley

---

		7. Mechanics Interaction

* Player Mechanics :
	* Strongly punishes isolated or marked players
	* Forces target prioritization in group fights
	* Difficult for melee players without gap closers
* Environment Interaction :
	* Uses elevation advantage for range and visibility
	* Can attack from unreachable cliff edges if not repositioned
* Spawn Mechanics :
	* Often positioned with other enemies
	* Acts as a support/leader unit in encounters

---

		8. Quotes / Lore Lines

* "You’ve already been seen."
* "Distance will not save you."
* "Marked… and condemned."
* "The horizon watches all."

---

		9. Respawn & Encounter Rules

* Respawn Timer / Conditions : 2 hours after death
* Single / Group Combat Lock : No lock
* Escape / Reset Conditions :
	* Resets if players break line of sight and leave elevation range
* Interaction with other monsters or players :
	* Enhances nearby enemies via Mark
	* Often initiates combat for groups

---

		10. Special Rules

* Prioritizes lowest defense or already damaged targets
* Will reposition to maintain high ground whenever possible
* Mark effect can stack pressure in multi-enemy encounters

