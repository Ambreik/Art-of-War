			Saltmaw Devourer

---

		1. Basic Information

* Monster Name : Saltmaw Devourer
* Rank : Elite
* Monster Class : Predator / Ambusher / Bruiser
* Monster Type : Melee, Burst, Shoreline Hunter
* Monster Category / Race : Beast
* Element Type : Water / Earth (Salt-infused)
* Spawn Timer : 2 hours (real-time)
* Location / Sub-Area : "Broken Coastline" — rocky tide pools, jagged shoreline cliffs, submerged rock corridors, and zones where waves crash against uneven stone 
formations
* Group Pattern : Solo
* Aggro Type : Aggressive (territorial apex predator)
* Special Notes : Dominates shoreline hunting lanes, transitioning seamlessly between shallow water and land during combat

---

		2. Appearance	

	The Saltmaw Devourer is a large, heavily built coastal predator whose body reflects prolonged adaptation to harsh tidal environments. Its form resembles a 
hybrid between a massive aquatic reptile and a land-capable hunter, with a long, muscular body designed to move efficiently both through shallow surf and over 
jagged rock surfaces.

	Its skin is rough and uneven, covered in thick, salt-encrusted scales that appear cracked and layered, as though repeatedly weathered by constant exposure to 
seawater and abrasive coastal winds. These scales range in color from pale gray and dark slate to bleached white tones, with patches where accumulated salt crystals
form visible crusts along the ridges of its body. In certain areas, the salt deposits catch light, giving its surface a faint,shimmering sheen similar to wet stone.

	The creature’s head is broad and elongated, with a powerful jaw structure filled with jagged, uneven teeth that appear partially eroded and regrown over time. 
These teeth are stained with mineral deposits and marine residue, reinforcing the impression that the Devourer feeds heavily within abrasive coastal environments. 
Its maw opens wider than expected, allowing it to engulf large portions of prey in a single strike.

	Its eyes are set deep within its skull, glowing faintly with a dull, sea-green or grayish hue that reflects ambient light rather than emitting it strongly. 
These eyes remain partially protected by bony ridges above and below, shielding them from debris, crashing waves, and collisions with rock formations.

	Along its back runs a series of hardened ridges that protrude like jagged fins or broken spines. These ridges are uneven and irregular, some appearing chipped 
or fractured, yet reinforced by layers of mineral buildup. When the Devourer moves through shallow water, these ridges often break the surface first, cutting 
through waves and leaving a brief wake behind.

	Its limbs are short but extremely powerful, ending in clawed appendages capable of gripping wet stone surfaces with surprising stability. On land, it moves with
a low, grounded posture, using a combination of limb force and body momentum to drag itself forward in short, explosive bursts. In water, however, its tail becomes 
the primary driver of movement, allowing it to surge forward quickly through tidal currents.

	When at rest, the Saltmaw Devourer often lies partially submerged among rocks or tide pools, blending into the environment due to its muted coloration and salt-
stained textures. Its breathing is slow and heavy, sometimes producing faint disturbances in nearby water as air escapes through its nostrils or gills. Even in 
stillness, its presence feels dense and imposing, as though it is always prepared to lunge the moment movement is detected nearby.

