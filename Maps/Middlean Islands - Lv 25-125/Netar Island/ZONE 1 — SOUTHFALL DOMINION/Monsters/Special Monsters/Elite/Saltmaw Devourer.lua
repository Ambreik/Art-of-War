		5. Skills & Abilities

* "Maul of the Tides" : The Saltmaw Devourer lunges forward with its jaws wide open, attempting to bite and clamp down on a target. On hit, this ability deals heavy
Physical damage and applies "Bleed", representing tearing wounds caused by serrated teeth.

* "Armor Shatter Crush" : A powerful bite or slam that targets heavily armored opponents. This attack applies "Penetration", temporarily reducing the target’s defensive capabilities and making them more vulnerable to subsequent attacks.

* "Tide Surge Burst" : The Devourer rapidly propels itself forward using a combination of tail thrust and tidal momentum, covering short distances instantly. This 
burst can be used to close gaps or reposition around terrain obstacles.

* "Rockline Clamp" (Environmental Interaction) : When near rocky surfaces, the Devourer can anchor itself briefly, increasing stability and reducing knockback 
effects while preparing for a counterattack.

* "Salt " (Passive) : Attacks gradually weaken targets through repeated exposure, reinforcing the Armor Break effect and synergizing with sustained Bleed damage.

