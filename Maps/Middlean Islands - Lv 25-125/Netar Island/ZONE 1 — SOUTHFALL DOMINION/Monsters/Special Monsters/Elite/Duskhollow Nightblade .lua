			Duskhollow Nightblade

	
		Appearance

* Lean, agile humanoid figure clad in dark, layered leather armor designed for silent movement
* Armor is stitched with faint, worn cloth strips that subtly react to wind, helping break silhouette in low light
* Face is partially concealed by a hood and bone-thread mask, leaving only faint glowing eyes visible in darkness
* Dual daggers are curved and asymmetrical, with darkened metal that absorbs light rather than reflecting it
* Subtle shadow distortion trails follow its movement, especially when entering or exiting stealth
* During night, its outline becomes harder to distinguish, blending naturally with dim environments and narrow alleys
* When preparing an ambush, a faint flicker of movement (like heat distortion) can be noticed just before it strikes
---

		Behavior & Combat Profile

* Enters stealth when not in combat, preferring to engage from behind or from elevated positions
* Prioritizes isolated targets; avoids large groups unless paired
* Opens combat with a high-damage ambush strike from stealth
* Repositions frequently during combat using short burst movement
* Disengages briefly if target creates distance, attempting a second ambush

---

		Abilities

* "Shadow Lunge" – Rapid gap-closer from stealth, dealing high initial damage
* "Twin Fang Strike" – Dual melee attack that applies **Major Bleed**
* "Fade Step" – Short reposition ability, briefly reduces threat and breaks targeting
* "Night Veil" – Gains increased movement speed and stealth efficiency during nighttime (passive)

---

		Spawn Conditions

* Time : Night only
* Location : Southfall Village outskirts, narrow alleys, rooftops, and low-visibility paths
* Group Size : 1–2
* Spawn Behavior : Low frequency, replaces standard Duskhollow Scravel presence in certain zones during night cycles

---

		Loot Identity

* Light armor pieces (agility-focused)
* Assassin-themed weapons (daggers, short blades)
* Rare chance for stealth-enhancing gear
* Low chance for crafting component: *Nightshade Binding*

