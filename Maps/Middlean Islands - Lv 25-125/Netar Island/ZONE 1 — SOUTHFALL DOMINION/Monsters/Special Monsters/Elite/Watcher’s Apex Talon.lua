			Watcher’s Apex Talon

---

		1. Basic Information

* Monster Name : Watcher’s Apex Talon
* Rank : II
* Monster Class : Elite
* Monster Type : Ranger, Deathblow, Patrol
* Monster Category / Race : Beast
* Element Type : Wind
* Spawn Timer : 3 hours (Elite real-time timer)
* Location / Sub-Area : Old Watcher’s Rise – Upper Cliffs / High Altitude Airspace
* Group Pattern : Solo
* Aggro Type : Aggressive
* Special Notes : Elite aerial predator; controls upper cliff zones; applies Heavy Bleed; high mobility combat

---

		2. Appearance

* Size : Large
* Coloration / Skin / Scales / Fur : Dark slate feathers with metallic undertones that shimmer under sunlight
* Eyes / Markings / Luminescence : Piercing amber eyes that glow faintly when targeting prey
* Special Features / Appendages : Massive bladed talons, razor-edged wings, elongated hooked beak
* **Distinctive Traits / Visual Indicators for Mechanics :
	When preparing "Skyfall Dive", wings fold tightly and the creature emits a sharp wind-piercing screech before descending

---

		3. Core Attributes

* HP Bar : Giant
* Defense / Armor : Medium
* Evasion / Dodge : High
* Movement Speed / Mobility : Very High (Aerial mobility)
* Chase / Leash Radius : Very Large (covers entire upper cliff region)
* Attack Speed : Fast
* Damage Type : Physical (Wind-enhanced strikes)
* Damage Pattern : Burst, DoT, Critical
* Core Status Mechanics :
	* Applies stacking "Bleed" (Heavy Bleed variant)
	* Bonus damage on low HP targets (execution behavior)
* CC Resistances : High resistance to Root and Slow effects while airborne

---

		4. Combat Behavior / AI

| State                 | Description                                                                   |
| --------------------- | ----------------------------------------------------------------------------- |
| Idle / Patrol         | Circles high above cliffs in wide aerial patterns; rarely lands               |
| Detection             | Detects targets from long range via line of sight from above                  |
| Combat                | Engages with dive attacks, then repositions into air; avoids prolonged melee  |
| Enrage / Phase Change | At 40% HP, increases dive frequency and reduces recovery time between attacks |
| Death                 | Crashes violently to the ground, dealing minor AoE impact damage              |

---

	5. Skills & Abilities

* "Skyfall Dive" : The Apex Talon ascends briefly, locks onto a target, then dives at extreme velocity.
	* Damage Type : Physical (Burst)
	* Target : Single target + small AoE on impact
	* Effect : Massive damage; deals bonus damage if target is below 50% HP
	* Cooldown : Medium
	* Mechanic : Primary execution ability; highly telegraphed but lethal if not avoided

---

* "Rending Talons" : A brutal claw strike following a dive or close engagement.
	* Damage Type : Physical + DoT
	* Target : Single target
	* Effect : Applies "Heavy Bleed" (stacking DoT)
	* Cooldown : Short
	* Mechanic : Encourages hit-and-run cycles; bleed stacks punish extended fights

---

* "Wind Shear Pass" :
  A low-altitude flyby generating cutting wind currents.
	* Damage Type : Physical (AoE)
	* Target : Frontal cone
	* Effect : Moderate damage + Knockback
	* Cooldown : Medium
	* Mechanic : Disrupts positioning; often used after missed dives

---

* "Predator’s Focus" (Passive) : The Apex Talon instinctively targets weakened prey.
	* Effect : Deals increased damage to targets below 50% HP
	* Mechanic : Forces defensive play once HP drops

---

		6. Status Effects / CC Applied

* Heavy Bleed :
	* Duration: 8 seconds
	* Tick Frequency: Every 1 second
	* Effect: Physical DoT; damage increases with each stack

* Knockback : Applied by Wind Shear Pass

---

		7. Mechanics Interaction

* Player Mechanics :
	* Can target mounted players easily due to aerial advantage
	* Difficult to engage for melee players without timing dives
	* Punishes low HP players aggressively

* Environment Interaction :
	* Uses cliffs and verticality for dive attacks
	* Can force players off positioning near edges via knockback

* Spawn Mechanics :
	* Only one active per region
	* Spawns in high-altitude patrol routes

---

		8. Quotes / Lore Lines

* "The sky belongs to me."
* "You were seen long before you arrived."
* "Fall… like all things beneath me."

---

		9. Respawn & Encounter Rules

* Respawn Timer / Conditions : 3 hours after death
* Single / Group Combat Lock : No hard lock; can disengage vertically
* Escape / Reset Conditions :
	* Resets if target leaves cliff zone or remains unreachable too long
* Interaction with other monsters or players :
	* Other aerial creatures do not spawn while Apex Talon is active

---

		10. Special Rules

* Cannot be grounded by standard CC
* Gains increased aggression toward lowest HP target in range
* Dive attacks ignore minor terrain obstacles

