---

		2. Appearance

	The Viper Knot Matron is a massive serpentine creature whose body is formed from a tightly coiled mass of intertwined vines, roots, and serpent-like organic 
segments. Its form resembles a living knot of writhing coils, with multiple overlapping layers that continuously shift and tighten, as if the creature is 
perpetually binding itself together.
	Its head is more defined than the rest of its body, featuring a viper-like skull with elongated fangs that protrude slightly even when its mouth is closed. Its 
eyes glow with a sharp, predatory intensity, scanning its surroundings with calculated awareness. Surrounding its head are smaller tendrils and vine-like appendages
that flick and coil independently, reacting to movement and environmental stimuli.
	Along its elongated body, several segments resemble individual serpent heads or elongated coils that move semi-independently, creating the illusion of multiple 
creatures intertwined into a single organism. These segments occasionally uncoil and recoil, tightening the structure of its body in rhythmic patterns.
	The Matron’s presence is often accompanied by subtle hissing sounds and the faint rustling of movement within the surrounding roots, as smaller Rootcoil Vipers 
remain hidden or partially embedded in the environment, responding to its signals.

