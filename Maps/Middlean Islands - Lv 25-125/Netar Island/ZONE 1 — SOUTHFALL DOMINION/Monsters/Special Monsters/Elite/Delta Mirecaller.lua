		5. Skills & Abilities

* Mirecall Ritual : The Delta Mirecaller channels energy from the swamp to summon localized hazards such as bog patches, spore clouds, or water distortions. These hazards persist for a duration and create zones that slow movement and apply damage over time to players who remain within them.

* Reedbind Snare : Roots and reed-like tendrils erupt from the ground or water surface, attempting to bind nearby targets. Affected players are slowed significantly
and may be rooted briefly if they remain within the area of effect.

* Swamp Echo Pulse : The Mirecaller emits a pulse of resonant energy that reverberates through nearby water and mud. This ability deals moderate AoE damage and may amplify existing environmental hazards, increasing their intensity temporarily.

* Summon Bog Attendants : Calls forth minor swamp entities or constructs (e.g., mire spirits, swamp fragments, or small amphibious creatures) to assist in combat.
These summons are not individually strong but contribute to pressure through numbers and distraction.

* Ritual Amplification (Passive) : While alive, the Mirecaller increases the potency of swamp-based environmental effects in its vicinity, making terrain hazards 
more dangerous and persistent.

