---

		2. Appearance

	The Delta Mirecaller appears as a tall, slender humanoid figure whose body seems partially fused with the swamp environment rather than fully separate from it. 
Its posture is slightly hunched, as though constantly listening to something beneath the water’s surface. Its limbs are elongated and thin, with subtle 
irregularities that suggest prolonged exposure to natural and arcane forces rather than normal physical development.

	Its skin has a damp, earth-toned complexion, ranging between muted greens, browns, and grayish hues that resemble wet clay or decomposed plant matter. In 
certain areas, faint vein-like patterns of glowing greenish-blue light pulse beneath the surface, particularly along the arms, neck, and torso. These pulses are 
slow and rhythmic, resembling a breathing cycle tied to its magical activity.

	The Mirecaller’s head is partially obscured by a hood-like structure formed from layered reeds, moss, and draped organic fibers that hang downward in uneven 
strands. These materials appear to grow continuously, shifting slightly with ambient moisture and air movement. Beneath this covering, its face is only partially 
visible—its eyes emit a dim, bioluminescent glow, often flickering between dull green and pale cyan depending on its current magical state.

	Attached to its body are ritual bindings made from braided vines, bone fragments, and carved wooden charms. These objects are not merely decorative; they hang 
in deliberate arrangements across its chest, arms, and waist, subtly swaying even when the creature is stationary. Some of these charms emit faint resonance hums 
when spells are cast, suggesting they function as conduits or stabilizers for its abilities.

	When the Delta Mirecaller moves, it does so with a slow, deliberate gait, often leaving behind faint ripples in nearby water or slight disturbances in the 
surrounding vegetation. Its presence seems to influence the environment passively—small plants appear more vibrant nearby, while stagnant water may ripple without 
direct contact.

	During spellcasting, the Mirecaller raises its arms or leans slightly forward, and the air around it becomes noticeably denser with moisture. Glowing symbols or
arcane patterns may briefly form in the space around its hands or along the ground, though these are transient and fade quickly after the ability is released.

	Overall, the Delta Mirecaller gives the impression of being less of a standalone entity and more of a living focal point for the swamp itself, acting as both a 
ritual practitioner and a conduit through which the delta’s latent energy is expressed.

