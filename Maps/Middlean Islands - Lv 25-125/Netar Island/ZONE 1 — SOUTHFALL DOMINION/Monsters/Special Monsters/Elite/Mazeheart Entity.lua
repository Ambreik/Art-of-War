* Special Notes : Acts as the living core of the Root Maze; directly influences path formation and environmental layout within its domain

---

		2. Appearance

	The Mazeheart Entity appears as a massive, pulsating organism embedded deep within the center of the Root Maze. Its body resembles a colossal heart made of 
intertwined roots, bark-like tissue, and living organic matter that continuously expands and contracts in a slow, rhythmic cycle.
	From its core, thick root structures extend outward in all directions, branching into the surrounding maze like veins feeding an entire living network. These 
roots are not static; they subtly shift, retract, and regrow, as if the entity is constantly reshaping its own body to adapt to intrusions.
	The surface of the Mazeheart is rough and layered, composed of overlapping root segments fused together over time. Between these layers, faint organic 
luminescence pulses in sync with its central rhythm, giving the impression that energy flows through it like lifeblood.
	Occasionally, parts of the surrounding maze respond to its movements—roots nearby will twitch, rearrange, or tighten their formations, reflecting the entity’s 
influence over the environment. Its presence is not just physical but structural, as though the maze itself is an extension of its body.

