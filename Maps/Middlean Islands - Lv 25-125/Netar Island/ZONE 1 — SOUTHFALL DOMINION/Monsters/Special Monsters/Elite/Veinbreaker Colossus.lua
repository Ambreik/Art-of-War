			Veinbreaker Colossus

---

		1. Basic Information

* Monster Name : "Veinbreaker Colossus"
* Rank : Elite
* Monster Class : Superior
* Monster Type : Tanky, Melee
* Monster Category / Race : Beast
* Element Type : Earth
* Spawn Timer : 2h (real-time)
* Location / Sub-Area : Deep layers of "The Sundrop Quarry" — lower excavation pits, resonance chambers, and near Quarrysteel Nodes
* Group Pattern : Solo
* Aggro Type : Aggressive
* Special Notes : Elite guardian of deep quarry zones; partially tied to quarry resonance mechanics; engages players who mine or cause heavy noise nearby

---

		2. Appearance

	"The Veinbreaker Colossus" towers like a living fragment of the quarry itself, its massive body formed from a fusion of hardened stone, compacted earth, and 
thick, muscle-like layers of mineral-infused flesh. Its silhouette is uneven and jagged, as if it was carved directly from the quarry walls and forced into motion.
	Its skin resembles cracked basalt plates, layered over glowing veins of dull orange and faint gold, pulsing slowly beneath the surface like molten ore 
struggling to break free. These veins intensify in brightness when the creature is agitated, especially around its shoulders, chest, and forearms.
	Its arms are disproportionately large, ending in heavy, blunt fists shaped like natural stone hammers rather than claws. Each movement of its limbs sheds dust 
and small rock fragments, creating a constant low rumble as debris falls from its body.
	The head is small compared to its bulk, partially embedded into its upper torso, with minimal facial features—only a deep-set mouth line and two glowing 
fissures acting as eyes. These emit a dim, earthen light, giving the impression that the creature sees through vibration rather than sight.
	When it moves, the ground reacts before it does—subtle tremors ripple outward with each step. Its presence alone feels heavy, oppressive, as if the quarry 
itself resists or acknowledges its movement. During combat, cracks widen across its body, and faint heat distortion can be seen leaking from within, hinting at 
unstable energy beneath its stone shell.

