---

		5. Skills & Abilities

* "Seismic Slam" : The Colossus raises both arms and slams the ground, creating a forward-facing shockwave that travels in a straight line. Deals heavy Physical 
damage and applies a brief stagger. The shockwave widens as it travels, making distance positioning important.

* "Quarry Quake" : A localized AoE ability centered on the Colossus. Causes the ground within a radius to rupture in multiple points after a short delay. Players 
standing still are hit multiple times; movement reduces total damage taken.

* "Resonance Pulse" : Triggered when near active mining or after taking sustained damage. Emits a low-frequency pulse that deals minor damage but briefly reveals 
all nearby players (breaks stealth). Can also awaken nearby "Stone Mites", linking it to quarry ecosystem behavior.

* "Crushing Grip" : Single-target melee ability. The Colossus grabs a nearby player and slams them into the ground, dealing heavy burst damage and applying a short 
stun. Has a clear wind-up animation.

* "Stonehide Passive" : Reduces incoming damage by a flat percentage. Effect weakens slightly after each Seismic Slam, encouraging timing-based damage windows.

---

