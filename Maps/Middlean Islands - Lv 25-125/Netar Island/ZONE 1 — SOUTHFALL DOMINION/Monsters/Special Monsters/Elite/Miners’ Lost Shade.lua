			Miners’ Lost Shade

---

		1. Basic Information

* Monster Name : Miners’ Lost Shade
* Rank : IV
* Monster Class : Elite
* Monster Type : Hybrid (Humanoid / Undead)
* Monster Category / Race : Undead
* Element Type : Dark
* Spawn Timer : 8 hours 30 minutes (Elite respawn cycle)
* Location / Sub-Area : Quarry Descent Passage – Deep Work Shafts / Abandoned Mining Chambers / Collapsed Excavation Sites
* Group Pattern : Solo / Occasional paired manifestations
* Aggro Type : Aggressive (Psychological trigger-based)
* Special Notes : Former miner corrupted into a lingering shade; exhibits fear-inducing presence and aggressive retaliation when approached

---

		2. Appearance

	The Miners’ Lost Shade appears as a deteriorated humanoid figure draped in tattered remnants of mining gear. Its body is partially translucent, with faint 
outlines of bone and decayed flesh visible beneath a veil of shadow-like energy that continuously seeps and reforms around it.
	Its limbs hang slightly loose, as though disconnected from proper control, yet still move with unsettling intent and precision. The lower half of its form fades
irregularly into mist-like fragments that trail behind it as it drifts across the ground. In darker environments, its silhouette becomes more defined, while in lit 
areas, it appears fragmented and unstable, flickering between presence and absence.
	The shade still carries traces of its former life: a broken helmet fused into its head, fragments of mining tools clutched in its hands, and faint glowing 
points where its eyes would have been. These eyes emit a dim, hollow light that seems to fixate on intruders with lingering resentment and unease. Subtle whispers 
and echoes of distant cave-ins or labor sounds can sometimes be perceived when it is nearby, as if memories of its past continue to reverberate through its 
existence.

