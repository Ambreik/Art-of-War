---

		2. Appearance

	The Fenback Crocodilian is a large, heavily built reptilian predator with a low, elongated body designed for both submerged stealth and sudden explosive 
movement. Its hide is thick and layered with hardened scales, colored in dark swamp greens, muddy browns, and algae-stained tones that allow it to blend seamlessly 
into murky waters.
	Along its back runs a series of pronounced, jagged ridges—its defining “fenback”—which resemble a fusion of bone, stone, and root-like growths. These ridges are
uneven and rugged, sometimes coated in moss or aquatic plant life, giving the creature an almost ancient, semi-terrestrial appearance.
	Its head is broad and flat, with a powerful jaw lined with thick, interlocking teeth designed for gripping rather than tearing. The eyes sit slightly elevated, 
allowing it to remain mostly submerged while still observing its surroundings. These eyes are dull but focused, often barely visible above the waterline until the 
moment of attack.
	Its limbs are short but muscular, used primarily for short bursts of movement on land, while its long, powerful tail provides propulsion in water. When idle, it
remains nearly motionless, blending into the water surface like driftwood or debris.

	When preparing to strike, subtle ripples form around its body, followed by a sudden, violent surge forward.

