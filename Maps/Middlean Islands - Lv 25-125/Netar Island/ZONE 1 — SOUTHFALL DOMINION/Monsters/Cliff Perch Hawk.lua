			Cliff Perch Hawk

---

		1. Monster Overview

* Name : Cliff Perch Hawk
* Monster Type : Beast
* Monster Class : Rare
* Rank : II
* Location : Netar Island – Zone 1 – Southfall Dominion (Cliff zones, elevated ridges, ruins, and high vantage points)
* Role : Aerial Scout / Environmental Observer
* Behavior Type : Territorial / Watchful / Opportunistic Predator
* Group Type : Solitary or small paired presence (rare)

---

		2. General Description

	Cliff Perch Hawks are aerial predators adapted to elevated terrain, where they establish dominance over cliffs, ruins, and high ground. Unlike aggressive 
hunting birds that rely purely on speed, these creatures exhibit a calculated and observant behavior pattern, often remaining perched for extended periods while 
surveying large areas.
	They function as natural reconnaissance predators within their ecosystem, detecting movement from great distances and reacting quickly to perceived threats or 
prey. While not overtly aggressive unless provoked, they become highly responsive when their territory or perch zones are disturbed.

---

		3. Appearance

	The Cliff Perch Hawk is a large bird of prey with a streamlined and aerodynamic body built for gliding rather than constant flapping. Its wings are broad and 
slightly angular, allowing it to ride air currents efficiently along cliff faces and open skies.
	Its plumage is layered with earthy tones—dark browns, muted grays, and subtle streaks that help it blend seamlessly into rocky environments. The feather 
patterns across its wings and tail are naturally camouflaged, resembling the textures of stone and shadow when it is perched against cliffside surfaces.
	Its talons are sharp and prominently curved, adapted for gripping uneven rock surfaces rather than only capturing prey. These talons allow it to anchor itself 
securely even in strong winds.
	The hawk’s eyes are its most striking feature—piercing and focused, with a reflective quality that gives the impression of constant vigilance. When perched, its
posture is upright and still, with minimal movement aside from occasional head rotations as it scans its surroundings. In flight, it glides with controlled 
precision, rarely wasting energy on unnecessary motion.

---

		4. Behavior

	Cliff Perch Hawks exhibit the following behavioral traits:
* Prefer high elevation perches
* Maintain line-of-sight surveillance over large areas
* Remain stationary for long durations
* React quickly to sudden movement below or nearby
* May circle before engaging or fleeing
* Avoid unnecessary confrontation unless threatened or provoked

	They act as environmental observers, making them valuable indicators of activity in their territory.

---

		5. Monster Class

* Class Tier : Rare
* Rank : II
* Encounter Frequency : Moderate in cliff regions, low in dense or low-altitude areas
* Threat Level : Moderate (due to detection and reaction capabilities rather than raw damage)

---

		6. Abilities / Skills

	1. Aerial Dive Strike

	The hawk launches from its perch into a high-speed dive toward its target.

* Effect :
	* Rapid descent attack from elevation
	* Deals increased damage based on distance of the dive
	* Has a high chance to catch targets off-guard

* Mechanics :
	* Requires altitude advantage
	* Initiates after brief target lock
	* Best used against isolated or unaware targets

---

	2. Perch Surveillance

	A passive scanning behavior where the hawk remains stationary while observing its surroundings.

* Effect :
	* Detects movement within a wide radius
	* Improves reaction time to intruders
	* Enables early engagement or evasion

* Mechanics :
	* Non-offensive state
	* Acts as a detection layer in its territory

---

	3. Alert Cry

	The hawk emits a sharp call when it detects threats.

* Effect :
	* Warns nearby allied creatures (if any exist in the area)
	* Temporarily increases awareness of nearby units
	* May trigger defensive or evasive behavior
* Mechanics :
	* Area-based alert signal
	* Functions as an environmental trigger

---

	4. Wind Glide

	Allows the hawk to travel efficiently using air currents.

* Effect :
	* Sustained gliding over long distances without flapping
	* Enables repositioning across cliffs and open air zones
	* Reduces energy consumption during movement
* Mechanics :
	* Movement ability rather than attack
	* Used for repositioning and scouting

---

		7. Combat Behavior

* Engages from range using aerial advantage
* Prefers initiating combat via dive attacks
* Attempts to reposition to higher ground after engagement
* Avoids prolonged direct confrontation if outmatched
* Uses elevation as both offense and defense

