* Effect :
	* Sudden acceleration in a chosen direction
	* Used to evade attacks or close short distances quickly
	* Leaves behind a brief visual blur effect

* Mechanics :
	* Short cooldown behavior
	* Often chained with directional changes
	* Primarily defensive / repositioning skill

