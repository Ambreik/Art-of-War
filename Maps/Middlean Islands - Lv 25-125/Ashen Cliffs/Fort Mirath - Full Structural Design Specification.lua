		5. Environmental Logic

	Fort Mirath is heavily influenced by :

* Weather Layer (from Ashen Cliffs system)
	* fog reduces tower visibility
	* rain reduces ranged precision
	* clear weather maximizes fortress dominance
* Altitude Effect : 
	* highest elevation on island
	* naturally enhances:
		* sightlines
		* wind exposure
		* fog density interaction

