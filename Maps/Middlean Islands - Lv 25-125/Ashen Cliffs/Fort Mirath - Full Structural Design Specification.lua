			FORT MIRATH — FULL LOCATION DESIGN SPECIFICATION

		1. Core Identity

	Fort Mirath is a high-elevation military fortress built into the central plateau of the "Ashen Cliffs" island formation.
	It is not a town, not a dungeon, and not an instance.

	It is :

> A fully operational hostile military stronghold occupying a naturally fortified volcanic plateau.

	The entire structure is designed around :
* defense in depth
* vertical control
* layered visibility dominance
* internal reinforcement flow

	It functions as a living war machine architecture, not a static environment.

---

		2. Macro Structure (World Shape)

	The fortress is built on a semi-circular mountain plateau ridge, forming :
* a high central plateau (core fortress)
* steep outer cliffs (natural defense barrier)
* multiple elevation drops into lower sublevels

	Structural layers from outside → inside :
1. Cliff approach routes (external terrain)
2. Outer walls and perimeter battlements
3. Courtyard combat basin (central open zone)
4. Inner halls (structured military interior)
5. Leadership wings (segmented command sectors)
6. Sublevel detention and utility layer
7. Hidden cliffside access routes (grates/sewers)

---

		3. Vertical Architecture Philosophy

	Fort Mirath is defined by stacked combat elevation, not flat geography.

	Vertical tiers: 

* Tier 1: Ground / Courtyard Level
	* open combat basin
	* cannon coverage zone
	* main gate approach pressure point

* Tier 2: Wall Level
	* patrol circuits
	* defensive chokepoints
	* ladder access conflict zones

* Tier 3: Rooftop Level
	* traversal network via bridges and broken structures
	* high-risk melee + ranged hybrid combat
	* flank and infiltration layer

* Tier 4: Watchtower Level
	* extreme visibility dominance
	* ranged suppression layer

* Tier 5: Inner Hall Network
	* controlled interior corridors
	* trap systems
	* reinforcement routing layer

* Tier 6: Leadership Wings
	* segmented command zones
	* system-critical AI anchors

* Tier 7: Sublevel Detention Layer
	* confined corridors
	* prisoner holding cells
	* interrogation zones

