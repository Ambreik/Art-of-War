			Military Discipline Baseline Layer (Pre-Degradation State)

	Core Concept

	Before any leadership is removed, the fortress must exist in a state of :

> High-coordination military efficiency

	This is not about adding mechanics — it is about ensuring that all existing systems operate at their maximum disciplined version.

	Why this matters :
* Because later mechanics (leader death, alert degradation, patrol disorder) only work if the starting point feels controlled and precise.

---

	1. Patrol Precision Baseline

	Before degradation :
* Patrol routes are:
	* tightly timed
	* evenly spaced
	* non-overlapping in coverage gaps
* Each patrol group maintains clear zone responsibility (walls, courtyards, towers, halls)

	Effect on Player :
* Very few blind spots
* Minimal “safe gaps”
* Predictable but strict coverage

---

	2. Watchtower Discipline Baseline

	Before degradation :
* Watchtower units :
	* maintain constant scanning rhythm
	* prioritize high-risk zones (gates, courtyards, wall approaches)
* No idle behavior during duty positions

	Effect on Player :
* Open areas feel exposed at all times
* Vertical threat is constant, not random

---

	3. Alert System Precision Baseline

	Before degradation :
* Suspicious → Alarmed transition is :
	* fast
	* reliable
	* consistent across fortress zones
* Alarm propagation is instant and structured

	Effect on Player :
* No "safe delay windows" after detection
* Mistakes escalate quickly into full response

---

	4. Reinforcement Coordination Baseline

	Before degradation:
* Reinforcements :
	* arrive from correct internal routes
	* reach target zones efficiently
	* avoid unnecessary pathing conflicts
* Chokepoint defense is always supported

	Effect on Player :
* Fortress feels “complete” defensively
* No weak reinforcement timing windows

---

	5. Defense Grid Discipline Baseline

	Before degradation :
* Traps operate in logical coordination with patrols
  * chokepoints are actively defended
  * cannons are manned quickly when needed
  * shield formations appear efficiently

	Effect on Player :
* Fortress behaves like a unified defense system
* No disjointed or delayed reactions

---

	6. Why This Layer Exists (Critical Design Intent)

	This is not "difficulty scaling."

	It is :

> A contrast amplifier for later degradation mechanics

	Because your leadership system depends on this :

| State                       | Meaning                                          |
| --------------------------- | ------------------------------------------------ |
| Baseline (Discipline Layer) | Fortress is efficient, coordinated, dangerous    |
| Post-Leader Loss            | Fortress becomes fragmented, slower, exploitable |

	Without this baseline, later mechanics lose impact.

---

	7. Player Perception Goal

	At full strength, players should feel :

* "Every angle is covered"
* "They react immediately"
* "There are no mistakes in their defense"

	Later, after leader removal :

* "Something is wrong here"
* "They’re slower now"
* "They are not coordinated anymore"

	That contrast is the core emotional payoff.

