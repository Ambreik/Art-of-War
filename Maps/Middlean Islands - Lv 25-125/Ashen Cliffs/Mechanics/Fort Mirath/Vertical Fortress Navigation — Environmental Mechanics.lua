			Vertical Fortress Navigation — Environmental Mechanics

	This mechanic defines how the fortress is physically traversed as a vertical structure, where height, elevation, and layered access are part of gameplay, not 
decoration.
	The fortress is not meant to be approached as a flat combat area, but as a stacked defensive structure composed of interconnected elevation levels.

---

	1. Structural Vertical Layers

	The fortress is divided into five functional elevation tiers :

| Tier   | Area                     | Role                               |
| ------ | ------------------------ | ---------------------------------- |
| Tier 1 | Outer walls & gate level | First defensive ring, patrol heavy |
| Tier 2 | Watchtowers & wall tops  | Surveillance and ranged control    |
| Tier 3 | Rooftops & rope bridges  | Lateral elevated traversal         |
| Tier 4 | Inner halls              | Interior control space             |
| Tier 5 | Dungeon level            | Underground layer & hidden access  |

	Players can move upward, across, and downward through these tiers using environmental elements.

---

	2. Wall Ladders (Primary Vertical Access)

	Placed along :
* Inner wall sections
* Courtyard-to-wall transitions
* Tower access points

	Behavior : 
* Allow direct ascent from ground to wall level
* Expose players while climbing (no combat possible)
* Commonly within patrol sightlines

	Gameplay Role : 
* Fastest vertical access
* Highest risk if patrols are active
* Intended for opportunistic movement when patrol gaps appear

---

	3. Crumbled Tower Section (Alternate Entry Path)

	A partially destroyed tower creates :
* A natural ramp of debris and broken stone
* Access from outer approach directly to mid-tower elevation

	Behavior : 
* No ladder required
* Sloped traversal with partial cover
* Less visible to gate and courtyard patrols

	Gameplay Role : 
* Stealth-friendly infiltration route
* Avoids main gate and wall ladders
* Encourages exploration of fortress perimeter

---

	4. Rooftop Rope Bridges (Horizontal Elevated Traversal)

	Rope bridges connect :
* Tower tops
* Rooftop sections
* Wall tops across gaps

	Behavior : 
* Allow movement across fortress without touching courtyard
* Narrow path: limited maneuverability during combat
* Visible from some tower angles

	Gameplay Role : 
* Enables rooftop traversal playstyle
* Allows players to bypass ground patrol density
* Provides positional advantage for ranged combat

---

	5. Rooftops as Combat Platforms

	Flat rooftop sections serve as :
* Combat arenas
* Transition points between towers
* Alternative routes into inner structure

	Behavior : 
* Provide height advantage
* Risk of falling if knocked back
* Partial cover via chimneys, crates, battlements

	Gameplay Role : 
* Rewards players who take vertical routes
* Allows avoidance of chokepoints and traps in corridors

---

	6. Inner Hall Vertical Connections

	Inside the fortress :
* Staircases connect hall floors to rooftop access points
* Balconies overlook inner chambers
* Some rooms have upper walkways

	Behavior : 
* Verticality continues indoors
* Enemies can engage from above and below

	Gameplay Role : 
* Prevents interior from feeling flat
* Maintains vertical combat logic even inside

---

	7. Sewer / Dungeon Grate (Quest-Unlocked Route)

	Located on cliffside beneath fortress.

	Behavior : 
* Initially inaccessible
* Later unlocked via quest progression
* Leads directly into dungeon level (Tier 5)

	Gameplay Role : 
* Underground infiltration path
* Bypasses walls, towers, and courtyards entirely
* Ideal for stealth or alternative story approach

---

	8. Verticality & Patrol Interaction

	Because patrols exist primarily on :
* Courtyards
* Walls
* Towers

	Players using rooftops, bridges, and crumbled tower path :
* Interact less with patrol density
* Trade patrol risk for fall risk and exposure

	This creates a choice of risk type, not risk removal.

---

	9) Environmental Combat Consequences

	Due to elevation :
* Knockbacks can cause falls from :
	* Walls
	* Towers
	* Rooftops
	* Bridges
* Ranged units gain increased effectiveness from height
* Open courtyards become least safe traversal option during alert

---

	10) Design Purpose Recap

	This mechanic ensures :
* The fortress is navigated in three dimensions
* Multiple playstyles are supported naturally :
	* Stealth infiltration
	* Rooftop traversal
	* Direct assault
	* Underground entry (later)
* Verticality replaces linear corridor progression

	Players are not funneled through one path — they choose their elevation path through the stronghold.
