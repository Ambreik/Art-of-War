			Rooftop & Wall Combat Advantage

	Type : Environmental Combat Logic

	Core Concept : Combat on elevated structures of the fortress is mechanically different from combat in courtyards or halls.

	Height is not cosmetic.
	Height is a combat factor.

	This applies to both :
* Players
* Enemy defenders

---

	High Ground Ranged Advantage

	When standing on :
* Walls
* Watchtowers
* Rooftops
* Elevated ledges

	Ranged attackers gain :
* Increased effective range
* Clearer line-of-sight over obstacles
* Priority targeting over units below

	This makes towers and rooftops dominant ranged positions, as they realistically should be.

---

	Knockback & Fall Risk

	Edges on :
* Walls
* Towers
* Rooftops
* Stair openings

	Are dangerous during combat.

	Any knockback, stagger, or forced movement near an edge can cause :
* Falling to lower levels
* Fall damage
* Forced relocation into a worse combat position (often into courtyards or patrol zones)

	This is true for :
* Players knocked down by enemies
* Enemies knocked down by players

---

	Enemy Behavior — Ledge Control

	Some defenders positioned on walls and rooftops are trained to :
* Use kick, shove, or shield bash style abilities
* Attempt to push opponents toward edges
* Fight more aggressively near ledges

	They understand the terrain advantage.
	This makes fighting on rooftops tense, not safe.

---

	Tactical Meaning for Players

	Players quickly learn :
* Rooftops are great for ranged advantage
* But extremely dangerous in melee
* Walls are powerful positions but risky to hold
* Courtyards are safer from falling but worse for visibility

	So choosing where to fight becomes a decision.

---

	Interaction with Vertical Navigation

	All those :
* Rope bridges
* Ladders
* Crumbled tower paths

	Now have combat implications, not just traversal value.
	A rope bridge fight is very different from a courtyard fight.

---

		Design Purpose Recap

	This mechanic ensures :
* Verticality is part of combat strategy
* Positioning matters as much as abilities
* The fortress feels designed for defense, not decoration
