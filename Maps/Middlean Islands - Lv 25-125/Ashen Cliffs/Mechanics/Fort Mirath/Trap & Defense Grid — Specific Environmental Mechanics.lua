			Trap & Defense Grid — Specific Environmental Mechanics

	This mechanic defines the passive defensive infrastructure of the fortress.
	These are not random hazards, but intentional military defenses designed to :
* Detect intruders
* Slow advancement
* Create kill zones
* Support defenders during Alert states

	They are placed in logical defensive locations : corridors, gates, courtyards, and choke passages.

---

	1. Tripwire Alarm System (Detection Trap)

	Placement : 
* Narrow interior corridors
* Stair transitions
* Hallway turns with low visibility

	Behavior : 
* Invisible at first glance
* Triggered when crossed
* Does not deal damage

	Effect : 
* Immediately shifts local area into Suspicious state
* Nearby guards converge to the location
* If already Suspicious → contributes to escalation toward Alarmed

	Gameplay Role : 
* Punishes rushing through corridors
* Forces players to observe floor-level details
* Integrates directly with the Alert System

---

	2. Pressure Plates → Arrow Slit Activation (Defense Trap)

	Placement : 
* Long corridors
* Gate approach hallways
* Interior choke passages

	Behavior : 
* Hidden floor plates
* When stepped on :
	* Arrow slits open in walls
	* Volley of projectiles fired across corridor length

	Effect : 
* Sustained directional damage zone for a short duration
* Forces players to retreat, take cover, or push through quickly

	Gameplay Role : 
* Turns straight corridors into lethal tunnels
* Encourages careful movement and positioning
* Makes interior layout tactically meaningful

---

	3. Oil Spill Zones (Courtyard Environmental Hazard)

	Placement : 
* Courtyard stone sections
* Near gate chokepoints
* Beneath wall firing lines

	Behavior : 
* Visible darkened ground patches
* Initially harmless terrain

	Ignition Triggers : 
* Oil can be ignited by :
	* Player fire abilities
	* Enemy fire attacks
	* Cannon blast impact

	Effect When Ignited : 
* Area becomes fire zone for duration
* Damages anyone standing inside
* Blocks passage temporarily

	Gameplay Role : 
* Dynamic battlefield shaping
* Can be used by both players and enemies
* Turns courtyard into shifting hazard map

---

	4. Gate Chokepoints & Shield Formations (AI + Environment Synergy)

	Placement : 
* Main gate interior
* Narrow passages between courtyard and inner halls

	Behavior During Alarmed State : 
* Enemies form shield line formations
* Physically block passage through chokepoint
* Ranged enemies attack from behind formation

	Environmental Synergy

	These chokepoints are often near :
* Oil spill zones
* Cannon firing arcs
* Arrow slit corridors

	Gameplay Role : 
* Creates realistic defensive stand positions
* Forces players to :
	* Break formation
	* Use vertical routes
	* Use environmental tools (oil, cannon, elevation)

---

	5. How the Defense Grid Works Together

	These traps are not isolated. They combine :

| Trap               | Supports                |
| ------------------ | ----------------------- |
| Tripwire           | Alert system escalation |
| Pressure plates    | Corridor denial         |
| Oil zones          | Courtyard control       |
| Shield chokepoints | Passage denial          |

	They create a fortress that :

> Detects → Delays → Damages → Blocks

---

	6. Design Purpose Recap

	This system ensures the fortress interior feels like :
* A prepared military stronghold
* Designed to repel intruders intelligently
* A place where environment fights alongside enemies

	Players cannot treat corridors and courtyards as neutral space — they are defensive weapons built into the architecture.
