			Weather & Fog Integration

	Type : Global Environmental + Specific POI Environmental Mechanics

	Core Concept : 

	Because "Fort Mirath" sits at the highest elevation of the island plateau, it is the most exposed location to Ashen Cliffs’ weather patterns :
* Dense rolling fog
* Coastal rainstorms
* Clear high-visibility daylight

	These conditions directly affect how effective the fortress defenses are — especially the watchtowers and battlements.

	This turns :

> Weather and time of day into tactical infiltration factors.

---

	Interaction with Existing Systems

	This mechanic directly modifies behavior of :
* Watchtower line-of-sight system
* Alert system efficiency
* Ranged attacks from elevated positions
* Patrol detection capability on walls and courtyards

	It does not create new systems — it modifies the ones you already approved.

---

	Condition 1 — Heavy Fog

	When island fog rolls over the plateau:

	Effects on Defenders : 
* Watchtower visual detection range is heavily reduced
* Towers cannot clearly see courtyard or gate approaches
* Guards rely more on hearing radius (as defined in Alert mechanic)
* Identification time of targets increases

	Effects on Ranged Units : 
* Muskets, bows, crossbows from towers suffer :
	* Reduced accuracy
	* Shorter effective range

	Player Impact

	This becomes the ideal time for :

* Gate approach
* Courtyard traversal
* Wall ladder climbing
* Rooftop movement

	Fog favors stealth and movement.

---

	Condition 2 — Rainstorms

	Rain has a different effect than fog.

	Effects on Defenders : 
* Slightly reduced visibility (less than fog)
* Slower reaction speed to distant movement
* Sound masking from rainfall reduces hearing clarity at long range

	Effects on Environment : 
* Oil spill zones are harder to ignite
* Some surfaces (ladders, rooftops) become slightly riskier to traverse (fits vertical navigation tension)

	Player Impact

	Rain favors :
* Rooftop and wall approaches
* Less favorable for trap ignition tactics

---

	Condition 3 — Clear Daylight

	This is when the fortress is at maximum defensive efficiency.

	Effects on Defenders : 
* Maximum tower detection range
* Clear line-of-sight across :
	* Gate
	* Courtyard
	* Wall sections
* Fast visual identification of intruders

	Ranged Units : 
* Maximum accuracy and range from towers and battlements

	Player Impact

	This is the hardest time to infiltrate from open areas.

	Players are pushed toward :
* Sewer/grate entry
* Crumbled tower access
* Interior infiltration routes

---

	Why This Works So Well Here

	Because Fort Mirath has :
* Height advantage
* Towers dominating sightlines
* Multiple vertical paths
* Alert system based on sight and hearing

	Weather becomes a natural modifier, not an artificial mechanic.

---

		Design Purpose Recap

	This mechanic achieves :
* Encourages players to observe environment
* Makes timing part of strategy
* Makes the fortress feel physically integrated into Ashen Cliffs’ climate
* Rewards patient players without forcing mechanics

	Players who rush at noon face a disciplined fortress.
	Players who wait for fog face a vulnerable one.
