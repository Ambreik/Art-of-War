			Sublevel Holding Cells & Interrogation Wing

	Type : Environmental + Lore + Emergent Gameplay Mechanics
	
	Concept : Beneath the inner halls of the fortress exists a sublevel detention and interrogation area.

	This is not a dungeon instance.
	
	It is a structural lower level of the fortress, reachable through :
* Interior stair access from inner halls
* A later-unlocked cliffside grate/sewer entry (from Vertical Navigation mechanic)

	This sublevel serves as :

> Where the Forsaken Band keeps captured islanders, scouts, and prisoners for interrogation.

---

		Layout Identity

	The sublevel contains :
* Rows of holding cells
* Interrogation rooms
* Guard posts
* Storage for confiscated belongings
* Narrow corridors designed for control, not comfort

	This area is tighter, more claustrophobic, and more controlled than the open courtyards and walls above.

---

		Environmental Storytelling (Lore Integration)

	Inside interrogation rooms, players can find :
* Documents referencing Mirath’s betrayal
* Notes about stolen supplies
* References to movements across Ashen Cliffs
* Evidence of organized occupation, not random banditry

	This reinforces story without NPC dialogue.

---

		Prisoner Interaction (Optional Objective)

	Some cells contain living prisoners.

	Players can choose to :
* Ignore them and proceed with main objectives
* Open cells and release prisoners

	Opening cells is an interaction, not a quest requirement.

---

		Chaos Event Trigger

	When multiple cells are opened :
* Prisoners begin fleeing through corridors toward surface exits
* They run through inner halls and into courtyards trying to escape

	This triggers a localized chaos state in the fortress AI.

	What happens during this chaos :
* Nearby guards stop patrolling and attempt to chase prisoners
* Some guards abandon posts temporarily
* Patrol routes become temporarily disrupted
* Attention shifts away from players in that area

	This is not an alert state.
	This is distraction behavior.

---

		Important: This Does NOT Replace Alert System

	If the fortress is already "Suspicious" or "Alarmed", this chaos adds to the disorder.
	If the fortress is "Calm", this becomes a subtle advantage for stealth players.

---

	Player Advantage (Emergent, Not Forced)

	Releasing prisoners creates :

* Temporary patrol gaps
* Reduced guard density in certain corridors
* Opportunity to move through inner halls or reach leadership chambers easier

	Players who explore and think benefit.
	Players who rush never see this.

---

	Interaction with Vertical Navigation

	Because of the cliffside grate access :
* Players can enter from below
* Release prisoners
* Let chaos rise upward into the fortress
* Use that as cover for infiltration

	This ties beautifully with the vertical design you already approved.

---

		Design Purpose Recap

	This mechanic makes the fortress feel like :
* A real occupied military site
* A place where captives are held
* A place that can be destabilized indirectly

	Without adding quests, NPC hubs, or artificial systems.

	It rewards exploration and observation.

