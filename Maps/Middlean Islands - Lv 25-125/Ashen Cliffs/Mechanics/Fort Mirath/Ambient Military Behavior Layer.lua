			Ambient Military Behavior Layer

---

		Ambient Military Behavior Layer

	Core Concept : The fortress is always in a state of organized occupation.

	Not scripted events. Not NPC routines.
	But consistent military logic expressed through movement and positioning.

	The goal is 

> The player feels they are infiltrating a functioning military stronghold, not an enemy spawn grid.

	Inside "Fort Mirath", every visible unit exists as part of an operational structure.

---

	1. Patrol Behavior as “Shift Rotation Logic”

	Patrols are not random loops.

	They behave as :
* Rotating duty assignments across:
	* walls
	* towers
	* courtyards
	* inner halls

	Behavioral Meaning :
* Some guards are "on watch"
* Some are "relieved and repositioning"
* Some are transitioning between posts

	Gameplay Effect :
* Patrol routes feel organic instead of mechanical
* Sightlines constantly shift without feeling scripted

---

	2. Courtyard Activity Layer

	Courtyards are not empty combat spaces.

	They naturally contain :
* Groups moving between positions
* Short pauses of regrouping near supply points
* Movement between gate and inner hall access points

	Behavioral Meaning :
* This is the logistical core space of the fortress.

	Gameplay Effect :
* Courtyard is a dynamic exposure zone
* Not a static arena

---

	3. Logistical Movement (Crates / Supplies / Equipment Flow)

	Certain enemies are seen :
* Carrying supplies between storage areas
* Moving ammunition toward battlements
* Transporting equipment toward cannon positions

	Behavioral Meaning :
* This represents internal reinforcement of defenses

	Gameplay Effect :
* Creates moving visual obstacles
* Reveals high-value areas (ammo routes, cannon access points)
* Helps players read fortress structure visually

---

	4. Cannon Maintenance Presence

	Some guards are positioned :
* Near cannons
* Performing idle maintenance checks
* Standing guard over artillery positions

	Behavioral Meaning :
* Cannons are active military assets, not static props.

	Gameplay Effect :
* Reinforces cannon importance before combat begins
* Makes later cannon takeover more meaningful

---

	5. Watchtower Sentinel Layer

	Watchtowers are always occupied.

	But behavior varies :
* Some units actively scanning
* Some stationed in fixed observation stance
* Some rotating between observation angles

	Behavioral Meaning :
* Surveillance is continuous, not event-based

	Gameplay Effect :
* Reinforces vertical threat awareness
* Makes rooftops and towers feel dangerous even in calm state

---

	6. Pre-Combat Transition Logic (Important)

	This ambient layer directly supports your existing :
* Calm
* Suspicious
* Alarmed system

	Meaning :

> These behaviors don’t disappear — they escalate.

	Example :
* Carrying crates → becomes rushed movement under Suspicious
* Patrol rotations → become tight response formations under Alarmed
* Watchtowers → shift from scanning → targeting

---

		Design Purpose

	This system ensures :
* The fortress feels occupied and structured at all times
* Players read the environment before combat begins
* No area feels like a "spawn zone"
* Existing mechanics gain realism without adding complexity

---

		Important Design Rule

	This is NOT :
* a scheduling system
* a simulation system
* a time-based routine system

	It is :

> A visual + behavioral layer applied over existing AI logic

