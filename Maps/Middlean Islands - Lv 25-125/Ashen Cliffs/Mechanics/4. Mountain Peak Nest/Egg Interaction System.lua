			Egg Interaction System

	Picking an Egg : 
* Interaction requires short channel time
* Egg becomes bound to player immediately upon pickup :
	* Cannot be traded
	* Cannot be dropped
	* Cannot be destroyed

	Egg State UI (conceptual)

* "Stable"
* "Warming"
* "Cracking"
* "Hatching"

---

		Hatch System — 2 In-Game Hour Evolution

	After pickup, egg begins a fixed evolution cycle (2 in-game hours).

---

	Phase 1 — "Warming State" : 
* Egg emits faint vibration
* No visible changes
* Player may carry it freely

---

	Phase 2 — "Cracking State" : 
* Surface cracks appear
* Occasional sound cues (movement inside)
* Slight buff aura begins to emit (subtle passive feeling)

---

	Phase 3 — "Hatching Event" : 

	At 2 hours :
* Egg hatches into either :
	* Flying Pet (cosmetic + minor utility)
	* Flying Mount (movement progression unlock)

---

		Outcome System

	Flying Pet Outcome : 
* Follows player
* Minor passive effect (environmental exploration benefit)
* No combat function

	Flying Mount Outcome : 
* Unlocks aerial traversal capability
* Can only be used in :
	* open sky zones
	* non-indoors environments
	* island exterior regions

---

		Bonus Egg Effect (Random Layer)

	Each egg may contain a hidden internal buff seed :

	Examples :
* Minor stamina regeneration boost (exploration)
* Reduced fall damage (mountain traversal synergy)
* Temporary wind resistance (climbing support)
* Short movement speed increase after hatch

---

	Balance Constraints (Important) : 
* No stacking eggs
* No immediate re-farming of the nest
* Daily reset prevents exploit loops
* Hatch outcome is player-bound progression, not trade economy.

