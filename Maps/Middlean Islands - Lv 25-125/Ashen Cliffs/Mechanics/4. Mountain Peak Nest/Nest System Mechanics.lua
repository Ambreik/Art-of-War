			Nest System Mechanics

		Core Rule — One Egg Ownership Rule

* Each player may hold only 1 active "Mountain Nest Egg" at a time
* Once an egg is taken :
	* That nest becomes inactive for that player
	* It visually appears "emptied" from their perspective
* A new egg can only be taken when :
	* A fresh egg respawns in that nest cycle

---

		Nest Respawn Cycle

* Each nest has a global egg respawn timer (daily cycle)
* When all eggs are taken :
	* Nest enters "Dormant State"
	* No new interaction possible until reset

