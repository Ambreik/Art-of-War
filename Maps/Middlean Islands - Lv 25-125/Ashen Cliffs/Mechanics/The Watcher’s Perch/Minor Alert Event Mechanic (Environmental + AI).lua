			Minor Alert Event Mechanic (Environmental + AI)

	This POI introduces a very light but meaningful mechanic.

	The signal brazier can be interacted with by players.

	If the brazier is lit :
* A visible smoke column rises
* Nearby Forsaken patrols interpret it as a signal
* Patrol patterns in the surrounding cliffs and paths temporarily change
* Extra patrols converge toward the tower base and nearby paths
* Alert state lasts 5–8 minutes

	This is not a full fortress alert.
	It is a localized investigation response.

	If the brazier is extinguished :
* Patrols slowly return to normal routes

	This gives players a choice :
* Use the tower safely for recon
* Or intentionally create movement in enemy patrols to manipulate routes

