			Environmental Traps
			
		Trap 1 — "Lurebloom Plant"

	Effect :
* Emits charming glow
* Attracts nearby players AND monsters slowly toward it
* After 6 seconds → releases "Spirit Burst"
* Spawns a hostile forest spirit that deals AoE nature damage

	Funny/creepy because mobs walk willingly into danger.

---

		Trap 2 — "Rootsnare Patch"

	Looks like normal ground vines.

	Effect :
* Roots grab player’s legs (root 3 s)
* Nearby bushes rustle loudly → can attract patrol mobs
* Player must spam interact to break free faster

---

		Trap 3 — "Spore Puff Fungus"

	Player steps near it → explodes into spores.

	Effect :
* Confusion effect (reversed movement for 4 s)
* Screen slight distortion
* Harmless alone, deadly if enemies nearby

---

		Trap 4 — "Hollow Log Snap"

	Looks like lootable log.

	Effect : 6+
* When interacted → log “snaps shut”
* Minor damage + loud noise
* Chance to spawn 1–2 small forest creatures

---

		Trap 5 — "Watching Eyes"

	Glowing eyes appear in bushes.

	Effect :
* If player stares too long → fear for 2 s
* If ignored → nothing happens
* Pure psychological trap
