			Mini-Event Mechanic — The Old Stone Markers

---

		1. Mechanic Overview

	Hidden within the Glade are four ancient stone markers, almost fully swallowed by moss, roots, and time.
	They are not immediately recognizable as a puzzle.

	Players must :
1. Notice the unusual stones
2. Clean the moss to reveal carved symbols
3. Rotate the stones to form the correct symbolic pattern

	The solution is not shown on the stones themselves.

	It is hinted by :
* The position of surrounding trees
* The way light/shadows fall through the canopy
* Natural alignment in the environment

	This is a pure observation and logic puzzle.

---

		2. Trigger Conditions

* Player enters the Forest Glade
* 25% chance this mini-event becomes active (mutually exclusive with other events)
* Stones appear as ordinary mossy rocks until interacted with
* Only one player can have the puzzle active at a time
* Event duration : 8 minutes

	When active :
* Slight ray-of-light shafts become more visible through trees
* Birds go quiet in the immediate area
* A faint low hum can be heard when near a correct stone

---

		3. Stone Marker Setup

	There are 4 Stone Markers placed in a rough circle.

	Each stone has :
* Moss layer (must be cleaned first)
* A carved symbol hidden beneath
* Ability to be rotated in 4 directions (N/E/S/W)

	Possible symbols example set :
* Spiral
* Branch
* Eye
* Wave

(You can theme symbols later in art pass.)

---

		4. Player Interaction Flow

	Step 1 — Discovery
	Player interacts → "Clean Moss" action.

* Moss fades
* Symbol revealed
* Stone becomes rotatable

	Step 2 — Observation Phase
	The correct orientation is hinted by environmental clues :
* Tree branches form shapes matching symbols when viewed from certain angles
* Shadow cast from canopy points toward correct facing direction
* When standing at center of stones, correct alignment subtly “makes sense” visually

	No UI hint is provided.

	Step 3 — Rotation
	Player rotates stones.

	Each wrong full configuration attempt triggers feedback.

---

		5. Feedback System

	Incorrect full alignment :
* Stones emit dull thud sound
* Moss begins to regrow slightly
* Low rumble
* Player receives minor stagger (flavor feedback)

	Partially correct alignment :
* One or two stones emit faint glow in cracks
* Soft vibration sound

	Fully correct alignment :
* All stones glow through cracks
* Ground roots retract slightly
* Light beam briefly shines in the center
* Hidden NPC spawns

---

		6. Failure & Reset

	Event resets if :
* Player leaves Glade
* Time expires
* Player dies
* Player brute-forces rotations too quickly (anti-spam : stones temporarily lock for 10 seconds)

	After reset, stones return to moss-covered state.

---

		7. Success Outcome

	When all stones are correctly aligned :
* Ground in the center clears of leaves
* Ancient symbol briefly appears on the soil
* Hidden NPC spawns
* Player receives the buff

---

		8. Buff Reward (for your Buff file)

* NAME : Memory of the Old Paths
* How to get : Align the stone symbols correctly
* Effect :
	* +12% stamina efficiency (climbing/running)
	* Fall damage reduced
	* +5% dodge chance
* Duration : 20 minutes
* Suffer Debuff : –10% attack speed (careful movement mindset)
* UI Icon : Carved stone rune
* Flavor : "You remember paths you’ve never walked."
* Environmental & Gameplay Interaction :
	* Helps in cliffs, ramps, vertical traversal
	* Strong synergy with island terrain and vertical design

---

		9. Design Purpose

	This event teaches players :
* To read the environment as a hint system
* That nature itself contains clues
* That patience and positioning matter more than speed
* To look up, not just around

