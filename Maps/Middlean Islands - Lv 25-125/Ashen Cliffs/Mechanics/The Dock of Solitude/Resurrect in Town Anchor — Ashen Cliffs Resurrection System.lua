			Resurrect in Town Anchor — Ashen Cliffs Resurrection System

	The "Dock of Solitude" is the primary resurrection hub of the entire island.
	There are no alternative "town" anchors.

---

	Core Rule : 

	When a player dies on Ashen Cliffs :

1. If the player selects "Resurrect in Town" :
	→ They are teleported to "The Dock of Solitude"

2. Exception:
	If the player dies within proximity radius of "The Sunken Encampment" :
	→ They resurrect at the Encampment’s fixed respawn location

	There are no taverns.
	There are no secondary town hubs.

---

	1. Dock Resurrection Spawn Logic

	Unlike traditional fixed respawn points, the dock uses a distributed spawn system.

	Mechanic : 
* When resurrecting at the dock :
	* Player is spawned at a randomized location within the dock’s safe radius
	* Spawn points include :
		* Near moored boats
		* Beside cargo crates
		* At the end of the pontoon
		* Near the warehouse edge
		* Beside rope posts or lantern pillars

	The system selects randomly from approved safe coordinates.

	Why Random?
* Prevents corpse camping patterns
* Avoids player stacking on one spot
* Makes resurrection feel natural, not mechanical
* Adds slight immersion: “you were brought ashore”

---

	2. Sunken Encampment Override Rule

	If death occurs within the Encampment zone :
* Player respawns at a single, fixed camp spawn point
* No randomness there
* Represents local civilian aid / field medical support

	This creates :
* Logical world consistency
* Clear distinction between :
	* Military port authority (Dock)
	* Civilian settlement support (Encampment)

---

	3. Safe Radius System (Hard Protection Zone)

	The dock area is a "Hard Safe Zone".

	Inside this radius :
* No hostile spawns
* No patrol routing allowed
* No environmental hazards (fall damage zones excluded from spawn points)
* No aggro can cross boundary
* Kited enemies instantly reset at edge

	This ensures :
* Resurrected players are never killed instantly
* Dock remains psychologically stable

---

	4. Combat State Handling on Resurrection

	Upon resurrection at dock :
* Player HP/MP restored to base resurrection values
* Combat state cleared
* All enemy aggro wiped
* Environmental DoTs removed

	This ensures no delayed-death scenarios.

---

	5. Narrative Framing of Resurrection

	The dock is framed as :

> The last stable connection between Ashen Cliffs and the outside world.

	Repeated deaths reinforce :
* The island is dangerous
* You always fall back to civilization
* The dock becomes familiar and emotionally grounding

	The more punishing Fort Mirath becomes,
the more meaningful the dock feels.

---

	6) Anti-Exploit Layer

	To prevent abuse :
* Players cannot intentionally kite mobs toward dock to force resets repeatedly
* If a player enters safe radius while in combat :
	* Enemies reset
	* Player cannot re-engage enemies from inside safe zone

	Prevents edge abuse farming.

---

	7. System Impact on Island Design

	Because this is the only resurrection anchor :
* Travel time after death matters
* Players mentally map the island from dock outward
* The dock becomes the true Level 45–70 reset anchor

	It reinforces the island structure	:

	Dock → Exploration → Encampment → Watcher’s Perch → Fort → Death → Dock

	The loop is clean.

