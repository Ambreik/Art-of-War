			Safe Zone Behavioral Shift

	Inside the dock radius, the game subtly changes tone.

	Mechanic :
* Weapons auto-sheathe after a few seconds
* Combat music fades
* NPC idle chatter audible
* Ambient sounds: water, ropes, wood creaking, gulls

	Purpose :
* Player decompresses mentally
* Contrast with the rest of Ashen Cliffs tension
* Reinforces feeling of refuge

