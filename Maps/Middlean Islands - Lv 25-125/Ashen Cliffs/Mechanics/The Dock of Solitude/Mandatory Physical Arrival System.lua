			Mandatory Physical Arrival System (No Teleport Entry)

	This dock is the only legal world entry point to "Ashen Cliffs".

	Mechanic :

* Players cannot teleport directly onto the island
* Fast travel / teleport to Ashen Cliffs is disabled unless :
	* Player is using approved naval transport routes

	Purpose :	
* Makes the island feel remote and intentional
* Reinforces “you came here by choice, not by map click”
* Gives narrative weight to arriving on "Ashen Cliffs"

