			Recovered Supply System

* POI : The Sunken Encampment
* Primary NPC : Commander (storyline)
* Secondary NPCs : Vendor, Miner, Herbalist
* Linked POI : Fort Mirath
* Linked Questline : Commander Edran Holt chain

---

		Core Concept

	During island exploration and Mirath-related quests, players recover :
* Supply crates
* Salvaged materials
* Stolen logistics
* Wreckage resources

	These items are NOT immediately usable.
	
	They must be registered at the Encampment.

> The camp acts as a field logistics checkpoint for the island campaign.

---

	What This Mechanic Achieves : 

✔ Forces player to physically return to camp
✔ Creates risk while transporting supplies
✔ Links exploration to faction progression
✔ Makes the camp feel like a military operation, not a rest area
✔ Connects Mirath story to gameplay loop

---

	Part 1 — Supply Crate Types (found in world / quests)

	Players may find or be tasked to recover crates such as :
* Food Rations Crate
* Weapon Shipment Crate
* Herbal & Alchemy Pack
* Salvaged Tool Crate
* Medical Supply Box
* Sealed Military Parcel (rare)

	Some crates are :
* Trapped
* Decoys
* Empty
* Corrupted by Forsaken

	Player must identify the correct ones.

---

	Identification Mini-Interaction

	Before picking up :
* Inspect crate
* Visual hints (markings, smell, sounds, leakage, symbols)
* Wrong guess may :
	* Trigger trap
	* Spawn enemies
	* Apply poison cloud
	* Alert nearby mobs

	This adds tension and observation.

---

	Part 2 — Carrying the Crate (Core Risk Mechanic)

	Once picked :
* Player gains status : "Carrying Supplies"

	Effects :
* –30% movement speed
* Cannot climb
* Cannot stealth
* Cannot mount
* Visible to enemies from slightly increased range
* If player dies → crate drops on ground

	This creates escort-yourself gameplay through hostile terrain.

---

	Part 3 — Registering at the Encampment

	At the camp, interacting with a "Supply Log Table" near the Commander :
	Player "logs" the crate.

	Only after this :
* Items inside become usable
* Quest progresses
* Reputation is awarded

---

		Reputation Integration

	Registering supplies grants REP with :

	1. Player Main Faction
* "Dendera" (Knights)
* "Zonen" (Pindar)

---

	2. Middlean Capital Military Authority (new faction)
* "Middlean Vanguard Accord"

> The organized military and expedition authority operating from "Capital City", responsible for island operations, logistics, and Mirath campaign.

---

		📈 REP Rewards Examples

| Crate Type             | Main Faction REP | Vanguard Accord REP |
| ---------------------- | ---------------- | ------------------- |
| Food Rations           | Small            | Medium              |
| Weapon Shipment        | Medium           | Medium              |
| Herbal Pack            | Small            | Small               |
| Medical Box            | Medium           | High                |
| Sealed Military Parcel | High             | High                |

---

	Part 4 — Why Registration Matters

	Until registered : 
* Herbs inside cannot be used for crafting
* Ores cannot be refined
* Medical supplies unusable
* Quest flags don’t trigger

	This prevents "loot and ignore camp".

---

	Part 5 — Direct Link to Fort Mirath Quests

	Some Mirath quests from Commander Edran Holt require :

> "Recover 3 weapon crates and register them at the encampment."

	This forces : Mirath ➜ wilderness ➜ Encampment ➜ back to Mirath

	A living war supply line.

---

		Environmental Integration

	While carrying crate:

* Traps from forest glade become more dangerous
* Predator lair becomes higher risk
* Players must choose safer paths
* Archer Support Mechanic becomes very valuable here

	This beautifully connects previous mechanics.

---

		Supply Log Table (object)

	A small interactable object near Commander tent :
* "Register Recovered Supplies"
* Plays writing/logging animation
* Crate disappears
* Rewards granted

---

		Player Experience Loop

1. Player finds crate in world or quest
2. Identifies correct one
3. Picks up → becomes vulnerable
4. Navigates hostile terrain carefully
5. Reaches camp
6. Registers → rewards + REP + quest progress

	This is gameplay, not delivery.

---

		Why This Mechanic Is Powerful

	It turns:

> "Bring me 5 items"

	into

> "Survive a hostile island while transporting critical war supplies"

	That’s memorable gameplay.

---

		✅ System Rules

* Only 1 crate can be carried at a time
* Crates despawn if left too long
* Some crates spawn only during certain quests or tide cycles.

