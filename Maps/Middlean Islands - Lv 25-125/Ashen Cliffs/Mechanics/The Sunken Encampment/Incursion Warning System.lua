			Incursion Warning System

		The Sunken Encampment — Dynamic Defensive Event

	This system creates living tension between the camp and the nearby presence of the "Forsaken Pirates", without turning the camp into a battlefield or a 
destructible area.

	It is a controlled, narrative combat event that can occur :
* On a timer (world cycle / tide cycle)
* When X players are present in the camp
* When players progress certain Mirath-related quests
* Or randomly at low probability during the day

---

	Event Trigger Conditions (any can trigger) : 

1. 2–5 players inside camp radius
2. Player recently returned from "Fort Mirath"
3. Certain supply recovery quests active
4. Tide cycle / time-of-day check
5. Low random chance fallback

---

#	Phase 1 — Warning State (20–30s)

	What happens :
* Distant horn sound from cliffs
* NPCs stop idle behavior
* Commander shouts warning line
* Subtle red UI edge pulse for players in camp
* Text: "Forsaken movement detected near the perimeter!"

	This is pure tension-building.

---

	Phase 2 — Defensive State Activated

* Camp enters "Defense Mode"
* NPCs move to predefined positions :
	* Archer → elevated crate / rock position
	* Soldiers → gate-side cover
	* Commander → central command stance
* Players are not forced to participate, but can.

> No enemies enter the Safe Zone.

	Instead :
* 3–6 Forsaken mobs spawn outside the camp boundary
* They attempt to approach but are held at perimeter line
* Archer NPC begins cover fire mechanic (ties with Mechanic 4)
* Occasional projectile lands inside camp (visual pressure only)

---

		Player Involvement (Optional)

	Players may :
* Step outside boundary and fight
* Stay inside and watch NPCs handle it
* Assist from inside with ranged attacks

	If players do nothing → NPCs win slowly.
	If players help → event resolves faster.

---

	Duration : 

~90 seconds to 2 minutes.

---

		Resolution States

	If Forsaken are defeated :
* Commander thanks players
* Small chance to drop :
	* Supply crate
	* Ledger fragment
	* Minor crafting materials

	If time expires (NPCs handle it) :
* No loot
* Just narrative flavor

---

		Hidden Purpose

	This mechanic :
* Reinforces that the camp is under constant threat
* Makes the world feel alive
* Links :
	* Archer mechanic
	* Supply system
	* Mirath storyline
* Teaches players the camp perimeter boundary naturally

---

	Technical Boundaries : 

| Rule                      | Behavior             |
| ------------------------- | -------------------- |
| No PvP                    | Enforced             |
| No enemy enters safe zone | Hard boundary        |
| No camp destruction       | Visual-only pressure |
| No quest failure          | Pure event           |

