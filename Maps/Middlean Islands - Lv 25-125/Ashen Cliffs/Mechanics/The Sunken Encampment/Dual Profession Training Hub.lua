			Dual Profession Training Hub

* POI : The Sunken Encampment
* *NPCs Involved :
	* Miner Trainer (Ore / Mining)
	* Herbalist Trainer (Herb / Gathering)

---

		System Summary

	This mechanic defines how profession progression and resource gathering is enhanced by the trainers inside the safe zone through :
✔ In-field training
✔ Bonus yield mechanics
✔ Profession milestone triggers
✔ Learning unlocks tied to camp progression

	This makes professions feel strategic and tied to exploration, not static skill menus.

---

		Core Mechanic Goals

1. Profession unlocks occur through trainers in the field
	Not just UI selection — players must visit the encampment to unlock higher tiers.

2. Nearby resource gathering bonus
	When gathering specific island resource nodes within a radius of the encampment, players receive bonus productivity.

3. Profession quests and progression tie-ins
	Trainers can give short gathering / refinement quests that :
		* teach mechanics
		* distribute useful items
		* unlock further profession options

---

		System Components

	1. Field-Based Training Unlocks

	When a player interacts with the miner or herbalist trainer :
* They may unlock new gathering skills
* They may unlock node tracking benefits
* They can learn advanced techniques

	Unlike static UIs, this requires :

✔ Physical presence in the encampment
✔ Completion of trainer-issued gathering quests
✔ Meeting certain profession prerequisites

---

	2. Resource Yield Bonus

	Players receive a passive bonus when harvesting resources within the encampment’s influence zone(camp interior + immediate exterior field, e.g., 20–30m radius).

	This includes :
* Increased drop counts
* Increased chance of rare node yield
* Increased chance of bonus nodes spawning

	Example effect :
* Within camp influence :
	* +10% ore yield
	* +12% herb yield
	* Slight increased chance for rare nodes (Mistveil, Cascade Veinstone, Abyssal Glassfin spawn triggers, etc.)

	These buffs are not permanent outside encampment influence — they are region-tied.

---

	3. Trainer Quest Unlocks

	Both trainers can give short, repeatable, or one-time tasks such as :
* Collect 10 Cascade Veinstone samples
* Gather 5 Mistveil Fern bundles
* Refine 3 Saltstone Ores using the camp’s portable forge

	These quests :
🔹 Teach gathering mechanics
🔹 Provide direct practice of skill mechanics
🔹 Unlock new recipes or tools

---

		Trainer Progression Tiers

	The trainers offer tiered learning paths :

	➤ Tier 1 — Basic Tools & Techniques

	Unlocked freely upon first interaction

	Examples :
* Basic pick-axe handling technique
* Herb identification basics

---

	➤ Tier 2 — Intermediate Proficiency

	Requires completion of short trainer task
	
	Examples :
* Efficient mine rock fracture technique
* Recognizing rare herb clusters

---

	➤ Tier 3 — Advanced Expertise

	Unlocks after profession quests + encampment progression flags
	
	Examples :
* Enhanced vein targeting methods
* Environmental herb flow mapping
* Ability to identify hidden rare nodes in nearby forests/caves

	This is where the system feels rewarding and networked.

---

		Skill Unlock Example

	For Herbalist Trainer :
* "Identify rare herb nodes (Mistveil, Drownroot)"
* "Locate hidden herb nests after completing glade events"

	For Miner Trainer :
* "Break Cascade Veinstone faster"
* "Higher yield chance for Saltstone Veins near waterfalls"

---

		Integration With Other Island Systems

	This mechanic also connects to :
✔ Secret Location resources (rare node availability)
✔ Tide Reset Influence (some node respawns tied to tide)
✔ Ranger quests (Sylvaris’ tracking might hint rare herb sites)

	This allows profession work to feel connected, not isolated.

---

		System Rule Safeguards

	Profession bonuses do not stack infinitely :
* Only one encampment bonus can apply at once
* If the player moves outside influence, bonus fades
* Higher-tier profession tool abilities require active unlock

	This prevents farming exploitation and keeps motivation to return.

---

		Player Experience Loop

1. Player arrives from dock → safe zone triggers
2. Visits trainers → unlock basic gathering techniques
3. Takes trainer quest → has purpose, direction
4. Ventures out → uses new skills
5. Returns → gets additional unlocks / quests

	This recursively ties exploration, gathering, and camp progression.

---

		Unlock Narrative Flavor Lines

	Trainer NPCs can say things like :

	Herbalist :

> "The forest yields what it trusts… you just need the right touch."
> "I can teach you to see herbs others walk past."

	Miner :

> "Veinstone fractures whisper before they break… listen."
> "Saltstone Veins like water, but speak louder."

	These fit with their personality files already present.

---

		Summary

	The "Dual Profession Training Hub" mechanic :
✔ Makes profession training spatial and interactive
✔ Gives visible benefit when gathering nearby
✔ Ties into game progression explicitly
✔ Scales with player investment and exploration

