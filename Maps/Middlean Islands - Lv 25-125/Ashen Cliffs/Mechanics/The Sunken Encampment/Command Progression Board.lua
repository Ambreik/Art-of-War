			Command Progression Board

* POI : "The Sunken Encampment"
* Primary NPC : "Commander of the camp"
* Narrative Target : "Fort Mirath"

---

		Purpose

	This is not just a quest giver.
	This is the strategic brain of the island.

	The board visually and mechanically communicates :

> “" are part of an ongoing military operation against Fort Mirath."

	It connects :
* Story quests
* Side objectives
* Exploration progress
* Other POIs and Secret Locations
* Player discoveries across the island

	Into one visible war effort.

---

		Core Concept

	A physical board near the Commander containing :
* Maps
* Notes
* Marked locations
* Reports from scouts
* Symbols indicating progress

	Players interact with the "Board", not directly with the Commander for everything.

	The Commander becomes the voice.
	The Board becomes the system.

---

		What the Board Tracks

	1. Main Storyline Track — "Assault on Fort Mirath"

* Shows current phase of operations
* Unlocks primary chain quests
* Visually updates as player progresses

	Examples of visual changes :
* New red markings on the map
* Crossed-out enemy patrol routes
* Notes pinned over time

---

	2. Regional Objectives — "Forsaken Activity"

	Tracks player actions across the island such as :
* Clearing specific enemy camps
* Discovering secret locations
* Completing ranger / glade / cave / dock related content
* Recovering supplies

	These are not quests, but logged accomplishments.
	When enough are completed → new quests unlock.

---

	3. Exploration Flags

	The board reacts when the player has :
* Found certain secret POIs
* Met hidden NPCs (like Sylvaris)
* Survived certain mini-events
* Killed certain elite creatures

	The player never sees this as a checklist.

	They see :

> "New report added to the board."

---

		Unlock Logic

	The Board enables chain quest availability based on :

| Player Did            | Board Reaction      | Result                     |
| --------------------- | ------------------- | -------------------------- |
| Explored glade        | Ranger note pinned  | Tracking quest unlocks     |
| Cleared cave predator | Warning removed     | Supply route quest unlocks |
| Found hidden NPC      | Scout report added  | Dialogue options change    |
| Killed many Forsaken  | Red markers reduced | Assault prep quest unlocks |

---

		Why This Is Powerful

	Without the player realizing:
	You connect all island content into a single narrative system.
	Nothing feels random anymore.
	Everything feels like it contributes to the war effort.

---

		Commander Interaction Layer

	When interacting after Board updates, the Commander comments based on Board state :

* "I see you’ve been busy in the forest."
* "Reports say the western cliffs are quieter lately… your doing?"
* "Good. This gives us an opening toward Mirath."

---

		Visual Evolution Over Time

	The board is never static.

	It evolves as the player progresses :
* More notes
* More markings
* More urgency
* More clarity toward final objective

	By late progression, the board looks chaotic and intense.

---

		Player Experience

	Player feels:

> "My actions matter. The island is reacting."

	Instead of:

> "I’m doing unrelated quests."

---

		Important Design Rule

	This Board does not give rewards.

	It gives :
* Access
* Context
* Direction

	The rewards come from the quests it unlocks.

