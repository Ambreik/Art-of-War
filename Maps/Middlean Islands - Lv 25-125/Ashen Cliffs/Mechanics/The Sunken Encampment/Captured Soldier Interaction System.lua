			Captured Soldier Interaction System

* Type : Cross-location narrative & quest unlock system
* Primary Locations :
	* Captured Soldier → Fort Mirath
	* Commander → Sunken Encampment

---

		Core Concept

	The soldier is :

> A living intel source trapped behind enemy lines.

	He is not just a quest NPC.
	
	He is a dynamic story flag holder whose dialogue and usefulness change depending on :
* Player progress in Mirath Fort
* Supplies registered at the Encampment
* Quests completed for Commander

---

		The Hidden Link

	The player never fully understands Mirath from the Commander alone.

	The Commander has strategy.
	The Soldier has reality.

	You must talk to both to piece together truth.

---

		What This Mechanic Achieves

✔ Forces player to revisit Mirath multiple times
✔ Makes the soldier relevant before and after rescue
✔ Creates optional quest branches (rescue vs intel)
✔ Deepens Forsaken narrative without cutscenes
✔ Connects Encampment progression to Mirath infiltration

---

	Phase 1 — Before Any Rescue Attempt

	When player first reaches the soldier in Mirath:

	He provides "Intel Fragments".

	Short pieces of information such as :
* Supply routes used by Forsaken
* Weak patrol times
* Hidden paths
* Warnings about traps
* Mention of stolen crates (ties to Recovered Supply System)

	These are not quests yet. They are hints.

---

		Intel Fragments Unlock Things Back at the Encampment

	After hearing certain intel lines, new dialogue appears at Commander:

> "A soldier mentioned weapon crates being moved through the eastern ridge…"

	This unlocks :
* New supply recovery quests
* New Mirath objectives
* Optional side missions

	The soldier indirectly expands the Commander’s quest board.

---

	Phase 2 — Optional Player Choice

	After enough interactions, player can choose:

* Option A — Leave him, keep gathering intel

You continue receiving hints over time.

* Option B — Start a Rescue Plan

	This unlocks a special Mirath quest chain from Commander.

	This is optional, not mandatory for storyline.

---

	Phase 3 — Dialogue Evolution Based on Progress

	The soldier’s dialogue changes depending on :

| Player Progress                     | Soldier Behavior                  |
| ----------------------------------- | --------------------------------- |
| First visit                         | Weak, desperate, confused         |
| After some supply crates registered | More hopeful, gives clearer intel |
| After Mirath objectives done        | Talks about internal structure    |
| After rescue quest accepted         | Urgent, tactical, precise         |

	He feels alive in time.

---

		Post-Rescue Outcome (later usage)

	If player rescues him :
* He relocates to the Encampment.

	Now he becomes :
* Secondary quest giver
* Provides unique Mirath aftermath quests
* Comments on player achievements
* Interacts with Commander in dialogues

* If not rescued :
	* He remains intel source forever.

	Both paths valid.

---

		Gameplay Loop Created

1. Player explores Mirath
2. Finds soldier
3. Learns intel
4. Returns to Encampment
5. New quests unlock
6. Player goes back better prepared

	This is a living information loop between POIs.

---

		Why This Mechanic Is Powerful

	Was turned a “trapped NPC” into :

> A narrative relay system between two major POIs.

	Without cutscenes. Without forced story.

	Purely through player curiosity.

---

		System Flags (behind the scenes)

	The game tracks :
* Times spoken to soldier
* Intel fragments heard
* Supplies registered
* Mirath quests completed
* Rescue decision

	These flags control his dialogue tree.

---

		Natural Synergy With Previous Mechanics

	This mechanic ties into :
* Recovered Supply System
* Command Progression Board
* Archer Support (for rescue quest later)
* Tide Reset (some dialogues only at certain times later)

