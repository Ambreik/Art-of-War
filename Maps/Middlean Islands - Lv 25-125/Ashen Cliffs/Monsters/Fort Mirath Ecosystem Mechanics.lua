			Forsaken Band — Internal Military Hierarchy (Traitor Faction Ecosystem)

	This is a rank-based monster structure, not NPC society.
	They are "human enemies" functioning as a corrupted military occupation force.

---

	1. Base Labor Class (Lowest Tier)

	Supply Thralls / Laborers : 
* Unarmored or lightly armored workers
* Carry crates, ammo, tools, supplies
* Move between storage zones, cannons, and inner halls

	Role in ecosystem :
* Fortress logistics backbone
* Populate courtyards and corridors during "calm state”
* Become chaotic during combat

---

	Forge Assistants : 
* Maintain weapons, cannons, armor racks
* Work near artillery zones or inner storage halls

	Role :
* Sustain war machine infrastructure
* Natural presence near cannons and supply routes

---

	2. Basic Combat Units (Core Occupation Force)

	Militia Cutthroats : 
* Primary melee enemies
* Poor discipline individually, but dangerous in groups
* Patrol courtyards and hallways

	Role :
* Main bulk of fortress combat population
* First responders in combat

---

	Shield Guards : 
* Defensive infantry units
* Used in chokepoints, gates, stair entrances

	Role :
* Form defensive walls during Alarmed state
* Anchor vertical choke control

---

	Archers / Ranged Marksmen

* Stationed on :
	* walls
	* towers
	* rooftops

	Role :
* Provide vertical pressure
* Force players into cover zones

---

	3. Specialized Tactical Units

	Scouts : 
* Light armor, high mobility
* Patrol outer walls, rooftops, and crumbled tower zones
* Detect intruders early

	Role :
* Early detection layer of fortress AI
* Trigger Suspicious state escalation

---

	Trap Wardens : 
* Assigned to corridor control zones
* Patrol near pressure plates, arrow slit corridors

	Role :
* Ensure trap systems remain active
* React to intrusions in interior layers

---

	4. Heavy Support Units

	Cannon Operators : 
* Stationed at artillery positions
* Prioritize cannon usage in Alarmed state

	Role :
* Area denial through siege weapons
* Control courtyards and gates

---

	Iron Breakers (Heavy Infantry) : 
* Slow, heavily armored units
* Guard gates, main entrances, chokepoints

	Role :
* Prevent brute-force entry
* Stabilize defensive lines during chaos

---

	5. Command Layer (Leadership System — your existing mechanic anchors)

	These are NOT just bosses — they are system controllers

	Fortress Commanders (Trait Leaders)

	Each governs a system :
* Wall & Tower Command (vision + ranged discipline)
* Gate & Courtyard Command (melee coordination + shield formations)
* Interior Hall Command (trap response + corridor control)
* Reinforcement Command (spawn logic + deployment routes)

	Role :
* Maintain fortress coordination (your leadership degradation mechanic)
* Their removal weakens AI structure

---

	6. Elite Field Operatives (Rare Units)

	Executioners : 
* High-damage melee units
* Appear in Alarmed state or leadership zones

	Veteran Marksmen : 
* Superior ranged units
* Control rooftop and tower dominance zones

	Enforcers : 

* Mid-boss tier units
* Assigned to leadership wings or key chokepoints

