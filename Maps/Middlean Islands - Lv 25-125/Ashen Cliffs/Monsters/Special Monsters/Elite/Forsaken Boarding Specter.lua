			Forsaken Boarding Specter

---

		1. Basic Information

* Name : Forsaken Boarding Specter
* Type : Human (Elite)
* Rank : Rank III
* Level : 66
* Role : Skillable / Ranger / Add Controller / Ambush Unit
* Location : Sunken Ship – "The Forsaken Vessel" (deck wreckage + surrounding water + shoreline transition zone)

---

		2. Appearance

	A half-submerged Forsaken boarding soldier preserved by saltwater exposure and dark enchantment residue from the shipwreck. His armor is fragmented naval 
boarding gear, layered with rope bindings, rusted hooks, and cracked leather plating.
	His face is partially visible beneath a broken breathing mask used for underwater boarding operations. Sea growth clings to his limbs, and spectral water trails
follow his movements when he shifts between surfaces.

	He carries :
* A hooked harpoon blade (used for pulling targets)
* A compact signal horn corrupted by Forsaken energy (used for summoning allies)

	Unlike the Semi-Boss, this entity feels less anchored to the wreck and more like an active patrol remnant.

---

		3. Combat Behavior & Mechanics

	General Role

	"The Forsaken Boarding Specter" is a combat disruptor unit designed to :
* Break player positioning
* Summon reinforcements
* Force multi-target decision making

	He operates between water and shipwreck surfaces and actively reacts to player movement patterns.

---

	Phase 1 — "Boarding Protocol Active" (100%–65%)

* "Harpoon Pull" : Long-range grab pulling players into melee range
* "Deck Flank" : Rapid repositioning between wreck edges
* "Signal Burst" : Calls in 1–2 Forsaken Add Units (Rank I soldiers or drowned crew remnants)
* "Marked Target" : Applies debuff increasing damage taken from all sources

	Behavior : Circles shipwreck perimeter, avoids direct tanking

---

	Phase 2 — "Routed Engagement" (64%–0%)

* "Chain Hook Combo" : Repeated pull + strike sequence
* "Tactical Retreat" : Brief underwater dive to reposition and reset aggro angle
* "Call of the Forsaken" : Spawns additional adds (higher frequency than Phase 1)
* "Pressure Dive Strike" : Emerges from water beneath player position for burst damage

	Behavior : Becomes highly mobile, constantly shifting between water surface and wreck edges

---

	Special Mechanic — Shoreline Lure Transformation
* If the Forsaken Boarding Specter is pulled or baited fully onto land :

	Transformation Event — "Dry Dock Instability"
*  His aquatic boarding adaptations fail, and his combat style shifts.

---

	Land Combat Changes

* Loses :
	* "Harpoon Pull" (water-based displacement reduced)
	* "Dive Strike" (water-only ability)
* Gains :
	* "Hooked Rush" (straight-line charge attack)
	* "Anchor Trap" (ground snare zones using chain hooks)
	* "Fractured Signal Call" (summons weaker but faster add waves)
* Becomes faster in short bursts but easier to predict

---

		4. Add System (Core Mechanic)

	This Elite is designed around controlled reinforcement spawning :

	Add Types : 
* Forsaken Deckhand (Rank I melee pressure unit)
* Drowned Rifleman (Rank II ranged harassment unit — rare spawn)

	Add Behavior : 
* Spawn near wreck edges or water surface
* Prioritize attacking isolated players
* Disappear if Elite is killed or too far from combat zone

---

		5. Environmental Interaction

* Wreck hull provides vertical combat layers
* Waterline determines ability availability
* Add spawns increase if fight stays in central wreck zone too long
* Shoreline transition creates tactical shift in fight pacing

---

		6. Combat Identity

	This Elite is designed to :
* Break formations
* Punish stationary gameplay
* Force awareness of vertical + water boundaries
* Act as a combat pressure layer before or during Semi-Boss engagement

