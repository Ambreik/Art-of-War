			Gatebreaker Captain

---

		1. Basic Information

Name : Gatebreaker Captain
Type : Human
Rank : Elite
Role : Gate Defense Anchor / Frontline Stability Unit
Location : Fort Mirath — Main Gate Inner Defense Line

---

		2. Appearance

	A heavily armored fortress captain clad in reinforced gate-defense plate armor designed specifically for impact resistance and frontline blockade. The armor is 
bulkier than standard military units, with layered steel reinforcement across the chest and shoulders, visibly scarred from repeated siege impacts.	The shield is 
oversized and reinforced with iron bands, designed not only for blocking attacks but also for physically crushing and redirecting enemy formations. His stance is 
permanently forward-leaning, as if constantly bracing against a siege that never ends. The helmet is fully enclosed with a reinforced visor slit, giving him a 
faceless, immovable presence at the gate line. Every movement produces heavy metallic impact sounds, reinforcing his role as a living barrier rather than a mobile 
soldier.

---

		3. Core Identity

	The Gatebreaker Captain is the primary structural defense anchor of the fortress gate system.
	Unlike standard guards, he does not respond as part of patrol logic — he exists to prevent structural collapse of the gate defense line itself.
	When active, the main gate is treated as a sealed military pressure point, not an entry route.

---

		4. Behavior & Combat Role

	This is a solo elite anchor encounter.
	The Gatebreaker Captain remains stationed at the inner gate defense line and engages all intrusions directly.

	Core behavior rules :	
* Never abandons gate zone unless forcibly displaced
* Prioritizes blocking choke points over chasing targets
* Actively disrupts group movement through knockback control
* Gains defensive stability when surrounded by multiple enemies
* Escalates control abilities when HP drops

	Combat identity :
> Static frontline anchor designed to physically and mechanically seal fortress entry points

---

		5. Combat Mechanics

	Shield Wall State : 
* Gains increased damage reduction when blocking frontal attacks
* Reduces incoming damage significantly when positioned near gate structure

	Gate Control Pressure : 
* Applies knockback to prevent group stacking at entry points
* Uses Shield Crash to break formations (2s Stun)

	Defensive Escalation : 
* Below 50% HP: increased resistance and block efficiency
* Below 25% HP: becomes near immovable gate anchor with enhanced knockback

---

		6. Spawn System

* Spawn Type : Solo Elite Unit
* Spawn Location : Main Gate Inner Defense Line
* Respawn : Linked to fortress state cycle
* Cannot exist simultaneously with another instance

---

		7. Environmental Interaction

* Uses gate structure as defensive reinforcement point
* Converts choke points into controlled engagement zones
* Prevents bypassing of gate through direct combat pressure
* Strong synergy with wall and courtyard defensive systems

---

		8. Strengths

* Extremely strong chokepoint control
* High durability under focused pressure
* Strong anti-group formation disruption
* Excellent defensive anchoring

---

		9. Weaknesses

* Limited mobility outside gate zone
* Predictable positioning
* Weak against ranged spread pressure

