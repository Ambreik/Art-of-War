			War Overseer of Mirath

---

		1. Basic Information

Name : War Overseer of Mirath
Type : Human
Rank : Elite
Role : Command Control Anchor / Fortress Coordination Unit
Location : Fort Mirath — Inner Leadership Wings

---

		2. Appearance

	A high-ranking war commander adorned in refined but heavily reinforced command armor, distinct from frontline units. His armor is lighter than gate defenders 
but layered with tactical insignia plates, signaling authority rather than brute force protection. A long military coat flows beneath segmented armor plating, 
marked with chain insignias and command seals tied to fortress hierarchy systems. He carries a command blade and signal insignia tools rather than heavy weapons, 
emphasizing coordination over direct destruction. His presence is controlled and still — he does not move like a soldier, but like a system operator embedded inside
the fortress structure.

---

		3. Core Identity

	The "War Overseer of Mirath" is the central coordination anchor of the fortress military system.
	Unlike combat-focused elites, his existence maintains structured combat behavior across the entire fortress ecosystem.
	When active, fortress units operate with full coordination efficiency and tactical reinforcement logic.
	When removed, the fortress begins to lose structured combat behavior integrity.

---

		4. Behavior & Combat Role

	This is a solo elite anchor encounter.
	He remains inside leadership wings and commands battlefield logic rather than engaging as a frontline fighter.

	Core behavior rules :
* Does not engage in prolonged melee unless directly pressured
* Maintains aura-based control over nearby units
* Enhances allied combat efficiency passively
* Repositions allies tactically during combat
* Gains defensive awareness when allies are present

	Combat identity :

> System-level combat coordinator controlling fortress-wide engagement efficiency

---

		5. Combat Mechanics

	Tactical Command Aura : 
* Increases attack speed and defense of nearby units
* Enhances coordination between fortress groups

	Reposition Override : 
* Forces nearby allies to adjust positioning during combat
* Interrupts player formation advantages

	Fear Suppression System : 
* Prevents allied units from fleeing or breaking morale
* Maintains stable combat formation under pressure

	Collapse Sensitivity : 
* When defeated, nearby units temporarily lose coordination efficiency

---

