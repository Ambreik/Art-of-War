			Cursed Guards

---

	1. Basic Information

* Name : Cursed Guard
* Race : Human
* Type : Elite Add (Boss Phase Spawn)
* Rank : Rank III
* Role : Phase Pressure / Player Disruption
* Location : Spawned only during "Mirath" Phase 3 — Central Leadership Chamber, Fort Mirath

---

	2. Appearance

	"Cursed Guards" wear the decayed uniforms of Fort Mirath soldiers. Their armor is mismatched, corroded, and strapped together with rope and metal scraps. Pale 
cracked skin shows through gaps in their gear, and their eyes glow faint blue like Mirath’s — a sign of prolonged exposure to the Living Water.

	They carry :
* Rusted short swords
* Broken tower shields marked with the old coalition insignia, now scratched beyond recognition

	Their movements are stiff and unnatural, like soldiers still trying to obey drills they no longer remember.

---

	3. Behavior & Combat Role

	"Cursed Guards" exist to disrupt the group while "Mirath" enters his final aggressive state.
	They do not behave like normal elites found in the fort.
	They behave like bodyguards on last command.

	Combat Traits :
* Prioritize non-tank players
* Attempt to flank rather than face directly
* Stay within medium range of Mirath if possible

---

	4. Abilities

* "Shield Bash" — "Stun" (2 s) on close target.
* "Guard Intercept" — Moves quickly to a player targeting Mirath and applies "Slow" (40%, 3 s).
* "Broken Formation" — When both guards are alive, they gain +15% movement speed.

---

	5. Strengths

* Disrupt healers and ranged DPS
* Add pressure during Mirath’s healing-reduction phase
* Hard to ignore due to stuns and slows

---

	6. Weaknesses

* Moderate HP for Rank III
* No ranged abilities
* Lose effectiveness when separated

---

	7. Quotes

*(raspy, breathless, almost whispered — like soldiers repeating orders)*

* "Hold the line…"
* "Protect the Commander…"
* "No retreat… no retreat…"
