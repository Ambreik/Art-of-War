			Black Powder Duelist

---

		1. Basic Information

Name : Black Powder Duelist
Type : Human
Rank : Rare (World Rare Unit)
Role : Duelist / Cannon Zone Disruption Unit
Location : Fort Mirath — Cannon Platforms

---

		2. Appearance

	A heavily armored human duelist outfitted in modified fortress infantry gear, adapted for close-quarters combat on cannon decks.
	His armor is asymmetrical and battle-altered, with reinforced shoulder plating on one side and stripped-down mobility layers on the other to allow rapid turning
and lunging movements.
	The chestplate bears scorched powder marks and embedded metal fragments from repeated cannon misfires and close-range explosions, suggesting long-term exposure 
to artillery zones.

	He carries dual sabres with slightly curved blades, both dulled near the base from constant contact with metal deck plating and cannon structures.
	His movement style is unstable but precise — leaning forward aggressively when advancing, and pivoting sharply around cannon structures as if the entire 
platform is part of his combat rhythm.
	When idle, he often rests one blade against cannon edges or powder crates, visually reinforcing his dominance over the artillery space.

---

		3. Core Identity

	A former elite duelist embedded into cannon operations after losing formal rank status within the fortress hierarchy. Unlike standard infantry, this unit does 
not function as a guard or patrol element.
	It exists as a localized instability node inside artillery logistics zones, emerging unpredictably during operational cycles of the cannon platforms.
	When active, the cannon deck ceases to function as a safe logistics space and becomes a controlled combat arena.

---

		4. Behavior & Combat Role

	This is a solo rare encounter.

	The Black Powder Duelist does not patrol, but instead spawns into active cannon workflow zones and immediately enters combat awareness.

	Core behavior rules :
* Prioritizes isolated targets in cannon zones
* Ignores large groups unless directly engaged
* Forces 1v1 engagement patterns in tight deck geometry
* Escalates aggression as HP decreases
* Actively disrupts cannon operation flow by repositioning into operator paths

	Combat identity :

> Duel-focused melee disruption unit designed to break logistical stability

---

		5. Combat Mechanics

	Duel State Trigger : 
* Activates when engaged in combat for more than a few seconds
* Locks target focus on a single opponent
* Gains increased movement speed inside cannon platforms

	Berserk Scaling : 
* Below 70% HP: increased attack frequency
* Below 40% HP: major attack speed amplification
* Below 25% HP: aggressive gap-closing behavior increases drastically

	Execution Pressure : 
* Attempts to force players into narrow cannon walkways or edge zones
* Gains advantage when near environmental hazards (drops / cannon edges)

---

		6. Spawn System

* Spawn Type : Solo Rare Unit
* Spawn Location : Cannon Platforms only
* Respawn Window : 8–48 hours
* Spawn Condition : Randomized fortress operational cycle
* Cannot exist simultaneously with another instance

---

		7. Environmental Interaction

* Uses cannon structures as movement blockers and duel boundaries
* Gains positional advantage in narrow cannon walkways
* Can force players into open deck exposure zones
* Interferes indirectly with cannon usage by occupying operator paths

---

		8. Strengths

* High burst melee pressure
* Strong 1v1 control dominance
* Fast HP scaling aggression
* Excellent use of tight geometry environments

---

		9. Weaknesses

* Limited range capability
* Vulnerable when kited into open courtyard sightlines
* Loses efficiency against multi-directional pressure

