			Grate Horror Enforcer

---

		1. Basic Information

Name : Grate Horror Enforcer
Type : Human
Rank : Rare (World Rare Unit)
Role : Subterranean Hunter / Fear Pressure Unit
Location : Fort Mirath — Lower Holding Cells & Cliffside Grate Access

---

		2. Appearance

	A severely distorted human-shaped entity wrapped in fragmented prison armor and broken restraint chains fused into its body.
	Its limbs appear asymmetrically reinforced, as if multiple bindings were welded directly into flesh and armor over time, creating unnatural joint restrictions 
that do not stop movement but instead alter its motion patterns.
	The torso is covered in layered prison plating and iron shackles, some still partially embedded, suggesting long-term containment attempts failed or were 
repurposed into control mechanisms.
	Its face is partially obscured by a broken restraint mask, leaving only irregular gaps where breath and muffled sound escape, creating an unstable, unsettling
presence in enclosed corridors.
	When moving through narrow spaces, it does not walk normally — it drags and compresses itself through corridors with unnatural flexibility, as if the structure 
of the prison no longer applies to it.
	A faint trail of condensation and disturbed air follows it, especially near grated tunnel sections.

---

		3. Core Identity

	The Grate Horror Enforcer is a containment failure entity repurposed into an active enforcement anomaly within the lower fortress systems.
	It exists in areas where prisoners, interrogation zones, and cliffside access tunnels intersect — acting as both deterrent and execution pressure unit.
	Unlike standard guards, it does not maintain order through presence alone, but through psychological destabilization and forced retreat mechanics in enclosed 
environments.

---

		4. Behavior & Combat Role

	This is a solo rare encounter.
	It does not patrol predictable routes, but instead shifts between cell corridors and grate passages based on player proximity and combat noise.

	Core behavior rules :

* Prefers enclosed combat spaces (cells, tunnels, narrow halls)
* Actively isolates players from group formations
* Gains strength when players are in tight or low-visibility environments
* Punishes bleeding targets and prolonged close combat
* Repositions through grate-linked corridors unpredictably

	Combat identity :

> Ambush-based subterranean execution unit that weaponizes confinement

---

		5. Combat Mechanics

	Fear Pressure State : 
* Applies Fear (short duration) when first entering combat in enclosed spaces
* Increases aggression if players attempt to retreat through narrow corridors

	Vampiric Sustain : 
* Gains health from Bleed effects applied to targets
* Becomes more stable during prolonged melee exchanges

	Corridor Dominance : 
* Gains movement unpredictability in narrow passages
* Can re-engage from alternate grate-connected routes

---

		6. Spawn System

* Spawn Type : Solo Rare Unit
* Spawn Location : Lower Holding Cells / Cliffside Grate Access
* Respawn Window : 8–72 hours
* Spawn Condition : Random subterranean activity cycle
* Cannot exist simultaneously with another instance

---

		7. Environmental Interaction

* Uses prison corridors as forced engagement zones
* Gains advantage in enclosed spaces with limited escape routes
* Repositions through grate-linked tunnels to flank players
* Amplifies pressure in interrogation and cell zones

---

		8. Strengths

* Extremely strong in confined environments
* High sustain through Bleed interaction
* Unpredictable repositioning in underground layouts
* Strong isolation pressure on groups

---

		9. Weaknesses

