			Ironbound Sentinel

---

		1. Basic Information

Name : Ironbound Sentinel
Type : Human
Rank : Rare (World Rare Unit)
Role : Defensive Anchor / Wall Stability Unit
Location : Fort Mirath — Outer Wall Break Sections & Crumbled Tower Paths

---

		2. Appearance

	A towering heavily armored fortress unit encased in layered iron plating that has been repeatedly reinforced and welded over time.
	Its armor is not uniform — it is visibly patched, riveted, and structurally overbuilt, as if multiple generations of fortress engineers kept adding protection 
without replacing the core frame beneath.
	The helmet is fully sealed with only narrow horizontal vision slits, giving no visible facial expression. The head is slightly tilted forward, making it appear 
constantly braced against incoming force.
	Its arms are oversized compared to its torso, each reinforced with heavy iron bracing used for shield impact blocking and structural reinforcement against 
breaches.
	The boots are embedded with stone and metal mix, designed to anchor it firmly into broken wall terrain, preventing knockback or displacement.
	When it moves, it does not stride normally — it shifts weight like a moving siege pillar, dragging armor friction across stone surfaces.

---

		3. Core Identity

	The Ironbound Sentinel is a structural reinforcement unit, deployed in areas where the fortress wall integrity has been compromised or historically weakened.
Unlike standard guards, it does not patrol or respond dynamically — it is stationed as a living stabilization point for broken defensive architecture.
When active, destroyed wall sections and tower ruins are treated as defended territory nodes, not traversal paths.

---

		4. Behavior & Combat Role

	This is a solo rare encounter.
	The Ironbound Sentinel remains anchored near broken wall geometry and engages only when players enter its structural control zone.

	Core behavior rules :
* Does not chase far from wall breach zones
* Prioritizes pushing enemies away from wall edges
* Attempts to control narrow broken pathways
* Becomes increasingly resistant as HP drops
* Uses terrain as defensive advantage rather than mobility

	Combat identity:

> Static defensive anchor that turns broken terrain into a controlled kill zone

---

		5. Combat Mechanics

	Structural Anchor State : 
* Gains reduced damage while standing on rubble / broken wall zones
* Immune to most knockback effects
* Gains increased defense when multiple enemies are nearby

	Wall Control Pressure : 
* Actively pushes players away from breach points
* Uses terrain edges to force directional combat flow

	StoneSkin Reinforcement : 
* Below 50% HP: enters hardened state (damage reduction increases)
* Below 25% HP: becomes near immovable defensive core

---

		6. Spawn System

* Spawn Type : Solo Rare Unit
* Spawn Location : Outer Wall Break Sections / Crumbled Tower Paths
* Respawn Window : 12–72 hours
* Spawn Condition : Random fortress integrity cycle
* Cannot exist simultaneously with another instance

---

		7. Environmental Interaction

* Gains full advantage from broken wall geometry
* Converts rubble zones into defensive strongpoints
* Blocks traversal routes through wall breaches
* Punishes vertical movement attempts on damaged towers

---

		8. Strengths

* Extremely high durability in terrain zones
* Strong positional control
* High resistance to displacement mechanics
* Excellent anti-breach defender

---

		9. Weaknesses

* Limited pursuit capability
* Weak outside structural zones
* Predictable engagement patterns

