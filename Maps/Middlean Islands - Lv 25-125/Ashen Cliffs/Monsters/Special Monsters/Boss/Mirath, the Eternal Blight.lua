			Mirath, the Eternal Blight

---

		1. Basic Information

* Name : Mirath, the Eternal Blight
* Type : Human Boss
* Rank : Boss (Rank IV)
* Role : Fortress Command Entity / Multi-Phase Tactical Encounter
* Location : Central Leadership Chamber — Flooded Courtyard Basin, Fort Mirath
* Respawn Timer : 3 hours (real time)
* Recommended Group Size : Up to 5 players
* Aggro Range : Wide within courtyard perimeter; retreats if dragged too far into upper fort levels.

---

		2. Lore

	During the final years of the "Second Great War", Mirath was a high commander within the coalition forces. Tasked with guarding and transporting samples of the 
"Living Water" for study by the alliance leaders, he instead betrayed his oath.
	Mirath and several loyal officers stole portions of the "Living Water" and deserted the war effort, fleeing to a remote island where they constructed a hidden 
fortress — now known as "Fort Mirath".
	There, they drank from the stolen source.

	They did not gain youth.
	They did not gain peace.
	They gained **endless life inside bodies that continue to decay**.

	Over the century that followed, the fort did not fall.
	It did not change.
	It simply remained… occupied by soldiers who cannot die, who cannot leave, and who no longer remember what they were guarding.

	Mirath still commands.

	Not because there is a war.
	But because command is the only thing his mind has left.

---

		3. Appearance

	Mirath still carries the posture of a battlefield commander, but his body betrays the cost of immortality. His skin is pale and cracked like dried parchment, 
faint glowing veins visible beneath it — not from magic, but from the unnatural persistence of life in failing flesh. His eyes glow a dim blue haze, unfocused at 
times, as if he sees battles that no longer exist. He wears a ruined commander’s coat reinforced with scavenged armor plates from fallen soldiers of the fort. His 
right arm is wrapped in old iron prison chains, once used to bind traitors — now used by Mirath himself to stabilize his weakening limb.

	Weapons :
* "Runebound Sabre" — a heavy curved blade, corroded by time but still deadly.
* "Rusted Lasso Launcher" — a hybrid grappling device used to control enemies at mid-range.

	Every movement he makes feels forced, like a man whose body should have died decades ago but refuses to obey.

---

		4. Behavior & Combat Role

	Mirath is a three-phase tactical boss that mixes :
* Melee pressure
* Player reposition control
* Short ranged bursts
* Area denial
* Add pressure in final phase

	The fight reflects a commander losing control of both battlefield and his own body.

---

		5. Phase Structure

	Phase 1 (100%–70%) — Command of the Shore

	Mirath fights with discipline and structure.

	Abilities :
* "Cleave Strike" — Wide frontal AoE slash.
* "Anchor Pull" — Lasso pulls distant player and applies "Root" (3 s).
* "Roar of Defiance" — *Fear (2 s)* and 20% slow.

> Players learn positioning and control mechanics.

---

	Phase 2 (69%–35%) — The Cursed Persistence

	His body begins to fail. Movements become erratic.

	Abilities :
* "Living Surge" — Ground eruptions every 2 s for 10 s.
* "Blighted Armor" — 25% damage reduction for 8 s.
* "Rifle Burst" — Three shots; third has 25% chance to "Stun" (2 s).

> Alternating melee and ranged pressure with AoE management.

---

	Phase 3 (34%–0%) — Wrath of the Immortal

	Mirath abandons tactics and fights on instinct.

	Abilities :

* "Final Stand (30%)" — +10% attack speed, summons two "Cursed Guards".
* "Blight Overload" — Pulse every 20 s applying stacking –3% healing received (5 s).
* "Last Lunge (10%)" — Charge + heavy knockback.

> Chaos phase with add pressure and healing control.

---

		6. Environmental Interaction

* Water in the flooded courtyard ripples with each heavy strike.
* Loose debris and ruined stone act as natural obstacles during fight.
* If dragged too far from the basin, Mirath retreats and resets after 10 s.

	The environment is not magical — it is a ruined command courtyard turned battlefield.

---

		7. Strengths

* Strong reposition control
* Mix of melee and ranged pressure
* Healing denial in final phase
* Add pressure under stress

---

		8. Weaknesses

* Predictable patterns in Phase 1
* Vulnerable during Blighted Armor downtime
* Add phase can be controlled with coordination

---

		9. Group Composition

* 1 Tank recommended
* 1 Healer strongly recommended
* Add control in Phase 3 is critical

