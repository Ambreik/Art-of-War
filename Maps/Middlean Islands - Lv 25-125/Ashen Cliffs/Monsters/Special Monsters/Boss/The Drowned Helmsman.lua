			The Drowned Helmsman

---

		1. Basic Information

* Name : The Drowned Helmsman
* Type : Human (Semi-Boss)
* Rank : Rank III
* Level : 67
* Role : Tanky / Control / Area Denial (Water Combat Specialist)
* Location : Sunken Ship – "The Forsaken Vessel" (wreck interior + surrounding water zone)

---

		2. Appearance

	A once-naval officer fused with barnacle-covered armor and shattered shipwreck debris. His body is partially preserved but heavily waterlogged, with seaweed 
strands embedded into torn naval uniform.
	His helm is permanently sealed, filled with dark water that never spills. Chains and anchor fragments are fused into his torso, dragging behind him as he moves 
through water.
	One arm still holds a broken ship wheel segment used like a shield, while the other drags a rusted boarding blade.

---

		3. Combat Behavior & Mechanics

	General Role
* The Helmsman controls the wreck zone, using currents, debris, and water pressure to restrict player movement.
* Combat is primarily underwater but transitions if conditions are triggered.

---

	Phase 1 — "Sunken Command" (100%–60%)

* Tidal Pull : Creates localized water currents dragging players toward wreck center
* Anchor Slam : Heavy melee AoE that stuns briefly if players are close
* Barnacle Armor : Reduces incoming damage while near wreck structure
* Debris Drift : Floating wreck parts slowly orbit the combat area, damaging contact points

	Behavior : Stays close to shipwreck hull, never leaving central zone

---

	Phase 2 — "Rising Pressure" (59%–0%)

* Pressure Collapse : Periodic shockwave bursts pushing players outward
* Flood Surge : Expands water combat field (larger AoE zone)
* Drowned Grasp : Roots players underwater briefly using spectral chains
* Final Drift : Movement speed increases; becomes more aggressive and unpredictable

	Behavior : Starts breaking away from wreck structure, becomes less anchored

---

		Special Mechanic — Land Lure Transition

	If players successfully bait or push "The Drowned Helmsman" out of the water zone :

	Transformation Event — "Drying Curse"

* Armor cracks and hardens
* Water inside helm drains partially
* Gains **land-based movement form**

---

	Land Combat Changes

* Loses Tidal Pull and water control abilities
* Gains :
	* "Heavy Chain Swing" (knockback)
	* "Anchor Throw" (ranged pull)
	* "Crushing Stomp" (AoE stun radius)
* Movement becomes slower but heavier impact damage increases

	Design Purpose : Turns him from control boss → brute executioner

---

		4. Environmental Interaction

* Wreck structure can be used as partial cover
* Broken mast pieces block line of sight underwater
* Water currents define safe and unsafe zones
* On land phase, wreck no longer assists him defensively

---

		5. Group Composition

* Solo Semi-Boss encounter
* No permanent adds, but environmental hazards act as pseudo-enemies

