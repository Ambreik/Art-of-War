		Humanoid Monsters Structure : 
		
	1. Forsaken Soldiers (Structured Military)

* Organized
* Patrols, formations, ranged support
* Found near :
	* Fortifications
	* Cannons
	* Watchtowers

---

	2. Savagers (Resource-driven, brutal survivors)

* Former soldiers turned scavengers
* Less organized, more aggressive
* Use crude weapons, tools, stolen gear
* Found in :
	* Jungle edges
	* Shipwrecks
	* Broken camps

---

	3. Lunatics (Mad remnants of Mirath)

* Unstable, unpredictable
* Erratic movement / aggression
* Some lightly “ritualistic” behavior
* Found in :
	* Deep jungle
	* Isolated ruins
	* Fog-heavy areas