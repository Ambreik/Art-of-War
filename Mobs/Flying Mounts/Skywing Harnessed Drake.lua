			Skywing Harnessed Drake

	(Flying Master Transport Mount – Netar Island)

---

	Core Identity : 

* Name : Skywing Harnessed Drake
* Type : Transport Flying Mount (Service Only)
* Ownership : Flying Masters of Netar Island
* Usage : Fixed flight paths only
* Player Ownership : ❌ No
* Player Mountable Freely : ❌ No
* System Category : Controlled Transport Mount

---

	Visual Appearance : The Skywing Harnessed Drake resembles a dark avian-draconic hybrid, combining the silhouette of a massive raven with subtle drake traits.

	Body : 
* Sleek, predatory avian shape
* Long, narrow torso adapted for sustained flight
* Feathered body reinforced with scaled plating along:
	* Chest
	* Spine ridge
	* Wing joints
* Beak slightly curved, reinforced with bone ridges

	Wings : 
* Vast wingspan, broader than normal drakes
* Feathers transition into leathery membrane near joints
* Wing tips glow faintly with cold-blue wind sigils when airborne
* Creates visible air currents when flapping

	Head : 
* Raven-like skull with draconic horns sweeping backward
* Eyes glow pale frost-blue or storm silver
* Emits faint vapor breath in cold climates

	Tail : 
* Feathered base with scaled, spiked end
* Used for aerial balance and aggressive stabilization

---

	Harness & Equipment :
* Each Skywing Drake is fitted with a "Flight Harness", making it unmistakably a service mount.

	Harness Design : 
* Reinforced leather and chain hybrid saddle
* Steel rings engraved with:
	* Wind runes
	* Sky sigils of the Flying Masters
* Passenger seat stabilized by:
	* Wind-binding glyphs
	* Anti-fall arcane locks
* Tether lines prevent riders from falling during turbulence

	Visual Markings : 
* Flying Master emblem on saddle cloth
* Route markings carved on metal plates
* Blue-white cloth streamers trailing behind during flight

---

	Behavior & Personality : 
* Skywing Drakes are not wild mounts, but trained aerial beasts.

	On the Ground : 
* Remain calm, statuesque
* Fold wings tightly, lowering head for rider boarding
* Occasionally shift talons or shake feathers

	In Flight
* Extremely stable
* Rarely aggressive
* Adjusts altitude dynamically based on:
	* Wind conditions
	* Storm events
	* Invasion states
* Avoids combat entirely

	When Approached by Players
* Will not respond unless interacting with Flying Master
* Does not allow direct mounting
* Emits warning shriek if players attempt hostile actions

---

		Mechanical Integration

	1. Transport-Only Flight System

	Skywing Harnessed Drake operates strictly through:
* "Flying Masters"
* Fixed "Flight Routes"
* No manual control by players

	Players cannot:
* Freely steer
* Change routes mid-flight
* Use abilities while mounted

---

	2. Island Barrier Compatibility

	This mount is one of the few exceptions to Netar Island’s invisible flying barrier.

✔ Can cross the island split barrier
✔ Can fly across restricted zones
❌ Cannot be dismounted mid-air
❌ Cannot be used for combat or exploration

	Lore Reason : Its harness contains "Barrier-Attuned Sky Runes", allowing safe traversal where player-owned mounts are blocked.

---

	3. Invasion & World State Interaction

	Skywing Drakes react to village/world state :

	Calm / Alert
* Normal routes
* Regular flight schedule

	Besieged
* Routes may:
	* Delay
	* Divert
	* Cancel temporarily
* Drake wings glow brighter due to defensive enchantments

	Broken
* All flights suspended
* Drakes grounded and guarded by soldiers
* Flying Masters deny service

---

	4. Safety & Anti-Exploit Mechanics

* Cannot be attacked
* Cannot be dismounted by force
* Cannot be hijacked
* If Flying Master is killed or unavailable → no access to mount

---

	Environmental Integration

	Skywing Drakes contribute to immersion :
* Shadow cast across plazas when landing
* Strong wind gust effect on landing/takeoff
* Snow and dust swirl dynamically
* NPCs react when Drake lands:
	* Guards salute
	* Civilians step aside

---

	Audio Design : 
* Low-pitched wing beats
* Metallic harness clinks
* Occasional sharp raven-like cries
* Wind whistle during descent and ascent

---

	Narrative & Lore Hooks

	Skywing Drakes are not native to Netar Island.

	Rumors suggest :
* Imported from high-altitude breeding grounds
* Descended from ancient storm beasts
* Once wild, now fully domesticated by Flying Masters
* Some whisper their bloodline shares ancestry with Skelvar Windrider

