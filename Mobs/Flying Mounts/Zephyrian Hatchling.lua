			Zephyrian Hatchling

**Type:** Flying Mount
**Class:** Flying Mount
**Elemental Type:** Wind
**Acquisition:** Hatch from Mountain Peak Nest egg
**Leveling:** No.
**Taming Requirement:** Automatic upon egg hatching

---

#### **General Overview**

* **Description:**
  A majestic, wind-element bird that emerges from a high-altitude nest. Its wings shimmer with silver-blue feathers that glint in sunlight. Known for its agility and keen vision, it is ideal for aerial reconnaissance and swift travel across the island.

* **Appearance:**
  Sleek, medium-sized bird with elongated tail feathers and elegant wing spans. Eyes glow faintly with a cyan hue. The mount carries a lightweight, reinforced saddle and harness for rider safety.

* **Behavior:**
  Loyal to its owner, it can soar across cliffs, swoop through narrow valleys, and maintain stable flight in strong winds. Aggressive wildlife will evade it, but it cannot attack directly.

