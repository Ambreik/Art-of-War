---

#### **Mount Skills**

* **Passive Skills:**

  * Aerial Stability (improves flight handling, reduces stamina loss)
  * Wind Glide (minor speed bonus in windy regions)
  * Mounted Combat Training (small bonus to player damage while mounted)

* **Active Skills:**

  * Those skills can be learned through different methods and are part of the "Aerial Skills".

---

#### **Maintenance & Feeding**

* Must be fed **Sky Feed** regularly.
* Starvation causes mount to enter **Dormant State**; revival requires Mount Master services.

---

#### **Special Notes**

* Only one hatch per nest per day.
* Hatching takes **2 in-game hours** after egg is collected.
* Mount is permanently bound to the player.
* Can participate in flying combat and exploration missions.

