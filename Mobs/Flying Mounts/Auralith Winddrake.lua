			Auralith Winddrake — Mount Version

	Location : Middlean Islands \ Netar Island \ Zone 3 — Split Horizon Arch

---

	Appearance : Larger than the pet version, with expanded wingspan capable of sustained gliding. Wing membranes streaked with glowing glyphs along the edges. 
Muscular tail tipped with feathered fin for aerial maneuvering. Amber eyes signal intelligence and trust in the rider.

	Behavior : Fluid and responsive flight, reacts dynamically to player gliding, dive, and ascent commands. Aware of hazards like wind gusts, cliff edges, and 
narrow ledges, assisting navigation.

	Role / Mechanics : 
* Flight-enabled mount with gliding and aerial mobility
* Passive abilities while mounted:
	* Reduced fall damage
	* Glide / slow-fall augmentation
	* Enhanced movement in windy zones
* Can interact with environmental mechanics (move lily leaves, trigger hidden ledges)
* Auto-dismount in narrow tunnels

	Taming Process (Mount Version)

	Phase 0 — Spawn Requirement : Completion of "Cliffside Platforming Challenge" + "Light Puzzle" triggers spawn on ledge.

	Phase 1 — Observation Phase :
* Approach calmly, avoid sudden movement or attacks
* Successful observation unlocks "Ritual Bonding Phase"

	Phase 2 — Ritual Bonding Phase :
* Match creature’s movement / wing signal cues
* Optional items: "Wind-Sealed Relic", "Gale Feather Token" to boost affinity
* Success unlocks "Mount Training Phase"

	Phase 3 — Mount Training Phase :
* Navigate wind tunnel flight path
* Avoid gust hazards, cliff collisions
* Skills like glide, slow-fall, mount control assist success
* Success → creature accepts mounting, unlocks "Glide Assist" & "Bonded Leap" skills

	Phase 4 — Pet vs Mount Choice :
* Choosing mount locks pet summon unless special quest completed

	Phase 5 — Final Acceptance :
* Creature glows fully + emits wing flare
* Added to player’s mount list
* Cooldowns apply for summoning / dismount

	Quotes / Animations : 
* “The Winddrake stretches its wings wide, catching the updraft as you take flight.”
* “It flaps powerfully, carrying you across the cliffs with effortless grace.”
* “A low, rumbling growl echoes as it adjusts to a sudden wind gust, keeping you steady.”

