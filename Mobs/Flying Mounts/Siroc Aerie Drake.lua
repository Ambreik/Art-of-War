			Siroc Aerie Drake

---

		1. Basic Information

* Name : Siroc Aerie Drake
* Type : Flying Mount
* Elemental Type : Wind
* Class : Flying
* Tier : Flying Mount (Epic / special reward from Mountain Peak Nest)
* Source : Mountain Peak Nest Egg Hatch

---

		2. Description

	The "Siroc Aerie Drake" is a winged drake with feathery crests and sleek aerodynamic body adapted to high-altitude winds. Its plumage shifts in color from 
storm-gray to sky-blue, and its eyes gleam with keen intelligence. Its wings generate gentle updrafts, allowing stable and graceful flight even in turbulent 
conditions around mountain peaks.

	Externally, the Drakes carry subtle wind-glyph patterns along their spines that glow faintly during flight.

---

		3. Acquisition

* Can only be obtained by hatching the "Mountain Peak Nest Egg"
* Only one mount per egg
* Bound to the player upon hatch (cannot be traded)

---

		4. Mount Role

* Primary Use : Aerial exploration, traversal, and limited aerial combat
* Unlocks :
	* Aerial movement mode
	* Greater traversal freedom on Ashen Cliffs and beyond
	* Access to otherwise unreachable high-air zones

---

		5. Mount Attributes

* Base Speed Modifier : 130% (in air)
* Flight Ceiling : Tier-dependent height limit (region boundary)
* Combat : Able to use passive and active Wind abilities while flying
* Elemental Bonus : +10% movement in windy or open air regions

---

		6. Mount Skills

	Aerial Skills (Active & Passive) :

* "Wind Glide" (Passive) : Sustains lift longer and reduces stamina drain
* "Aerie Dive" (Active) : Fast downward burst — brief knockback on impact
* "Cloud Burst" (Active) : Generates a minor wind shield for the rider
* "Soaring Grace" (Passive) : Improves handling in gusty air conditions

---

		7. Integration

* Works within game’s "Mount System UI"
* Appears under "Flying Mounts" category
* Can level up and gain experience like other mounts 

---

		8. Feeding & Care

* Food Type : "Sky Herb Mix" — increases stamina and reduces hunger
* Has a 14-day starvation threshold (must feed periodically) 

---

		9. Rewards & Use

* Aesthetic + functional mount
* Unlocks aerial exploration content
* Grants minor navigation aid bonuses

---

		10. Lore

	Born among the highest winds, the Siroc Aerie Drake represents the freedom of the peaks and the enduring spirit of explorers who scale above storm and cliff 
alike. Its appearance marks a rite of passage for climbers who conquer the "Mountain Peak Nest" and unlock the skies beyond.

