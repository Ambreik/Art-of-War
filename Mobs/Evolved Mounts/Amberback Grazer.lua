			Amberback Grazer

---

		1. Basic Information

* Mount Name : Amberback Grazer
* Mount Class : Pack Mount
* Mount Type : Large Sturdy Herbivore
* Taming Difficulty : Moderate
* Habitat Origin : Open plains, river borders, lightly forested valleys
* Required Tool : Standard Taming Kit
* Special Taming Condition : Must approach a calm herd and gain trust before attempting taming

---

		2. Appearance

	A massive, broad-backed quadruped with sandy-golden fur and a pronounced hump along its spine for carrying heavy loads. Horns curve gently backward, and its 
eyes are calm but observant. Muscular legs support long-distance travel, and its gait is steady rather than fast. Often grazes in small herds.

---

		3. Core Attributes

* HP : High
* Defense : Medium–High
* Speed : Low–Moderate
* Mobility Type : Ground / Plains traversal
* Role : Heavy cargo transport, steady long-distance travel

---

		4. Mount Abilities

* "Load Bearer" (Passive) – Increases carry capacity for player inventory or supplies
* "Sturdy Step" (Passive) – Reduced chance to stumble on uneven terrain
* "Pack Momentum" (Active) – Charges forward in a slow but forceful movement; can knock small obstacles aside
* "Grazing Regeneration" (Passive) – Slowly regenerates HP when idle in open plains or near food sources

---

		5. Traversal Role

	The Amberback Grazer excels at :
* Long-haul cargo transport
* Traversing open plains and gentle hills
* Serving as a pack mount in caravans

	It is not suited for swamps, cliffs, or fast combat scenarios.

---

		6. Special Taming Mechanic

* The player must first calm the herd by feeding or waiting near grazing Amberback Grazers
* Only one mount can be tamed at a time from the herd
* If the player fails the taming attempt, the herd scatters, requiring a cooldown period

---

		7. Behavior While Mounted

* Slow, steady gait; rarely panics
* Lean forward slightly while idle, ready for controlled movement
* Emits low, rumbling calls if threatened or startled

---

		8. Restrictions

* Performs poorly in dense forest, swamps, or narrow paths
* Cannot sprint rapidly
* Relies on open terrain for optimal mobility and load carrying

