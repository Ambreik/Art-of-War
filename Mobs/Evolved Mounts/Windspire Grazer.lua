			Windspire Grazer

---

	1. Basic Information

* Mount Name: Windspire Grazer
* Mount Class: Pack Mount
* Mount Type: Large Plains Herbivore
* Taming Difficulty: Medium
* Habitat Origin: Open plains and gentle rolling hills of Northspire Reach
* Required Tool: Standard Taming Kit
* Special Taming Condition: Must approach a herd and isolate a young adult for taming

---

		2. Appearance

	A massive, sturdy quadruped with sandy-brown fur, long muscular legs, and a pronounced ridge along its back. Horns are short but strong, curving slightly 
outward. Eyes are calm and observant. Its body is well-suited for carrying cargo or multiple passengers. Its gait is slow but tireless, and the hide is thick, 
offering natural protection.

---

		3. Core Attributes

* HP: High
* Defense: Medium–High
* Speed: Low–Medium (steady pace)
* Mobility Type: Ground
* Role: Stamina-heavy travel, pack transportation, and general cargo hauling

---

		4. Mount Abilities

* "Steady March" (Passive) : Reduces stamina drain for the rider and itself over long distances.
* "Pack Carry "(Passive) : Can carry extra cargo or additional passenger units.
* "Terrain Adaptation" (Passive) : Slightly faster traversal over uneven plains and gentle hills.
* "Stampede Kick" (Active) : Forward stomp that can knock back smaller enemies; minimal damage to rider’s path.

---

		5. Traversal Role

	The Windspire Grazer excels at :
* Plains and grasslands travel
* Long-distance caravan escort
* Heavy cargo transport

	Not suitable for :
* Narrow ledges, cliff paths, or deep forest
* High-speed combat traversal

---

		6. Special Taming Mechanic

1. Approach a herd of Windspire Grazers in open plains.
2. Identify and isolate a young adult that is calm but alert.
3. Use a **Standard Taming Kit** to subdue and bond over a period of time.
4. Maintaining proximity to the herd increases taming success.

	If the Grazer is startled by predators during taming, it may flee, resetting progress.

---

		7. Behavior While Mounted

* Moves in a steady, plodding pace
* Ears twitch at nearby sounds; occasionally stops to graze
* Horns and tail movements reflect alertness
* Emits low rumbling calls if startled

---

		8. Restrictions

* Poor performance in narrow or vertical terrain
* Cannot jump over large obstacles
* Ineffective in forested or swampy areas
* Requires plains or gentle hill biome for optimal efficiency

