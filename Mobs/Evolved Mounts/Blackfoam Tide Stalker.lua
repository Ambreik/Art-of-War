			Blackfoam Tide Stalker

---

		1. Basic Information

* Mount Name : Blackfoam Tide Stalker
* Mount Class : Evolved Mount
* Mount Type : Shoreline / Shallow Water Combat
* Taming Difficulty : Very Hard
* Habitat Origin : Blackfoam Shore, shallow coastal waters, tidepools at night
* Required Tool : Combat Taming Kit
* Special Taming Condition : Must be approached at night to reduce aggression

---

		2. Appearance

	The Blackfoam Tide Stalker is a muscular, amphibious predator with dark, wet scales that absorb moonlight, making it nearly invisible at night. Its eyes glow 
faintly, reflecting bioluminescent plankton along the shore. Powerful limbs end in clawed feet for shore traction, while webbed segments assist in swimming. Its 
tail is long and flattened for propulsion, and its jaw is lined with sharp teeth, perfect for aggressive skirmishes along the waterline.

---

		3. Core Attributes

* HP : High
* Defense : Medium-High
* Speed : Medium on land, High in shallow water
* Mobility Type : Amphibious
* Role : Combat mount, shoreline and shallow water skirmishes

---

		4. Mount Abilities

* "Night Predator" (Passive) : Gains +20% damage and detection during night cycles.
* "Tide Sweep" (Active) : Tail strike deals knockback to enemies in shallow water.
* "Shore Ambush" (Active) : Quick lunge from water onto land for short bursts of speed.
* "Aquatic Stability" (Passive) : Maintains balance in turbulent shallow water.
* "Bite Strike" (Active/Combat) : Quick melee attack with chance to apply minor bleed.

---

	5. Traversal Role

* Shallow water navigation
* Tidepool exploration
* Beach-to-water skirmishes
* Coastal combat advantage, especially at night

---

		6. Special Taming Mechanic

	Players must tame the Tide Stalker during night-time along "Blackfoam Shore" :
1. Locate the creature at night near active bioluminescent foam.
2. Approach quietly without making excessive noise, as daytime aggression prevents taming.
3. Use the Combat Taming Kit while staying partially submerged.
4. Complete a short mini-sequence of synchronized movement and feeding to gain trust.

	Failing to respect night conditions or noise tolerance causes the Stalker to flee or attack.

---

		7. Behavior While Mounted

* Swims and lunges fluidly between shallow water and beach.
* Tail flicks and jaws snap in coordination with movement.
* Shows increased alertness at night, responding dynamically to enemy proximity.

---

		8. Restrictions

* Cannot travel deep ocean distances efficiently
* Limited mobility on steep cliffs or rugged inland terrain
* Combat abilities weakened in bright daylight

