			Frostback Elk

---

		1. Basic Information

* Mount Name: Frostback Elk
* Mount Class: Sprint / Utility Mount
* Mount Type: Large Arctic Herbivore
* Taming Difficulty: Hard
* Habitat Origin: Snowy plains, frozen forests, and frost-laden ridges of Northspire Reach
* Required Tool: Advanced Taming Kit
* Special Taming Condition: Must tame during calm weather or while using warmth-providing gear

---

		2. Appearance

	A majestic elk with silvery-gray fur flecked with icy blue streaks along the back and antlers. Large, curved antlers sweep backward, adorned with frost patterns
that shimmer in sunlight. Legs are long and lean, adapted for fast movement over snow and ice. Eyes are sharp and reflective, giving excellent vision in dim or 
snowy conditions. The fur is thick, providing natural insulation against extreme cold.

---

		3. Core Attributes

* HP: Medium–High
* Defense: Medium
* Speed: High (excellent sprinting ability)
* Mobility Type: Ground / Snow Traversal
* Role: Fast travel over snowy and icy terrain, capable of carrying light cargo or a single passenger

---

		4. Mount Abilities

* "Ice Sprint" (Active) : Short burst of high-speed sprint across snow or frozen terrain; reduces risk of slipping.
* "Frost Step" (Passive) : Footfalls leave temporary ice patches that slow pursuing enemies.
* "Snow Sense" (Passive) : Improves navigation in snowy terrain and reveals hidden paths or obstacles.
* "Calm Presence" (Passive) : Reduces rider stamina drain in extreme cold conditions.

---

		5. Traversal Role

	The Frostback Elk excels at :
* Fast travel in snowy plains and ice fields
* Traversing moderate hills and ridges
* Escaping ambushes on open frosted terrain

	Not suitable for :
* Dense forests or marshlands
* Cliffside ledges or vertical rock faces
* Wet or muddy plains

---

		6. Special Taming Mechanic

1. Locate a small herd of Frostback Elks in snowy regions.
2. Approach during calm weather conditions to avoid startling the herd.
3. Use "Advanced Taming Kit" and warmth-inducing items to soothe the mount.
4. Bonding requires patience; repeated feeding and proximity to the herd improves success.

	Failure may result in the elk fleeing several kilometers away.

---

		7. Behavior While Mounted

* Moves gracefully over snow, maintaining balance
* Tail and antler movement reflects alertness
* Emits soft bellowing calls when surprised or agitated
* Grazes occasionally if idle for extended periods

---

		8. Restrictions

* Poor traction on wet or muddy terrain
* Not suited for narrow cliffs or rocky verticals
* Cannot carry heavy cargo efficiently
* Requires snow or frost-laden environment for peak performance

