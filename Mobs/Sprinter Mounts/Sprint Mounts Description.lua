			Sprint Mounts

	Overview : "Sprint Mounts" are bred for long-distance travel and rapid movement across vast territories.
* Lightweight, aerodynamic, and responsive, they specialize in speed and endurance rather than strength.
* They are favored by messengers, scouts, and travelers who value swiftness above all else.

	Gameplay Role :
* Not levelable (fixed performance).
* Consume stamina slowly over distance.
* Possess a "Sprint" skill, temporarily doubling speed at high stamina cost.
* Cannot be used effectively in combat situations.

	Behavioral Traits :
* Agile and nervous, responsive to player commands.
* Prone to fatigue if overused.
* React strongly to weather — slower in storms, faster in sunlight.

	Lore Note : Legends tell of ancient riders who crossed the entire continent on "Sprint Mounts" in a single dawn, their steeds leaving trails of dust like fire 
behind them.

