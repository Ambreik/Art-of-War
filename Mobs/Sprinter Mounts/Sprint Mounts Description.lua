			Flying Mounts

	Overview : "Flying Mounts" represent the pinnacle of travel freedom and mastery over the skies.
* They range from draconic creatures to celestial beasts, each requiring tremendous skill and discipline to tame.
* Their flight allows access to otherwise unreachable zones, but maintaining altitude and stamina balance is critical.

	Gameplay Role :
* Capable of full 3D movement and aerial combat for limited durations.
* Stamina drains steadily while flying; rapidly when sprinting or evading.
* Automatically land when stamina is depleted.

	Behavioral Traits :
* High intelligence; responsive to aerial maneuvers.
* Can sense incoming storms or high-altitude threats.
* Visual wing animation and wind trails depend on mount rarity and speed.

	Lore Note : "Flying Mounts" are sacred companions of heroes and sky guardians. Their bond transcends mortal limits, symbolizing freedom and dominance over 
heaven and earth alike.

