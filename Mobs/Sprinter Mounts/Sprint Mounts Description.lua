			Aquatic Mounts

	Overview : "Aquatic Mounts" dwell beneath the surface of Legrand’s seas, lakes, and rivers.
* They serve as both transportation and guardians in underwater environments, enabling exploration of regions unreachable by land dwellers.
* They vary from tamed sea beasts to magical aquatic spirits bonded through resonance.

	Gameplay Role :
* Provide enhanced underwater mobility and breathing capabilities.
* Immune to water pressure and drowning effects.
* Stamina drains faster in combat or turbulent currents.

	Behavioral Traits :
* Graceful movement underwater; inert on land.
* React to water temperature and salinity (cosmetic or behaviorally).
* Some variants emit light, serving as natural underwater illumination.

	Lore Note : "Aquatic Mounts" are revered by coastal tribes who see them as protectors of the deep — gifts from the ocean’s heart, forged by currents and ancient
tides.

