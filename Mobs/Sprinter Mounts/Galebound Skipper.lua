			Galebound Skipper

---

		1. Basic Information

* Mount Name : Galebound Skipper
* Mount Class : Sprint Mount
* Mount Type : Wind-Assisted Cliff Runner
* Taming Difficulty : Hard
* Habitat Origin : High cliffs, wind shelves, fog-covered ledges, elevated coastlines
* Required Tool : Advanced Taming Kit
* Special Taming Condition : Must be tamed during strong wind currents at elevation

---

		2. Appearance
		
	A lean, long-legged avian creature with narrow wings that never fully fold against its body. Its feathers are swept permanently backward as if shaped by 
constant wind. The legs are powerful and elastic, built for bounding strides across stone, while the wings act like stabilizers rather than tools for flight. Its 
eyes are pale and reflective, always scanning the horizon from high ground.

---

		3. Core Attributes

* HP : Low–Medium
* Defense : Low
* Speed : Very High (situational)
* Mobility Type : Ground / Cliff / Ledge traversal
* Role : Rapid traversal across elevated and windy terrain

---

		4. Mount Abilities

* "Gale Sprint" (Active) : A powerful forward burst of speed. If used inside a wind zone, the sprint distance and speed are greatly increased.
* "Ledgebound Leap" (Active) : Performs a long horizontal leap, allowing traversal between cliffs, broken stairs, and stone gaps.
* "Wind Glide" (Passive) : Reduces fall speed and prevents fall damage when descending from heights.
* "Updraft Affinity" (Passive) : Automatically gains movement speed when traveling against strong wind currents.
* "Cliffrunner Instinct" (Passive) : Improved pathing and control on narrow ledges and uneven rock terrain.

---

		5. Traversal Role

	The Galebound Skipper excels at :
* Cliffside travel
* Broken vertical environments
* Wind-heavy zones
* Fast repositioning between elevations

	It is not meant for forests, swamps, or tight interiors.

---

		6. Special Taming Mechanic

	This mount cannot be tamed in calm weather.

	To tame it, the player must :
1. Reach a high elevation cliff where wind gusts are visibly affecting foliage or fog
2. Wait for a strong wind surge event
3. Begin taming while the Skipper is actively running against the wind

	If the wind dies down, the taming fails and the creature flees to another cliff.

---

		7. Behavior While Mounted

* Constant subtle feather movement as if blown by wind
* Leans forward while idle, ready to sprint
* Emits sharp avian calls when wind speed increases

---

		8. Restrictions

* Performs poorly in dense forest or swamp terrain
* Cannot be used effectively indoors or underground
* Relies heavily on environmental wind mechanics for peak performance

