			Archscale Serpent

---

		1. Basic Information

* Mount Name : Archscale Serpent
* Mount Class : Aquatic Mount
* Mount Type : Water / Shoreline Traversal
* Taming Difficulty : Hard
* Habitat Origin : Coastal inlets, tidepools, submerged arches, shallow reefs
* Required Tool : Aquatic Taming Kit
* Special Taming Condition : Must be approached and tamed while fully submerged

---

		2. Appearance

	The Archscale Serpent is a sleek, elongated serpent with iridescent scales that shimmer in aquatic light. Its body tapers into a powerful tail, ideal for 
propulsion through water. The head is narrow with pronounced, forward-facing eyes, giving it an alert, predatory gaze. Fins along its spine ripple subtly as it 
moves, helping it stabilize in currents, while its forked tail allows agile turns underwater.

	On land, its movement is awkward and serpentine, though it can drag itself short distances across shorelines.

---

		3. Core Attributes

* HP : High
* Defense : Medium
* Speed : High in water, low on land
* Mobility Type : Aquatic / Shoreline
* Role : Fast water traversal, limited coastal mobility

---

		4. Mount Abilities

* Hydro Burst (Active) : Performs a short sprint underwater, increasing travel speed significantly.
* Water Glide (Passive) : Moves smoothly through currents and maintains stability in turbulent water.
* Tail Sweep (Active/Combat, Optional) : Strikes enemies or obstacles while mounted in water, applying minor knockback.
* Aquatic Vision (Passive) : Clearer underwater sight; detects hidden objects or creatures in murky water.
* Land Drag (Passive) : Can traverse short beach stretches, but with reduced speed and agility.

---

		5. Traversal Role

	Archscale Serpent is optimized for :
* Deep water exploration
* Coastal shortcuts
* Tidepool networks
* River and delta navigation

	It encourages players to use waterways for efficient travel.

---

		6. Special Taming Mechanic

	The player must tame the Serpent while swimming in its aquatic habitat. Steps include :
1. Locate the Serpent in its natural water zone.
2. Approach from underwater stealth to avoid startling it.
3. Use the Aquatic Taming Kit while maintaining submersion.
4. Successfully complete a short sequence of “swim in sync” movements with the Serpent.

	Failure to stay submerged or match its movement pattern causes the Serpent to flee.

---

		7. Behavior While Mounted

* Body undulates rhythmically, reflecting currents.
* Head tilts naturally with turns to indicate direction.
* Tail flicks to maintain balance during high-speed movement.

---

		8. Restrictions

* Poorly suited for open land travel
* Cannot traverse vertical cliffs or rough, dry terrain
* Combat efficiency reduced on land

