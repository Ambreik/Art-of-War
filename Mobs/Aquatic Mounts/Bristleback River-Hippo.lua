			Bristleback River-Hippo

---

		1. Basic Information

* Mount Name : Bristleback River-Hippo
* Mount Class : Amphibious / Utility Mount
* Mount Type : Semi-Aquatic Herbivore
* Taming Difficulty : Moderate
* Habitat Origin : Wide river crossings, lowland lakes, and marshes near Sunveil Plains
* Required Tool : Standard Taming Kit
* Special Taming Condition : Approach calmly from riverbank; must avoid sudden water disturbances

---

		2. Appearance

	A massive, armored semi-aquatic beast with spiked ridges along its back and short tusks framing a powerful jaw. Its thick hide is grayish-brown, naturally camouflaging in muddy waters and riverbanks. Eyes are alert and partially hooded, giving a calm but watchful expression. Limbs are short and powerful, capable of pushing through water and mud while carrying heavy cargo or riders.

---

		3. Core Attributes

* HP : High
* Defense : High
* Speed : Low (ground) / Moderate (water)
* Mobility Type : Amphibious (land + water)
* Role : Heavy-load river mount; capable of crossing shallow to mid-depth water and carrying multiple riders or cargo

---

		4. Mount Abilities

* "River Trample" (Active) – Slow frontal charge; knocks back enemies and light obstacles; deals minor damage
* "Water Glide" (Passive) – Moves through shallow and moderate-depth water with reduced stamina cost
* "Mudwall Stance" (Active) – Temporarily reduces damage taken while standing in water or mud
* "Loadbearer" (Passive) – Increases carrying capacity for cargo by 30%

---

		5. Traversal Role

	The Bristleback River-Hippo excels at :
* Crossing rivers and marshlands
* Transporting cargo and players across water
* Supporting caravans in lowland or floodplain zones

	It is not intended for steep mountains, cliffs, or dense forest travel.

---

		6. Special Taming Mechanic

* Must approach while the creature is resting or grazing near water
* Avoid splashing, sudden movements, or aggressive displays
* Feeding aquatic vegetation or river reeds increases taming success
* Nearby predators or water disturbances reduce taming chance

---

		7. Behavior While Mounted

* Moves steadily through water and mud, occasionally pausing to shake off water
* Defensive when approached aggressively, using trample ability if startled
* Roams slowly on land; prefers water for optimal movement

---

		8. Restrictions

* Poor performance in dense forests or high mountains
* Cannot perform fast sprints on land
* Requires rivers, lakes, or swampy terrain for peak mobility

