			Mirejaw Crocodile

---

		1. Basic Information

* Mount Name: Mirejaw Crocodile
* Mount Class: Amphibious Mount
* Mount Type: Semi-Aquatic Predator
* Taming Difficulty: Very Hard
* Habitat Origin: Marshes, slow rivers, and flooded lowlands of Northspire Reach
* Required Tool: Expert Taming Kit
* Special Taming Condition: Juveniles only; taming must occur in shallow water under supervision

---

		2. Appearance

	A robust juvenile crocodilian with dark green-brown scales patterned with lighter streaks for camouflage in water and reeds. Strong tail and short, muscular 
legs allow both aquatic propulsion and limited terrestrial movement. Eyes sit high on the head for surface observation while submerged. Teeth are sharp but 
relatively small in juveniles, making them trainable for riding.

---

		3. Core Attributes

* HP: Medium
* Defense: Medium–High (natural armored hide)
* Speed: Moderate on land, High in water
* Mobility Type: Amphibious (Water / Shoreline)
* Role: Short-distance river crossing, stealthy aquatic movement

---

		4. Mount Abilities

* "River Glide" (Active) : Boosts swimming speed for short bursts; improves maneuverability in narrow channels.
* "Reed Camouflage" (Passive) : Reduces detection by aquatic predators or hostile mobs while submerged.
* "Tail Sweep" (Active) : Brief knockback in shallow water; defensive ability for mounted combat.
* "Water Sense" (Passive) : Detects underwater obstacles, hidden paths, or submerged hazards.

---

		5. Traversal Role

	Ideal for :
* Short river crossings
* Marsh and swamp navigation
* Stealthy approach along water edges

	Limitations :
* Not suited for long-distance land travel
* Cannot navigate strong river currents effectively
* Restricted to shallow waters for mounted use

---

		6. Special Taming Mechanic

1. Capture juvenile Mirejaw Crocodiles in shallow river bends or marsh pools.
2. Use "Expert Taming Kit" and food incentives to reduce aggression.
3. Remain patient; the mount requires repeated sessions to establish trust.
4. Adult crocodiles are too aggressive for taming; juveniles are necessary.

	Failure results in fleeing or aggressive retaliation.

---

		7. Behavior While Mounted

* Subtle head and tail movements reflect alertness
* Snaps lightly when startled but avoids harming rider if trained
* Periodically surfaces to breathe and adjust position

---

		8. Restrictions

* Cannot traverse open seas or fast-flowing rivers
* Limited land mobility; slow on plains or uneven terrain
* Requires consistent care and aquatic environment for optimal performance
* Vulnerable to terrain hazards outside water

