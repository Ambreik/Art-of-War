			Abyssal Reef Tyrant

---

		1. Basic Information

* Name : Abyssal Reef Tyrant
* Type : Aquatic Mount
* Category : Rare / Tamed Creature
* Source : Taming (Apex Predator – Reef Predator System)

---

		2. Appearance

	The mount retains its original apex predator form, now slightly stabilized but still visibly dangerous.
	Its massive, reef-armored body remains intact, with coral growths and jagged protrusions forming natural armor plating. Bioluminescent veins continue to pulse 
faintly along its body, especially when moving at high speed.
	The eyes glow with a subdued intensity, no longer fully hostile but still predatory. The dorsal fins remain sharp and blade-like, cutting through water as it 
swims.

	When ridden :
* The player is positioned behind the head, gripping hardened coral ridges
* Water flows dynamically around the creature, creating a visual trail

	Movement remains :
* Smooth and controlled at low speed
* Explosively fast during bursts

---

		3. Mount Type & Usage

* Environment : Water Only
* Restrictions :
	* Cannot be used on land
	* Cannot be summoned in shallow water below threshold depth

---

		4. Movement Profile

* Base Speed : High (above standard swimming speed)
* Acceleration : Medium → High burst capability
* Turn Rate : Moderate

---

		5. Mount Stamina System Integration

---

	Stamina Behavior : 
* Stamina drains while :
	* Sprint swimming
	* Using abilities
* Stamina regenerates :
	* Faster in deep water
	* Slower in shallow zones

---

	Stamina Traits : 

* Deep Water Efficiency
	* Reduced stamina consumption
* Current Adaptation
	* Less stamina loss in strong currents

---

		6. Mount Passive Effects

---

	Apex Swimmer : 
* Increased swim speed compared to standard mounts

---

	Current Resistance : 
* Reduced impact from water current systems

---

	Predator Instinct : 
* Detects nearby hostile aquatic creatures at short range

---

		7. Mount Skills (Integrated with Mount Skills System)

---

