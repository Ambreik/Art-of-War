			Evolved Mounts

	Overview : "Evolved Mounts" are the product of natural adaptation or long-term training.
* They exhibit enhanced physical attributes, improved stamina, and partial combat responsiveness.
* Unlike normal mounts, evolved variants form a stronger synchronization with the rider, adjusting their speed and reactions dynamically during travel.

	Gameplay Role :
* Levelable up to "Level 30".
* Provides improved movement speed and stamina.
* Grants moderate combat bonuses to the rider (+Damage Reduction, +Critical Chance).
* Can learn mount-exclusive skills such as "Charge" or "Endurance Aura".

	Behavioral Traits :
* Intelligent, capable of basic tactical responses.
* React to rider health and positioning.
* May display unique idle animations tied to their temperament.

	Lore Note : "Evolved Mounts" are said to be descendants of ancient war-beasts bred by early human tribes — symbols of strength and resilience that endure beyond
generations.

