			Sprint Mounts

	Overview : "Sprint Mounts" are bred for long-distance travel and rapid movement across vast territories.
* Lightweight, aerodynamic, and responsive, they specialize in speed and endurance rather than strength.
* They are favored by messengers, scouts, and travelers who value swiftness above all else.

	Gameplay Role :
* Not levelable (fixed performance).
* Consume stamina slowly over distance.
* Possess a "Sprint" skill, temporarily doubling speed at high stamina cost.
* Cannot be used effectively in combat situations.

	Behavioral Traits :
* Agile and nervous, responsive to player commands.
* Prone to fatigue if overused.
* React strongly to weather — slower in storms, faster in sunlight.

	Lore Note : Legends tell of ancient riders who crossed the entire continent on "Sprint Mounts" in a single dawn, their steeds leaving trails of dust like fire 
behind them.

---

			Aquatic Mounts

	Overview : "Aquatic Mounts" dwell beneath the surface of Legrand’s seas, lakes, and rivers.
* They serve as both transportation and guardians in underwater environments, enabling exploration of regions unreachable by land dwellers.
* They vary from tamed sea beasts to magical aquatic spirits bonded through resonance.

	Gameplay Role :
* Provide enhanced underwater mobility and breathing capabilities.
* Immune to water pressure and drowning effects.
* Stamina drains faster in combat or turbulent currents.

	Behavioral Traits :
* Graceful movement underwater; inert on land.
* React to water temperature and salinity (cosmetic or behaviorally).
* Some variants emit light, serving as natural underwater illumination.

	Lore Note : "Aquatic Mounts" are revered by coastal tribes who see them as protectors of the deep — gifts from the ocean’s heart, forged by currents and ancient
tides.

---

			Flying Mounts

	Overview : "Flying Mounts" represent the pinnacle of travel freedom and mastery over the skies.
* They range from draconic creatures to celestial beasts, each requiring tremendous skill and discipline to tame.
* Their flight allows access to otherwise unreachable zones, but maintaining altitude and stamina balance is critical.

	Gameplay Role :
* Capable of full 3D movement and aerial combat for limited durations.
* Stamina drains steadily while flying; rapidly when sprinting or evading.
* Automatically land when stamina is depleted.

	Behavioral Traits :
* High intelligence; responsive to aerial maneuvers.
* Can sense incoming storms or high-altitude threats.
* Visual wing animation and wind trails depend on mount rarity and speed.

	Lore Note : "Flying Mounts" are sacred companions of heroes and sky guardians. Their bond transcends mortal limits, symbolizing freedom and dominance over 
heaven and earth alike.

