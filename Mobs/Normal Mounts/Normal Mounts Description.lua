			Exotic Mounts

	Overview : "Exotic Mounts" are rare, mystical creatures drawn from forgotten regions or ancient bloodlines.
* They defy the limits of natural breeding and are often bonded through ritualistic taming or events of cosmic alignment.
* Their powers extend beyond physical form, often manifesting in elemental or spiritual abilities.

	Gameplay Role :
* Levelable up to "Level 50".
* Provide powerful player bonuses (+Unique Elemental Auras, +Stat Scaling).
* May possess passive traits such as "Fire Resistance", "Frost Aura", or "Arcane Momentum".
* Require rare items and advanced "Tame Passive Skill" (Rank V – Grandmaster).

	Behavioral Traits :
* Highly intelligent and unpredictable.
* Can refuse commands if stamina or morale drops too low.
* Display visual cues of their affinity (elemental glow, particles, or aura effects).

	Lore Note : It is said that "Exotic Mounts" are born only when the balance of nature and magic intertwines — creatures of legend that choose their rider rather 
than being chosen.

