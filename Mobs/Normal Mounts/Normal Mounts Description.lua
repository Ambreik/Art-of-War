			Normal Mounts

	Overview : "Normal Mounts" represent the most common and reliable companions found throughout the world.
* Bred or tamed for simple transportation, these creatures are the foundation of every traveler’s journey — sturdy, loyal, and easy to maintain.
* They lack advanced skills or combat functionality but compensate with exceptional endurance and ease of control.

	Gameplay Role :
* Serves as the player’s first mount type.
* Provides basic movement speed increase.
* Cannot level up or gain new abilities.
* Consumes minimal stamina over time.

	Behavioral Traits :
* Calm and obedient; rarely panic.
* Compatible with most terrains.
* Do not enter combat or react to enemies.

	Lore Note : Across Legrand’s plains and Sudeon’s fields, these mounts are considered a rite of passage for young adventurers — the first bond between man and 
beast.

