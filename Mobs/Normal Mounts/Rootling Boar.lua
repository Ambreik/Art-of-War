		5. Mount Classification

* Mount Type : Utility Mount
* Specialization : Forest / Dense Terrain Traversal
* Movement Style : Ground
* Speed Tier : Moderate
* Combat Capability : None (movement-focused mount)
* Primary Function : Stable traversal through difficult terrain

---

		6. Core Mount Attributes

* Mount HP : Medium
* Mount Durability : Medium–High
* Movement Speed : Moderate (consistent, not burst-focused)
* Terrain Adaptation : High (forest, roots, uneven terrain)
* Handling : Stable (low drift, high control)
* Stamina System : Balanced (long-duration travel capability)

---

		7. Mount Abilities / Traits

	1. Forest Stride : The Rootling Boar moves efficiently through dense vegetation.

* Effect :
	* Ignores movement penalties from:
		* Roots
		* Thick grass
		* Low obstacles
	* Maintains consistent speed in forest terrain
* Mechanic : Passive terrain adaptation

---

	2. Root Charge (Mount Ability) : A controlled forward burst of momentum.

* Effect :
	* Short forward dash
	* Breaks through minor obstacles (brush, roots)
	* Slightly pushes aside small enemies or creatures
* Cooldown : Medium
* Mechanic : Movement-focused ability (non-combat oriented, but impactful in traversal)

---

	3. Stabilized Footing : Enhances control on uneven terrain.

* Effect :
	* Reduces slipping or slowdown on slopes
	* Improves turning and control in tight forest paths
* Mechanic : Passive handling improvement

---

	4. Terrain Momentum : Maintains speed consistency over long distances.

* Effect :
	* Reduced stamina drain while traveling through forest zones
	* Sustained movement efficiency
* Mechanic : Travel optimization passive

---

		8. Passive Bonuses

* Smooth traversal through dense forest environments
* Reduced environmental slowdown penalties
* Increased control on uneven terrain
* Improved exploration flow in jungle/forest zones

---

		9. Evolution / Progression Path (Optional Design)

	The Rootling Boar can evolve through mount progression systems:

	Potential Evolution States : 
* "Ironroot Boar" (increased durability + stronger charge)
* "Deepwood Charger" (improved speed + terrain dominance)
* "Ancient Rootbeast" (enhanced traversal + environmental interaction)

	Evolution Triggers : 
* Distance traveled in forest terrain
* Use of Root Charge ability
* Bond progression
* Exploration milestones

