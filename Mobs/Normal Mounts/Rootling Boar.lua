			Rootling Boar (Tamed Variant)

---

		1. Tamed Entity Overview

* Tamed Name : Rootling Boar
* Companion Type : Mount
* Mount Role : Ground Traversal / Forest Specialist
* Mount Category : Utility Mount → Terrain Specialist (Forest)
* Progression Tier : Normal (with potential Evolved variant)
* Acquisition Type : Taming (Wild Capture)
* Taming Difficulty : Medium
* Required Player Level : Low–Mid
* Applicable Systems : Mount System (Movement Speed, Terrain Modifiers, Mount Abilities, Progression)

---

		2. Taming Method

	Rootling Boars are territorial but not overly aggressive unless provoked, making them tamable through controlled interaction.

	Standard Taming Process : 
1. Locate a Rootling Boar within dense forest zones.
2. Reduce its HP to a safe taming threshold*(without killing it).
3. The boar must enter a fatigued or subdued state (post-combat).
4. Player initiates "Mount Taming Interaction".

---

		3. Secret / Unique Taming Mechanic

	"Rooted Trust" (Hidden Mechanic)

	To unlock enhanced bonding and improved mount quality:

* The player must :
	* Lure or engage the boar within dense root or vegetation areas
	* Allow the boar to use "Ground Rooting" at least once during the encounter

	Bonus Condition : 
* If taming is initiated while :
	* The boar is standing on root-covered terrain
* Then :
	* Higher taming success chance
	* Unlocks passive trait: "Forest Bond"

This reinforces the creature’s deep connection with its environment.

---

		4. Appearance (Tamed Variant)

	The tamed Rootling Boar retains its robust and grounded physique, but its presence becomes more stable and controlled under the rider.

	Its fur appears slightly cleaner and more defined, while the root-like growths along its back become more structured, almost forming a natural saddle-like 
surface. These hardened ridges provide both visual identity and functional support for mounted travel.
	Subtle traces of moss or plant life may remain along its back and shoulders, but instead of appearing wild, they seem integrated and balanced. In some variants,
faint glowing veins of earthy energy can be seen pulsing through the root structures when the mount is in motion, especially during bursts of speed.
	Its posture becomes more disciplined, and its movements more directed, responding smoothly to the rider’s input. Despite this, it retains its powerful, forward-
driving momentum, pushing through terrain rather than avoiding it.

