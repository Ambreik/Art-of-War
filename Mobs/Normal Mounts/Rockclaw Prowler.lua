			Rockclaw Prowler

---

		1. Basic Information

* Mount Name : Rockclaw Prowler
* Mount Class : Utility / Climbing Mount
* Mount Type : Cliff and rocky terrain traversal
* Taming Difficulty : Hard
* Habitat Origin : Windcaller Cliffs, Broken Stone Forest
* Required Tool : Utility Taming Kit
* Special Taming Condition : Must lure the creature onto stable ledges before initiating taming

---

		2. Appearance

The Rockclaw Prowler is a muscular, quadrupedal beast with jagged, stone-like scales that provide natural camouflage against cliff faces. Its limbs are thick and padded, ending in sharp, retractable claws specialized for gripping sheer rock surfaces. A short, rigid tail aids in balance on uneven ledges. Its head is angular with keen amber eyes, giving it a predatory yet intelligent expression. Dust and moss cling naturally to its body, blending it perfectly with rocky terrain.

---

		3. Core Attributes

* HP : Medium-High
* Defense : Medium
* Speed : Medium on flat ground, High on cliffs and rocky surfaces
* Mobility Type : Climbing / Vertical Traversal
* Role : Utility mount for steep and uneven terrain

---

		4. Mount Abilities

* "Cliff Grip" (Passive) : Can cling to vertical or near-vertical rock surfaces without falling.
* "Pounce Ledge" (Active) : Jump between ledges with precision, avoiding fall damage.
* "Stability Mastery" (Passive) : Immune to knockback effects from falling debris on cliffs.
* "Terrain Scout" (Active) : Increases player vision on uneven or rocky surfaces.
* "Rocklash Tail" (Active/Combat) : Quick tail strike for minor crowd control when on cliffs.

---

		5. Traversal Role

* Vertical cliff scaling
* Rocky ridge navigation
* Narrow ledge crossing
* Short distance jumps between elevated points

---

		6. Special Taming Mechanic

	Players must tame the Rockclaw Prowler using a precision climbing sequence :
1. Track the Prowler along cliff ledges or steep boulder fields.
2. Approach silently and match the creature’s pace to gain its trust.
3. Use the Utility Taming Kit when positioned on a stable ledge with minimal drop risk.
4. Complete a climbing mini-challenge sequence with timed movement inputs to finalize taming.

	Failure to maintain balance or approach too aggressively causes the Prowler to retreat or attack.

---

		7. Behavior While Mounted

* Moves fluidly along cliff faces, automatically adjusting grip.
* Tail and claws dynamically respond to terrain changes.
* Shows heightened alertness to environmental hazards like falling rocks or sudden gusts.

---

		8. Restrictions

* Limited speed on flat or soft terrain
* Cannot swim effectively
* Abilities ineffective on smooth or vertical metal/ice surfaces

