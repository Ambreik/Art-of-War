			Ambercrest Grazers

---

		1. Basic Information

* Mount Name: Ambercrest Grazer
* Mount Class: Pack Mount
* Mount Type: Large Plains Herbivore
* Taming Difficulty: Medium
* Habitat Origin: Open plains, gentle hills, and grasslands of Northspire Reach
* Required Tool: Standard Taming Kit
* Special Taming Condition: Can be tamed as adults, preferably in low-stress grazing environments

---

		2. Appearance

	A massive, sturdy quadruped with tawny-golden fur and thick horns curving back from the head. Muscular build with broad shoulders and strong legs, designed for 
carrying heavy loads and enduring long treks. Calm, alert eyes and a slow, deliberate gait convey docility if approached respectfully.

---

		3. Core Attributes

* HP: High
* Defense: Medium (natural hide, thick muscle)
* Speed: Low–Moderate
* Mobility Type: Terrestrial (plains, gentle slopes)
* Role: Cargo transport, pack traversal, stable mount for slow travel

---

		4. Mount Abilities

* "Heavy Haul" (Passive) : Increases carry capacity for the rider or attached cargo.
* "Stampede Shock" (Active) : Momentary forward charge; knocks back smaller creatures or obstacles.
* "Steady Stamina" (Passive) : Maintains movement endurance over long distances without tiring.
* "Terrain Adaptation" (Passive) : Can traverse soft soils, shallow mud, and gentle hills without penalty.

---

		5. Traversal Role

	Ideal for :
* Long overland journeys across plains
* Carrying supplies or multiple passengers
* Serving as pack animals for caravans or exploration parties

	Limitations :
* Poor performance in rocky or steep terrain
* Ineffective in forests, swamps, or narrow passes
* Low agility; cannot dodge attacks easily

---

		6. Special Taming Mechanic

1. Approach calm grazing Ambercrest Grazers in herds of 3–8.
2. Use "Standard Taming Kit" with food or soothing items to gain trust.
3. Mounting attempt succeeds after repeated exposure and positive reinforcement.

	Failure may result in the mount fleeing or defensive horn charges.

---

		7. Behavior While Mounted

* Slow and deliberate gait, stable for riders or cargo
* Can respond to gentle directional commands
* Emits low rumbles when startled, but remains mostly docile

---

		8. Restrictions

* Cannot traverse narrow cliffs or steep mountainous paths
* Slow movement outside plains or open terrain
* Cannot swim in deep waters efficiently

