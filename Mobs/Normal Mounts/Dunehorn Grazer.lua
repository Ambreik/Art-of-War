			Dunehorn Grazer

---

		1. Basic Information

* Mount Name : Dunehorn Grazer
* Mount Class : Pack / Utility Mount
* Mount Type : Plains Herbivore
* Taming Difficulty : Low–Moderate
* Habitat Origin : Open plains, grasslands, and gently sloped ridges west and south of Sunveil Town
* Required Tool : Standard Taming Kit
* Special Taming Condition : Must approach while grazing; sudden attacks reduce taming chance

---

		2. Appearance

	A large, horned quadruped with a long neck and sandy fur tones. Its body is sturdy and muscular, built for endurance rather than speed. Horns curve slightly 
backward, used for minimal defensive combat and herd signaling. Eyes are calm and observant; the hooves are wide, suitable for stable travel across plains.

---

		3. Core Attributes

* HP : Medium–High
* Defense : Medium
* Speed : Low
* Mobility Type : Ground / Plains traversal
* Role : Sturdy pack mount; can carry players and light cargo; steady over uneven grasslands

---

		4. Mount Abilities

* "Sturdy Stomp" (Active) : Minor AoE knockback around the mount; triggered when startled or panicked. Cooldown 20s
* "Pack Haul" (Passive) : Increases carried cargo weight by 25%
* "Trample Charge" (Active) : Slow frontal charge that lightly pushes small enemies; mostly utility
* "Terrain Adaptation" (Passive) : Reduces stamina drain over plains, grasslands, and shallow inclines

---

		5. Traversal Role

	The Dunehorn Grazer excels at :
* Long-distance travel across plains
* Light caravan support
* Stable platform traversal for resource collection

	It is not intended for mountainous terrain, cliffs, forests, or swamps.

---

		6. Special Taming Mechanic

* Tameable while grazing
* Approach slowly to avoid panic
* Feeding grass bundles or plains forage increases taming success
* Nearby predator presence reduces taming chance

---

		7. Behavior While Mounted

* Moves steadily with minimal sudden acceleration
* Panics if attacked or startled by predators, triggering minor AoE knockback
* Grazes passively when idle

---

		8. Restrictions

* Cannot traverse mountainous cliffs or water bodies effectively
* Cannot sprint; low speed mount
* Performance heavily affected by rough or forested terrain

