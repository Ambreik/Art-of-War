---

		8. Mount Abilities / Traits

---

	1. "Stonewalk Stability" : Aegiscar anchors itself to terrain while moving.

* Effect :
	* Cannot be easily displaced
	* Immune to knockback while mounted
	* Maintains balance on steep or uneven surfaces
* Mechanic : Core passive

---

	2. "Cliff Anchor" : Allows traversal of steep or near-vertical terrain.

* Effect :
	* Moves across:
		* Cliff edges
		* Steep rock inclines
		* Broken terrain
	* Prevents sliding or falling
* Cooldown : None (passive traversal trait)

---

	3. "Aegis Stance" : The mount locks itself into a defensive posture.

* Effect :
	* Greatly reduces incoming damage to rider
	* Prevents movement temporarily
	* Acts as a temporary “safe point”
* Cooldown : Medium–High

---

	4. "Seismic Step" : Each step creates minor ground impact.

* Effect :
	* Slightly disrupts nearby small enemies
	* Creates minor stagger effect in close proximity
* Mechanic : Passive environmental interaction

---

		9. Passive Bonuses

* Complete control on unstable terrain
* Immunity to forced dismount from minor effects
* Safe traversal across cliffs and broken paths
* Increased survivability while mounted

