			Aegiscar, the Bound Cliffwarden

	*(Cliffstone Guardian — Tamed Variant Mount)*

---

		1. Tamed Entity Overview

* Tamed Name : Aegiscar, the Bound Cliffwarden
* Base Creature : Cliffstone Guardian
* Companion Type : Mount
* Mount Role : Defensive Traversal / Cliff & Rock Specialist
* Mount Category : "Exotic Mount → Construct / Fortress-Type"
* Progression Tier : Late-Game / Exotic
* Acquisition Type : Partial Tame (Binding Ritual)
* Taming Difficulty : Very High
* Required Player Level : High
* Applicable Systems : Mount System (Advanced Traversal, Stability Mechanics, Environmental Interaction, Unique Mount Behavior)

---

		2. Exotic Mount Identity

	Aegiscar is not a creature that is “ridden” in the traditional sense—it is a bound construct, forced into cooperation through ancient mechanisms.

	This mount represents :
* Absolute stability over speed
* Mastery of vertical and hazardous terrain
* A mobile fortress-like presence

	Unlike organic mounts, Aegiscar does not respond to instinct—it responds to control and command.

---

		3. Taming Method (Partial Construct Binding)

	"Rite of Stone Binding"

This is not taming—it is binding a fragment of the construct’s will.

---

	Phase 1: Guardian Activation

* Player must locate an inactive "Cliffstone Guardian"
* Interact with ancient ruins or core fragments nearby
	This awakens the Guardian

---

	Phase 2: Core Exposure

* During combat:
	* Player must reduce Guardian HP to 30%
	* Trigger "Core Exposure Phase"
* The Guardian’s chest or core begins to glow
* Its defenses temporarily weaken

---

	Phase 3: Fragment Binding

	Instead of killing it :
* Player must :
	* Interrupt a reconstruction pulse
	* Interact with the exposed core

	This extracts a "Bound Core Fragment"

---

	Phase 4: Ritual Completion

* Player must bring the fragment to :
	* A ruin altar / stone forge
* Perform a binding ritual

	This creates : "Aegiscar "(Mount Form)

---

		4. Secret Mechanic — "Willbreaker Synchronization"

	During binding :
* If the player :
	* Avoids taking heavy damage during Core Phase
	* Successfully interrupts multiple abilities

	Then :
* Unlocks hidden trait : "Stable Core Matrix"

	Bonus Effects :
* Improved mount stability
* Reduced stamina drain
* Enhanced terrain control

---

		5. Appearance (Tamed Variant)

	Aegiscar no longer resembles a free-standing guardian, but rather a restructured construct designed for controlled movement. Its massive stone body has been 
altered, its form lowered and broadened to support a rider.
	Its limbs are thicker and more reinforced, moving with deliberate, mechanical precision rather than autonomous motion. The once-rigid torso has shifted into a 
more stable platform, with segments of its back flattening and locking into place to form a natural riding surface composed of interlocked stone plates.
	The glowing core that once powered its independent will is now partially contained and stabilized, its light dimmer but more controlled, pulsing rhythmically 
beneath layers of stone. Thin lines of energy trace across its body like cracks filled with molten earth-light, indicating the binding process that holds it 
together.
	Its movements are slow but unstoppable—each step is heavy, grounded, and absolute. When traversing cliffs or steep rock surfaces, its limbs anchor firmly, 
gripping terrain with unnatural precision, as if it becomes part of the environment rather than moving across it.
	When idle, it stands motionless like a carved monument. When commanded, it moves with purpose, like a siege engine given direction.

