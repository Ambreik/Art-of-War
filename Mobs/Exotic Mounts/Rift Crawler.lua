			Rift Crawler

---

		1. Basic Information

* Mount Name : Rift Crawler
* Mount Class : Exotic Mount (Late Game)
* Mount Type : Wall and ceiling traversal specialist
* Taming Difficulty : Very Hard / Advanced
* Habitat Origin : The Rift Caverns, Broken Stone Forest fissures
* Required Tool : Rift Harness (specialized climbing equipment)
* Special Taming Condition : Must lure creature onto a flat wall or ceiling using bait and maintain player stealth; mounts itself after repeated successful climbing
interactions

---

		2. Appearance

	The Rift Crawler is a sleek, spider-like creature with elongated limbs and retractable gripping pads at the ends of its legs. Its chitinous carapace shimmers 
with dark iridescence, reflecting the faint light of cavern bioluminescence. Multiple eyes glint in the dark, giving it an almost hypnotic appearance. Its abdomen 
is segmented with subtle muscle ridges, allowing agile bending for ceiling or wall traversal. Small, membranous flaps along its legs aid in balance and subtle 
gliding during drops.

---

		3. Core Attributes

* HP : Medium-High
* Defense : Medium
* Speed : Medium on ground, High on vertical surfaces
* Mobility Type : Wall/ceiling climbing, short glides
* Role : Exotic traversal mount for extreme vertical environments

---

		4. Mount Abilities

* "Ceiling Cling" (Passive) : Can attach to ceilings or vertical walls, allowing movement across otherwise inaccessible terrain.
* "Wall Run" (Active) : Burst movement along vertical rock faces, usable for both exploration and evasive maneuvers.
* "Rift Sense" (Passive) : Detects weak or unstable walls, fissures, or cavern edges for safe traversal.
* "Grip Claws" (Active) : Temporarily increase climbing speed or attach to slippery surfaces.
* "Short Glide" (Active) : Allows controlled drops from heights to safely land or traverse gaps.

---

		5. Traversal Role

* Vertical cliffs and cavern walls
* Ceiling navigation in Rift Caverns
* Extreme terrain exploration where standard mounts fail

---

		6. Special Taming Mechanic 

	Players must bait and interact with the "Rift Crawler" while remaining largely undetected:
1. Identify a vertical wall or cavern ceiling frequented by the creature.
2. Deploy bait to attract the Rift Crawler to climb near the player.
3. Perform repeated “climbing synergy” interactions (matching movement with Rift Crawler) without alarming it.
4. Once the creature trusts the player, use the Rift Harness to tame.

	Failure to synchronize movement or make noise causes the Rift Crawler to retreat into fissures.

---

		7. Behavior While Mounted

* Naturally clings to walls and ceilings, adjusting posture automatically.
* Moves slower on flat terrain but adapts speed on vertical surfaces.
* Can make sudden leaps or short glides when directed by the player.
* Responds to environmental hazards like loose stones, fissures, or strong gusts.

---

		8. Restrictions

* Ground speed is limited; best used for vertical traversal.
* Cannot traverse water or open plains effectively.
* Requires precise player input in complex climbing environments.

