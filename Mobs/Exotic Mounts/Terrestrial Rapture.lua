			Terrestrial Rapture – Mount Version

	File Name Suggestion : `Terrestrial_Rapture_Mount`

	Description (Appearance & Behavior) :

	Appearance : Full-size terrestrial rapture. Muscular limbs adapted for climbing and gliding short distances. Wings folded along back, rainbow-toned plumage, 
longer tail for balance. Keen eyes with a subtle glow, alert and aware of surroundings. Claws are large but non-lethal, designed for gripping cliff surfaces.
	
	Behavior : Calm, intelligent, and reactive to player commands. Stands on ledges with careful balance, adjusts stance when the player moves. Can perform short 
glides/jumps from cliff edges; reacts to wind gusts naturally.

	Mechanics / Interaction :

* Rideable : Can be mounted for terrestrial travel, cliff traversal, and short glides.
* Slow-Fall Assistance : Reduces falling damage by 50% when jumping from ledges.
* Minor Jump Boost : Helps reach elevated platforms or ledges.
* Taming/Loyalty System : Player must follow bonding sequence; higher loyalty improves mount responsiveness, agility, and unlocks idle animations.
* Fog Sensitivity : Mount prefers foggy environments (Veilfall Step); in clear weather may require extra player guidance.

	Gameplay Tie-in :

* Combines exploration, platforming, and environmental awareness.
* Encourages using environmental mechanics (fog, ledges) safely to reach hidden areas.
* Rewards patient players who interact carefully with the mount.

	Visual / Audio Flavor :

* Subtle wing flutters when starting movement.
* Tail sways naturally during traversal; feathers glimmer in sunlight.
* Emits soft cooing or chittering when idle, reacts to player commands with nods or minor movements.
* During cliff traversal or jumps, feathers shimmer slightly and dust/water particles trail behind lightly.

