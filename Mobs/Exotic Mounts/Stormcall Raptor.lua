			Stormcall Raptor

---

		1. Basic Information

* Mount Name : Stormcall Raptor
* Mount Class : Exotic / Aerial Mount (Limited)
* Mount Type : Apex aerial predator, suited for updrafts and cliff zones
* Taming Difficulty : Very Hard
* Habitat Origin : Windcaller Cliffs, Seabridge Arch
* Required Tool : Sky Taming Harness
* Special Taming Condition : Must be tamed mid-air during a dive near an active updraft column

---

		2. Appearance

	The Stormcall Raptor is a sleek, aerodynamic raptor with feathered wings that shimmer with a faint metallic-blue hue. Its talons are curved and razor-sharp, 
perfectly designed for gripping rock outcrops or riding strong updrafts. The head is crowned with a crest of stiff feathers that bristle in response to wind 
currents. Eyes are sharp and amber, glowing faintly when tracking movement below. Its plumage flows dynamically with wind, giving an impression of speed even while 
perched.

---

		3. Core Attributes

* HP : Medium
* Defense : Low-Medium
* Speed : Very High in air; moderate on cliffs
* Mobility Type : Flight / Aerial Maneuvering
* Role : Exotic aerial mount, scouting and rapid traversal

---

		4. Mount Abilities

* "Updraft Glide" (Passive) : Gains lift and speed when entering updraft columns; can sustain altitude longer.
* "Dive Strike" (Active) : Perform high-speed aerial dives, temporarily boosting movement and allowing limited mid-air attacks.
* "Wind Sense" (Passive) : Alerts player to approaching gusts or unstable air currents.
* "Cliff Perch" (Active) : Can perch safely on narrow ledges or cliff edges mid-flight.
* "Talon Grapple" (Active/Combat) : Grips surfaces or small enemies during aerial strikes.

---

		5. Traversal Role

* Long-distance aerial scouting
* Updraft-assisted climbs
* Rapid vertical and horizontal movement along cliff zones
* Mid-air jump and dive sequences for exploration or combat

---

		6. Special Taming Mechanic

	Players must time their approach with environmental updrafts :

1. Identify a strong updraft near cliffs or Seabridge Arch.
2. Enter flight (gliding or mounted aerial support if possible) to match the Raptor’s movement.
3. Perform a dive-sync sequence, staying within a narrow speed and altitude window.
4. Deploy Sky Taming Harness during synchronized flight.

	Failure to maintain the dive pattern or approach too aggressively causes the "Stormcall Raptor" to flee to higher altitudes.

---

		7. Behavior While Mounted

* Flies with dynamic wing adjustments responding to wind currents.
* Automatically stabilizes during gusts or turbulence.
* Can perform sharp turns or dives when the player directs.
* Responds to cliff-side hazards, avoiding collisions where possible.

---

		8. Restrictions

* Limited ground speed
* Cannot traverse deep water efficiently
* Requires skillful use in areas without wind currents

