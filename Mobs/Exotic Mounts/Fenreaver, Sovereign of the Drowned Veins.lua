		8. Mount Abilities / Traits

---

	1. Drowned Glide : Fenreaver moves effortlessly through water.

* Effect :
	* Removes all movement penalties in water
	* Allows smooth traversal across :
		* Swamps
		* Rivers
		* Delta zones
* Mechanic : Core aquatic movement passive

---

	2. Submerge Traverse : Allows partial submersion movement.

* Effect :
	* Rider lowers into water level
	* Reduces detection from enemies
	* Enables stealth-like aquatic movement
* Cooldown : Medium
* Mechanic : Tactical traversal ability

---

	3. Fenbreaker Charge : A powerful forward surge through water or mud.

* Effect :
	* Burst movement forward
	* Breaks through obstacles
	* Displaces small enemies
* Cooldown : Medium–High
* Mechanic : Mobility + environmental control

---

	4. Swamp Dominion (Passive) : Fenreaver thrives in swamp environments.

* Effect :
	* Increased stamina regeneration in water
	* Slight resistance to slowing effects
	* Improved control in murky terrain

