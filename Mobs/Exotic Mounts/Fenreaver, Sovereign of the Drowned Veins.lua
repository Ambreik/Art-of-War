		2. Exotic Mount Identity

	Fenreaver is not just a mount — it is a territorial apex creature bound through dominance rather than simple taming.

	This mount represents :
* Control over swamp and delta ecosystems
* Mastery of aquatic traversal
* A prestige mount with presence and weight

---

		3. Taming Method (Exotic Encounter)

	"Trial of the Drowned Veins"

	This is not a standard tame — it is a multi-step encounter :

---

	Phase 1: Lure the Apex

* Player must enter a deep swamp zone
* Trigger disturbance by :
	* Moving through water for extended time
	* Defeating smaller aquatic creatures

	This summons "Fenreaver" (Hidden Spawn Variant)

---

	Phase 2: Survival Trial

* Fenreaver becomes highly aggressive
* Player must :
	* Survive its ambush patterns
	* Avoid being dragged into deep water zones
	* Reduce its HP to critical threshold (NOT kill it)

---

	Phase 3: Submission Window

	At low HP :

* Fenreaver enters a "Dominance Struggle" state
* Player must :
	* Remain within water
	* Avoid leaving the swamp
	* Initiate taming while inside its domain

---

		4. Secret Mechanic — "Breath of the Fen"

	During taming :
* Player must not exit water for the entire channel duration

	If successful :
* Unlocks hidden trait: "Drowned Bond"
* Grants enhanced aquatic bonuses permanently

	If failed :
* Tame breaks instantly

---

		5. Appearance (Exotic Mount Variant)

	Fenreaver is a far more imposing and ancient version of the Fenback Crocodilian, its body appearing less like a creature and more like a living fragment of the 
swamp itself.
	Its scales are darker, almost blackened in places, with deep green undertones that shimmer faintly beneath layers of moisture and algae. The jagged ridges along
its back are significantly more pronounced, rising like natural spines formed from hardened root and stone. These ridges are interwoven with faint, vein-like 
channels that pulse subtly with dim, murky light, as if the swamp’s lifeblood flows through them.
	Its eyes glow faintly beneath the surface, no longer dull but instead carrying a slow, ancient awareness. When submerged, only the faint glow of its gaze and 
the silhouette of its ridged back betray its presence.
	When moving through water, it does not create chaotic splashes—instead, the water parts around it unnaturally, as if yielding to its presence. On land, it moves
slower but with overwhelming weight, each step heavy and deliberate, leaving deep impressions in mud and soil.

	When mounted, the root-like ridges along its back naturally form a stable riding structure, almost as if it was always meant to carry a rider.

