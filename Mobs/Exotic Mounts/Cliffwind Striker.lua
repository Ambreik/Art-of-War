			Cliffwind Striker

---

		1. Basic Information

* Mount Name : Cliffwind Striker
* Mount Class : Exotic Mount
* Mount Type : Updraft Rider / Vertical Traversal
* Taming Difficulty : Very Hard
* Habitat Origin : Sheer cliffs, updraft columns, foggy chasms, elevated coastal ridges
* Required Tool : Advanced Taming Kit
* Special Taming Condition : Requires interaction with active updraft columns

---

		2. Appearance

	The Cliffwind Striker is a powerful raptor-like avian with elongated wings and a narrow, aerodynamic body. Its feathers are dark along the spine and pale along 
the edges, designed to catch and read the wind. The talons are long and hooked, built for gripping rock faces and cliff edges. Its head is sharp and angular, with 
eyes that track vertical movement rather than horizontal prey.

	When perched, it faces into the wind, wings slightly open, feeling air currents constantly.

---

		3. Core Attributes

* HP : Medium
* Defense : Low–Medium
* Speed : High (situational)
* Mobility Type : Ground / Vertical / Cliff traversal
* Role : Vertical exploration and advanced elevation control

---

		4. Mount Abilities

* "Updraft Ride" (Active) : When inside an updraft column, the Striker rides the air vertically upward for several seconds, allowing access to high ledges and 
platforms.
* "Dive Glide" (Active) : From elevation, performs a controlled forward dive that converts height into forward distance.
* "Cliff Grip" (Passive) : Can stand and move safely on very narrow cliff edges without slipping.
* "Wind Sense" (Passive) : Automatically detects nearby updraft zones through subtle visual cues.
* "Aerial Balance" (Passive) : Reduced fall speed and no fall damage when descending from height.

---

		5. Traversal Role

	The Cliffwind Striker is designed for :
* Vertical maps
* Broken ruins and stairways
* Cliff-heavy regions
* Skilled traversal using environment mechanics

	It rewards players who understand terrain and wind behavior.

---

		6. Special Taming Mechanic

	This mount cannot be tamed on the ground.

	To tame it, the player must :
1. Locate an active updraft column
2. Climb to a nearby ledge above the Striker’s perch
3. Drop into the updraft so both player and creature are lifted briefly
4. Begin taming mid-air while both are suspended in the wind current

	If the player touches the ground, the attempt fails and the Striker relocates.

---

		7. Behavior While Mounted

* Wings constantly adjusting to wind direction
* Subtle leaning animations when near cliffs
* Sharp screech when entering updrafts

---

		8. Restrictions

* Difficult to control in tight interiors or forests
* Requires environmental elevation to be effective
* Not suitable for flat terrain travel

