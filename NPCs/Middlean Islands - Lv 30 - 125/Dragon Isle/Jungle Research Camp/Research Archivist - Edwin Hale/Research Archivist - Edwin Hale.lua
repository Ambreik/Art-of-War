			Research Archivist

---

	Name : "Edwin Hale"

---

	Type : Human NPC – Archivist / Observer

---

	Role : Research Archivist / Knowledge Keeper

---

	Location : Jungle Research Camp – roaming between key research points and quiet observation spots

---

	Overview : "Edwin Hale" is the silent observer of the "Jungle Research Camp", tasked with documenting everything that happens — from research findings to 
unexplained anomalies and behavioral patterns of both creatures and people.
	He moves quietly through the camp, recording notes with unwavering focus, often appearing detached from the dangers around him. His presence ensures that 
knowledge is preserved, structured, and made meaningful.
	Unlike others, Edwin does not contribute directly to survival — but without him, nothing learned would endure. His value lies not in strength, but in memory.

---

	Behavior : 
* Roaming NPC
	* Moves between:
		* Research stations
		* Observation points
		* Camp interior paths
* Frequently :
	* Writes in notebook
	* Observes NPCs and players
	* Pauses to “record” unseen details

