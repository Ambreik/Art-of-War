		NPC Characteristics

---

	Personality : 
* Observant
* Detached
* Intellectual
* Slightly unsettling

---

	Appearance : Edwin wears a long, dark coat that reaches his knees, paired with polished black boots. A black hat shadows his face, partially obscuring his 
expression behind thin-framed glasses.
	He constantly carries a notebook and pen, writing with quiet intensity. Even when danger is near, his focus rarely breaks — as if recording events matters more 
than surviving them.

