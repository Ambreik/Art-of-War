			Expedition Recruiter

---

	Type : NPC
	Role : Expedition Recruiter
	Affiliation : Jungle Research Camp / External Expedition Network
	State : Non-Combat / System Gateway
	Names : "Eris Valmyr"

---

		Description

	The Expedition Recruiter stands apart from the rest of the camp.
	While others react to the jungle, this one studies it.
	Clad in cleaner, more structured attire than the rest — reinforced leather with expedition insignias — the recruiter carries scrolls, maps, and sealed documents
rather than weapons. A satchel filled with contracts and marked routes hangs at their side.
	Their posture is composed.
	Their gaze is deliberate.
	They are not here to survive the jungle.
	They are here to organize those who will.

	A small table or crate nearby often holds :
* Rough maps of nearby islands
* Marked routes across waters
* Notes referencing places not yet known to the player

---

		Behavior

---

	Base State : 
* Stationary within camp (usually near edge or planning area)
* Interacts primarily through dialogue
* Observes players rather than reacting to environment

---

	The recruiter does not panic.
	Even when danger rises, they remain focused.
	Because their concern is not this moment.
	It is what comes next.

