---

		Description

	Expedition Guards are hardened fighters assigned to protect the fragile perimeter of the Jungle Research Camp.
	Unlike trained city soldiers, these guards are not polished — they are survivors. Their armor is mismatched, reinforced with whatever materials the expedition 
could salvage or carry. Leather layered over metal plates, jungle-worn boots, and weapons that show signs of constant use.
	Each guard carries the weight of long days and restless nights.
	Their eyes never settle.
	They constantly scan the treeline, the ground, even the air — as if expecting danger from all directions.
	Because here…
	It often comes from exactly that.

---

		Behavior

---

	Base State (Stable Camp) : 
* Patrol camp perimeter in short routes
* Maintain visual watch toward jungle edges
* Occasionally stop and observe surroundings

---

	They are alert, but not aggressive.

---

---

	Alert State (Suspicion / Minor Threats) : 

	Triggered by :
* Nearby unusual movement
* Player dragging enemies close
* Minor hazard triggers

---

	Behavior :
* Draw weapons
* Focus attention toward threat direction
* Prepare for engagement

---

---

		Combat State (Active Threat / Event)

	Triggered by :
* Pirate attack events
* Hazard breaches
* Hostile NPC proximity

---

	Behavior :
* Engage enemies immediately
* Prioritize :
	* Threats near camp center
	* Targets attacking NPCs
* Coordinate loosely with other guards

---

---

		Containment Response (Special Behavior)

	When :
* Hazard zones expand
* Environmental threats breach camp proximity

---

	Guards will :
* Move toward breach point
* Attempt to intercept threats
* Hold position rather than chase

---

	They defend, not hunt.

---

---

		Skill & Combat Design

---

	Expedition Guards are skillable, but not elite.

	They are designed to :
* Hold ground
* Support players indirectly
* Delay threats

---

	Combat Characteristics : 
* Balanced melee fighters
* Moderate durability
* Average damage output

---

---

		Abilities

---

	Guard Strike : 

	A standard melee attack with slightly increased threat generation.

	Used to :
* Maintain aggro
* Keep enemies focused on them instead of weaker NPCs

---

---

	Brace Position : 

	The guard plants their stance and reduces incoming damage for a short duration.

	During this :
* Movement speed is reduced
* Defense is increased

---

	Used when overwhelmed or protecting others

---

---

	Sweeping Blow 

	A short-range AoE attack.

	Used when :
* Surrounded by multiple enemies
* Effect :
	* Damages multiple targets
	* Slight knockback

---

---

	Rally Presence (Passive Interaction)

	When players fight near guards :
* Guards generate slight threat on nearby enemies
* Help stabilize chaotic fights

---

---

		Durability Mechanics

---

	Expedition Guards are tougher than normal NPCs but not invincible.

---

	Death Conditions : 

	They can be killed if :
* Overwhelmed by multiple enemies
* Left unsupported during events
* Camp instability is high

---

---

	Recovery Behavior : 

	After combat :
* Return to patrol routes
* Resume base state

---

