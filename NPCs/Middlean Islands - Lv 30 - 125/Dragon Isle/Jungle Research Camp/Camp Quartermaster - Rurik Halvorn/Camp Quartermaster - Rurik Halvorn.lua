			Camp Quartermaster

---

	Name : "Rurik Halvorn"

---

	Type : Human NPC – Expedition Logistics Officer

---

	Role : Camp Quartermaster (Supply Officer)

---

	Location : Jungle Research Camp – supply depot / storage area

---

	Overview : "Rurik Halvorn" is responsible for the survival of the Jungle Research Camp. Every crate, tool, ration, and piece of equipment passes through his 
hands. Where others see chaos, Rurik sees numbers, shortages, and priorities.
	He maintains strict control over incoming and outgoing supplies, constantly monitoring the camp’s condition and adjusting distribution based on necessity. His 
work ensures that research continues, defenses hold, and the camp does not collapse under pressure.
	Unlike most logistics officers, Rurik is no stranger to combat. When supplies are threatened, he defends them with ruthless efficiency, turning the camp’s 
defensive position into a controlled battlefield.

---

	Behavior : 
* Semi-static NPC
	* Remains near:
		* Supply crates
		* Storage structures
	* Delivery zones
* Frequently:
	* Inspects crates
	* Writes inventory notes
	* Interacts with dock runners (visual immersion)

