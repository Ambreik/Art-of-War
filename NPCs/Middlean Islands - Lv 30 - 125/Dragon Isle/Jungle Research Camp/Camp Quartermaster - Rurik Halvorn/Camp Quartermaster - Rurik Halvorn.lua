---

	Appearance : Rurik wears reinforced work gear layered with armor plating, built for both labor and combat. His hands are calloused, his posture grounded, and 
his movements efficient.
	Surrounded by crates, ropes, and tools, he looks more like a battlefield engineer than a merchant — someone who knows that logistics win wars long before swords
are drawn.

