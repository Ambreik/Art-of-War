			Hazard Surveyor

---

	Name : "Kael Strider"

---

	Type : Human NPC – Recon Specialist

---

	Role : Hazard Surveyor / Scout

---

	Location : Jungle Research Camp – perimeter zones, watch paths, outer edges

---

	Overview : "Kael Strider" operates on the edge of the camp — rarely seen standing still, always observing. Tasked with tracking environmental threats and 
mapping danger zones, he serves as the camp’s first line of awareness against both natural and hostile forces.
	Unlike the structured researchers or grounded quartermaster, Kael moves with the jungle itself — silent, precise, and unpredictable. He identifies threats long 
before they reach the camp and ensures others are warned before it’s too late.
	When danger escalates, Kael shifts from observer to hunter, using stealth and precision strikes to dismantle threats before they overwhelm the camp.

---

