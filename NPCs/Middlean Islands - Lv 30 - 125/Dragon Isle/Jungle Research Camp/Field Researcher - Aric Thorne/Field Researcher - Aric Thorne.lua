			Field Researcher

---

	Name : "Aric Thorne"

---

	Type : Human NPC – Senior Field Researcher

---

	Role : Lead Analyst & Research Processor

---

	Location : Jungle Research Camp – central analysis station (secured work area)

---

	Overview : "Aric Thorne" is a seasoned researcher and survival-hardened analyst, responsible for interpreting all collected data from the jungle. Unlike his 
assistant Liora, Aric is calm, methodical, and deeply focused, treating the island not as a threat, but as a complex system waiting to be understood.
	He rarely leaves his station, surrounded by organized tools, preserved specimens, and structured notes. Every sample brought to him is carefully examined, 
cataloged, and transformed into usable knowledge.
	Aric serves as the final step in the research process, converting raw discoveries into **Research Progress**, insights, and practical benefits for players.

