			Camp Medic

---

	Type : NPC
	Role : Field Medic
	Affiliation : Jungle Research Camp Expedition
	State : Non-Combat / Support

---

		Description

	The Camp Medic is rarely still.

	Moving between makeshift beds, supply crates, and injured bodies, this NPC embodies the strain of maintaining life in a place that constantly tries to take it 
away.
	Wearing a worn field coat, stained with layers of old and fresh blood, the medic carries a satchel filled with improvised tools — bandages, vials, stitched 
cloth, and crude instruments adapted for survival rather than precision.
	Their hands are steady, but not calm.
	Every movement is efficient, practiced, and slightly rushed — as if time is always about to run out.
	Their eyes are tired.
	Not from lack of sleep, but from repetition.

	Too many injuries.
	Too many close calls.
	Too many people brought in too late.

---

		Behavior

---

	The Camp Medic operates as a reactive NPC, meaning their function evolves depending on the state of the camp and surrounding activity.

---

	Base Behavior (Stable Camp State)

	When the camp is well-supplied and stable :
* Treats minor injuries
* Offers light recovery services
* Provides basic dialogue about recent incidents
* Remains within central medical area

---

---

	Instability Behavior (Low Supplies / High Danger) : 

	When the camp begins to destabilize :
* Movement becomes more urgent
* Dialogue becomes shorter, sharper
* May refuse non-critical assistance
* Focus shifts toward NPC survival rather than player comfort

---

---

	Critical State (Severe Instability / Attacks)

	During events such as :
* Pirate attacks
* Hazard escalations
* Supply collapse

---

	The medic :
* Prioritizes NPCs over players
* Moves between injured NPCs dynamically
* May temporarily stop offering services

---

---

		Player Interaction

---

	The Camp Medic does not function as a full healer.

	Instead, they provide :
* Limited, situational recovery

---

		Recovery Services

---

	Field Stabilization
* The medic treats the player using basic supplies.
* Effect :
	* Restores a small portion of HP
	* Removes minor status effects (Bleed, Poison – low tier)

---

	This is not a full heal.

	It is :
* Enough to keep going
* Not enough to ignore danger

---

---

	Emergency Patch

	A slightly stronger recovery option, available only when :
* Camp supplies are sufficient

	Effect :
* Moderate HP restoration
* Clears one active DoT effect

---

---

		Service Limitations

---

	Recovery services are affected by :
* Supply Chain state
* Camp condition
* Ongoing events

---

	If supplies are low :
* Healing is reduced
* Options may become unavailable

---

---

		Connected Mechanics

---

	Supply Chain Link

---

The medic directly reflects supply levels.

---

	High Supply State : 
* Full service availability
* Faster interaction
* Occasional bonus effects (slightly increased healing)

---

---

	Low Supply State : 
* Reduced healing
* Limited options
* Dialogue reflects shortage

---

---

	Critical Supply State : 
* Services may be disabled
* Medic focuses on NPC survival
* Players must rely on their own resources

---

---

	Hazard System Interaction

---

	When hazards escalate :
* Medic references injuries caused by :
	* Wildlife
	* Terrain
	* Environmental anomalies

---

	This reinforces :
* The danger is real
* The consequences are visible

---

---

		Mechanics Impact on Gameplay

---

	The Camp Medic creates a risk feedback loop :

---

	Players :
* Take damage in the jungle
* Return to camp for stabilization
* Notice changes based on camp condition

---

---

	This leads to :
✔ Awareness of supply systems
✔ Indirect pressure to maintain camp stability
✔ Reduced dependency on infinite healing

