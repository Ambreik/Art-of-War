			Injured Explorer - Survivor NPC

---

* Type : NPC
* Role : Injured Explorer / Survivor
* Affiliation : Jungle Research Camp Expedition
* State : Non-Combat / Vulnerable

---

		Description 

	This explorer is found far from safety, somewhere within the jungle — collapsed, barely conscious, and clearly on the edge of death.
	His clothes are torn and soaked, stained with mud and dried blood. One of his arms is tightly wrapped in a crude bandage, already leaking through. His breathing
is uneven, shallow at times, as if every inhale costs him effort.
	He does not call for help.
	He barely reacts when approached.
	Only when a player comes close does he stir — just enough to acknowledge presence, not enough to act.
	There is something unsettling about him.
	Not just the wounds.
	But what he has seen.

---

		Behavior

	The Injured Explorer exists in two possible states :

	1. Found in the Jungle (Critical State)

* Spawns randomly in jungle areas
* Lies on the ground, barely moving
* Cannot relocate on his own

---

	When approached, the player is given two interaction paths :

---

	A. Aid the Explorer : 

* The player may :
	* Place a "HP Potion" on the NPC
* Result :
	* The explorer regains partial strength
	* Slowly stands up
	* Delivers fragmented dialogue
	* Begins moving back toward camp

---

	This triggers :
* Follow-up Camp Event / Quest

---

---

	B. Kill the Explorer : 
* The player may :
	* Execute the NPC

---

	Result :
* NPC dies immediately
* Body remains temporarily

---

	Player can then :
* Return to camp and report the death

---

---

		Moral Design Impact

---

	This is not a “good vs evil” system.

	It is :
* Choice vs consequence

---

* Helping = delayed reward + narrative depth
* Killing = immediate simplicity + different outcome

---

---

		Camp Interaction Outcomes

---

	If Saved 

	When the explorer reaches the camp :
* A local quest is unlocked
* Camp NPCs react positively
* Additional dialogue becomes available

---

---

	If Killed

	When reported :
* Camp reacts differently (colder tone)
* No recovery quest
* Possible reduced trust (future expansion hook)

---

---

		Connected Mechanics

---

	Research Notes System

	The explorer provides :
* Fragments of information
* Hints about :
	* Jungle anomalies
	* Hidden areas
	* Dangerous zones

---

		Dynamic Dialogue System

---

	This NPC does not give structured quests directly (outside the rescue chain).

	Instead, he provides :	
* Fragmented memories
* Partial warnings
* Unreliable information

---

	His dialogue evolves based on :
* Player progress
* Discoveries made
* Time since rescue

