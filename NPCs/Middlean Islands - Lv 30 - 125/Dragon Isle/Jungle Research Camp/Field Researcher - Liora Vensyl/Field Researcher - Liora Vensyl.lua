			Field Researcher

---

	Name : "Liora Vensyl"

---

	Type : Human NPC – Field Research Assistant

---

	Role : Primary Field Research Coordinator (Quest Provider)

---

	Location : Jungle Research Camp – near plant study area / sample tables

---

	Overview : "Liora Vensyl" is a young but dedicated field researcher tasked with cataloging Dragon Isle’s flora and environmental anomalies. Though highly 
knowledgeable, she lacks field experience and is visibly uneasy within the dangerous jungle environment.
	She relies heavily on others to gather samples and observations, acting as the first point of contact for players engaging with the "Field Research System". Her
notes are detailed but often unfinished, reflecting both her curiosity and her fear of the unknown.
	When danger approaches, Liora abandons her post and retreats toward safer ground, prioritizing survival over research.

---

	Behavior : 

* Static / Semi-static NPC
	* Remains near :
		* Sample tables
		* Research tools
		* Plant study stations
* Frequently performs :
	* Writing notes
	* Inspecting samples
	* Looking around nervously

---

	Fear Response Behavior

	When danger is detected :
* Immediately stops all interactions
* Runs toward: Male Field Researcher (analysis station)
* Remains there until :
	* Threat is gone
	* Area is safe again

---

	Interaction Type : 
* Quest Giver (Primary)
* Non-combat NPC (Fragile)

---

	Combat Behavior : 
* Does NOT fight
* Does NOT defend herself

---

	On Threat Detection : 
* Attempts to flee
* Will not re-engage until safe

---

	On Death (Important Mechanic Decision)
* Chosen Design: Research Reset (Partial Failure, Not Full Loss)

---

	Effect :
* Active research task:
	* Fails current stage
* Player must:
	* Re-initiate task
* Previously discovered knowledge:
	* NOT lost

---

	Reasoning : 
* Punishes failure
* Avoids frustration
* Keeps system fair

---

		Quest Interaction

---

	Function : 
* Assigns :
	* Plant sampling tasks
	* Animal observation tasks
	* Anomaly investigation

---

	Behavior : 
* Provides context :
	* What to collect
	* Where to look
* Does NOT process results (that’s Male NPC role)

---

	Connected Mechanics : 
* Field Research System
* Research Progress

---

		NPC Characteristics

---

	Personality : 
* Intelligent but anxious
* Curious
* Easily startled
* Dedicated despite fear

---

	Appearance : Wears light expedition robes with multiple pockets filled with notes, tools, and sample containers. Her hands are often stained with plant residue,
and her equipment is slightly disorganized, reflecting her rushed and nervous working style.
	She constantly scans her surroundings, as if expecting something to emerge from the jungle at any moment.

---

		Quotes : 

---

	Idle / Ambient : 
* "I… I think that plant moved earlier… I’m not imagining it… right?"
* "There’s too much here… too much we don’t understand…"
* "I just need more samples… then it’ll make sense…"

---

	Player Interaction : 
* "You’re… you’re capable, right? I need help gathering samples."
* "Please be careful out there… the jungle reacts to everything."

---

	During Fear / Danger : 
* "No, no — not again!"
* "We’re not safe here!"
* "I knew this would happen!"

---

	After Returning to Safety : 
* "I’m sorry… I panicked… but we can continue."
* "Did you… see what that was?"

---

	Function Summary : 
* Entry point for "Field Research System"
* Assigns research tasks
* Adds vulnerability and realism to camp

