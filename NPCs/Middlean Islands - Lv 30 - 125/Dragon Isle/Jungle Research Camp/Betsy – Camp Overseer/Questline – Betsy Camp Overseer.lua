			Questline – Betsy Camp Overseer

---

		Quest 1 – "Signs in the Canopy"

---

	Objective : Investigate surrounding jungle for enemy scouts

---

	Description : 
* The Overseer suspects that pirates are watching the camp.
* Players are sent to patrol nearby jungle edges and confirm enemy presence.

---

	Tasks : 
* Search designated scouting zones
* Kill enemy scouts (if present)
* Retrieve 3 Proofs

---

	Proof Items (Examples) : 

* "Torn Pirate Insignia"
* "Signal Whistle"
* "Marked Dagger"

---

	Alternative (If No Scouts Spawn) : 

	Players find :
* Fresh Footprints
* Hidden Observation Markers carved into trees
* Recently extinguished campfire

These convert into : "Scout Activity Evidence"

---

	Return Objective : Report findings to Camp Overseer

---

	Design Purpose : 

* Introduces :
	* Exploration
	* Threat awareness
* Foreshadows :
	* Camp Defense Event

---

---

		Quest 2 – "Echoes Without Bodies"

---

	Objective : Investigate a disturbance reported during the night

---

	Location : "Shattered Grove" (small jungle clearing with broken vegetation)

---

	Description :
* Strange noises were heard during the night — combat, shouting, then silence.
* No patrol returned.

---

	Tasks : 
* Travel to Shattered Grove
* Investigate the area

---

	Findings : 
* Signs of battle :
	* Broken weapons
	* Blood traces
	* Destroyed terrain
* No bodies present

---

	Key Item : "Abandoned Expedition Backpack"

---

	Interaction : 
* Inspecting the backpack reveals :
	* Notes cut short
	* Signs of sudden disappearance

---

	Return Objective : Deliver the backpack to Camp Overseer

---

	Design Purpose : 
* Builds mystery
* Connects to :
	* Anomalies
	* Unknown threats

---

---

		Quest 3 – "Delayed Supplies"

---

	Objective : Recover missing supplies from "Blackwater Landing" and gather plant samples

---

	Description : 
* A shipment of "Empty Bottles" meant for research has not arrived.
* The Overseer sends the player to retrieve them and gather additional materials.

---

	Tasks : 
1. Travel to "Blackwater Landing"
2. Obtain:
	* "Bundle of Empty Bottles"

3. On return, collect :
	* "Emberleaf Fern"
	* "Glowcap Fungus"

---

	Return Objective : Deliver all items to Camp Overseer

---

	Design Purpose : 
* Links:
	* Camp ↔ Dock
* Introduces:
	* Plant system
* Reinforces:
	* Supply Chain dependency

