			Betsy – Camp Overseer

---

	Type : Human Settlement NPC – Expedition Leader

---

	Role : Leader of the Jungle Research Camp

---

	Location : Jungle Research Camp – central area, moving between key operational points

---

	Overview : "The Camp Overseer" is the acting authority of the" Jungle Research Camp", responsible for maintaining order, coordinating research efforts, and 
ensuring the survival of the expedition in a hostile and unpredictable environment.
	Unlike static leaders, the Overseer is constantly on the move, inspecting different parts of the camp, observing ongoing work, and responding to emerging 
threats. His presence reflects the current condition of the camp — calm and structured when supplies are stable, tense and reactive when the situation deteriorates.
	He serves as the primary link between players and the camp’s core systems, offering direction, purpose, and progression within the island’s jungle operations.

---

		Behavior : 

* "Roaming NPC"
	* Moves between :
		* Research areas
		* Supply storage
		* Containment zones
		* Camp perimeter
* Stops periodically to :
	* Observe NPC activities
	* Interact with environment elements
* Movement pattern reflects :
	* Camp activity
	* Supply state

---

		State-Based Behavior (Supply Chain Integration)

---

	High Supply (Stable / Full) : 
* Calm, composed demeanor
* Offers full interaction options
* Provides additional guidance and optional dialogue

---

	Low Supply (Strained / Critical) : 
* More urgent movement
* Shortened dialogue
* Focused on survival and stabilization
* May relocate more frequently toward :
	* Storage areas
	* Defensive positions

---

	Interaction Type : 
* Skillable NPC
* Quest Giver (Primary)
* Event Participant

---

	Quest Integration : 
* Provides 3 Major Quests

---

		Combat Behavior : 

---

	Engagement Condition : 
* Does NOT engage in normal combat
* Activates only during:
	Camp Defense Event (Pirate Assault)

---

		Combat Role : 

	Support / Control NPC

---

	Skills : 

* All abilities are :
	* AoE-based
	* Support-focused

---

	Skill 1 – Commanding Presence
* Type : AoE Buff
* Effect : 
	* Increases :
		* Player damage (+X%)
		* Movement speed (+X%)
* Duration: Short
* Visual : Subtle aura radiating from Overseer

---

	Design Purpose : 
* Encourages players to stay near him
* Creates defensive anchor point

---

	Skill 2 – Defensive Formation : 
* Type : AoE Protection Zone
* Effect : 
	* Reduces incoming damage for players inside area
	* Slight resistance to control effects
*Visual : Ground-marked defensive circle

---

	Design Purpose : 
* Provides survival tool during waves
* Helps less experienced players

---

	Skill 3 – Suppression Command
* Type : AoE Crowd Control
* Effect : 
	* Briefly slows and disrupts enemies
	* Interrupts weaker enemies
* Visual : Shockwave / command pulse

---

	Design Purpose : 
* Controls pirate waves
* Prevents overwhelm situations

---

	Skill 4 – Rally the Expedition : 
* Type : Emergency AoE Buff
* Trigger : Used at low camp HP / final wave
* Effect : 
	* Strong temporary buff:
		* Damage increase
		* Damage reduction
		* Faster recovery


---

	Combat Presence : 
* Remains near:
	* Central camp area
	* Strategic defensive points

---

		Event Mechanic – Camp Defense (Pirate Assault)

---

	Trigger Condition : 
* Player remains inside camp for minimum 3 minutes

---

	Event Flow : 

1. Mini-event quest is triggered : “Defend the Camp”
2. 3 Waves of Pirates attack the camp :
	* Increasing difficulty
	* Target:
		* NPCs
		* Camp structures
		* Player

---

	Overseer Involvement : 
* Actively participates in defense
* Uses support abilities to :
	* Aid players
	* Stabilize situation

---

	Outcome : 

* Successful defense :
	* Rewards player
	* Stabilizes camp temporarily
* Failure :
	* Camp enters unstable state
	* Affects :
		* Supply Chain
		* NPC availability

