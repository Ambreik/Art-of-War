			Dock Patrol

	Role : Skillable Combat / Patrol NPCs
	Location : Blackwater Landing – Dock Area
	Faction : Neutral (hostile to threats)

---

		Introduction / Narrative : 

	"Dock Patrols" are the trained defenders of Blackwater Landing. These skillful NPCs monitor the docks, piers, and storage zones, ensuring the safety of incoming
and outgoing ships. They are vigilant and coordinated, constantly walking their patrol routes and scanning for threats, while ready to engage any pirate incursions 
or hostile players.

	Clad in practical combat-ready attire — leather-reinforced tunics, boots with reinforced soles, and light armor — each Dock Patrol carries a spear, short sword,
or ranged weapon for quick response. Despite their readiness, they maintain a professional neutrality toward the average arriving adventurer, only reacting if 
danger arises.

---

		Core Attributes : 

* Level : 35–40 (scalable based on player group / event trigger)
* Rank : Elite / Skillable NPC
* HP / Defense : Medium; capable of taking some damage before fleeing or dying
* Movement : Patrolling dock, pier edges, cargo zones
* Aggro/Threat : Neutral by default; hostile if players interfere with dock operations or trigger events
* Respawn : Instant respawn after leaving safe zone or event ends

---

		Behavior & AI : 

* Default State : Patrol
* Roaming / Patrol Routes :
	* Dock Cargo Zone
	* Pier Edge
	* Storage Stacks
	* Outer Pier Perimeter
* Event Response :
	* Engage pirates or hostile players
	* Alert Dock Guardians if under threat
* Skillable NPC Mechanic :
	* Can be killed only outside the safe zone
	* Requires minimum 2 players or minimum 5 Rank III monsters to die
* Day/Night Behavior : Active at all times, maintaining patrols

---

		Interaction Mechanics : 

* CanTalk : No (except ambient shouts: “Move along!”, “Secure the crates!”)
* Quest Interaction : No
* Trade / Shop : No
* Player Interaction Notes :
	* Will attack if event triggers or player crosses into restricted dock area
	* Can participate indirectly in environmental puzzles or events (e.g., barrel chain explosions)

---

		Combat / Skills : 

* Weapons : Spear, short sword, ranged crossbow
* Skills :
	* Melee strike
	* Piercing ranged shot
	* Alert nearby Dock Guardians
* Behavior : Group tactics with other patrols; hold choke points and respond to threats efficiently
* Environmental Awareness : Patrol reacts dynamically to pirate incursions or triggered explosions

---

		NPC Mechanics / Event Integration : 

* Environmental Patrol : Maintain realism for the dock with visible presence and coordinated movement
* Threat Response : Attack hostile targets; call for reinforcements
* Skillable Death Mechanics : Enforced rules for player engagement (2+ players or 5+ Rank III monsters)
* Support for Mechanics : Can be used in mini-events (e.g., escort missions, dock sabotage, pirate raids)

