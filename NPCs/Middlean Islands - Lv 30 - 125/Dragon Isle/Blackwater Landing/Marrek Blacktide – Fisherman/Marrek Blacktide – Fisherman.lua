			Marrek Blacktide – Fisherman

	Role : Aquatic Specialist / Bait Provider / Sea Guide
	Location : Blackwater Landing – Near dock edge or fishing post
	Faction : Neutral

---

		Introduction / Narrative : 

	The Fisherman is a weathered local who has spent years navigating the dangerous waters surrounding Dragon Isle. Unlike most, he does not fear the sea — he 
respects it.

	He understands its patterns, its creatures, and more importantly… what lies beneath.

	While others see fishing as survival, he treats it as a controlled gamble with the unknown. He knows which bait draws fish… and which bait draws something far 
worse.

