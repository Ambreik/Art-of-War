		Behavior & AI : 

* Default State : Stationary (studying maps, writing notes)
* Activity Loop :
	* Examining map fragments
	* Drawing or updating charts
	* Reacting to player discoveries
* Event Response :
	* Remains in place during danger
	* Dialogue may change if rare discoveries are active on the island
* Awareness :
	* Detects when players carry specific items (map fragments, relics)
	* Triggers special interactions based on those items

---

		Interaction Mechanics : 

* CanTalk : Yes
* Primary Function : Exploration Support / Map Interpretation

---

	Dialogue Examples : 

* "This fragment… it does not belong to any chart I’ve seen."
* "You’ve been to the ruins, haven’t you? I can see it in the markings."
* "Maps lie. Fragments… they whisper the truth."

---

		Abilities & Core Mechanics : 

	1. Map Interpretation System

* Players can bring:
	* "Weathered Maps" (from pirates)
	* "Explorer Map Fragments"
	* Damaged or incomplete charts
* The Cartographer can:
	* Reveal true locations of hidden caches
	* Convert vague maps into usable objectives
	* Unlock**hidden markers on the player’s map

---

	2. Explorer Map Fragment Integration

* Directly linked to your Explorer’s Map Fragment mini-event

* Functions:
	* Combines fragments into complete maps
	* Tracks player progress in fragment collection
	* Unlocks:
		* Hidden treasure locations
		* Secret POIs
		* Optional mini-events

---

	3. Hidden Discovery Trigger System

* When players bring rare or complete map sets:
	* May unlock:
		* Hidden caches
		* Rare exploration encounters
		* Secret routes across the island

* Some discoveries are:
	* Not guaranteed (chance-based outcomes)
	* Unknown to players beforehand → reinforces exploration mystery

---

	4. Elara Connection Mechanic

* The Cartographer recognizes Elara’s influence

* Special Interactions:
	* If player has interacted with Elara recently:
		* New dialogue unlocks
		* Additional hints about relic locations

* Can indirectly guide players toward :
	* "Sky Relic Fragments"
	* "Whispering Ruins tablets"
	* Other relic-based mechanics

---

	5. Exploration Progress Tracking (Optional System)

* Tracks :
	* Number of fragments collected
	* Discovered POIs
	* Completed exploration tasks

* Can reward :
	* Minor buffs
	* Unique map upgrades
	* Rare hints instead of direct rewards

