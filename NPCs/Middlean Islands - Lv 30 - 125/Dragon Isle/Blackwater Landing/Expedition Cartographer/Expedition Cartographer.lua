			Expedition Cartographer

	Role : Exploration Specialist / Map Interpreter
	Location : Blackwater Landing – Map Table / Observation Area
	Faction : Neutral

---

		Introduction / Narrative : 

	The Expedition Cartographer is a scholar of forgotten paths and shifting landscapes, tasked with documenting Dragon Isle’s ever-changing terrain. Surrounded by 
maps, fragments, and ink-stained notes, this NPC studies every detail brought back by explorers — from crude sketches to ancient relic markings.

	Unlike the Harbor Quartermaster, who deals in goods, the Cartographer deals in knowledge. They are deeply fascinated by the island’s hidden structures, 
especially those tied to ancient dragon energy and lost civilizations.

	They speak in measured tones, often more interested in what players found than what they did. To them, every fragment is a piece of a larger truth waiting to be
uncovered.

