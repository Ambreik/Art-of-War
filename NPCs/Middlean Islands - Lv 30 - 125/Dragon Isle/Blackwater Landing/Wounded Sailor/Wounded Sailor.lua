			Wounded Sailor

	Role : Survivor / Information Broker
	Location : Blackwater Landing – Resting near crates or a sheltered corner
	Faction : Neutral

---

		Introduction / Narrative : 

	The Wounded Sailor is a broken remnant of a failed expedition — a man who has seen too much of Dragon Isle and lived to regret it. Sitting against crates or 
resting near a makeshift bed, his body is weak, but his mind remains sharp.

	He speaks in fragments, often drifting between reality and memory, recounting eerie encounters with the island’s dangers — ships dragged beneath the waves, 
whispers in the jungle, and pirates who vanish without a trace.

	Most dismiss him as delirious. Those who listen carefully, however, realize something unsettling:
		"he knows things he shouldn’t."

---

		Core Attributes : 

* Level : N/A (Non-Combat NPC)
* Rank : Unique / Special Interaction NPC
* HP / Defense : Minimal
* Movement : Stationary
* Aggro/Threat : None
* Reputation Impact : Neutral, but reacts differently to Smuggler-aligned players

---

		Behavior & AI : 

* Default State : Resting / Injured
* Activity Loop :
	* Sitting or leaning against objects
	* Occasional coughing, slow movements
	* Whispering or muttering
* Awareness :
	* Detects players entering a small “sight radius”
	* Tracks certain player activities (Smugglers, movement patterns)
* Event Response :
	* Dialogue shifts when global events are active
	* May hint at dangers before players encounter them

---

		Interaction Mechanics : 

* CanTalk : Yes
* Primary Function : Hidden Information System

---

	Base Interaction (Without Item)

	Provides:
* Eerie, unreliable stories
* Hints about:
	* Pirate activity
	* Underwater dangers
	* Strange island phenomena

---

	Core Mechanic – "Promised Fruit" System

	A rare interaction system tied to a specific item :
* Item : "Promised Fruit"
* Drop Source : All animal-type monsters on the island
* Drop Rate : ~3%

---

	Activation Method

* The fruit must be manually offered/placed on the NPC
* Each fruit = ONE piece of information
* Players must choose carefully what they want to know

---

	Unlocked Functions (Per Fruit Use)

	Each fruit allows the player to request one accurate information type :

	1. Global Event Awareness :

* Provides accurate info about :
	* Ongoing island-wide events
	* Event states (active, near completion, triggered recently)

---

	2. Rare / Elite / Boss Tracking : 

* Provides :
	* Spawn timers
	* Estimated respawn windows
	* General location on the island

---

	3. Ship Tracking System : 

* Provides :
	* Latest ship arrival
	* Exact timing in "h:m:s" format from docking moment

---

	4. Smuggler Activity Tracking : 

* Provides :
	* Name of Smuggler player
	* Last known location within his sight radius
	* Time since last seen

	*(Example: "That one… slipped through here… 3 minutes ago… heading inland…")*

---

		Abilities & Mechanics :

* Combat : None
* Passive Trait – "Broken Witness"
	* NPC has access to hidden world-state data
	* Acts as a manual information trigger system

* Limitation Mechanic :
	* One fruit = one answer
	* No stacking responses
	* No passive free information

---

		NPC Mechanics / System Integration

	1. Hidden Information Economy : 

* Converts a rare drop item into knowledge currency
* Forces :
	* Decision-making
	* Strategic use
	* Player trade potential (fruit can become valuable)

---

	2. Underwater Wreck Integration : 

* Provides subtle hints about :
	* Location of wreck
	* Danger level
	* Possible triggers

---

	3. Pirate Lore System : 

* Shares fragmented stories:
	* Missing ships
	* Pirate rituals
	* Strange behaviors tied to the "Sleeping Flame"

---

	4. Anti-Handholding Design : 

* Information is :
	* Accurate
	* But only when requested and paid for
* Keeps mystery intact while rewarding effort

