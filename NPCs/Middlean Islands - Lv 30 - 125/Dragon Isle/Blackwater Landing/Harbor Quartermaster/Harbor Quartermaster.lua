			Harbor Quartermaster

	Role : Supply Logistics Officer
	Location : Blackwater Landing – Cargo Management Area
	Faction : Neutral

---

		Introduction / Narrative : 

	The Harbor Quartermaster is responsible for managing all incoming and outgoing goods at Blackwater Landing. Surrounded by crates, manifests, and supply ledgers,
this NPC ensures that every shipment is accounted for — whether it’s food for expeditions, tools for exploration, or rare materials recovered from the island.

	Calm, methodical, and highly observant, the Quartermaster rarely leaves their post. Every crate has a destination, every shortage has consequences, and every 
delivery matters. They are not concerned with glory or adventure — only with keeping the fragile supply chain of Dragon Isle intact.

	To adventurers, the Quartermaster represents opportunity: a steady source of structured work tied to logistics, exploration, and survival.

---

		Core Attributes :

* Level : N/A (Non-Combat NPC)
* Rank : Civilian / Specialist
* HP / Defense : Minimal (protected by Dock Guardians)
* Movement : Stationary
* Aggro/Threat : None (non-combatant)
* Reputation Impact : Neutral, but interacts with Smuggler-aligned players differently

---

		Behavior & AI : 

* Default State : Stationary (working at cargo table or crate area)
* Activity Loop :
	* Reviewing cargo manifests
	* Inspecting crates
	* Writing or checking delivery logs
* Event Response :
	* Does not move during combat
	* May trigger emergency dialogue if dock is under attack
* Awareness :
	* Reacts to nearby activity (player interaction, cargo changes, quest triggers)

---

		Interaction Mechanics : 

* CanTalk : Yes
* Primary Function : Quest Provider (Logistics-Based)

		Dialogue Examples :

* "Supplies don’t move themselves. If you’re here to help, speak clearly."
* "We’re short on resources again. The jungle takes more than it gives."
* "Every crate lost is a delay we cannot afford."

---

		Quest Integration : 

	The Harbor Quartermaster is the main provider for Cargo Delivery quests, structured as part of the Dockside Quest Board ecosystem.

	Quest Types Provided :

*	"Cargo Transport"
	* Deliver supplies to:
		* Tidebreaker Cove
		* Jungle Research Camp
		* Exploration outposts
* "Supply Shortage Tasks"
	* Retrieve missing or stolen cargo
	* Recover supplies lost during pirate ambushes
* "Expedition Logistics"
	* Deliver tools or provisions to exploration teams
	* Assist in establishing temporary camps

---

		Abilities & Combat Mechanics : 

* Combat : None
* Defense : Protected by Dock Guardians and Patrols
* Passive Traits :
	* Cannot be displaced or interrupted during interaction
	* Always available for quest interaction unless under extreme event conditions

---

		NPC Mechanics / System Integration : 

	1. Cargo Delivery System (Core Mechanic)

* Acts as primary quest issuer for cargo-related missions
* Links directly to :
	* Tidebreaker Cove
	* Jungle Research Camp
	* Other future POIs

---

	2. Expedition Economy System

* Represents the logistical backbone of Dragon Isle
* Enables:
	* Resource circulation between POIs
	* Justification for recurring delivery quests
	* Dynamic supply-demand narrative

---

	3. Supply Shortage Logic (Expandable Mechanic)

* Occasionally, certain goods become "limited"
* Triggers :
	* Increased number of delivery quests
	* Optional higher rewards
* Can be expanded into :
	* Island-wide mini-events (shortage crisis)

---

	4. Smuggler Integration (Optional Layer)

* Players aligned with Smugglers may :
	* Receive alternative delivery routes
	* Unlock hidden or illegal cargo missions
	* Gain better rewards for Pirate Token-related exchanges

