			Dock Guardians

	Role : Elite Defensive NPCs / Area Control
	Location : Blackwater Landing – Key Defensive Points
	Faction : Neutral (hostile to threats)

---

		Introduction / Narrative : 

	"Dock Guardians" are the last line of defense at Blackwater Landing. Unlike the constantly moving patrols, these elite defenders are stationed at critical 
positions — near the main pier, supply stacks, and entry points into the dock’s safe zone.

	They are seasoned veterans, chosen not for speed, but for resilience and discipline. Their presence alone discourages trouble. Clad in reinforced armor and 
equipped with heavy weaponry, Dock Guardians stand firm against threats, whether it be pirate incursions or reckless adventurers pushing too far.

	They rarely speak, but when they do, it is with authority — their duty is clear: "hold the line, no matter the cost".

---

		Core Attributes : 

* Level : 40–75 
* Rank : Elite / Heavy Defender NPC
* HP / Defense : High; significantly more durable than Patrols
* Movement : Mostly stationary with limited repositioning
* Aggro/Threat : Neutral by default; highly aggressive when triggered
* Safe Zone Authority : Enforcers of safe zone boundaries

---

		Behavior & AI : 

* Default State : Stationary Guard
* Positioning :
	* Main Dock Entrance
	* Supply Storage Area
	* Central Pier Junction
* Movement Behavior :
	* Minimal movement; may take a few steps to intercept threats
	* Do not patrol — they anchor defensive zones
* Event Response :
	* Engage any hostile threat immediately
	* Support Dock Patrols in combat
	* Protect fleeing Dock Workers
* Combat Threshold Mechanic :
	* Can only be killed outside the safe zone
	* Requires:
		* Minimum 3 players, OR
		* Minimum 7 Rank III monsters

---

		Interaction Mechanics : 

* CanTalk : Very limited (short authoritative lines)
* Dialogue Examples :
	* "Hold your ground."
	* "No trouble within these docks."
	* "Step back, or face consequences."
* Quest Interaction : No
* Trade / Shop : No
* Player Interaction Notes :
	* Will not engage unless provoked or conditions are met
	* Instantly reacts to hostile actions within proximity
	* Acts as a soft boundary system for players testing limits of the safe zone

---

		Combat / Skills :

* Weapons : Heavy sword / halberd / shield
* Combat Style : Defensive, high-impact strikes
* Skills :
	* "Shield Slam" – High damage, short stun
	* "Guard Stance" – Reduces incoming damage temporarily
	* "Zone Control Strike" – Wide swing to control multiple enemies
	* "Reinforcement Call" – Alerts nearby Dock Patrols
* Behavior in Combat :
	* Holds position, prioritizes defense over chasing
	* Focuses on keeping enemies away from key areas
	* Coordinates with patrols rather than acting alone

---

		NPC Mechanics / Event Integration : 

* Safe Zone Enforcement :
	* Prevents hostile entities from overwhelming the landing
	* Acts as a natural barrier without hard restrictions
* Anchor Defense System :
	* Guardians define “safe pockets” within the dock
	* Their presence shapes player movement and safety perception
* Event Integration :
	* Strong response to pirate incursions or triggered chaos events
	* Can stabilize or escalate encounters depending on player actions
* Environmental Interaction :
	* Resistant to environmental hazards (barrel explosions, minor AoE effects)
	* Not easily displaced or interrupted

