			Harbormaster Selrik Tidewalker

---

		1. General Overview

* Name : Selrik Tidewalker
* Title : Harbormaster of Emerald Bay
* Role : Boat Rental NPC / Currency Exchange NPC / Island Questgiver / Respawn Anchor
* Faction : Neutral Maritime Authority (Capital City Expedition Navy Division)
* Location : Emerald Bay Dock, South-Eastern Coast of Asku’lan Island
* NPC Type : Utility Hub NPC / Travel System / Economy Conversion NPC
* Map Marking : Dock Anchor Icon + “Harbormaster Selrik Tidewalker”

---

		2. Appearance

	"Selrik Tidewalker" is a tall, weather-beaten sailor in his late 50s, shaped by decades of navigating unstable waters and storm-charged coastlines. His skin is 
heavily tanned and leathery, etched with salt burns and faint scars caused by rope burns and storm debris.
	He wears a long, dark naval coat reinforced with thick maritime rope bindings and metal clasps salvaged from shipwrecks. The coat is layered unevenly, 
suggesting constant repairs rather than replacement. A sea-worn tricorn hat sits loosely on his head, tilted slightly to one side, often vibrating subtly when 
strong winds pass through the dock.
	His boots are reinforced with heavy soles designed for wet, unstable surfaces, and his belt is cluttered with hooks, seals, navigation tools, and small 
containers used for cargo handling and currency storage.
	Around his neck hangs a cracked compass that never points consistently north — something he insists is “normal here.”
	He carries a brass spyglass and a heavily worn ledger filled with boat schedules, cargo logs, and Storm Shard conversion records.
	His eyes are sharp but tired, as if constantly measuring distance between safe harbor and disaster.

---

		3. Personality

	Selrik is practical, blunt, and highly transactional. He does not waste words on unnecessary warnings unless directly relevant to survival or cost.
	He treats Asku’lan not as an island, but as a risk system that must be navigated economically.

	To him :
* storms are operational delays
* monsters are hazard taxes
* players are temporary clients

	However, beneath his commercial mindset lies genuine survival experience. He has seen enough failed voyages to respect the island’s unpredictability, even if he
rarely admits it openly.
	He is one of the few NPCs who openly acknowledges that "some routes are not meant to be profitable."

---

		4. Core Functions

		Boat Rental System

	Selrik manages all maritime transport on Asku’lan.

	Players can rent boats for :
* Island traversal between POIs and coastal zones
* Resource gathering routes (fishing, exploration, harvesting zones)
* Capital City transport route (long-distance travel system)

	Mechanics :
* Travel time varies per route
* Boats have durability and can be damaged during storms
* Storm conditions may restrict or increase cost
* Optional “emergency travel surcharge” during high-risk weather

---

		Currency Conversion System

	Selrik operates a local economy conversion system tied to island monsters.

	Item: "Storm Shards"

* Dropped from Asku’lan high-tier monsters
* Represents storm energy crystallization from island environment

	Conversion :
* 10 × Storm Shards → 1 × Thunder Chest

	Thunder Chest Rewards :

* Rare island materials
* Herbal bundles
* Fishing supplies
* Totem-related puzzle fragments (Skyreach system integration)

	Selrik often refers to Storm Shards as:

> "Debt the island pays you… sometimes."

---

		5. Quest System

	Quest 1 — "Mapping the Hidden Shores"

	Objective :
* Explore 3 hidden coastal coves across Asku’lan

	Mechanics :
* Requires boat rental or traversal system usage
* Environmental hazards vary per cove
* Some areas may only appear during specific weather states

	Reward :
* Gold
* Rare fishing bait
* Minor navigation chart fragment (reveals hidden coastline nodes)

---

	Quest 2 — "Cargo Run Chaos"

	Objective :
* Deliver a fragile cargo chest to a designated POI under time constraint

	Mechanics :
* Cargo can be damaged by :
	* storm winds
	* enemy creatures
	* falling off boat / terrain hazards
* Players must choose safest route vs fastest route
* Optional escort or solo completion

	Reward :
* Gold
* Island crafting materials
* Storm Shards bonus drop chance

---

		6. Respawn Anchor System

	Selrik also functions as a respawn return point for Asku’lan.

	Upon player death :
* Player respawns at Emerald Bay Dock
* Temporary status effect applied:
	"Saltwater Fatigue" (minor movement reduction + visual blur effect)

	Selrik’s respawn line varies based on weather:

> "Sea didn’t want you. Dock did. Be grateful for that."
> "You’re back earlier than your cargo."
> "Storm must’ve liked you enough not to finish the job."

---

		7. Behavior

	Idle Behavior :
* Checks cargo crates for damage
* Updates ledger entries
* Observes horizon and wind direction shifts
* Occasionally adjusts boat ropes even when unnecessary

	Interaction Behavior :
* Turns toward player slowly, scanning equipment condition
* Responds differently depending on weather state
* Prioritizes business logic over conversation

	Storm Behavior :
* Cancels all boat rentals
* Locks conversion system temporarily if dock instability is high
* Warns players in short, direct statements only

---

