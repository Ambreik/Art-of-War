---

		9. Additional Notes

* Cannot be killed or removed (system anchor NPC)
* Fully tied to Asku’lan Weather Engine
* Currency system integrated with monster ecosystem (Storm Shards)
* Works in tandem with Dock Guardian NPC (defensive + environmental control role)
* Occasionally hints at “routes that shouldn’t exist” (future exploration hooks)

