			Dock Guardian Rask Veylor

---

		1. General Overview

* Name : Rask Veylor
* Title : Sentinel of Emerald Bay
* Role : Dock Guardian / Environmental Defense NPC / Combat Training Opponent / Event Reaction Unit
* Faction : Capital City Expedition Navy – Asku’lan Coastal Enforcement Division
* Location : Emerald Bay Dock, Asku’lan Island
* NPC Type : Combat NPC / Patrol AI / System Event Trigger Unit
* Map Marking : Shield Icon (Emerald Bay Perimeter)

---

		2. Appearance

	"Rask Veylor" is a broad-shouldered, heavily built man in his early 40s, shaped by years of exposure to violent coastal storms and constant maritime threats. 
His presence is less like a soldier and more like a fixed structure — something the dock relies on to remain stable.
	His armor is a reinforced hybrid of naval and military design: thick iron-plated chest armor over layered storm-resistant fabric, reinforced shoulder guards 
etched with weather-resistant runes, and heavy gauntlets designed for gripping wet surfaces or striking with blunt force.
	A long waterproof cloak hangs behind him, torn at the edges from wind erosion and constant exposure to lightning-static storms. The cloak occasionally flickers 
faintly during storm conditions, as if reacting to ambient electricity.
	His helmet is open-faced but reinforced along the brow and jawline, leaving his sharp, tired eyes visible. A faint scar runs from his left cheek down to his 
jaw — a mark from an early dock incursion.

	At his side rests a polearm designed for both combat and utility: it can hook ropes, push creatures off docks, and strike with controlled force.
	His boots are weighted and magnetized for stability on wet wood and unstable pier structures.

---

		3. Personality

	Rask is disciplined, alert, and permanently in a partial combat readiness state.
	Unlike Selrik, who treats the dock as a business node, Rask treats it as a breachable perimeter that must never fail.
	He does not relax, even during calm weather.
	However, he is not emotionless — he has a dry, tired humor that surfaces only during non-critical moments, especially when dealing with repeated seagull 
disturbances or reckless adventurers.

	He respects strength, discipline, and survival instinct above all else.
	Players who assist during dock events or survive harsh encounters earn his quiet approval.

---

		4. Core Functions

		Dock Defense System (Core Role)

	Rask acts as the primary defensive AI for "Emerald Bay Dock".

	He:
* Detects hostile entities near dock perimeter
* Engages threats automatically (PvE only unless spar mode enabled)
* Coordinates with environmental hazards (storms, wind bursts, seagull events)
* Protects NPCs: Selrik Tidewalker + dock infrastructure

	If multiple threats appear, he prioritizes :
1. NPC protection
2. Player protection
3. Environmental control

---

		Spar & Training System

	Rask functions as a high-difficulty combat trainer NPC.

	Players can :
* Initiate spar sessions
* Test builds (melee/ranged/tank behavior checks)
* Practice against environmental interference conditions (wind, rain, lightning modifiers)

	Mechanics :
* Scales with player level dynamically
* Gains buffs during storm conditions
* Uses adaptive AI (reacts to repeated player tactics)
* Cannot be permanently defeated (spar resets automatically)

---

		Weather Enforcement Interaction

	Rask is deeply tied to Asku’lan’s weather system.

	He reacts dynamically :
* Clears dock during extreme storms
* Locks combat spar mode during “blackout storms”
* Calls out environmental warnings to nearby players
* Physically anchors himself during high wind events (animation state change)

	He sometimes refers to storms as :

> "The island breathing too hard."

---

		Seagull Event Integration

	During Seagull Harassment Events :
* Rask actively engages birds using polearm swings
* Performs crowd-control "wide sweep attacks"
* Occasionally uses torch-push intimidation behavior (environmental interaction)
* Can coordinate with players if they assist

	If players ignore the event :
* Rask handles it alone, but becomes visibly more irritated in dialogue afterward

---

		5. Combat Behavior

	Standard Combat Style :
* Polearm-based melee control
* Wide-area sweeps for crowd control
* Defensive stance priority (rarely overextends)

	AI Traits :
* Aggro stabilizer (prevents dock chaos escalation)
* Targets fastest-moving threats first
* Adjusts positioning based on wind direction (unique mechanic)
* Gains reaction speed buffs during storm conditions

	Emergency Protocol :
* If dock is overwhelmed :
	* Activates “Perimeter Lock Stance”
	* Slows enemy movement near dock edges
	* Calls out environmental hazards verbally

