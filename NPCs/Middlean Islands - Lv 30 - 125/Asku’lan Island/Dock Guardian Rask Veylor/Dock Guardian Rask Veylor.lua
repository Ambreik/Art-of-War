		7. Environmental Behavior States

	Calm State : 
* Patrols dock perimeter
* Checks structural stability
* Observes horizon and sky movement

	Rain / Fog State : 
* Reduces visibility patrol radius
* Switches to auditory detection mode
* Warns players more frequently

	Storm State : 
* Activates defensive stance
* Restricts dock access zones
* Prioritizes NPC shielding behavior
* Gains lightning-reactive buffs

	Event State (Seagulls) : 
* Enters anti-swarm behavior mode
* Coordinates with players if present
* Uses crowd control instead of lethal force

---

		8. Additional Notes

* Cannot be permanently killed or removed
* Core part of "Emerald Bay Dock" ecosystem stability system
* Interacts directly with:
	* Weather system
	* Seagull event system
	* Boat rental system (indirect enforcement)
* Has hidden affinity system:
	* High player cooperation unlocks bonus spar dialogue
	* Ignoring events leads to colder interaction tone
* Seres as first line of defense for Asku’lan landing integrity

