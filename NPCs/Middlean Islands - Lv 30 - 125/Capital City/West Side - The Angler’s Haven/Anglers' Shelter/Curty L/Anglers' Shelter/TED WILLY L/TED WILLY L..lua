			TED WILLY L.

---

		Location : Capital City – Streets, Dockside Alleys, Market Lanes (Wandering NPC Route)

---

		Appearance :

	"Ted Willy L." is a weathered Angler in his early 40s, with sunburned skin and messy blond hair tied under a faded maritime bandana. His sharkskin armor is 
lighter than standard Angler gear, worn and flexible, reinforced only where needed for movement and quick reaction.
	He carries a fishing rod at all times, not as a tool of leisure, but as a practical survival weapon. The rod is visibly reinforced with metallic wrapping along 
its shaft, hinting at its secondary combat use.

	His fishing satchel is oversized and loosely packed, constantly shifting as he walks, filled with bait containers, rolled fishing lines, and tournament tokens.
	He moves with relaxed unpredictability, often stopping mid-walk to observe water reflections, stalls, or passing players.

---

		Personality :

	Ted is eccentric, enthusiastic, and slightly unstable under pressure. He behaves like a carefree fisherman most of the time, but switches into a hyper-reactive 
"combat instinct" mindset when threatened.

	He believes fishing intuition and combat instinct are the same thing — both rely on reaction, timing, and reading movement.
	He is friendly to most players but becomes unpredictable when his environment feels “disrupted.”

---

		Behaviour :

* Wanders predefined routes in Capital City (dock districts, markets, streets)
* Greets NPCs with waves, salutes, or silent observation
* Occasionally pauses to watch stalls, water, or crowd movement
* Spawns daily at "09:00 AM"
* Despawns automatically at "16:00 PM" (unless in combat state)
* Reacts dynamically to nearby fishing-related events or conversations
* During fishing tournament aftermath, becomes temporarily high-value interaction NPC

---

		Role :

* Role(s) : Wandering Angler Vendor / Event-Linked Shop NPC / Reactive Combat NPC
	"Ted Willy L." is a roaming specialist vendor who appears only during daytime cycles. He provides rare fishing supplies to high-tier Fisherman profession players 
and acts as a post-event reward vendor.

---

		Mechanics :

* Type : Wandering Vendor / Event NPC / Skillable Combat NPC
* Reputation : "Angler Profession Reputation" (restricted to Rank IV–V Fisherman only for shop access)
* Interaction Limitations :
	* Shop access only for "Fisherman Profession Rank" "IV" or "V"
	* General dialogue open to all players
	* Special inventory locked behind profession progression
* PvP :
	* PvP Enabled Zone NPC
	* Non-combat by default
	* Enters "Reactive Combat Mode" if attacked or threatened
	* Can trigger AoE counter-skills affecting ALL nearby entities (players + NPCs)
	* AoE actions may escalate global alert system (Guardian response trigger)
* Respawn Time :
	* Standard daily spawn cycle (09:00–16:00)
	* Immediate respawn next cycle regardless of prior death state
* Other Mechanics :
	* Post-Fishing Tournament interaction bonus window (30-minute time frame)
	* Sells seasonal fishing items :
		* bait variants
		* reinforced fishing lines
		* rare hooks and lure kits
	* Rare shop unlock: "Fishing Tabard" (available only if found within 30 minutes after tournament ends)
	* Combat trigger system :
		* Fishing rod used as melee weapon
		* AoE shock swings (area knockback + crowd disruption effect)
		* Accidental ally damage possible (including NPCs)
		* Automatically escalates local Guardian AI response

---

		Skills :

	Skill 1 : "Tidebreaker Swing"

* Description : Ted swings his reinforced fishing rod in a wide arc, using momentum and body rotation to strike multiple nearby targets. This is an instinctive 
counterattack triggered when he is surrounded or attacked.
* Effect :
	* AoE physical knockback
	* Medium damage to all nearby entities
	* Can interrupt enemy actions and stagger players
	* May hit unintended targets (NPCs included)

---

	Skill 2 : "Panic Current Burst"

* Description : A chaotic defensive reaction where Ted performs a rapid spinning motion, creating unpredictable strike angles with his fishing rod. It reflects his 
unstable combat instincts.
* Effect :
	* Random multi-hit AoE around Ted
	* Applies disorientation/stagger effect
	* High chance of collateral damage
	* Strong Guardian alert trigger

---

	Skill 3 : "Dockside Overreaction Protocol"

* Description : Triggered when Ted enters critical threat perception. He assumes he is under coordinated ambush and escalates force dramatically.
* Effect :
	* Large AoE shockwave attack
	* Forces nearby NPCs into “alert state”
	* Instantly triggers Guardian intervention response
	* After activation, Ted enters cooldown “calm-down” state

