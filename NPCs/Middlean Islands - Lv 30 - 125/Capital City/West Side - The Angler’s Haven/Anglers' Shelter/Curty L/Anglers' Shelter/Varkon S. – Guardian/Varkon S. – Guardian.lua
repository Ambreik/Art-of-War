			Varkon S. – The Tidewarden – SHELTER GUARDIAN

---

	Location : Anglers’ Shelter – Main Entrance / Dock Gate Perimeter

---

		Appearance :

	Varkon S. is a massive, heavily built guardian with a presence that contrasts sharply with the slender Anglers. His armor is a reinforced hybrid of steel plating and sharkskin layering, visibly thicker and darker than standard Angler attire.

	His face is partially covered by a water-resistant iron mask shaped like a breaking wave. Only his sharp golden eyes are visible. He carries a massive harpoon-like spear used both for combat and anti-boarding defense.

	A heavy anchor chain is wrapped around his back, symbolizing his role as “the one who keeps the Shelter grounded.”

---

		Personality :

	Silent, disciplined, and absolute in authority. Varkon speaks rarely, and when he does, it is direct and final.
	He has zero tolerance for smuggling conflicts escalating inside the Shelter, but paradoxically tolerates controlled illegal activity outside its gates 
	(dock-side rules).
	He respects Curty L. and answers only to him or higher Angler authority.

---

		Behaviour :

* Guards Shelter entrance and dock-facing perimeter
* Scans incoming players for threats or wanted status
* Intercepts PvP escalation inside Shelter boundaries
* Can arrest or forcibly remove hostile players
* Calls reinforcement Angler guards during high threat levels
* Occasionally steps into combat if elite threats appear nearby

---

		Role :

* Role(s) : Guardian NPC / Security Enforcer / PvP Control Unit
	Varkon enforces controlled chaos rules of the West Side district while maintaining order inside "Anglers’ Shelter".
	He is the only true authority capable of overriding PvP freedom inside the building zone.

---

		Mechanics :

* Type : Elite Guard / PvP Enforcement NPC
* Reputation : Angler Authority Rank (Independent from player reputation)
* Interaction Limitations : Restricted dialogue; only basic interaction unless player is flagged
* PvP : Fully PvP-Enabled Response NPC (can engage players in combat)
* Respawn Time : Instant reinforcement replacement system (if defeated, another Guardian spawns within 60–120 seconds)
* Other Mechanics :
	* Arrest system (teleport to detention zone / dock holding cells)
	* Anti-smuggling escalation response
	* Detects contraband trades inside Shelter
	* Can escalate into “Lockdown Mode” during invasions or raids
	* Coordinates with other Angler guards dynamically

---

		Quotes :

* "You step into the Shelter… you respect the water."
* "Order is not optional here."
* "Break the rules of the tide, and you drown in it."

