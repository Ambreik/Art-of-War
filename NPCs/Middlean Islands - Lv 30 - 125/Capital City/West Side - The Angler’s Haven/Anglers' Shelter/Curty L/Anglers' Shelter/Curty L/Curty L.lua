			Curty L.

--- 

	Location : West Side of Capital City / Anglers’ Shelter (main hall, coastal dock district)

---

		Appearance :

	"Curty L." is a tall, slender man of the Anglers lineage, with long blond hair often tied back in a loose ponytail. His sharp features and calm eyes give him a 
composed, almost ritualistic presence. He wears the traditional Anglers uniform: a white t-shirt beneath sleeveless armor made of dried shark skin, paired with 
reinforced gray pants crafted from the same material. The armor subtly reflects light like a wet surface, hinting at its hardened, wave-resistant properties.
	On his back is the unmistakable Anglers insignia: a silver fishing rod enclosed within a square with bent corners, set against a flowing wave-like pattern. He 
always carries a finely carved fishing rod in his left hand and a compact fishing kit strapped at his side. His posture is relaxed, but precise—like someone who has
spent a lifetime reading water currents more than people.

---

		Personality :

	Curty L. embodies the quiet discipline of the "Anglers" lineage. He is patient, observant, and speaks with measured confidence, often pausing as if considering 
the "current" of the conversation. He respects skill above all else, especially mastery of fishing techniques and knowledge of the sea.

	To outsiders, he can seem reserved or slightly distant, but to those within the "Fisherman Profession", he becomes unexpectedly warm and encouraging. He values 
tradition heavily, often referencing ancient Angler methods or forgotten fishing myths. However, he is not naïve—he is aware of the darker uses of maritime trade, 
including smuggling routes and illegal dockside dealings, and treats such matters with cautious neutrality unless they threaten the balance of the docks.

---

		Behaviour :

* Remains primarily inside the Anglers’ Shelter, observing players and fishing activities.
* Occasionally walks between interactive fishing stations during peak hours or events.
* Reacts dynamically to fishing tournaments, rare catch announcements, and Angler-related world events.
* Shifts tone and dialogue depending on player reputation within the Anglers system.
* Becomes noticeably more attentive and open to players showing mastery in fishing techniques or rare catches.

---

		Role :

* Role(s) : Major NPC, Fisherman Profession Master, Anglers Faction Leader (Capital Region Branch), Quest Giver, Vendor, Craft/Training Interface Provider.
	Curty L. serves as the central authority of fishing knowledge within Capital City. He trains Fisherman Profession players, unlocks advanced fishing mechanics, 
oversees seasonal competitions, and acts as a gatekeeper to elite Angler knowledge and legendary sea content.

