			Curty L. – Quest File (Anglers’ Shelter)

---

		1. Quest Title

	Title : "The Master’s Challenge"

---

		2. Quest Type
* Type : Legendary Quests / Profession Quests
* Category : Exploration / Combat-based / Environmental-Survival

---

		3. Quest Giver
* NPC/Location : Curty L. – Anglers’ Shelter, West Side of Capital City (Dock District)
* Quest Giver Description : Curty L. offers this quest after detecting a player with **Skilled Angler reputation** or higher. He initiates the dialogue after 
recognizing rare fishing achievements or completion of prior Anglers quests. The quest may also trigger during seasonal fishing events.

---

		4. Quest Objectives

* Primary Objectives :
	* Locate the seasonal spawn zone of the "Azure Leviathan"
	* Successfully catch the "Azure Leviathan"

* Secondary Objectives :
	* Survive environmental hazards during deep-sea fishing encounter
	* Optionally document the creature for Anglers research archives

* Thirdly Objectives :
	* Unlock hidden Leviathan migration pattern (chain discovery for future legendary fish systems)

---

		5. Quest Description

	"Curty L." challenges the player to prove mastery over the sea by hunting one of the rarest known aquatic creatures. The "Azure Leviathan" is not simply a fish, 
but a living phenomenon of the deep ocean, appearing only under unpredictable seasonal conditions.

---

		6. Quest Rewards

* Primary Rewards :
	* Massive XP reward (Fisherman Profession scaling bonus)
	* Anglers REP increase (Curty L.)

* Secondary Rewards :
	* "Legendary Fishing Rod" (boosts rare/legendary catch rate)
	* Unlock: Hidden deep-sea fishing zones

* Optional Rewards :
	* Choice between :
		* Stability buff for fishing (reduced failure rate)
		* Increased legendary spawn detection range

---

		7. Quest Conditions

* Prerequisites :
	* Skilled Angler Reputation (minimum rank required)
	* Completion of at least 1 Curty L. profession quest
* Fail Conditions :
	* Leaving fishing zone during Leviathan encounter
	* Death during deep-sea event phase
	* Missing seasonal spawn window

---

		8. Quest Locations

* Start Location :
	* Anglers’ Shelter (Curty L. interaction point)
* Important Locations :
	* Open sea dynamic spawn zone (seasonal coordinates)
	* Deep-water hazard region (storm/tide event layer)
* End Location :
	* Anglers’ Shelter (return for validation and reward)

---

		9. Quest Dialogue & NPC Interaction

* Quest Initiation : "The sea does not reveal its kings easily… but it has chosen to reveal one to you."
* In-Quest Dialogue : "Do not chase it like prey… listen to the water. It will tell you where to stand."
* Quest Completion Dialogue : "So the Azure Leviathan has surfaced for you… the ocean has acknowledged your patience."

---

		10. Quest Mechanics & Gameplay

* Core Gameplay Tasks :
	* Rare fish tracking system
	* Dynamic spawn detection mechanic
	* High-risk fishing combat-like timing system
* Special Mechanics :
	* Leviathan appears only under specific environmental conditions
	* Multi-phase fishing struggle (stamina, timing, resistance system)
	* Storm interference affecting catch stability

---

		11. Quest Progression & Timeline

* Quest Phases :
	1. Receive Leviathan signal (world event trigger)
	2. Travel to spawn zone
	3. Tracking phase (movement prediction minigame)
	4. Capture phase (multi-input fishing struggle)
	5. Extraction phase (return confirmation)
* Cooldowns & Timers :
	* Seasonal spawn only (cannot be repeated until next cycle)

---

		12. Optional or Hidden Content

* Hidden Objectives :
	* Discover secondary Leviathan shadow variant (rare encounter version)
	* Identify alternate spawn anomaly locations
* Alternative Endings :
	* Successfully capture Leviathan alive (perfect completion)
	* Fail capture but obtain partial scale fragment (lower reward path)

---

		13. Post-Quest Impact & Continuity

* Unlockables :

	* Legendary fishing tier progression
	* Access to Curty’s advanced mentorship path
* Character Relationships :
	* Curty L. gains higher trust and may offer future “secret sea knowledge” quests
	* Unlocks hidden Anglers expedition chain

---

		14. Miscellaneous Notes

* Easter Eggs or Lore :
	* Leviathan is part of ancient sea migration myth known only to Anglers lineage
	* References lost expedition journals in Anglers Shelter displays

* Player Agency : Player can abandon tracking or attempt early capture (risk-based outcome system)

---

		15. Quest Closure & Debriefing

* Resolution : If successful, Curty formally acknowledges the player as someone the sea has “recognized,” marking a major Fisherman progression milestone.
* Post-Quest Reflection :
	Curty may remark : "The ocean did not lose a creature today… it simply decided to show you one of its oldest memories."

