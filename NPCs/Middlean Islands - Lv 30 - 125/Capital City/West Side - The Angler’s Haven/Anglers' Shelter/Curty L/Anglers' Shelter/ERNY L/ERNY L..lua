			ERNY L.

---

	Location : Anglers’ Shelter – Main Hall (Training Platforms / Technique Stations)

---

		Appearance :

	"Erny L." is a tall, slender Angler in his late 30s, with long blond hair tied into a tight ponytail and a few strands falling over his sharp, focused face. His
eyes are pale blue and constantly scanning movement, as if calculating trajectories even when idle.
	He wears the standard Angler uniform: a white fitted shirt under sleeveless sharkskin armor, reinforced with layered stitching along the arms and chest. His 
gray sharkskin trousers are slightly worn from constant movement on wet decks. Around his waist hangs a compact fishing kit filled with specialized hooks, weighted 
lines, and bait capsules.

	He carries a modified fishing rod that is shorter and more rigid than standard ones — clearly designed for precision rather than distance.

---

		Personality :

	Erny is strict, analytical, and highly technical. Unlike Curty L., who teaches philosophy and mastery of fishing, Erny focuses on precision and efficiency. He 
speaks in short, direct sentences and often corrects players mid-action.

	He respects discipline above talent and believes fishing is a controlled combat discipline, not a hobby.

---

		Behaviour :

* Constantly moves between training stations inside the Shelter
* Observes players attempting fishing techniques
* Interrupts failures with corrections or challenges
* Occasionally demonstrates perfect casting mechanics in real time
* Can refuse interaction if player lacks basic Fisherman progression

---

		Role :

* Role(s) : Advanced Fishing Technique Trainer / Skill Progression Instructor
	Erny L. is responsible for refining player execution in fishing mechanics.He unlocks advanced techniques tied to timing, precision casting, deep-water tracking,
and rare fish behavior prediction.

	He acts as a secondary progression gate after Curty L.

---

		Mechanics :

* Type : Trainer / Quest Giver
* Reputation : Angler Reputation (shared progression with Curty L., but weighted toward technical mastery unlocks)
* Interaction Limitations : Requires Fisherman Profession unlocked + Novice Angler rank minimum
* PvP : Non-PvP (Protected Angler NPC – cannot be attacked; Guardian NPCs respond if attempted)
* Respawn Time : N/A (Persistent Major NPC)
* Other Mechanics :
	* Unlocks advanced fishing techniques (precision timing, rare catch prediction)
	* Provides "Fishing Mastery Trials" (skill-based challenges)
	* Improves efficiency of rare fish encounters
	* Can override Curty L. tutorial restrictions once player reaches Skilled Angler

---

		Quotes :

* "Your timing is off. The fish already escaped before you reacted."
* "Fishing is not patience. It is prediction."
* "Show me precision, not effort."

