			Historian Jaren — Lorekeeper of the Second Great War

* NPC Type : Lore / Storytelling NPC
* Location : Pilgrim’s Sanctuary — Archive Hall (Study Wing, near scroll vaults)
* Role : Historical Chronicler & Interactive Lore Narrator
* Interaction Type : Dialogue-based lore progression + unlockable codex entries
* Unlock Requirement : Accessible upon entering Pilgrim’s Sanctuary (no level lock), but deeper chapters unlock through Sanctuary progression quests and Pilgrim 
reputation

---

		Appearance

	"Historian Jaren" is an elderly human scholar with a posture slightly bent from years spent over ancient tomes and stone tablets. His long, ash-gray hair is 
tied back loosely with a worn leather cord, and strands often fall across his face while he writes.
	He wears layered archival robes in muted tones of brown and deep blue, stitched with faded insignias from lost factions of the Second Great War. Around his neck
hangs a small metal seal bearing the emblem of the old Alliance Council.
	His hands are ink-stained, trembling slightly when he speaks of certain events—not from weakness, but from memory weight.

	A floating set of enchanted parchment sheets or a self-turning chronicle book hovers beside him, recording everything he narrates in real time.

---

	Personality : 

* Calm, precise, and deeply reflective
* Speaks in a structured narrative tone, often shifting between objective history and emotional interpretation
* Becomes noticeably more solemn when recounting betrayal, war events, or divine interference
* Treats history as something "alive", not just recorded facts
* Avoids judgment unless describing confirmed atrocities or heroic sacrifice

---

		Core Role — HISTORICAL ARCHIVE SYSTEM

	Historian Jaren functions as the primary lore access point for the "Second Great War" era and pre-Expansion II world events.

	He does NOT give combat quests or material rewards. Instead, he unlocks :
* World history codex entries
* Region background revelations
* Faction origin stories
* Event reconstruction sequences
* Hidden lore flags tied to exploration achievements

---

		Mechanics & Systems

		1. Echo Memory Reconstruction System

	Jaren can "replay" historical events as interactive narrative scenes.

* Players can enter reconstructed memory zones such as :
	* Nakazamian Castle diplomatic collapse
	* Siege of Emberwaste
	* Battle of Abyssal Gorge
* These are non-linear lore simulations, not combat dungeons
* Players may walk through events as observers or limited interactors

---

		2. Codex Unlock Progression

	Each chapter unlocks progressively :
* Chapter access depends on :
	* Pilgrim Reputation Rank
	* Completion of Sanctuary NPC storylines
	* Discovery of world relics tied to historical events

	Unlocked entries include:
* Timeline of factions
* Key heroes (e.g., General Alithar, Captain Lyra, Mage Eldros)
* Divine intervention records (Thundralis, Horras, Zarrah)
* Artifact disappearance logs (e.g., Ebon Spear)

---

		3.  World Context Flag System

	Jaren can flag global world state understanding :

* Unlocks hidden dialogue options in :
	* Military NPCs
	* Scholars
	* Certain dungeon lore gates
* Enables “You know this already” branching dialogue paths in other systems

---

		4. Player Inquiry System

	Players can ask Jaren about :

* Specific locations (e.g., "Nakazamian Castle")
* Historical figures
* War factions
* Ancient wars and treaties
* Myth vs confirmed history distinctions

	Responses vary depending on :
* Player progression
* Lore discoveries
* Pilgrim reputation

---

		5. Relic Cross-Reference Mechanic

	If a player carries certain historical items:

* Jaren reacts and expands lore dynamically
* Example :
	* Ebon Spear fragment → unlock Abyssal Gorge deeper truth layer
	* War relic → reveals missing battle timeline gaps

