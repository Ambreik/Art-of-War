			Seer Kira — Oracle of the Veil of Shadows

* NPC Type : Lore / Vision / High-Lore Narrative NPC
* Location : Pilgrim’s Sanctuary — Obsidian Reflection Chamber (Inner Hall, Dimlight Wing)
* Role : Underworld Lore Oracle + Vision System Guide
* Interaction Type : Vision-based storytelling, prophecy unlocks, moral-alignment lore tracking
* Unlock Requirement : Available after entering Pilgrim’s Sanctuary; deeper visions unlock at Pilgrim Rank progression and after exposure to Underworld-related 
content

---

		Appearance

	Seer Kira is an ethereal, unsettlingly calm figure seated in a circular chamber lined with faintly glowing obsidian pillars. The room is always dim, regardless 
of external lighting, as if light itself is partially absorbed.
	She has pale skin with faint luminous veins that subtly pulse when she channels visions. Her long hair is dark with shifting silver strands that appear to move 
like smoke rather than strands.
	Her most defining feature is the obsidian mirror she constantly gazes into — a floating, fractured surface that does not reflect the room, but instead shows
shifting scenes from other realms, often inconsistent and partially corrupted.
	Her robes are layered, light, and almost weightless, adorned with thin ritual bindings and arcane seals that gently float around her like restrained fragments 
of reality.

---

	Personality : 
* Soft-spoken, calm, and emotionally detached in tone
* Speaks as if partially aware of multiple timelines simultaneously
* Never fully confirms what is “true” or “seen”
* Treats fate as fluid rather than fixed
* Becomes more fragmented in speech when discussing the Underworld Realm
* Occasionally pauses mid-sentence as if receiving overlapping visions

---

		Core Role — UNDERWORLD PROPHECY SYSTEM

	Seer Kira functions as the primary narrative gateway to the "Underworld Realm", "Abyssal Entities", and moral consequence systems tied to player progression.**

	She does NOT provide combat quests directly. Instead, she governs :
* Vision-based world warnings
* Underworld entry lore unlocking
* Moral consequence foreshadowing
* Hidden realm discovery triggers
* Seal of Binding progression system

---

		Mechanics & Systems

	1. Vision Fragment System

	ira grants vision fragments instead of standard dialogue rewards.

	Players receive :
* Short interactive vision scenes
* Fragmented lore clips
* Symbolic warnings about future zones or dungeons

	These visions may include :
* Underworld portals opening in real-time world locations
* Death echoes of “Fallen Souls”
* Flash-forward glimpses of corrupted regions
* Entity appearances (Abyssal Ones)

	Visions are partially randomized but influenced by :
* Player level
* Exploration history
* Corruption / moral flags (if applicable system exists later)
* Underworld-related item possession

---

		2. Underworld Access Hint System

	Kira does NOT open portals directly — she reveals conditions :
* Celestial alignment hints
* Ritual locations
* Environmental triggers (ruins, cursed forests, drowned temples)
* Time-sensitive world states

	This creates :
* Exploration-driven discovery loop
* Hidden dungeon emergence system without direct teleportation

---

		3. Moral Echo System (Passive Layer)

	Kira subtly tracks player narrative alignment :
* She does NOT assign “good/evil” labels, but reacts to:
	* Repeated violent choices
	* Mercy-based decisions
	* Interaction with cursed or forbidden systems

	Effects :
* Dialogue shifts in tone
* Visions become darker or more distorted
* Certain lore paths unlock earlier or become unstable

---

		4. Seal of Binding Progression Thread

	Kira is the primary narrative anchor for the "Seal of Binding arc"

	She provides :
* Fragmented lore pieces of the Seal
* Location hints of broken seal shards
* Insight into “why the seal is weakening”
* Connection to Abyssal One entities

	Progression is multi-stage :
1. Awareness of the Seal
2. Discovery of corruption signs
3. Partial seal fragment recovery
4. Underworld breach warnings
5. End-state event foreshadowing (future expansion hook)

---

		5. ️ Reality Overlap System

	When near Kira, players may experience :
* UI distortion effects (visual only)
* Temporary world “echo overlays”
* NPC shadow duplication (non-interactive illusions)
* Whisper audio fragments

	These effects intensify based on :
* Time spent in Sanctuary
* Number of vision fragments unlocked

