---

		Mechanics & Functions

	Sacred Purification System

* Harlos introduces a system where :
	* corrupted zones can be cleansed
	* sanctified areas may temporarily gain buffs
	* repeated cleansing increases sanctuary influence

	This reinforces long-term world stability mechanics.

---

		Defensive Event System

	He is tied to :
* wave defense events
* shrine protection missions
* escort-style sacred operations

	These events scale with player level and zone corruption severity.

---

		Corruption Detection Layer (Passive System Hook)

	When players enter his radius :
* corrupted players may trigger unique dialogue
* heavily corrupted players may be refused quest access
* certain NPC interactions may change based on corruption state

---

			Trial Authority System

	Harlos acts as :
* gatekeeper for combat-based progression inside the sanctuary
* validator of "worthiness through action"

	Some sanctuary doors or interactions may require his approval.

---

		Reputation System — "Sanctuary Wardenship"

	Players gain reputation through :
* shrine cleansing
* defensive quests
* completing Eternal Flame questline

	Unlocks :
* advanced PvM resistance buffs
* access to higher sanctum trials
* unique defensive crafting recipes
* dialogue variations acknowledging “sanctuary defender status”

