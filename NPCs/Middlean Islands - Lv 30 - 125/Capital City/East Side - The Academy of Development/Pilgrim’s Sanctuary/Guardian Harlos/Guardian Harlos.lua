			Guardian Harlos

	Basic Information

* Name : Guardian Harlos
* Title : Defender of the Sacred Path
* Race : Human
* Gender : Male
* Location : Pilgrim’s Sanctuary — Outer Shrine Corridors / Sacred Fountain Approach
* Role : Sacred Defender / Corruption Purger / Combat Trial NPC
* Faction Association : Order of the Sanctum (Neutral-Aligned Protective Order)
* Availability : Permanent

---

		Appearance

	"Guardian Harlos" is a battle-hardened warrior clad in worn but sacred armor forged from pale steel and reinforced with faintly glowing sanctified runes. His 
armor is not ceremonial—it bears scratches, cracks, and repaired sections, each marking a past conflict against corruption and blight.
	A deep blue cloth mantle hangs over his shoulders, embroidered with the symbol of a sealed flame surrounded by a circular oath-ring. His chestplate carries 
faint burn marks that never fully fade, as if touched by divine fire.

	His face is stern and weathered, marked by old scars crossing his cheek and brow. His eyes are sharp and focused, constantly scanning his surroundings as if 
expecting an unseen enemy to emerge at any moment.

	He carries :
* A heavy sanctified longsword engraved with oath inscriptions
* A round ward-shield marked with purification seals

	When idle, his sword remains planted into the ground beside him, as he stands in silent vigilance.

---

		Personality

* Disciplined and duty-driven
* Serious, rarely humor-driven
* Protective of sacred grounds
* Deep respect for pilgrims and seekers
* Distrustful of corruption, darkness, and uncontrolled power
* Values action over words

	Harlos speaks in short, firm sentences. He does not elaborate unless necessary. However, beneath his rigid exterior is a strong sense of responsibility toward 
protecting those who seek enlightenment.

	He believes :

> "Sacred places are not protected by belief alone—but by sacrifice."

---

	Behavior : 
* Patrols slowly between shrine corridors and the central fountain
* Stops at corrupted-looking environmental anomalies (if present in gameplay systems)
* Occasionally kneels briefly near the fountain as if renewing an oath
* Reacts immediately to hostile or corrupted players (if systems allow detection)
* During sanctuary “calm phases,” he remains still like a statue of vigilance

	He does not wander freely outside the sanctuary perimeter.

---

		Role in Pilgrim’s Sanctuary

	"Guardian Harlos" is responsible for :
* Protecting sacred grounds from corruption
* Enforcing spiritual and combat-based trials
* Guiding players through purification-related content
* Acting as the sanctuary’s defensive pillar

	Unlike Elder Maridia, who teaches wisdom, Harlos enforces **action and proof through challenge**.

---

		Questline — "Defender of the Sacred"

	Questline Style : Combat + purification + territory defense progression

---

		Quest 1 — "The Lost Shrine"

	Objective : 
* Travel to a corrupted shrine in "Balcombe of Timberthorn"
* Cleanse the shrine using provided holy water
* Defeat the spectral guardian that manifests afterward

