			Guardian Harlos	— Questline
		
		Questline — "Defender of the Sacred"

	Questline Style : Combat + purification + territory defense progression

---

		Quest 1 — "The Lost Shrine"

	Objective : 
* Travel to a corrupted shrine in "Balcombe of Timberthorn"
* Cleanse the shrine using provided holy water
* Defeat the spectral guardian that manifests afterward

	Gameplay Mechanics : 
* Corruption zone encounter
* Mini-boss fight (spectral entity)
* Environmental cleansing interaction

	Reward : 
* Holy Relic (PvM defense enhancement)
* Minor faction reputation with Sanctuary Order

---

		Quest 2 — "Guardians of the Hidden Way"

	Objective : 
* Defend a hidden passage in "Highland"
* Prevent hostile forces from taking control
* Survive timed wave-based encounters

	Gameplay Mechanics : 
* Defensive hold-out event
* Scaling enemy waves
* Position-based survival challenge

	Reward : 
* Armor Fragment (part of future set crafting system)
* Increased Sanctuary Reputation

---

		Quest 3 — "Call of the Eternal Flame"

	Objective : 
* Retrieve the Eternal Flame from "Glimmering Spring" in "Bartallin Peak"
* Solve environmental puzzles within the dungeon path
* Defeat elemental fire guardian

	Gameplay Mechanics : 
* Puzzle + combat hybrid dungeon
* Elemental boss encounter
* Environmental hazard navigation

	Reward : 
* Symbol of Valor (PvP resilience boost)
* Special commendation token
* High Sanctuary reputation increase

