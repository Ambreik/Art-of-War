			Lorekeeper Aedan — Archivist of the Lavender Grotto

* NPC Type : Dungeon Lore / Megadungeon Narrative Anchor NPC
* Location : Pilgrim’s Sanctuary — Vault of Trials (Deep Archive Chamber, near sealed codex walls)
* Role : Lavender Grotto Knowledge Keeper + Trial Structure Revealer
* Interaction Type : Progressive lore unlocks, dungeon preview system, trial analysis
* Unlock Requirement : Available in Sanctuary, but deeper chapters require Pilgrim progression + discovery of Grotto-related fragments or dungeon access flags

---

		Appearance

	"Lorekeeper Aedan" is a stoic, composed scholar seated within a circular chamber lined with levitating stone tablets and rotating arcane codices.
	He appears older than most historians, though his exact age is unclear. His face is calm, expression controlled, and his eyes reflect faint violet illumination 
whenever he speaks of the Lavender Grotto.
	He wears structured archival robes reinforced with stitched rune-thread, designed not for combat but for protection against “memetic overload” — the idea that 
some knowledge itself can harm the mind.

	Around him float fragmented pages, rotating slowly in orbit, each one containing shifting illustrations of dungeon rooms, guardians, and unknown architectural 
layouts.

	When he speaks of the "Dark Conclave", the pages around him distort briefly, as if resisting being read aloud.

---

	Personality : 

* Analytical, precise, and emotionally restrained
* Treats dungeons as structured systems rather than places of danger
* Speaks as if mapping logic rather than telling stories
* Shows rare hesitation only when referencing the Dark Conclave
* Deep respect for “trial design philosophy” of ancient entities
* Believes every dungeon is a reflection of intentional intelligence

---

		Core Role — LAVENDER GROTTO KNOWLEDGE SYSTEM

	Lorekeeper Aedan functions as the primary pre-dungeon intelligence system for the "Lavender Grotto Megadungeon".

	He does NOT directly send players into combat, but instead provides :
* Full structural understanding of dungeon layers
* Trial logic explanations
* Guardian behavioral frameworks
* Deep lore of imprisoned entities
* Endgame narrative foreshadowing

---

		Mechanics & Systems

		1.  Trial Structure Revelation System

	Aedan reveals the "Lavender Grotto" as a designed philosophical construct, not a random dungeon.

	He unlocks:

* Full breakdown of the "Five Trials" system
* Environmental rules per trial :
	* Wisdom → logic manipulation zones
	* Strength → endurance scaling arenas
	* Courage → fear-based illusion layering
	* Patience → time distortion mechanics
	* Unity → cooperative synchronization locks

	Each revelation :
* Unlocks map hints
* Improves dungeon navigation efficiency
* Reduces trap uncertainty (system-level "clarity bonus")

---

		2. Guardian Behavioral Analysis System

	Aedan provides predictive AI-style insights into dungeon guardians :
* Sentinel of Wisdom → illusion logic disruption patterns
* Champion of Strength → scaling aggression thresholds
* Wraith of Courage → fear-response adaptation system
* Serpent of Patience → movement prediction and timing windows
* Unity Guardian → mirrored player behavior replication model

	This creates :
* Tactical preparation advantage before entering dungeon
* Optional “pre-run intelligence buff” system
* Reduced unknown encounter penalties

---

		3. Dark Conclave Corruption Layer

	Aedan tracks the corruption narrative layer of "the Lavender Grotto"

	He reveals :
* Zones influenced by Conclave magic distortion
* Enemy mutation patterns tied to Conclave presence
* Hidden boss escalation phases
* Forbidden knowledge warnings (risk-based lore locks)

	Key figures documented :
* Sythra the Betrayer
* Vareth the Undying
* Mournstone

	Each has :
* Lore profile unlocks
* Future encounter foreshadowing
* Optional hidden lore quests (not combat quests)

---

		4. Dungeon Logic Codex System

	Aedan acts as a procedural dungeon codex generator.

	When players learn from him :

* Dungeon entries update dynamically
* New "rule interpretations" are added
* Hidden mechanics become partially visible in UI hints

	Example:

* "Unity Guardian reflects synchronized actions within 1.2s delay window"

---

		5. Endgame Foreshadowing System

	Aedan gradually unlocks deep dungeon narrative escalation.

	He hints at :
* Conclave potential escape conditions
* Grotto structural instability
* Possible "awakening event" of imprisoned entities
* Long-term megadungeon evolution system

	This ties Lavender Grotto into :
* Future expansion scaling content
* Raid-tier narrative escalation
* World threat progression system

