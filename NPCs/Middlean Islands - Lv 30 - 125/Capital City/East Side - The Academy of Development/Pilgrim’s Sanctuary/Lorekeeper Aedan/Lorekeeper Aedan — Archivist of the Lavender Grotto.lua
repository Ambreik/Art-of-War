---

		Gameplay Purpose

	Lorekeeper Aedan is designed to :

* Turn Lavender Grotto into a strategic knowledge-based megadungeon
* Reward preparation and intelligence over blind exploration
* Provide deep narrative structure to endgame content
* Act as a bridge between lore, mechanics, and high-level dungeon systems
* Anchor one of the most important PvE experiences in the world

