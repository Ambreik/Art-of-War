			Elder Maridia

	Basic Information

* Name : Elder Maridia
* Title : Keeper of the Path of Insight
* Race : Human
* Gender : Female
* Location : Pilgrim’s Sanctuary — Meditation Hall
* Role : Spiritual Guide / Philosophical Mentor / Nature Wisdom Keeper
* Faction Association : Neutral
* Availability : Permanent

---

		Appearance

	"Elder Maridia" is an elderly woman with long silver-white hair flowing gently down her back, partially braided with thin strands of dried herbs and tiny 
elemental charms. Her pale robes are layered in soft earth-toned fabrics embroidered with ancient symbols representing harmony, balance, and the four classical 
elements.
	Her eyes glow faintly with a serene turquoise hue, carrying the calmness of someone who has witnessed generations pass before her. Around her neck hangs a 
weathered crystal pendant that softly pulses whenever elemental energies are nearby.
	She moves slowly and gracefully through the sanctuary, often barefoot upon the cold stone floors. Small particles of light and drifting leaves occasionally 
swirl around her during moments of meditation, as if nature itself responds to her presence.

---

		Personality

* Calm and introspective
* Philosophical and poetic
* Deeply connected to nature and balance
* Rarely speaks directly
* Encourages players to think rather than obey
* Believes wisdom must be experienced, not taught

	Maridia speaks through metaphors, observations, and layered meanings. Many players leave conversations uncertain whether they received advice or a riddle.

	She values :
* patience
* awareness
* humility
* spiritual understanding
* harmony between mortals and the world

---

	Behavior : 
* Usually found seated near the sanctuary fountain in meditation
* Occasionally walks slowly between the stained-glass halls
* Stops near flowers, trees, or sunlight beams as if listening to unseen voices
* During rain, she relocates near the sanctuary windows and silently observes the storm
* At nighttime, she may be found praying beside the radiant crystal dome

	She never runs or performs sudden movements.

---

		Role in Pilgrim’s Sanctuary

"Elder Maridia" serves as:

* the sanctuary’s spiritual guide
* philosophical mentor
* elemental wisdom keeper
* initiator of spiritual exploration questlines

	Unlike trainers or merchants, Maridia does not focus on power progression through combat.

	Instead, she guides players toward :
* world exploration
* hidden environmental discovery
* spiritual reflection
* understanding ancient balances
* observing the world carefully

