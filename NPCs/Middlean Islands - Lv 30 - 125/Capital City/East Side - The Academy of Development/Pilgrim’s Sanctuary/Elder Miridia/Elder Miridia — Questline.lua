			Elder Miridia — Questline
		
		Questline — "The Path of Insight"

	Questline Requirement : 
* Unlocks at Level 71

---

		Quest 1 — "Gathering the Elements"

	Objective : 
* Collect symbolic elemental objects from distant lands : 
	* Earth
	* Water
	* Fire
	* Air

	Gameplay Focus : 
* World exploration
* Environmental observation
* Multi-region travel
* Elemental hotspot discovery

	Example Locations : 

* "Crystal Flower Lake" → Water
* "Emberwaste" → Fire
* Hidden cliffs and ancient groves → Air & Earth

	Reward : 
* Minor Elemental Resistance Potion
* Scroll of Wisdom

---

		Quest 2 — "The Hidden Grove"

	Objective : Locate a concealed sacred grove in "Farellia Plateau" within "Aarong Forest".

	Mechanics : 
* Time-sensitive environmental trigger
* Hidden path discovery
* Observation-based progression

	Players must arrive during a specific daylight condition hinted by Maridia.

	Reward : 
* Unique Health Elixir Recipe
* Increased Reputation with Elder Maridia

---

		Quest 3 — "The Soul of the Land"

	Objective : Meditate at "Thunder Inn" in "Frozen Forest".

	Mechanics : 
* Meditation interaction system
* Spiritual vision sequence
* Lore revelation event

	During meditation :
* players enter a temporary spiritual vision
* confront a manifestation of the land itself
* witness fragments of the ancient war between gods and mortals

	Reward : 
* Title: "Seeker of Wisdom"
* Rare Potion Recipe

---

		Mechanics & Functions

	Spiritual Meditation Guidance

	Maridia introduces players to :
* meditation mechanics
* environmental interaction systems
* spiritual locations throughout the world

	Certain hidden areas may only become visible after completing portions of her questline.

---

		Elemental Awareness System

	After progressing through her storyline :
* players gain subtle environmental hints near elemental anomalies
* hidden particles, sounds, or visual cues may appear in special locations

	This mechanic encourages exploration instead of map markers.

---

		Philosophical Dialogue System

	Maridia’s dialogue changes depending on :
* player reputation
* completed explorations
* corruption status
* faction alignment
* major world events

	Corrupted players may receive darker interpretations of her teachings.

---

		Environmental Lore Guidance

	Maridia indirectly hints at :
* hidden ruins
* sacred lakes
* forgotten shrines
* unstable elemental regions
* future expansion locations

	She never directly marks locations on the map.

---

		Reputation System

	Players can gain :

* "Pilgrim’s Sanctuary Reputation"

	By :
* completing her quests
* discovering hidden spiritual sites
* cleansing corrupted locations
* meditating at sacred places

	Higher reputation unlocks :
* unique philosophical dialogues
* rare recipes
* spiritual titles
* hidden lore fragments

