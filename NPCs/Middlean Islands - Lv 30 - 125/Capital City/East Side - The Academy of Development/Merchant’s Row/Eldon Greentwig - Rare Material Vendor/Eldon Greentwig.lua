			Eldon Greentwig

---

	Location : Middlean Islands / Capital City / East Side District / The Academy of Development / Merchant’s Row

---

	Appearance : "Eldon Greentwig" is an elderly elf with a calm and weathered appearance shaped by decades of travel across distant lands and forgotten regions. 
His long silver hair is loosely tied behind his back, and several thin braids decorated with wooden beads and carved stones hang beside his face. His pale skin 
carries the faint wrinkles of old age, yet his posture remains graceful and composed. He wears layered earth-toned robes embroidered with intricate natural patterns
representing forests, mountains, rivers, and ancient trade routes. Around his waist rests a woven sash carrying numerous small pouches filled with herbs, minerals, 
seeds, and rare fragments collected during his travels. His stall appears modest compared to the louder merchants nearby, but each displayed item is meticulously 
organized and labeled with handwritten notes describing origin, rarity, and unusual properties.

---

	Personality : Eldon is quiet, thoughtful, and deeply contemplative. He speaks slowly in a calm melodic tone, carefully choosing his words and rarely wasting 
conversation on meaningless topics. Unlike most merchants, Eldon shows little interest in wealth or aggressive trade. He values curiosity, wisdom, and genuine 
appreciation for rare materials far more than coin. Players who approach respectfully quickly realize that Eldon possesses extraordinary knowledge about ancient 
civilizations, forgotten regions, and uncommon crafting resources. Though reserved at first, he occasionally becomes unexpectedly passionate when discussing unusual
artifacts, distant landscapes, or stories from his journeys. Many adventurers leave his stall feeling as though they learned far more than they purchased.

---

	Behaviour : Eldon spends most of his time quietly organizing materials, writing notes inside weathered journals, or carefully examining newly acquired artifacts
under soft lantern light. He rarely calls customers toward his stall, preferring instead to allow interested individuals to approach naturally. Occasionally, he 
pauses mid-conversation as though remembering fragments of distant memories tied to certain objects. During quieter hours, he sometimes shares stories of hidden 
ruins, lost trade routes, or mysterious lands beyond Middlean Islands with attentive listeners gathered around his stall.

---

	Role :

* Role(s) : Traveling Artisan, Rare Materials Merchant, Lore Merchant
	Eldon functions as one of Merchant’s Row’s most knowledgeable traders, specializing in rare materials, unusual crafting components, ancient curiosities, and 
culturally significant artifacts gathered throughout his travels. Beyond commerce, he acts as an important source of world lore, exploration hints, and historical 
insight for players interested in uncovering deeper knowledge about the world.

---

