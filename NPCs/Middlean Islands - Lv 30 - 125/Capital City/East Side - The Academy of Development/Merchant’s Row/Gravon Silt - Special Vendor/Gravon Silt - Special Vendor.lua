			Gravon Silt

--- 

	Location : Middlean Islands → Capital City → East Side District → The Academy of Development → Merchant’s Row

---

	Appearance : "Gravon Silt" is a lean, weathered man in his late forties with a permanently amused expression and the posture of someone who never fully trusts 
his surroundings. His dark coat is stitched from mismatched fabrics gathered from various regions, giving him the appearance of a wandering trader rather than a 
fixed merchant. The inside of the coat contains dozens of hidden pockets and concealed compartments, many reinforced with smuggling-grade leather linings designed 
to hide contraband or illegal valuables.
	His gloves are fingerless and stained with ink, ash, and old coin residue from years of handling questionable goods. Around his neck hangs a tarnished silver 
chain holding several fake merchant seals and broken insignias from confiscated trade factions.
	Gravon’s eyes constantly scan the crowds of Merchant’s Row, not out of fear, but out of habit. He often leans casually against crates or market pillars, 
blending into the flow of the city while quietly observing guards, merchants, and travelers alike.
	Unlike legitimate vendors, Gravon never establishes a fully permanent stall. His goods are transported through hidden lockboxes, false-bottom crates, and 
temporary hidden caches positioned throughout the market district.

---

		Personality :

	Gravon Silt is sarcastic, opportunistic, and dangerously charismatic. He speaks casually about illegal trade as if discussing ordinary business, often making 
jokes about guards, confiscated shipments, or failed smugglers who lacked “professional talent.”
	Despite his criminal affiliations, Gravon is not reckless. He values discretion, efficiency, and survival above greed. He dislikes violence inside the city and 
believes smart criminals avoid unnecessary attention.
	He treats Outlaws, smugglers, pirates, and black-market players with surprising professionalism, often respecting players who successfully avoid detection by 
authorities. Toward lawful players, he becomes evasive, vague, or dismissive unless they have hidden corruption-related standings.
	Gravon rarely speaks directly about his connections, but it is heavily implied that he maintains ties with underground trade routes operating across Capital 
City, the harbor districts, and certain smuggling factions scattered throughout Middlean Islands.

---

		Behaviour :

	Gravon Silt does not operate like a normal merchant NPC.

	He constantly wanders through :
* Merchant’s Row
* nearby alleyways
* temporary crowd pockets
* shaded corners near supply crates

	He periodically changes standing locations throughout the day to avoid suspicion from guards and merchant inspectors.

	When guard patrols pass nearby :
* Gravon may temporarily stop interactions
* close his vendor access
* pretend to be an ordinary civilian
* casually whistle or inspect random market goods

	He occasionally makes public jokes regarding :
* confiscated smuggling cargo
* incompetent thieves
* unlucky outlaws
* corrupt guards
* overpriced merchant taxes

	If Civic Enforcement activity becomes too high due to local events or systems :
* Gravon may temporarily disappear
* relocate to Gray Zone sectors
* reduce illegal inventory availability

---

	Role :

* Role(s) : Fence Merchant, Black Market Vendor, Smuggling Network Contact, Illegal Goods Buyer
	Gravon Silt functions as one of the primary underground commerce NPCs operating openly within Capital City without direct arrest by authorities.

	He exists to support :
* outlaw player progression
* smuggling economy systems
* black market item circulation
* illegal item laundering
* stolen goods liquidation

	Unlike ordinary vendors, Gravon specifically buys goods that lawful merchants refuse to purchase due to :
* illegal ownership flags
* stolen status
* contraband markings
* black market signatures
* smuggling traces
* restricted trade classifications

	He also provides access to hidden inventories containing :
* untraceable items
* contraband equipment
* illegal trade supplies
* forged shipment goods
* gray-market consumables

---

		Mechanics :

* Type : Black Market Vendor, Fence Merchant, Smuggling NPC
* Reputation :
	Gravon does not use traditional reputation systems.

	Instead, his interactions depend on :
* Smuggling Network standing
* Black Market access level
* Corruption & Loyalty values
* Outlaw status
* criminal activity records
* hidden trust flags

	Certain inventory tabs only unlock for players deeply involved in illegal systems.

---

* Interaction Limitations :

	Gravon only fully interacts with :
* Outlaw players
* Smuggling-affiliated players
* Black Market aligned players
* corrupted or criminal-aligned characters

	Lawful players may :
* receive minimal dialogue
* be denied access
* see empty vendor windows

	Some highly lawful players may trigger defensive suspicion dialogue.

	If a player is actively pursued by guards or has recent criminal exposure :
* Gravon may temporarily refuse service to avoid attention.

---

* PvP : Gravon cannot be attacked or targeted directly.

	Under the Controlled PvP Law System :
* attacking near Gravon heavily increases guard response chance
* illegal combat near him may trigger Gray Zone escalation events

	Because of his underground importance :
* several hidden NPC networks indirectly protect him
* disappearing behavior activates if major disturbances occur nearby

---

* Respawn Time : Gravon uses a semi-dynamic presence system.

	He is generally active :
* during afternoon hours
* evening crowd periods
* heavy market traffic cycles

	During high guard enforcement periods :
* he may temporarily despawn
* relocate
* reduce appearance frequency

