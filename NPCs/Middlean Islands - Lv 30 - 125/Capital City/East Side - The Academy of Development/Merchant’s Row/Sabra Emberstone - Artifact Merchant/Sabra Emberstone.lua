			Sabra Emberstone

---

	Location : Middlean Islands / Capital City / East Side District / The Academy of Development / Merchant’s Row

---

	Appearance : "Sabra Emberstone" is a tall and slender woman with sharp facial features and an intense, almost unsettling gaze that immediately captures 
attention. Her long dark hair flows freely beneath a deep midnight-blue hooded cloak embroidered with intricate silver arcane symbols that shimmer faintly under 
lantern light. Small feathers, polished beads, and enchanted charms are woven throughout her hair and clothing, softly moving even when no wind is present. Her pale
hands are adorned with silver rings etched with protective runes, and faint traces of magical burns mark several fingertips from years of artifact handling. Her 
stall is among the most visually striking within Merchant’s Row, filled with carefully arranged relics, glowing gemstones, enchanted trinkets, sealed scrolls, and 
mysterious objects displayed beneath reinforced protective glass cases. Dim lanterns infused with magical crystals cast a shifting blue-purple glow around her 
corner of the market.

---

	Personality : Sabra is calm, composed, and highly perceptive. She speaks softly but with unmistakable confidence, carefully observing those who approach her 
before deciding how much information to reveal. Unlike ordinary merchants, Sabra treats magical artifacts with deep caution and respect, often warning customers 
about the dangers tied to reckless use of enchanted objects. She possesses a mysterious aura that makes many people uncertain whether to trust or fear her. Despite 
her reserved demeanor, Sabra is not unfriendly; she simply values wisdom and restraint over curiosity without discipline. Players who demonstrate patience, 
intelligence, or magical understanding earn her respect and may discover a far more insightful and surprisingly honest side beneath her enigmatic exterior.

---

	Behaviour : Sabra rarely raises her voice or makes unnecessary movements. She spends much of her time carefully inspecting enchanted items, maintaining magical 
seals, or quietly studying ancient texts behind her counter. Occasionally, faint magical energy pulses across her stall as artifacts react to nearby players or 
environmental changes within the city. During nighttime hours, some customers claim her stall feels different, with strange whispers, glowing runes, or shifting 
shadows appearing briefly among the displays. Sabra pays close attention to customers carrying cursed items, unstable magical objects, or unusually powerful 
artifacts, often immediately sensing hidden magical disturbances others overlook.

---

	Role :

* Role(s) : Artifact Merchant, Enchantment Specialist, Arcane Advisor
	Sabra serves as Merchant’s Row’s primary specialist in enchanted objects, magical artifacts, arcane curiosities, and mystical equipment. She advises players 
regarding magical risks, enchantment compatibility, artifact handling, and the consequences tied to powerful relics or unstable magical energies.

---

