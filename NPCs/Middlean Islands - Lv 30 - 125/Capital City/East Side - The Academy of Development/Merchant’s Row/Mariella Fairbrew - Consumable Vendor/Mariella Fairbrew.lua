			Mariella Fairbrew

---

	Location : Middlean Islands / Capital City / East Side District / The Academy of Development / Merchant’s Row

---

	Appearance : "Mariella Fairbrew" is a petite woman in her early thirties with lively emerald-green eyes and long red curls usually tied into a loose braid 
falling over one shoulder. Her face is often lightly dusted with traces of powdered herbs or alchemical residue from her constant potion crafting. She wears a 
colorful layered dress beneath a thick practical apron stained by years of mixing ingredients, oils, and reagents. Numerous glass vials, corked flasks, and tiny 
ingredient pouches hang from leather straps around her waist, softly clinking whenever she moves. Her stall is one of the brightest spots within Merchant’s Row, 
filled with rows of glowing bottles, colorful liquids, dried herbs, powders, and small handwritten labels explaining the effects of her creations. The air 
surrounding her stand constantly shifts between sweet floral aromas, bitter medicinal scents, and occasionally unpleasant experimental fumes.

---

	Personality : Mariella is warm, approachable, and naturally talkative. She enjoys interacting with customers and treats even inexperienced adventurers with 
patience and enthusiasm. Unlike many merchants focused purely on profit, Mariella genuinely enjoys helping people prepare for their journeys and takes pride in 
finding the right consumables for each individual. She becomes especially animated when discussing ingredients, potion reactions, or unusual mixtures discovered 
during her experiments. Her curiosity often leads her into long conversations about distant plants, monster toxins, or strange alchemical accidents. While cheerful 
most of the time, Mariella becomes surprisingly strict when discussing dangerous potions or irresponsible misuse of alchemical substances.

---

	Behaviour : Mariella constantly moves around her stall reorganizing potions, grinding herbs, preparing samples, or testing mixtures inside small glass 
containers. She frequently offers tiny free samples to nearby visitors, especially newcomers unfamiliar with potion effects. Throughout the day she can be heard 
chatting with customers, giving travel advice, or explaining how certain ingredients react under different environmental conditions. Occasionally, small puffs of 
smoke, colorful sparks, or bubbling noises erupt from behind her counter during experimental brewing attempts, usually followed by embarrassed laughter or quick 
cleanup efforts.

---

	Role :

* Role(s) : Potion Seller, Consumables Merchant, Alchemical Advisor
	Mariella serves as Merchant’s Row’s primary supplier of potions, restorative items, consumables, and travel mixtures. Beyond selling goods, she helps educate 
adventurers on the practical use of alchemical items, survival preparation, and consumable management during exploration or combat.

---

