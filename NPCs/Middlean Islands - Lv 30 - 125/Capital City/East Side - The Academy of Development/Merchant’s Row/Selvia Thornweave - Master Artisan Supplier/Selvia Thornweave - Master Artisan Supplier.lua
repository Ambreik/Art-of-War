			Selvia Thornweave — Master Artisan Supplier

---

	Location : Capital City / East Side District / Merchant’s Row / Artisan Fabric Pavilion (Indoor Tailoring Workshop Stall)

---

	Appearance : "Selvia Thornweave" is an elegant, middle-aged artisan whose presence carries the calm precision of someone who has spent decades mastering fabric,
thread, and enchantment weaving. Her attire is a refined blend of artisan practicality and ceremonial tailoring heritage — layered robes of deep indigo and muted 
silver, embroidered with intricate stitch patterns that subtly shimmer when light passes over them.
	Her hands are marked by fine needle scars and faint thread-calluses, evidence of constant high-precision crafting. Around her wrists are spool-bracelets 
containing enchanted threads used for experimental stitching techniques. A large tailoring frame stands behind her, constantly shifting between unfinished garments 
and arcane fabric samples that float gently in place as if held by invisible hands.
	Her hair is partially tied up with woven cloth bands, each representing mastery tiers of tailoring she has achieved over her lifetime. Her gaze is calm, 
focused, and observant — the kind of eyes that immediately assess material quality just by looking at it.

---

	Personality : Selvia is patient, detail-oriented, and deeply disciplined in her craft philosophy. She views tailoring not as simple crafting, but as a form of 
structured transformation where materials carry identity, function, and magical potential.
	She is not overly friendly, but she is not cold either — instead, she is professional, precise, and quietly encouraging to those who show genuine interest in 
craftsmanship. She respects effort and material understanding far more than wealth or status.

	To Selvia, every fabric has a “behavior,” and every stitch is a controlled decision that affects the final structure of the item.

---

	Behaviour :

	Selvia remains stationed within her tailoring workshop and does not wander. She continuously engages in background crafting animations, including :
* fabric inspection cycles
* thread enchantment alignment
* blueprint stitching simulations
* material compatibility testing

	She reacts to players based on crafting progression level, profession rank, and Citizen Standing System access thresholds.
	Higher-tier players unlock deeper interaction layers of her crafting system.

---

	Role :

* Role(s) : Master Tailoring Supplier, High-Tier Recipe Unlocker, Fabric Enhancement Specialist, Craft Progression Gatekeeper

	"Selvia Thornweave" is responsible for advancing the Tailoring profession beyond basic crafting limits. She provides access to rare materials, advanced 
tailoring recipes, and gear enhancement patterns tied to high-level crafting progression.

	She functions as a progression gate for crafting specialization, not a general merchant.

