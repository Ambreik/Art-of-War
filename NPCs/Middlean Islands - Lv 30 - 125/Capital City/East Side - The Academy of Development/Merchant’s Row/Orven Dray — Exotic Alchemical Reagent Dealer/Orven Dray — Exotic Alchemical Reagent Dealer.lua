* Other Mechanics :

---

	1. Five-Tab Alchemy Vendor System (Core Feature)

	Orven Dray operates a unique multi-tab shop interface, structured as follows :

* Tab 1 — Basic Reagents
	* universal low-tier ingredients
	* starter alchemy materials

* Tab 2 — Refined Compounds
	* mid-tier crafting reagents
	* stabilized potion bases

* Tab 3 — Advanced Catalysts
	* profession-gated materials
	* enhancement reagents

* Tab 4 — Experimental Mixtures
	* unstable reagents
	* high-risk / high-reward crafting components
	* unlocks only at high Alchemy Rank (III+)

* Tab 5 — Forbidden / Controlled Alchemy
	* extremely rare reagents
	* system-controlled materials
	* heavily restricted availability

---

	2. Profession Rank Unlock System

	Tabs are unlocked based on Alchemy Profession Rank :

* Rank I → Tab 1
* Rank II → Tabs 1–2
* Rank III → Tabs 1–3
* Rank IV → Tabs 1–4
* Rank V → Tabs 1–5

	This ensures :
* clear progression curve
* controlled crafting economy
* meaningful profession advancement

---

