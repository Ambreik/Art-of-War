			Orven Dray — Exotic Alchemical Reagent Dealer

---

	Location : Capital City / East Side District / Merchant’s Row / Alchemy & Volatile Reagents Stall (Enclosed Chemical Pavilion)

---

	Appearance : "Orven Dray" is a slightly eccentric but highly disciplined alchemical merchant whose appearance reflects constant exposure to volatile substances.
His face is sharp and angular, partially obscured by protective arcane goggles that filter chemical vapors and unstable magical residues. His skin carries faint 
discoloration patterns from prolonged reagent handling, giving him the look of someone who has survived countless controlled explosions.
	He wears a reinforced alchemist’s coat layered with heat-resistant and corrosion-proof fabric, stitched with multiple containment seals designed to prevent 
accidental reactions. Small glass vials, sealed reagent capsules, and stabilized essence containers hang from his belt in organized clusters, each labeled with 
precise alchemical notation.
	Behind him are five structured alchemical display stations, each sealed behind protective enchantment barriers, representing his internal vendor tab system. 
Occasionally, faint glowing reactions can be seen occurring inside these containment fields as experimental compounds continuously stabilize and destabilize.

---

	Personality : "Orven Dray" is analytical, mildly obsessive, and highly experimental. He speaks in a precise, technical tone, often describing substances not by 
name but by reaction properties and stability classes. He views alchemy as a controlled form of chaos — something that must be contained, measured, and refined 
rather than feared.
	He is not dangerous in demeanor, but his thought process is unpredictable when discussing experimental compounds. He becomes especially focused when analyzing 
rare reagents or unstable event materials.

	He respects progression, precision, and controlled experimentation above all else.

---

	Behaviour :

	Orven remains stationed in his enclosed alchemy stall at all times. He performs continuous background actions such as :
* reagent stability testing
* chemical containment recalibration
* experimental mixture simulation
* tab-based inventory restructuring

	His interaction system dynamically changes depending on :
* player Alchemy Profession Rank
* Citizen Standing Recognition System
* active world events or seasonal modifiers

	He does not physically move between locations or patrol.

---

	Role :

* Role(s) : Alchemy Reagent Vendor, Experimental Ingredient Specialist, Profession Progression Vendor, Seasonal Craft Material Distributor
	"Orven Dray" serves as the central NPC for the Alchemy profession in Merchant’s Row. He provides structured access to reagents, crafting materials, and
experimental alchemical components through a tiered, tab-based unlocking system tied directly to profession progression.

	He also acts as a seasonal alchemy hub during world events.

