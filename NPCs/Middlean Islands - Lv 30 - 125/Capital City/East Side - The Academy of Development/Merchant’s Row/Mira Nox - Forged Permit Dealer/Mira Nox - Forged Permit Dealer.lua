# Secondary File — Permit Requests & Illegal Favor Structures

# Illegal Permit Acquisition Structure

Mira Nox does not freely distribute forged permits.

Players must complete:

* requests
* favor tasks
* hidden deliveries
* item exchanges
* administrative manipulations

before receiving forged documentation.

These are handled separately from her main NPC file.

---

# Request Type 1 — Administrative Supply Acquisition

### Request :

Retrieve specific administrative supplies from legitimate merchants without drawing suspicion.

### Possible Requested Items :

* Official Sealing Wax
* Blank Trade Ledger Pages
* Merchant Registry Ink
* Silver Approval Thread
* Inspector’s Writing Quill

### Source :

Usually purchased from lawful vendors inside Merchant’s Row.

### Purpose :

Used by Mira to create higher-quality forged documents.

---

# Request Type 2 — Hidden Delivery Tasks

### Objective :

Deliver sealed packages to:

* dock workers
* tavern keepers
* corrupted guards
* black market couriers

without being inspected.

### Failure Conditions :

* getting caught by guards
* opening the package
* dying during delivery

### Reward :

Improved permit quality or reduced suspicion generation.

---

# Request Type 3 — Record Alteration Requests

### Objective :

Interact with hidden administrative boards or archives to:

* replace records
* remove shipment names
* alter citizen logs
* erase confiscation reports

### Mechanics :

Stealth-oriented interactions tied to:

* Veil of the Crowd System
* Administrative Access Control System

---

# Request Type 4 — Contraband Procurement

### Objective :

Acquire restricted materials used in forgery creation.

### Examples :

* Black Ink Powder
* Noble Wax Seal Fragments
* Broken Inspection Stamps
* Counterfeit Merchant Emblems

These items are usually obtained through:

* smuggling
* black market vendors
* outlaw activities

---

# Request Type 5 — Silence Contracts

### Objective :

Prevent certain NPCs from reporting suspicious activities.

Possible solutions:

* bribe them
* intimidate them
* complete favors
* deliver requested items

This system avoids forced assassination gameplay while preserving roleplay flexibility.

