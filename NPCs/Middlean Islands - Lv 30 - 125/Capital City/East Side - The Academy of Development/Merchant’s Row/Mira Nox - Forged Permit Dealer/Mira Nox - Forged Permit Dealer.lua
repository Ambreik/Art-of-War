			Mira Nox

---  
	
	Location : Middlean Islands → Capital City → East Side District → The Academy of Development → Merchant’s Row

---

	Appearance : "Mira Nox" is a refined and unsettling woman whose appearance carefully balances elegance with secrecy. She wears dark layered clothing tailored 
similarly to administrative officials, though subtle imperfections reveal that her attire is imitation rather than authentic government issue. Thin silver chains 
hang from her belt alongside wax seals, folded parchments, counterfeit insignias, and compact engraving instruments used for forging official documentation.
	Her black hair is neatly pinned behind her head, exposing sharp facial features and cold gray eyes that constantly evaluate everyone around her. Her gloves are
immaculate despite the ink stains beneath her fingernails — evidence of countless forged signatures and altered permits.
	Unlike ordinary merchants, Mira rarely stands openly in crowded sections of Merchant’s Row. She prefers partially obscured corners, covered balconies, abandoned
kiosks, or shaded administrative passageways near the market district. A small folding desk often accompanies her, covered in official-looking paperwork and seal 
presses.

	To most civilians, she appears to be little more than a minor clerk or traveling scribe. Only observant players notice the subtle tension surrounding her 
interactions.

---

		Personality :

	Mira Nox is composed, intelligent, and highly manipulative. She speaks calmly and professionally, almost never raising her voice regardless of the situation. 
	Unlike smugglers or black market traders who embrace criminality openly, Mira treats illegal documentation as a form of bureaucracy rather than crime.

	She values discretion above loyalty and believes systems exist primarily to be exploited by those clever enough to understand them. Mira rarely threatens 
players directly, but her carefully chosen words constantly imply hidden consequences.

	She dislikes reckless criminals and refuses to work with players who attract excessive guard attention. Players who behave intelligently, avoid unnecessary 
violence, or demonstrate strategic thinking gain her respect much faster than brute-force outlaws.

	Although deeply tied to Gray Zone operations, Mira maintains a surprisingly clean public profile within Capital City due to her ability to manipulate records, 
erase traces, and redirect suspicion toward others.

---

		Behaviour :

	"Mira Nox" operates through shifting locations throughout Merchant’s Row and nearby administrative alleys.

	She never remains stationary for long periods and frequently changes :
* writing desks
* meeting points
* hidden drop locations
* permit exchange corners

	During periods of increased guard patrols :
* she may temporarily disappear
* suspend interactions
* refuse permit creation requests

	Mira actively observes:
* guard movement
* crowd density
* suspicious player activity
* administrative inspections

	If players openly mention illegal activities near civilians or guards :
* Mira immediately terminates interaction
* her vendor/interaction window closes
* hidden suspicion values increase

	She occasionally burns forged documents in public braziers after completing transactions.

---

	Role :
* Role(s) : Forged Permit Dealer, Gray Zone Administrative Contact, Illegal Access Broker
	Mira Nox functions as one of Capital City’s primary illegal administrative operators.
	
	Her role is deeply connected to :
* bypassing restricted access systems
* forging temporary authorizations
* manipulating trade permissions
* creating false identity documents
* granting access to restricted sectors

	She provides players with forged permits used to :
* access restricted city sectors
* bypass administrative limitations
* enter controlled trade zones
* transport regulated cargo
* avoid specific inspection layers
* unlock temporary interactions normally unavailable

	Unlike dungeon keys or official progression permits, Mira only handles civilian, trade, movement, and administrative access documentation.

