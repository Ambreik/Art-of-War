			Varric Selborne — Merchant Guild Representative

---

	Location : Capital City / East Side District / Merchant’s Row / Guild Inspection Route (Dynamic Pathing NPC)

---

	Appearance : "Varric Selborne" is a tall, composed middle-aged man whose presence immediately separates him from the chaos of Merchant’s Row. His posture is 
perfectly upright, trained by years of bureaucratic authority and constant observation. He wears layered noble-merchant attire, dominated by deep navy fabric 
reinforced with gold-threaded insignias of the Merchant Guild. The coat is structured and symmetrical, designed not for comfort but for authority.
	White gloves cover his hands at all times, never stained, symbolizing both cleanliness and control over commerce. On his chest sits a finely engraved guild 
emblem, subtly glowing when he performs inspections or issues permits. At his side hangs a sealed ledger tablet infused with arcane registry enchantments used to 
validate trade activity in real time. A signet ring on his right hand acts as his official authorization seal for permits and sanctions.
	His expression is calm but analytical, with eyes that constantly track movement, pricing behavior, and crowd interactions. Nothing about him feels casual—he 
looks like a man who is always processing systems rather than people.

---

	Personality : "Varric Selborne" is emotionally restrained and system-oriented. He does not speak with warmth or hostility; instead, his tone remains neutral, 
precise, and procedural. He perceives the world through structured economic logic rather than personal sentiment. To him, merchants are not individuals but nodes in
a larger regulatory framework.
	He is neither cruel nor kind—he is consistent. His approval is not earned through charm but through compliance, stability, and contribution to the city’s 
economic equilibrium. He respects efficiency, punishes instability, and ignores emotional appeals unless they affect system integrity.

---

	Behaviour : Varric operates on a strict daily cycle. He spawns at 06:00 during the Market Activation Phase and begins a structured patrol through Merchant’s 
Row. He does not remain stationary and instead moves between stalls in a predefined but adaptive inspection route.
	At each merchant stall, he pauses briefly to perform an evaluation scan. This includes observing pricing behavior, inventory legitimacy, customer flow 
stability, and compliance with guild regulations. If irregularities are detected, he logs them silently into his registry system and may return later for a 
secondary inspection.

	He despawns at 22:00 during Market Closure Phase, when the economic activity of Merchant’s Row transitions into a non-regulated night state.

	He does not engage in idle wandering outside this schedule.

---

	Role :

* Role(s) : Merchant Guild Representative, Economic Regulator, Trade Inspector, Administrative Authority Unit
	"Varric Selborne" serves as the living enforcement arm of the Merchant Guild within Merchant’s Row. His role is to maintain economic order, ensure legal 
compliance of all vendors, and regulate trade activity according to Capital City’s governance systems. He acts as both inspector and validator of the marketplace’s 
economic health.

---

	Mechanics :

* Type : System NPC / Dynamic World Regulator / Inspection Authority

* Reputation :
	Varric is directly tied to the "Citizen Standing Recognition System". Player interaction with him affects their hidden economic credibility score. Positive 
standing improves access to high-tier merchants, while negative standing may restrict trade privileges or flag the player for further inspection.

	He also contributes to the Merchant Guild Reputation Layer, influencing how NPC vendors react to both players and world events.

---

* Interaction Limitations :
	Only players with standard merchant access or registered citizen status may fully interact with Varric. Players with low standing, flagged criminal activity, or
unresolved Civic Offenses may experience restricted dialogue options or inspection triggers.

	Interaction is also context-sensitive—he only engages fully during inspection proximity windows or when economic anomalies are detected in the player’s 
inventory or behavior patterns.

---

* PvP :
	Varric is non-combatant and cannot be targeted or harmed. He is flagged under protected Administrative Authority status. Any attempt to attack or disrupt him 
triggers immediate Civic Offense escalation through the Civic Offense & Fines System, potentially invoking guard intervention or market lockdown states.

---

* Respawn Time :
	He does not follow a traditional respawn system. Instead, he operates on a daily system cycle spawn loop :
* Spawns at 06:00 (Market Activation)
* Despawns at 22:00 (Market Closure)
* Reinitializes at next cycle without persistence loss

---

* Other Mechanics :

	1. Vendor Inspection System
  Varric performs dynamic inspections of all Merchant’s Row vendors. Each stall has a hidden compliance state that he evaluates in real time. This includes : 
* price stability checks
* inventory legality validation
* merchant behavioral assessment
* supply chain consistency analysis

  If anomalies are detected, he marks the vendor for follow-up audits or system flagging.

---

	2. Trade Permit System
	Varric issues and validates trade permits for high-tier merchants. These permits are required for :
* rare item sales
* exotic imports
* artifact trade
* regulated crafting materials

	Players may indirectly influence permit access through reputation progression or system-triggered approvals.

---

	3. Vendor Performance Index (Hidden System)
	Every merchant in the area is assigned a hidden performance score influenced b:
* pricing fairness
* customer flow efficiency
* legal compliance
* interaction quality

	Varric updates this index during patrol cycles, feeding into CLAS (Capital Life & Activity System).

---

	4. Illegal Trade Detection Layer
	Varric passively scans for anomalies linked to the Gray Zones of the Capital System. Suspicious items or transactions may trigger :
* silent logging
* delayed inspection
* escalation flags to enforcement NPCs

---

	5. Economic Stability Feedback Loop
	His presence directly stabilizes Merchant’s Row economy. High compliance improves :
* merchant stock quality
* spawn rate of rare goods
* market pricing stability

	Low compliance leads to :
* increased inspections
* restricted goods availability
* higher chance of fines or vendor shutdowns

---

	6. Stall Authorization & Ranking Control
	Varric influences which merchants are allowed to expand or upgrade their stalls. High-performing vendors may unlock :
* larger stalls
* rare item permissions
* traveling merchant licenses

