			Harrin Stout

---

	Location : Middlean Islands / Capital City / East Side District / The Academy of Development / Merchant’s Row

---

	Appearance : "Harrin Stout" is a stout, middle-aged human with a rugged but welcoming presence that immediately blends him into the lively chaos of Merchant’s 
Row. His broad frame is covered by a well-worn linen shirt and a thick leather apron patched in several places from years of heavy use. A neatly trimmed brown beard
frames his round face, often paired with a flushed expression from either laughter or constant bargaining with customers. His sleeves are rolled up at all times, 
revealing strong forearms used to haul crates, stack supplies, and manage daily deliveries. Behind his stall, everything appears slightly cluttered at first glance,
but every item—from food rations and repair kits to ropes, nails, and crafting materials—is carefully arranged for quick access. Wooden crates, hanging bundles, and
stacked supplies create a practical, lived-in merchant space that reflects his no-nonsense but friendly approach.

---

	Personality : Harrin is jovial, talkative, and naturally warm toward everyone he meets. He enjoys conversation as much as commerce, often greeting customers 
with a loud laugh or a friendly remark before any transaction begins. Unlike more specialized merchants, Harrin sees himself as part supplier, part storyteller, and
part advisor for adventurers preparing for their journeys. He loves hearing tales of distant lands, recent battles, and strange encounters, often reacting with 
exaggerated enthusiasm or disbelief. While he enjoys friendly bargaining and light haggling, he is fundamentally honest in his dealings and values long-term trust 
over short-term profit. He also has a surprising instinct for understanding what an adventurer might need next, often recommending supplies before players even 
realize they are missing them.

---

	Behaviour : Harrin is constantly active, moving between crates, reorganizing stock, unloading deliveries, or shouting greetings to passing customers. He 
frequently stops mid-task to engage in conversation, especially when he hears interesting rumors or stories from adventurers. During peak hours, he manages his 
stall with energetic efficiency, calling out deals, offering quick suggestions, and keeping the flow of customers moving smoothly. Occasionally, he lowers his voice
to share useful survival tips or subtle warnings about travel conditions beyond the city walls. At quieter moments, he is seen resting on a crate, polishing tools 
or simply observing the bustling market with a satisfied expression.

---

	Role :

* Role(s) : General Goods Merchant, Supply Vendor, Expedition Preparation Advisor, Rumor Source
	Harrin serves as the backbone supplier of Merchant’s Row, providing essential goods and basic survival items required by adventurers, traders, and travelers. 
	Beyond commerce, he acts as a community figure who shares practical advice, travel rumors, and preparation guidance for expeditions across the Middlean Islands.

---

