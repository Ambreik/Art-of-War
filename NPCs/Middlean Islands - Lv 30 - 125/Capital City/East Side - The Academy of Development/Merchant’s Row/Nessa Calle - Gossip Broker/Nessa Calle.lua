* Other Mechanics :

---

	1. Local Intelligence Aggregation System

	Nessa collects structured data from distributed NPC sources :
* tavern keepers
* market vendors
* dock workers and porters
* guard rotation patterns (indirect system feed)
* crowd movement anomalies
* trade flow irregularities

	This data is processed into :
* Rumors (low confidence, high volume)
* Market Alerts (medium confidence, time-sensitive)
* Critical Intelligence (high confidence, rare triggers)

	All outputs are strictly limited to :
* last 48 hours of activity
* or scheduled upcoming events
* or active system-generated anomalies

---

	2. Whisper Network Interface Layer

	Nessa acts as the localized access point for the Whisper Network System.

	She translates system-level hidden flags into player-readable rumor structures such as :
* suspicious trade behavior
* unusual NPC clustering
* sudden price shifts
* hidden movement patterns in Merchant’s Row

	She does NOT provide direct system values — only interpreted signals.

---

	3. Bounty Intelligence Protocol (Bounty Hunter Exclusive)

	If the interacting player is a Bounty Hunter, Nessa unlocks specialized intelligence streams :
* last known sightings of outlaw-class players
* movement trace fragments (time + zone based)
* suspected interaction points with illegal systems
* probability-based location suggestions

	This does NOT provide exact tracking — only investigative leads.

---

	4. Sealed Information Token System (Interaction Cost)

	Each information request requires a consumable item:

* Item Name : Sealed Information Token
* Item Type : Consumable / Trade Utility Item
* Function : Access key for rumor extraction

	This item can be obtained from :
* General Goods Merchant (Merchant’s Row vendors)
* minor courier NPCs
* low-tier event rewards
* trade exchanges in safe zones

	Purpose :
* prevents information spam
* creates economic sink for intelligence access
* enforces value of knowledge acquisition

---

	5. Time-Bound World State Filter (≤48h System)

	All intelligence is filtered through strict temporal rules :
* Only recent events (past 48 hours)
* OR upcoming scheduled events
* OR active system anomalies

	This ensures :
* no outdated lore dumping
* consistent world realism
* dynamic city behavior relevance

---

	6. Crowd-Dependent Intelligence Quality (Veil of the Crowd Integration)

	Information quality changes based on Merchant’s Row activity :
* High crowd density → surface-level rumors only
* Medium density → merchant disputes + pricing shifts
* Low density → rare or hidden intelligence fragments

