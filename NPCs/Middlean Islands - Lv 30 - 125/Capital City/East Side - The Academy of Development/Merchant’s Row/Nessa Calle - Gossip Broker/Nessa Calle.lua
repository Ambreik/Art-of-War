			Nessa Calle

---

	Location : Capital City / East Side / Merchant’s Row / Central Market Network Routes

---

	Appearance : "Nessa Calle" is a lean, fast-moving woman in her late twenties with sharp, constantly observant eyes that seem to track movement patterns rather 
than people themselves. Her dark hair is tied into a loose but practical knot, with a few strands left intentionally free to soften her otherwise highly focused and
analytical presence.
	She wears a layered market runner coat reinforced with hidden internal pockets, designed not for carrying goods, but for storing folded notes, coded merchant 
tags, and information slips collected throughout the city. Small brass pins are attached to her collar, each subtly marking different information sources she trusts
within the city network.
	Her posture is relaxed but never still. She naturally positions herself in locations where sightlines intersect: between stalls, near fountains, or at walkway 
crossings, always observing crowd movement, vendor interactions, and subtle behavioral shifts within Merchant’s Row.

---

	Personality : Nessa is calm, analytical, and socially adaptive. She rarely initiates conversations and instead listens first, allowing others to reveal useful 
information unintentionally. She treats speech as a controlled exchange rather than casual interaction.
	Her mindset is transactional but not hostile. She does not lie, but she selectively filters truth based on relevance, risk level, and access permissions. To 
her, information is not knowledge — it is structured value that must be exchanged carefully.
	She has a neutral emotional tone in conversation, but her responses often carry layered implications that require interpretation. She is highly aware of 
hierarchy, legality, and behavioral risk patterns within the city.

---

	Behaviour :

	Nessa is a fully dynamic roaming NPC within Merchant’s Row.

	During daytime cycles (06:00–22:00 Capital City time), she moves between :
* high-traffic market intersections
* dock-facing entrances to Merchant’s Row
* public fountains and rest areas
* vendor clustering zones
* information density points (auction boards, notice posts)

	She dynamically reacts to :
* CLAS System state fluctuations
* Crowd Flow & Density changes
* Harbor Pulse activity spikes
* recent illegal trade activity detection
* bounty-related incidents in the district

	At night, she shifts to low-traffic circulation routes, indicating a transition from active data collection to consolidation of gathered intelligence.

	She does not engage in combat, does not flee, and cannot be forced into interaction states.

---

	Role :

* Role(s) : Gossip Broker, Local Intelligence Broker, Whisper Network Interface Node, Bounty Intelligence Handler
	Nessa Calle functions as the localized human interface layer for multiple city simulation systems. She aggregates fragmented behavioral, economic, and security 
data from the Merchant’s Row environment and converts it into structured rumor-based intelligence accessible to players.

She is the primary access point for localized world-state awareness, especially for systems that are not directly visible through UI.

