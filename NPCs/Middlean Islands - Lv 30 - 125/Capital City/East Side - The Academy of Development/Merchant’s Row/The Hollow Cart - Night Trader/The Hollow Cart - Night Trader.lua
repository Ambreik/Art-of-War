			The Hollow Cart - Night Trader

---
	
	Location : Middlean Islands → Capital City → East Side District → The Academy of Development → Merchant’s Row

---

		Appearance :

	"The Hollow Cart" is not merely the name of a merchant stall, but the identity of a strange wandering trader whose true face is never clearly visible. The 
merchant operates from an old black wooden cart reinforced with iron bindings and covered in layered cloth canopies that conceal most of its interior. Strange 
lanterns emitting pale amber and blue flames hang from the cart’s corners, illuminating shelves filled with mysterious containers, wrapped relics, sealed boxes, 
rune fragments, and unstable-looking artifacts.
	The trader himself is always obscured beneath heavy layered robes and a broad hood lined with faded symbols from unknown regions. His hands are covered by old 
leather gloves stitched with silver thread, and his voice sounds distorted, as though echoing from deep inside the cart itself.

	The cart wheels creak unnaturally even while standing still, and players occasionally report hearing whispers, coins shifting, or distant ocean sounds coming 
from within the covered compartments.

	No guards openly approach the cart, though many clearly notice its presence.

---

		Personality :

	The Hollow Cart trader is cryptic, unpredictable, and impossible to fully understand. He speaks in riddles, half-truths, and unsettling observations, often 
behaving as though he already knows what the player seeks before interaction begins.
	Unlike smugglers or black market dealers motivated by greed, this trader appears fascinated by chance, temptation, and human curiosity. He intentionally avoids 
confirming whether his goods are authentic, defective, cursed, or entirely fake.

	He finds amusement in uncertainty and often mocks players who blindly chase rarity without caution. Despite this, he is not openly malicious. Players who 
repeatedly interact with him begin noticing subtle patterns in his behavior, suggesting that his scams, gifts, and rare offers follow hidden rules.

	Toward greedy or impatient players, he becomes sarcastic and manipulative. Toward patient or observant players, his dialogue becomes strangely respectful.

---

	Behaviour : The Hollow Cart only appears during nighttime hours within Merchant’s Row.

	Spawn Conditions :
* Appears only after nightfall
* Usually manifests between 21:00 and 04:00
* Uses semi-random spawn positions inside darker sections of Merchant’s Row
* Sometimes absent entirely for multiple nights

	The cart appears silently without visual arrival animation. NPCs nearby may react nervously or avoid the area entirely while it is active.

	When nearby crowd density increases excessively :
* the cart may relocate
* temporarily close interactions
* vanish unexpectedly

	If guards or law-enforcement event states intensify due to city systems :
* the cart’s appearance chance decreases significantly

	Players below Level 70 cannot interact with the trader and receive only vague dialogue responses.

---

		Role :

* Role(s) : Night Trader, Gray Zone Vendor, Rare Goods Dealer, Unstable Item Merchant
	The Hollow Cart functions as one of Capital City’s rarest rotating underground vendor systems.

	Unlike ordinary merchants :
* inventory changes constantly
* stock quantities are heavily restricted
* item authenticity is not always guaranteed
* availability depends on hidden systems and rotations

	The Hollow Cart exists to provide :
* extremely rare progression opportunities
* unstable or experimental items
* rotating profession goods
* hidden economy pressure
* high-risk gambling purchases

	It serves as both :
* a reward layer for experienced players
* and a dangerous temptation system capable of deceiving careless buyers.

