			Lysanne Vell — Currency Exchange Broker

---

	Location : Capital City / East Side District / Merchant’s Row / Central Exchange Pavilion (Indoor Stall within Market Core Structure)

---

	Appearance : "Lysanne Vell" presents herself as a composed, sharply dressed financial specialist whose presence immediately contrasts with the chaos of 
"Merchant’s Row". She wears a refined layered silk-and-leather merchant coat dyed in muted ivory and deep emerald tones, subtly embroidered with exchange sigils 
representing different world currencies. Thin golden chains hang across her shoulders, each engraved with symbols of trade routes and regional economies.
	Her long dark hair is neatly tied into a low braid, secured with a metallic clasp shaped like interlocking coins. She wears delicate fingerless gloves designed 
for handling coin seals, exchange tokens, and arcane currency verification tools. Around her waist is a compact ledger case infused with minor enchantments that 
allow her to instantly identify and classify any currency type she touches.
	Her eyes are calm and calculating, constantly shifting between analytical focus and subtle observation of market fluctuations. She carries herself with quiet 
confidence, as if she is always aware of the current state of the global economy at any given moment.

---

	Personality : "Lysanne Vell" is highly analytical, calm, and financially intuitive. She speaks in a controlled, measured tone that reflects her understanding of
complex economic systems. Unlike typical merchants, she does not perceive currency as simple wealth but as a dynamic flow of value across interconnected systems.

	She is neither emotional nor socially driven in her decisions. Instead, she evaluates everything through :
* liquidity
* scarcity
* demand volatility
* regional economic pressure

	Lysanne has a subtle awareness of hidden economic forces, including black-market fluctuations and unofficial trade channels, though she never openly 
acknowledges them unless absolutely necessary.

---

	Behaviour : Lysanne remains stationed within the Merchant’s Row Exchange Pavilion during active market hours. She interacts primarily with players and merchants
seeking currency conversion or valuation services.

	Her behavior dynamically adjusts based on world economic conditions :
* During high trade activity, she becomes more active and offers variable exchange rates.
* During low activity periods, she limits conversion options to stabilize currency flow.
* During special global or regional events, she may shift rates unpredictably due to external economic pressure.

	She does not patrol like Varric Selborne; instead, she operates as a stationary financial processing hub with reactive systems.

---

	Role :

* Role(s) : Currency Exchange Broker, Economic Flow Analyst, Multi-Currency Conversion Specialist, Market Stability Node
	Lysanne Vell is responsible for converting and stabilizing all in-game currency types, including standard coin systems and world-drop currencies. She acts as a 
central node between regional economies, allowing players to exchange value across different systems and geographic zones.

	She is the primary interface for :
* cross-region trade conversion
* rare currency valuation
* event-based currency exchange
* economic anomaly tracking

---

	Mechanics :

* Type : System NPC / Economic Conversion Engine / Multi-Currency Exchange Hub

---

* Reputation :
	Lysanne is tied directly to :
* CLAS System (Capital Life & Activity System)
* Harbor Pulse System (foreign trade flow influence)
* Whisper Network System (indirect market intelligence correlation)

	Her reputation function is not traditional; instead, she evaluates economic credibility rather than personal standing.

	Players with higher economic activity or stable trading patterns may receive :
* better conversion rates
* access to rare currency swaps
* reduced transaction fees

	Players with unstable or suspicious transaction history may experience :
* restricted conversion options
* delayed processing
* unfavorable exchange rates

---

* Interaction Limitations :
	Players must have access to Merchant’s Row economic systems to interact with Lysanne.

	Restrictions may apply based on :
* Citizen Standing Recognition System
* detected illegal trade patterns (Gray Zone influence)
* unresolved Civic Offenses
* lack of recognized currency types in inventory

	She does not interact with combat-related systems or provide quests.

---

* PvP :
	Lysanne Vell is a protected economic entity NPC and cannot be attacked or disrupted. Any interference with her exchange functions triggers immediate Civic 
Offense escalation and potential market lockdown conditions through the Civic Offense & Fines System.

---

* Respawn Time :
	She does not use a respawn system. Instead, she operates on a continuous economic service loop tied to Merchant’s Row market hours :
* Active during market operation cycle
* Temporarily inactive during closure phase (22:00–06:00)
* System-state persists independently of physical presence

---

* Other Mechanics :

---

	1. Multi-Currency Conversion System

	Lysanne handles all currency types in your world, including :
* Silver, Gold, Platinum Coins
* Diamonds (premium currency) : sometimes can convert "Diamonds" into Silver or Gold.
* Regional world-drop currencies (e.g. Whispering Leaf, Ebon Shard Sigil, Outland Shards, etc.)
* Event currencies (e.g. Spring Leaf, Obol, Stormreach Commendation Token)

	Each category has :
* base conversion value
* regional modifiers
* event-driven volatility scaling

---

	2. Dynamic Exchange Rate System

	Exchange rates are not static.

	They fluctuate based on :
* global player economy flow
* regional supply/demand pressure
* CLAS system activity level
* event participation spikes
* Harbor Pulse trade influx

	This creates a living economy where :
* rare currencies may spike in value during events
* regional currencies depreciate outside their native zones

---

	3. Hidden “Dirty Money Flow” Detection

	Lysanne passively tracks irregular currency movement patterns linked to :
* Gray Zones of the Capital System
* illegal trade routes
* rapid laundering loops between players
* high-risk exchange chains

	She does NOT confront players directly but may :
* adjust conversion rates downward
* flag transactions internally
* trigger Whisper Network system updates

---

	4. Regional Currency Mapping System

	Each world-drop currency is mapped to :
* its origin region
* its intended service function (transport, crafting, event access, etc.)
* its exchange elasticity

	This allows Lysanne to function as a global economic translator between systems.

---

	5. Economic Event Reaction System

	During world events, Lysanne :
* adjusts conversion rates dynamically
* introduces temporary exchange restrictions
* unlocks limited-time currency swaps
* may stabilize collapsing currencies during global events

---

	6. Transaction Fee System

	All conversions include :
* base service fee (standard exchange tax)
* dynamic market fee (based on volatility)
* optional premium stabilization fee (reduces risk fluctuation)

	These fees act as a money sink mechanic, tying into the broader economic cycle system.

