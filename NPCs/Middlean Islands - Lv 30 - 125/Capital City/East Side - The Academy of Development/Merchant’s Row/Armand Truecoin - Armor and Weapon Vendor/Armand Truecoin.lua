			Armand Truecoin

	Location : Middlean Islands / Capital City / East Side District / The Academy of Development / Merchant’s Row

---

	Appearance : "Armand Truecoin" is a broad-shouldered middle-aged human with a powerful build shaped by years of lifting armor crates, inspecting weapon 
shipments, and dealing personally with craftsmen from across the continent. His short steel-gray hair and neatly trimmed beard frame a stern face marked by old 
scars and constant exposure to forge smoke and sea air. His piercing blue eyes rarely miss details, carefully studying both merchandise and customers with the same 
level of scrutiny. He wears a finely tailored dark leather tunic reinforced with brass fittings and thick protective gloves designed for handling sharpened steel. 
Around his waist hangs a heavy keyring attached to locked weapon cases and secured shipment containers. His stall is meticulously organized, with polished armor 
sets, carefully mounted weapons, and labeled equipment racks displaying his appreciation for order and quality craftsmanship.

---

	Personality : Armand is disciplined, practical, and highly business-oriented. He values reliability, honesty, and craftsmanship above charm or flashy displays. 
Most first-time customers find him intimidating due to his direct way of speaking and his habit of silently judging people before addressing them. However, regular 
customers slowly discover that beneath his stern exterior lies a merchant who genuinely respects hardworking adventurers and skilled warriors. Armand dislikes 
wastefulness, poor weapon maintenance, and reckless fighters who treat equipment carelessly. While he rarely engages in unnecessary conversation, he occasionally 
offers valuable advice regarding weapon balance, armor durability, or battlefield preparation to customers he considers serious professionals.

---

	Behaviour : Armand spends most of his day inspecting weapon edges, polishing armor pieces, reviewing shipment manifests, or negotiating with blacksmith 
suppliers arriving through the harbor district. He regularly checks every displayed item personally, immediately noticing if something has been moved or mishandled.
During busy hours, he maintains strict control over the flow of customers around his stall, preventing overcrowding and discouraging thieves or troublemakers simply
through his presence. At night, he carefully secures his most valuable merchandise inside reinforced display cases protected by multiple locks and merchant seals.

---

	Role :

* Role(s) : Armor Merchant, Weapon Merchant, Equipment Advisor
	Armand functions as one of Merchant’s Row’s primary equipment suppliers, specializing in reliable weapons, protective gear, and combat-related supplies for 
adventurers traveling throughout Middlean Islands and beyond. Beyond simple trade, he also acts as a knowledgeable advisor regarding combat equipment quality, 
weapon care, and practical battlefield preparation.

