			Apprentice Blacksmith Varren Fellspar

---

	Location : Middlean Islands / Capital City / Central Side District / The Blacksmith’s Forge

---

		Appearance :

	Varren Fellspar is a tall, lean human apprentice in his early twenties with an earnest expression and focused eyes that rarely leave the weapon he is working 
on. His dark brown hair is usually tied back loosely to keep sparks and metal dust away from his face, though strands constantly fall across his forehead during 
work.
	Unlike veteran blacksmiths whose bodies bear years of forge scars, Varren’s hands show only the early signs of the profession — small burns, roughened 
fingertips, and fresh cuts from sharpening blades. His lighter leather apron hangs over a practical linen tunic with rolled sleeves, and metal dust often coats his 
clothing from long hours beside the grinding wheel.
	A collection of whetstones, polishing cloths, miniature hammers, and sharpening oils hang neatly from his belt. He is most commonly found standing near the 
grinding stone at the side of the forge, carefully refining weapon edges with patient, repetitive precision.

	Though still an apprentice, his workstation is unusually organized, reflecting both discipline and pride in his craft.

---

		Personality :

	Varren is ambitious, hardworking, and deeply passionate about blacksmithing. Unlike his mentor’s gruff demeanor, he is approachable and enjoys speaking with 
adventurers about their weapons, fighting styles, and maintenance habits.
	He speaks enthusiastically about steel quality, edge balance, and weapon care, often becoming overly detailed when discussing sharpening techniques. Despite his
youth, he takes his responsibilities seriously and constantly seeks approval from his mentor and experienced warriors alike.

	Varren admires skilled fighters and often asks customers how his sharpened blades performed in battle. He enjoys hearing stories from distant regions and sees 
every repaired or sharpened weapon as another lesson in the craft.
	While confident in his sharpening abilities, he remains humble about his overall skill level, openly acknowledging that he still has much to learn before 
becoming a true master blacksmith.

---

		Behaviour :

	Varren spends most of his time :
* Sharpening weapons at the grinding stone.
* Performing small equipment repairs.
* Organizing tools and ore shipments.
* Studying weapon damage patterns from returning adventurers.

	He frequently inspects weapons brought by players, occasionally commenting on :
* Blade balance
* Edge quality
* Signs of improper maintenance
* Combat wear

	When idle, he practices sharpening techniques on damaged training blades or assists other forge workers with smaller tasks around the workshop.
	During busy hours, sparks continuously fly from his workstation as the grinding wheel echoes through the forge.

---

	Role :

* Role(s) : Apprentice Blacksmith, Weapon Maintenance Specialist, Precision Sharpening NPC
	Varren specializes in :
* Weapon sharpening
* Minor repairs
* Temporary combat enhancements for melee weapons

	He acts as an accessible support NPC for adventurers preparing for combat encounters, dungeons, raids, or hunting expeditions.
	Unlike full blacksmiths focused on heavy forging and crafting, Varren concentrates on precision finishing and weapon upkeep.

---

		Mechanics :

* Type : Service NPC / Weapon Enhancement NPC
* Reputation : No direct reputation system attached.
	However:
	* Frequent usage of his services slightly improves local familiarity dialogue.
	* Blacksmith profession players may unlock additional dialogue interactions.
* Interaction Limitations :
	* Primarily interacts with players using melee weapons.
	* Cannot sharpen broken weapons.
	* Temporary effects cannot stack with stronger sharpening buffs.

* PvP :
	* Cannot be attacked under normal conditions.
	* Protected by nearby city guards and forge workers.
	* Not flagged for PvP.

* Respawn Time : Immediate respawn.

* Other Mechanics :

		Precision Sharpening

	Varren offers a special sharpening service known as : "Precision Sharpening"
	Using specialized grinding techniques and polishing compounds, Varren sharpens melee weapons to an exceptionally fine edge.

	Eligible Weapons : 
* Swords
* Axes
* Daggers
* Spears
* Glaives
* Rapier
* Claws

	Effects
* The service grants :
	* Temporary Critical Damage Increase
	* Slight increase to physical attack precision
	* Improved edge quality visuals on certain weapons

	Duration Methods : 
* Depending on balancing systems, the effect may last :
	* A fixed gameplay duration
		or
	* A limited number of successful hits

	Restrictions : 
* Cannot be applied while another sharpening effect is active.
* Effect disappears upon weapon breakage.
* Magical weapons may receive reduced effectiveness depending on enchantments.

	Visual Effects : 
* Sharpened weapons may display :
	* Refined blade glow
	* Metallic sheen
	* Sharper impact spark effects

	Varren takes pride in this technique and considers it his personal signature craft.

