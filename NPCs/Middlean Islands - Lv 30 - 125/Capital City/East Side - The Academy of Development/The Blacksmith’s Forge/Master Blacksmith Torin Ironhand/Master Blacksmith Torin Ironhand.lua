		Quest :

* Quest Title : Forging of Legend – Trial of the First Flame
* Quest Type : Storyline / Profession Advancement / Legendary Crafting Chain
* Objective(s) :
	* Acquire Epic +9 equipment
	* Gather category-specific catalysts and materials
	* Complete Cursed Tower trial (multi-floor combat instance)
	* Obtain Legendary Perchant item
	* Present full material set to Torin Ironhand

