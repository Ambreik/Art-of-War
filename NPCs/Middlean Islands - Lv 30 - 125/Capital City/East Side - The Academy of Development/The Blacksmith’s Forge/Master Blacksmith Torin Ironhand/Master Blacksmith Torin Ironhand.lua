* Forge Trust increase
* Access to regional legendary recipes
* Exclusive forging title: "Heir of the First Flame"

* Conditions :
	* Blacksmith Profession Rank III minimum
	* Access to Legendary Blacksmith system unlocked
	* Completion of prerequisite forging tutorials or hidden discovery trigger

* Quest Dialogue :
	* Opening : "So… you seek to reshape fate itself through steel? Show me what you believe is worth becoming legend."
	* Mid-Quest : "The fire tests not the metal alone… but the one who dares command it."
