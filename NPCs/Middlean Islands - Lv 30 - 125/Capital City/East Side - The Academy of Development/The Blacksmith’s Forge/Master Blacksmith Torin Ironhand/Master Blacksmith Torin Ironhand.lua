---

		Skills :

* Skill 1 : Ancestral Forge Awakening
	* Description : Torin channels inherited forge energy from his lineage, awakening latent material properties in weapons and armor.
	* Effect : Temporarily increases success rate for reinforcement and crafting outcomes.

* Skill 2 : Dragonbone Tempering
	* Description : A forbidden technique originating from the Second Great War, used to refine materials derived from dragon remains.
	* Effect : Enhances durability and unlocks hidden stats in certain crafted items.

* Skill 3 : Forge Memory Seal
	* Description : Torin binds ongoing forging projects into a stable forge-memory state.
	* Effect : Allows interruption-free Legendary Forging Rituals and safe item storage during crafting.

