			Master Blacksmith Torin Ironhand

---

	Location : Capital City (Middlean Islands) / Blacksmith District / The Blacksmith’s Forge (Shared Legendary Forge)

---

		Appearance :

	"Torin Ironhand" is a towering, heavily built dwarf of ancient lineage, his body shaped by centuries of forging and divine metallurgy. His skin carries the 
darkened tint of constant exposure to primordial flame, while his arms are etched with old burn marks that glow faintly when he channels forge energy.
	His beard is thick, braided, and threaded with fragments of meteoric iron and ancestral forge rings — heirlooms passed down from the First Legendary Blacksmith 
lineage. His eyes hold a deep ember-like glow, not natural, but the result of drinking from the "Living Water", a sacred source said to preserve the soul of master 
artisans.
	He wears a reinforced blacksmith’s mantle layered with enchanted forge-leather and molten-resistant alloy plates. A massive forging apron, marked with the sigil
of the "First Forge", hangs over his torso. His hands are enormous, calloused beyond recognition, and permanently stained with metallic dust and rune ash.

	Unlike ordinary smiths, Torin carries no excessive tools — only a single ancestral hammer known as "Gravemelt", capable of shaping both physical and magical 
essence.

---

		Personality :

	Torin is stern, deeply disciplined, and carries the weight of an ancient craft lineage. He speaks with deliberate precision, never wasting words, and evaluates 
every player based on intent rather than appearance.
	He respects perseverance, craftsmanship, and patience above all else. To him, failure is not weakness but an unrefined stage of mastery.

	Despite his intimidating presence, Torin is not hostile or arrogant. Instead, he carries a quiet pride rooted in responsibility — the belief that he and his 
bloodline are guardians of forged destiny.

	He occasionally references forgotten history, the First Legendary Blacksmith, and the burden of shaping weapons born from dragon remains and primordial war 
relics.

---

		Behaviour :

	Torin is almost always found at his central forge, actively engaged in high-intensity crafting or reinforcement processes.

	His behaviour includes :
* Inspecting legendary-grade materials with intense focus
* Reacting to rare ores with visible interest or silence
* Entering forging trance states during legendary upgrades
* Occasionally pausing to observe players’ equipment quality
* Showing subtle emotional shifts when encountering weapons tied to ancient wars or dragon lineage

	During "Legendary Forging Rituals", he becomes fully immersed in the process, initiating forge-memory stabilization and guiding the ritual through sacred chants
inherited from his bloodline.

---

		Role :

* Role(s) : Legendary Blacksmith, Tier IV Blacksmith Trainer, Reinforcement Master, Repair Specialist, Crafting Mentor, Vendor, Forge Ritual Artisan
	
	Torin serves as one of the highest-tier blacksmith NPCs in the world, responsible for :
* Upgrading Epic equipment into Legendary equipment
* Teaching advanced Blacksmith profession techniques (Tier IV Trainer)
* Reinforcing and stabilizing high-tier gear
* Repairing advanced equipment based on profession rank and reputation
* Providing access to rare forging knowledge from ancient lineage

	He is one of the last living descendants of the "First Legendary Blacksmith" and continues his lineage alongside his brother, both having inherited the sacred 
craft through the "Living Water", a mythical essence that made them immortals.

---

		Core Functionality Revision

	The "Legendary Blacksmith" represents the highest evolution of the traditional blacksmith system within the world.
	Rather than functioning as a mystical or unreachable figure detached from normal crafting, this NPC is deeply integrated into the equipment progression 
ecosystem as a master artisan capable of advanced forging techniques unavailable to ordinary blacksmiths.

	The "Legendary Blacksmith" acts as :
* A superior version of the standard Blacksmith NPC.
* A Tier IV "Blacksmith Profession Trainer".
* A creator of advanced upgrade materials.
* A specialist in equipment evolution.
* A master craftsman capable of legendary forging.
* A support NPC for high-end upgrading systems.

	The NPC remains grounded in the world’s core equipment progression systems and advanced forgecraft traditions.

---

		Core Identity

	The "Legendary Blacksmith" is fundamentally :
* A master blacksmith.
* A progression-based crafting NPC.
* A high-end equipment evolution specialist.
* A creator of enhancement-support materials.

	Their systems are extensions of the normal blacksmith ecosystem rather than separate magical systems.

	Players should feel that :
* Standard blacksmiths handle ordinary crafting and upgrading.
* Legendary blacksmiths handle advanced evolution, stabilization, reinforcement, and legendary-tier progression.

---

		Primary Functions

	1. Advanced Equipment Evolution

	The "Legendary Blacksmith" can evolve existing equipment into stronger versions using :
* Base equipment
* Evolution materials
* Boss drops
* Regional crafting resources
* Upgrade catalysts

	The evolved equipment becomes :
* Stronger
* Visually distinct
* More resource-intensive
* Dependent on progression materials

	This system is intended to represent the advanced stage of weapon and armor progression.

---

	2. Legendary Item Forging

	The blacksmith is also responsible for :
* Epic → Legendary equipment evolution

	Legendary forging is considered the highest stage of the upgrade ecosystem.

	The process requires :
* Specialized materials
* Advanced forgecraft
* Time-based reforging
* A "Legendary Blacksmith"

	This process remains tied to craftsmanship and advanced forging mastery rather than pure magical transformation.

---

	3. Blacksmith Profession Trainer (Tier IV)

	The NPC functions as a :
* Tier IV "Blacksmith Profession Trainer"

	Training functions include :
* Advanced forging recipes
* High-tier reinforcement techniques
* Enhancement material creation
* Repair technologies
* Stabilization systems
* Legendary crafting blueprints

	This directly integrates the NPC into the "Blacksmith Profession System".

---

	4. Advanced Upgrade Support

	Unlike regular blacksmiths, the "Legendary Blacksmith" can :
* Create upgrade enhancers
* Create failure-reduction materials
* Create advanced repair tools
* Restore durability
* Create binding-removal tools
* Create reinforcement catalysts

	These functions expand and support the higher tiers of the equipment upgrade ecosystem.

