			The Legendary Forging Ritual

		Epic → Legendary Evolution

---

		Overview

	The "Legendary Forging Ritual" is an advanced crafting process available exclusively through all "Legendary Blacksmiths" across the world. This sacred ritual 
allows players to evolve fully upgraded "Epic Equipment" (+9) into powerful "Legendary Equipment".
	The ritual is considered one of the highest achievements within the "Blacksmith Profession System", requiring rare materials, specialized catalysts, and the 
expertise of a true "Legendary Blacksmith".

	Players undergo a multi-stage forging sequence involving material gathering, profession progression, world exploration, and time-based reforging.
	Only one item may undergo the ritual at a time.

---

		Eligible Equipment Categories

	Only specific equipment types may undergo the "Legendary Forging Ritual".
	Each ritual belongs to one of three recognized forging categories :

---

	Armor Category

Includes :
* Armor
* Helmets
* Shields

	These items embody endurance, defense, and physical resilience.
	Armor-category legendary equipment often gains enhanced defensive scaling, durability enhancements, and resistance-oriented effects.

---

	Weapon Category

Includes :
* Swords
* Axes
* Spears
* Daggers
* Bows
* Bells
* Class-specific weapons

	Weapons forged through the ritual carry elemental resonance and battle essence tied to the wielder.
	Legendary weapons frequently gain aura effects, enhanced combat scaling, and unique visual properties.

---

	Accessory Category

Includes :
* Necklaces
* Earrings
* Bracelets
* Shoes

	Accessories forged into legendary quality become spiritual conduits that strengthen attributes, passive effects, and aura-based enhancements.

---

	Required Materials : The ritual requires a complete set of rare materials and catalysts before forging may begin.

---

		1. Primary Catalyst

	Each equipment category requires a unique catalyst item.

	Armor : 
* "Emberheart Core"

	Weapon : 
* "Shard of Celestite"

	Accessory : 
* "Twilight Sigil"

	Source : These catalysts are dropped by elite enemies and instance bosses located throughout the "Outland Territories".

---

		2. Legendary Perchant

	A special quest-bound forging component required for all rituals.

	Acquisition : 
* Obtained exclusively through the :
	* "Forging of Legend" questline

	Quest Details : 
* Initiated at any "Legendary Blacksmith"
* Sends players into the "Cursed Tower"
* Requires completion of a multi-floor combat trial
* Final boss guarantees :
	* 1x "Legendary Perchant"

	Restrictions : 
* Bound quest item
* Cannot be traded
* Consumed upon ritual initiation

---

		3. Epic Equipment Base

	The item selected for evolution must meet the following conditions :
* Must be "Epic" rarity
* Must be upgraded to +9
* Must not be locked in another progression system

	Ritual Binding
* Once forging begins :
	* The item is removed from the player inventory
	* Stored within the "Forge Memory" of the initiating "Legendary Blacksmith"
	* Becomes inaccessible until ritual completion

---

		4. Category Focus Components

	Additional category-specific materials are required.

	Armor : 
* "Ancestral Core"

	Weapon : 
* "Dragonforged Ember"

	Accessory : 
* "Celestial Binding Gem"

	Source : 
* Dropped by open-world bosses throughout the "Outland Territories".
* These components represent the spiritual focus required to stabilize legendary evolution.

---

		5. Elemental Essences

	The ritual requires :
* 50x of each required elemental essence

	Essence Sources : 

| Region              | Essence          |
| ------------------- | ---------------- |
| Aarong Forest       | "Earth Essence"  |
| Lagooma Jungle      | "Wind Essence"   |
| Tenebress Territory | "Fire Essence"   |
| Frozen Territory    | "Ice Essence"    |
| Underworld          | "Shadow Essence" |

	Monster Requirement

	Essences drop from :
* Rank II monsters
* Rank III monsters
* Rank IV monsters

	Additional Notes : "Light Essence" is a crafted material and is not required for legendary item creation.

---

		6. Refined Minerals and Ores

	The forging process also requires advanced crafting metals and stones.

	Required Materials : 
* 20x "Black Iron Bar"
* 15x "Obsidian"
* 10x "Shadowstone"

	Sources
* Obtained through :
	* Mining professions
	* Regional trading
	* Crafting exchanges
	* Specialized vendors

---

		Forging Process

	Once all requirements are fulfilled, the "Legendary Blacksmith" initiates the :

	"Ritual of Ascension"

	This is a two-hour forging sequence representing :
* Spiritual tempering
* Material reforging
* Arcane stabilization
* Legendary infusion

---

		Forge Memory System

	During the ritual :
* The submitted item is removed from the player's inventory
* Stored safely inside the forge memory of the initiating blacksmith
* Cannot be accessed, traded, or destroyed during the process

	The forging sequence is fully tied to the specific "Legendary Blacksmith" who initiated the ritual.

---

		Forge Progress UI

	Upon ritual activation :
* A special "Forge Progress UI" appears within the player's buff/debuff interface.

	UI Appearance : 
* Animated forge emblem
* Surrounded by burning flames
* Visible active timer

	Tooltip

Hovering over the icon displays :

> "Forging in Progress — Time Remaining: [hh:mm:ss]"

	Timer Behavior : 
* Counts down in real time
* Continues regardless of player location
* Persists through logout

---

		Blacksmith System Messages

	Throughout the ritual, the player may receive immersive forge messages in the system feed.

	Examples include :
* "The anvil hums with life…"
* "I can feel the soul of your weapon resisting!"
* "Patience, hero. True power cannot be rushed."

	These messages reinforce the living nature of legendary crafting.

---

		Blacksmith Binding Restriction

	The ritual remains permanently linked to the initiating blacksmith until completion.

	Attempting to interact with another "Legendary Blacksmith" while the ritual is active results in the message :

> "This forge is not bound to your creation. Seek the smith who began your legend."

	Players must return to the original blacksmith to :
* Complete the ritual
* Claim the result
* Resolve failures
* Retrieve forged equipment

---

	Ritual Outcome : At the end of the forging duration, the ritual resolves into one of two outcomes.

---

		Success

	If successful :
* Results : 
	* The Epic item evolves into a "Legendary Item"
	* Gains enhanced stat scaling
	* Unlocks unique visual aura effects
	* Dynamically scales with player progression

	Signature Effect
* The tooltip gains the additional line :

> "Forged by the hand of a Legend."

	This signature permanently identifies the item as a true legendary creation.

---

		Failure

	If the ritual fails :
* Results : 
	* The item is safely returned
	* No destruction occurs
	* No downgrade occurs
	* No stat loss occurs

	Temporary Debuff : 
* The player receives :
	* "Temper of the Unforged"

	Tooltip : 

> "Still recovering from the strain of divine heat. Cannot be reforged for 12 hours."

	Effect : 
* Prevents another legendary forging attempt
* Duration :
	* 12 Hours

	This cooldown represents the instability caused by failed legendary tempering.

---

	Additional Notes : 
* Only one active legendary ritual may exist per player at a time.
* Legendary forging is considered one of the highest-tier progression systems in the game world.
* The process is accessible to both factions through neutral "Legendary Blacksmiths".
* Ritual materials are consumed upon successful or failed completion unless otherwise specified.
* Legendary items are considered unique creations tied to the legacy of the ancient forge arts.
