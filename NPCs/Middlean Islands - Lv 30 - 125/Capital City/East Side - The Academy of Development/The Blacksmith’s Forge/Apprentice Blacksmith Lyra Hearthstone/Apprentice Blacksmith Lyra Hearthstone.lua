			Apprentice Blacksmith Lyra Hearthstone

---
	
	Location : Outland Territories / Major City / Central District / The Blacksmith’s Forge

---

		Appearance :
	"Lyra Hearthstone" is a slender high elf with pale skin and silver-blonde hair usually tied into a practical braid to keep it away from sparks and magical 
residue. Her sharp amber eyes constantly study every detail of the equipment she handles, reflecting both concentration and curiosity. Unlike the heavier appearance
of most forge workers, Lyra wears a fitted dark robe reinforced with leather straps and metal-thread embroidery resistant to heat and magical backlash.
	Around her waist hangs a carefully organized toolbelt filled with engraving needles, rune chisels, enchanted powders, crystal lenses, and delicate smithing 
instruments used for magical infusions. Thin protective gloves cover her hands when handling enchanted metals, though she occasionally removes them when performing 
precise rune work.
	Her workstation at the rear of the forge is quieter than the main anvil area, illuminated by blue arcane flames and surrounded by rare ores, glowing gemstones, 
and partially completed enchanted equipment. Unlike the loud clanging near Torin and Varren, Lyra’s section emits soft humming sounds from magical resonance and 
rune stabilization.

---

		Personality :
	Lyra is calm, reserved, and exceptionally detail-oriented. She speaks softly and carefully, rarely wasting words, but when discussing magical metals or 
enchantments her passion becomes clear. While she may initially appear distant, she treats respectful adventurers with patience and professionalism.
	She believes every weapon and armor piece possesses a “spirit” shaped by its owner’s battles and experiences, which is why she handles equipment with unusual 
care. Lyra values precision over speed and often criticizes careless craftsmanship or reckless enchantment attempts.

	Despite her quiet demeanor, she is highly knowledgeable and willing to educate players interested in magical forging or enchanted equipment maintenance.

---

		Behaviour :
	Lyra spends most of her time quietly engraving runes, inspecting magical reactions within ores, or stabilizing enchantments on unfinished gear. She rarely 
raises her voice and prefers working in silence while focusing on delicate imbuing procedures.
	When players bring unstable or corrupted equipment, Lyra becomes visibly cautious and may temporarily halt nearby enchantment work until the item is safely 
examined. Occasionally, faint magical sparks or glowing sigils appear around her hands while she works.

---

	Role :
* Role(s) : Enchantment Specialist, Craft NPC, Blacksmith Assistant, Magical Equipment Imbuer
	Lyra specializes in imbuing weapons and armor with magical effects that improve combat efficiency, resistances, and utility bonuses. She assists players by 
applying enchantments, removing old magical effects, stabilizing unstable enchantments, and advising players on compatible magical enhancements for their equipment.
	She also supports Torin Ironhand’s advanced forging operations by preparing enchanted materials required for high-tier upgrades and Legendary crafting 
procedures.

---

		Mechanics :

* Type : Craft NPC, Enchantment NPC, Support Blacksmith NPC
* Reputation :
	Players may unlock additional enchantment options and reduced enchanting costs through Reputation (REP) gained with the forge or through Blacksmith Profession 
progression. Certain advanced enchantments require higher regional REP or profession milestones.
* Interaction Limitations :
	Most standard enchantments are available to all players. Advanced magical infusions require :	
	* Higher level equipment
	* Specific magical materials
	* Certain Reputation thresholds
	* Profession progression for advanced crafting-based infusions
* PvP : Lyra is a protected city NPC and cannot normally be attacked outside PvP-enabled interactions. Attacking her within city limits immediately alerts nearby 
guards and temporarily disables her services for aggressive players.
* Respawn Time : If defeated during PvP-enabled situations or special events, Lyra respawns after a standard city NPC recovery duration.
* Other Mechanics :
	* Allows players to apply elemental enchantments to weapons and armor
	* Can add resistance bonuses to defensive equipment
	* Removes existing enchantments to free item slots for new effects
	* Certain enchantments have success chances depending on item quality
	* Advanced enchantments may require rare reagents, enchanted stones, or boss materials
	* Enchantments visually alter some equipment with glowing effects, magical particles, or rune markings
	* Failed advanced enchantments may consume materials without damaging the item
	* Some enchantments are temporary while others are permanent
	* Can stabilize unstable magical items before upgrading procedures

---

		Skills :

* Skill 1 : Enchantment Imbuing
	* Description : Lyra engraves magical runes and channels arcane energy into equipment, granting weapons and armor elemental or defensive properties.
	* Effect : Adds magical bonuses such as fire resistance, mana regeneration, elemental damage, or attribute increases.

* Skill 2 : Rune Stabilization
	* Description : Carefully stabilizes unstable magical energy within equipment before further upgrading or enchanting.
	* Effect : Reduces the chance of enchantment failure on certain advanced procedures.

* Skill 3 : Enchantment Cleansing
	* Description : Removes old magical imprints from equipment without damaging its structure, allowing new enchantments to be applied.
	* Effect : Clears existing enchantment slots and resets magical properties on selected gear.

* Skill 4 : Arcane Infusion Analysis
	* Description : Examines equipment resonance and identifies compatible magical effects based on item category and quality.
	* Effect : Reveals possible enchantment paths and hidden magical compatibility for players.

