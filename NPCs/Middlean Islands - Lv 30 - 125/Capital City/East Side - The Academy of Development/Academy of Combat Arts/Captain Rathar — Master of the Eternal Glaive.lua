			Captain Rathar — Master of the Eternal Glaive (Paladin)
			
---

	Location : Academy of Combat Arts — Sanctified Bulwark Wing (East Side District, Capital City)

---

	Appearance : "Captain Rathar" stands in heavy sanctified plate armor engraved with layered oath-seals and defensive scripture markings. A long Glaive is planted
firmly beside him, its metallic surface reinforced with holy alloy bands.
	A calm, steady light surrounds him — a "Sanctified Oath Aura", giving the impression of unwavering protection and absolute discipline.

---

	Personality : Authoritative, disciplined, and principled. Speaks with military precision and moral certainty.

---

	Behavior :
* Rathar never leaves his position inside the academy.
* He oversees structured defensive drills and formation training layouts designed for tactical discipline.
* Players may challenge him to sparring matches. During sparring, Rathar perfectly adjusts to the player’s level, equipment, and skill progression to create a 
balanced combat experience.

---

	Role : 
* Class Master for :
	* Paladin (Zonen) — Glaive Specialist

	Rathar is a higher authority than common class trainers found in starting zones.
	He does not teach basic skills but explains advanced mechanics, defensive rotations, aggro control principles, positioning discipline, and hybrid offense-
defense optimization.

	He is responsible for unlocking the "Ultimate Skill" of the Paladin when the time comes.

---

	Mechanics & Functions : 
* Explains every Paladin skill in depth
* Explains defense/offense balancing mechanics
* Explains aggro control and battlefield positioning
* Explains survivability scaling and mitigation optimization
* Allows sparring practice that scales dynamically to the player
* Unlocks the future "Ultimate Skill"
* Skillable NPC
* No quests
* No vendor window

---

	Interaction : Rathar acknowledges players with a strict nod, as if accepting them into formation rather than conversation.

---

	Quotes : 
* "Defense is not passive. It is command."
* "Hold the line, or you are already defeated."
* "Every step must have purpose."
* "A shield that falters becomes a burden."

