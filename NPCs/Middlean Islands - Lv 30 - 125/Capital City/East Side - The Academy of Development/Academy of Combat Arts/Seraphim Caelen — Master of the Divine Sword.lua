			Seraphim Caelen — Master of the Divine Sword

	Location : Academy of Combat Arts — Swordsmen Wing (East Side District, Capital City)

---

	Appearance : "Seraphim Caelen" stands tall in polished silver-and-gold plate armor engraved with symbols of valor and discipline. A long royal-blue tabard flows
from his waist, marked with the emblem of the sword academy. His greatsword rests tip-down before him, hands calmly placed over the pommel.
	A faint warmth and visual shimmer surrounds him — a "Silent Valor Aura" that makes nearby weapons hum softly in resonance with his presence.

---

	Personality : Calm, disciplined, and commanding. Speaks with clarity and purpose.

---

	Behavior : 
* Seraphim never leaves his position inside the academy.
* He remains in a composed stance, observing the training grounds.
* Players may challenge him to sparring matches. During sparring, Seraphim perfectly adjusts to the player’s level, equipment, and skill progression to create a 
balanced combat experience.

---

	Role : 
* Class Master for :
	* Warrior Knight (Dendera) — Sword Specialist

	Seraphim is a higher authority than common class trainers found in starting zones.
	He does not teach basic skills but explains advanced mechanics, skill interactions, combos, and hidden efficiencies of the class.

	He is responsible for unlocking the "Ultimate Skill" of the "Warrior Knight" when the time comes.

---

	Mechanics & Functions : 

* Explains every Warrior Knight skill in depth
* Explains combo chains and optimal skill rotations
* Explains hidden mechanics and efficiency tricks
* Allows sparring practice that scales dynamically to the player
* Unlocks the future "Ultimate Skill"
* Skillable NPC
* No quests
* No vendor window

---

	Interaction : When approached, Seraphim acknowledges the player’s presence without breaking his stance.

---

	Quotes : 

* "A sword is only as noble as the one who wields it."
* "Strength without discipline is chaos."
* "Show me your stance."
* "You seek mastery, not power."

