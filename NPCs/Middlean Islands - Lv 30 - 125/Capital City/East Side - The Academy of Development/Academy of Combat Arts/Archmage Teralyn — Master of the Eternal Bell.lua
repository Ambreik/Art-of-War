			Archmage Teralyn — Master of the Eternal Bell

---

	Location : Academy of Combat Arts — Arcane Wing (East Side District, Capital City)

---

	Appearance : "Archmage Teralyn" wears layered arcane robes infused with faint glowing runic patterns that shift depending on his movement. In his hand rests a 
finely carved Bell, embedded with a crystalline core that pulses with controlled elemental energy.
	A constant low shimmer surrounds him — an "Arcane Flow Aura" that distorts light slightly around his silhouette, as if reality bends in small ways near him.

---

	Personality : Analytical, composed, and intellectually precise. Speaks in structured, deliberate sentences.

---

	Behavior : 
* Teralyn never leaves his position inside the academy.
* He stands within a circular arcane training chamber surrounded by floating elemental sigils and practice runes.
* Players may challenge him to sparring matches. During sparring, Teralyn perfectly adjusts to the player’s level, equipment, and skill progression to create a 
balanced combat experience.

---

	Role : 
* Class Master for :
	* Mage / Dragon Mage (Dendera) — Bell Specialist

	Teralyn is a higher authority than common class trainers found in starting zones.
	He does not teach basic skills but explains advanced mechanics, elemental scaling, spell interactions, mana control, and hidden arcane efficiencies.

	He is responsible for unlocking the "Ultimate Skill" of the Mage when the time comes.

---

	Mechanics & Functions : 
* Explains every Mage skill in depth
* Explains elemental interactions, scaling, and spell amplification
* Explains mana efficiency and casting optimization
* Explains hidden mechanics and arcane synergy effects
* Allows sparring practice that scales dynamically to the player
* Unlocks the future "Ultimate Skill"
* Skillable NPC
* No quests
* No vendor window

---

	Interaction : Teralyn often pauses before speaking, as if calculating the most efficient possible explanation for the player’s understanding.

---

	Quotes : 
* "Magic is structure before it is power."
* "Control defines outcome."
* "Do not cast what you do not understand."
* "Every spell has a cost. Know it."

