			Fenric Bloodhowl — Master of the Beast Within

---

	Location : Academy of Combat Arts — Lunar Instinct Wing (East Side District, Capital City)

---

	Appearance : "Fenric Bloodhowl" stands with a powerful, athletic build, partially armored in reinforced leather and bone-bound plates designed for unrestricted 
movement. His hands are unarmed, but his fingers carry faint claw-like markings as if his body itself is part of the weapon.
	A deep, unstable aura surrounds him — a "Lunar Instinct Aura", shifting subtly between calm and violent energy, like a restrained storm waiting to break.

---

	Personality : Instinct-driven, intense, and direct. Speaks with raw certainty rather than structured explanation.

---

	Behavior : 
* Fenric never leaves his position inside the academy.
* He trains within an open circular arena of cracked stone and marked scratch lines, designed for uncontrolled movement and reactive combat drills.
* Players may challenge him to sparring matches. During sparring, Fenric perfectly adjusts to the player’s level, equipment, and skill progression to create a 
balanced combat experience.

---

	Role : 
* Class Master for :
	* Werewolf (Zonen) — Claw Specialist

* Fenric is a higher authority than common class trainers found in starting zones.
* He does not teach basic skills but explains advanced mechanics, rage state transitions, instinct scaling, transformation timing, damage escalation windows, and 
hidden primal combat efficiencies.

* He is responsible for unlocking the "Ultimate Skill" of the Werewolf when the time comes.

---

	Mechanics & Functions : 
* Explains every Werewolf skill in depth
* Explains transformation mechanics and rage scaling systems
* Explains instinct-based combat flow and reaction timing
* Explains hidden beast-form efficiency mechanics
* Allows sparring practice that scales dynamically to the player
* Unlocks the future "Ultimate Skill"
* Skillable NPC
* No quests
* No vendor window

---

	Interaction : Fenric does not greet players traditionally — he simply studies their stance, as if reading their instincts before they move.

---

	Quotes : 
* "Think less. Move more."
* "Your body knows before you do."
* "Control is an illusion — instinct is truth."
* "Let the beast decide."

