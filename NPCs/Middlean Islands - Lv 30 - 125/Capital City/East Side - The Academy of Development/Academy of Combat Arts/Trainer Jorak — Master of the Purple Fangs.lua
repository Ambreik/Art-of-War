			Trainer Jorak — Master of the Purple Fangs
			
---

	Location : Academy of Combat Arts — Shadow Discipline Wing (East Side District, Capital City)

---

	Appearance : "Trainer Jorak" wears dark layered leather armor reinforced with light metal plating designed for agility and silent movement. A pair of finely 
balanced daggers are always visible at his sides, worn with deliberate readiness rather than display.
	A faint violet mist clings subtly around him — a "Venomstep Aura", giving the impression of motion even when he stands still.

---

	Personality : Sharp, pragmatic, and opportunistic in mindset. Speaks in short, efficient statements with tactical focus.

---

	Behavior : 
* Jorak never leaves his position inside the academy.
* He monitors agility drills, stealth pathways, and precision strike exercises from elevated shadow walkways.
*Players may challenge him to sparring matches. During sparring, Jorak perfectly adjusts to the player’s level, equipment, and skill progression to create a 
balanced combat experience.

---

	Role : 
* Class Master for :
	* Rogue (Zonen) — Dagger Specialist

	Jorak is a higher authority than common class trainers found in starting zones.
	He does not teach basic skills but explains advanced mechanics, stealth engagement timing, combo optimization, poison application efficiency, and hidden 
execution mechanics.

	He is responsible for unlocking the "Ultimate Skill" of the Rogue when the time comes.

---

	Mechanics & Functions : 
* Explains every Rogue skill in depth
* Explains stealth entry/exit timing and positioning logic
* Explains combo flow and execution optimization
* Explains poison application efficiency and damage scaling
* Allows sparring practice that scales dynamically to the player
* Unlocks the future "Ultimate Skill"
* Skillable NPC
* No quests
* No vendor window

---

	Interaction : Jorak evaluates players briefly, often noticing their movement patterns before they even speak.

---

	Quotes : 
* "If they see you, you failed."
* "Speed is not movement. It is intent."
* "One strike is enough — if it is correct."
* "Silence is your greatest weapon."

