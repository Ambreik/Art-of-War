			Varek Duskgrave — Master of the Necrotic Staff

---

	Location : Academy of Combat Arts — Forbidden Arcane Wing (East Side District, Capital City)

---

	Appearance : "Varek Duskgrave" wears long, layered necromantic robes stitched with faded sigils that seem partially erased by time itself. In his grasp is a 
tall, carved staff of darkened wood reinforced with bone-like inlays and a dimly glowing core that pulses like a distant heartbeat.
A heavy, unnatural stillness surrounds him — a "Gravebind Aura", where ambient sound feels slightly muted, as if life itself hesitates nearby.

---

	Personality : Ancient, analytical, and emotionally detached. Speaks slowly with deliberate precision, often treating life and death as academic concepts rather 
than moral ones.

---

	Behavior : 
* Varek never leaves his position inside the academy.
* He stands within a sealed arcane circle engraved into the floor, surrounded by floating fragments of runic bone constructs used for training visualization.
* Players may challenge him to sparring matches. During sparring, Varek perfectly adjusts to the player’s level, equipment, and skill progression to create a 
balanced combat experience.

---

	Role : 
* Class Master for :
	* Necromancer (Zonen) — Staff Specialist

	Varek is a higher authority than common class trainers found in starting zones.
	He does not teach basic skills but explains advanced mechanics, corpse energy manipulation, summon scaling, decay amplification, mana conversion into necrotic 
force, and hidden dark arcane efficiencies.

	He is responsible for unlocking the "Ultimate Skill" of the Necromancer when the time comes.

---

	Mechanics & Functions : 
* Explains every Necromancer skill in depth
* Explains summon behavior and scaling mechanics
* Explains decay damage and life-force conversion systems
* Explains corpse interaction mechanics and necrotic amplification
* Allows sparring practice that scales dynamically to the player
* Unlocks the future "Ultimate Skill"
* Skillable NPC
* No quests
* No vendor window

---

	Interaction : Varek studies players as if evaluating a phenomenon rather than a person.

---

	Quotes : 
* "Death is not an end. It is a resource."
* "All things return to form."
* "You misunderstand decay. It is structure in reverse."
* "Even silence has remains."

