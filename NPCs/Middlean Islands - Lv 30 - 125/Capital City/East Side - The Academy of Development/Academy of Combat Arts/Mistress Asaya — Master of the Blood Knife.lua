			Mistress Asaya — Master of the Blood Knife

---

	Location : Academy of Combat Arts — Shadow Wing (East Side District, Capital City)

---

	Appearance : "Mistress Asaya" stands in dark, fitted leathers layered for silent movement. Twin daggers rest reversed in her grip, their edges faintly 
stained from countless drills. A hood partially veils her face, and only her sharp, watchful eyes are visible.
	A thin, shifting haze surrounds her — a "Veil of Shadows Aura" that makes her presence feel uncertain, as if she is never fully where she appears to be.

---

	Personality : Quiet, precise, observant. Speaks little and wastes no motion.

---

	Behavior : 
* Asaya never leaves her position inside the academy.
* She watches over stealth drills and agility exercises without being noticed.
* Players may challenge her to sparring matches. During sparring, Asaya perfectly adjusts to the player’s level, equipment, and skill progression to create a 
balanced combat experience.

---

	Role : 
* Class Master for:
	* Ninja Assassin (Dendera) — Dagger Specialist

	Asaya is a higher authority than common class trainers found in starting zones.
	She does not teach basic skills but explains advanced mechanics, combo point usage, stealth rotations, and hidden efficiencies of the class.

	She is responsible for unlocking the "Ultimate Skill" of the "Ninja Assassin" when the time comes.

---

	Mechanics & Functions : 
* Explains every Ninja Assassin skill in depth
* Explains Combo Point generation and finishing techniques
* Explains stealth mechanics, timing, and positioning
* Explains hidden mechanics and efficiency tricks
* Allows sparring practice that scales dynamically to the player
* Unlocks the future "Ultimate Skill"
* Skillable NPC
* No quests
* No vendor window

---

	Interaction : When approached, her voice seems to come from slightly behind the player rather than in front.

---

	Quotes : 
* "You were seen."
* "Too slow."
* "Strike before thought."
* "Shadows are your armor."

