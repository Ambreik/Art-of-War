			Master Arvos — Master of the Divine Blade

	Location : Academy of Combat Arts — Solar Wing (East Side District, Capital City)

---

	Appearance : "Master Arvos" wears radiant plate armor forged with clean, angular designs that reflect disciplined craftsmanship rather than ornament. A long
ceremonial sword rests at his side, its blade polished to a mirror-like sheen that reflects light even in dim environments.
	A steady golden pressure radiates from him — a "Divine Radiance Aura", giving the impression of controlled authority rather than aggression, like judgment held 
	in restraint.

---

	Personality : Disciplined, direct, and morally grounded. Speaks with clarity and certainty, avoiding unnecessary words.

---

	Behavior : 
* Master Arvos never leaves his position inside the academy.
* He stands within a structured training hall marked by luminous floor sigils used for combat evaluation drills.
* Players may challenge him to sparring matches. During sparring, Master Arvos perfectly adjusts to the player’s level, equipment, and skill progression to create a
balanced combat experience.

---

	Role : 
* Class Master for :
	* Arahan (Zonen) — Sword Specialist

	Master Arvos is a higher authority than common class trainers found in starting zones.
	He does not teach basic skills but explains advanced mechanics, offensive rotations, stance control, combo optimization, and hidden efficiencies of the class.

	He is responsible for unlocking the "Ultimate Skill" of the Arahan when the time comes.

---

	Mechanics & Functions :
* Explains every Arahan skill in depth
* Explains offensive stance transitions and timing windows
* Explains combo chains and execution flow
* Explains hidden mechanics and efficiency optimization
* Allows sparring practice that scales dynamically to the player
* Unlocks the future "Ultimate Skill"
* Skillable NPC
* No quests
* No vendor window

---

	Interaction : Master Arvos evaluates the player in silence before speaking, as if measuring their intent before their strength.

---

	Quotes : 
* "A blade is purpose made visible."
* "Strike without hesitation. Or do not strike at all."
* "Control your offense, or it will control you."
* "Strength without direction is waste."

