			Trainer Sable — Master of the Nightfall Arrow

---

	Location : Academy of Combat Arts — Eclipse Archery Wing (East Side District, Capital City)

---

	Appearance : "Trainer Sable" wears a dark, lightweight ranger outfit designed for silence, precision, and mobility. Her posture is always aligned with 
calculated discipline, and a finely crafted bow rests in her hand or is loosely held at her side.A quiver of specialized arrows is strapped tightly across her back.
A dim, shadow-like distortion surrounds her — a "Nightwind Aura", making her presence slightly harder to focus on at distance, as if she blends into peripheral vision.

---

	Personality : Reserved, precise, and observant. Speaks only when necessary, with measured intent.

---

	Behavior : 
* Sable never leaves her position inside the academy.
* She oversees long-range precision trials, stealth firing lanes, and moving-target training fields.
* Players may challenge her to sparring matches. During sparring, Sable perfectly adjusts to the player’s level, equipment, and skill progression to create a 
balanced combat experience.

---

	Role : 
* Class Master for :
	* Ranger (Zonen) — Bow Specialist

	Sable is a higher authority than common class trainers found in starting zones.
	She does not teach basic skills but explains advanced mechanics, ranged positioning,stealth archery transitions, shot timing, and hidden precision efficiencies.

	She is responsible for unlocking the "Ultimate Skill" of the Ranger when the time comes.

---

	Mechanics & Functions : 
* Explains every Ranger skill in depth
* Explains ranged positioning and optimal engagement distance
* Explains stealth-shot timing and accuracy mechanics
* Explains projectile behavior and attack chaining optimization
* Allows sparring practice that scales dynamically to the player
* Unlocks the future "Ultimate Skill"
* Skillable NPC
* No quests
* No vendor window

---

	Interaction : Sable studies the player quietly for a moment, as if calculating their effective range before speaking.

---

	Quotes : 
* "Distance is control."
* "You miss because you decide too late."
* "Stillness creates precision."
* "One shot, one outcome."

