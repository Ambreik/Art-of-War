			Barak Ironfist — Master of the Eternal Spear

---

	Location : Academy of Combat Arts — Guardian Wing (East Side District, Capital City)

---

	Appearance : Barak Ironfist is a massive, heavily built warrior clad in reinforced plate armor layered with thick shoulder guards and a long, protective war-
tabard. His tower shield rests against the stone beside him while he holds a long, battle-worn spear upright with unwavering stability.
	A subtle pressure fills the air around him — a "Silent Valor Aura" that feels like standing behind an unbreakable wall.

---

	Personality : Calm, immovable, and resolute. Speaks with grounded certainty.

---

	Behavior : 
* Barak never leaves his position inside the academy.
* He stands firm, observing defensive drills and sparring rings.
* Players may challenge him to sparring matches. During sparring, Barak perfectly adjusts to the player’s level, equipment, and skill progression to create a 
balanced combat experience.

---

	Role : 
* Class Master for :
	* Warrior Defender (Dendera) — Spear Specialist (Tank)

	Barak is a higher authority than common class trainers found in starting zones.
	He does not teach basic skills but explains advanced mechanics, skill interactions, threat control, defensive rotations, and hidden efficiencies of the class.

	He is responsible for unlocking the "Ultimate Skill" of the "Warrior Defender" when the time comes.

---

	Mechanics & Functions : 
* Explains every Warrior Defender skill in depth
* Explains threat generation, defensive rotations, and positioning
* Explains hidden mechanics and efficiency tricks
* Allows sparring practice that scales dynamically to the player
* Unlocks the future "Ultimate Skill"
* Skillable NPC
* No quests
* No vendor window

---

	Interaction : When approached, Barak acknowledges the player with a firm nod, never lowering his spear.

---

	Quotes : 

* "A true warrior protects before he strikes."
* "Stand your ground."
* "Endure."
* "You are the wall."

