			Training Dummy — Combat Analysis Construct
			
---

	Location : Academy of Combat Arts — All Training Wings (East Side District, Capital City)

---

	Appearance : "The Training Dummy" is a reinforced humanoid construct made from layered wood, iron fittings, and rune-stabilized cores. Its body is segmented 
with visible durability plates and arcane calibration nodes that pulse faintly when struck. Some variants are stationary humanoid figures, while others are 
reinforced elite models with rotating armor plates for advanced testing.
	A faint "Arcane Stabilization Aura" surrounds each dummy, preventing destruction while recording all combat interactions.

---

	Personality : None.

---

	Behavior : 
* "Training Dummies" remain completely stationary and non-hostile at all times.
* They do not react, move, or engage in combat. Instead, they function as passive combat evaluation targets for training purposes across all academy wings.

---

	Role : 
* Combat Training Construct
* Training Dummies are used for :
	* Skill testing and rotation practice
	* Damage evaluation and scaling assessment
	* Combo timing refinement
	* Class mechanic experimentation
	* Movement and positioning drills

	They are distributed throughout the "Academy of Combat Arts", with specialized versions depending on the training wing (melee, ranged, magic, stealth, etc.).

---

	Mechanics & Functions : 

	Inspired by structured combat systems similar to MMO training environments, with expanded academy-specific features :

	1. Core Mechanics

* "Damage Log Recording" — Tracks all incoming damage in real time
* "DPS/HPS Meter Output" — Displays combat performance summary after interaction ends
* "Combo Tracking System" — Records skill chains and execution efficiency
* "Crit & Proc Analysis" — Shows critical hit rates and triggered effects
* "Skill Rotation Memory" — Evaluates repeated skill usage patterns

	2. Advanced Academy Mechanics

* "Class Simulation Mode" — Dummy adjusts resistance profile based on selected class training wing
* "Burst Window Analysis" — Measures player performance during high-damage phases
* "Sustain Evaluation Mode" — Tracks long-duration combat efficiency
* "Movement Penalty Mode (Optional Variant)" — Rewards or penalizes stationary vs mobile combat styles
* "Target Uptime Tracking" — Measures how effectively players maintain engagement
* "Interrupt & Timing Feedback System" — Logs interrupted casts and delayed executions

	3. Special Systems (Custom to your world)

* "Adaptive Resistance Core" — Allows toggling physical/magical resistance balance
* "Weapon Type Response Mode" — Adjusts feedback based on weapon class (sword, bow, staff, etc.)
* "Skill Discovery Logging" — Detects unknown skill combinations for future system expansion
* "Ultimate Skill Test Flag (Locked)" — Future compatibility for testing Ultimate Skills safely

---

	Interaction : 
* "Training Dummies" do not interact verbally or physically.
* They respond only through system feedback outputs, combat logs, and visual UI indicators tied to academy training systems.

