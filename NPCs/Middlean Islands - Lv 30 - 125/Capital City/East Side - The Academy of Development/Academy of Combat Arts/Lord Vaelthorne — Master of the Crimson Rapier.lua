			Lord Vaelthorne — Master of the Crimson Rapier

---

	Location : Academy of Combat Arts — Crimson Wing (East Side District, Capital City)

---

	Appearance : "Lord Vaelthorne" stands as an elegant yet unsettling figure, dressed in a long aristocratic coat layered over ceremonial armor etched with faint, 
blood-like silver engravings. A finely crafted rapier rests lightly in his hand, its blade unnaturally pristine yet faintly glowing with a deep crimson hue.
	A slow, pulsing aura surrounds him — a "Crimson Dominion Aura", evoking both nobility and ancient predation, as if the air itself remembers old bloodlines.

---

	Personality : Calm, aristocratic, and ancient in presence. Speaks with refined precision and quiet authority, often implying knowledge far older than the 
academy itself.

---

	Behavior : 
* Vaelthorne never leaves his position inside the academy.
* He stands within a dimly lit hall lined with reflective obsidian pillars that mirror distorted reflections of those who enter.
* Players may challenge him to sparring matches. During sparring, Vaelthorne perfectly adjusts to the player’s level, equipment, and skill progression to create a 
balanced combat experience.

---

	Role : 
* Class Master for :
	* Vampire (Dendera) — Rapier Specialist

	Vaelthorne is a higher authority than common class trainers found in starting zones.
	He does not teach basic skills but explains advanced mechanics,blood energy manipulation, life-steal interactions, combo flow, and hidden vampiric efficiencies.

	He is responsible for unlocking the "Ultimate Skill" of the Vampire class when the time comes.

---

	Mechanics & Functions : 
* Explains every Vampire skill in depth
* Explains Blood Orb generation and consumption mechanics
* Explains life-steal scaling and sustain combat systems
* Explains combo flow, timing, and execution optimization
* Explains hidden vampiric mechanics and advanced interactions
* Allows sparring practice that scales dynamically to the player
* Unlocks the future "Ultimate Skill"
* Skillable NPC
* No quests
* No vendor window

---

	Interaction : Vaelthorne observes the player silently for a few seconds before speaking, as if assessing their “value” rather than their strength.

---

	Quotes : 
* "Blood is not taken. It is negotiated."
* "You are not alive… you are enduring."
* "Refinement is survival made elegant."
* "Every heartbeat is a borrowed debt."

