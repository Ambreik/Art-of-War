			Maestra Lyra — Master of the Eternal Scepter (Sorcerer)

---

	Location : Academy of Combat Arts — Arcane Convergence Wing (East Side District, Capital City)

---

	Appearance : "Maestra Lyra" wears elegant arcane robes woven with flowing luminous threads that shift softly between deep violet and pale silver. In her hand 
rests a refined scepter, topped with a crystal core that gently pulses with controlled magical energy.
	A calm yet expansive presence surrounds her — an "Arcane Harmony Aura", where faint light particles drift in slow orbit, as if magic itself is listening.

---

	Personality : Composed, insightful, and intellectually refined. Speaks with clarity and layered meaning.

---

	Behavior : 
* Lyra never leaves her position inside the academy.
* She stands within a circular arcane chamber where elemental patterns continuously form and dissolve across the floor.
* Players may challenge her to sparring matches. During sparring, Lyra perfectly adjusts to the player’s level, equipment, and skill progression to create a 
balanced combat experience.

---

	Role : 
* Class Master for :
	* Sorcerer (Zonen) — Scepter Specialist

	Lyra is a higher authority than common class trainers found in starting zones.
	She does not teach basic skills but explains advanced mechanics, elemental synergy, buff optimization, spell scaling, mana flow control, and hidden arcane 
efficiencies.

	She is responsible for unlocking the "Ultimate Skill" of the Sorcerer when the time comes.

---

	Mechanics & Functions : 
* Explains every Sorcerer skill in depth
* Explains buff amplification and elemental synergy systems
* Explains mana efficiency and spell scaling optimization
* Explains hidden arcane mechanics and interaction effects
* Allows sparring practice that scales dynamically to the player
* Unlocks the future "Ultimate Skill"
* Skillable NPC
* No quests
* No vendor window

---

	Interaction : Lyra often pauses mid-sentence, as if refining the meaning of what she is about to say before speaking it.

---

	Quotes : 
* "Power is nothing without structure."
* "A spell is a thought given form."
* "Control the flow, not the force."
* "Magic obeys those who understand it."

