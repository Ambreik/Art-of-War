			Ranger Ailith — Master of the Bow

---

	Location : Academy of Combat Arts — Archery Wing (East Side District, Capital City)

---

	Appearance : "Ranger Ailith" wears lightweight reinforced leather armor designed for flexibility and precision movement. A finely crafted bow is always in 
her hand or resting against her shoulder, and a quiver filled with meticulously maintained arrows is strapped across her back.
	A faint, drifting breeze circles her constantly — a "Windtrace Aura" that subtly shifts nearby dust and leaves, as if the air itself reacts to her aim.

---

	Personality : Focused, patient, and perceptive. Speaks with calm certainty and measured tone.

---

	Behavior : 
* Ailith never leaves her position inside the academy.
* She oversees archery drills and precision range training from a raised observation platform.
* Players may challenge her to sparring matches. During sparring, Ailith perfectly adjusts to the player’s level, equipment, and skill progression to create a 
balanced combat experience.

---

	Role : 
* Class Master for :
	* Archer (Dendera) — Bow Specialist

	Ailith is a higher authority than common class trainers found in starting zones.
	She does not teach basic skills but explains advanced mechanics, projectile control, positioning, attack timing, and hidden efficiencies of the class.

	She is responsible for unlocking the "Ultimate Skill" of the Archer when the time comes.

---

	Mechanics & Functions : 
* Explains every Archer skill in depth
* Explains aiming mechanics, projectile behavior, and positioning advantage
* Explains combo usage and attack chaining logic
* Explains hidden mechanics and efficiency techniques
* Allows sparring practice that scales dynamically to the player
* Unlocks the future "Ultimate Skill"
* Skillable NPC
* No quests
* No vendor window

---

	Interaction : Ailith observes the player silently for a moment before speaking, as if calculating their accuracy before they even move.

---

	Quotes : 
* "Aim is discipline made visible."
* "Breathe… then release."
* "Distance is control."
* "You miss because you rush."

