			Seer Kalista — Master of the Essence of Life

---

	Location : Academy of Combat Arts — Sanctuary Wing (East Side District, Capital City)

---

	Appearance : "Seer Kalista" wears flowing ceremonial robes woven with soft luminous threads that subtly shift between pale green and warm gold. She carries an 
elegant fan, crafted from lightwood and engraved with healing sigils. Her presence is gentle, and the air around her feels lighter, as if tension itself is reduced 
nearby.
	A calm, restorative glow surrounds her — a "Life Resonance Aura" that softly pulses like a heartbeat.

---

	Personality : Gentle, patient, and deeply empathetic. Speaks with warmth and emotional clarity.

---

	Behavior : 
* Kalista never leaves her position inside the academy.
* She remains seated near the center of a serene healing chamber, observing restorative training and support practice.
* Players may challenge her to sparring matches. During sparring, Kalista perfectly adjusts to the player’s level, equipment, and skill progression to create a 
balanced combat experience.

---

	Role : 
* Class Master for :
	* Healer (Dendera) — Fan Specialist

	Kalista is a higher authority than common class trainers found in starting zones.
	She does not teach basic skills but explains advanced mechanics, healing optimization, buff synergy, mana efficiency, and hidden support interactions.

	She is responsible for unlocking the "Ultimate Skill" of the Healer when the time comes.

---

	Mechanics & Functions : 
* Explains every Healer skill in depth
* Explains healing scaling, buff stacking, and support timing
* Explains mana efficiency and sustain mechanics
* Explains hidden support interactions and synergy effects
* Allows sparring practice that scales dynamically to the player
* Unlocks the future "Ultimate Skill"
* Skillable NPC
* No quests
* No vendor window

---

	Interaction : Kalista greets players softly, often noticing their emotional state before their combat stance.

---

	Quotes : 
* "To heal is to understand pain."
* "Your strength begins where your wounds end."
* "Do not rush recovery. Guide it."
* "Life flows where intent is pure."

