			Hiel Mall

* 1v1 Arena Referee — Master of Heroes’ Ascent
* Arena of Valor, East Side District — The Academy of Development*

---

		Overview

	"Hiel Mall" is the official referee and overseer of "Heroes’ Ascent", the structured 1v1 PvP dueling system hosted inside the "Arena of Valor". Where team 
coordination defines the "Grand Skirmish", personal mastery defines "Heroes’ Ascent" — and "Hiel" is the quiet authority who ensures every duel is honorable, 
recorded, and remembered.

	To newcomers, he appears calm and formal.
	To veterans, he is the keeper of their dueling legacy.

	He does not encourage spectacle.
	He encourages precision.

---

		Physical Appearance

	Hiel is a lean, middle-aged man with sharp features and composed posture. He wears refined, dark duelist attire rather than armor, marked subtly with the 
insignia of the "Capital City Civic Authority". A thin ceremonial blade rests at his side — never drawn, purely symbolic of his role.
	His eyes are observant and analytical, constantly studying stance, posture, and discipline in those around him.
	He looks like a man who has seen thousands of duels and forgotten none.

---

	Personality : 
* Calm, disciplined, and formal in speech
* Values precision, honor, and technical skill over aggression
* Speaks little, but every word carries weight
* Has deep respect for dedicated duelists
* Dislikes loud, reckless fighters who mistake chaos for skill

	Hiel rarely raises his voice. Silence around him tends to grow naturally.

---

		Backstory

	"Hiel Mall" was once a renowned duelist in his youth, traveling across regions to challenge masters of various combat styles. His reputation was not built on 
strength alone, but on his ability to read opponents and win with minimal motion.
	After retiring from active dueling, he was invited by the "Capital City" authorities to establish and oversee a formal dueling system that would preserve honor 
while allowing competition to thrive safely within the city.

	Thus, "Heroes’ Ascent" was born.

---

		Role in the Arena of Valor

	Hiel Mall is responsible for :
* Registering players into "Heroes’ Ascent" (1v1 PvP) duels
* Monitoring duel integrity and rule enforcement
* Tracking insignia points, ranks, and seasonal standings
* Overseeing leaderboard displays
* Validating duel rewards and titles
* Maintaining the ceremonial dignity of dueling combat

	He is the guardian of personal combat prestige.

---

		Systems Integration

	Hiel is directly linked to :
* "Heroes’ Ascent PvP System (1v1 dueling)
* "Citizen Standing Recognition System" — recognizes renowned duelists
* "Controlled PvP Law System" — ensures duels occur only within official framework
* "Capital Life & Activity System" (CLAS) — follows arena activity cycles
* "Crowd Flow & Density System" — duels attract quiet spectators
* "Whisper Network System" — rumors of legendary duelists spread through the city

---

	Daily Routine (CLAS Behavior)

* Arrives mid-morning when duelists begin to gather
* Most active during afternoon and evening hours
* Observes duels silently when matches are in progress
* During low activity, studies rankings and speaks quietly with veteran fighters

	When the arena becomes crowded, Hiel’s presence becomes more reserved, allowing players to approach him directly rather than calling attention to himself.

---

		Player Interaction

	Players approach Hiel to :
* Enter the 1v1 Heroes’ Ascent queue
* Check personal duel rank and insignia
* View the dueling leaderboard
* Claim duel rewards and titles

	Example Dialogue

* Greeting : "The path of ascent is walked alone. Are you prepared?"

* Advice : "A duel is won before the first strike — in the stance, in the breath, in the mind."

* When players act recklessly : "This is not a tavern brawl. Compose yourself."

---

		Quests & Rewards

	Hiel offers PvP progression objectives such as :
* Participate in multiple duels per day
* Win duels without taking excessive damage
* Reach seasonal insignia thresholds

	Rewards include :
* Heroes’ Ascent Insignia Points
* Duelist Titles
* Unique cosmetics and prestige items

---

	Relationships : 
* Professional rivalry with "Rypere Phil" over which PvP format demands more skill
* Deep respect for "Grandmaster Heklan Vaross"
* Known quietly among top duelists as the man whose recognition truly matters

---

		World Presence

	Hiel Mall gives the Arena a sense of discipline and tradition. Through him, dueling is not chaotic combat — it is a respected practice with legacy, records, and
honor.
	He makes "Heroes’ Ascent" feel like a path of personal mastery rather than simple PvP.

