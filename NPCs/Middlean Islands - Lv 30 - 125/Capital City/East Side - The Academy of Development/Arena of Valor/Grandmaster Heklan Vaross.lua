			Grandmaster Heklan Vaross

	Location : Middlean Islands / Capital City / East Side District / The Academy of Development / Arena of Valor / Hall of Heroes Chamber

---

	Appearance : "Grandmaster Heklan Vaross" is an aging warrior whose presence alone commands silence within the Hall. His tall, broad frame is still imposing 
despite the years etched into his face. Deep scars trace across his jawline and left brow — marks of battles long past, never hidden, never healed by magic. He 
wears ceremonial grandmaster armor forged from dark steel and gold trims, polished to a mirror sheen yet clearly ancient in design. A long crimson mantle falls from
his shoulders, bearing the faded insignias of forgotten champions.
	His grey hair is tied back in a tight warrior’s knot, and his beard is short but thick, streaked with white. His eyes are sharp, observant, and unsettlingly 
calm, scanning every player as if judging their worth without a single word spoken. Behind him stand towering statues of past champions, and before him lies an 
empty circular dueling platform — untouched, waiting.
	He does not lean, sit, or relax. He stands perfectly upright at all times, hands resting over the pommel of a massive sheathed greatsword that has clearly seen 
more war than ceremony.

---

	Personality : "Heklan Vaross" is a man of very few words. He does not greet players warmly, nor does he dismiss them rudely. His tone is calm, heavy, and
deliberate, as if every word carries the weight of history. He speaks like a judge, not a guide. Like a man who has seen thousands of warriors rise with pride and 
fall with arrogance.
	He respects strength, discipline, and proof — not claims. Players who approach him feel as though they are being evaluated silently before any interaction even 
begins. There is no hostility in him, but no friendliness either. Only expectation.
	He believes that true warriors are remembered not by their boasts, but by the battles they survive and the honor they carry.

---

	Behaviour : Heklan Vaross never moves from his position. He does not patrol, emote, or react to nearby noise. He remains perfectly still, observing. When 
players approach, he slowly turns his head toward them before any dialogue begins, creating the feeling that the player has been noticed long before speaking.
	He cannot be distracted, provoked, or interrupted.

---

	Role :

* Role(s) : PvP Authority, Tournament Master, Historical Record Keeper

	"Grandmaster Heklan Vaross" is the living authority of organized PvP combat and the gatekeeper of the future "Hall of Heroes" tournament. He evaluates players 
based on their achievements in other PvP systems and will, in the future, serve as the registrar and overseer of the most prestigious PvP competition in the world.
	He does not allow players to join freely — he determines who is worthy.

---

	Mechanics :

* Type : PvP System NPC, Eligibility Evaluator, Tournament Registrar (future)
* Reputation : Grants and checks PvP Reputation tied to Heroes’ Ascent, Grand Skirmish, and future Hall of Heroes standings
* Interaction Limitations : Only players with recorded participation in PvP systems can access full dialogue options
* PvP : Cannot be attacked, not flagged for PvP, immune to all player actions
* Respawn Time : Instant (cannot be killed)
* Other Mechanics :
	* Checks player PvP history across systems
	* Flags players as "Eligible" or "Unworthy" for "Hall of Heroes" 
	* Displays records of past champions and legendary fights
	* Will serve as tournament entry point once Hall of Heroes is implemented

