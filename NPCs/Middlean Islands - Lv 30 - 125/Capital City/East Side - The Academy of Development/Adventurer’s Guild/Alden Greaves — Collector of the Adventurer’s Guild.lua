			Alden Greaves — Collector of the Adventurer’s Guild

	*(Bounty Intelligence & Target Registry Officer)*

---

	Location : Adventurer’s Guild — Intelligence Archive Desk (East Side District, Capital City)

---

		Appearance

	Alden Greaves sits at a wide, map-covered intelligence desk surrounded by layered stacks of parchment reports, marked contracts, and pinned regional charts. The
desk surface itself is partially embedded with a world-mapping stone board, where glowing markers indicate active bounty targets across regions.

	He wears a long dark investigator’s coat reinforced with light travel leather, designed for field mobility despite his primarily stationary role. Round glasses 
rest on his nose, reflecting shifting map overlays and tracking symbols when the system updates live data.

	A faint "Tracking Resonance Aura" surrounds him — subtle spatial distortions appear briefly when new bounty intelligence is registered or updated.

---

	Personality : Calm, analytical, and deeply detail-oriented. Alden speaks rarely, but when he does, every word is precise and data-driven. He views the world as 
a living dataset of movements, threats, and patterns.

---

	Behavior : 
* Alden remains permanently stationed at his intelligence desk.
* He is not a quest giver and does not interact emotionally with players.
* Instead, he functions as a live intelligence operator, continuously updating and maintaining the global bounty ecosystem.

	He reacts primarily to system triggers rather than direct dialogue.

---

		Role — BOUNTY INTELLIGENCE SYSTEM CORE

	Alden Greaves is the primary data input engine for the "Bounty Hunter System".
	He is responsible for maintaining the "Outlaw Registry and World Target Tracking Network", feeding critical intelligence into the guild system.

---

		Core Functions

	1. Target Registry Management
* Records all bounty-eligible entities :
	* Players (outlaw flagged)
	* Monsters
	* Elite entities
	* Boss-level threats
* Assigns and updates target identifiers in real time

---

	2. World Target Tracking System : 
* Maintains live positional intelligence (region-based tracking)
* Updates movement patterns of high-value targets
* Logs last known sightings and engagement reports
* Works with scout and field intelligence feeds

---

	3. Bounty Intelligence Layer
* Classifies targets into risk tiers :
	* Low Risk
	* Standard Threat
	* High Value Target
	* Extreme Threat (Regional Boss Level)
* Adjusts bounty visibility based on system escalation rules

---

	4. System Synchronization : 
* Feeds validated intelligence directly to :
	* Elara Ironhand (for reward execution)
	* Bounty Hunter System Core (for contract lifecycle updates)
* Maintains consistency between :
	* Active contracts
	* Completed hunts
	* Failed / expired bounties

---

	Mechanics & Functions : 
* Real-time bounty registry updates
* Target lifecycle tracking (spawn → active → hunted → resolved)
* Regional threat mapping system
* Outlaw identification & classification
* Intel validation from scout reports
* Dynamic bounty escalation triggers

❌ No combat interaction
❌ No quest giving
❌ No rewards handling
✔ Pure intelligence system operator

---

		System Integration Role

	Alden is a live feed node inside the Bounty Hunter System architecture :
* Inputs: Scout reports, player activity, monster movements
* Processes: Threat classification + registry updates
* Outputs: Verified target data for Elara Ironhand

	He is effectively the "eyes of the system", while Elara is the execution layer.

---

	Quotes : 
* "Data does not lie. Only interpretation does."
* "A target is never lost. Only unobserved."
* "Every movement leaves a trace — I simply connect them."
* "The system updates… and so does your problem."

