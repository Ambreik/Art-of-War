			Guild Gatekeeper — "Varric Threshold"

	*(Entry Sentinel of the Adventurer’s Guild)*

	Location : Adventurer’s Guild — Main Entrance Gate (East Side District, Capital City)

---

		Appearance

	"Varric Threshold" stands motionless at the massive arched entrance of the Adventurer’s Guild, framed by iron-bound stone doors engraved with the crossed-swords
insignia of the "Bounty Hunters".
	He wears heavy ceremonial guard armor reinforced with layered steel plates and reinforced chain sections, designed more for authority presence than combat 
mobility. His helmet is partially open-faced, revealing a calm, unreadable expression.

	A faint "Boundary Seal Aura" flows around the entrance behind him — a subtle spatial distortion that reacts when unauthorized individuals approach.

---

	Personality : 
* Minimalist, detached, and procedural in expression.
* Varric does not judge people — he evaluates conditions.
* He speaks only when system conditions require it.

---

	Behavior : 
* Varric remains permanently stationed at the guild entrance.
* He does not move, patrol, or engage in conversation beyond system-triggered interaction.
* His sole function is access regulation to the "Adventurer’s Guild" internal systems, especially the bounty interface zones.

---

		Role — ACCESS CONTROL SENTINEL

	Varric Threshold is the entry enforcement layer of the "Bounty Hunter System" ecosystem.
	He ensures that only eligible individuals can access internal guild functions.

---

	Core Functions

	1. Entry Validation System : 
* Verifies player eligibility as a "Bounty Hunter"
* Blocks unauthorized access to :
	* Bounty board interface zones
	* Contract registry systems
	* Intelligence archive sections

---

	2. Faction Restriction Enforcement : 
* Enforces "Bounty Hunters Only" access rule
* Prevents cross-system exploitation from non-qualified classes or factions
* Maintains structural separation between :
	* Civil adventurers
	* Guild bounty hunters
	* External factions

---

	3. Security Boundary System : 
* Maintains an invisible "access threshold field" at guild entrance
* Detects system flags tied to bounty participation
* Triggers denial or allowance states based on system rules

---

	Mechanics & Functions : 
* Entry permission validation
* System access gating for bounty UI zones
* Passive restriction enforcement
* Non-combat security presence
* Faction-based access filtering

