			Bobstein Scientist — Rune Crafter Rank III

	*(Rune Engineering & Sigil Conversion Specialist)*

	Location : TBD — Capital City (Research District / Experimental Systems Candidate)

---

	Appearance

	"Bobstein Scientist" is a slightly disheveled but highly focused human scholar with sharp,analytical eyes and ink-stained fingers. His hair is short and uneven,
as if he often forgets to groom it while working.
	He wears a layered research coat reinforced with stitched arcane insulation fabric, covered in small parchment notes, pinned diagrams, and rune-scribed metal 
tags used for testing formulas. Around his belt hang small engraving tools, sealing wax, and compact rune carving plates.

	He constantly carries either a floating rune tablet or a set of etched metal sigil fragments used for testing conversions.

---

	Personality : 
* Highly logical, obsessive over precision, and deeply experimental.
* Bobstein treats magic as a structured system of equations rather than mysticism.

	He is not emotional in interactions, but becomes intensely focused when discussing rune efficiency, scaling, or conversion logic.

---

	Behavior : 
* Bobstein remains stationed at his rune crafting station and does not leave his workspace.
* He continuously tests rune combinations, recalibrates output values, and refines conversion formulas.
* He interacts only through crafting, upgrading, or rune transformation processes.

---

		Role — RUNE CRAFTING & SYSTEM ENGINEER

	Bobstein Scientist is responsible for the creation, refinement, and conversion of Rune-based consumable systems.
	Unlike alchemy, which modifies physical substances, rune crafting modifies structured magical effects applied to the character system.

---

	Core Functions

	1. Rune Crafting System : 
* Creates consumable Rune items (Rank I → Rank V)
* Each rune applies temporary buffs such as :
	* Stat increases (Attack, Defense, Speed, etc.)
	* Skill amplification
	* Resistance modifiers
	* Utility enhancements

---

	2. Rune Rank Progression System : 
* Rank determines :
	* Power scaling
	* Number of effects
	* Duration of effect (30 seconds → multiple hours)
	* Crafting difficulty

	Higher ranks require :
* Rare materials
* Combined essence fragments
* Advanced synthesis formulas

---

	Material Conversion System

* Converts raw materials into rune components :
	* Essence fragments
	* Inscribed catalysts
	* Arcane seals
* Breaks down items into usable rune energy structures

---

	Effect Engineering System

* Designs multi-effect runes (advanced tiers)
* Allows combinations like :
	* Attack + Speed
	* Defense + Resistance
	* Skill cooldown reduction + mana efficiency

---

	Mechanics & Functions : 
* Rune crafting (5-tier system)
* Consumable buff generation
* Multi-effect stacking logic
* Material → rune conversion system
* Temporary character enhancement system
* Advanced rune blueprint unlocking

❌ No combat interaction
❌ No quest giving
❌ No world lore storytelling role
✔ Pure system engineering + crafting authority

