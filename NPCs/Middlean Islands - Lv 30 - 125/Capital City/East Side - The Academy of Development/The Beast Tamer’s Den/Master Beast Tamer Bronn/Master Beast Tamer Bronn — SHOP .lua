			Special Vendor Mechanics

		Trust Rank Unlocks

	Bronn unlocks additional inventory depending on player affinity and beast mastery progression.

	Rank I — Wanderer
* Access to common food and care items.

	Rank II — Beast Handler
* Unlocks advanced feed and basic enhancement gear.

	Rank III — Beast Keeper
* Unlocks rare traps, advanced saddles, and pet accessories.

	Rank IV — Wildspeaker
* Unlocks epic taming items and advanced bonding equipment.

	Rank V — Legendary Tamer
* Unlocks legendary reagents, rare mount rituals, and hidden creature research items.

