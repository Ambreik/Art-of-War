			Master Beast Tamer Bronn

---

	Location : Outland Territories / Human Settlements / The Beast Tamer’s Den

---

		Appearance :

	Bronn is an older, battle-worn beast handler whose presence immediately commands respect. Tall and broad-shouldered, he carries the posture of a man who has 
spent decades beside dangerous creatures rather than behind city walls. His weathered skin bears scars from claws, bites, and ancient encounters, with a 
particularly deep mark running across his left shoulder — rumored to have come from a legendary beast no hunter survived except him.

	He wears layered earth-toned leathers reinforced with thick hide plating, mixed with ceremonial beast pelts symbolizing mastery over multiple creature 
bloodlines. Around his waist hang numerous tools of his trade: carved whistles, feeding pouches, herbal medicine satchels, taming ropes, grooming brushes, and small
bone charms used in beast rituals.

	Bronn’s eyes possess a faint amber glow when examining injured or unstable creatures, giving him an almost spiritual aura. His hair is dark gray, tied behind 
his back with leather cords decorated with feathers and small carved fangs collected during his travels.

	Unlike soldiers or mercenaries, Bronn carries no visible weapon besides a long beast-carved wooden staff engraved with ancient symbols from the 
"First Beastbinders". The staff doubles as a walking aid, calming tool, and ritual focus during creature healing ceremonies.

	His section of the Den is always surrounded by animals resting peacefully near him — even aggressive beasts appear unnaturally calm in his presence.

---

		Personality :

	Bronn is calm, disciplined, observant, and deeply empathetic toward all creatures. He speaks slowly and carefully, often pausing to observe both the player and
their companion before responding. While approachable, he carries an intimidating sense of authority earned through decades of experience handling creatures few 
dare approach.
	Unlike ordinary trainers, Bronn values emotional bonds above raw power. He strongly believes that mounts and pets are living companions rather than tools, and 
much of his dialogue reflects this philosophy.
	Toward respectful players, Bronn behaves warmly and offers guidance, lore, or subtle approval. Players who regularly care for their companions may unlock unique
dialogue, discounts, or personal recognition from him.
	However, Bronn quietly disapproves of cruelty, neglect, or reckless treatment of creatures. Players who repeatedly allow mounts or pets to die, neglect stable 
fees, or mistreat animals may receive colder dialogue, increased service costs, or temporary refusal of advanced services.
	Despite his stern reputation, Bronn possesses a hidden fascination with rare species, ancient bloodlines, and corrupted creatures. When discussing legendary 
beasts, his otherwise controlled demeanor briefly shifts into visible curiosity and reverence.

---

		Behaviour :

	Bronn is one of the most dynamically reactive NPCs within the Beast Tamer’s Den.

	He constantly moves throughout the Den performing small tasks :
* feeding mounts
* examining injured pets
* brushing creature fur
* recording notes into research journals
* preparing herbal mixtures
* calming frightened beasts through whistles or chants

	During storms or dangerous world events, Bronn personally secures the stables, closes gates, and moves vulnerable creatures indoors.

	If combat erupts nearby, Bronn immediately prioritizes protecting animals rather than defending himself. Nearby mounts or pets may even gather defensively 
around him during scripted events.

	Bronn reacts emotionally to player behavior :
* approving players who maintain strong creature bonds
* expressing concern for injured companions
* scolding neglectful players
* showing admiration toward rare creatures
* displaying curiosity toward unknown species

	Players with high affinity may occasionally witness hidden interactions :
* Bronn treating legendary creatures
* secret feeding rituals
* conversations about extinct species
* research experiments involving corrupted beasts

