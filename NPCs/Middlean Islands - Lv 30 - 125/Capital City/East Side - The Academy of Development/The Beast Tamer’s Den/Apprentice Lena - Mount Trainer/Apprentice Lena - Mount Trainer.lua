			Apprentice Lena

--- 
	Location : "Outland Territories / Capital City / The Beast Tamer’s Den"

---

		Appearance :

	"Apprentice Lena" is a young woman in her early twenties with sun-touched skin, bright amber eyes, and long chestnut hair usually tied into a practical braid to
keep it out of her face while working around mounts. Her attire reflects years spent traveling alongside caravans and herders — rugged leather boots, reinforced 
riding trousers, and a sleeveless weather-worn vest layered over a linen tunic.
	Around her waist hangs a heavily used utility belt filled with taming tools, rope coils, whistles, feeding pouches, and small herbal satchels used to calm 
frightened or aggressive mounts. Her leather gloves are scratched and worn from years of handling reins and wild creatures.

	Lena often smells faintly of hay, herbs, and stable dust. Unlike veteran tamers, her gear lacks ornamental prestige, but every piece shows careful maintenance 
and practical experience.

	One of her most recognizable features is the small carved wooden charm hanging from her belt — a keepsake from her family’s old herding caravan.

	When idle, she is frequently seen :
* Brushing young mounts
* Organizing tack equipment
* Preparing feed mixtures
* Practicing whistle commands
* Taking notes about mount behavior

Her posture is energetic and constantly active, rarely standing still for long.

---

		Personality :

	Lena is enthusiastic, approachable, and endlessly curious about mounts and creature behavior. Unlike the more stoic and reserved Bronn, she openly expresses 
excitement when discussing rare beasts, riding techniques, or mount training methods.
	She treats players warmly regardless of status and speaks with genuine passion whenever mounts are involved. Though inexperienced compared to senior tamers, she
compensates with determination and eagerness to learn.

	Lena tends to :
* Speak quickly when excited
* Over-explain mount facts
* Offer unsolicited riding advice
* Become fascinated by unusual creatures
* Admire players with rare or well-trained mounts

	She is especially fond of travelers, scouts, racers, and wilderness adventurers, often asking them about distant regions and the creatures they encountered 
there.
	Despite her cheerful demeanor, Lena becomes serious when discussing mount neglect or reckless treatment of animals.

---

		Behaviour :

	Lena constantly moves throughout the stable grounds, helping maintain order among mounts and assisting Bronn with daily operations.

	Specific behaviors include :
* Approaching nervous mounts calmly
* Carrying water buckets or feed sacks
* Inspecting saddles and reins
* Demonstrating riding posture to novice players
* Using whistles to guide nearby animals
* Kneeling beside injured creatures to apply herbs

	When players summon exotic or rare mounts nearby, Lena may temporarily interrupt her routine to observe them more closely.	
	During mount races or mounted competitions, she often watches enthusiastically from stable fences or arena edges, commenting excitedly on rider technique and 
mount endurance.

	If players mistreat mounts nearby :
* Lena visibly disapproves
* Crosses her arms
* Shakes her head
* Delivers stern but calm warnings

	Unlike Bronn, she reacts emotionally and immediately rather than with quiet restraint.

---

		Role :

* Role(s) :
	* Mount Specialist, Stable Assistant, Creature Handling Advisor, Mount Racing Enthusiast

	Lena assists players by offering guidance related to :
* Mount taming
* Wild mount behavior
* Mount care
* Riding techniques
* Racing preparation
* Creature temperament
* Environmental mount survival

	She acts primarily as an informational and immersive NPC, reinforcing the world’s mount systems through dialogue, environmental interaction, and atmosphere.
	Lena also helps introduce newer players to mount mechanics organically through conversations and contextual hints.

