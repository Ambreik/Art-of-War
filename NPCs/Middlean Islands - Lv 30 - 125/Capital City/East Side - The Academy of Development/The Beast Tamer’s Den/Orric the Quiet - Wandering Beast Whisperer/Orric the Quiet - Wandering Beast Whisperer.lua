		Appearance :

	"Orric the Quiet" is an aging wanderer whose appearance blurs the line between hermit, tracker, and mystic. His face is weathered by years spent traveling 
through untamed wilderness, marked with faint scars, wind-burned skin, and pale gray eyes that seem unusually attentive to distant sounds.
	He wears layered travel garments stitched from animal hides, faded cloth, and weatherproof leather gathered from many regions of the world. His long dark cloak 
is decorated with feathers, carved bone charms, tiny bells, and braided cords representing creatures he has encountered throughout his journeys.

	Across his back hangs a crooked wooden staff wrapped in vines and beast talismans, while small pouches filled with herbs, bait powders, and tracking dust line 
his belt. Several tiny spirit charms sway gently whenever he walks, emitting faint whispers during strong winds.

	Most notably, animals rarely fear him.

	Wild creatures often :
* Rest nearby peacefully
* Follow him briefly
* Watch him from treelines
* Gather near his campfires
* Remain calm in his presence

	When encountered at night, faint glowing motes sometimes drift around him, especially near regions associated with spirit beasts or ancient wildlife.

	Orric’s camps are temporary and minimal :
* Small fire pits
* Hanging charms
* Animal tracks surrounding the area
* Strange carved symbols
* Feeding bowls left for unseen creatures

	His appearance subtly changes depending on the biome in which he spawns :
* Snow regions → fur-lined cloak
* Jungle regions → feathered tribal wrappings
* Desert regions → dust-covered scarves and bone ornaments
* Corrupted zones → dim spirit lanterns and protective runes

---

		Personality :

	Orric is calm, cryptic, and deeply connected to the natural world. He speaks slowly and softly, often pausing before answering questions as if listening to 
sounds others cannot hear.
	Unlike scholars or trainers who study creatures academically, Orric treats beasts as ancient equals deserving respect rather than ownership.
	He avoids crowded settlements and grows visibly uncomfortable around excessive noise, machinery, or reckless violence.

	His personality traits include :
* Wise
* Elusive
* Patient
* Observant
* Spiritual
* Melancholic
* Compassionate toward creatures

	Orric rarely speaks directly. Instead :
* He gives hints
* Uses metaphors
* References old folklore
* Speaks through stories and observations

	Players often leave conversations unsure whether he revealed a secret or simply told a strange tale.

	Despite his mysterious nature, Orric becomes noticeably warmer toward players who :
* Protect wildlife
* Care for companions properly
* Discover hidden creatures peacefully
* Avoid unnecessary slaughter

	He strongly dislikes :
* Trophy hunters
* Creature cruelty
* Corrupted taming rituals
* Forced domination of spirit beasts

