			Apprentice Tarek

---
	Location : "Outland Territories / Capital City / The Beast Tamer’s Den"

---

		Appearance :

	"Apprentice Tarek" is a quiet young man with a slender build, pale olive skin, and observant gray-green eyes that constantly scan nearby creatures and player 
companions. His dark hair is slightly unkempt, often falling across his face while he writes notes or studies animal behavior.
	Unlike the rugged appearance of many beast tamers, Tarek dresses modestly and practically. He wears a simple earth-toned tunic reinforced with stitched leather 
patches, durable trousers, and lightweight boots suitable for traveling through forests and wilderness trails.

	A small satchel hangs across his shoulder, filled with :
* Handwritten creature journals
* Pet treats
* Small taming whistles
* Scented herbs
* Tiny traps
* Feathers and claw samples collected during expeditions

	Attached to his belt are several carefully labeled pouches containing bait mixtures and calming powders used when approaching nervous or aggressive creatures.
	Tarek almost always carries a weathered notebook filled with sketches and observations about pet species encountered across the world. Many pages contain 
handwritten warnings, feeding habits, migration patterns, and taming notes.

	When idle, he is often seen :
* Writing observations into his journal
* Studying nearby pets closely
* Feeding small creatures
* Organizing traps and tools
* Kneeling beside animals to observe injuries or behavior
* Comparing claw marks, fur, or scales with recorded notes

	His posture is reserved and cautious, often avoiding direct eye contact unless discussing creatures.

---

		Personality :

	Tarek is introverted, highly intelligent, and deeply fascinated by animal behavior. While shy around large crowds or overly loud adventurers, he becomes 
noticeably more comfortable when discussing pets, wilderness ecosystems, or rare creatures.
	He speaks softly and carefully, often choosing his words with precision. Though socially reserved, Tarek genuinely enjoys helping players understand the 
creatures they tame rather than simply capturing them.

	Key personality traits include :
* Observant
* Patient
* Thoughtful
* Analytical
* Compassionate toward animals
* Easily nervous around aggressive personalities

	Unlike Lena’s energetic enthusiasm, Tarek’s passion manifests through quiet focus and intense curiosity.

	He strongly dislikes :
* Reckless taming
* Creature abuse
* Needless killing of wildlife
* Players treating pets as disposable tools

	However, he rarely confronts players aggressively. Instead, his disappointment appears through subtle dialogue, silence, or avoidance.
	Players with unusual pets often fascinate him, sometimes causing him to forget his shyness entirely while asking questions about the creature.

---

		Behaviour :

	Tarek spends most of his time within the quieter side of "The Beast Tamer’s Den," particularly near pet enclosures, research shelves, or smaller taming stalls.

	His behaviors include :
* Quietly observing player pets
* Recording notes in his journal
* Testing bait mixtures
* Organizing pet food and traps
* Calming frightened animals
* Examining pawprints or feathers brought by adventurers
* Studying sleeping creatures carefully

	When players approach with rare pets summoned :
* Tarek may pause his work
* Carefully circle the creature
* Ask observational questions
* Mention similar species or rumored variants

	If multiple pets are nearby, he occasionally attempts to identify behavioral patterns or interactions between them.

	During ambient world activity :
* He avoids crowded arguments
* Retreats from loud combat nearby
* Becomes visibly uncomfortable around reckless adventurers
* Prefers calm conversations about exploration and wildlife

	Unlike Bronn, who commands authority, or Lena, who openly engages travelers, Tarek behaves more like a researcher quietly devoted to understanding creatures.

---

		Role :

* Role(s) :
	* Pet Specialist, Creature Behavior Researcher, Taming Advisor, Wildlife Observer

	Tarek assists players by providing :
* Pet behavior information
* Taming advice
* Habitat hints
* Companion care guidance
* Rare pet rumors
* Wildlife tracking insights
* Companion compatibility observations

	He serves as an immersive support NPC designed to deepen the pet-taming experience through environmental storytelling and behavioral lore.
	Tarek also acts as one of the world’s unofficial chroniclers of wild companion species.

---

