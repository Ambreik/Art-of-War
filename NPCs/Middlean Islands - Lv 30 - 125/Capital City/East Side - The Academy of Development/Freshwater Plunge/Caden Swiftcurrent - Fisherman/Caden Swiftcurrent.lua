				Caden Swiftcurrent

	Location : Middlean Islands / Capital City / East Side District / The Academy of Development / Freshwater Plunge

---

	Appearance : "Caden Swiftcurrent" is a young and athletic fisherman with an energetic presence that immediately draws attention around "Freshwater Plunge". His 
lightly tanned skin and lean muscular build reflect years spent swimming, diving, and training within the freshwater pools surrounding the docks. His messy brown 
hair is almost always soaked, usually pushed back carelessly after emerging from the water. He wears lightweight sleeveless training clothes designed for mobility 
in water, reinforced with small leather straps around the knees and wrists to protect him from underwater rocks and rough surfaces. Around his waist hangs a simple 
belt carrying small hooks, diving weights, and random trinkets he retrieves from the bottom of the pools during practice sessions. His bright green eyes constantly 
move with excitement, and his body language rarely remains still for more than a few moments.

---

	Personality : Caden is cheerful, competitive, and naturally friendly toward players and visitors of "Freshwater Plunge". Unlike many disciplined trainers or 
veteran fishermen, he treats swimming and fishing as enjoyable challenges rather than strict responsibilities. He constantly jokes with players, encourages 
beginners, and turns almost every interaction into some form of playful competition. Beneath his carefree attitude, however, lies genuine skill and dedication. He 
respects persistence more than talent and often spends extra time helping players struggling with swimming techniques or underwater movement. His enthusiasm helps 
make "Freshwater Plunge" feel less like a professional training facility and more like a lively community gathering place.

---

	Behaviour : Caden spends most of his time actively swimming or practicing dives around the freshwater pools. He frequently performs flips from nearby rocks or 
platforms into the water, often attempting increasingly difficult tricks simply to entertain nearby players. He occasionally dives to the deepest sections of the 
pool to retrieve lost objects or hidden items and challenges nearby players to race him underwater. During crowded hours, he sometimes organizes spontaneous 
swimming contests or breath-holding challenges for visitors training nearby.

---

	Role :

* Role(s) : Swimmer, Fisherman
	Caden acts as both a social atmosphere NPC and an informal aquatic trainer within Freshwater Plunge. He helps newer fishermen and swimmers improve agility, 
underwater movement, reaction timing, and diving control through friendly competitions and practical demonstrations.

---

	Mechanics :

* Type : Support NPC, Atmosphere NPC
* Reputation : Indirectly contributes to aquatic training progression and swimmer-related profession interactions.
* Interaction Limitations : Available to all players. Additional dialogue may unlock for players with Fisherman profession progression.
* PvP : Cannot be targeted or attacked. Not flagged for PvP.
* Respawn Time : Instant (non-combat NPC).
* Other Mechanics :
	* Occasionally initiates small swimming-related interactions around Freshwater Plunge.
	* Can help players locate submerged objects during aquatic activities.
	* His diving routines subtly reveal hidden underwater paths and obstacle placements.
	* Reinforces the social and community-focused atmosphere of the building.

