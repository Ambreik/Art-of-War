			Elda Marshstrider

	Location : Middlean Islands / Capital City / East Side District / The Academy of Development / Freshwater Plunge

---

	Appearance : "Elda Marshstrider" is a slender woman in her late thirties with pale skin lightly freckled from years spent near water and marshlands. Her long 
dark-blonde hair is loosely tied behind her back with braided reeds and thin strands of dried aquatic herbs woven between them. She wears layered herbalist garments
 made from lightweight waterproof fabrics dyed in muted green and brown tones, allowing her to move comfortably near wet surfaces and shallow pools. Around her 
waist hangs a collection of small glass jars, leather pouches, and herb-cutting tools, many stained by algae, oils, and plant residue. Her fingers are often tinted
green from handling aquatic plants, and a faint scent of wet moss and river herbs surrounds her wherever she sits.

---

	Personality : "Elda" is quiet, observant, and deeply focused on her work. She rarely starts conversations herself, but players who approach respectfully quickly
discover that she possesses extensive knowledge about aquatic plants and underwater ecosystems around Capital City. She speaks calmly and carefully, often pausing 
while examining herbs or preparing mixtures before answering questions. Unlike louder personalities within "Freshwater Plunge", Elda prefers peaceful environments 
and seems most comfortable when surrounded by water, plants, and silence. Though reserved, she enjoys helping curious players learn how to identify rare underwater 
herbs and appreciates those who show patience and attention to detail.

---

	Behaviour : "Elda" is usually found seated near the edge of the freshwater pools beside several carefully organized jars and herb containers. She spends most of
her time extracting liquids from aquatic plants, separating algae strands, or cleaning freshly gathered herbs with delicate precision. Occasionally, she stands near
shallow areas of the pool to inspect underwater vegetation or quietly collect rare plants growing between rocks beneath the surface. During quieter hours, she can 
sometimes be seen observing the movement of water currents while taking notes inside a weathered journal.

---

	Role :

* Role(s) : Herb Collector
	Elda functions as an atmosphere and knowledge-based NPC within "Freshwater Plunge", helping reinforce the connection between aquatic environments, herbalism, 
and underwater gathering. While she does not offer quests, she provides environmental lore and occasional guidance regarding underwater herbs and aquatic resources 
found around "Capital City".

