			Rhea Tidemender

	Location : Middlean Islands / Capital City / East Side District / The Academy of Development / Freshwater Plunge

---

		Appearance :
	"Rhea Tidemender" is a woman in her early forties with weather-touched skin and long sea-green hair usually tied in a thick braid that rests over one shoulder. 
Her attire is practical but elegant: layered rivercloth robes reinforced with leather straps, decorated with small shells, riverstones, and fishing charms tied by 
thin cords. Around her waist hangs a set of waterproof pouches filled with herbs, salves, and freshwater reagents. Her boots are always damp at the edges, as if she
has just stepped out of shallow water. Her eyes carry a calm, observant expression, the look of someone who studies currents and living things with equal patience. 
A faint scent of algae and river mint follows her, and her posture is relaxed but attentive, like someone who listens to things others cannot hear.

---

		Personality :
	Rhea is calm, nurturing, and deeply patient. She speaks slowly and thoughtfully, often using metaphors drawn from rivers, tides, and aquatic life. To players, 
she feels grounding and reassuring, the kind of NPC who never rushes a conversation. She has a healer’s temperament mixed with an angler’s intuition, treating water
not only as a resource but as a living presence. She shows particular warmth toward players involved in fishing or gathering professions, recognizing in them a 
shared respect for nature. While gentle in tone, she possesses a quiet firmness when speaking about pollution, waste, or mistreatment of the waterways around 
"Capital City".

---

		Behaviour :
	Rhea is often seen tending to basins of freshwater, cleaning fish specimens, or preparing mixtures from aquatic plants. At intervals, she walks outside the shop
to pour small vials of treated water into the nearby canal system, as if maintaining its health. During rain, she temporarily moves closer to the entrance, 
collecting rainwater in glass containers. If players idle nearby, she occasionally comments on the “state of the waters today,” reflecting dynamic environmental 
flavor tied to the Harbor and Crowd systems.

---

	Role :

* Role(s) : Craft NPC, Support NPC
	Rhea assists players with water-related crafting interactions tied to fishing, freshwater reagents, and aquatic components. She acts as a supportive figure 
within "Freshwater Plunge", enabling certain preparation steps needed before rare fish can be properly processed or preserved.

---

	Mechanics :

* Type : Craft NPC
* Reputation : Indirectly contributes to progression tied to the Anglers’ lineage and freshwater-related profession interactions.
* Interaction Limitations : Accessible to all players, but provides additional interaction options for players with Fisherman profession progress.
* PvP : Cannot be targeted. Not flagged for PvP. No consequences system tied to her.
* Respawn Time : Instant (non-combat NPC).
* Other Mechanics :
	* Enables preparation or purification steps for certain rare fish components.
	* Provides environmental flavor interactions connected to water quality and the harbor atmosphere.
	* Acts as a soft-lore anchor to the living ecosystem around the docks and canals.

