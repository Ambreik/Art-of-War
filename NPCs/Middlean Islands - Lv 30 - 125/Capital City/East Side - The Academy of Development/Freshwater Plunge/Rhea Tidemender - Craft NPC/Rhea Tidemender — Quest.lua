			Rhea Tidemender — Quest

---

		1. Quest Title

* Title : Beneath the Surface

---

		2. Quest Type

* Type :
	* Profession Quests
	* Solo Quests
* Category :
	* Crafting/Profession
	* Environmental/Survival
	* Exploration
	* Progression/Unlock

---

		3. Quest Giver

* NPC/Location : Rhea Tidemender — Freshwater Plunge — East Side District — Capital City
* Quest Giver Description :
	Rhea offers this quest to players practicing near the freshwater pool. Players must be Fisherman profession users. She approaches those showing patience and 	
control with the fishing rod rather than speed.

---

		4. Quest Objectives

	Primary Objectives :
* Collect 5x "Sacred Seaweed Clusters" from the hidden coves beneath Freshwater Plunge

	Secondary Objectives :
* Reach the coves without taking environmental damage from rocks or currents

	Thirdly Objectives :
* Unlocks the next quest in the chain

---

		5. Quest Description

	Rhea explains that sacred seaweed grows only in dangerous submerged coves and is valued for its healing properties by coastal cultures.

---

		6. Quest Rewards

	Primary Rewards :

* "Tidemender’s Gauntlets" (boosts healing items effectiveness)
* Fisherman Profession XP

	Optional Reward (Bonus) :

* "Healing Salve" if no damage taken

---

		7. Quest Conditions

	Prerequisites :
* Fisherman Profession
* Access to underwater section of Freshwater Plunge

	Fail Conditions :
* Player death
* Abandon quest

---

		8. Quest Locations

* Hidden underwater coves beneath Freshwater Plunge

---

		9. Quest Dialogue & NPC Interaction

	Opening :

> "Not all treasures float on the surface. Some must be earned beneath it."

	Mid-Quest :

> "The seaweed grows where only the patient dare to swim."

	Completion :

> "You moved like the tide itself. Well done."

---

		10. Quest Mechanics & Gameplay

* Underwater navigation
* Avoiding environmental hazards
* Diving mechanics

---

		11. Quest Progression & Timeline

* Leads directly to next quest: "Whisper of the Tide"

---

		12. Optional or Hidden Content

* Bonus reward for no damage taken

---

		13. Post-Quest Impact & Continuity

* Unlocks next quest in Rhea’s chain

---

		14. Miscellaneous Notes

* Introduces players to submerged navigation mechanics of the building

---

		15. Quest Closure & Debriefing

	Rhea rewards the player and prepares them for more advanced water-based challenges.

