			Carp Barbeau D. – Quest 

---

		1. Quest Title

* Title : Legacy Beneath the Surface

---

		2. Quest Type

* Type :
	* Profession Quests
	* Class Quests

* Category :
	* Crafting/Profession
	* Exploration
	* Environmental/Survival
	* Lore/History
	* Progression/Unlock

	This quest serves as the introductory chain for advanced Fisherman progression under Carp Barbeau D., tying directly into the Swordfish Fleet lineage.

---

		3. Quest Giver

* NPC/Location : Carp Barbeau D. – Freshwater Plunge – East Side District – Capital City – Middlean Islands

* Quest Giver Description : The quest becomes available once the player reaches "Level 42" and has the "Fisherman Profession" active.
	Upon approaching Carp after reaching level 42, he observes the player’s stance and initiates dialogue automatically if :
		* The player has at least Intermediate Fisherman Rank.
		* The player has completed at least one aquatic-based quest in "Capital City".

	No item is required to trigger the quest. However, players who carry rare fish in their inventory receive additional flavor dialogue.

---

		4. Quest Objectives

	Primary Objectives :
1. Complete the "Freshwater Plunge Endurance Trial" (timed underwater obstacle course).
2. Catch 3 "Deepwater Ironfin Eels" in the "Capital Island" coastal waters.
3. Retrieve "Elara’s Drift Compass Fragment" from a submerged wreck off the docks.

	Failure Conditions :
* Failing the underwater endurance trial timer resets that phase.
* Dying underwater during the wreck retrieval resets the objective.

---

	Secondary Objectives :
* Speak to "Rhea Tidemender" for advanced breathing techniques.
* Explore a hidden underwater tunnel beneath the docks (optional lore discovery).

	Completing these grants additional Fisherman XP and minor stamina buffs.

---

	Thirdly Objectives (Chain Trigger) :

	Upon completion, the player unlocks :
* A hidden reference to "Oscar Fisher D." on "Netar Island".
* Access to the second chain quest: "Echoes of the Outland Sea".

---

		5. Quest Description

* Brief Description  : Carp believes the player may be worthy of understanding the deeper legacy of the D Family. To prove themselves, the player must conquer water
not just as a tool — but as an element. The quest challenges endurance, fishing mastery, and historical awareness, echoing the trials once faced by Elara and the 
"Swordfish Fleet" during the "Second Great War".

---

		6. Quest Rewards

	Primary Rewards :
* Fisherman Profession XP (High Tier)
* Standard XP (Scaled to Level 42+)
* Gold & Silver currency

---

	Secondary Rewards :
* +Reputation with Fisherman Profession
* Unlock: Advanced Fisherman Techniques (hidden progression tier)
* Item: "Driftwood Sigil of the Fleet" (Trinket – Minor stamina increase while swimming)

---

		Optional Rewards :

	Player chooses one :
1. Ironfin Reinforced Line (Improves chance to catch rare coastal fish)
2. Breath of Narrawind (Consumable – increases underwater breath duration temporarily)
3. Swordfish Fleet Emblem (Cosmetic back insignia)

---

		7. Quest Conditions

	Prerequisites :
* Level 42+
* Fisherman Profession active
* Completed at least one Freshwater Plunge activity

---

	Fail Conditions :
* Failing endurance timer (retry allowed).
* Abandoning quest resets progression.
* Wreck objective fails if player leaves zone during retrieval.

---

		8. Quest Locations

* Start Location  : Freshwater Plunge – East Side District
* Important Locations :
	* Capital Island Coastal Waters
	* Submerged Wreck near Docks
	* Hidden Underwater Tunnel (optional)
* End Location : Return to Carp Barbeau D. at Freshwater Plunge

---

		9. Quest Dialogue & NPC Interaction

	Quest Initiation : Carp crosses his arms and studies the player.

	Opening Dialogue : "Water doesn’t care about your level, lad. It cares about your lungs and your nerve. If you want to stand where my ancestors stood — prove it."

	Player choice :
* "I’m ready."
* "Tell me about the Swordfish Fleet."

---

		In-Quest Dialogue :

	When failing endurance trial : "You panicked. Water smells fear. Try again."

	When retrieving compass fragment : "Careful down there. Old wrecks don’t forget."

---

	Quest Completion Dialogue : Carp inspects the fragment quietly before nodding.

	"You didn’t fight the sea. You moved with it. Elara would’ve approved."

---

		10. Quest Mechanics & Gameplay

	Core Gameplay Tasks :
* Timed underwater obstacle trial
* Rare fish catching
* Underwater exploration
* Environmental hazard navigation

---

	Special Mechanics :
* Underwater stamina drain system
* Breath management mechanic
* Timed endurance challenge
* Environmental hazards (entangling seaweed, unstable wreck beams)

---

		11. Quest Progression & Timeline

	Quest Phases :
1. Acceptance & Trial Unlock
2. Endurance Completion
3. Rare Fish Hunt
4. Wreck Exploration
5. Return & Evaluation

---

	Cooldowns & Timers :
* Endurance Trial timer: 4 minutes.
* Quest repeatable? No (Storyline chain).
* Failure retry cooldown: 2 minutes before retrying trial.

---

		12. Optional or Hidden Content

	Hidden Objectives :
* Discover Elara’s etched name inside the wreck hull.
* Finding hidden underwater chest grants bonus dialogue.

---

		Alternative Endings :

	No major branching, but :
* Completing optional objectives unlocks additional lore dialogue from Carp.

---

		13. Post-Quest Impact & Continuity

	Unlockables :
* Unlocks next chain quest.
* Opens subtle dialogue references to Oscar Fisher D.
* Unlocks hidden recognition within D Family progression path.

---

	Character Relationships : Carp begins addressing the player by nickname ("Deckhand" or "Wavewalker").

---

		14. Miscellaneous Notes

	Easter Eggs or Lore :
* The compass fragment contains coordinates subtly referencing Outland Sea.
* Environmental carvings reference Narrawind village.

---

		Player Agency :

	Moderate freedom :
* Fish can be caught in different coastal spots.
* Wreck can be approached from multiple underwater angles.

---

		15. Quest Closure & Debriefing

	Resolution : Carp mounts the restored compass fragment inside Freshwater Plunge.

	"You’ve earned a place in this water. But the sea goes deeper than this city."

---

	Post-Quest Reflection : Other NPCs in Freshwater Plunge acknowledge the player’s accomplishment with new dialogue lines.

