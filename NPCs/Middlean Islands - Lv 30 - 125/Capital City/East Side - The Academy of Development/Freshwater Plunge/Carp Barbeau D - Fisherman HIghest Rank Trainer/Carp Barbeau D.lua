			Carp Barbeau D.

* Location : Middlean Islands / Capital City / East Side District / The Academy of Development / Freshwater Plunge

---

	Appearance : "Carp Barbeau D." is a broad-shouldered, sun-tanned man in his early forties whose body still carries the strength of a lifelong fisherman. His 
forearms are thick and scarred from years of hauling nets and wrestling stubborn catches from the water. He wears a sleeveless linen shirt faded by salt and sun, 
loose canvas trousers tucked into waterproof boots, and a leather belt heavy with small tools, hooks, and line spools. Around his neck hangs a carved driftwood 
pendant shaped like a swordfish — a family relic passed down through generations.
	His dark hair is tied loosely behind his head, often still damp from demonstrating swimming drills in the freshwater pool. A permanent smell of river reeds and 
sea salt seems to follow him. When he stands near the pool, arms crossed and chest slightly forward, he looks less like a shopkeeper and more like a seasoned 
deckhand watching over a crew.

---

	Personality : Carp is lively, loud, and deeply welcoming. He laughs easily and speaks with the booming voice of someone used to shouting across crashing waves. 
He treats players less like customers and more like young anglers he is personally training. Beneath his cheerful demeanor lies a strong sense of family pride and 
respect for the legacy of the Swordfish Fleet. He enjoys telling stories, often drifting into tales of Elara the Navigator or the legendary journeys of his 
ancestors when players linger near him.
	He is patient with beginners but holds experienced fishermen to higher standards, often teasing them when they fail simple aquatic tasks. His tone is never 
harsh, only challenging — he believes that struggle in water builds character on land.

---

	Behaviour : Carp frequently walks around the edges of the central pool, observing swimmers and occasionally shouting advice or encouragement. At times, he 
kneels near the water to adjust floating obstacles or untangle ropes. During quiet hours, he can be found sitting near the fire pit, carving small wooden fish or 
repairing old nets while humming old sea chants from Narrawind.

---

	Role :

* Role(s) : Craft NPC, Shop NPC, Hidden Rank V Fisherman Trainer, Quest Giver
	Carp is the owner and heart of the "Freshwater Plunge". While he officially operates as a crafting and shop NPC (shop system already defined), his true 
importance lies in his role as a hidden "Rank V Fisherman Trainer" and the primary quest anchor for advanced fisherman progression starting at level 42. Through his
quests and guidance, players are introduced to endurance training, aquatic challenges, and the deeper lore of the "D Family" and the "Swordfish Fleet".

---

	Mechanics :
* Type  : Craft NPC, Shop NPC, Quest Giver, Profession Trainer (hidden)
* Reputation  : Grants Fisherman Profession reputation and contributes to recognition within the Anglers’ legacy tied to the D Family
* Interaction Limitations  : Fully interactable by all players, but quests and certain dialogue options unlock only for players with the Fisherman profession and 
level 42+
* PvP  : Cannot be targeted, cannot be attacked, never flagged for PvP
* Respawn Time  : Not applicable (non-killable NPC)
* Other Mechanics  :
  * Acts as a skillable NPC tied to aquatic endurance and fisherman progression
  * Central node for a chain-quest line connected to rare fish, underwater challenges, and Swordfish Fleet lore
  * Indirectly links players to other members of the D Family (Oscar and Sushi) through quest narrative
  * Integrated with the Freshwater Plunge obstacle pool mechanics for swimming and stamina challenges

---

	Quest :

* Quest Title : "Legacy Beneath the Surface"
	* Quest Type  : Chain Quest (Storyline / Profession)
	* Objective(s)  :
		* Complete underwater endurance trials in the Freshwater Plunge pool
		* Catch specific rare fish in designated regions
		* Retrieve aquatic plants and crafting components
		* Discover clues about the Swordfish Fleet’s history
	* Rewards  :
		* Fisherman Profession Experience
		* Unique fishing components and rare bait materials
		* Reputation tied to the Anglers’ legacy
	* Conditions  :
		* Level 42+
		* Fisherman Profession required
	* Quest Dialogue  :
		* Opening  : "Water tells you who you are, lad. If you can’t breathe with it, you’ll never live from it. Let’s see what you’re made of."
		* Mid-Quest  : "The fish aren’t your enemy. Your fear is. Dive again."
		* Completion : "Ha! Elara herself would’ve nodded at that catch. You’re starting to understand the sea."
	* Additional Notes  :
		* Quest chain subtly introduces the player to the wider D Family storyline and encourages exploration toward other related NPCs in future regions.

