		9. Quest Dialogue & NPC Interaction

	Quest Initiation :
Finnick raises an eyebrow : "Fish don’t fight the current. They become the current. You done that yet?"

	Player Options :
* "I’m ready."
* "Tell me more."

---

	In-Quest Dialogue :

On eel defeat : "Good… but those were the warm-up."

During net haul : "These ropes don’t care about your strength. They care about your resolve."

---

	Completion Dialogue :
Finnick claps the player’s shoulder : "Now that’s how the sea earns respect. You’re no longer just fishing — you’re commanding it."

---

		10. Quest Mechanics & Gameplay

	Core Gameplay Tasks :
* Combat against water-adapted eel mobs (environmental combat)
* Strength/distance challenge with physics-based net dragging
* Time-based endurance, stamina/oxygen system

---

	Special Mechanics :
* Weighted net drag slows movement based on stamina
* Simulated water current increases knock-back chance
* Eel AI uses evasive aquatic behavior

---

