---

		7. Quest Conditions

	Prerequisites :
* Player must be Level 40+
* Fisherman Profession unlocked
* Must have completed Carp’s first quest "Legacy Beneath the Surface" (recommended)

	Fail Conditions :
* Failing net haul distance
* Eels defeated outside current zone
* Leaving turbulence zone early

