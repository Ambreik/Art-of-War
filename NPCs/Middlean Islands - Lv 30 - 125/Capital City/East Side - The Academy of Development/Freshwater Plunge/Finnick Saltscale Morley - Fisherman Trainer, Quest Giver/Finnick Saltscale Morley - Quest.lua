		3. Quest Giver

* NPC/Location : Finnick “Saltscale” Morley – Freshwater Plunge – Academy of Development – Capital City – East Side District
* Quest Giver Description :
	Finnick challenges anglers who show promise but lack raw endurance and strength. Players must actively train or fish near the Freshwater Plunge pool before 	Finnick acknowledges them with the demand: "If you want to haul sea monsters… prove you can haul yourself."

	The quest auto-triggers once the player completes a moderate training course and has Fisherman Profession active.

---

		4. Quest Objectives

	Primary Objectives :

* Defeat "10 Current-Sworn Eels" encountered in the coastal arc near Freshwater Plunge
* Complete "Weighted Net Haul Trials" (dragging heavy nets underwater for distance)
* Survive "10 minutes" in simulated turbulent water conditions within the pool

	Failure Conditions :
* Net drags not completed within the distance requirement must be retried
* Simulated turbulence ends if player surfaces too soon

---

	Secondary Objectives :
* Speak with "Rhea Tidemender" for finesse techniques
* Retrieve "Strange Sea Glass Shards" from eel lairs

---

	Thirdly Objectives :
* Unlock further training objectives if all Secondary bonuses are completed.

---

		5. Quest Description

* Brief Description :
	Finnick wants to push anglers beyond mere technique — to make them strong, relentless, and unyielding. He challenges the player to fight tiring currents, 
wrestle powerful eels, and endure exhaustive trials until the sea feels less like an obstacle and more like territory worth mastering.

---

