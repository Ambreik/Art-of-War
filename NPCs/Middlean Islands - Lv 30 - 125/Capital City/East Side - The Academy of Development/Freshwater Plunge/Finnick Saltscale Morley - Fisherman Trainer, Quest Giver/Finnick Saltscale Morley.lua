			Finnick "Saltscale” Morley

---

	Location : Middlean Islands / Capital City / East Side District / The Academy of Development / Freshwater Plunge

---

		Appearance :

	"Finnick "Saltscale” Morley" is a rugged, sturdy man in his late fifties with a weather-beaten face and a bristling white beard thick with salt stains from years 
spent in and around the water. His once-dark hair is now mostly grey, bound loosely beneath a battered fisher’s cap adorned with bits of washed-up coral and tiny 
shells. His eyes are a steely blue — sharp, observant, and forever scanning bodies of water for signs of life.
	He wears a worn leather jerkin patched with reinforced netting, thick canvas trousers rolled up to mid-calf, and leather bracers etched with simple aquatic 
runes. Strapped to his back is a large tackle sack filled with various fishing tools, weights, charms, and old trinkets collected from the sea.
	A distinctive set of medals made from carved fish vertebrae hangs around his neck — each one representing a challenge he conquered in his youth.Despite his age 
Finnick stands firm and steady, with the confident gait of someone who has faced the ocean’s worst and survived.

---

		Personality :

	Finnick is gruff, no-nonsense, and speaks with a voice weathered from years of shouting over storms and crashing waves. He doesn’t suffer fools gladly, and 
players might initially find his tone abrupt or intimidating — but those who persist soon realize he’s deeply proud of the skills he teaches and fiercely loyal to 
those who learn from him.
	He has a dry sense of humor that creeps into his dialogue once trust is earned, and he often greets players with a half-smile and a teasing comment like "Hope 
you don’t sink as fast as my last catch."

	Finnick pushes trainees hard but fairly. He believes strength and endurance are forged through challenge, not idle repetition.

---

		Behaviour :

	Finnick rarely stays in one place long. He walks the perimeter of the freshwater pool, pacing with a purposeful stride as he watches swimmers and anglers in 
training. He frequently stops to demonstrate biting techniques or posture adjustments, often wading ankle-deep into the water to better show a point.
	During peak activity hours, his voice booms over the pool: correcting swimmers, calling out tasks, or awarding progress to struggling trainees.
	When it’s quiet, he sits on a wooden crate near the pool edge, cleaning hooks or tending to fishing gear while muttering about nostalgic catches of days past.

---

	Role :

* Role(s) : Fisherman Trainer, Quest Giver
	Finnick serves as the primary Trainer for Strength and Endurance within aquatic expertise. He takes players beyond mere survival swimming into combat-prepared 
water traversal and fishing mastery under adverse conditions. In gameplay terms, he trains players to endure difficult coastal conditions, equips them with advanced
fishing stamina tasks, and assigns quests linked to strain-based mastery — such as dragging heavy nets, ocean-current battles, or extended deepwater quests.

---

	Mechanics :

* Type : Profession Trainer, Quest Giver
* Reputation : Grants reputation and progression within the Fisherman Profession system and contributes to legacy progression in the Swordfish Fleet storyline.
* Interaction Limitations :
	* Must have Fisherman Profession unlocked
	* Must be Level 40+ to access advanced training
* PvP : Cannot be attacked; not flagged for PvP.
* Respawn Time : Instant (cannot be killed in regular gameplay)
* Other Mechanics :
	* Unlocks "Strength & Endurance Fishing Tasks"
	* Adds conditional training objectives when weather conditions are simulated (e.g., currents, waves)
	* Provides bonus aquatic buff on completing his training challenges

