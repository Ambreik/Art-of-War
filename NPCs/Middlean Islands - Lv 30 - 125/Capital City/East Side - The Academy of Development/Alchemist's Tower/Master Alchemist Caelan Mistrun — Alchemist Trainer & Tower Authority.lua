			Master Alchemist Caelan Mistrun — Alchemist Trainer & Tower Authority

---

		Appearance

	"Caelan Mistrun" is a tall, slender alchemist with a refined and scholarly presence. His long, stark white hair contrasts sharply with his deep purple alchemist
robe, which is decorated with intricate silver arcane symbols that faintly shimmer under light.
	He often holds a crystalline flask or an alchemical tome, constantly studying or muttering formulas. His silver-green eyes reflect curiosity and deep analytical
focus rather than emotion.


---

	Personality : 
* Curious, analytical, and deeply devoted to the science and art of alchemy.
* Caelan sees alchemy as both a science and an evolving mystery.

	He is patient with learners but highly demanding in precision and execution.

---

	Behavior : 
* Caelan remains stationed within the central alchemy workspace of the tower.
* He interacts directly with players as a trainer NPC, guiding progression through alchemy systems.

	He is the only functional NPC in this structure and serves as both :
* Trainer
* Lore authority
* Craft progression gatekeeper

---

		Role — MASTER ALCHEMIST & SYSTEM TRAINER

	"Caelan Mistrun" is the core alchemy progression authority of the entire" Alchemist’s Tower".

---

