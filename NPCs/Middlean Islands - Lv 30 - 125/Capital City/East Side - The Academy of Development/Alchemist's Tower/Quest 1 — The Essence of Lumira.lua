			Quest 1 — The Essence of Lumira

---

		1. Quest Title

	Title : The Essence of Lumira

---

		2. Quest Type

* Type : Profession Quests
* Category : Exploration / Crafting / Lore-History / Environmental

---

		3. Quest Giver

* NPC / Location : "Master Alchemist Caelan Mistrun" — Alchemist’s Tower, Ground Floor Alchemical Station
* Quest Giver Description :
	The quest becomes available only when:
		* Player has "Alchemy Profession Rank I"
		* Player interacts with Caelan during night time inside the Tower

  Caelan does not offer the quest immediately.
  He first comments about the scent of night air entering through the Tower vines, hinting at Lumira.

---

		4. Quest Objectives

	Primary Objectives : 

1. Travel to "Friggel Wood"
2. Wait for a "Full Moon night cycle"
3. Locate and gather "3 Lumira Flowers"
4. Return them intact to Caelan

	Secondary Objectives

* Defeat "Spectral Wolves" and "Shadow Wisps" encountered near the flowers
* Observe that "Lumira Flowers" are only visible under direct moonlight

	Thirdly Objectives (Chain Trigger)

* When player picks the first Lumira Flower, a hidden objective appears :
	"Observe how the flower reacts to your presence under moonlight."

---

		5. Quest Description (Player View)

	Caelan believes the Lumira Flower reacts to lunar energy in ways never properly studied.
	He asks you not merely to collect it, but to witness how it lives only in moonlight.

	This is not a gathering task.
	This is your first lesson in environmental alchemy.

---

		6. Quest Rewards

	Primary Rewards : 
* XP
* Gold
* Recipe: "Elixir of Vital Bloom"

	Secondary Rewards : 
* +Reputation with Caelan
* Unlocks Quest 2

	Optional Rewards : 
* None

---

		7. Quest Conditions

	Prerequisites : 
* Alchemy Rank I
* Player Level 25+
* Night cycle active

	Fail Conditions : 
* If Lumira Flowers are gathered during dawn transition → flowers wither → must wait next full moon

---

		8. Quest Locations

* Start Location : "Alchemist’s Tower"
* Important Location : "Friggel Wood" (Full Moon only)
* End Location : "Alchemist’s Tower"

---

		9. Quest Dialogue & NPC Interaction

	Quest Initiation (Caelan)

> "Do you smell it? The night carries knowledge the sun burns away.
> There is a flower that refuses to exist in daylight. Bring me three… but more importantly, bring me what you learn by watching them."

	n-Quest Trigger (after first flower)

> "You notice the Lumira petals faintly glow as the moonlight touches them."

	Quest Completion

> "Good… you did not simply harvest them. You observed them.
> Then you are ready to begin learning alchemy as it truly is."

---

		10. Quest Mechanics & Gameplay

	Core Tasks : 
* Time-based exploration
* Environmental observation
* Combat survival at night
* Gathering rare resource

	Special Mechanics : 
* "Lumira Flowers" do not appear without full moon light
* Flowers emit glow only when player stands still near them

---

		11. Quest Progression & Timeline

	Phases : 
1. Accept quest at night
2. Travel to "Friggel Wood"
3. Wait for full moon
4. Gather flowers
5. Return to Caelan

	Cooldown : 
* If failed → must wait next full moon cycle

---

		12. Optional / Hidden Content

	Hidden Objective : 
* If player stays 20 seconds near a flower without picking it → gains hidden lore message

---

		13. Post-Quest Impact & Continuity

* Unlocks deeper dialogue with Caelan
* Unlocks Quest 
* Introduces player to time & environment dependency in alchemy

---

		14. Miscellaneous Notes

* First time player realizes world time matters for professions
* Establishes Hook Wood as mystical place for future content

---

		15. Quest Closure & Debriefing

	Resolution : 
* Player is no longer treated by Caelan as a beginner.

	Post-Quest Reflection (Caelan) : 

> "Most harvest. Few observe. Fewer understand. You may continue."

