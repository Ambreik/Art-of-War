			Quest 2 — Elixir of the Eternal Flame

---

		1. Quest Title

* Title : Elixir of the Eternal Flame

---

		2. Quest Type

* Type : Profession Quest
* Category : Combat-based / Crafting / Environmental-Survival / Lore-History

---

		3. Quest Giver

* NPC / Location : Master Alchemist Caelan Mistrun — Alchemist’s Tower, Upper Alchemical Station
* Quest Giver Description :
	Available only after completing "The Essence of Lumira."
	Caelan is found studying a cracked, heat-scorched flask when the player approaches.

---

		4. Quest Objectives

	Primary Objectives : 
1. Travel to "Emberwaste"
2. Hunt "Flamebound Drakes"
3. Obtain "1 Heart Ember" (rare drop from elite drakes)
4. Return the Heart Ember undamaged to Caelan

	Secondary Objectives : 
* Avoid water or frost damage to the Heart Ember while carrying it
* Survive prolonged fire exposure in Emberwaste

	Thirdly Objectives (Chain Trigger) : 
* If the player takes fire damage over a threshold while carrying the ember:
	"You feel the Ember resonate with the flames around you."
---

		5. Quest Description (Player View)

	Caelan explains that some ingredients are not harvested — they are taken from living fire.
	The Heart Ember is the core of a drake’s internal flame, still alive after death.

	You are not sent to collect.
	You are sent to retrieve something that is trying to burn its way back to life.

---

		6. Quest Rewards

	Primary Rewards : 
* XP
* Gold
* Recipe: "Elixir of Inferno Shield"

	Secondary Rewards : 
* Reputation with Caelan
* Unlocks Quest 3

	Optional Rewards : 
* None

---

		7. Quest Conditions

	Prerequisites : 
* Completion of Quest 1
* Alchemy Rank II
* Level 35+

	Fail Conditions : 
* If player enters water, receives frost damage, or dies → Heart Ember cracks → must retrieve a new one

---

		8. Quest Locations

* Start Location : "Alchemist’s Tower"
* Important Location : "Emberwaste"
* End Location : "Alchemist’s Tower"

---

		9. Quest Dialogue & NPC Interaction

	Quest Initiation (Caelan) : 

> "Some ingredients resist being taken. This one will try to return to the fire it came from. Do not let it."

	Mid-Quest System Message : 

> "The Heart Ember pulses violently as flames surround you."

	Quest Completion : 

> "You did not extinguish it… you controlled it. That is the difference between a brewer and an alchemist."

---

		10. Quest Mechanics & Gameplay

	Core Tasks : 
* Elite monster hunting
* Environmental survival in high fire-damage zone
* Careful transport of fragile quest item

	Special Mechanics : 
* Heart Ember is a fragile carried item
* Certain damage types affect its integrity
* Visual heat distortion effect while carrying it

---

		11. Quest Progression & Timeline

	Phases : 
1. Accept quest
2. Travel to Emberwaste
3. Kill Flamebound Drakes until Heart Ember drops
4. Safely transport Ember to Caelan
5. Deliver item intact

	Cooldown : 
* None, but drop rate encourages multiple fights

---

		12. Optional / Hidden Content

	Hidden Objective : 
* If player avoids all frost/water damage while carrying ember → bonus Caelan dialogue

---

		13. Post-Quest Impact & Continuity

* Player now introduced to fragile ingredient mechanics
* Unlocks Quest 3
* Caelan’s dialogue becomes more respectful

---

		14. Miscellaneous Notes

* Introduces concept: ingredients reacting to environment
* Encourages group play due to elite drakes

---

		15. Quest Closure & Debriefing

	Resolution : 
* Player learns control over volatile alchemical materials.

	Post-Quest Reflection (Caelan) : 

> "Fire is not dangerous because it burns. It is dangerous because it lives."

