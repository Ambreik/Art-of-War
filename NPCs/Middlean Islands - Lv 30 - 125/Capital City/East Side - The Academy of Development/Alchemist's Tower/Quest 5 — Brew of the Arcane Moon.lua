			Quest 5 — Brew of the Arcane Moon

---

		1. Quest Title

* Title : Brew of the Arcane Moon

---

		2. Quest Type

* Type : Profession Quest
* Category : Exploration / Crafting / Time-based / Lore-History / Progression-Unlock

---

		3. Quest Giver

* NPC / Location : "Master Alchemist Caelan Mistrun" — Alchemist’s Tower Observatory Level
* Quest Giver Description :
	Caelan only offers this quest at night and only after Quest 4 is completed.
	The observatory dome is open, moonlight flooding the floor.

---

		4. Quest Objectives

	Primary Objectives : 
* Obtain "Arcane Moonstone" from the "Moonlit Caverns"
* Deliver it to Caelan before the night cycle ends

	Secondary Objectives : 
* Avoid triggering lunar traps inside the caverns
* Recover the stone without shattering its outer layer

	Thirdly Objectives (Chain Trigger) : 
* Unlock advanced mana-based elixir knowledge
* Hint toward future legendary alchemy path

---

		5. Quest Description (Player View)

	Some ingredients are not grown.
	They are born from the sky itself.

	Caelan believes the moon hides a property no alchemist has fully understood.

	Tonight, you prove him right.

---

		6. Quest Rewards

	Primary Rewards : 
* XP
* Gold
* Recipe: " of Arcane Tide" (rapid mana regeneration)

	Secondary Rewards : 
* Unlock: Moon-based alchemical ingredients knowledge
* Reputation with Caelan

	Optional Rewards : 
* Choice between :
  * Extra Elixir recipe
  * Rare alchemy material pack

---

		7. Quest Conditions

	Prerequisites : 
* Completion of Quest 4
* Level 65+
* Alchemy Rank V

	Fail Conditions : 
* Daylight begins before return
* Moonstone breaks due to combat damage
* Player death inside caverns

---

		8. Quest Locations

* Start Location : "Alchemist’s Tower Observatory"
* Important Location : "Moonlit Caverns"
* End Location : "Alchemist’s Tower"

---

		9. Quest Dialogue & NPC Interaction

	Quest Initiation (Caelan) : 

> "The moon is not light. It is residue… from something far older than this world."

	Mid-Quest (entering caverns) : 

> "Do not rush. The stone listens before it allows itself to be taken."

	Completion : 

> "Yes… yes! This confirms it. The moon is an ingredient."

---

		10. Quest Mechanics & Gameplay

	Core Gameplay Tasks : 
* Timed exploration during night cycle
* Careful navigation through magical traps
* Special interaction to extract the Moonstone

	Special Mechanics : 
* Inside the caverns :
	* Lunar traps activate if player runs
	* Some enemies reflect magic damage
	* The Moonstone must be mined slowly (channeling interaction)

---

		11. Quest Progression & Timeline

	Phases : 
1. Accept quest at night
2. Travel to caverns
3. Navigate traps and enemies
4. Extract Moonstone carefully
5. Return before dawn

---

		12. Optional / Hidden Content

	Hidden Objective : 
* If player returns without triggering any traps, Caelan teaches a hidden recipe later

---

		13. Post-Quest Impact & Continuity

* Marks the player as a true master of alchemy
* Opens narrative path toward legendary elixirs
* Completes Caelan’s primary questline

---

		14. Miscellaneous Notes

* Strong lore connection between celestial bodies and alchemy
* Teaches patience and environmental awareness

---

		15. Quest Closure & Debriefing

	Resolution : 
* Caelan realizes a breakthrough in alchemical theory thanks to the player.

	Post-Quest Reflection (Caelan)

> "We were wrong for centuries. We looked to the earth for answers… when they were falling from the sky."

