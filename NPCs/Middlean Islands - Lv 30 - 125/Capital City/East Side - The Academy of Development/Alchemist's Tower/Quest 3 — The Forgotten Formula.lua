			Quest 3 — The Forgotten Formula

---

		1. Quest Title

* Title : The Forgotten Formula

---

		2. Quest Type

* Type : Profession Quest
* Category : Exploration / Mystery-Investigation / Lore-History / Puzzle / Combat-based

---

		3. Quest Giver

* NPC / Location : Master Alchemist Caelan Mistrun — Alchemist’s Tower, Observatory Level
* Quest Giver Description :
	Available after completing "Elixir of the Eternal Flame."
	Caelan is found surrounded by old parchments and broken sealing wax, clearly frustrated.

---

		4. Quest Objectives

	Primary Objectives : 
1. Travel to the "Ruins of Eldergrove"
2. Locate "3 Missing Pages" of an ancient alchemical formula
3. Return all pages to Caelan

	Secondary Objectives : 
* Solve environmental puzzles guarding each page
* Avoid triggering ancient traps within the ruins

	Thirdly Objectives (Chain Trigger) : 
* After retrieving the second page, the player gains a temporary debuff:
  "Whispers of the Past" — faint voices, distorted screen edges

---

		5. Quest Description (Player View)

	Caelan explains that some formulas were never lost — they were hidden.

	The pages you seek were removed deliberately from history because the potion they describe does not enhance the body… it enhances everything.

---

		6. Quest Rewards

	Primary Rewards : 
* XP
* Gold
* Recipe: "Elixir of Forgotten Power"

	Secondary Rewards : 
* Reputation with Caelan
* Unlocks Quest 4

	Optional Rewards : 
* None

---

		7. Quest Conditions

	Prerequisites : 
* Completion of Quest 2
* Alchemy Rank III
* Level 45+

	Fail Conditions : 
* None (but traps and enemies make retrieval difficult)

---

		8. Quest Locations

* Start Location : "Alchemist’s Tower"
* Important Location : "Ruins of Eldergrove"
* End Location : "Alchemist’s Tower"

---

		9. Quest Dialogue & NPC Interaction

	Quest Initiation (Caelan) : 

> "They did not burn this knowledge. They feared it too much to destroy it… so they hid it where no one sane would search."

	Mid-Quest System Message (after 2nd page) : 

> "You hear faint whispers… as if the paper remembers being read."

	Quest Completion : 

> "You do not realize what you’ve brought me… and that is precisely why you were able to find it."

---

		10. Quest Mechanics & Gameplay

	Core Tasks : 
* Exploration of trap-filled ruins
* Puzzle-solving for access to pages
* Combat with ancient guardians and creatures

	Special Mechanics

	Each page is protected differently :
1. "Page of Body" — guarded by stone constructs (combat challenge)
2. "Page of Mind" — locked behind a symbol-matching puzzle
3. "Page of Essence" — hidden behind an invisible wall revealed only at night cycle

---

		11. Quest Progression & Timeline

	Phases : 
1. Accept quest
2. Travel to Eldergrove
3. Retrieve pages (non-linear order)
4. Experience whispers effect after 2nd page
5. Return to Caelan

	Cooldown : 
* None

---

		12. Optional / Hidden Content

	Hidden Objective : 
* If player retrieves "Page of Essence" during night without taking damage → hidden Caelan dialogue

---

		13. Post-Quest Impact & Continuity

* Unlocks access to stat-boosting potion recipes
* Leads into Caelan testing player directly in Quest 4
* Introduces concept of ancient suppressed knowledge

---

		14. Miscellaneous Notes

* First quest heavily focused on puzzle + exploration instead of gathering
* Reinforces world history and alchemical lore depth

---

		15. Quest Closure & Debriefing

	Resolution : 
* Player proves capable not only in gathering but in understanding hidden knowledge.

	Post-Quest Reflection (Caelan) : 

> "Some knowledge is buried not because it is lost… but because it is dangerous to remember."

