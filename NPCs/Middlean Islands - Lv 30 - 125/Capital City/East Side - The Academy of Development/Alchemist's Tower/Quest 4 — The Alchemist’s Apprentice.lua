			Quest 4 — The Alchemist’s Apprentice

---

		1. Quest Title

* Title : The Alchemist’s Apprentice

---

		2. Quest Type

* Type : Profession Quest
* Category : Crafting / Skill-based / Progression-Unlock / Time-based

---

		3. Quest Giver

* NPC / Location : Master Alchemist Caelan Mistrun — Alchemist’s Tower, Central Alchemical Station
* Quest Giver Description :
	Available after completing "The Forgotten Formula."
	Caelan does not give ingredients lists this time — he hands you materials directly.

---

		4. Quest Objectives

	Primary Objectives : 
* Craft three complex potions using materials provided by Caelan :
1. Stabilizing Draught
2. Reactive Catalyst
3. Dual-Phase Elixir

	Secondary Objectives : 
* Follow Caelan’s instructions precisely
* Do not fail more than two crafting attempts

	Thirdly Objectives (Chain Trigger) : 
* Upon success, player unlocks passive crafting bonus inside the Alchemist’s Tower

---

		5. Quest Description (Player View)

	Knowledge is not proven in the wild.
	It is proven at the table.

	Caelan now tests whether you truly understand alchemy… or merely follow recipes.

---

		6. Quest Rewards

	Primary Rewards : 
* XP
* Gold
* Title: "Caelan’s Apprentice"

	Secondary Rewards : 
* Passive: +Crafting Success Chance while inside Alchemist’s Tower
* Access to exclusive advanced recipes

	Optional Rewards : 
* Choice of one advanced potion recipe

---

		7. Quest Conditions

	Prerequisites : 
* Completion of Quest 3
* Alchemy Rank IV
* Level 55+

	Fail Conditions : 
* Failing 3 crafting attempts resets the quest (cooldown 30 minutes)

---

		8. Quest Locations

* Start Location : "Alchemist’s Tower"
* Important Location : "Central Alchemical Station"
* End Location : Same

---

		9. Quest Dialogue & NPC Interaction

	Quest Initiation (Caelan) : 

> "Out there, mistakes cost blood. In here, they cost knowledge. Let us see which you value more."

	Mid-Quest Dialogue (after first success) : 

> "You are not guessing. Good."

	On Failure : 

> "You followed steps. You did not understand them."

	Completion : 

> "Now… you are no longer a student of alchemy. You are a practitioner of it."

---

		10. Quest Mechanics & Gameplay

	Core Gameplay Tasks : 
* Real crafting interaction
* Precision and attention to instructions
* Time-window inputs during crafting

	Special Mechanics : 

	Each potion has a hidden rule the player must discover from Caelan’s hints:

| Potion              | Hidden Rule                                | Failure Cause          |
| ------------------- | ------------------------------------------ | ---------------------- |
| Stabilizing Draught | Ingredients must be added in reverse order | Normal order fails     |
| Reactive Catalyst   | Must wait 5 seconds before final mix       | Mixing too early fails |
| Dual-Phase Elixir   | Requires heating, cooling, then reheating  | Skipping a phase fails |

---

		11. Quest Progression & Timeline

	Phases : 
1. Accept quest
2. Receive materials
3. Craft 3 potions correctly
4. Return to Caelan

	Cooldown : 
* 30 minutes on full failure

---

		12. Optional / Hidden Content

	Hidden Objective : 
* Completing all three potions without a single mistake unlocks hidden Caelan dialogue and a bonus recipe

---

		13. Post-Quest Impact & Continuity

* Player earns recognized status in the Tower
* Unlocks Quest 5
* Introduces true crafting mastery mechanics

---

		14. Miscellaneous Notes

* This quest teaches players that crafting is not only materials, but process
* Encourages attention, memory, and experimentation

---

		15. Quest Closure & Debriefing

	Resolution : 
* Caelan acknowledges the player as a true alchemist.

	Post-Quest Reflection (Caelan)

> "Most learn to mix ingredients. Few learn to listen to them."

