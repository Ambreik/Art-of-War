			Archivist of the Lore Archives — Archivist Thalen

		Overview

	"Archivist Thalen" is the senior librarian of the "Great Library", entrusted with preserving and organizing the historical memory of the realm. He is a living 
index of ancient wars, pantheons, forgotten treaties, and the evolution of the "Capital City". Players seeking knowledge, context, or lore clarification will often 
be directed to him.
	
	He functions as a lore exposition NPC, a knowledge checkpoint, and a narrative anchor for players who explore the world’s history.

---

		Appearance

	An elderly man with thin silver hair pulled back neatly, wearing layered scholar robes adorned with faded insignias of old kingdoms. He carries scrolls tucked 
under one arm and wears small crystal lenses over his eyes for reading. Ink stains mark his fingers permanently.

---

		Personality

	Calm, patient, and deeply thoughtful. Speaks slowly and precisely. Shows visible excitement when someone asks about history or forgotten events. Dislikes loud 
voices and interruptions.

---

		Behaviour

* Walks slowly between archive shelves and reading desks.
* Occasionally rearranges scrolls and books.
* Adjusts his lenses when speaking to players.
* Reacts strongly to disorder, shouting, or violence in the library.
* If disturbances occur, he signals the Guardian at the entrance immediately.

---

		Role

* Lore exposition
* Historical dialogue trees
* Knowledge verification NPC
* World-building narrative device
* Context provider for quests, zones, and factions

---

		Mechanics

* Uses dialogue trees tied to :
	* Player level
	* Zones discovered
	* Factions encountered
	* Major world events completed
* Provides contextual historical explanations about :
	* Pantheons
	* Ancient wars
	* Capital City founding
	* Outland Territories
	* Legendary figures
* If the player has high "Citizen Standing Recognition", he shares rare historical insights not available to others.
* Reacts to :
	* Gray Zone activity nearby (becomes nervous, ends dialogue early)
	* Crowd density (asks player to speak quietly)
	* Guard alerts (stops interaction)

---

		Interaction

	Players can ask him about :
* History of regions
* Meaning of ruins or monuments they discovered
* Old factions and fallen kingdoms
* Legendary characters referenced in quests
* Origins of certain professions or classes

	He never gives items, quests, or rewards — only knowledge.

---

		Quotes (general)

* "History is not written in ink… it is written in consequence."
* "You seek answers. Most seek power. You are already different."
* "Every ruin you walk upon once had a banner flying proudly."
* "Careful with that scroll. It is older than this city."
* "The past always explains the present, if you know where to look."

---

		Quotes (reactive)

	During noise or combat : 
* "This is a sanctuary of thought! Take your chaos outside!"
* "Guardian! Restore order at once!"

	During Gray Zone tension : 
* "Something feels… off. These halls have seen such omens before."
* "I have read about times like this. They never ended peacefully."

	High Citizen Standing player : 
* "Ah… you are known in this city. Then perhaps you are ready to hear truths few are told."

	Low standing / suspicious player : 
* "Knowledge is not for reckless minds. Return when you value it."

---

		Notes

	"Archivist Thalen" is a core narrative NPC of the "Great Library".
	He is designed to make the world feel deep, ancient, and interconnected through dialogue rather than quests or rewards.
