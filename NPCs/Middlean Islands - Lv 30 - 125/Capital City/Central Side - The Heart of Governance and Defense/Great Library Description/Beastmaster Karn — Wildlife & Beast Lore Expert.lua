			Beastmaster Karn — Wildlife & Beast Lore Expert

		Overview

	"Beastmaster Karn" curates the Great Library’s collection of wildlife studies, monster behavior records, and regional creature documentation. His work focuses 
	on understanding how beasts think, move, hunt, migrate, and react to environmental or world disturbances.

	He turns creature encounters into predictable knowledge rather than random danger.

---

		Appearance

	A rugged man wearing reinforced leather gear marked by claw scratches and old bite marks. Several small bones, teeth, and creature tags hang from cords at his 
belt. His table is filled with anatomical sketches, fur samples, and preserved claws.

---

		Personality

	Grounded, practical, and experienced. Speaks plainly. Has little tolerance for romanticized views of monsters.Treats beasts as animals with patterns, not myths.

---

		Behaviour

* Studies anatomical drawings and creature behavior charts.
* Compares tracks sketched on parchment.
* Sorts fur, scale, and claw samples into labeled containers.
* Occasionally sharpens a hunting knife while thinking.

---

		Role

* Creature behavior specialist
* Wildlife migration analyst
* Monster documentation authority
* Practical knowledge source for dealing with beasts

---

		Mechanics

* Dialogue adapts based on :
	* Regions the player has visited
	* Known creature-heavy areas
	* Recent monster activity (via Scout Lira’s reports)
* Explains :
	* Why certain creatures appear in certain zones
	* How monsters react to disturbances and Gray Zones
	* Behavioral patterns of dangerous wildlife
* Recognizes players who frequently hunt or explore wild regions.

---

		Interaction

	Players can ask about :
* Creature habits and territories
* Dangerous wildlife regions
* How monsters react to environmental change
* Differences between wildlife, beasts, and rare creatures

	He provides practical beast knowledge, not myths or legends.

---

		Quotes (general)

* "Beasts don’t act without reason. People just fail to see it."
* "If you know how it hunts, you know how to survive it."
* "Most creatures avoid people. The dangerous ones don’t."
* "Migration always means something disturbed their home."
* "Monsters are predictable. Fear makes them seem otherwise."

---

		Quotes (reactive)

	During disruption : 
* "Noise like this agitates even distant creatures."
* "This kind of unrest makes beasts move closer to settlements."

	During Gray Zone tension : 
* "You’ll start seeing creatures here that shouldn’t be here."
* "Their territories are shifting. That is never a good sign."

	High Citizen Standing player :
* "You look like you’ve faced beasts and lived. That earns respect."

	Low standing / suspicious player :
* "You don’t look like you’d last long outside the walls."

---

		Notes

	"Beastmaster Karn" completes the creature intelligence branch of the Great Library:

* Quinlan = rare & legendary creatures
* Karn = wildlife and monster behavior
* Lira = sightings and movement
* Elda = terrain where they live
