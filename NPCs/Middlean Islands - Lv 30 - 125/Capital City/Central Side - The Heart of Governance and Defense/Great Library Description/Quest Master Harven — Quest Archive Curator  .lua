			Quest Master Harven — Quest Archive Curator  

		Overview

	"Quest Master Harven" oversees the "Quest Archives" section of the "Great Library", where records of active, completed, and unresolved world quests are 
documented and categorized.

	He does not assign quests directly, but serves as a navigation and context hub for players seeking direction, progression awareness, or storyline connections.

---

		Appearance

	A middle-aged archivist dressed in layered administrative robes marked with archive seals. He carries a large ledger book bound in dark leather, filled with 
indexed quest summaries, notes, and cross-referenced entries. Ink quills are always tucked behind his ear.

---

		Personality

	Organized, methodical, slightly overwhelmed by the volume of ongoing world activity. Speaks in structured, catalog-like sentences. Prefers clarity and 
categorization over storytelling.

---

	Behaviour

* Continuously updates quest ledger entries.
* Organizes quest information into categorized archive stacks.
* Cross-references player progression with documented events.
* Occasionally reorders entire archive sections when new world events occur.
* Reacts to system instability (Gray Zones / CLAS disruptions) by accelerating archive updates.

---

	Role

* Quest information archive manager
* Progression awareness NPC
* Storyline guidance facilitator
* Indirect quest navigation system

---

	Mechanics

* Tracks :
	* Active world quests (summarized states only)
	* Regional quest chains
	* Historical quest completion records
* Provides contextual guidance, such as :
	* "This region is tied to multiple unresolved events"
	* "This storyline connects to prior campaigns"
* Updates dialogue based on :
	* Player progression level
	* Explored regions
	* Completed major events
* Collaborates indirectly with :
	* General Caelin (war-related quests)
	* Scout Lira (field-driven quest triggers)

---

		Interaction

	Players can ask :

* "What is happening in this region?"
* "Are there unresolved conflicts nearby?"
* "What storylines connect to this area?"
* "What major events have I influenced?"

	He provides structured summaries, not quest assignment or rewards.

---

		Quotes (general)

* "Everything happening in the world is recorded here—eventually."
* "This entry is still unresolved… which means the world is still changing."
* "You are not the only one influencing events, just one of the recorded ones."
* "Patterns emerge when enough events overlap."
* "A quest is just history still in motion."

---

		Quotes (reactive)

	During disruption or chaos : 
* "I cannot update records under these conditions!"
* "Events are unfolding faster than they can be documented!"

	During Gray Zone tension : 
* "This region is producing conflicting entries… that is not normal."
* "Some events are no longer matching recorded history."

	High Citizen Standing player : 
* "You are recognized in multiple entries. Your actions are being tracked carefully."

	Low standing / suspicious player : 
* "Your record is incomplete or unstable. Access is limited."

---

		Notes

	Quest Master Harven functions as the world progression indexing system of the "Great Library" :
* He does not create quests
* He does not reward quests
* He organizes reality into readable progression paths

	He connects :
* history (Thalen)
* interpretation (Ionia)
* strategy (Caelin)
* live intelligence (Lira)

	into a structured world-state overview for the player.
