			Cartographer Elda — Regional Map Specialist

		Overview

	"Cartographer Elda" maintains the cartographic archives of the "Great Library" — a vast collection of regional maps, terrain surveys, elevation sketches, sea 
routes, and annotated travel paths gathered over decades.

	She translates geography into strategy, safety, and understanding, making terrain itself a readable source of knowledge.

---

		Appearance

	A meticulous woman dressed in ink-stained scholar robes with measuring tools hanging from her belt. Her station is covered in layered maps, compasses, rulers,
and parchment sheets weighted by stones. Fine spectacles rest on the bridge of her nose.

---

		Personality

	Precise, observant, patient. Speaks carefully and descriptively. Finds comfort in accuracy and detail.

---

		Behaviour

* Carefully redraws sections of maps with updated notes.
* Measures distances using strings and rulers.
* Pins new terrain notes over older maps.
* Studies elevation lines and natural barriers for long periods.

---

		Role

* Geographic intelligence authority
* Terrain and route strategist
* Keeper of cartographic records
* Environmental awareness guide

---

		Mechanics

* Dialogue adapts based on :
	* Regions the player has explored
	* Dangerous terrain areas (cliffs, swamps, dense forests, sea routes)
	* Known Gray Zones affecting travel safety
* Provides context such as :
	* Safe travel paths
	* Natural choke points and defensive terrain
	* Environmental hazards
* Works conceptually alongside :
	* Scout Lira (movement reports)
	* General Caelin (terrain-based strategy)

---

		Interaction

	Players can ask about :
* Terrain difficulty and safe paths
* Geographic advantages and disadvantages of regions
* Natural barriers and defensive locations
* Sea routes, land bridges, and wilderness passages

	She provides terrain-based intelligence, not lore or events.

---

		Quotes (general)

* "The land tells you where you are allowed to go."
* "Mountains decide wars long before soldiers arrive."
* "If you know the terrain, you control the journey."
* "This path looks short on paper. It is not."
* "Maps are promises. Terrain is reality."

---

		Quotes (reactive)

	During disruption : 
* "Movement becomes unpredictable when people ignore geography."
* "Panic never follows safe routes."

	During Gray Zone tension : 
* "These areas become traps when the city grows unstable."
* "Routes that were safe yesterday are no longer safe today."

	High Citizen Standing player : 
* "You seem like someone who respects the land. That is rare."

	Low standing / suspicious player : 
* "You would get lost even with this map."

---

		Notes

	"Cartographer Elda" anchors the physical reality of the "Great Library" knowledge system :
* Thalen = history
* Ionia = meaning
* Caelin = strategy
* Lira = live intelligence
* Harven = progression tracking
* Quinlan = exploration danger
* Elda = terrain and geography intelligence
