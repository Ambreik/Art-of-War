			Senior Scribe — Scribe Ionia

		Overview

	"Scribe Ionia" is responsible for interpreting the oldest texts stored within the "Great Library" — myths, prophecies, fragmented manuscripts, and accounts of 
legendary heroes and forgotten battles. Where Archivist Thalen preserves history, Ionia deciphers meaning from it.

	She serves as a lore cross-reference NPC, connecting myths to real places, prophecies to current events, and legends to living factions.

---

		Appearance

	A young woman with long dark hair braided over one shoulder. She wears light scholar garments reinforced with leather straps holding parchment rolls, ink vials,
and charcoal sticks. Her fingers are constantly smudged with ink. Her eyes move quickly when reading, as if scanning multiple lines at once.

---

		Personality

	Highly intelligent, curious, slightly obsessive. Speaks quickly when excited about a discovery. Often lost in thought. Less patient than Thalen but far more 
energetic.

---

		Behaviour

* Sits at large desks covered in scrolls and fragmented pages.
* Frequently compares multiple texts at once.
* Murmurs to herself while reading.
* Occasionally rushes to shelves to pull additional references.
* Becomes irritated if interrupted during analysis.

---

		Role

* Myth and prophecy interpreter
* Legendary hero and battle historian
* Lore cross-referencing NPC
* Foreshadowing device for future content and events

---

		Mechanics

* Dialogue changes based on :
	* Regions the player has explored
	* Dungeons or ruins discovered
	* World events completed
* Can connect :
	* Myths to real map locations
	* Old prophecies to present-day factions or threats
	* Legendary heroes to current class archetypes
* With high "Citizen Standing Recognition", she reveals hidden interpretations and speculative theories.
* Reacts to Gray Zone tension by becoming distracted and anxious.
* Stops dialogue if disturbances occur, calling for silence.

---

		Interaction

	Players can ask about :
* Meaning of strange symbols or inscriptions they found
* Prophecies related to zones or bosses
* Legends tied to specific classes or professions
* Historical battles and the heroes who fought them

	She provides interpretation, not raw history.

---

		Quotes (general)

* "This text contradicts three others… which means it might be true."
* "Myths are just history told by survivors."
* "You would be surprised how many legends are poorly translated."
* "The margins often contain more truth than the text itself."
* "Wait… say that again. That matches a passage I read!"

---

		Quotes (reactive)

	During noise or combat : 
* "I cannot think with this racket!"
* "Please! Quiet! These texts demand focus!"

	During Gray Zone tension : 
* "I have read about times like this in prophetic scripts… I don’t like the parallels."
* "Some prophecies are not meant to be understood before they happen."

	High Citizen Standing player : 
* "If you are trusted in this city, then perhaps I can share an interpretation few would understand."

	Low standing / suspicious player : 
* "These texts are fragile. Reckless minds tend to damage fragile things."

---

		Notes

	Scribe Ionia complements Archivist Thalen :
* Thalen explains what happened
* Ionia explores what it means and what it may lead to
