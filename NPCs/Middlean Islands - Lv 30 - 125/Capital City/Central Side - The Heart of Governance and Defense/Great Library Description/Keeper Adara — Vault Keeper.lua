			Keeper Adara — Vault Keeper

---

		Overview

	"Keeper Adara" is entrusted with the oversight of the secured vault chambers beneath the Great Library. These vaults contain rare artifacts, restricted tomes, 
relic fragments, and items deemed too dangerous, too valuable, or too historically significant to be publicly accessible.

	She does not grant access or distribute items. She provides contextual understanding of what is kept, why it is kept, and the consequences surrounding such 
artifacts.

---

		Appearance

	A composed woman in dark, formal keeper robes marked with subtle sigils of authority. A ring of heavy iron keys rests at her waist. Her posture is perfectly 
straight, and her expression rarely changes. A faint metallic echo follows her steps from the vault corridor behind her.

---

		Personality

	Reserved, disciplined, and highly observant. Speaks carefully and chooses words with precision. Values responsibility above curiosity.

---

		Behaviour

* Stands near the secured vault entrance at all times.
* Occasionally checks and rechecks vault seals and locks.
* Reviews a small ledger listing vault contents by category, not detail.
* Watches people more than she speaks to them.

---

		Role

* Vault oversight authority
* Artifact context provider
* Restricted knowledge guardian
* Risk awareness NPC

---

		Mechanics

* Dialogue adapts based on :
	* Player Citizen Standing
	* Player reputation and behavior in the city
* Provides high-level information about :
	* Types of artifacts stored
	* Historical consequences of certain relics
	* Why access is restricted
* Becomes more guarded during Gray Zone instability or city disturbances.
* Guards and Guardians treat her area as high-priority patrol zone.

---

		Interaction

	Players can ask about :
* Rare artifacts and relics (context only)
* Why certain knowledge or items are restricted
* Historical incidents related to dangerous artifacts
* The purpose of the vault chambers

	She provides awareness, not access.

---

		Quotes (general)

* "Some knowledge must be preserved. Some must be contained."
* "Curiosity is not a key to these doors."
* "Everything here has a history written in consequences."
* "We guard these vaults not from thieves, but from mistakes."
* "The most dangerous objects are the ones that appear harmless."

---

		Quotes (reactive)

	During disruption : 
* "If the city grows unstable, this becomes the most dangerous place in it."
* "I will not allow panic near the vaults."

	During Gray Zone tension : 
* "Instability makes people seek power they do not understand."
* "These vaults become more tempting when fear spreads."

	High Citizen Standing player : 
* "You are recognized as responsible. That matters here."

	Low standing / suspicious player : 
* "You should not linger near this corridor."

---

		Notes

	"Keeper Adara" represents the controlled danger aspect of the "Great Library" :

* Thalen = preserved history
* Ionia = interpreted lore
* Caelin = war knowledge
* Quinlan & Karn = creatures
* Elda = terrain
* Adara = dangerous artifacts and restricted relics
