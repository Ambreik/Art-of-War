			Scout Lira — Scout - Field Report Analyst  

		Overview

	"Scout Lira" is responsible for collecting, verifying, and updating field intelligence reports within the "Great Library’s Campaign Halls". She works directly 
under the strategic framework overseen by General Caelin, translating raw field data into structured situational awareness.

	She functions as a live intelligence relay NPC, connecting exploration, regional danger, and enemy movement into readable, actionable context.

---

		Appearance

	A practical field operative dressed in lightweight scout gear reinforced for travel and survival. She wears a short cloak, utility straps, and carries rolled 
field maps and report scrolls. Her boots are worn from constant movement. A small compass pendant hangs around her neck.

---

		Personality

	Focused, alert, and direct. Speaks quickly and efficiently. Prefers facts over interpretation. Slightly impatient with theoretical discussions, but highly 
attentive to field data.

---

	Behaviour

* Sorts and pins incoming field reports on map boards.
* Cross-checks sightings from multiple sources.
* Frequently updates battlefield or regional markers.
* Moves quickly between desks and report stations.
* Occasionally leaves the library briefly to “verify reports” through external contacts (lore behavior only, not functional travel mechanic unless expanded later).

---

	Role

* Field intelligence aggregator
* Creature and enemy movement analyst
* Regional threat update NPC
* Tactical support for General Caelin
* Live-world awareness extension of the Great Library

---

	Mechanics

* Updates dialogue based on :
	* Player-discovered regions
	* Active enemy zones
	* Recent world events and CLAS-driven activity spikes
* Provides dynamic intelligence summaries :
	* Enemy sightings
	* Monster migrations
	* Suspicious regional activity
* Collaborates with General Caelin for strategic interpretation
* Reacts strongly to Gray Zone activity with increased urgency in tone
* Becomes temporarily unavailable during major library disruptions (Guard enforcement / anomalies)

---

		Interaction

	Players can ask about :
* Current dangerous regions
* Reported enemy activity
* Monster migration patterns
* Recent sightings near explored zones
* "Safe" vs "unsafe" travel corridors

	She provides real-time informational context, not lore or history.

---

		Quotes (general)

* "Three sightings confirmed near the eastern border within two cycles."
* "This area is no longer stable for travel. Adjust routes accordingly."
* "Reports don’t lie when they overlap this consistently."
* "Movement patterns have changed. That is rarely a good sign."
* "I don’t speculate—I confirm."

---

		Quotes (reactive)

	During noise or disruption : 
* "I can’t verify reports in this chaos!"
* "Clear the area or I lose signal accuracy!"

	During Gray Zone tension : 
* "That region has gone silent… that is not normal."
* "We’ve lost all field reports from that sector."

	High Citizen Standing player : 
* "You’re trusted in the city records. I can share unfiltered field data."

	Low standing / suspicious player : 

* "You are not cleared for current intelligence summaries."

---

		Notes

	"Scout Lira" functions as the real-time awareness layer of the "Great Library" :

* Thalen = history
* Ionia = meaning
* Caelin = strategy
* Lira = **current reality (live field intelligence)**
