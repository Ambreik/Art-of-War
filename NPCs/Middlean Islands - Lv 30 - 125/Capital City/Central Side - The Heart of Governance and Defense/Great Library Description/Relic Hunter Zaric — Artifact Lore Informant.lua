			Relic Hunter Zaric — Artifact Lore Informant

---

		Overview

	"Relic Hunter Zaric" is not a formal scholar of the "Great Library", but an invited contributor whose experience with lost relics, uncanny objects, and 
recovered artifacts has proven too valuable to ignore.

	He provides contextual histories of artifacts found across the world — where they were discovered, what happened around them, and why some objects develop 
reputations that outlive their owners.

---

		Appearance

	A travel-worn figure dressed in layered expedition gear mixed with trinkets and oddities collected from his journeys. Small relic fragments, strange charms, and
unidentified pieces hang from cords across his chest. His hands are rough and scarred from excavation work.

---

		Personality

	Charismatic, observant, slightly mysterious. Speaks in a storytelling tone, but always grounded in personal experience. Enjoys curiosity but respects danger.

---

		Behaviour

* Cleans and examines small relic fragments.
* Sketches objects he has encountered from memory.
* Rearranges strange items laid across his desk.
* Occasionally pauses mid-sentence as if recalling something unpleasant.

---

		Role

* Artifact field-history provider
* Relic contextual storyteller
* Source of knowledge about lost, cursed, or uncanny objects
* Complement to Keeper Adara’s vault knowledge

---

		Mechanics

* Dialogue adapts based on :
	* Player exploration history
	* Regions visited with known relic presence
	* Citizen Standing
* Provides stories about :
	* Where artifacts were found
	* What happened to those who carried them
	* Why certain objects are feared or misunderstood
* Becomes more serious when Gray Zones or disturbances are active.
* Recognizes players who frequently explore dangerous or ancient locations.

---

		Interaction

	Players can ask about :
* Lost relics and strange objects
* Histories of artifacts now stored in the vaults
* Expeditions that ended badly
* Rumors surrounding cursed or legendary items

	He provides experiential artifact knowledge, not academic study.

---

		Quotes (general)

* "Most relics are harmless. The stories around them are not."
* "You can learn a lot from where something was buried."
* "Objects don’t become legendary by accident."
* "I’ve seen men fight over things they didn’t understand."
* "Sometimes the danger is not the relic, but what people believe about it."

---

		Quotes (reactive)

	During disruption : 
* "Instability makes people start looking for power in old places."
* "This is when relic hunters get very busy."

	During Gray Zone tension : 
* "These are the times when forgotten places are disturbed again."
* "I’ve seen this before. People start digging where they shouldn’t."

	High Citizen Standing player : 
* "You look like someone who has walked through ruins and came back wiser."

	Low standing / suspicious player : 
* "Relics have a way of finding people who shouldn’t carry them."

---

		Notes

	"Relic Hunter Zaric" complements "Keeper Adara" :
* Adara = guarded vault knowledge
* Zaric = field experience and artifact history

	He completes the artifact knowledge branch of the "Great Library NPC" network.
