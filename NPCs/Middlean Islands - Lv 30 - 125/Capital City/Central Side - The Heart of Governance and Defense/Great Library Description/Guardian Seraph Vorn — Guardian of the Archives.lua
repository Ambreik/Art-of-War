			Guardian Seraph Vorn

		Overview

	"Guardian Seraph Vorn" is permanently stationed at the entrance of the Great Library. His duty is to enforce silence, prevent disorder, and ensure that no armed
conflict or disruptive behavior enters the halls of knowledge.

	He serves as the first line of enforcement for the Library’s non-combatant rules and is tightly integrated with the city’s Guardian systems.

---

		Appearance

	A heavily armored Guardian in polished city-regalia armor marked with the sigil of "Capital City" authority. His helmet remains on at all times. A long halberd 
rests planted beside him. His stance is immovable and disciplined, facing the entrance doors.

---

		Personality

	Silent, authoritative, and intimidating. Speaks only when necessary. Every word carries the weight of enforcement.

---

		Behaviour

* Stands fixed at the library entrance without wandering.
* Watches every individual entering or leaving.
* Slightly shifts stance when someone approaches with visible weapons.
* Immediately reacts to loud disturbances, running, or aggressive movement.

---

		Role

* Entrance enforcement Guardian
* Silence and order regulator
* Non-combatant rule enforcer
* First responder for disturbances at the Library

---

		Mechanics

	Integrated directly with :

* "CLAS" (Capital Life & Activity System) — reacts to crowd agitation, panic, or suspicious behavior.
* "Gray Zones System" — becomes more alert and restrictive during instability.
* "Guard Shift Rotation System" — remains fixed, but coordinates with patrolling guards.
* "Citizen Standing Recognition" — tone and tolerance change based on player standing.

	Capabilities :
* Stops players with weapons drawn from entering.
* Issues warnings for running, shouting, or disruptive actions.
* Calls nearby Guards if violence, theft, or chaos occurs.
* Temporarily restricts entry during major city disturbances.

---

		Interaction

	Players interacting with him receive short, authoritative responses regarding :
* Library rules
* Conduct expectations
* Access during unstable conditions

	He does not engage in conversation beyond enforcement.

---

		Quotes (general)

* "Weapons remain lowered inside."
* "Silence is mandatory beyond this point."
* "Order is not optional here."
* "Proceed calmly or do not proceed at all."

---

		Quotes (reactive)

	Player approaches with weapon drawn : 
* "Lower your weapon. Now."
* "You do not enter armed."

	Running / disruptive movement : 
* "Walk. This is a place of knowledge, not panic."

	During Gray Zone tension : 
* "Access is restricted. Maintain discipline."
* "The city is unstable. Conduct yourself accordingly."

	Low Citizen Standing : 
* "You are being watched. Do not test the rules."

	High Citizen Standing : 
* "You are trusted. Do not break that trust here."

	Violence nearby : 
* "Guards! Library entrance!"

---

		Notes

	"Guardian Seraph Vorn" is not a roaming guard.
	He is a fixed enforcement anchor for the "Great Library" and a visible symbol that this building is protected by both knowledge and authority.
