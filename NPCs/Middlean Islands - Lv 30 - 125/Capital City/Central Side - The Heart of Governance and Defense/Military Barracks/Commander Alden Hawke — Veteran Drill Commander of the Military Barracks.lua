			Commander Alden Hawke — Veteran Drill Commander of the Military Barracks

---

		Appearance

	Commander Alden Hawke is an aging human veteran whose body still carries the marks of wars long past.
* Tall, broad-shouldered, hardened posture despite his age
* Short iron-grey hair and a trimmed battle-worn beard
* His left hand is heavily scarred by old fire burns, the skin darkened and tightened — a permanent reminder of the "Second Great War"
* Wears reinforced military training armor adapted for command rather than frontline combat

	Over his shoulders hangs a heavy commander’s cape bearing the historic emblem of :

		"Lightbright Shields"

	The legendary human defensive order that stood against the "Primordial Gods" during the "Second Great War".

	The symbol on his cape :
* A radiant tower shield emitting light rays outward
* Representing humanity’s last line of defense during the war

	Unlike active military insignia, this is a historic war emblem, worn out of honor, not rank.

	He carries :
* A command baton used during drills
* A whistle made from old war metal alloy
* A training blade at his side, never drawn for combat — only demonstration

---

		Personality

* Stern, disciplined, and intensely demanding
* Speaks with the authority of someone who has seen the worst of war
* Has little patience for weakness, excuses, or lack of focus
* Deeply cares for recruits but shows it through harsh preparation
* Carries quiet survivor’s guilt for outliving many comrades

---

		Behaviour

* Oversees training routines personally on the Training Grounds of the Barracks
* Walks slowly among recruits correcting posture, stance, and discipline
* Occasionally pauses, staring into the distance as if recalling old battles
* Touches his burned hand unconsciously when discussing war
* Raises his voice sharply when discipline breaks

---

		Role & Purpose

	"Commander Alden Hawke" is responsible for :

* Training new soldiers for campaigns in the Outland Territories
* Preparing recruits mentally and physically for real warfare
* Preserving the combat doctrines learned during the Second Great War
* Instilling discipline, unity, and battlefield awareness

	He represents the living bridge between past legendary wars and future campaigns.

---

		Player Interactions

	Players can interact with him to :
* Learn about the Second Great War and the Heroes who fought in it
* Understand military training philosophy and discipline
* Hear stories of the Lightbright Shields and human resistance
* Receive perspective on what real war looks like compared to adventures

---

		Knowledge Scope

	"Commander Hawke" has deep knowledge of :
* The Second Great War and the Primordial Gods conflict
* The legendary Heroes who fought beside humanity
* Ancient combat doctrines and defensive formations
* Outland campaign expectations and dangers
* The effects and mystery of the "Living Water", which extended his life

---

		Quest Hooks / Quest Relevance

	"Commander Hawke" is ideal for future :
* Military training questlines
* Historical war narrative arcs
* Veteran memory quests or flashback scenarios
* Preparation quests for Outland campaigns

	He may function as :
* Quest starter for military arcs
* Quest mentor for combat trials
* Lore anchor for historic war storytelling

---

		Special Notes

* One of the very few survivors who accepted the "Living Water" and still lives
* Fought alongside the Heroes during the Second Great War
* Wears the Lightbright Shields emblem as a badge of honor, not rank
* Symbolizes living war history inside the Barracks

