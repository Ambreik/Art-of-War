			Sergeant Brina Thornfield — Tactical Patrol Supervisor

---

		Basic Information

* Name : Brina Thornfield
* Title : Tactical Patrol Supervisor
* NPC Type : Core NPC – Military Barracks Officer
* Location : Military Barracks, Central Side – Capital City

---

		Appearance

	"Sergeant Brina Thornfield" is a human female with an athletic, battle-ready posture and a constantly alert gaze.

	She wears standard "Capital City" military patrol armor :
* Reinforced leather and steel hybrid chestpiece for mobility during patrols
* Dark blue-gray military cloak suited for urban and perimeter movement
* Bracers marked with patrol unit engravings indicating route authority
* Utility belt filled with signal flares, report scrolls, and patrol markers

	Her armor is practical, worn, and clearly used in active field duty rather than ceremonial presence.

	She carries :
* A short tactical blade
* A patrol horn for emergency alerts
* A rolled patrol route map attached to her belt

---

		Personality

* Sharp-minded and highly observant
* Direct in communication, wastes no words
* Strong sense of responsibility toward city safety
* Values coordination and timing above brute strength
* Trusts discipline and patterns more than instincts

---

		Behaviour

* Frequently studies patrol maps and guard rotation schedules
* Moves between Barracks and Guardhouse to coordinate patrol coverage
* Briefs guards before they start their shifts
* Updates route markers and checks patrol reports for inconsistencies
* Occasionally sends runners to Commander Hawke with field updates

---

		Role & Purpose

	"Sergeant Thornfield" is responsible for :

* Coordinating all patrol routes originating from the Barracks
* Synchronizing patrol timing with Guard Shift Rotation System
* Ensuring no district of Capital City is left uncovered
* Adjusting patrol paths during Gray Zone alerts or city instability
* Monitoring guard performance during field assignments

	She represents the link between training and real city protection.

---

		Player Interactions

	Players may interact with her to :
* Learn how patrol systems protect the city
* Understand how guards respond to threats and disturbances
* Receive information about safe and unsafe zones during instability
* Gain insight into how city security adapts dynamically

---

		Knowledge Scope

	Sergeant Thornfield knows :
* Patrol routes across all districts
* Guard shift timings and rotation structure
* Gray Zone adjustments and emergency coverage plans
* Recent disturbance patterns across the city
* Coordination between Barracks and Guardhouse

---

		Quest Hooks / Quest Relevance

	Sergeant Thornfield is ideal for future :
* Patrol assistance quests
* Guard support missions during city unrest
* Investigation quests involving patrol route anomalies
* Emergency response coordination quests

	She may function as :
* Quest starter for patrol-related activities
* Quest checkpoint for guard cooperation tasks

---

		Special Notes
* Active field coordinator, not a desk officer
* Constantly interacts with Guard Shift Rotation mechanics
* Important NPC for explaining how the city stays protected in motion

