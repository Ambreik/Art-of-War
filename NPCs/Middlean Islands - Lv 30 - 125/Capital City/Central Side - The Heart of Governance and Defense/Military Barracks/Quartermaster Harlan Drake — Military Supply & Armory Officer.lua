			Quartermaster Harlan Drake — Military Supply & Armory Officer

---

		Basic Information

* Name : Harlan Drake
* Title : Military Supply & Armory Officer
* NPC Type : Core NPC – Military Logistics
* Location : Military Barracks, Central Side – Capital City

---

		Appearance

	"Harlan Drake" is a sturdy middle-aged human male with broad shoulders and thick forearms shaped by years of lifting crates, armor, and weapon racks rather than
wielding them in battle.

	He wears :
* Reinforced military leather apron over a standard guard uniform
* Heavy gloves stained with oil, metal dust, and ink from inventory logs
* A ring of iron keys attached to his belt, constantly clinking as he moves
* Spectacles resting low on his nose for reading supply manifests

	His station is surrounded by :
* Weapon racks
* Armor stands in various states of repair
* Crates marked with patrol districts and unit numbers
* Supply ledgers stacked in meticulous order

---

		Personality
* Methodical and extremely organized
* Practical thinker, values resources and efficiency
* Speaks in measured, no-nonsense sentences
* Dislikes waste and careless handling of equipment
* Respects soldiers who maintain their gear properly

---

		Behaviour

* Constantly updating supply logs and requisition sheets
* Inspecting returned gear for damage or neglect
* Issuing equipment to new recruits and patrol units
* Coordinating with Sergeant Brina Thornfield on patrol equipment needs
* Sending periodic reports to Commander Hawke regarding stock levels

---

		Role & Purpose

	Quartermaster Drake is responsible for :
* Managing all weapons, armor, and field supplies for the Barracks
* Ensuring patrol units are properly equipped before deployment
* Tracking equipment wear and scheduling repairs or replacements
* Distributing specialized gear during Gray Zone alerts
* Maintaining logistical readiness for Outland campaign preparation

	He represents the logistical backbone of the military presence in the city.

---

		Player Interactions

	Players may interact with him to :
* Understand how the military equips and maintains its guards
* Learn about different equipment types used by patrol units
* Gain insight into preparation for campaigns in Outland Territories
* Receive contextual information about military logistics and readiness

---

		Knowledge Scope

	Quartermaster Drake knows :
* Equipment standards for each guard unit type
* Supply flow between Barracks, Guardhouse, and city districts
* Resource shortages and emergency stock protocols
* Preparations being made for future campaigns
* The importance of maintenance discipline among soldiers

---

		Quest Hooks / Quest Relevance

	Quartermaster Drake is ideal for future :
* Equipment delivery or recovery quests
* Repair or resource acquisition missions
* Preparation quests for Outland campaigns
* Investigations into missing or stolen military supplies

	He may function as :
* Quest starter for logistical support missions
* Quest checkpoint for equipment-related objectives

---

		Special Notes

* Non-combatant but critical to military functionality
* Frequently referenced by other guards when speaking about gear and readiness
* Key NPC for explaining how the military sustains long-term operations

