---

	Special Notes : 

* These NPCs are designed purely for environmental immersion.
* They are not quest givers and do not provide gameplay systems directly.
* Minimal interaction by design to avoid cluttering the Barracks experience.
* Their purpose is to make the Military Barracks feel operational, disciplined, and alive.
* They reinforce the atmosphere of a constantly active military training facility preparing for Outland campaigns.
