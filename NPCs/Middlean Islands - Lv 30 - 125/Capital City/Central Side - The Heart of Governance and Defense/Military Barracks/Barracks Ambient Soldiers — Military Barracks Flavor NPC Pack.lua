		Barracks Ambient Soldiers — Military Barracks Flavor NPC Pack

---

	Basic Information

* NPC Type : Ambient Flavor NPC Pack
* Location : Military Barracks, Central Side – Capital City
* Interaction Type : Minimal / Non-Interactive
* Combat Status : Non-Hostile
* Purpose : Environmental immersion and military atmosphere

---

		Included Ambient NPCs

---

	1. Training Archers

	Appearance : Human soldiers wearing lightweight military training armor designed for mobility and ranged practice. Equipped with training bows, quivers, and arm
protection guards. Usually positioned near archery targets within the Barracks yard.

	Personality

Not applicable — ambient NPC.

	Behaviour : Continuously fire arrows toward practice targets, retrieve arrows, and recalibrate stance between shots.

	Role & Purpose : Visual representation of ranged military preparation and discipline training inside the Barracks.

	Quotes : 

* "Steady…"
* "Loose."
* "Again."

---

	2. Shield Formation Trainees

	Appearance : Groups of heavily armored recruits carrying reinforced practice shields and blunt training weapons. Their armor is visibly worn from repeated 
drills.

	Personality 

Not applicable — ambient NPC.

	Behaviour : Practice formation movements, shield wall positioning, and synchronized defensive drills under military cadence.

	Role & Purpose : 
Represents defensive formation training and battlefield coordination exercises.

	Quotes : 

* "Hold formation!"
* "Forward!"
* "Brace!"

---

	3. Running Recruits

	Appearance : Young soldiers in lighter training gear, often sweating and visibly exhausted from repeated physical exercises around the Barracks yard.

	Personality

Not applicable — ambient NPC.

	Behaviour : Run repeated laps around the training grounds carrying weighted packs or wooden training weapons.

	Role & Purpose : Represents endurance training and physical conditioning for military readiness.

	Quotes : 

* "Keep moving…"
* "Don’t stop…"
* "Almost there…"

---

	4. Weapon Maintenance Soldiers

	Appearance : Military personnel stationed near weapon racks, sharpening stones, oil tables, and sword buckets. Their gloves and aprons are stained with metal 
dust and weapon oil.

	Personality

Not applicable — ambient NPC.

	Behaviour : Sharpen blades, clean armor pieces, organize weapon racks, and inspect damaged training equipment.

	Role & Purpose : Represents ongoing military maintenance operations required to sustain Barracks readiness.

	Quotes : 

* "Rust never sleeps."
* "Needs sharpening."
* "Careful with that blade."

---

	5. Armor Repair Assistants

	Appearance : Support soldiers wearing reinforced leather aprons over simplified military attire, carrying repair tools and small armor components.

	Personality

Not applicable — ambient NPC.

	Behaviour : Hammer dents from armor pieces, replace straps, and transport repaired gear between stations.

	Role & Purpose : Visual support layer for the military logistics and repair infrastructure of the "Barracks".

	Quotes : 

* "Hold still."
* "That’ll last."
* "Next piece."

---

	6. Supply Carriers

	Appearance : Strong-built military workers carrying crates of arrows, weapons, food supplies, and armor between the Barracks storage areas.

	Personality

Not applicable — ambient NPC.

	Behaviour : Move continuously between supply depot sections and training grounds.

