			Court Clerk Elira Voss — Judicial Records Administrator of Judgment Hall

---

		Appearance

	"Court Clerk Elira Voss" is a human female with a precise, orderly appearance that reflects her administrative role within the Judgment Hall.

	She wears a formal "Judicial Records Uniform", consisting of :
* A structured dark-gray robe with thin crimson lining (signifying legal authority support role)
* A fitted inner vest reinforced with light protective material
* A high-collared undershirt with the Capital City administrative seal embossed near the throat

	On her back is the official military insignia of "Capital City" :

		Military Insignia — "The Unified Crest of Dominion"

* Central upright spear (law enforcement authority)
* Interwoven wings (unity of governance and enforcement)
* Segmented circular chain (order, containment, legal structure)

	Her version of the insignia is smaller and silver-toned*, indicating administrative/legal support rank rather than enforcement authority.

	She carries :
* A multi-layered judicial ledger system (bound documents + coded records)
* Ink stamps for verdict validation
* Archive scroll tubes tied to her belt
* A small communication slate linked directly to Guardhouse and Magistrate systems

---

		Personality

* Highly organized and detail-oriented
* Emotionally neutral in professional context
* Efficient, precise, and structured in communication
* Deep respect for legal process and hierarchy
* Slightly overwhelmed during high-volume case surges (CLAS spikes / city unrest)

	She is not emotional in judgment — only in accuracy.

---

		Behaviour

* Continuously records incoming legal reports from the Guardhouse
* Cross-references citizen records with CLAS activity logs
* Updates bounty classification statuses in real-time
* Maintains strict categorization of all legal cases
* Coordinates silently with Magistrate Valerion Kade’s rulings
* Occasionally pauses to recheck inconsistencies in reports before validation

She never improvises — everything is processed through structured system logic.

---

		Role & Purpose

	"Court Clerk Elira Voss" serves as the judicial data backbone of "Judgment Hall" .

	She is responsible for :
* Logging all criminal reports from Guardhouse systems
* Maintaining official legal case records
* Updating bounty statuses and escalation tiers
* Synchronizing Citizen Standing Recognition data with legal outcomes
* Ensuring consistency between enforcement, tracking, and judgment systems

	She is effectively the memory of the legal system.

---

		Player Interactions

	Players can interact with her for :
* Viewing legal case summaries (high-level only)
* Checking bounty status updates
* Understanding why certain judgments or escalations occurred
* Confirming recorded criminal activity tied to their name
* Receiving structured explanations of legal outcomes

	She does NOT :
* Make decisions
* Offer quests
* Interpret law or provide opinions

---

		Knowledge Scope

	"Elira Voss" has access to :
* Full Guardhouse criminal report feeds
* CLAS incident logs tied to legal classifications
* Bounty progression and escalation data
* Citizen Standing Recognition system outputs
* Judicial rulings issued by the Magistrate

	She understands the system of law, not its philosophy.

---

		Quest Hooks / Quest Relevance

	"Court Clerk Elira Voss" is a system support NPC, not a quest giver.

	She may be involved in :
* Bounty status verification chains
* Criminal record investigation arcs
* Legal consequence tracking quests
* System audit or corruption detection storylines (future expansion potential)

	She functions as :
* Information validation node
* Legal record checkpoint
* System transparency interface

