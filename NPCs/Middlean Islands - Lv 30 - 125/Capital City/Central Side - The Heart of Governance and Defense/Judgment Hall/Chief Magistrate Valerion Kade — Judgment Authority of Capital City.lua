			Chief Magistrate Valerion Kade — Judgment Authority of Capital City

---

		Appearance

	"Chief Magistrate Valerion Kade" is a human male with an imposing, rigid presence that immediately conveys authority without the need for movement or speech.

	He wears the formal "Judgment Hall" judicial regalia, a layered black-and-crimson robe reinforced with subtle armored lining beneath the fabric. The robe is 
embroidered with the "Capital City Military Authority" insignia on the back :

		Military Insignia — "The Unified Crest of Dominion"

* A central upright spear (authority and final judgment)
* Two interwoven wings (unity under law)
* A segmented circular chain (order, containment, and consequence)

	Unlike field officers, his insignia is burnished gold and crimson, symbolizing judicial finality rather than active enforcement.

	He carries :	
* A heavy sealed judgment ledger bound in black leather
* A ceremonial gavel-like authority seal used to finalize rulings
* Thin metallic reading lenses for legal document inspection

	He does not appear armed — because within his authority, law itself is the weapon.

---

		Personality

* Absolute, disciplined, and emotionally restrained
* Speaks in deliberate, weighted sentences
* Values structure, consequence, and legal consistency above all else
* Shows no favoritism or emotional bias in judgment
* Views chaos as something that must be converted into order through consequence

---

		Behaviour

* Remains seated in a fixed judicial position at all times
* Reviews Guardhouse reports before issuing rulings
* Occasionally pauses for long silence before making decisions
* Writes verdicts directly into the official city record
* Reacts minimally, but his presence immediately silences surrounding NPCs
* Never raises his voice — authority is expressed through certainty, not volume

---

		Role & Purpose

	"Chief Magistrate Valerion Kade" is the final authority of legal consequence in "Capital City".

	He is responsible for :
* Reviewing criminal reports from the Guardhouse
* Approving punishments, fines, or detainment orders
* Validating bounty escalation tiers
* Maintaining judicial consistency across city law enforcement
* Acting as the final layer of the security system hierarchy

---

		Player Interactions

	Players may interact with him for :
* Understanding criminal rulings or punishments
* Reviewing bounty escalation consequences
* Learning legal consequences of actions in the city
* Receiving final judgment explanations for high-tier offenses

	He does NOT :
* Offer quests
* Engage in casual dialogue
* Provide guidance or lore explanations

---

		Knowledge Scope

	He has full awareness of :
* City law enforcement records
* Guardhouse reports and tracking confirmations
* CLAS-based incident history
* Citizen Standing Recognition outcomes
* Bounty escalation logic and criminal classification systems

---

		Quest Hooks / Quest Relevance

