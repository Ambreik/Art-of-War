			High Priestess Elara Grace — Primary Guardian of the Temple of Virtue

---

	Basic Information : 

* Name : Elara Grace
* Title : High Priestess of Virtue
* NPC Type : Core Religious Authority NPC
* Location : Temple of Virtue, Central Side – Capital City

---

	Appearance	

	High Priestess Elara Grace is a serene human woman with an ethereal presence that immediately calms those around her : 
* Long silver hair flowing gently over her shoulders
* Soft, composed facial expression that reflects inner peace
* Piercing blue eyes that convey wisdom and emotional depth
* Flowing white-and-gold ceremonial robes
* Robes are engraved with sacred virtue symbols :
	* Courage
	* Humility
	* Honor
	* Sacrifice
* Subtle luminous accents on her attire give a faint sacred glow inside the temple hall

	She always appears still, composed, and grounded, as if unaffected by external chaos.

---

	Personality : 
* Deeply compassionate and patient
* Speaks with calm certainty rather than authority pressure
* Non-judgmental but morally firm
* Believes guidance is stronger than punishment
* Sees virtue as balance, not perfection

---

	Behaviour : 
* Stationed within the inner sanctum of the Temple of Virtue
* Greets visitors who seek blessings or guidance
* Performs blessing rituals for adventurers before they depart
* Observes visitors silently before speaking, as if reading their emotional state
* Rarely moves quickly; every action is deliberate and controlled

---

	Role & Purpose : 
	
	High Priestess Elara Grace is responsible for :
* Maintaining the spiritual identity of the Temple of Virtue
* Offering divine blessings tied to virtue energy
* Preserving remembrance of fallen heroes of Capital City
* Guiding citizens and adventurers through moral uncertainty
* Acting as a symbolic anchor of peace and reflection in the city

	She represents the spiritual conscience of "Capital City".

---

	Gameplay Function

✔ Provides blessings :
* Luck boost
* Strength boost
* Wisdom boost

❌ Does NOT give quests
❌ Does NOT engage in combat
❌ Does NOT leave the temple

---

	Player Interaction

	Players interacting with her may :
* Receive temporary virtue blessings
* Gain moral or philosophical insight about their journey
* Learn symbolic meaning behind Capital City’s history and sacrifices
* Experience reflective dialogue tied to inner growth

---

	Knowledge Scope

	Elara Grace understands :
* History of Capital City’s defenders and sacrifices
* Meaning of virtue-based relics and symbolism
* Emotional burdens carried by adventurers
* The spiritual significance of sacrifice and protection
* The importance of balance between strength and restraint

