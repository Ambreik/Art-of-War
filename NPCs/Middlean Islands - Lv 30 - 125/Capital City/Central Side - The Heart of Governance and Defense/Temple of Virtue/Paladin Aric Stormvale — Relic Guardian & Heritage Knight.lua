			Paladin Aric Stormvale — Relic Guardian & Heritage Knight

---

	Basic Information

* Name : Aric Stormvale
* Title : Paladin of the Stormvale Lineage
* NPC Type : Core Relic Guardian / Chain-Quest NPC
* Location : Temple of Virtue, Central Side – Capital City

---

	Appearance

	Paladin Aric Stormvale is a tall, physically imposing human male whose presence reflects disciplined strength and inherited responsibility : 
* Muscular, battle-hardened build shaped by years of combat training
* Dark armor reinforced with engraved heritage detailing
* Armor bears a golden hawk crest over a blue field, symbolizing his family lineage
* A worn but well-maintained cloak drapes over his shoulders
* Subtle scars visible on exposed skin, showing past conflicts
* Calm, focused expression with sharp blue eyes reflecting discipline and restraint
* His ancestral weapon is often carried at his side or displayed respectfully within the temple

	Every element of his appearance reflects legacy rather than decoration.

---

	Personality

* Serious, disciplined, and duty-driven
* Deeply respectful toward tradition and legacy
* Speaks rarely, but with purpose and weight
* Holds strong belief in honor, sacrifice, and responsibility
* Carries emotional burden of being the last of his lineage
* Encourages perseverance through action, not words

---

	Behaviour 

* Guards and monitors sacred relics within the Temple of Virtue
* Observes visitors silently before engaging
* Tests players indirectly through tasks rather than dialogue persuasion
* Remains composed even in tense or uncertain situations
* Treats relics as sacred extensions of fallen heroes
* Occasionally studies his ancestral weapon in silence

---

	Role & Purpose

	Paladin Aric Stormvale is responsible for :
* Protecting sacred relics within the Temple of Virtue
* Preserving his family’s heroic legacy
* Guiding players through a structured chain-quest experience
* Teaching values of courage, persistence, and sacrifice through action
* Connecting players to Capital City’s heroic heritage

	He represents the living continuation of ancient heroism.

---

	Gameplay Function : 

✔ Chain Quest NPC

	He provides a structured questline :

	Quest 1 — The Missing Memento : 
* Recover a lost relic from the outskirts of Capital City
* Introduction to relic recovery mechanics

	Quest 2 — Shattered Legacy : 
* Retrieve fragments of a broken heroic shield scattered across the city
* Expands understanding of past defenders

	Quest 3 — The Ancestral Blade : 
* Final trial involving a dangerous encounter outside the city
* Tests player strength and determination

	Final Reward : 
* Title: "Defender of Virtue"
* Replica of ancestral weapon
* Permanent +1 Luck attribute

---

	Player Interaction

	Players interacting with him may :
* Accept and progress through chain quests
* Learn about heroic lineage and past defenders
* Understand relic significance through lived experience rather than explanation
* Be tested for discipline, persistence, and combat readiness
* Receive recognition based on progression through trials

