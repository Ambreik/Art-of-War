			Guardian of Virtue — Temple Entrance Sentinel

---

	Basic Information

* Name : Lucien Ward
* Title : Guardian of Virtue
* NPC Type : Fixed Security Guardian (System NPC)
* Location : Entrance of the Temple of Virtue, Central Side – Capital City

---

	Appearance

	Lucien Ward is a disciplined human guardian stationed at the grand entrance of the "Temple of Virtue" : 
* Tall, rigid posture with strict military alignment
* Clean, reinforced ceremonial guard armor (not combat-heavy, but authoritative)
* White and silver accented uniform symbolizing temple sanctity rather than aggression
* A long guardian cloak marked with the "Capital City" military insignia of unity and protection
* The insignia design :
	* A vertical shield split by a rising light beam
	* Encircled by two symmetric wings representing order and protection
	* Symbolizes: Unity, Discipline, and Civil Protection

* Helmet partially open, revealing a calm but watchful expression
* Carries a ceremonial halberd used for authority enforcement, not execution

---

	Personality

* Calm, disciplined, and unshakably strict
* Speaks minimally and only when required
* Values order above emotion
* Treats the temple as a sacred law-bound zone
* Shows no hostility unless rules are violated
* Absolute respect for temple sanctity and civilian safety

---

	Behaviour

* Stationed permanently at the Temple entrance
* Monitors all incoming and outgoing visitors
* Performs visual inspection of behavior and intent
* Prevents weapon use or hostile actions inside temple grounds
* Calls external guards if escalation occurs
* Remains neutral unless system rules are broken
* Reacts to CLAS / Gray Zone alerts when active

---

	Role & Purpose

	Guardian Lucien Ward is responsible for :

* Enforcing non-violence inside the Temple of Virtue
* Maintaining sacred silence and order within temple grounds
* Preventing theft, aggression, or disruption
* Acting as the first enforcement layer of temple security
* Supporting Capital City’s overall law system integration

	He represents the boundary between the outside world and sacred virtue space.

