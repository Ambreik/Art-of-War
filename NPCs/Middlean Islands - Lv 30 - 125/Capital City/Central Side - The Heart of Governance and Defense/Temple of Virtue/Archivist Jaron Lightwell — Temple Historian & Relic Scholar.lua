			Archivist Jaron Lightwell — Temple Historian & Relic Scholar

---

	Basic Information

* Name : Jaron Lightwell
* Title : Archivist of the Temple of Virtue
* NPC Type : Core Lore / Relic Interpretation NPC
* Location : Temple of Virtue, Central Side – Capital City

---

	Appearance

	Archivist Jaron Lightwell is a middle-aged human scholar with a calm, observant presence shaped by years spent among ancient records and relics : 
* Neatly combed salt-and-pepper hair
* Wire-rimmed glasses that slightly magnify his focused eyes
* Light scholarly robes, simple but elegant, suited for archive work
* Always carries a leather-bound notebook filled with notes, sketches, and observations
* Occasionally ink-stained fingers from constant writing and cataloging
* Often seen surrounded by scroll stacks, relic registers, and historical fragments

	His posture is slightly leaned forward, as if always analyzing something unseen.

---

	Personality : 
* Highly curious and deeply analytical
* Speaks thoughtfully, often pausing to recall details
* Passionate about history, relics, and forgotten narratives
* Easily absorbed into explanations and historical context
* Treats relics as living pieces of history rather than objects
* Respects players who show genuine interest in lore

---

	Behaviour :
* Stationed within the relic archive sections of the Temple of Virtue
* Continuously documents, organizes, and cross-references historical records
* Carefully examines any relic brought to him for analysis
* Becomes animated when discussing heroic figures or ancient events
* Writes notes even during conversations if something important is mentioned
* Maintains strict order of relic catalogues and historical entries

---

	Role & Purpose

	Archivist Jaron Lightwell is responsible for :
* Preserving historical knowledge of Capital City’s heroes and relics
* Cataloging sacred artifacts and their origins
* Providing lore interpretation for discovered relics
* Connecting present-day adventurers with historical events
* Acting as the memory keeper of the Temple of Virtue

	He represents the intellectual and historical foundation of the Temple.

---

	Gameplay Function : 

❌ Does NOT give quests
✔ Provides lore interpretation for relics
✔ Explains historical significance of items
✔ Unlocks deeper narrative context for discovered artifacts

---

	Player Interaction

	layers interacting with him may :

* Present relics for identification and historical explanation
* Learn detailed stories behind legendary artifacts
* Discover connections between relics and ancient heroes
* Gain context for world history and Capital City’s past
* Unlock narrative understanding of quest-related items (indirectly)

---

	Knowledge Scope

	"Jaron Lightwell" has deep knowledge of :
* Capital City’s heroic history and major events
* Legendary relics such as:
	* The Shield of Valor
	* The Amulet of Tranquil Waters
	* The Sword of the Phoenix
	* The Staff of the Starlit Sage
* Ancient wars and defining moments of the city
* Symbolism behind artifacts and their cultural meaning
* Lineage and legacy of heroes connected to relics

