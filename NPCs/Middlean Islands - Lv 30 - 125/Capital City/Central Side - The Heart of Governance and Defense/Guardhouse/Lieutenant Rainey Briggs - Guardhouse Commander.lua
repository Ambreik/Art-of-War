			Lieutenant Rainey Briggs — Guardhouse Commander

---

		Appearance

	Lieutenant Rainey Briggs is a human female of strong, athletic build, standing with disciplined posture that immediately communicates authority.

	She wears the official "Capital City Island Security Officer" uniform, consisting of reinforced dark navy military fabric with silver trim lines that indicate
rank and command status. The armor is light but structured, designed for mobility and authority rather than frontline warfare.

	On her back is the emblem of the "Capital City Military Authority" :

		Military Insignia — "The Unified Crest of Dominion"

	A circular symbol featuring :
* A central upright spear representing enforcement and protection
* Two interlocking wings symbolizing unity between districts and factions
* A surrounding ring of segmented chains forming a perfect circle, representing control, order, and stability

	This emblem visually represents :

> Unity through strength, and strength through structure	

	It is the official symbol of the Capital City military and Guard hierarchy.

	She also wears :
* A command shoulder cape (short, structured, ceremonial)
* A tactical belt with communication devices and sealed warrant scroll cases
* Heavy-duty boots marked with the same insignia etched into the heel plates

---

		Personality	

* Strict, disciplined, and command-oriented
* Values order, structure, and efficiency above all else
* Direct in speech, avoids unnecessary words
* Protective of civilians, but uncompromising toward threats
* Sees chaos as something that must always be controlled, not tolerated

---

		Behaviour

* Stands in a fixed commanding position when inside the Guardhouse
* Constantly monitors reports and guard dispatch activity
* Gives clear, rapid instructions when security situations escalate
* Reacts immediately to signs of disorder or criminal activity reports
* Maintains formal posture even during high-pressure situations
* Observes players carefully before deciding how much information to disclose

---

		Role & Purpose**

	"Lieutenant Rainey Briggs" is the core command authority of the "Guardhouse" and one of the primary military officers of "Capital City" security.

	She is responsible for :
* Guard coordination and patrol assignment
* Criminal threat monitoring
* Bounty system oversight
* Emergency security responses
* Maintaining city-wide stability protocols

---

		Player Interactions

	Players can engage her for :
* Guardhouse operational explanations
* Bounty and criminal activity updates
* Security threat assessments of the city
* Guidance on law enforcement systems
* Reporting dangerous individuals or events

	She does not engage in casual conversation — all dialogue is functional or authoritative.

---

		Knowledge Scope

	She possesses full operational awareness of :
* City security infrastructure
* Patrol routes and guard shifts
* Criminal activity patterns and bounty intelligence
* Emergency containment procedures
* High-level military coordination within Capital City

