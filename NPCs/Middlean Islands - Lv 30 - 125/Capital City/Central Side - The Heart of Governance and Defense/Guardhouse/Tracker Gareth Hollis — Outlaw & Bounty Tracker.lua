			Tracker Gareth Hollis — Outlaw & Bounty Tracker

---

		Appearance

	"Tracker Gareth Hollis" is a human male with a rugged, field-weathered appearance. His body shows signs of long-term tracking work across difficult terrain—lean
muscle, slightly hunched posture from years of scanning ground patterns, and sharp, observant eyes that constantly analyze movement.

	He wears the "Capital City Island Security" field-tracking uniform, which is more practical than ceremonial :
* Dark reinforced leather and cloth mix designed for mobility and outdoor deployment
* Light armored shoulder plating marked with worn tracking insignia
* A long hunter-style cloak used for concealment in field operations
* Multiple utility straps holding tracking tools, sample vials, and marking chalk

	On his back is the official "Capital City Military Authority" insignia :
		Military Insignia — "The Unified Crest of Dominion"

* Central spear (authority and enforcement)
* Interwoven wings (unity of city forces)
* Segmented chain-ring (order and control across regions)

	Unlike ceremonial officers, his version of the insignia is slightly faded from field exposure.

	He carries :
* Tracking dagger (utility tool, not ceremonial)
* Field notebook filled with suspect movement logs
* Rope and marking tools for trail identification

---

		Personality

* Focused, analytical, and highly observant
* Speaks in short, precise statements
* Prefers action and evidence over theory
* Slightly intense when discussing fugitives or tracking patterns
* Deep respect for discipline and coordination within the Guard system

	He treats tracking as both science and instinct.

---

		Behaviour

* Constantly studies footprints, reports, and movement patterns
* Draws tracking lines on maps within the Guardhouse
* Compares multiple reports to identify inconsistencies
* Occasionally leaves the Guardhouse for field verification missions
* Works closely with Lieutenant Briggs for bounty validation
* Reacts strongly to misinformation or false reports

---

		Role & Purpose

	Tracker Gareth Hollis is the primary bounty intelligence and tracking specialist within the "Guardhouse".

	He is responsible for :
* Tracking fugitives and outlaw movement patterns
* Analyzing field reports and witness statements
* Supporting bounty classification and threat assessment
* Teaching tracking logic to approved Guard personnel

	He functions as the bridge between raw field data and actionable pursuit intelligence.

---

		Player Interactions

