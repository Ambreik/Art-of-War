			Corporal Danith Finn — Public Liaison Guard

---

		Appearance

	"Corporal Danith Finn" is a human male of average height and lean build, wearing the standard "Capital City Island Security Guard" uniform, but with lighter 
plating compared to higher-ranking officers.

	His uniform is designed for civil interaction and mobility, rather than combat command. It consists of reinforced navy-blue fabric with silver trimming, marked 
with the official military insignia of "Capital City Security" on his back :

		Military Insignia — "The Unified Crest of Dominion"

	A circular emblem representing :
* A central upright spear (authority and protection)
* Two interwoven wings (unity between districts and people)
* A surrounding segmented chain-ring (order and stability)

	This emblem identifies him as part of the official "City Guard "structure, but not command hierarchy.

	He carries :
* A light patrol baton (non-lethal enforcement tool)
* A city map pouch strapped to his belt
* A small communication device used to contact Guardhouse dispatch
* A soft leather shoulder satchel for notes and citizen reports

	His posture is relaxed compared to higher-ranking officers, making him appear more approachable.

---

		Personality

* Friendly, patient, and approachable
* Calm under pressure, especially with civilians
* Eager to help newcomers understand the city
* Respectful toward authority and higher-ranking officers
* Prefers de-escalation over confrontation

	He represents the human face of law enforcement in the "Capital City".

---

		Behaviour

* Greets newcomers entering the Guardhouse area
* Offers guidance without being asked when confusion is detected
* Observes citizen behavior and redirects them if needed
* Reports suspicious activity to superior officers
* Maintains a calm presence even during tense security situations
* Frequently checks posted notices and patrol updates

---

		Role & Purpose

	"Corporal Danith Finn" serves as the public interface of the "Guardhouse" .

	His responsibilities include :
* Assisting civilians and newcomers with city orientation
* Providing safety instructions and basic legal guidance
* Directing citizens to proper guard or administrative channels
* Acting as a communication bridge between civilians and enforcement units

	He does not make strategic decisions — he ensures clarity, understanding, and order at the citizen level.

---

		Player Interactions

	Players can interact with him for :

* Directions within "Capital City"
* Basic explanations of Guardhouse functions
* Safety guidelines in the city
* Reporting minor disturbances or concerns
* Understanding where to go for law enforcement or bounty issues

	He is often the first NPC new players or visitors will interact with in the "Guardhouse".

---

		Knowledge Scope

	"Corporal Finn" is knowledgeable about :
* City layout and district orientation
* Basic security rules and conduct expectations
* Guardhouse reporting procedures
* Public safety protocols
* Locations of key administrative NPCs within Capital City

	He does NOT have access to classified security data or strategic operations.

---

		Quest Hooks / Quest Relevance

	Corporal Danith Finn is a low-level entry NPC for future systems, including :
* Introductory Guardhouse orientation quests
* Civil assistance tasks (lost persons, delivery guidance, reports)
* Tutorial-style law enforcement introduction chains
* Early bounty system awareness quests (informational only)

	He is designed as a soft entry point into the Guard system narrative, not a quest authority.

---

		Special Notes

* Acts as a civilian-facing liaison for Guardhouse operations
* Represents the approachable layer of Capital City law enforcement
* Bridges gap between civilians and high-ranking officers like Lieutenant Briggs
* Key NPC for onboarding players into the city’s security systems

