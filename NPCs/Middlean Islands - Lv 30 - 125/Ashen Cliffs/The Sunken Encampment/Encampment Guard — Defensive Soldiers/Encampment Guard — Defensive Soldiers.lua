			Encampment Guard — Defensive Soldiers

Location: "The Sunken Encampment"
Faction: "Middlean Vanguard Accord"
Role: Defensive Patrol • PvP Training Opponents • Skillable Combat NPCs • Incursion System Participants

	These soldiers are not quest givers.
	They are part of the living defensive structure of the camp.

	Players may spar with them (PvP flagged training), and they are intentionally very difficult to defeat. Their purpose is to :
* Represent trained military presence from Capital City
* Act as patrol AI for the Incursion Warning System
* Provide realistic combat training for players
* Reinforce the Safe Zone perimeter narratively and mechanically

	They follow individual waypoint patrol routes inside the camp and along the outer perimeter walls and cliff edges.

---

		Section 1 — Soldier Roster

1. "Sergeant Roderic Hale" — Shield Specialist
2. "Corporal Maelis Varn" — Dual Blade Skirmisher
3. "Private Jorren Feld" — Spear and Net Controller

---

		Section 2 — Appearance

	Sergeant Roderic Hale : A tall, broad-shouldered veteran in his early 40s with a thick beard streaked with grey. His armor is heavy, scratched, and reinforced 
with additional steel plating clearly added after multiple battles. A large tower shield rests almost permanently on his arm, marked with faded insignias of past 
campaigns. His helmet hangs from his belt, revealing a scar across his temple. He walks slowly but with immense presence, every step deliberate and grounded.

---

	Corporal Maelis Varn : Lean, agile, and sharp-eyed, Maelis is in her late 20s with dark hair braided tightly behind her head. She wears lighter military armor 
adapted for speed and flexibility, with twin short blades sheathed across her back. Her gear is cleaner than the others’, but shows signs of constant maintenance. 
She moves constantly — pacing, stretching, scanning — like someone who cannot stay still for long.

---

	Private Jorren Feld : Youngest of the three, late 20s, with short blond hair and a calm, observant expression. He carries a long spear and a weighted net rolled
at his waist. His armor is medium-weight, practical, and built for control rather than raw defense. He often leans on his spear while watching the surroundings, 
appearing relaxed but never inattentive.

---

		Section 3 — Personality

	Sergeant Roderic Hale : Roderic is disciplined, quiet, and carries the demeanor of someone who has survived too many battles to waste words. He believes in 
structure, defense, and preparation. When players spar with him, he treats it like a real lesson, not a game. He respects strength and patience, and shows visible 
approval when players fight smart rather than aggressively.

---

	Corporal Maelis Varn : Maelis is sharp-tongued, confident, and enjoys testing players. She sees sparring as entertainment and education combined. Quick to 
comment on player mistakes, she laughs when someone gets disarmed or outmaneuvered. Despite her attitude, she is extremely loyal to the encampment and reacts first 
when incursion warnings trigger.

---

	Private Jorren Feld : Jorren is calm, analytical, and observant. He studies how players fight and adapts during sparring. He prefers disabling opponents rather 
than overpowering them. He gives advice after duels and often explains what the player did wrong in a composed, helpful manner.

---

		Section 4 — Combat & Mechanics

* PvP Flagged : Players may initiate sparring combat
* Very High Difficulty : Designed to be hard to defeat even for experienced players
* Skillable NPCs : Fully functional combat AI
* Waypoint Patrols :
	* Inside camp between tents and supply crates
	* Perimeter patrol along outer walls and cliff edges
	* Move toward gate/perimeter when Incursion Warning triggers
* Combat Styles :
	* Roderic: Defensive tank, shield bashes, stuns, absorbs damage
	* Maelis: Fast attacks, dodges, flanking behavior
	* Jorren: Crowd control, slows, net throws, positional control

