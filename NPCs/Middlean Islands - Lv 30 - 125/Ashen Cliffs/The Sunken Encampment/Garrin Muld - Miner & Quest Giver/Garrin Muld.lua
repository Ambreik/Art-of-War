			Garrin Muld — Veteran of Stone and Salt

---

		1. General Overview

* Name : Garrin Muld
* Role : Profession Trainer (Mining) • Field Task Giver • Environmental Guide
* Faction : Middlean Vanguard Accord
* Location : "The Sunken Encampment" — near stacked ore crates and salvaged ship metal
* NPC Type : Profession Trainer / Skillable Utility NPC
* Map Visibility : Visible within the camp safe zone

	Garrin is not a city trainer relocated to the island.
	He is a working miner, sent with the expedition specifically because the cliffs of the island are rich in unstable ore veins needed for war supplies.

	He is deeply tied to the Dual Profession Training Hub mechanic and the field-based training unlocks around the island.

---

		2. Appearance & Personality

	"Garrin Muld" is a broad, thick-armed man in his mid-50s, built like the rock he’s spent his life breaking. His beard is short and gristled with grey. Coal dust
permanently stains the lines of his hands and the creases of his face.
	He wears reinforced leather mining gear layered with metal patches cut from the wrecked ship. A heavy belt holds chisels, wedges, and two small pickaxes. His 
boots are scarred from cliff work. His helmet is dented and scratched from cave-ins long survived.
	Despite the rugged exterior, Garrin speaks with patience and measured thought. He studies the terrain, listens to the wind against stone, and treats mining as a
discipline — not labor.

	He often taps stones together, listening to their tone.

---

		3. Behavior & World Presence

* Idly inspects rocks or taps ore chunks with tools
* Occasionally wipes dust from his hands onto his trousers
* If monsters approach camp edge during events, he grips his pickaxe defensively
* Faces players directly when speaking, with grounded posture

---

		4. Profession Role — Mining Trainer

	Garrin provides :
* Mining skill training
* Access to island-specific ore knowledge
* Field-based mining tasks tied to nearby cliffs and caves
* A 5-day consecutive mini daily quest line related to ore gathering

	After 5 days, his daily tasks stop until weekly reset or for new players.

	This ties directly into the "Dual Profession Training Hub" mechanic where learning happens in the field, not via menu.

---

		5. Skillable Combat Behavior

	Though not a fighter, Garrin can defend himself.

* Uses mining pick as blunt weapon
* Slow but heavy swings
* Targets creatures threatening camp perimeter or player nearby
* Returns to idle once danger passes

---

		6. Standard Interaction Quotes

> "These cliffs hold more than just stone… watch your back while gathering."
> "Not all veins are easy to break. Some will test your strength."
> "I’ve seen miners lose more than tools out here… keep your wits about you."
> "Stone speaks, if you know how to listen."

---

		7. Situational Quotes

	When Player Returns From Gathering : 

> "Good. You didn’t rush it. That’s how miners live long."
> "You read the vein properly. I can tell."

	If Player Has Low Mining Skill : 

> "You’re swinging like you’re angry. Calm hands break better stone."

	During Incursion Warning : 

> "Bah… always when I find a good vein, trouble follows."

	During Night Tide Cycle : 

> "Hear that? Rock shifts different when the tide pulls hard."

---

		8. Race-Specific Quotes

	Human : 

> "You’ve got the patience for this work. Don’t waste it."

	Vampire : 

> "You move quiet. Good trait in unstable caves."

	Werewolf : 

> "Strength’s good. But don’t let it make you reckless with stone."

---

		9. Environmental Guidance Quotes

	These subtly teach players about island mining dangers.

> "If the stone hums, step back. That’s trapped gas."
> "Green shimmer in the cracks? Leave it. That ore bites back."
> "Loose gravel before a vein means the cliff wants it back."

---

		10. Integration With POI Mechanics

	Garrin directly supports :
* Dual Profession Training Hub
* Field-based mining unlocks
* Bonus yield from island resources
* Encampment life presence
* Incursion reaction flavor

---

	Garrin Muld is not just a trainer.

	He is the man who understands the island’s bones, and teaches players that mining here is not a profession — it is survival through knowledge of stone.
