			Tavia Morn — Quartermaster of the Wreck

---

		1. General Overview

* Name : Tavia Morn
* Role : Vendor • Minor Quest Initiator • Island Survival Informant
* Faction : Independent civilian attached to the "Middlean Vanguard Accord" supply effort
* Location : "The Sunken Encampment" — beside salvaged crates and a makeshift counter built from ship planks
* NPC Type : Vendor / Informational NPC
* Map Marking : "Vendor – Tavia Morn”

	Tavia is not a soldier, nor a scholar, nor a trainer.
	She is the reason the camp functions day to day.
	Everything recovered from wreckage, from crates found across the island, from supplies reclaimed near "Fort Mirath", eventually passes through her hands.

	She is deeply tied to :
* Recovered Supply System
* Early survival for newly arrived players
* Island-exclusive consumables
* Subtle mechanical hints about traps, flora, monsters, and dangers

---

		2. Appearance & Personality

	"Tavia Morn" is a woman in her mid-30s with short brown hair tied back with a leather cord, more for practicality than style. Her leather vest and apron are 
permanently stained with herbal residue, charcoal markings, and faded ink from constant inventory tracking.
	She wears reinforced boots suitable for the rocky, uneven terrain of Ashen Cliffs and carries a wooden staff with a hooked end — used for dragging crates, 
lifting bundles, or steadying herself on slopes.
	Her face is open and warm, but her eyes are always moving — watching the treeline, the cliffs, the sky. She has the alertness of someone who has survived too 
many close calls.

	Tavia speaks like a trader, but thinks like a survivor.

---

		3. Behavior & Presence in Camp

* Rearranges crates, counts items, notes things in her small notebook
* Occasionally inspects recovered supplies brought by players
* Waves at passing players but keeps working while talking
* Moves items under canvas covers when incursion warnings occur
* During tide/night changes, she secures goods nervously

	If Forsaken patrol warnings trigger, she audibly rushes to secure stock.

---

		4. Vendor Role & Item Logic

	Tavia sells :
* Consumables useful specifically on Ashen Cliffs
* Herbal and alchemical helpers sourced via Sereth
* Utility items for exploring cliffs, forests, and caves
* Limited-quantity island goods (per player purchase lock)
* Items only usable after being registered via the "Recovered Supply System"

	Her inventory is partially dynamic depending on player progression in island mechanics.

---

		5. Standard Interaction Quotes

> "Stock up if you’re heading into the forest — you’ll need it."
> "I don’t sell junk. If it’s here, it keeps you alive."
> "Most of this came from wreckage… the sea gives back strange things."
> "If you don’t know what something does, don’t test it far from camp."

---

		6. Situational Quotes

	When Player Returns With Supply Crates : 

> "Good. Very good. Let me log this before anyone touches it."
> "Careful with that one — some crates are trapped by Mirath’s men."

	During Incursion Warning : 

> "Inside! Inside! I’m not losing another shipment to those madmen!"

	During Night / Tide Shift : 

> "I hate this time… the island feels closer when the tide changes."

	When Player Buys Rare Item : 

> "That’s not easy to replace. Use it wisely."

---

		7. Race-Specific Quotes

	Human : 

> "You lot always think you can manage with less. Not here."

	Vampire : 

> "You move quietly. That’ll help more than you think."

	Werewolf : 

> "Your senses will keep you alive… if you trust them."

---

		8. Environmental Hint Quotes (Mechanical Hints)

	These lines subtly teach players about island traps, flora, and dangers.

> "If you see a plant glowing too beautifully, don’t walk toward it."
> "Vines that look like ground? They aren’t always ground."
> "Logs don’t usually snap shut by themselves."
> "If your head starts spinning after stepping on a fungus… run first, think later."

(These reference the secret trap mechanics without exposing them directly.)

---

		9. Minor Quest Hook Role

	Tavia can initiate small, local tasks such as :
* Fetching specific safe herbs for stock
* Recovering a fallen crate from nearby cliffs
* Delivering supplies to Garrin or Sereth
* Identifying decoy vs real supply crates found in the wild

	These quests feed directly into the "Recovered Supply System" mechanic.

---

		10. System Integration

	Tavia Morn is the operational core of :
* Recovered Supply System
* Island survival loop
* Early player preparedness
* Environmental mechanic hinting
* Resource circulation between NPCs

	She is the NPC that makes the island feel logistically alive, not just narratively alive.

---

	Tavia Morn is not important because of power.

	She is important because without her, the camp would collapse within days.
