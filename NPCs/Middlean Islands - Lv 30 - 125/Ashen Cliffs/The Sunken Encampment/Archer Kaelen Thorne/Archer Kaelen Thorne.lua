			Archer Kaelen Thorne — Encampment Field Archer

---

		1. General Overview

* Name : Kaelen Thorne
* Title : Encampment Field Archer
* Role : Quest Sidekick • Deployable Ranged Support • Skillable Combat NPC
* Faction : Middlean Vanguard Accord
* Location : *The Sunken Encampment*, southern shore of Ashen Cliffs island
* NPC Type : Skillable Quest Ally / Environmental Support NPC
* Map Visibility : Appears on map only when player is nearby or when specific mechanics/quests activate

	Kaelen Thorne is not a static NPC. He is a living defensive extension of the encampment. His presence connects the safety of the camp with the dangers outside 
it. Players do not merely talk to him — they experience his support in the field.

	He is the physical embodiment of :
* The "Archer Support Field Mechanic"
* The "Incursion Warning System"
* Parts of the "Narrative Anchor System"

---

		2. Appearance & Personality

	Kaelen is a tall, lean human in his mid-thirties with sun-darkened skin and sharp green eyes constantly scanning his surroundings. His posture is never relaxed;
even when standing still, he looks like a drawn bowstring waiting to release.
	He wears worn leather armor reinforced with small steel studs, optimized for speed rather than protection. A longbow rests across his back, polished by use 
rather than care. His quiver is always full, meticulously organized. A short dagger hangs at his belt for emergencies he clearly hopes never to face.
	His green hooded cloak is torn in several places from branches and blades alike, evidence of prolonged survival in hostile wilderness. Fingerless gloves, light 
boots, and a utility belt full of small pouches give him the look of someone who lives outside walls more than inside them.
	Personality-wise, Kaelen is practical, observant, and direct. He is not unfriendly, but he wastes no words. He respects competence and silently judges 
carelessness. Unlike the Commander, he speaks like a man who has seen the island from the trees, not from a tent.

	He trusts actions more than promises.

---

		3. Core Behavior

	Idle Behavior inside Encampment : 
* Observes tree lines and cliffs rather than people
* Occasionally adjusts bowstring tension
* Walks to the edge of the camp perimeter to scan distance
* Reacts visibly when Incursion System warnings trigger

	Field Behavior (Archer Support Mechanic)
* Kaelen can assist players outside the camp without being formally grouped.

	This happens when :
* Player is within defined perimeter radius of the camp
* Player is fighting Forsaken, wildlife, or island threats
* Specific quests or events are active

	Players may suddenly notice arrows flying from treelines or rocks — that is Kaelen.
	He never fully joins the player as a follower unless a quest requires it. Instead, he acts as cover fire.

---

		4. Skillable Combat Profile

* Skillable : Yes
* Scaling : Scales with player or party average level

	Combat Behavior :
* Targets up to 3 enemies simultaneously
* Prioritizes :
	1. High damage enemies
	2. Enemies targeting the player
	3. Enemies attempting to flee for reinforcements
* Keeps maximum effective bow range
* Switches to dagger only if forced into melee

	Special Shots (low chance per shot) :
* Armor-piercing arrow
* Slowing shot
* 5% chance stun shot
* Occasional "Volley Arrow" for clustered enemies (AoE)

---

		5. Archer Support Field Mechanic (Full Integration)

	Outside the camp, within a large radius :
* Kaelen provides invisible overwatch
* Arrows may come from off-screen angles
* Enemies may be interrupted or slowed without player knowing why at first
* Players learn: "The archer is watching this area."

	This makes the surroundings of the camp feel protected but not safe.

---

		6. Incursion Warning System Integration

	When Forsaken patrol approaches :
* Kaelen is first NPC to react
* He climbs crates, rocks, or tent structures for vantage point
* Fires warning arrows into the ground near players
* Shouts warnings (quotes below)
* Visibly shifts camp into defensive mood

---

		7. Narrative Anchor Integration

	As player progresses Mirath storyline :
* His dialogue changes
* He references events player completed
* Speaks differently if soldier is rescued or still captive
* Shows increasing respect toward the player

