			Sereth Lume — Keeper of Wild Remedies

---

		1. General Overview

* Name : Sereth Lume
* Role : Profession Trainer (Herbalism) • Field Knowledge Instructor • Nature Resource Specialist
* Faction : Middlean Vanguard Accord
* Location : "The Sunken Encampment" — near makeshift herb drying racks and salvaged ship planters
* NPC Type : Profession Trainer / Environmental Utility NPC
* Map Visibility : Always visible within camp safe zone

	"Sereth Lume" is the camp’s living connection to the island’s botanical systems. While others see "Ashen Cliffs" as rock and wreckage, she sees it as a living 
network of survival biology.

	She is directly tied to :
* Dual Profession Training Hub system
* Field-based gathering mechanics
* Bonus yield from nearby island flora
* Recovered Supply System (herbal/alchemy supplies)

---

		2. Appearance & Personality

	"Sereth Lume" is a slender, middle-aged woman with long dark hair threaded with natural silver streaks, not age alone but exposure to strange island flora. Her 
presence is calm, deliberate, and almost rhythmic — as if she moves in sync with invisible currents of nature.
	She wears layered forest-green robes adapted for fieldwork rather than ceremonial use. The robes are reinforced with stitched pockets, herb-binding straps, and 
hanging pouches filled with seeds, dried leaves, and crushed powders. Her belt carries small botanical tools — scissors, pestles, and sealed vials.
	Her hands are stained in soft gradients of green and amber from constant plant handling. A faint scent of crushed herbs, saltwater blooms, and medicinal resin 
surrounds her.

	Unlike Garrin’s grounded physicality, Sereth feels lighter — observant, patient, and attentive to subtle environmental changes. She often pauses mid-sentence as
if listening to something no one else can hear.

---

		3. Behavior & World Presence

* Tends to hanging herb bundles and drying racks
* Inspects soil samples brought from players
* Occasionally kneels to examine ground flora near camp edges
* Reacts subtly to environmental changes (fog, tide shifts, incursion alerts)
* Does not move far from her herbal workspace

---

		4. Profession Role — Herbalism Trainer

	Sereth provides :
* Herbalism skill training
* Identification of unknown island plants
* Crafting knowledge for potions and consumables
* Field-based resource interpretation (what plants are safe or dangerous)
* Minor herbal gathering tasks (non-daily system)

	She does not operate on a strict daily quest loop like Garrin Muld, but instead focuses on adaptive environmental learning.

---

		5. Skillable Combat Behavior

	Sereth is non-combat oriented by nature, but not defenseless.

	When threatened :
* Uses thrown herbal vials (smoke, irritant, calming spores)
* Creates short-duration area denial effects
* Targets enemy vision or movement rather than damage
* Prioritizes escape and control over confrontation

	Her combat style is described as non-lethal botanical disruption.

---

