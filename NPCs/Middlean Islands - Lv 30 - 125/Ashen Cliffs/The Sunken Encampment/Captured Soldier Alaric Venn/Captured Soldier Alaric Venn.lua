			Captured Soldier Alaric Venn — Imprisoned Vanguard

---

		1. General Overview

* Name : Alaric Venn
* Title : Imprisoned Vanguard
* Role : Storyline Quest NPC • Rescue Target • Intel Source (post-rescue)
* Faction : Middlean Vanguard Accord
* Primary Location : Cage inside "Fort Mirath"
* Secondary Location (post-rescue) : The Sunken Encampment
* NPC Type : Captured Soldier / Narrative Progression NPC
* Map Visibility : Hidden until rescue quest is active; appears on minimap only at close range

	"Alaric Venn" is not simply a man to be freed. He is a living narrative bridge between "Fort Mirath" and the "Sunken Encampment". His condition, dialogue, and 
usefulness evolve based on player progression.

	Before rescue, he represents urgency and vulnerability.
	After rescue, he becomes intel, atmosphere, and narrative memory for the camp.

	He is central to:
* The Mirath storyline
* The Archer escort quest phase
* The Narrative Anchor System
* The Captured Soldier Interaction System

---

		2. Appearance & Personality

	Alaric is a young but battle-worn human soldier in his mid-thirties. His short brown hair is matted with sweat and dirt. His Capital City armor is visibly 
damaged — scratched chestplate, bent shoulder guards, straps crudely repaired with rope fibers.
	His wrists are bound, knees bruised from long periods forced to kneel. His face shows exhaustion, but his eyes remain sharp and observant. He constantly studies
his surroundings, calculating chances of survival.
	A rusted short sword still hangs at his side — not taken by his captors, perhaps as mockery. A small, half-torn satchel remains near him, holding remnants of 
field supplies.

	Alaric’s personality is disciplined but shaken. He is not cowardly — he is a soldier who has endured days of psychological pressure. After rescue, he speaks 
like someone who has seen what Mirath is building and cannot forget it.

---

		3. Behavior (Pre-Rescue — Inside Cage)

* Kneels or sits inside crude wooden/rope cage
* Occasionally tries to loosen rope bindings
* Flinches at distant sounds
* Whispers to himself about past battle
* Attempts subtle signals when player approaches

	Pre-Rescue Quotes : 

> "Please… quietly… they mustn’t hear you."
> "Mirath took the others. I don’t know who’s left."
> "If you’re from the Capital… don’t leave me here."
> "They patrol in pairs. Always in pairs…"

---

		4. Rescue Phase Integration (with Archer Kaelen Thorne)

	During the rescue quest :
* Cannot move until cage is opened
* Weak movement speed initially
* Follows player closely
* Archer prioritizes enemies attacking Alaric
* If Alaric takes heavy damage, he stumbles and must be protected briefly

	During Escape Quotes : 

> "I can walk… just don’t let them surround us."
> "I remember this path… they dragged me through here."
> "Almost there… don’t stop now…"

---

		5. Post-Rescue — Behavior at The Sunken Encampment

	Once returned to the camp, Alaric does not become a static NPC.

	He becomes part of :
* Camp atmosphere
* Intel provider
* Dialogue that evolves with player progress

	He is usually seen :
* Sitting near crates or fire
* Speaking with the Commander
* Sharpening his rusted sword slowly
* Watching the sea or treeline silently

---

		6. Captured Soldier Interaction System (Post-Rescue)

	After rescue, players can speak to Alaric repeatedly over time.

	He provides :
* Intel fragments about Mirath
* Hints for future quests
* Emotional weight to the story
* Changes in dialogue based on player progress

---

		7. Dynamic Dialogue Based on Progress

	If Player Has Just Rescued Him : 

> "I owe you my life. I won’t waste the second chance."
> "You don’t know what he’s building in there…"

---

	If Player Has Not Yet Advanced Mirath Questline : 

> "You’ve seen the inside. You know we can’t ignore it."
> "He’s preparing for something bigger than this island."

---

	If Player Progressed Deep into Mirath Story : 

> "Then you know… you’ve seen it yourself."
> "We were too late for many. But not for this."

---

	If Incursion Warning Event Happens : 

> "That pattern… that’s how they moved inside the fort."
> "They’re testing the camp’s defenses."

---

		Race-Specific Quotes : 

	Human Player : 

> "Seeing you here… reminds me what we fight for."

	Vampire Player : 

> "I saw Mirath fear your kind. Use that."

	Werewolf Player : 

> "If you break their lines like you do… they won’t stand long."

---

	Night Time : 

> "Nights were the worst in the cage. They talked about plans…"

---

	Ambient / Emotional : 

> "I still hear the cage door when I close my eyes."
> "Freedom feels strange after ropes."
> "I won’t forget what you did. Ever."

---

		8. Narrative Anchor Role

	Alaric is one of the NPCs whose dialogue changes the most as story progresses.

	He acknowledges :
* Player victories
* Delays
* Incursions
* Mirath developments

	He makes the camp feel like a place that remembers what happened.

---

		9. Interaction Notes

* Non-combat NPC
* Cannot leave camp after rescue
* Acts as living memory of Mirath
* Strengthens emotional connection between Fort and Encampment

