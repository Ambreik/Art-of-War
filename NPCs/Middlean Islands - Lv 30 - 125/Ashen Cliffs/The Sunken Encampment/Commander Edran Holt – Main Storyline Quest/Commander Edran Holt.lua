			Commander Edran Holt — Field Marshal of the Wreck

---

		1. General Overview

* Name : Commander Edran Holt
* Title : Field Marshal of the Wreck
* Role : Main Storyline Quest Giver • Narrative Anchor • Event Controller
* Faction : Middlean Vanguard Accord
* Location : "The Sunken Encampment"
* NPC Type : Quest Giver / Event NPC / Story Checkpoint Authority
* Map Marking : Golden Exclamation Mark (Storyline)

	"Commander Holt" is the central narrative authority of the island. Every major storyline thread — Mirath, the rescue, the supplies, the incursions, the camp’s 
survival — passes through him.

	He is not a static quest giver.
	He is the living command post of the encampment.

	He directly interfaces with :
* Command Progression Board mechanic
* Narrative Anchor System
* Incursion Warning System
* Recovered Supply System
* Arrival Stabilization acknowledgment
* Dialogue changes based on tide cycle and player progress

---

		2. Appearance & Personality

	Edran Holt is a veteran human in his late 50s. His presence is heavy, authoritative, and calm under pressure. His face is lined with age and campaign scars. His
hair is greying, tied loosely behind his head.
	He wears aged military armor bearing the sigil of the Capital’s army, scratched and salt-stained from sea travel. A dark blue cloak hangs from his shoulders, 
torn at the edges. Strapped across his back is a broken battlefield banner from the Second Great War — not for display, but remembrance.

	A longsword rests at his side, rarely drawn but always maintained.
	He paces near a broken cannon overlooking the sea, often staring toward the horizon or toward the direction of "Fort Mirath" as if he can feel it watching back.
	Holt speaks like a commander, but carries the weight of a man who once fought beside Mirath before the betrayal.

---

		3. Behavior & World Presence

* Paces, stops, observes sea or cliffs
* Occasionally kneels to inspect the broken cannon
* Turns fully toward player when approached
* Reacts to incursion events, tide cycle, and quest progress
* Voice carries authority without shouting

---

		4. Narrative Context

	Holt was dispatched by the Middlean Vanguard Accord to investigate missing scouting units. Privately, he knows the truth: Mirath is alive.
	He fought alongside "Mirath" and "Aric" in the "Second Great War". What the player uncovers on this island is not news to him — it is confirmation of an old 
fear.
	This makes his dialogue deeply reactive to player progression.

---

		5. Dynamic Quotes & Situational Dialogue

	Idle Lines : 

> "Still no word from the scouts… something’s wrong."
> "Mirath’s shadow lingers here. I can feel it."
> "This island remembers war."

---

	When Player First Arrives (Arrival Stabilization recognized) : 

> "Easy. Breathe. The sea disorients even veterans."
> "You’re safe here. For now."

---

	If Player Has Not Progressed Mirath Questline : 

> "You’ve seen the cliffs. You know where this leads."
> "We cannot sit idle while he builds strength."

---

	If Player Advanced Mirath Story : 

> "Then you understand what we’re facing."
> "What you saw in that fort… confirms my worst fears."

---

	During Incursion Warning Event : 

> "Positions! They’re probing the perimeter!"
> "Hold the line! Do not chase them into the trees!"

---

	During Night Tide Cycle : 

> "Nights like this… he used to plan campaigns by torchlight."
> "The dark makes men remember things they wish forgotten."

---

	After Player Rescues Alaric : 

> "You brought one of ours back. That matters."
> "He’s proof we can still take from Mirath, not just lose."

