---

		8. Narrative Anchor Function

	Holt is one of the primary NPCs whose dialogue tree expands as hidden story flags progress.

	He acknowledges :
* Supplies recovered
* Soldier rescued
* Mirath progression
* Incursions
* Tide cycle atmosphere

	He makes the camp feel like an active military foothold, not a refugee site.

---

		9. Interaction Notes

* Non-combat NPC
* Central quest distributor for island storyline
* Tied directly to multiple mechanics of the POI
* Dialogue evolves more than any other NPC in the camp

---

	Commander Edran Holt is not just a quest giver.

	He is the **voice of command**, the memory of the past war, and the man who knows exactly what Mirath used to be — which is why he fears what Mirath has become.
