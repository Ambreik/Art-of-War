		QUEST 13 — FINAL EVENT (FULL MESSAGE)

	"The Siege of The Sunken Encampment"

---

	QUEST TYPE : 
* World Event / Defense Siege / Multi-NPC Survival Event

---

		QUEST TRIGGER

	Automatically activates immediately after player returns from Fort Mirath assassination attempt.

	Commander Edran Holt detects :

> "Forsaken retaliation fleet inbound. This is not pursuit… this is execution."

---

		EVENT STRUCTURE

		Phase 1 — Warning State (30–60 seconds)

* Skybox darkens slightly
* Horn signal from camp triggers
* NPCs move to combat positions :
	* Soldiers take perimeter walls
	* Archer Kaelen moves to high ground
	* Vendor NPC hides (non-combat removal state)
	* Trainers enter defensive stance

---

		Phase 2 — Wave Assault System

	Wave Structure :
* Wave 1: Forsaken Scouts (light infantry)
* Wave 2: Supply Raiders (mixed ranged/melee)
* Wave 3: Elite Commander Unit (mini-boss)
* Wave 4: Combined assault wave

	Each wave :
* scales with player count
* increases aggression per survival time
* triggers environmental destruction effects (visual only, no base destruction state loss)

---

		Phase 3 — Elite Encounter

	Elite Enemy: "Forsaken Reprisal Captain"
* Command aura buffs nearby units
* Calls reinforcements mid-fight
* Attempts to break NPC defensive AI lines

---

		Phase 4 — Encampment Survival State

	If elite reaches 50% HP :
* NPC coordination system activates :
	* Archer Kaelen executes AoE volley support
	* Commander issues global buff:
		* "Hold the line protocol"
	* Soldiers gain temporary defense scaling

---

		Phase 5 — Final Collapse / Victory Condition

	Event ends when :
* Elite is defeated OR retreat condition triggered
* Remaining waves cleared

	Forsaken retreat triggers scripted dialogue :

> "This island still breathes… retreat."

