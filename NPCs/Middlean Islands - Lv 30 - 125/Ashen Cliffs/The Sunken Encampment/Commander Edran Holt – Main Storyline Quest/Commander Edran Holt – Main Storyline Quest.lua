		QUEST 1 — "Ashes Upon Arrival"

* Quest Type : Main Story Intro
* Quest Giver : Commander Edran Holt
* Location : The Sunken Encampment
* Level Range : Entry Story Phase
* Party : Solo or Group

---

		Narrative Overview : 

	The player arrives at the encampment as part of the "Capital City" military expedition sent by the "Middlean Vanguard Accord". The island is unstable, and the 
Forsaken presence is already confirmed in fragments—but not understood.
	"Edran Holt" assigns the player their first field reconnaissance: stabilize the camp perimeter and confirm hostile presence patterns.

---

	Objectives : 
* Secure 3 perimeter observation points
* Eliminate or repel Forsaken scouting creatures
* Report back to "Commander Edran Holt"

---

		Key Mechanic Introduction

* First activation of "Incursion Warning System"
* First exposure to Island hostility scaling (dynamic spawn pressure)

---

	Dialogue Snippet : 

> "You are not here as a soldier of glory. You are here because the island is already watching us."

---

	Reward : 
* Medium EXP
* 5 Gold
* Unlock: Camp Safe Zone Field awareness system (tutorial flag)

