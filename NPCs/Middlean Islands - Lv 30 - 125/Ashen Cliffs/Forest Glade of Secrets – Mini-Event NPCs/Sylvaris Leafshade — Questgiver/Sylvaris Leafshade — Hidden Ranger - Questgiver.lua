			Sylvaris Leafshade — Hidden Ranger

---

		1. Basic Information

* Name : Sylvaris Leafshade
* Race : Human
* Role : Hidden Ranger / Temporary Ally / Quest Giver
* Location : Forest Glade of Secrets — appears only when certain exploration conditions are met
* Status : Ephemeral NPC (event-spawn, not persistent)
* Affiliation : Unknown — operates independently, not tied to dock, army, or settlement

---

		2. Appearance

	Sylvaris is dressed in layered forest leathers dyed in muted greens and browns, almost indistinguishable from the surrounding foliage. A hood of woven leaves 
and cloth shadows most of his face, and thin strips of bark and vine are tied across his shoulders like natural camouflage.
	A longbow rests across his back, crafted from pale wood polished smooth by time. Small pouches filled with herbs, powders, and tools hang from his belt, quietly
clinking when he moves.
	
	His boots are wrapped in moss-lined cloth to silence his steps. When standing still, he is nearly impossible to notice unless he chooses to reveal himself.
	His eyes are sharp, always scanning — never fully at ease.

---

		3. Personality

	Sylvaris is cautious, perceptive, and speaks as someone who has spent far too long alone in dangerous territory.

* Speaks softly, rarely wastes words
* Observes the player before trusting them
* Values balance of nature over human conflicts
* Pragmatic — survival first, explanations later
* Seems to know the glade far better than any map could show

	He is not unfriendly — but trust must be earned in moments, not assumed.

---

		4. Behavior & AI

	Spawn Behavior :
* Does not exist permanently in the world
* Appears partially concealed in dense foliage when player triggers the mini-event area correctly
* If ignored for too long, he silently disappears

	Movement :
* Minimal movement, mostly idle observation
* Occasionally steps between trees, blending with environment
* If combat occurs nearby, he may assist briefly with ranged attacks

	Despawn Conditions :
* Quest completed
* Player leaves the glade radius
* Player dies
* Timer expires

	Combat AI (Support Only) :
* Uses bow attacks from distance
* Targets threats attacking the player
* Never chases enemies far
* Disengages quickly once danger passes

---

		5. Dialogue Interaction (Quotes)

	Greeting (first reveal) :

> "Easy… I’ve been watching you for some time."
> "Not many notice the signs that you did."
> "You walk like someone who listens to the forest."

	If player approaches too fast / runs :

> "Slow your steps. The glade punishes impatience."

	If player has active forest/glade buff :

> "Ah… the forest has already spoken to you."

	If hostile creatures are nearby :

> "Stay behind me. They hunt by movement."

	If player draws weapon immediately :

> "Put that away. If I meant harm, you wouldn’t have seen me."

	If player lingers without interacting :

> "I don’t remain visible for long. Decide."

	When offering help / task context :

> "There are things here that must be done quietly."
> "Predators are not the only danger in this glade."

	If player leaves mid-interaction :

> "And like that… gone. Perhaps for the best."

	Upon quest completion (general tone) :

> "You did well. The forest will remember your steps."

	Before despawning :

> "We may meet again… if you learn to look properly."

---

		6. NPC Mechanics

* Event-spawn NPC tied to Glade mini-events
* Can provide escort, collection, or tracking style tasks (defined later)
* Temporarily assists in combat if needed
* Rewards exploration-type players rather than combat-focused ones
* Exists to make the glade feel alive, watched, and intelligent

---

		7. Additional Notes

	Sylvaris feels less like an NPC and more like another presence of the forest itself — a living extension of the Glade’s awareness.
	Players should feel like they were noticed, not that they found him.
