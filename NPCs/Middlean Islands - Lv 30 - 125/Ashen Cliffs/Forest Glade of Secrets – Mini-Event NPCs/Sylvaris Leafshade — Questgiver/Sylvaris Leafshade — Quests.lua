		Group 2 — Collection Quests (Herb / Monster Component)

---

		Quest 1 — "Glade Blossoms Before the Beasts"

	Quest Giver : "Sylvaris Leafshade"

	Objective : Collect "6 Glade Blossoms" before predators trample them.

	Quest Item : "Glade Blossom" — fragile forest flower found only in shaded patches of the glade.

	What Player Does : 
* Search specific shaded vegetation pockets
* Compete with roaming wildlife that can destroy blossoms if they pass over them
* Careful pathing and awareness required

	Narrative : Sylvaris studies how certain plants survive despite the heavy predator presence. The "Glade Blossoms" only grow where predator paths rarely cross.
He needs fresh samples before they are ruined.

	Environmental Interaction : 
* If a "Thornback Boar" or "Rootfang Lizard" runs over a blossom → it despawns
* Encourages stealth or quick collection

	Completion : Return 6 intact "Glade Blossoms" to Sylvaris.

	Rewards : 
* Experience (exploration / gathering)
* Random minor consumable
* Increased chance Sylvaris appears again later

---

		Quest 2 — "Venom for Study, Not for Death"

	Quest Giver : "Sylvaris Leafshade"

	Objective : Obtain "4 Rootfang Venom Sacs" from "Rootfang Lizards".

	Quest Item : "Rootfang Venom Sac" — drops from Rootfang Lizards near the glade edges and rocky roots.

	What Player Does : 
* Hunt "Rootfang Lizards" in nearby forest edge
* Venom sac has not 100% drop chance
* Requires multiple engagements

	Narrative : Sylvaris suspects the Rootfang venom is used by the lizards not only for hunting but for marking territory. He wants to test this theory.

	Environmental Interaction : 
* Rootfang Lizards attempt to retreat into roots when low HP
* Player must finish them before escape

	Completion : Bring 4 intact venom sacs to Sylvaris.

	Rewards : 
* Experience (combat / ecology)
* Small poison resistance consumable
* Increased chance Sylvaris appears again later

