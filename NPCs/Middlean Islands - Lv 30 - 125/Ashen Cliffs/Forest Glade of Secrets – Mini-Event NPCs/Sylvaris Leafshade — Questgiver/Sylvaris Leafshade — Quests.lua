			Sylvaris Leafshade — Quests 

---

		Group 1 — Escort Quests (Forest Navigation & Safe Travel)

	These quests are given by "Sylvaris Leafshade" when the player encounters him in the "Forest Glade of Secrets".
	They involve traveling between notable locations in "Ashen Cliffs", using stealth and terrain awareness — fitting Sylvaris’ ranger lore.

---

		Quest 1 — "Through the Whispering Paths"

	Quest Giver : "Sylvaris Leafshade"

	Objective : Escort Sylvaris from the "Forest Glade of Secrets" to the "Broken Maw" (Waterfall Split Basin).

	Tasks : 
* Follow Sylvaris without getting too far ahead
* Avoid or navigate past at least three ambush points (Rootfang Lizard, Thornback Boar, Basin Croc Alternative)
* Protect Sylvaris from danger — guards will automatically fire if he gets hit twice

	Narrative : Sylvaris believes that the "Broken Maw" holds evidence of hidden predator corridors that he cannot reach alone due to its unstable terrain. He needs
a trustworthy partner.

	Challenges : 
* Narrow cliffside paths
* Ambush threats (Thornback Boars, Rootfang Lizards) 

	Completion Condition : Reach the "Broken Maw" with Sylvaris alive.

	Rewards : 
* Experience (exploration + combat)
* Minor herb bundle (e.g., Mistveil Fern)

---

		Quest 2 — "Hidden Watcher’s Call"

	Quest Giver : "Sylvaris Leafshade"

	Prerequisite : "Through the Whispering Paths"

	Objective : Escort Sylvaris from the "Broken Maw" to the "Hidden Watcher’s Lair".

	Tasks : 
* Proceed along the cliff edge past Razorwind Hawk nests
* Survive a random Shadowfang Panther ambush near the final gap
* Reach Hidden Watcher’s Lair entrance

	Narrative : Sylvaris believes that the "Watcher’s Lair" contains knowledge of how larger predators track movement in the forest — information rare and vital for
survival. He insists the player provides protection.

	Challenges : 
* Cliffside aerial predators (Cliff Talon Vultures, Razorwind Hawks)
* Occasional cave navigator checks

	Completion Condition : Reach the "Hidden Watcher’s Lair" entrance with Sylvaris alive.

	Rewards : 
* Greater experience
* Rare crafting herb (e.g., Mistveil Fern)
* Minor gear buff as "Equipment Full Repair".

