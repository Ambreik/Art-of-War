		Group 3 — Tracking Quests

---

		Quest 1 — "The Silent Prowler"

	Quest Giver : "Sylvaris Leafshade"

	Objective : Track and locate the "Shadowpaw Panther’s" resting ground without killing it.

	What Player Does : 
The player must follow a trail made of :
* Scratched tree bark
* Faint paw prints in mud
* Half-eaten carcass
* Disturbed bushes

	Each sign appears in sequence. Interacting with the wrong clue resets progress.
	At the final point, the player finds the "Shadowpaw Panther" resting.

	Important : Player must observe, not attack.

	Interact with the environment near the panther to complete.

	Narrative : Sylvaris studies how apex predators move unseen through the forest. He wants confirmation of the panther’s resting cycle, not its death.

	Failure Conditions : 
* Attacking the panther → quest fails
* Losing the trail → must restart

	Completion : Observe the resting ground and return to Sylvaris.

	Rewards : 
* Experience (tracking / awareness)
* Minor stealth-related consumable
* Increased chance Sylvaris appears again later

---

		Quest 2 — "Where the Forest Drinks"

	Quest Giver : "Sylvaris Leafshade"

	Objective : Track a "Glade Stag" to its hidden water source.

	What Player Does : 

Follow environmental signs :
* Broken low branches
* Hoof marks near soft soil
* Droppings
* Rubbed tree trunks (antler marks)

	The trail leads to a hidden freshwater pool deep in foliage.
	The "Glade Stag" appears briefly to drink, then leaves.
	Player must reach the pool before it leaves.

	Narrative : Sylvaris believes this hidden water source explains why certain animals never leave the glade even during dry periods.

	Failure Conditions :
* Too slow → stag leaves → reset
* Aggro nearby creatures and lose focus → reset

	Completion : Discover the hidden pool and report back.

	Rewards : 
* Experience (exploration / tracking)
* Minor stamina-related consumable
* Increased chance Sylvaris appears again later

