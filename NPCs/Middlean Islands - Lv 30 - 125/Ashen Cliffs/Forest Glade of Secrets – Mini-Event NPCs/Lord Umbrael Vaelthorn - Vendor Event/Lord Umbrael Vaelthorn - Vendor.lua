		7. Combat Reaction

	Umbrael does not fight.

	If threatened :
* Emits one ominous resonance line
* Then retreats into mist (despawns)
* Drops no loot
* Will not be trade-accessible until next spawn

	Example:

> "Violence becomes you less than silence."

---

		8. Additional Notes

	Umbrael is not just a vendor — he is a narrative anchor for the "Forest Glade".

	He embodies :
* Mystery
* Balance between reward & effort
* Knowledge beyond surface comprehension

