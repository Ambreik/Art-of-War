			Lord Umbrael Vaelthorn

---

		1. Basic Information

* Name : Lord Umbrael Vaelthorn
* Race : Unknown Shadowborn (appears humanoid but composed of flowing darkness)
* Role : Mysterious Secret Vendor — Forest Glade of Secrets
* Location : Forest Glade of Secrets — Western dense forest (spawns only after mini-event completion)
* Status : Shadowbound Trader / Occult Merchant
* Affiliation : Neither faction — possibly tied to ancient natural forces

---

		2. Appearance

	"Lord Umbrael Vaelthorn" stands tall — an elegant, shadow-forged knight whose armor is wrought from midnight obsidian and curling smoke. He wears a deep dark 
cloak that never flutters in the wind, yet always seems alive around him. Where his face should be, there is only a mask of void with dim, pale lights flickering 
like distant stars.
	His gauntleted hands always remain just slightly obscured in shadow, and his footsteps leave no mark on the forest floor. Around his presence lingers a quiet 
resonance — as if the forest itself pauses when he speaks.

---

		3. Personality

	Umbrael is :
* Eloquent yet cryptic
* Polite but unnervingly observant
* Amused by mortal persistence
* Quick to tease players lacking currency
* Patient in voice, sharp in humor

	He deals only in rare, high-value goods — not out of greed, but because such items are aligned with the hidden forces of the Glade.
	He reacts to players as if noticing an interesting anomaly — not necessarily as a friend or foe.

---

		4. Behavior & AI

* Spawns only after a mini-event is completed
* Remains visible for 4 minutes per spawn
* Does not walk or move from his spot
* Does not engage in combat
* Becomes slightly irritated if spawned repeatedly without currency
* Appears invisible in minimap and does not block player movement
* Only interacts with players who have a valid interaction state (player has completed event)

---

		5. Mechanics

	Spawn Conditions :
* Umbrael spawns only after a mini-event is successfully completed
* Event must not be completed previously by the same player within the same day
* Umbrael remains visible per spawn interval — 4 minutes
* Cannot be interacted with outside of this time

---

	Currency Mechanics :
* Trades exclusively in "Fragment of Sand Crystal"
* Does not accept gold, silver, or any other currency
* Each item can be bought only once per spawn
* Goods with exceptions (unique conditions) will be listed in SHOP file

---

	Anger & Interaction Lock :
* If player spawns Umbrael but has no fragments, Umbrael enters a displeased state
* He will only tolerate 2 repeated interactions per global spawn
* On the 3rd attempt without fragments :
	* Umbrael becomes non-interactable
	* Remaining active duration remains, but he refuses trade
	* Player MUST wait until next spawn cycle

---

	Interaction Conditions :
* Umbrael can be seen by all players present
* ONLY players who triggered the mini-event can trade
* Other players may see him but cannot open dialogue with him

