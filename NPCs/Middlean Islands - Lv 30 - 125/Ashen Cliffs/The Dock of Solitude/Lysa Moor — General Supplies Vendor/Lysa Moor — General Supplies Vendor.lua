			Lysa Moor — General Supplies Vendor (Dock of Solitude)

---

		1. Basic Information

* Name : Lysa Moor
* Role : General Supplies Vendor
* Location : The Dock of Solitude
* NPC Type : Vendor (Shop handled separately)

---

		2. Appearance

	A middle-aged woman with sun-worn skin and tied-back dark hair streaked with gray. She wears layered travel clothes with many stitched pockets and a thick 
leather apron. Small pouches, cloth wraps, and bundles hang from her belt.
	Her stall is made of stacked crates and a canvas sheet stretched for shade. Everything around her looks practical, organized, and easy to grab in a hurry.

---

		3. Personality

* Practical and efficient
* Speaks little but notices everything
* Used to dealing with travelers, soldiers, and sailors alike
* Dislikes wasted time and pointless chatter

---

		4. Behavior

* Rearranges items on her stall constantly
* Ties and re-ties small bundles with rope
* Checks inventory by touch rather than sight
* Occasionally looks toward arriving boats before anyone else notices them

---

		5. Quotes

	Idle : 

> "If you forgot it, I probably have it."
> "Nothing here is luxury. Everything is needed."
> "Travel light. Regret less."

	To Player : 

> "Don’t wait until nightfall to prepare."
> "Out there, small things matter."
> "You look like you’re missing something."

---

		6) Environmental Presence

* Her stall reinforces the idea of last-minute preparation before leaving the dock
* Adds to the feeling that this place is a true departure point into a hostile island
* Her constant organizing gives the dock a lived-in, active atmosphere

