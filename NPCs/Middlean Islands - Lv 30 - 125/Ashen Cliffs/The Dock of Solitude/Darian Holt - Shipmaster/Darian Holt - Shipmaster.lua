			Darian Holt

---

		1. Basic Information

* Name : Darian Holt
* Race : Human
* Role : Shipmaster — Boat Rental & Coastal Travel
* Location : The Dock of Solitude (left berth)
* Affiliation : Dock Authority under Captain Roderik Vance
* NPC Type : Skillable NPC, Service NPC (Boat Rental)

---

		2. Appearance

	Darian is a tall, lean man in his early forties with sun-burnt skin and dark hair tied into a short sailor’s knot. His beard is short and always well kept.

	He wears an oil-treated leather maritime coat, thick gloves tucked in his belt, reinforced boots for wet planks, and a brass whistle around his neck. A small 
compass hangs on a cord that he checks frequently out of habit.

	His boat is immaculate — ropes perfectly coiled, deck clean, sail maintained. Everything about him reflects discipline and order.

---

		3. Personality

* Calm and professional
* Values safety over speed
* Speaks in a measured tone
* Dislikes recklessness
* Constantly irritated by Marek’s behavior
* Treats players like passengers under his responsibility

---

		4. Behavior

* Inspects boat ropes and hull repeatedly
* Writes notes in a small route logbook
* Cleans already clean surfaces
* Watches Marek from distance and sighs
* Checks the horizon often

---

		5. Quotes

	Greeting Quotes : 

> "Transport requires discipline. I provide that."
> "You’ll arrive safely. That is my promise."
> "Step carefully. Wet planks claim careless feet."

	If player previously used Marek : 

> "I see you enjoy gambling with tides."
> "You’re still alive. That surprises me."
> "Next time, choose the sailor, not the showman."

	Idle Quotes : 

> "Rope tension tells more than eyes do."
> "The sea punishes impatience."
> "A clean deck is a safe deck."

	When player rents boat : 

> "Safety inspection first."
> "We leave when I say we leave."
> "Sit steady. Sudden moves unbalance boats."

	During travel : 

> "Notice how calm this route is?”
> "No unnecessary risks."
> "A longer path, but a wiser one."

	On arrival : 

> "We land here. Safer depth."
> "Wet boots are better than broken hulls."

	About Marek : 

> "Noise does not equal skill."
> "He trusts luck. I trust knowledge."

---

		6. Mechanics

	Boat Rental

	Darian rents boats that allow players to travel :
* Along island coastline
* Through safe waterways
* To coastal POIs

	His routes :
* Slightly slower
* Avoid known hostile shoreline paths
* Reduce chance of landing near enemy presence

---

	Functional Prank 1 — Safety Inspection Delay

	After player pays :
* Darian performs a "mandatory safety inspection”
* 3–5 seconds delay before departure
* Marek shouts from distance complaining about it

Pure personality mechanic that players will recognize over time.

---

	Functional Prank 2 — Over-Cautious Landing

	Upon arrival :
* Darian lands farther from the shore
* Player must walk a few meters through shallow water

	This happens randomly.

---

	Rivalry Tracking (Cosmetic)

	A small board near his boat tracks :

	"Safe Arrivals: Darian vs Marek"

If player uses Darian repeatedly, he comments positively.
If player comes from Marek, he makes sarcastic remarks.

---

		7. Environmental Presence

	Darian’s side of the dock feels orderly and controlled :
* Coiled ropes
* Clean planks
* Calm stance
* Structured atmosphere

	His berth feels like a naval checkpoint rather than a ferry spot.

---

		8. Notes

	Darian genuinely believes passengers’ lives are his responsibility.
	He sees himself as the only true professional sailor on the dock.
