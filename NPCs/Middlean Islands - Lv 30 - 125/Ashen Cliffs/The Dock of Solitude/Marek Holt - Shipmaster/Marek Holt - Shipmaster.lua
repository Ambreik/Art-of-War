			Marek Holt

---

		1. Basic Information

* Name : Marek Holt
* Race : Human
* Role : Shipmaster — Boat Rental & Coastal Travel
* Location : The Dock of Solitude (right berth)
* Affiliation : Dock Authority under Captain Roderik Vance
* NPC Type : Skillable NPC, Service NPC (Boat Rental)

---

		2. Appearance

	Marek is slightly younger than Darian, broader in the shoulders, with wind-messy hair and a permanent half-smirk. His beard is uneven as if trimmed with a knife
instead of care.

	He wears a sleeveless maritime vest, loose sailor trousers, a red sash around his waist, and a collection of small charms tied to his belt "for luck." His boots
are worn, and his gloves are missing fingers.

	His boat looks functional but chaotic — ropes loosely tied, a patched sail, and scratches along the hull that tell stories he proudly exaggerates.

---

		3. Personality

* Loud, confident, theatrical
* Believes speed is skill
* Loves showing off
* Enjoys annoying Darian
* Treats players like crewmates in an adventure
* Thinks rules are suggestions

---

		4. Behavior

* Leans on his boat railing casually
* Sharpens a knife on a whetstone
* Waves at distant ships for no reason
* Laughs loudly when Darian is "inspecting” things
* Tosses pebbles into the water while waiting

---

		5. Quotes

	Greeting Quotes : 

> "You want to *arrive*, or you want to *arrive fast*?"
> "Ignore my brother. He sails like he’s carrying glass."
> "Best boat on this rotten dock. And I prove it daily."

	If player previously used Darian : 

> "Ah… the cautious type, eh?”
> "Don’t worry, I’ll show you what real sailing feels like."
> "Ready for a route that isn’t made for grandmothers?"

	Idle Quotes : 

> "Wind’s good. Tide’s good. I’m good."
> "Ropes hold. Mostly."
> "If it floats, it sails."

	When player rents boat : 

> "Hold tight. This one’s lively!"
> "If we hit a wave, scream proudly!"
> "Fast trip. No refunds for fear."

	During travel : 

> "See? Shortest path!"
> "That rock? Missed it on purpose."
> "Relax! I know these waters better than maps do."

	On arrival :

> "Right on the sand. Perfect landing!”
> "Dry boots, fast trip. Thank me later."

	About Darian : 

> "He’d measure the sea if he could."
> "He sails like storms ask permission."

---

		6. Mechanics

	Boat Rental

	Marek rents boats that allow players to travel :
* Along island coastline
* Through tighter waterways
* To coastal POIs

	His routes :
* Faster than Darian’s
* Pass closer to hostile shores
* Occasionally land nearer to enemy paths or rough terrain

---

	Functional Prank 1 — "Sudden Push Off"

	After player pays :
* Marek instantly pushes the boat off
* Player character does a small stumble animation before travel starts

---

	Functional Prank 2 — Risky Landing Spot

	Upon arrival (random chance) :
* Marek lands very close to rocks, debris, or uneven shore
* Player must reposition carefully after landing

	Sometimes followed by :

> "See? Precision!"

---

	Rivalry Tracking (Cosmetic)

	Same board near his boat :

	"Safe Arrivals: Darian vs Marek"

	Marek celebrates loudly if his count is higher.

> "Numbers don’t lie, brother!"

---

		7. Environmental Presence

	Marek’s berth feels alive and chaotic :
* Loose ropes
* Scratched wood
* Random tools lying around
* Constant movement and noise

	His side of the dock feels like an adventure about to happen.

---

		8. Notes

	Marek is actually a very skilled sailor — he simply hides it behind recklessness and showmanship to irritate Darian and entertain himself.

