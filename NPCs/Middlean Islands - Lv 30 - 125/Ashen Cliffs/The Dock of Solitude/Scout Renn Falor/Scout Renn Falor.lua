			Scout Renn Falor

---

		1. Basic Information

* Name : Scout Renn Falor
* Role : Inland Recon / Field Reporter
* Type : Skillable NPC / Recon Specialist
* Location : The Dock of Solitude — frequently seen arriving from or preparing to leave toward the island interior

---

		2. Appearance

	Renn Falor is a wiry, sun-darkened scout in light leather gear suited for speed and silence. A hooded cloak, worn boots, and fingerless gloves mark him as 
someone who travels rough paths often. A compact crossbow rests across his back, and a satchel filled with rolled maps, charcoal sticks, and small field notes hangs
at his side.
	His clothes are dusty, sometimes damp, sometimes torn at the edges — clear signs he spends far more time inland than at the dock.
	He rarely stands still for long.

---

		3. Behavior

	Renn is almost never idle.

	He can be seen :
* Walking quickly from the pier toward the warehouse
* Speaking briefly with the Captain or Quartermaster
* Checking a small map against the horizon
* Leaving the dock at a brisk pace toward inland trails
* Returning later, tired, sometimes injured, sometimes frustrated

	When he is present, it feels temporary — like he is only stopping to breathe before going back out.

---

		4. Mechanics

* Has a travel cycle behavior — disappears from the dock for periods of time and later returns.
* When present, offers environmental dialogue hinting at inland dangers and patrol movements.
* Can defend himself if attacked inside the safe radius.
* Occasionally arrives with visible injuries or slowed walk (environmental storytelling).
* His presence timing can subtly align with player progression toward inland POIs.

---

		5. Personality

	Renn is alert, practical, and speaks in short, efficient sentences.
	He does not exaggerate. If he says something is dangerous, it is.
	He respects the guards but feels confined at the dock. The island calls him back constantly.
	He has seen enough inland to know that something about the Forsaken movements is too organized to be random.

---

		6. Quotes

	Idle (when briefly at dock)

* "Dock’s too quiet. I don’t like quiet."
* "I sleep better under trees than on planks."
* "I’ll be heading back out soon."

	When returning from inland

* "They’re moving again. Different paths this time."
* "Saw smoke where there shouldn’t be any."
* "Patrol routes changed. Someone’s thinking out there."

	When preparing to leave

* "If I’m not back by nightfall, don’t come looking."
* "I know the paths. They don’t know me."
* "Light gear. Fast feet. That’s how you live here."

	If player asks about island

* "You’ll learn more walking than asking."
* "Watch the ground, not the horizon."
* "They watch from high places."

	If combat happens near dock

* "Not here. Not at the dock!"
* "Keep them away from the pier!"
