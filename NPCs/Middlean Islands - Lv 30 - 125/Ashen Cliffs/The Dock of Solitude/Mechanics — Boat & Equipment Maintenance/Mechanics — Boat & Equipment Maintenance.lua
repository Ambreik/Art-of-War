			Mechanics — Boat & Equipment Maintenance (Dock of Solitude)

> These two NPCs are responsible for keeping every vessel, chain, anchor, and metal fitting at the dock functional. Without them, the Dock of Solitude would slowly 
fall apart under salt, wind, and constant use.

---

		1) Basic Information

* Role : Marine Mechanics & Structural Integrity
* Affiliation : Dock Authority under Captain Roderik Vance
* Location : The Dock of Solitude
* NPC Type : Skillable Ambient NPCs (non-combat, functional presence)

	Members :
* Torvin Hale — Boat hull and woodwork specialist
* Garris Weld — Metalwork, anchors, chains, fittings specialist

---

		2) Appearance

	Both wear heavy-duty work gear, different from regular dock workers.
	Oil-stained aprons, thick gloves, tool harness belts, and reinforced boots.

	Individual Notes : 

	"Torvin Hale" : 
* Broad shoulders, shaved head
* Constant smell of tar, resin, and wet wood
* Carries wood patches, resin bucket, carving knife
* Hands permanently darkened from pitch and sealant

	"Garris Weld" : 
* Lean build, dark beard, metal goggles on forehead
* Hammer always hanging from belt
* Sparks and soot marks on clothes
* Carries chain links, nails, and metal rings

---

		3. Personality

* Focused, technical, and highly skilled
* Speak little but observe everything
* Slight rivalry about whose job is more important: wood vs metal
* Take pride in keeping boats seaworthy

---

		4. Behavior (Per Mechanic)

	Torvin Hale : 
* Kneels beside boats applying resin patches
* Taps hull with knuckles listening for hollow sounds
* Scrapes barnacles and salt crust from lower planks
* Occasionally pushes a boat slightly to test balance

	Garris Weld : 
* Hammers metal fittings into dock posts
* Tests anchor chains by pulling them hard
* Repairs broken hooks, rings, and hinges
* Sharp metallic hammer sounds heard around his area

---

		5. Quotes (Per Mechanic)

	Torvin Hale

	Idle : 

> "Wood tells you when it’s tired."
> "Salt eats boats faster than storms."
> "This hull won’t sink on my watch."

	To player : 

> "Don’t kick the planks, I just sealed them."
> "That boat? Give me an hour, she’ll float like new."

---

	Garris Weld

	Idle : 

> "Metal doesn’t forgive neglect."
> "Rust is a patient enemy."
> "Chains hold more lives than people think."

	To player : 

> "Mind the hooks."
> "Anchor fails, boat’s gone. Simple as that."

---

		6. Mechanics (Shared)

	They reinforce equipment reliability at the dock :
* Constant repair animations on boats and dock structures
* Audible hammering / scraping sounds in their area
* React to weather :
	* After storms → increased activity
	* High humidity → Garris inspects chains more often
* If players observe long enough, they see boats being maintained, reinforcing travel believability

	They do not fight, but :
* If danger appears, they grab tools and retreat behind guards

---

		7. Environmental Presence

	Because of Torvin and Garris :
* Boats feel maintained, not decorative
* Dock looks actively preserved against harsh island climate
* Reinforces realism of sea travel and equipment wear
* Adds industrial, metallic, and wooden working atmosphere to the area
