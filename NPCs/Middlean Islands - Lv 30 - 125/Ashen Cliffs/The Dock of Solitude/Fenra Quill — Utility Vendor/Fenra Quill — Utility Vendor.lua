			Fenra Quill — Utility Vendor (Dock of Solitude)

---

		1. Basic Information

* Name : Fenra Quill
* Role : Utility Vendor
* Location : The Dock of Solitude
* NPC Type : Vendor (Shop handled separately)

---

		2. Appearance

	A slim woman with sharp facial features and short copper hair. She wears fitted work clothes with reinforced gloves and a tool belt full of small instruments. 
Metal clasps, hooks, and tools hang from her stall framework.
	Her setup looks more like a workbench than a market stand.

---

		3. Personality

* Precise, methodical, and observant
* Appreciates tools more than people
* Calm voice, rarely raises it
* Speaks in short, direct sentences

---

		4. Behavior

* Tests small tools repeatedly
* Tightens screws, adjusts clasps, inspects edges
* Occasionally scribbles notes on a small paper sheet
* Watches how players move, as if evaluating their equipment use

---

		5. Quotes

	Idle : 

> "A bad tool is worse than none."
> "Details keep people alive."
> "Most failures start small."

	To Player : 

> "Check your gear before you blame your luck."
> "You don’t look prepared."
> "Preparation is quiet. Panic is loud."

---

		6. Environmental Presence

* Her presence adds a technical, prepared-for-anything tone to the dock
* Reinforces the idea that players must think ahead before leaving
* Makes the dock feel like a staging ground, not a marketplace

