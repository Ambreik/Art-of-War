		6. Mechanics (Shared)

	All dock guards enforce the "Safe Radius" :
* No hostile NPCs can enter this zone
* No patrol paths intersect the dock
* Environmental hazards do not occur here

	If a hostile NPC somehow approaches :
* Guards engage immediately
* Use coordinated attacks and whistles to alert others

	They also :
* React to suspicious player combat behavior inside the dock
* Prevent fights between players or NPCs
* Create a feeling of protected civilization

---

		7. Senior Guard Extra Mechanics — Halren Pike

	Halren controls "Guard Rotation Routes".

	At timed intervals :
* Halren whistles
* Guards change patrol positions dynamically :
	* Moss rotates from pier to perimeter
	* Crow moves to higher vantage
	* Reed takes edge patrol
	* Brennor briefly leaves warehouse to walk outer line

	This makes the dock feel alive and actively protected rather than static.

	If combat happens near the dock edge :
* Halren directs guards toward the threat position first

---

		8. Environmental Presence

	Because of them, the dock feels :
* Structured
* Watched
* Organized
* Militarily disciplined

	Players clearly understand this is the only true safe foothold on Ashen Cliffs.

