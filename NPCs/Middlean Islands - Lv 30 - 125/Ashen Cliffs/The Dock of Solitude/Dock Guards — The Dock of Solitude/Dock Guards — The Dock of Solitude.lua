			Dock Guards — The Dock of Solitude

> Responsible for safe-radius enforcement, patrol edges, and watching incoming vessels.

---

		1. Basic Information

* Role : Dock Security Unit
* Affiliation : Dock Authority under Captain Roderik Vance
* Location : The Dock of Solitude
* NPC Type : Skillable NPCs, Guard Units

	Members :
* Guard Halren Pike — Senior Guard
* Guard Tomas Reed
* Guard Vellis Crow
* Guard Brennor Slate
* Guard Kieran Moss

---

		2. Appearance

	All five guards wear standardized marine guard attire :

* Heavy leather coats reinforced with metal shoulder plates
* Dark blue cloth underlayers with marine insignia
* Short swords and spears
* Signal whistles attached to chest straps
* Lantern hooks on their belts for night patrols

	Individual Notes

	"Halren Pike" — Older, scar across chin, short gray beard, carries himself with command presence.
	"Tomas Reed" — Clean face, relaxed posture, often smiles at travelers.
	"Vellis Crow" — Thin, sharp eyes, rarely blinks, always scanning horizons.
	"Brennor Slate" — Tall, broad, shaved head, intimidating silhouette.
	"Kieran Moss" — Young, alert, moves quickly, always walking.

---

		3. Personality

* Professional and disciplined
* Aware this is the only safe place on the island
* Used to seeing exhausted, wounded, or frightened adventurers arrive
* Take pride in keeping the dock calm and protected

	Halren acts more like a field commander than a simple guard.

---

		4. Behavior (Per Guard)

	Halren Pike — Senior Guard : 
* Walks slow inspection routes across the entire dock
* Stops to observe other guards during patrol
* Gives silent nods or short instructions
* Often stands at the edge of the safe radius looking outward

	Tomas Reed : 
* Talks with arriving players
* Leans on spear while watching ships
* Helps workers carry small crates occasionally

	Vellis Crow : 
* Stands facing the sea most of the time
* Rarely turns his back to the water
* Walks to elevated spots for better visibility

	Brennor Slate : 
* Mostly stationed near warehouse and cargo area
* Crossed arms, imposing stance
* Moves only when something needs checking

	Kieran Moss : 
* Constant pier patrol
* Checks ropes, ship edges, waterline
* Quick paced walking pattern

