---

		6. Mechanics (Shared)

	These NPCs reinforce the functional realism of the dock :
* Constant visible activity (repair, carry, light, maintain)
* Day/Night behavior differences (especially Milo)
* Do not engage in combat but will run inward if danger appears
* React to environmental conditions :
	* Strong winds → more repair animations
	* Night time → increased lantern activity

---

		7. Environmental Presence

	Because of them, the dock feels :
* Maintained daily
* Operational and believable
* A place where people actually live and work
* A fragile structure constantly fighting the island’s harsh environment
