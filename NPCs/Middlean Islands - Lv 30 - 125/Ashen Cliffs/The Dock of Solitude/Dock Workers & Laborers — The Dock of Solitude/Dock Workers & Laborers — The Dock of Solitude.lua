			Dock Workers & Laborers — The Dock of Solitude

> Make the dock feel active, lived-in, and functional.

---

		1. Basic Information

* Role : Dock Maintenance & Logistics Crew
* Affiliation : Dock Authority under Captain Roderik Vance
* Location : The Dock of Solitude
* NPC Type : Ambient Skillable NPCs (non-combat, functional behavior)

	Members :
* Old Bram Cutter — Rope and net specialist
* Joss Fenrick — Cargo handler
* Milo Thatch — Lantern keeper
* Eryn Pell — Structural repair worker

---

		2. Appearance

	Dock workers wear practical, weather-worn clothing :

* Thick wool shirts and rolled sleeves
* Leather gloves, tool belts, and patched trousers
* Salt-stained boots
* Simple head coverings or bandanas

	Individual Notes : 

* "Old Bram Cutter" — Elderly, hunched back, gray beard tied with twine, always carries coils of rope.
* "Joss Fenrick" — Muscular build, sweat-stained clothes, constantly lifting or dragging crates.
* "Milo Thatch" — Thin, soot marks on hands, carries oil flask and lighting rod.
* "Eryn Pell" — Focused expression, tool hammer at belt, wood splinters in clothing.

---

		3. Personality

* Hardworking and practical
* Used to harsh island weather
* Respect the guards and captain
* Speak casually with players but remain focused on tasks
* Provide the sense that the dock is maintained daily, not abandoned

---

		4. Behavior (Per Worker)

	Old Bram Cutter : 
* Kneels near mooring posts repairing ropes
* Tests rope tension by pulling hard
* Occasionally replaces nets hanging near the dock edge

	Joss Fenrick : 
* Carries crates between small storage areas
* Rearranges cargo piles
* Wipes sweat and stretches back frequently

	Milo Thatch : 
* Walks between lantern posts at dusk/night
* Lights lanterns one by one
* Refills oil containers during daytime

	Eryn Pell : 
* Hammers loose pontoon boards
* Inspects planks by stepping hard on them
* Replaces damaged wood panels slowly

