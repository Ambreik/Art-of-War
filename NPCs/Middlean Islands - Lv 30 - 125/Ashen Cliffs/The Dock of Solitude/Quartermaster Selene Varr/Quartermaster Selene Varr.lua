			Quartermaster Selene Varr

---

		1. Basic Information

* Name : Quartermaster Selene Varr
* Role : Supply Manifests, Cargo Logging, Military Shipments
* Type : Skillable NPC / Logistics Authority
* Location : The Dock of Solitude, primarily near the warehouse and cargo stacks

---

		2. Appearance

	"Selene Varr" is a lean, sharp-eyed woman in her late thirties, always dressed in reinforced leather over a marine quartermaster’s uniform. Her sleeves are 
rolled, ink stains mark her fingers, and a bundle of scrolls, tags, and sealing wax hang from her belt.
	A small ledger book is always in her hand or tucked under her arm. A short utility dagger rests at her hip — more tool than weapon. Her hair is tied back 
tightly, practical and severe, and her expression rarely softens.

	Crates around her often bear chalk marks, numbers, and coded symbols only she seems to understand.

---

		3. Behavior

	Selene moves constantly between :
* Warehouse stacks
* Incoming cargo from boats
* Dockside inspection points
* Marking and re-marking crates with chalk symbols

	She checks seals, verifies cargo against manifests, and sometimes mutters counts under her breath. If players linger too long near marked crates, she eyes them 
suspiciously but says nothing unless approached.
	If danger approaches the dock, she steps back but can defend herself with surprising competence if needed.

---

		4. Mechanics

* Walks a logistics patrol loop between dock, warehouse, and cargo inspection points.
* Periodically marks crates with chalk symbols (visual environmental storytelling).
* Can assist guards briefly if safe zone is breached.
* Provides flavor dialogue hinting at unusual shipments and increasing traffic to certain island areas.
* Reacts to players who interact repeatedly with cargo piles.

---

		5. Personality

	Selene is methodical, distrustful, and intensely detail-oriented.
	She trusts numbers more than people.
	To her, the island is a place where cargo disappears, routes change, and shipments never quite match the paperwork.
	She is convinced something irregular is happening with supplies moving inland — but she cannot prove it.

---

		6. Quotes

	Idle : 

* "Three crates arrive. Two leave. The ledger never lies."
* "Cargo tells stories if you know how to read it."
* "Someone on this island moves goods without my ink on it."

	When near cargo : 

* "Don’t touch that. It hasn’t been logged yet."
* "Seal’s broken… again."
* "I mark them. They still move."

	When players return from inland : 

* "You went where my crates go, didn’t you?"
* "Tell me — do you see our markings out there?"
* "Something is feeding off our supplies."

	If combat happens near dock : 

* "Keep them away from the cargo!"
* "If this burns, we starve!"

	Rare reflective line : 

* "War is loud. Logistics is silent. But both decide who survives."
