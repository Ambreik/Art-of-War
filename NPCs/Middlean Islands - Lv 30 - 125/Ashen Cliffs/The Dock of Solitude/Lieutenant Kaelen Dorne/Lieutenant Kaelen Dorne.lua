			Lieutenant Kaelen Dorne

---

		1. Basic Information

* Name : Lieutenant Kaelen Dorne
* Role : Military Liaison — Dock of Solitude to Island Operations
* Type : Skillable NPC / Authority Figure / Information Relay
* Location : The Dock of Solitude, usually near the traffic log board or speaking with Captain Roderik Vance

---

		2. Appearance

	Kaelen Dorne is a disciplined, sharp-featured officer in his early forties. His armor is practical marine issue, reinforced with leather straps and salt-worn 
metal plates. A dark blue officer’s cloak hangs from his shoulders, marked with the insignia of King Arlic’s marine forces.
	He carries a short saber at his side and a sealed document satchel strapped across his chest at all times. His posture is rigid, his gaze constantly scanning 
movement across the dock as if every arrival might be a report waiting to happen.
	Unlike the sailors and workers, Kaelen looks like a man who never truly "arrived” here — he is stationed, not settled.

---

		3. Behavior

	Kaelen rarely stands idle.

	He moves between :
* The dock log board
* Conversations with guards
* Inspecting incoming boats
* Brief exchanges with Captain Roderik Vance

	He records ship arrivals, notes unusual cargo, and quietly keeps track of which adventurers leave toward dangerous areas of the island.
	If hostile forces somehow breach near the dock, Kaelen can draw his saber and assist guards with competent combat ability.
	He speaks little, but when he does, it is precise and purposeful.

---

		4. Mechanics

* Acts as information anchor for island state (flavor dialogue reflecting player progress on island POIs).
* Can assist guards in combat if safe radius is violated.
* Walks a fixed administrative patrol route between key dock points.
* Observes players repeatedly leaving toward Fort Mirath or the cliffs and may comment on it.
* Shares military-flavored remarks about Forsaken discipline and movement patterns.

---

		5. Personality

	Kaelen is not emotional, not curious, not friendly.
	He is professional to the point of discomfort.
	He treats the island like an active military report that never ends.
	To him, the Forsaken are not legends or traitors.
	They are an unresolved military problem.

---

		6. Quotes

	Idle :

* "Every boat that leaves this dock writes a report I never get to read."
* "This island breathes like a battlefield that refuses to end."
* "Order survives here only because we force it to."

	When players return from dangerous areas :

* "You went far. I can see it in your posture."
* "Fort walls still stand, then."
* "You saw them, didn’t you? Still marching like soldiers."

	When near guards :

* "Rotation stays tight. No gaps near the warehouses."
* "Eyes on the waterline. Always."

	If combat happens near dock :

* "Form up! No breaches past this line!"
* "Hold position — do not scatter!"

	Rare reflective line :

* "A war that ends without closure never truly ends at all."

