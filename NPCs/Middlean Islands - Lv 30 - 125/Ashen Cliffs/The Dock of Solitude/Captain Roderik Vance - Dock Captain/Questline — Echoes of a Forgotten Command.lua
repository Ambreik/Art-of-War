			Questline — "Echoes of a Forgotten Command"

* Quest Giver : Captain Roderik Vance
* Type : Main Questline — Island Narrative Thread

---

		Quest 1 — "Old Names Don’t Die"

	Objective : Speak with "Captain Vance" about the purpose of the expedition to "Ashen Cliffs".

	Task : 
* Listen to Vance’s explanation
* Inspect the marine logbook on the dock wall (interact)
* Return to Vance

	What this establishes : 
* Mirath is not legend — he was real
* The island was a strategic refuge, not random exile
* This is an official investigation ordered by the Council

	Key Dialogue Insight : 

> "A hundred years and the reports still don’t sit right with me."

---

		Quest 2 — "Patterns on the Horizon"

	Objective : Observe the coastline from 3 marked spots near the dock.

	Task : 
* Go to 3 observation points
* Interact (simulate watching patrol smoke / movement trails)
* Return

	What this establishes : 
* The Forsaken still move in patterns
* They are organized
* Someone is still commanding… or the system never died

---

		Quest 3 — "Supplies Without Sailors"

	Objective : Investigate abandoned supply crates along the shoreline path toward inland.

	Task :
* Find 4 marked crates
* Inspect markings
* Discover Forsaken insignia scratched out

	What this establishes :
* The Forsaken still maintain logistics routes
* They erase old allegiance symbols
* They behave like a faction, not survivors

---

		Quest 4 — "The Watcher in the North"

	Objective : Speak with "Carler Pincher" at "The Watcher’s Perch".

	Task : 
* Travel to the POI
* Speak with Carler
* Return with his report

	What this establishes : 
* Links Captain Vance questline with Carler’s recon quests
* Introduces patrol discipline, signals, observation gameplay

---

		Quest 5 — "Broken Walls Tell Stories"

	Objective : Visit "The Shattered Rampart".

	Task @ 
* Inspect 3 ruin points
* Find old impact marks and cannon placements
* Return

	What this establishes : 
* The fort was defended militarily
* There was a real siege or expectation of one
* Mirath expected to be pursued

---

		Quest 6 — "They Still Drill"

	Objective : Observe Forsaken activity near outer fort walls without engaging.

	Task : 
* Reach marked stealth observation point
* Remain undetected for X seconds
* Return

	What this establishes : 
* Forsaken still train, patrol, rotate
* They are not feral or decayed
* Military discipline theme reinforced

---

		Quest 7 — "A Name You Know"

	Objective : Report back findings.

	Dialogue-heavy quest : 

	Here Vance reveals:
	* Mirath drank the "Living Water"
	* Mirath deserted during the "Second Great War"
	* Some officers followed him
	* The Council believes he may still be alive

	This is the first time player hears this clearly.

---

		Quest 8 — "Proof, Not Rumors"

	Objective : Retrieve a Forsaken officer insignia from near the fort outskirts.

	Task : 
* Kill a Rank II / III Forsaken Officer
* Loot insignia
* Return

	What this establishes : 
* Confirms chain of command still exists
* Physical proof for Council

---

		Quest 9 — "If He Lives" (Pre-Fort Quest)

	Objective : Stand at a cliffside vantage during specific weather (fog or clear)

	Task :
* Observe fort
* Return and choose dialogue option :
	* Fog approach
	* Daylight approach

	What this establishes : 
* Direct tie to Weather & Fog mechanic you designed
* Player is mentally preparing for Fort Mirath

---

		Quest 10 — "Fort Mirath Awaits" (Bridge Quest)

	Objective : Captain Vance sends player to infiltrate Fort Mirath.

	This quest does not have tasks.

	It unlocks the "Fort Mirath" experience as a narrative objective, not exploration.

	Final Words from Vance : 

> "If Mirath still draws breath… then history didn’t end here. It’s waiting."

