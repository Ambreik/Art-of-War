			Captain Roderik Vance

---

		1. Basic Information

* Name : Captain Roderik Vance
* Race : Human
* Role : Captain of the Dock / Authority of The Dock of Solitude
* Location : The Dock of Solitude — South-East Shore, Ashen Cliffs Island
* Status : Civilian Military Liaison / NPC Quest & Interaction Hub
* Affiliation : Former Marine Army lineage (King Arlic’s naval command)

---

		2. Appearance

	"Captain Roderik Vance" is an older man with a weathered, sea-hardened face. His once-dark hair is now gray and worn long, partially tucked into a faded fur 
cape that drapes over his broad shoulders—a remnant of his father’s uniform, a respected commander in King Arlic’s marine fleet during the Second Great War.
	His right eye is covered by a well-worn eye patch from an old battle wound. Scars trace the lines of his cheek and jaw, speaking to years at sea and near-
constant vigilance.
	Roderik wears his father’s marine uniform with visible pride—navy jacket trimmed with brass and embroidered with faded insignia, heavy boots caked in salt and 
sand, and a long fur cape that flutters in the coastal breeze. A well-maintained sword hangs in its sheath at his hip, the grip worn from years of use and memory.

	His posture remains upright and authoritative, even in old age.

---

		3. Personality

	Captain Vance embodies the essence of old naval discipline coupled with practical island adaptation :

* Astute and Observant — Sees patterns in movement and behavior others miss.
* Calm Under Pressure — Displays veteran resolve rarely rattled.
* Gruff but Fair — Not prone to soft sentimentality, yet deeply principled.
* Family Legacy Pride — Honors his father’s service with reverence.
* Strategic Interpreter — Applies maritime logic to land defense and logistics.

	He rarely raises his voice, but when he does, people listen.

---

		4. Behavior & AI

	Captain Vance’s AI is non-combat oriented — he is not a frontline fighter.

	Behavioral Patterns :
* Roams the dock in slow, measured patrol routes
* Pauses at vessel logs and arrival manifests
* Observes dock traffic from key vantage points
* Stops to inspect boats and equipment
* Interacts with guards and dock personnel non-aggressively

	Idle Movements :
* Leans against dock posts while reviewing logs
* Slowly paces between moored boats
* Stops occasionally to gaze toward horizon

	Combat AI :
* If threatened, he calls for guards immediately
* Uses only a defensive stance
* Avoids direct engagement

---

		5. Dialogue Interaction

	Captain Vance speaks with :
* Deep-toned voice, measured cadence
* Occasional wry humor rooted in decades of service
* Light irony when speaking of the Forsaken Band

	Greeting :

> "Welcome to the Dock of Solitude. This isn’t a resort, but it’s as safe as they come."

	When Player Approaches :

> "Keep to the walkways. Loose boards have claimed more sailors than the sea lately."
> "If you’re here for travel, I suggest sensible boots and a keen eye."

	When Asked About Forsaken Band :

> "I’ve seen my share of deserters and reavers in the war… but those at Mirath’s fort? They operate like soldiers without command."

	On Duty & Discipline :

> "The sea taught me patience… the dock taught me persistence."

	When Concerned About Trouble :

> "Trouble doesn’t always announce itself with steel. Sometimes it whispers between tides."

---

	6. NPC Mechanics

	Safe Zone Presence :

* When near Captain Vance within the dock safe radius :
	* Combat music fades
	* Enemy aggro is prevented
	* Players are implicitly marked as “non-combatants”
	* Narrative tutorial hints may trigger

	Directional Guidance Triggers :
* Approaching certain directions prompts short hints :
	* "You see the Shattered Rampart up ahead…"
	* "The Watcher’s Perch gives good views when fog breaks."

	Travel Guidance Dialogue :
* "If you seek the Sunken Encampment, take the weathered path west."
* "Boats leave at sunrise and dusk — best times to avoid low visibility."
* "Sharing travel routes strengthens dock safety reports."

---

	7. Additional Notes

	Captain Vance carries with him :
* A weathered sea log journal (non-interactable, world flavor)
* A set of navigation maps, pinned near the dock office wall
* A faded badge of marine command, inherited from his father


