			Carler Pincher

---

		1. Basic Information

* Name : Carler Pincher
* Race : Human
* Role : Recon Specialist / Quest Giver
* Type : Skillable NPC
* Location : The Watcher’s Perch — Northern Cliffs, Ashen Cliffs Island

---

		2. Overview

	Carler Pincher is a field reconnaissance agent sent to study the movements and behavior patterns of the Forsaken Band around Fort Mirath.
	He is not a soldier, nor a frontline fighter.
	He is an observer, a tracker of patterns, a patient watcher of routines.
	He chose The Watcher’s Perch because it gives him exactly what he needs: visibility, elevation, and isolation.
	The Forsaken know someone is watching them from the cliffs. They have searched the tower multiple times. They have never found him.
	Carler considers this a personal victory.

---

		3. Appearance

	Carler wears light, weather-worn leather mixed with cloth wraps suitable for long observation sessions in harsh wind and rain.
* A hooded mantle covered in charcoal smudges to break his silhouette
* A spyglass hanging from his belt
* Chalk pieces and map fragments tucked into small pouches
* A short blade and compact crossbow for emergencies
* A smoke vial belt used for emergency vanishing

	His posture is slightly hunched, the result of long hours leaning on stone windows and staring into the distance.
	His eyes are constantly scanning even while speaking.

---

		4. Behavior & Personality

	Carler is :
* Paranoid but intelligent
* Calm but visibly sleep-deprived
* Amused by the Forsaken’s failed attempts to find him
* Quietly worried that one day he will be caught off guard

	He speaks in half-thoughts, observations, and muttered conclusions rather than direct statements.
	He often pauses mid-sentence to look through a window slit.

---

		5. NPC Mechanics

	Carler is not static.
	He uses simple survival mechanics tied to the POI.

---

	Wandering Behavior : 
* Moves between :
  * Base level of the tower
  * Mid observation level
  * Top brazier platform
* Occasionally stands outside on the cliff edge observing patrol paths

---

	Vanishing Mechanic (Defensive Survival)

	If Forsaken patrols come too close to the tower :
* Carler throws a smoke vial
* Brief smoke effect
* Carler despawns for a short duration (30–60 seconds)
* Reappears at a different level of the tower

	This reinforces the idea :

> He has survived here for weeks by never being where enemies expect him.

---

	Self-Defense (Skillable NPC)

	If directly attacked :
* Uses short crossbow shots
* Throws blinding powder (minor blind on enemies)
* Attempts to disengage rather than fight

	He is built to escape, not win.

---

		6. Environmental Awareness

	Carler reacts to environmental systems of the island :
* During fog: stays on top platform longer (best observation time)
* During clear weather: prefers mid-level slits (less visible silhouette)
* If brazier is lit by player: he reacts with surprise and frustration

---

		7. Narrative Purpose

	Carler is the player’s first contact who :
* Explains that the Forsaken move in patterns
* Encourages observation before assault
* Introduces the idea that the fort is an organized military base, not chaos

	He sets the mental tone for approaching "Fort Mirath".

---

		8. Quotes

	Idle / Observing : 
* "They walk the same path every hour… like clockwork… fools."
* "Patterns. Everything is patterns. You just have to see them."
* "They know I’m here. I know they know. That’s the fun part."

	When player approaches : 
* "Quiet. Don’t stand in the open like that. You glow against the stone."
* "You’re here for the fort, aren’t you? Then you’ll want to look before you leap."

	If brazier is lit : 
* "No, no, no! Do you know how visible that smoke is?!"
* "Well… at least now we get to see how they react…"

	When patrols approach (before vanishing) : 
* "Ah. That’s my cue to not be here anymore."
* "Time to become a ghost again."

	After reappearing : 
* "Still alive. Still smarter than them."

	Worried / tired : 
* "One day I’ll fall asleep at the wrong moment… and that will be it."
* "If they catch me, everything I learned dies with me."

	About the Forsaken : 
* "They’re not madmen. That’s the dangerous part."
* "They move like soldiers. Because they still are."

---

		9. Function in Gameplay

	Carler is :
* A Quest Giver
* A Living tutorial for reconnaissance gameplay
* A narrative bridge between exploration POIs and "Fort Mirath"
* A character that makes the island feel observed, studied, and alive
