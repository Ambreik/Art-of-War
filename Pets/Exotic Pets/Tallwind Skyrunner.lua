			Tallwind Skyrunner

---

		1. Basic Information

* Pet Name: Tallwind Skyrunner
* Source Monster: Tallwind Skyrunner (wild variant)
* Pet Type: Aerial Predator
* Family: Avian / Wind-Adapted Predator
* Rarity: Rare Pet
* Role: Companion / Combat Support / Scouting
* Acquisition: Tamed from wild Tallwind Skyrunner
* Summon Item: Tallwind Skyrunner Contract

---

		2. Description

	The Tallwind Skyrunner is a medium-sized, sleek avian predator with long, narrow wings and sharp talons. Its feathers are subtly wind-patterned, giving it 
natural camouflage while in flight. Agile and perceptive, it excels at aerial reconnaissance and supporting its master in combat by harrying enemies from above. Its
keen eyesight allows it to detect movement and threats from great distances.

---

		3. Pet Type & Category

* Pet Category: Combat / Scout Pet
* Tamable: Yes
* Carrier: No
* Combat Pet: Yes (supports combat)
* Exotic: No
* Evolvable: Yes (level-based evolution)

---

		4. Statistics & Attributes

* Base Level: 1
* Max Level: 50
* Growth Type: Standard (Balanced scaling)
* Base HP: Medium
* Base Damage: Medium
* Defense: Moderate
* Aggression: Reactive (assists when master is attacked, or attacks marked targets)
* Mobility: Aerial flight, gliding, perching

---

		5. AI Behavior

* Core Logic :
	* Follows player unless in combat
	* Attacks enemies threatening master
	* Provides minor aggro diversion
	* Uses skill rotation based on archetype
* Archetypes (randomly assigned upon taming) :
	1. Scout: Focuses on detecting distant enemies/resources; low combat output
	2. Agile Striker: Medium combat support; hit-and-run aerial attacks
	3. Defensive: Buffs master’s evasion and counters ranged attackers
	4. Elite (Rare): Balanced, adaptive; good scouting, high combat support

---

		6. Skills

* Passive & Active Skill Pool (Sample)
1. "Wind Slash" (Melee / Active): Aerial dive attack dealing moderate damage; chance to knockback
2. "Gust Scout" (Utility / Passive): Reveals hidden enemies/resources in a small radius
3. "Sky Harrier" (Active): Circles target, attacking from multiple angles; increases crit chance for next attack
4. "Feathered Evasion" (Passive): Grants master minor evasion boost when mounted or nearby

* Skill sets are chosen randomly upon taming, influenced by archetype. Higher level pets can unlock additional skills.

---

		7. Evolution Path

* Level thresholds (30 / 40 / 50) grant chance to evolve into:
	* Evolved Form : Larger, stronger, increased HP/defense, better scouting abilities
	* Combat Form : Focused on aerial damage, tactical combat maneuvers, additional passive buffs

---

		8. UI & Player Interaction

* Displays: Name, level, health/status bars, skill list, hunger/loyalty meter
* Actions: Summon/dismiss, evolve, assign skill rotation

---

		9. Passive Bonuses

* While active, the Tallwind Skyrunner may grant:
	* +3% Movement Speed
	* +2% Evasion
	* +2% Detection of hidden enemies or resources
* Scales slightly with pet level

---

		10. Acquisition / Tame Rules

* Must use Tame Ability on wild Tallwind Skyrunner
* Requires patience and observation; aggressive taming may fail
* Cooldown: Standard taming cooldown applies
* Failure: Pet resists or temporarily flees; repeated failures increase difficulty temporarily

