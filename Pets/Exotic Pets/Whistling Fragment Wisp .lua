			Whistling Fragment Wisp 
			
---

		1. Basic Information

* Pet Name : Whistling Fragment Wisp
* Pet Class : Utility / Exotic Pet
* Pet Type : Sound-based Disorientation Companion
* Taming Difficulty : Hard (Exotic handling required)
* Habitat Origin : Wind corridors, broken stairs, hollow stone pockets, echoing ruins
* Required Tool : Advanced Taming Kit
* Special Taming Condition : Must be tamed inside a natural echo chamber where wind produces audible whistling

---

		2. Appearance

	A small floating shard of translucent mineral, constantly rotating in the air. Hairline cracks glow faintly from within as air passes through it, producing 
soft, haunting whistles. It has no face, no limbs—only a drifting presence and a persistent, unsettling sound.

---

		3. Core Attributes

* HP : Very Low
* Defense : Very Low
* Mobility : Floating / High
* Behavior : Non-combatant, evasive
* Role : Disorientation, sound manipulation, support utility

---

		4. Pet Abilities

* "False Footsteps" (Active) : Creates phantom sound cues at a target location, causing nearby enemies to turn and investigate.
* "Echo Scatter" (Active) : Emits a sharp whistle burst that briefly disorients enemies, lowering accuracy and interrupting targeting.
* "Wind Drift" (Active) : The wisp rapidly relocates to a nearby spot, avoiding incoming attacks.
* "Hollow Resonance" (Passive) : Enemies rely more on sound than sight when the wisp is present, making them easier to mislead.
* "Ambient Whistle" (Passive) : Constant low-volume sound that subtly increases enemy alertness radius—but toward false directions.

---

		5. Utility Role

	The Whistling Fragment Wisp excels at :
* Distracting patrols
* Breaking enemy formations without direct combat
* Assisting stealth or escape gameplay
* Manipulating AI behavior through environmental sound logic

---

		6. Special Taming Mechanic

	This entity cannot be tamed in open space.

	To tame it, the player must :
1. Find a location where wind naturally produces a whistling echo through ruins or stone gaps
2. Stand still within the sound corridor for several seconds without moving
3. Begin taming only when the wisp aligns with the wind sound and becomes brighter

If the player moves, attacks, or the wind sound stops, the wisp disperses and must be found again.

---

		7. Behavior While Summoned

* Floats around the player at head height
* Drifts toward walls, corners, and hollow spaces
* Frequently emits soft whistles even out of combat

---

		8. Restrictions

* Cannot deal damage
* Extremely fragile if targeted directly
* Requires thoughtful positioning to be effective

