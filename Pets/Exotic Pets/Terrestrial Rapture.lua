			Terrestrial Rapture – Pet Version

	File Name Suggestion : `Terrestrial_Rapture_Pet`

	Description (Appearance & Behavior) :

* Appearance : Miniature form of the terrestrial rapture. Soft, muted rainbow feathers, smaller wings tucked neatly at its sides, bright intelligent eyes. Its claws 
and beak are proportionally smaller and harmless. The tail feathers sway gently, and subtle glimmers trace along its plumage when idle.
* Behavior : Playful and curious; follows the player at a short distance. Occasionally hops, flutters lightly, or perches on the player’s shoulder/backpack. Mimics 
minor environmental movements (tilting head, flapping wings when startled).

	Mechanics / Interaction :

* Cosmetic companion; cannot attack or perform combat actions.
* Loyalty Meter : Tracks bonding level; affects idle animations and visual effects (e.g., feather shimmer intensity, small sparkles around the pet).
* Movement Bonus : Small boost to player movement speed (+2–3%) when pet is summoned nearby.
* Pet can interact with certain environmental objects (e.g., nudges levers, triggers minor visual cues).
* Automatically follows player; cannot be lost or aggroed by monsters.

	Gameplay Tie-in :

* Encourages exploration and collection, rewarding players with a visually appealing companion.
* Loyalty progression adds soft progression goals.
* Serves as a “visual scout”: subtly hints at nearby environmental interactions through its behavior (e.g., glances toward hidden paths).

	Visual/Audio Flavor :

* Gentle cooing or chirping sounds when moving.
* Tail and feather tips sparkle faintly when idle or happy.
* Subtle flutter of wings when approaching obstacles or small ledges.

