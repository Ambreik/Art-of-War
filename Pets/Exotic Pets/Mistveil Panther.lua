			Mistveil Panther

---

		1. Basic Information

* Pet Name: Mistveil Panther
* Source Monster: Mistveil Panther (wild variant)
* Pet Type: Stealth Predator
* Family: Feline / Forest Predator
* Rarity: Rare Pet
* Role: Companion / Combat Support / Tracking
* Acquisition: Tamed from wild Mistveil Panther
* Summon Item: Mistveil Panther Contract

---

		2. Description

	The Mistveil Panther is a medium-sized, lithe feline predator with dark, shadowy fur that blends perfectly with misty forests and dense underbrush. Its eyes are
keen and reflective, capable of detecting subtle movements and scents. Highly agile and silent, it excels at tracking prey or targets and ambushing enemies in 
coordinated strikes alongside its master.

---

		3. Pet Type & Category

* Pet Category: Combat / Stealth / Scout Pet
* Tamable: Yes
* Carrier: No
* Combat Pet: Yes (supports combat)
* Exotic: No
* Evolvable: Yes (level-based evolution)

---

		4. Statistics & Attributes

* Base Level: 1
* Max Level: 50
* Growth Type: Standard (Balanced scaling)
* Base HP: Medium
* Base Damage: Medium–High
* Defense: Moderate
* Aggression: Reactive (attacks marked targets, assists master in combat)
* Mobility: Ground mobility, climbing, ambush strikes

---

		5. AI Behavior

* Core Logic :
	* Follows player unless in combat
	* Detects and marks enemies for ambush
	* Assists in stealth attacks
	* Uses skill rotation based on archetype
* Archetypes (randomly assigned upon taming) :
	1. Tracker: Focuses on detecting hidden targets and following scent trails
	2. Ambusher: Excels at surprise attacks from stealth, high burst damage
	3. Guardian: Protects master, intercepting approaching enemies
	4. Elite (Rare): Balanced scouting, ambush, and reactive combat

---

		6. Skills

* Passive & Active Skill Pool (Sample)

1. "Shadow Pounce" (Active / Melee): Leaps to a target from stealth, dealing high initial damage and minor bleed
2. "Silent Stalk" (Passive): Reduces detection radius of master and pet during stealth
3. "Feral Swipe" (Active): Multi-target claw attack; applies bleed
4. "Predator’s Instinct" (Passive): Increases crit chance and evasion when engaging targets alone

* Skill sets are chosen randomly upon taming, influenced by archetype. Advanced pets unlock additional skills with evolution.

---

		7. Evolution Path

* Level thresholds (30 / 40 / 50) grant chance to evolve into :
	* Evolved Form : Larger, faster, gains additional stealth and tracking buffs
	* Combat Form : Focused on damage and ambush efficiency, minor area-of-effect attacks

---

		8. UI & Player Interaction

* Displays: Name, level, health/status bars, skill list, hunger/loyalty meter
* Actions: Summon/dismiss, evolve, assign skill rotation

---

		9. Passive Bonuses

* While active, the Mistveil Panther may grant :
	* +3% Stealth Efficiency
	* +2% Movement Speed
	* +2% Detection of hidden enemies or traps
* Values scale slightly with pet level

---

		10. Acquisition / Tame Rules

* Must use Tame Ability on wild Mistveil Panther
* Ideal when young for easier taming; fully grown adults are more challenging
* Cooldown: Standard taming cooldown applies
* Failure: Panther resists or temporarily flees; repeated failures increase difficulty temporarily

