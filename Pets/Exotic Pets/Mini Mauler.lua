			Exotic Pet: Mini Mauler

**Type:** Exotic Pet – Aquatic (Archetype: God)
**Acquisition Method:** Crafting via **Core Beast Fragments**

---

### **Core Beast Fragments – Required Monsters**

| Monster Name           | Type       | Spawn Location / Notes                             |
| ---------------------- | ---------- | -------------------------------------------------- |
| **Grimstone Warden**   | Semi-Boss  | Grimstone Quarry – main cavern                     |
| **Tidehunter Lurker**  | Rare Elite | Coastal cliffs / tide pools at low tide (party ≥3) |
| **Sunken Sentinel**    | Semi-Boss  | Sunken Warship interior, Veyra’s Edge              |
| **Molten Spire Golem** | Rare Elite | Veyra’s Reach – lava vent zones / rocky cliffs     |

**Drop Rules:**

* Each monster drops **1 Core Beast Fragment** per kill with a low % chance (~5%).
* Fragments are **player-bound**. Cannot be: sold, traded, vendored, deleted, fed to pet/mount/guardian/baron.
* When all 4 fragments are in the inventory, they **gather together** and **start to glow**.
* Glow is **active only in proximity to NPC: Pet Master Caldor Beastbinder** (Capital City).

---

### **Crafting Process**

**NPC:** Pet Master: Caldor Beastbinder
**Location:** Capital City (proximity required)
**Cost:** 30 Gold
**Crafting Result:** Pet Seal – “Mini Mauler Egg”

**Egg Mechanics:**

* **Hatch Duration:** 3 days (online time)
* **Archetype:** God (cannot be changed, cannot be re-rolled; prompt displayed if player attempts)
* **Summoning:** Can be summoned in any environment (land , water or underworld)
* **Leveling/Evolution:** None (endgame exotic pet)

---

### **Pet Functions**

| Function                          | Description                                                                                    |
| --------------------------------- | ---------------------------------------------------------------------------------------------- |
| **Lure Monsters (Underwater)**    | Pet attracts monsters around player within a small radius                                      |
| **Neutralize Aggro (Underwater)** | Pet reduces or nullifies aggro of monsters around player within a small radius                 |
| **Cosmetic/Follow**               | Pet swims alongside player, visible in water and land, purely cosmetic in general combat zones |

**Notes:**

* **Exotic pet cannot level up or evolve.**
* **Market Restrictions:** Can only be sold via Market (shop system, not AH). Cannot be traded or sold directly to other players.
* **Global Summon:** Pet can be summoned anywhere, not tied to environment restrictions.

---

### **Player Interaction Mechanics**

1. **Fragment Gathering:** Fragments glow in inventory once all 4 are collected.
2. **Proximity Crafting:** Pet Master detects fragments when player is nearby; option to craft “Mini Mauler” appears.
3. **Egg Handling:** Egg occupies inventory slot until hatch; cannot be manipulated otherwise.
4. **Hatch Completion:** Pet automatically appears as “Mini Mauler” after 3 days online. Player can summon immediately.
5. **Underwater Functions:** Player selects pet mode (Lure or Neutralize Aggro) in underwater environments.

