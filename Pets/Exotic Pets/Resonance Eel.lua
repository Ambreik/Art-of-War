			Resonance Eel

---

		1. Basic Information

* Pet Name : Resonance Eel
* Pet Class : Utility / Exotic Pet
* Pet Type : Detection & Support Companion
* Taming Difficulty : Advanced / Special Tame
* Habitat Origin : Tideglass Passage, Stormfall Coves, shallow inlets of Vaelthorn Frontier
* Special Taming Condition : Requires submersion in water pools at night and repeated interaction using sound-based lures (e.g., sonar stones or vibrating bait)

---

		2. Appearance

	The Resonance Eel is a long, slender aquatic creature with smooth, iridescent scales that shimmer in deep blues and greens. Its head features two small, glowing
sensory nodules that emit faint pulses when detecting vibrations. Along its spine, fine membranous fins ripple constantly, giving it a graceful undulating motion. 
Its eyes are large and reflective, adapted to dim, murky waters, allowing it to detect movements through both sight and sound.

---

		3. Core Attributes

* HP : Low-Medium
* Defense : Low
* Speed : Medium in water, sluggish on land
* Mobility Type : Swimming companion
* Role : Detection / support, scouting submerged or foggy areas

---

		4. Pet Abilities

* "Sonic Pulse" (Active) : Sends out a short-range sonar wave that reveals hidden or stealthed enemies through terrain.
* "Echo Awareness" (Passive) : Alerts the player to nearby hidden movement in water or foggy areas.
* "Camouflage Glide" (Passive) : Moves almost invisibly in dimly lit waters, blending with shadows.
* "Tidal Swim" (Active) : Quick burst of speed in currents or shallow water to evade danger or reposition.

---

		5. Utility Role

* Detects hidden creatures and ambushers near foggy coves or tidepools.
* Assists in exploration of submerged passages like Tideglass Passage.
* Serves as a tactical scout for both combat and environmental hazards.

---

		6. Special Taming Mechanic

1. Locate a Resonance Eel in shallow tide pools at night.
2. Use vibrating bait or sonar lure to attract the eel without alarming it.
3. Interact repeatedly to gain trust; any sudden movement or noise may cause retreat.
4. After successful luring sessions over a short period, the eel bonds with the player and becomes tamed.

---

		7. Behavior While Summoned

* Swims along water surfaces and shallow pools near the player.
* Periodically emits sonar pulses automatically when near hidden threats.
* Can follow the player passively or remain in a defined aquatic area.

---

		8. Restrictions

* Cannot leave water bodies for extended periods.
* Limited combat capability; primarily a support and detection pet.
* Effectiveness decreases in bright daylight or rough, turbulent waters.

