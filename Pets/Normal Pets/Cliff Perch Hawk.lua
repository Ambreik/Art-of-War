		6. Core Pet Attributes

* Pet HP : Low
* Pet Defense : Low
* Mobility : Very High (Aerial)
* Detection Capability : High
* Intelligence Behavior : High (tracking, scanning, circling)
* Combat Capability : None

---

		7. Pet Abilities / Traits

	1. Sky Survey

	The hawk performs periodic aerial scans of the surrounding area.

* Effect :
	* Reveals nearby enemies or points of interest within a radius
	* Helps detect hidden or distant targets
* Mechanic : Passive periodic reconnaissance

---

	2. Target Marking (Recon Tag)

	The hawk can mark a target upon player focus or engagement.

* Effect :
	* Highlights selected enemies or objects
	* May briefly reveal hidden or obscured targets
* Mechanic : Visual and informational assist

---

	3. Elevated Vision

	Provides enhanced awareness when the player is in elevated terrain.

* Effect :
	* Expands detection radius when player is on cliffs or high ground
	* Improves spotting of distant threats or movement
* Mechanic : Terrain-based passive bonus

---

	4. Glide Return

	When the player moves across terrain:
* The hawk will :
	* Glide to maintain overhead or nearby aerial position
	* Avoid unnecessary landing interruptions
* Ensures continuous scouting presence

---

		8. Passive Bonuses

* Increased environmental awareness
* Improved detection of distant enemies or hazards
* Enhanced visibility in vertical or open zones
* Reduced chance of ambush due to aerial scouting coverage

---

		9. Evolution / Progression Path (Optional Design)

	The Cliff Perch Hawk can evolve through bonding and usage:

	Potential Evolution States : 

* "Cliffwatch Hawk" (Improved detection range)
* "Storm Perch Hawk" (Enhanced aerial mobility + scanning frequency)
* "Apex Skyhawk" (Advanced scouting + multi-target marking)

	Evolution Triggers : 
* Time spent in aerial zones
* Successful reconnaissance actions
* Marking/spotting milestones
* Bond level progression

---

		10. Limitations

* Fragile (low survivability)
* No direct combat contribution
* Requires open or vertical environments to maximize value
* Limited effectiveness in enclosed underground zones

