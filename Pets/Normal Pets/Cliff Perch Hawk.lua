			Cliff Perch Hawk (Tamed Variant)

---

		1. Tamed Entity Overview

* Tamed Name : Cliff Perch Hawk
* Companion Type : Pet
* Pet Role : Aerial Scout / Vision Utility
* Pet Category : Utility Pet → Recon / Spotting Specialist
* Progression Tier : Normal (with potential Evolution path)
* Acquisition Type : Taming (Wild Capture)
* Taming Difficulty : Medium–High (timing + positioning dependent)
* Required Player Level : Low–Mid
* Applicable Systems : Pet System (Companion Slot, Passive Vision Abilities, Environmental Detection, Utility Traits)

---

		2. Taming Method

	Cliff Perch Hawks are highly aware aerial creatures that prefer elevated resting points such as cliffs, ledges, and ruins.

	Standard Taming Process :

1. Locate a Cliff Perch Hawk perched on a high vantage point.
2. Player must approach without triggering flight behavior.
3. Taming can only be initiated when the hawk is :
	* Resting (perched)
	* Not actively scanning or alarmed
4. Player must maintain line-of-sight and elevation proximity during taming.

---

		3. Secret / Unique Taming Mechanic

	"Stillness of the Cliff" (Hidden Mechanic)

	To successfully tame the hawk with higher efficiency :
* The player must :
	* Remain stationary for a short duration before initiating tame
	* Avoid sudden camera movement, jumps, or repositioning
	* Align themselves on a similar elevation level or nearby ledge

	Additional Hidden Condition
* If the player :
	* Faces the hawk directly without moving
	* Waits through a brief "observation window" before taming
* Then :
	* Taming success rate increases
	* The hawk gains a hidden trait: "Skybond Awareness"

This mechanic simulates trust-building through patience rather than force.

---

		4. Appearance (Tamed Variant)

	The tamed Cliff Perch Hawk retains its sharp, predatory silhouette but exhibits a calmer and more composed demeanor compared to its wild counterpart.
	Its feathers appear sleek and well-aligned, with subtle tonal variations that reflect light differently when viewed from various angles. The wings are broad and
structured for gliding, and when at rest, the hawk maintains an upright, vigilant posture rather than appearing tense or defensive.
	Its eyes remain intensely focused, but instead of scanning for threats aggressively, they periodically shift between the environment and the player, indicating 
awareness and bonding. When airborne, the hawk glides smoothly and deliberately, often circling above the player rather than flying erratically.
	When perched, it prefers elevated positions near the player’s line of sight, such as cliffs, ruins, or tall structures, reinforcing its identity as a 
reconnaissance companion. Its head movements are subtle but precise, constantly tracking points of interest in the surrounding environment.

