			Delta Skimmer Crab (Tamed Variant)

---

		1. Tamed Entity Overview

* Tamed Name : Delta Skimmer Crab
* Companion Type : Pet
* Pet Role : Utility / Environmental Traversal Companion
* Pet Category : Amphibious Companion
* Acquisition Type : Taming (Wild Capture)
* Taming Difficulty : Low
* Required Player Level : Low–Mid (early game accessibility)
* Applicable Systems : Pet System (Companion Slot, Passive Abilities, Utility Traits)

---

		2. Taming Method

	Delta Skimmer Crab uses a non-combat, observation-based taming method rather than direct aggression.

	Standard Taming Process : 
1. Player approaches a Skimmer Crab in shallow water or delta terrain.
2. The crab must remain undisturbed for a short duration.
3. Player uses a basic Tame Interaction (Pet System action).
4. If successful, the crab becomes a companion.

	Success Conditions : 

* Must be in shallow water or delta biome
* Crab must not be recently disturbed or fleeing
* Player must remain within a short interaction radius without triggering escape behavior

---

		3. Secret / Unique Taming Mechanic (Optional Enhancement)

	Delta Skimmer Crab includes a subtle hidden mechanic to encourage environmental awareness :

	"Still Waters Taming Condition"

* If the player :
	* Avoids movement for a short period near the crab
	* Interacts while standing in calm shallow water (no combat, no sprinting)
* Then :
	* Taming success chance increases
	* Pet gains a minor "Calm Current” trait"

	This mechanic rewards patience and environmental alignment rather than force.

---

		4. Appearance (Tamed Variant)

	The tamed Delta Skimmer Crab retains its natural form but exhibits subtle behavioral differences when bonded to a player. Its shell appears slightly cleaner and
more defined, with faint glowing traces along the edges of its carapace that pulse softly when it is active.
	Its movement becomes more synchronized and responsive to the player’s position, often staying close and adjusting its skimming path to match the player’s 
direction in shallow water. The leg movements appear more controlled and deliberate, as if guided rather than purely instinctual.
	In some variants, faint markings resembling small ripples or insignias may become more visible on its shell, representing its bonded state. Its eyes 
occasionally orient toward the player, indicating awareness and companionship rather than purely environmental awareness.

