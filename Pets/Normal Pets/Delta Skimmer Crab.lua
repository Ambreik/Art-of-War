---

		6. Pet Abilities / Traits

	1. Shallow Water Skimming

	Allows the player to traverse shallow water more efficiently when the pet is active.

* Effect :
	* Reduces movement penalties in shallow water zones
	* Enables smoother movement across mud, marsh, and delta terrain
* Type : Passive Aura / Utility Buff
* Activation : Always active while pet is summoned

---

	2. Surface Guidance

	The crab subtly leads or stabilizes movement across uncertain shallow terrain.

* Effect :
	* Highlights or implicitly assists in identifying traversable shallow zones
	* Improves traversal consistency in mixed-depth environments
* Type : Passive Environmental Assistance
* Mechanic : Non-combat navigation support

---

	3. Rapid Retreat Response (Pet Behavior)

	When danger is nearby :
* The crab will :
	* Retreat toward the player or nearby safe shallow zones
	* Avoid hostile entities
* Effect :
	* Does not engage enemies
	* Prioritizes survival and positioning

---

	4. Environmental Sensitivity

	The pet reacts to water depth and terrain changes.

* Effect :
	* Behavior changes depending on depth:
		* Shallow water → active, smooth movement
		* Deep water → stays closer to player or edges
* Mechanic : Enhances immersion and environmental awareness

