			Chillspike Hatchling
	*(Tamed from Frostveil Burrower)*

---

	BASIC INFORMATION : 

Pet Name : Chillspike Hatchling
Source Monster : Frostveil Burrower
Family : Insectoid
Rarity : Rare Pet
Role : Companion / Combat Support / Resource Detection
Acquisition : Tamed from Frostveil Burrower Pet Egg
Summon Item : Chillspike Hatchling Contract


---

	DESCRIPTION : 

The "Chillspike Hatchling" is a small insectoid companion hatched from the rare pet egg dropped by the "Frostveil Burrower".
It emits tiny frost spikes and glows with a cool blue shimmer.
Though small, it offers aid in exploration, resource detection, and minor combat. Its presence reflects the mineral-rich caves it was born from.

---

	PET TYPE & CATEGORY

Pet Category : Normal Pet
Tamable : Yes
Carrier : No
Combat Pet : Yes (supports combat)
Exotic : No
Evolvable : Yes (level-based evolution)

This pet begins as a "Normal Pet*"* and can evolve into a more powerful form if it reaches the evolution thresholds defined in your pet system.

---

	STATISTICS & ATTRIBUTES

Base Level : 1
Max Level : 50
Growth Type : Standard (Balanced scaling)
Base HP : Medium
Base Damage : Medium
Defense : Moderate
Aggression : Reactive (assists when master is attacked)

---

		AI BEHAVIOR

	Core Logic : 
* Follows player unless in combat
* Attacks enemies that threaten its master
* Provides minor aggro diversion
* Uses skill rotation based on archetype
	Pets roll skill sets from the species’ predefined skill pool on tame — typically 1–4 active and 1–3 passive skills. 

---

	Archetype : When tamed, this pet can randomly roll into one of the following archetypes :

	1. Tanky
* Draws enemy aggro
* Gains defensive buffs

	2. Berserk : 
* Deals increased damage
* Lower defense

	3. Skillable : 
* Uses slightly more intelligent combat skills
* Has tactical usage

	4. God (Rare) : 
* Balanced and adaptive
* Good support and burst damage

	These archetypes influence combat behavior, aggro logic, and specialization. 

---

		SKILLS

	Passive & Active Skill Pool (Sample)

	1. Frost Bite Aura
* Passive effect
* Deals continuous minor frost damage to nearby enemies
* Grants slight frost resistance bonus to master

	2. Ice Spike Lash
* Melee attack
* Chance to slow target for 2 seconds

	3. Crystal Sense (Utility)
* Detects hidden mineral or rare resource nodes near the player
* Icon appears on UI when resource is close

	4. Burrow Dash
* Quick dash forward to reposition
* Minor damage + brief stun

	Skill sets are randomly chosen upon taming, influenced by archetype. More advanced pets can unlock extra abilities through evolution.

---

		EVOLUTION PATH

	If the pet hits evolution thresholds by leveling (e.g., level 30, 40), it has a 50/50 chance to evolve into either :
* Evolved Form : 
	* Larger, sturdier
	* Gains higher defenses and advanced skills

* Combat Form : 
	* More DPS focused
	* Better burst damage and offensive skills

