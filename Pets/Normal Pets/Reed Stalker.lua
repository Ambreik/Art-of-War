			Reed Stalker


---

		BASIC INFORMATION

* Pet Name : Reed Stalker
* Source Monster : Reed Stalker
* Family : Feline / Predator
* Rarity : Uncommon Pet
* Role : Ambush Support / Reconnaissance
* Acquisition : Tamed from juvenile Reed Stalker in misty marshes or springs
* Summon Item : Reed Stalker Contract

---

		DESCRIPTION

	The "Reed Stalker" is a small-to-medium stealth predator adapted to misty wetland areas. Its mottled gray-green fur blends perfectly with tall reeds and 
grasses, making it almost invisible when stalking prey or surveying terrain. Agile and alert, the Reed Stalker excels at ambushing minor threats, scouting ahead for
the master, and disrupting enemy positions.

---

		PET TYPE & CATEGORY

* Pet Category : Normal Pet
* Tamable : Yes
* Carrier : No
* Combat Pet : Yes (supports ambush and reconnaissance)
* Exotic : No
* Evolvable : Yes (level-based evolution)

The Reed Stalker starts as a "Normal Pet" and can evolve into a more capable predator as it levels.

---

		STATISTICS & ATTRIBUTES

* Base Level : 1
* Max Level : 50
* Growth Type : Balanced
* Base HP : Low–Medium
* Base Damage : Medium
* Defense : Moderate
* Aggression : Reactive / Ambusher (assists master when needed)

---

		AI BEHAVIOR

* Stays close to master unless deployed to scout
* Uses stealth to approach enemies or survey terrain
* Engages enemies selectively, preferring ambushes
* Utilizes skill rotation based on archetype

	Archetypes (randomly rolled upon taming) :

1. "Scout" – Excels in detecting hidden enemies, hazards, or resources
2. "Ambusher" – Specializes in hit-and-run attacks and minor status effects
3. "Skillable" – Uses combat skills intelligently with tactical application
4. "God" (Rare) – Balanced, adaptive; strong reconnaissance and ambush support

---

		SKILLS

1. "Reed Camouflage" (Passive) – Improves stealth while in tall grass, reeds, or mist
2. "Pounce Strike" (Active) – Quick leap to target; moderate damage and brief stun
3. "Ambush Swipe" (Active) – Melee attack from stealth; chance to apply minor bleed
4. "Scout Sense" (Utility) – Detects hidden or nearby enemies; highlights them for master

	Skills are randomly assigned from the species skill pool upon taming, influenced by archetype.

---

		EVOLUTION PATH

	At level thresholds (20, 35, 50), Reed Stalker can evolve into :
* "Evolved Form" – Larger, more resilient; enhanced stealth and tracking
* "Combat Form" – Focused on damage and ambush effectiveness

---

		UI & PLAYER INTERACTION

* Name, level, and health display
* Passive and active skills display
* Loyalty / hunger meter
* Evolution / dismiss options

---

		PASSIVE BONUSES

* +5% Stealth in marsh/mist environments
* +3% Damage from ambush attacks
* +2% Movement speed in dense grass or reeds

	Bonuses scale with pet level.

---

		ACQUISITION / TAME RULES

* Tame Conditions : Must use "Tame Ability" on juvenile Reed Stalker
* Cooldown : Standard pet taming cooldown
* Success / Failure : Failure temporarily increases monster resistance; critical failure causes retreat

