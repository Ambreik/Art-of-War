			Cove Skimmer Gull

---

		1. Basic Information

* Pet Name : Cove Skimmer Gull
* Pet Class : Utility Pet (Scout)
* Pet Type : Aerial Scout Companion
* Taming Difficulty : Easy
* Habitat Origin : Vaelthorn Frontier — coastal cliffs, coves, windcaller edges
* Required Tool : Basic Taming Kit
* Special Taming Condition : Must be tamed while the gull is perched on a cliff edge during fog or while flying through a wind pressure zone

---

		2. Appearance

	The Cove Skimmer Gull is a lean, long-winged coastal bird shaped by relentless sea winds. Its feathers carry tones of salt-white and mist-gray, often dampened 
by sea spray. Silver streaks run faintly across its wings where salt crystals have formed over time. Its black eyes are glossy and observant, always scanning from 
above. When airborne, it barely flaps, gliding smoothly on invisible air currents. When perched, it leans forward into the wind as if listening to the sea itself.

---

		3. Core Attributes

* HP : Low
* Defense : Very Low
* Mobility : Very High (Aerial)
* Behavior : Passive, avoids combat
* Role : Vision, scouting, environmental awareness

---

		4. Pet Abilities

* "Fog Sight" (Passive) : Reveals nearby enemies, creatures, and interactive objects within fog-covered areas or low visibility zones.
* "High Perch" (Active) : The gull flies upward and circles above, increasing the player’s detection radius and revealing hidden or elevated threats for a short 
duration. Cooldown applies.
* "Wind Glide" (Passive) : Gains movement speed when the player travels through wind pressure zones or updraft areas.
* "Alarm Call" (Utility) : Emits a sharp cry that briefly highlights nearby hostile creatures on the player’s screen.

---

		5. Utility Role

	The Cove Skimmer Gull is designed for exploration and awareness, not combat. It excels in:
* Foggy terrain navigation
* Cliff and elevation scouting
* Detecting hidden enemies or ambushes
* Assisting players in wind-heavy environments

---

		6. Special Taming Mechanic

	The gull cannot be tamed on the ground.

	To tame it, the player must :
1. Approach a perched gull on a cliff during fog or
2. Follow one while it rides a wind current
3. Begin taming while it is in motion in the air

	If attempted incorrectly, the gull flies away and despawns temporarily.
	This teaches players about wind mechanics and environment timing.

---

		7. Behavior While Summoned

* Frequently flies ahead of the player rather than staying beside them
* Lands on rocks, cliffs, or ruins while the player is idle
* Reacts to fog density and elevation changes with unique animations

---

		8. Restrictions

* Cannot engage in combat
* Cannot be targeted by enemies
* Purely utility-focused companion

