			Basin Skydrift Kite

---

		BASIC INFORMATION

* Pet Name : Basin Skydrift Kite
* Source Monster : Basin Skydrift Kite
* Family : Avian
* Rarity : Common Pet
* Role : Companion / Minor Scouting
* Acquisition : Tamed directly from wild Skydrift Kites
* Summon Item : Skydrift Kite Contract

---

		DESCRIPTION

	The "Basin Skydrift" Kite is a small, lightly built bird with long, tapering wings and a slender tail that allows precise aerial maneuvering. Its feathers are 
pale with subtle iridescent sheens that shimmer in sunlight. Though naturally non-hostile, it is curious and responsive to its master’s commands, often circling 
above to scout or provide aerial observation.

---

		PET TYPE & CATEGORY

* Pet Category : Normal Pet
* Tamable : Yes
* Carrier : No
* Combat Pet : No (non-combat)
* Exotic : No
* Evolvable : Yes (level-based evolution for advanced scouting or combat variants)

---

		STATISTICS & ATTRIBUTES

* Base Level : 1
* Max Level : 50
* Growth Type : Standard (balanced scaling)
* Base HP : Low
* Base Damage : None (non-combat)
* Defense : Low
* Aggression : Passive unless commanded

---

		AI BEHAVIOR

* Core Logic :
	* Follows player while flying in nearby airspace
	* Provides minor scouting; highlights hidden or distant objects
	* Avoids combat unless commanded by player
	* Uses flight pathing to circle above obstacles and terrain

---

		Archetype

	When tamed, this pet can roll into one of the following archetypes :
1. "Scout" – Increases vision range; highlights hidden objects or enemies
2. "Support" – Alerts player to threats or nearby resources
3. "Skillable" – Can learn minor active abilities like distracting or buffing allies
4. "Rare Aerial" (Very Rare) – Increased flight speed and enhanced scouting radius

---

		SKILLS

* "Wind Watch" (Passive) – Automatically signals nearby threats or changes in weather affecting visibility
* "Aerial Scout" (Active) – Briefly hovers over distant locations to mark points of interest
* "Sky Glide" (Passive) – Reduces travel stamina drain for the player while flying companions are active
* "Feather Flare" (Utility) – Emits a small flare to mark or distract targets in sight

Skill sets are randomly chosen upon taming, influenced by archetype. Advanced evolution can unlock extra abilities.

---

		EVOLUTION PATH**

* Level 30–40 evolution chance :
	* "Enhanced Scout Form" – Increased flight agility, longer scouting range
	* "Combat Form" – Minor support combat abilities, including distraction or light debuffs

---

		UI & PLAYER INTERACTION

	Your pet UI will show :
* Name & level
* Health & status bars
* Passive & active skill list
* Hunger / loyalty meter (requires periodic feeding)
* Evolve / dismiss options

---

		PASSIVE BONUSES

	While active, the Basin Skydrift Kite may grant :
* +2% detection of rare resources
* +1% movement speed (aerial bonus)
* Minor alert for hidden threats

	Values scale slightly with pet level.

---

		ACQUISITION / TAME RULES

* Tame Conditions :
	* Must use “Tame Ability”
	* Pet Contract item required
	* Success chance influenced by pet resistance & environment
* Cooldown : Standard taming cooldown applied
* Success / Failure :
	* Failure temporarily increases resistance
	* Critical failure causes the kite to fly off to another area

