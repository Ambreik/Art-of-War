			Tallgrass Prowler


---

		BASIC INFORMATION

* Pet Name : Tallgrass Prowler
* Source Monster : Tallgrass Prowler
* Family : Feline / Predator
* Rarity : Uncommon Pet
* Role : Combat Scout / Ambush Support
* Acquisition : Tamed from juvenile Tallgrass Prowler
* Summon Item : Tallgrass Prowler Contract

---

		DESCRIPTION

	The "Tallgrass Prowler" is a medium-sized, feline-like predator that blends seamlessly into tall grasses and plains terrain. Its agile body, sharp claws, and 
stealthy movements make it ideal for scouting, ambushing minor threats, and assisting players in combat. When raised from a juvenile, it is highly trainable and 
forms a close bond with its master. Its fur is mottled green and brown, allowing it to vanish among the plains.

---

		PET TYPE & CATEGORY

* Pet Category : Normal Pet
* Tamable : Yes
* Carrier : No
* Combat Pet : Yes (supports ambush tactics)
* Exotic : No
* Evolvable : Yes (level-based evolution)

The Prowler starts as a "Normal Pet" and can evolve into more powerful forms as it levels up.

---

		STATISTICS & ATTRIBUTES

* Base Level : 1
* Max Level : 50
* Growth Type : Balanced
* Base HP : Medium
* Base Damage : Medium
* Defense : Moderate
* Aggression : Reactive (assists when master is threatened)

---

		AI BEHAVIOR

* Follows the player, remaining stealthy when idle
* Ambushes enemies threatening the master
* Can distract or provoke minor mobs to protect the master
* Uses skill rotation based on archetype

	Archetypes (randomly rolled upon taming) :

1. "Scout" – High mobility, increased stealth detection, minor damage
2. "Assassin" – Boosts ambush damage, applies bleed effects
3. "Skillable" – Uses intelligent skill rotations in combat
4. "God" (Rare) – Balanced, adaptive; effective for both combat and scouting

---

		SKILLS

1. "Grass Stalk" (Passive) – Reduces chance to be detected by enemies; increases stealth duration
2. "Fang Slash" (Active) – Melee attack; chance to apply minor bleed
3. "Pounce" (Active) – Leap to target; deals moderate damage and briefly stuns
4. "Silent Scout" (Utility) – Detects nearby hidden enemies or traps

Skill sets are assigned randomly at taming, influenced by archetype.

---

		EVOLUTION PATH

	When reaching certain level thresholds (e.g., 20, 35, 50), it can evolve into :

* "Evolved Form" – Larger, stronger, stealth optimized, better passive effects
* "Combat Form" – Focused on burst damage and ambush attacks

---

		UI & PLAYER INTERACTION

* Displays name, level, and health
* Shows passive and active skills
* Hunger / loyalty meter (requires feeding)
* Evolution / dismiss options

---

		PASSIVE BONUSES

* +5% Stealth detection
* +3% Ambush damage
* +2% Movement speed in grasslands

	These bonuses scale with pet level.

---

		ACQUISITION / TAME RULES

* Tame Conditions : Must use "Tame Ability" on juvenile Prowler
* Cooldown : Standard pet taming cooldown
* Success / Failure : Failure temporarily increases monster resistance; critical failure causes retreat

