			Echo Lurker Bat

---

		1. Basic Information

* Pet Name : Echo Lurker Bat
* Pet Class : Utility Pet (Detection)
* Pet Type : Cave Scout Companion
* Taming Difficulty : Moderate
* Habitat Origin : Vaelthorn Frontier — Rift Caverns, Echo Tunnels, Breathing Cavern
* Required Tool : Basic Taming Kit
* Special Taming Condition : Must be tamed inside an echo tunnel after creating enough noise to attract it

---

		2. Appearance

	The "Echo Lurker Bat" is a small, dark-winged cave dweller with thin membranous wings stretched between elongated fingers. Its fur is charcoal gray with faint 
silver specks that shimmer when light hits them. The ears are oversized and sharply pointed, constantly twitching to capture even the faintest vibrations. Its eyes 
are tiny and almost useless, replaced by an uncanny reliance on sound and echo perception. When at rest, it hangs upside down from ceilings or rocky overhangs, 
wrapped tightly in its wings like a living shadow.

---

		3. Core Attributes

* HP : Low
* Defense : Very Low
* Mobility : High (Aerial, confined spaces)
* Behavior : Passive, alert
* Role : Detection, stealth counter, cave navigation aid

---

		4. Pet Abilities

* "Echo Pulse" (Active) : Emits a sonar-like pulse that reveals hidden, stealthed, or obscured enemies through walls and terrain for a short duration. Cooldown 
applies.
* "Sound Mapping" (Passive) : Increases the player’s detection radius in caves, tunnels, fog, and low-visibility environments.
* "Vibration Sense" (Passive) : Highlights creatures that are moving, sprinting, mining, or making noise within range.
* "Ceiling Roos"t (Utility) : The bat briefly flies upward and attaches to a surface, increasing detection range vertically and marking elevated threats.

---

		5. Utility Role

	The Echo Lurker Bat is built specifically for :
* Cave and tunnel exploration
* Countering stealth and ambush predators
* Navigating echo-heavy environments
* Detecting enemies beyond line of sight

---

		6. Special Taming Mechanic
	This bat does not appear normally for taming.

	To tame it, the player must :
1. Enter an echo tunnel or cavern area
2. Produce repeated noise (mining, sprinting, striking walls, or combat)
3. The bat will be attracted to the sound and begin circling the player
4. Only while it is circling due to noise can the taming begin

	If the player stands still or remains silent, the bat loses interest and disappears.

	This teaches players about sound-reactive AI mechanics of "Vaelthorn Frontier".

---

		7. Behavior While Summoned

* Frequently circles above the player’s head in tight patterns
* Reacts to loud sounds with sharper movements
* In caves, often flies ahead and pauses near threats

---

		8. Restrictions

* Cannot engage in combat
* Cannot be targeted by enemies
* Purely detection and utility-focused

