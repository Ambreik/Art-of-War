			Mistpanther

---

		BASIC INFORMATION

* Pet Name : Mistpanther
* Source Monster : Mistpanther
* Family : Feline / Predator
* Rarity : Rare Pet
* Role : Combat Support / Tracking
* Acquisition : Tamed from juvenile Mistpanther
* Summon Item : Mistpanther Contract

---

		DESCRIPTION

	The "Mistpanther" is a medium-sized, shadowy feline predator that thrives in misty environments and dense underbrush. Its sleek black and gray fur, along with 
semi-transparent patches, allow it to move almost invisibly through fog or low-visibility terrain. It is highly agile and specializes in tracking targets, assisting
in combat by flanking or disrupting enemies.

---

		PET TYPE & CATEGORY

* Pet Category : Normal Pet
* Tamable : Yes
* Carrier : No
* Combat Pet : Yes (supports combat and tracking)
* Exotic : No
* Evolvable : Yes (level-based evolution)

The Mistpanther starts as a "Normal Pet" and can evolve into a more powerful predator form as it levels up.

---

		STATISTICS & ATTRIBUTES

* Base Level : 1
* Max Level : 50
* Growth Type : Balanced
* Base HP : Medium
* Base Damage : Medium
* Defense : Moderate
* Aggression : Reactive (assists when master is attacked)

---

		AI BEHAVIOR

* Follows the player stealthily when idle
* Tracks enemies or hidden creatures within misted areas
* Ambushes threats to support the master
* Uses skill rotation based on archetype

	Archetypes (randomly rolled upon taming) :

1. "Tracker" – Enhanced tracking of hidden enemies and resource nodes
2. "Assassin" – Focused on flanking and applying bleed or minor status effects
3. "Skillable" – Uses combat skills with tactical intelligence
4. "God" (Rare) – Balanced, adaptive; excels in both combat and scouting

---

		SKILLS

1. "Shadow Prowl" (Passive) – Increases stealth in mist or fog, harder to detect
2. "Claw Slash" (Active) – Melee attack; chance to apply minor bleed
3. "Silent Pounce" (Active) – Leap to target; deals moderate damage and briefly stuns
4. "Tracker Sense" (Utility) – Reveals hidden enemies or creatures nearby

Skills are randomly assigned based on archetype when tamed.

---

		EVOLUTION PATH

	At level thresholds (20, 35, 50), it can evolve into :

* "Evolved Form" – Larger, faster, better stealth and tracking bonuses
* "Combat Form" – Focused on higher damage output and ambush efficiency

---

		UI & PLAYER INTERACTION

* Displays name, level, and health
* Shows passive and active skills
* Loyalty / hunger meter
* Evolution / dismiss options

---

		PASSIVE BONUSES

* +5% Stealth in fog/mist
* +3% Damage against tracked targets
* +2% Movement speed in dense terrain

	Bonuses scale with pet level.

---

		ACQUISITION / TAME RULES

* Tame Conditions : Must use "Tame Ability" on juvenile Mistpanther
* Cooldown : Standard pet taming cooldown
* Success / Failure : Failure increases monster resistance temporarily; critical failure causes retreat

