			Skywing Hatchling

---

		1. Basic Information

* Name : Skywing Hatchling
* Type : Pet (Normal → Evolvable)
* Elemental Type : Wind
* Source : Mountain Peak Nest Egg Hatch
* Base Rarity : Normal Pet

---

		2. Description

	The "Skywing Hatchling" is a small, feathery companion bird with iridescent wings that flutter with bursts of wind magic. Though not large enough to lift a 
rider, it gracefully soars beside its master, calling out with cheerful chirps and hovering playfully in the breeze.

---

		3. Pet Role & Mechanics

* Category : Normal Pet
* Combat Role : Light combat support (ranged Wind gust pecks and minor buffs)
* Passive Bonuses : Minor jump height increase (+3%), slight stamina regeneration (+2%)
* Hunger System : Uses standard pet hunger mechanics as defined in the Pet System 
* Summon : Player can summon/un-summon anytime
* Evolvable : Can evolve into Evolved → Combat or Exotic pet types via standard evolution process 

---

		4. Skills

	Passive Skills (at Summon) :
* "Gentle Breeze" : Slight movement speed increase while the pet is active
* "Watcher’s Flight" : Increased awareness bonus (minor perception boost)

	Active Skills (wind-based) :
* "Feather Peck" : Short ranged strike that can slow an enemy
* "Wind Gust" : Brief movement speed buff to the player

---

		5. Acquisition

* Automatically obtained when Mountain Peak Egg hatches into a pet outcome
* Pet contract bound to player
* Can be summoned via Pet UI

---

		6. Evolution Potential

* Level up by participating in combat or exploration
* May evolve at Level 30 into :
	* "Evolved Pet" : Greater wind abilities, stronger stats
	* "Combat Pet" : Tactical aerial support
	* Rare chance to become "Exotic Wind Companion" via catalysts

---

		7. Pet UI Integration

* Appears in pet list upon hatching
* Shows hunger status, skill tabs, evolution panel
* Provides interaction commands (Follow, Assist, Defend) ([GitHub][2])

---

		8. Lore

	This hatchling represents a young wind spirit, forged in the high cold air of the peak winds. Earning its trust bonds it to the player as a loyal aerial 
scout — a companion both in calm sky and turbulent storm alike.

