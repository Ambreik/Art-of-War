			Windfeather Hatchling

### **General Information**

* **Type:** Bird
* **Element:** Wind
* **Origin:** *Mountain Peak Nest*, Ashen Cliffs Island
* **Acquisition:** Obtained from a single egg found in the Mountain Peak Nest secret location.
* **Hatching Time:** 2 in-game hours
* **Binding:** Soul-bound upon pickup

---

### **Appearance**

A small, azure-plumed fledgling with silver-tipped wings and bright amber eyes. Its feathers shimmer faintly with movement, creating the illusion of flowing air around it. When flying, small currents of wind trail behind its wings like wisps of mist.

---

### **Behavior**

The Windfeather Hatchling is highly agile and curious, often hovering near its owner’s shoulder or circling playfully. It occasionally lands on rocks or player equipment when idle.

At higher affection, it produces a soothing whistling tone resembling wind passing through mountain passes — this sound is known to calm nearby allies.

---

### **Growth Information**

* **Starting Level:** 1
* **Maximum Level:** 30
* **Evolution:** Evolves at Level 30 into **Windfeather Soarer**
* **Feeding Type:** Requires *Aerial Grain Feed* or *Fresh Fish* (both grant moderate EXP).
* **Mood Types:** Curious / Loyal / Energetic

