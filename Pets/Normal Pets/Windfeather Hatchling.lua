### **Skill List**

**Active Skills**

1. **Gust Peck** – A fast peck imbued with wind energy, dealing minor Wind damage. (3 s cooldown)
2. **Whirlwind Dart** – Releases a burst of wind blades around the pet, damaging up to 3 nearby enemies. (12 s cooldown)
3. **Tailwind Surge** *(Unlocked at Level 25)* – Temporarily increases the player’s movement speed by +10 % for 10 s.

**Passive Skills**

1. **Soothing Breeze** – Slightly reduces player’s Stamina consumption by 5 %.
2. **Aerial Instinct** – Increases evasion chance by +3 %.

---

### **Evolution – Windfeather Soarer (Lv 30)**

Upon reaching Level 30, the pet undergoes metamorphosis: its plumage turns silver-white, wing span doubles, and wind effects intensify.

**Evolution Bonuses**

* Gains +10 % base Attack Speed.
* Gains new skill: **Cyclone Shroud** – Creates a protective wind barrier that reduces incoming damage by 10 % for 8 s. (30 s cooldown)
* Passive: **Wind’s Bond** – Adds +2 % critical chance to the player when the pet is summoned.

---

### **Obtainment Notes**

* Only one egg can be collected per day per player.
* Once hatched, the pet cannot be traded.
* Hatching failure chance: 0 % (guaranteed hatch).
* Hatching environment bonus: if incubated on **Ashen Cliffs Island**, the pet gains +5 % experience during its first 10 levels.

