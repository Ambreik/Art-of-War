			Vinecrawler Lizard (Tamed Variant)

---
		1. Tamed Entity Overview

* Tamed Name : Vinecrawler Lizard
* Companion Type : Pet
* Pet Role : Utility / Vertical Traversal Companion
* Pet Category : Utility Pet → Traversal Specialist
* Progression Tier : Normal (with potential Evolution path)
* Acquisition Type : Taming (Wild Capture)
* Taming Difficulty : Medium (environment-dependent)
* Required Player Level : Low–Mid
* Applicable Systems : Pet System (Companion Slot, Passive Abilities, Utility Traits, Environmental Interaction)

---

		2. Taming Method

	Vinecrawler Lizard requires a movement- and positioning-based taming approach, reflecting its vertical nature.

	Standard Taming Process

1. Player locates the lizard on a vertical surface (cliffs, vines, walls).
2. The lizard must be in a stable climbing or resting state.
3. Player must approach without causing disturbance (no sudden movement or attacks).
4. Player initiates a "Tame Interaction" while maintaining position on a similar elevation level.

	Success Conditions

* Must be on or near vertical terrain
* Player must be stationary or moving slowly
* Lizard must not be in escape state (startled/fleeing)

---

		3. Secret / Unique Taming Mechanic

	"Vertical Alignment Taming" (Hidden Mechanic)

	To successfully tame the Vinecrawler Lizard more efficiently :
* The player must position themselves :
	* At a similar vertical height as the creature
	* On a climbable surface or ledge, not on flat ground below

	Bonus Condition (Improved Taming Chance)
* If the player :
	* Climbs using vines or vertical terrain
	* Avoids falling or abrupt repositioning during taming
* Then :
	* Taming success chance increases
	* Pet gains a hidden trait: "Climber’s Bond"

This mechanic reinforces the creature’s identity as a vertical traversal specialist.

---

		4. Appearance (Tamed Variant)

	The tamed Vinecrawler Lizard retains its natural reptilian form but exhibits subtle behavioral and visual changes indicating its bond with the player.
	Its scales appear slightly more refined, with faint, natural patterns that seem more defined and clean compared to its wild counterpart. In some cases, subtle 
glowing traces or markings may appear along its spine or limbs, especially when it is actively assisting the player in traversal.
	The lizard remains close to the player and demonstrates increased awareness of vertical positioning. It often positions itself on nearby walls, vines, or 
elevated surfaces rather than staying strictly on the ground. Its tail movements become more deliberate, frequently anchoring or stabilizing its posture as it waits
for movement cues from the player.
	When active, the pet may adjust its climbing path to mirror the player’s movement across vertical terrain, creating the impression of synchronized traversal 
behavior rather than independent wandering.

