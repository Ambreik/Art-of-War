			Auralith Winddrake — Pet Version

	Location : Middlean Islands \ Netar Island \ Zone 3 — Split Horizon Arch

---

	Appearance : A medium-sized drake with sleek, iridescent scales that shimmer in soft hues of teal and silver. Its wings are semi-transparent, resembling 
delicate dragonfly membranes edged with faint glowing glyphs. Eyes glow with gentle amber light. Small swirls of wind constantly circle its body, moving loose 
leaves and dust whenever it hovers near the player.

	Behavior : Loyal and curious, it floats near the player, perching occasionally on shoulders or nearby rocks. It reacts to player commands with playful 
gestures—circling, tail flicks, and gentle puffs of wind. The Winddrake can detect subtle environmental changes and hidden loot.

	Role / Mechanics : 
* Summonable companion
* Provides minor buffs:
	* Slight increase to wind-based skills
	* Alerts player to hidden objects or subtle environmental cues
* Can follow player across ledges and cliffs safely
* Cannot be mounted

	Taming Process (Pet Version)

	Phase 0 — Spawn Requirement : Completion of "Cliffside Platforming Challenge" + "Light Puzzle" triggers the "Winddrake" to appear on a ledge, glowing with wind 
glyphs.

	Phase 1 — Observation Phase :
* Remain near without provoking
* Sudden movement or attacks resets progress
* Calm approach unlocks "Ritual Bonding Phase"

	Phase 2 — Ritual Bonding Phase :
* Player matches movement/emotes to creature cues
* Items like "Wind-Sealed Relic" or "Gale Feather Token" improve affinity
* Success lowers aggression → unlocks "Final Acceptance"

	Phase 3 — Final Acceptance :
* Full-body glow and wing flare
* Creature added to summon list
* Failure resets observation/bonding phases, no item loss

	Quotes / Animations : 
* “The drake chirps softly, wings fluttering in sync with the wind.”
* “It hovers nearby, circling your head as if watching your every step.”
* “The Winddrake nudges at the shimmer on the ground, guiding your attention.”

