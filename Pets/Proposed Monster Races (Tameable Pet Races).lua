			Proposed Monster Races (Tameable Pet Races)

	1. Canines
* Wolf
* Dog
* Hyena
* Fox

	2. Felines
* Cat
* Tiger
* Leopard
* Panther
* Lion

	3. Ursines
* Bear (Brown Bear, Polar Bear, Cave Bear)
* Panda

	4. Hooved / Ungulates
* Deer
* Boar
* Elk
* Antelope

	5. Reptiles
* Crocodile
* Lizard (small / medium / giant)
* Snake (venomous / constrictor)
* Turtle / Tortoise

	6. Birds
* Eagle / Hawk / Falcon
* Owl
* Ostrich / Raptor
* Crow / Raven

7. Primates
* Monkey
* Baboon
* Gorilla

8. Arachnids / Insects (small and medium)
* Spider
* Scorpion
* Beetle

9. Aquatic / Semi-Aquatic
* Fish (small: trout, medium: pike, large: carp) – these are mostly food source pets, or small companions
* Frog / Toad (rare companion)
* Crab / Lobster

10. Mythical / Special *(reserved for Evolved / Rare / Exotic archetypes)*
* Dragon Whelp
* Griffin (part bird, part feline)
* Wyvern
* Basilisk
* Phoenix

---

	Notes for the skill system :

* Each species will have archetype-specific skill pools. For example:
	* Wolf (Berserk) → high offensive skills, Frenzy Bite, Howl Buff
	* Wolf (Tanky) → defensive skills, Guard Stance, Roar Debuff
* Passive skills will also vary per archetype (speed, regen, damage reduction, or buffing owner).
* The 10-skill pool per species will branch into archetype variants, ensuring diversity while keeping the species identifiable.

