			Dustburrow Rat

---

		1. Basic Information

* Pet Name : Dustburrow Rat
* Pet Class : Combat Pet
* Pet Type : Burrow Predator Companion
* Taming Difficulty : Easy–Moderate
* Habitat Origin : Quarry edges, collapsed tunnels, debris fields, miner camps
* Required Tool : Basic Taming Kit
* Special Taming Condition : Must isolate a single rat from a Ratpack group during combat

---

		2. Appearance

	The "Dustburrow Rat" is a lean, sinewy rodent with coarse sand-colored fur, cracked whiskers, and scarred ears from constant pack skirmishes. Its claws are dark
and chipped from digging through stone dust and debris. The eyes are small, beady, and restless, always scanning for threats or opportunity. Unlike its wild pack 
behavior, the tamed variant becomes fiercely loyal, redirecting its pack aggression toward the player’s enemies.

---

		3. Core Attributes

* HP : Medium–Low
* Defense : Low
* Mobility : High (ground, burrow bursts)
* Behavior : Aggressive, fast engager
* Role : Bleed damage, harassment, pressure

---

		4. Pet Abilities

* "Gnawing Bite" (Active) : Quick melee strike that applies a small "Bleed" effect over time.

* "Burrow Dash" (Active) : The rat briefly burrows underground and reappears behind the target, avoiding damage during the movement.
* "Pack Call" (Active) : Summons 2 small spectral rat echoes for a short duration that attack the target. These echoes cannot be targeted and disappear after a few 
seconds.
* **Relentless Nuisance (Passive) : Increases attack speed when attacking bleeding targets.

---

		5. Utility Role

	The Dustburrow Rat serves as :
* Early–mid game combat pressure pet
* Strong against lightly armored targets
* Excellent at interrupting casters and distracted enemies
* A harassment companion rather than a tank

---

		6. Special Taming Mechanic

	This pet cannot be tamed from a passive spawn.

	To tame it, the player must :
1. Engage a "Dustburrow Ratpack" group
2. Reduce one rat to low health while the rest of the pack is defeated or scattered
3. Begin taming before the remaining rat attempts to flee and burrow away

If the rat successfully burrows, the taming opportunity is lost.

This reflects the original swarm survival instinct of the creature.

---

		7. Behavior While Summoned

* Constantly circles the target’s legs in combat
* Makes short, erratic movements between attacks
* Occasionally scratches the ground as if preparing to burrow

---

		8. Restrictions

* Cannot tank multiple enemies
* Vulnerable to area damage
* Designed for aggression, not durability

