			Stoneveil Prowler

---

		1. Basic Information

* Pet Name : Stoneveil Prowler
* Pet Class : Combat / Stealth Pet
* Pet Type : Ambush Predator Companion
* Taming Difficulty : Moderate–Hard
* Habitat Origin : Fog-heavy cliffs, quarry rims, broken rock paths, low-visibility trails
* Required Tool : Advanced Taming Kit
* Special Taming Condition : Must be tamed while it is partially concealed by fog or terrain cover

---

		2. Appearance

	The "Stoneveil Prowler" resembles a lean rock-cat with slate-gray fur patterned like cracked stone. Its body is built low to the ground, muscles coiled for 
sudden bursts. Pale eyes reflect faint light in the fog, and its paws make almost no sound against gravel or stone. When still, it blends almost perfectly with the 
terrain, appearing like a carved rock formation rather than a living creature.

---

		3. Core Attributes

* HP : Medium–Low
* Defense : Low–Medium
* Mobility : High
* Behavior : Patient, ambush attacker
* Role : Stealth engagement, opening strikes, disruption

---

		4. Pet Abilities

* "Ambush Pounce" (Active) : Leaps from stealth, dealing bonus damage if used while unseen.
* "Veilstep (Active)" : The prowler briefly fades, becoming untargetable for a short moment and repositioning a few meters away.
* "Raking Claws (Active)" : Fast slashes that apply a light "Armor Tear" debuff.
* "Predator’s Patience" (Passive) : Damage increases the longer the prowler remains out of combat.
* "Stoneveil Instinct" (Passive) : Automatically enters a stealth state when in fog, shadows, or low-visibility environments.

---

		5. Utility Role

	The Stoneveil Prowler excels at :
* Supporting ambush-style gameplay
* Initiating fights with strong opening damage
* Distracting enemies through sudden vanish/reappear behavior
* Synergy with fog, cliffs, and broken terrain

---

		6. Special Taming Mechanic

	This creature cannot be tamed in clear visibility.

	To tame it, the player must :
1. Locate it during fog conditions or lure it into a fog-dense area
2. Reduce it to low health without breaking its stealth repeatedly
3. Begin taming while the prowler is partially faded by the environment

	If visibility clears or the prowler is forced into full visibility, the tame fails as it flees into the rocks.

---

		7. Behavior While Summoned

* Often sits motionless, blending with terrain when idle
* Circles wide before engaging targets
* Frequently disappears and reappears during combat

---

		8. Restrictions

* Not suited for prolonged fights
* Vulnerable when forced into open, clear areas
* Requires positioning awareness to maximize effectiveness

