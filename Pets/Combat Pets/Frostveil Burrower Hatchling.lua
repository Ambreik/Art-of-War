			Frostveil Burrower Hatchling

---

		1. Basic Information

* Pet Name: Frostveil Burrower Hatchling
* Source Monster: Frostveil Burrower (small variant)
* Pet Type: Combat Support / Resource Detection
* Family: Insectoid
* Rarity: Rare
* Role: Support / Utility / Minor Aggro Diversion
* Acquisition: Tamed from Frostveil Burrower Egg found in froststone burrows and cold mineral caverns
* Summon Item: Frostveil Burrower Hatchling Contract

---

		2. Description

	A small insectoid creature born from the mineral-rich frost burrows of the highlands. Its shell is lined with crystalline frost veins that glow faintly in dim 
light. Though fragile compared to its adult form, the hatchling retains the species’ instinct for burrowing, sensing minerals, and harassing threats with sharp ice-
tipped mandibles.

	When bonded to a handler, it becomes a valuable exploration companion, especially in areas rich with stone, ore, or hidden resources.

---

		3. Pet Type & Category

* Pet Category: Combat Support Pet
* Tamable: Yes
* Carrier: No
* Combat Pet: Yes
* Exotic: No
* Evolvable: Yes (level-based evolution)

---

		4. Statistics & Attributes

* Base Level: 1
* Max Level: 50
* Growth Type: Balanced / Utility scaling
* Base HP: Medium
* Base Damage: Medium
* Defense: Moderate
* Aggression: Reactive (assists when master is attacked)
* Mobility: Ground / Burrow dash movement

---

		5. AI Behavior

	Core Logic :
* Follows player closely
* Engages enemies that threaten the master
* Frequently repositions using short burrow movements
* Periodically scans for nearby mineral or rare resource nodes

	Archetypes (randomly assigned upon taming) :
1. Defender — Higher HP and aggro diversion
2. Harasser — Faster attacks and repositioning
3. Seeker — Improved resource detection range
4. Rare “Crystalborn” — Balanced combat and superior detection

---

### 6. Skills

	Passive & Active Skill Pool

1. "Frost Mandible Bite" (Active)
	* Melee strike with chance to slow target briefly

2. "Burrow Dash" (Active)
	* Quickly tunnels forward, dealing minor damage and repositioning

3. "Crystal Sense" (Passive)
	* Detects nearby ore, minerals, and rare resource nodes

4. "Chillspike Aura" (Passive)
	* Minor frost damage to nearby enemies over time

	Skills are rolled upon taming and influenced by archetype.

---

		7. Evolution Path

	At evolution thresholds, the pet may evolve into :

* "Frostveil Guardian Form" — Tankier, defensive abilities, stronger aggro control
* "Crystal Harvester Form" — Enhanced detection, higher damage, faster burrow skills

---

		8. UI & Player Interaction

	Pet UI displays :
* Name, level, health
* Passive and active skills
* Resource detection indicator on UI when active
* Hunger / loyalty meter
* Evolve / dismiss options

---

		9. Passive Bonuses

	While active, the Frostveil Burrower Hatchling may grant :
* +4% Elemental Resistance
* +5% Rare Resource Detection Radius
* +2% Stamina Recovery

	Values scale slightly with pet level.

---

		10. Acquisition / Tame Rules

* Requires Tame Ability
* Requires Frostveil Burrower Egg
* Easier to tame in cold mineral or froststone environments
* Standard taming cooldown applies
* Failure increases resistance temporarily; critical failure causes retreat underground
