			Reed Marsh Stalker

---

		1. Basic Information

* Pet Name: Reed Marsh Stalker
* Source Monster: Reed Marsh Stalker (wild variant)
* Pet Type: Stealth Predator / Recon
* Family: Feline / Wetland Predator
* Rarity: Uncommon
* Role: Companion / Combat Support / Reconnaissance
* Acquisition: Tamed from wild Reed Marsh Stalker in misty wetlands
* Summon Item: Reed Marsh Stalker Contract

---

		2. Description

	The Reed Marsh Stalker is a small-to-medium predator adapted to misty, marshy environments. Its fur is mottled gray and brown, perfectly blending with reeds, 
fog, and shallow waters. Highly agile and cautious, it excels at reconnaissance and ambush support. Its keen senses allow it to detect hidden enemies and prey, 
making it invaluable for scouting or assisting in minor skirmishes.

---

		3. Pet Type & Category

* Pet Category: Scout / Stealth / Combat Support
* Tamable: Yes
* Carrier: No
* Combat Pet: Yes (assists in minor combat)
* Exotic: No
* Evolvable: Yes (level-based evolution)

---

		4. Statistics & Attributes

* Base Level: 1
* Max Level: 50
* Growth Type: Standard (Balanced scaling)
* Base HP: Low–Medium
* Base Damage: Low–Medium
* Defense: Moderate
* Aggression: Reactive (assists master when threatened)
* Mobility: Ground mobility, swimming capability, stealth approach

---

		5. AI Behavior

* Core Logic :
	* Follows player and maintains stealth when possible
	* Detects hidden or camouflaged targets
	* Supports ambushes and minor combat
	* Uses skill rotation based on archetype
* Archetypes (randomly assigned upon taming) :
  1. Scout: Focuses on reconnaissance and alerting master to nearby threats
  2. Ambusher: Specializes in short-range surprise attacks
  3. Skirmisher: Balanced mobility and minor offensive support
  4. Elite (Rare): High detection, ambush damage, and reactive defensive support

---

		6. Skills

* Passive & Active Skill Pool (Sample)

1. "Reed Slash" (Active / Melee): Quick claw strike, can apply minor bleed
2. "Mist Camouflage" (Passive): Reduces chance of being detected in fog or reeds
3. "Silent Pounce" (Active): Short stealth leap to target; bonus damage if undetected
4. "Alert Senses" (Passive): Detects hidden traps or enemies near master

* Skills are rolled randomly upon taming, influenced by archetype. Advanced pets unlock additional skills with evolution.

---

		7. Evolution Path

* Level thresholds (30 / 40 / 50) grant chance to evolve into : 
	* Evolved Form : Larger, faster, enhanced stealth and ambush bonuses
	* *Combat Form : Focused on ambush and minor combat damage, gains a small area-of-effect strike

---

		8. UI & Player Interaction

* Displays: Name, level, health/status bars, skill list, hunger/loyalty meter
* Actions: Summon/dismiss, evolve, assign skill rotation

---

		9. Passive Bonuses

* While active, the Reed Marsh Stalker may grant :
	* +3% Stealth Efficiency
	* +2% Movement Speed in wetlands
	* +2% Detection of hidden enemies or traps
* Values scale slightly with pet level

---

		10. Acquisition / Tame Rules

* Must use Tame Ability on wild Reed Marsh Stalker
* Best tamed when young; adults are more resistant
* Cooldown: Standard taming cooldown applies
* Failure: Stalker may flee or resist; repeated failures temporarily increase taming difficulty

