			Duskrunner Fox (Tamed Variant)

---

		1. Tamed Entity Overview

* Tamed Name : Duskrunner Fox
* Companion Type : Pet
* Pet Role : Hybrid Scout / Skirmisher
* Pet Category : Combat Pet → Hybrid (Utility + DPS / Evasion-based)
* Progression Tier : Normal → Potential Evolved Variant
* Acquisition Type : Taming (Wild Capture)
* Taming Difficulty : Medium
* Required Player Level : Low–Mid
* Applicable Systems : Pet System (Combat AI, Companion Abilities, Utility Scouting Traits, Mobility Behavior)

---

		2. Taming Method

Duskrunner Foxes are cautious and highly reactive creatures, making them more difficult to approach than passive wildlife.

	Standard Taming Process : 

1. Locate a Duskrunner Fox in mixed terrain zones during low-light conditions (dusk/dawn is ideal).
2. The fox must be not actively fleeing or engaged in combat.
3. Player must approach slowly while avoiding sudden movement or sprinting.
4. Taming can be initiated when the fox is :
	* Observing its surroundings
	* Stationary or in light movement (not sprinting)

---

		3. Secret / Unique Taming Mechanic

	"Shadow Approach" (Hidden Mechanic)

	To increase taming success and unlock a stronger bond :
* The player must :
  * Approach the fox from behind or from a lateral blind angle
  * Avoid direct line-of-sight for as long as possible
  * Stay in low-movement or crouch-like behavior (if applicable in your system)

	Bonus Condition : 

* If the player :
	* Maintains stealth-like movement without alarming the fox
	* Initiates taming without triggering a flee response
* Then :
	* Taming success rate increases
	* Pet gains hidden trait: "Hunter’s Instinct"

	This mechanic reinforces the fox’s natural avoidance and awareness behavior.

---

		4. Appearance (Tamed Variant)

	The tamed Duskrunner Fox retains its sleek and agile physique, but its demeanor becomes noticeably more controlled and responsive to the player’s presence.
	Its fur appears well-groomed, with subtle tonal contrasts along its back, legs, and tail that become more visible under different lighting conditions. The tail 
remains prominent and expressive, often used for balance during movement and occasionally flicking in response to stimuli.
	Its eyes remain sharp and alert, but instead of constantly scanning for threats independently, they periodically shift toward the player, indicating 
coordination and awareness of commands or movement.
	When idle, the fox maintains a low, relaxed stance, but remains ready to react instantly. When in motion, it mirrors the player’s pace closely, weaving through 
terrain with fluid, precise movements. Its footfalls are light and deliberate, avoiding unnecessary noise, especially in stealth-oriented environments.

	During combat or movement, the fox exhibits coordinated bursts of speed, repositioning frequently to maintain advantageous angles relative to targets.

