		5. Pet Classification

* Pet Type : Combat Pet
* Specialization : Hybrid Skirmisher (DPS + Utility)
* Behavior Mode : Active Combat Companion with Scouting Traits
* Combat Role : Evasive damage dealer / flanking unit
* Primary Function : Mobility-based combat support + environmental awareness

---

		6. Core Pet Attributes

* Pet HP : Low
* Pet Defense : Low
* Pet Mobility : Very High
* Attack Style : Fast, precise, short-burst engagements
* AI Behavior : Evasive, reactive, positioning-focused
* Combat Presence : Active (frequent engagement with repositioning)

---

		7. Pet Abilities / Traits

	1. Duskrunner Strike : A quick forward lunge attack used to engage targets.

* Effect :
	* Deals rapid damage in a short burst
	* Initiates combat or follows up on player attacks
	* Often used from flanking positions
* Mechanics :
	* Low cooldown
	* High responsiveness in combat AI
	* Prioritizes weak or exposed targets

---

	2. Flanking Instinct : The fox naturally attempts to attack from the sides or rear of enemies.

* Effect :
	* Increases effectiveness when attacking from non-front angles
	* Improves damage or critical chance (depending on your combat system)
	* Encourages tactical positioning
* Mechanics :
	* AI-driven positioning behavior
	* Constant repositioning during combat

---

	3. Evasive Reflex : Allows the fox to avoid incoming attacks through rapid movement.

* Effect :
	* Increased survivability via evasion rather than tanking
	* Dodges or avoids predictable attacks
	* Reduces incoming damage indirectly
* Mechanics :
	* Triggered when targeted or under threat
	* Short bursts of directional movement

---

	4. Scouting Presence : The fox retains its natural scouting instincts even in combat mode.

* Effect :
	* Detects nearby threats earlier than standard pets
	* Helps reveal hidden or approaching enemies
	* Provides situational awareness in exploration
* Mechanics :
	* Passive detection enhancement
	* Works outside of combat as well

---

		8. Combat Behavior

* Engages quickly and retreats frequently
* Prefers hit-and-run tactics over sustained engagement
* Constantly repositions during combat
* Coordinates with player actions rather than acting independently
* Avoids direct tanking roles entirely

---

		9. Passive Bonuses

* Increased movement synergy with player
* Improved encounter awareness
* Enhanced survivability through evasion
* Better performance in mixed terrain environments
* Slight advantage in detecting ambushes or hidden enemies

---

		10. Evolution / Progression Path (Optional Design)

	The Duskrunner Fox can evolve through continued use and bonding :

	Potential Evolution States : 
* "Duskrunner Stalker" (Enhanced stealth + crit focus)
* "Duskrunner Alpha" (Improved combat efficiency and mobility)
* "Eclipse Runner Fox" (Advanced hybrid with heightened scouting and combat synergy)

	Evolution Triggers : 
* Combat participation milestones
* Successful flanking engagements
* Time spent in mixed/stealth environments
* Bond level progression

---

		11. Limitations

* Low durability (cannot sustain damage)
* Requires active positioning to maximize combat effectiveness
* Less effective in confined or heavily controlled environments
* Relies on mobility rather than raw power

