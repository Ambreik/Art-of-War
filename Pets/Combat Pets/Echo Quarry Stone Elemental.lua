			Echo Quarry Stone Elemental

---

		BASIC INFORMATION

* Pet Name : Echo Quarry Stone Elemental
* Source Monster : Echo Quarry Stone Elemental (small variant)
* Family : Elemental
* Rarity : Uncommon Pet
* Role : Support / Environmental Interaction
* Acquisition : Tamed directly from small wild Echo Quarry Stone Elementals
* Summon Item : Quarry Stone Elemental Contract

---

		DESCRIPTION

	The small Echo Quarry Stone Elemental is a living fragment of rock infused with subtle elemental energy. Its surface is rough but lightly luminescent, with 
faint rune-like cracks that glow when the elemental is agitated or excited. Though diminutive, it is responsive to skilled handlers and can manipulate minor 
environmental objects or trigger small area effects.

---

		PET TYPE & CATEGORY

* Pet Category : Normal Pet
* Tamable : Yes
* Carrier : No
* Combat Pet : Yes (support-focused)
* Exotic : No
* Evolvable : Yes (level-based evolution into larger or more combat-capable elemental)

---

		STATISTICS & ATTRIBUTES

* Base Level : 1
* Max Level : 50
* Growth Type : Standard (balanced scaling)
* Base HP : Medium
* Base Damage : Low
* Defense : Medium
* Aggression : Reactive (assists when master is attacked)

---

		AI BEHAVIOR

* Core Logic :
	* Follows the player at short distance
	* Interacts with environmental objects or terrain features
	* Supports master in combat with minor elemental effects
	* Can block paths or create small obstacles in strategic positions

---

		Archetype

	When tamed, this pet can roll into one of the following archetypes :
1. "Support" – Focused on environmental manipulation; buffs allies near terrain
2. "Combat Support" – Uses minor AoE stone attacks to assist in fights
3. "Skillable" – Can learn tactical abilities for both combat and utility
4. "Rare Elemental" (Very Rare) – Greater elemental effects, increased durability and passive buffs

---

		SKILLS

* "Pebble Shield" (Passive) – Occasionally blocks minor projectiles or reduces incoming damage for master
* "Stone Tap" (Active) – Strikes a small area, knocking back or staggering enemies
* "Environmental Sense" (Utility) – Highlights nearby interactable terrain objects or hidden passages
* "Quarry Pulse" (Passive) – Slightly enhances master’s defensive stats when near rocks or stone surfaces

	Skill sets are randomly chosen upon taming, influenced by archetype. Advanced evolution can unlock additional abilities.

---

		EVOLUTION PATH

* Level 30–40 evolution chance:
	* "Greater Quarry Elemental" – Larger, sturdier, higher HP and defense; improved environmental control
	* "Combat Elemental" – More powerful AoE attacks, minor crowd control

---

		UI & PLAYER INTERACTION

	Pet UI will show :
* Name & level
* Health & status bars
* Passive & active skill list
* Hunger / loyalty meter (requires periodic feeding)
* Evolve / dismiss options

---

		PASSIVE BONUSES

	While active, the Echo Quarry Stone Elemental may grant :
* +3% Environmental Interaction efficiency (detect resources, interact with objects)
* +2% Defense while near stone or rocky terrain
* Minor crowd control bonus (e.g., slow effect on nearby enemies)

	Values scale slightly with pet level.

---

		ACQUISITION / TAME RULES

* Tame Conditions :
	* Must use "Tame Ability"
	* Pet Contract item required
	* Success chance influenced by pet resistance & environment
* Cooldown : Standard taming cooldown applied
* Success / Failure :
	* Failure temporarily increases resistance
	* Critical failure causes the elemental to retreat and hide in rocky terrain

